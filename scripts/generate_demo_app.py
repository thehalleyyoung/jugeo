"""Generate the Sheaf Explorer demo via Copilot + JG obligation verification.

This script demonstrates the judgment-geometric approach to LLM-driven
generation:

  1. Copilot proposes *sections* for each fiber of the app sheaf
     (HTML structure, CSS styling, JS interaction, content, animation,
     navigation, data layer, theme).

  2. The obligation presheaf verifies *descent*: do the proposed sections
     meet the typed quality requirements ("stunning" preset)?

  3. If not, the enrichment functor repairs obstructions automatically.

  4. The result is a standalone HTML/CSS/JS app with no server required.

Run:
    python3 scripts/generate_demo_app.py [--outdir DIR] [--port PORT]
"""
