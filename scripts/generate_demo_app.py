def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Sheaf Explorer via Copilot + JG obligations")
    parser.add_argument("--outdir", "-o", default=os.path.join(REPO_ROOT, "examples", "sheaf_explorer"))
    parser.add_argument("--port", "-p", type=int, default=8080)
    args = parser.parse_args()

    print("=" * 64)
    print("  Sheaf Explorer — Copilot + JG Obligation Presheaf Generator")
    print("=" * 64)
    print()

    driver = CopilotGenerationDriver(
        name="sheaf_explorer",
        title="Sheaf Explorer",
        description="Interactive sheaf theory explorer generated by Copilot through jugeo-webapp",
        port=args.port,
        obligations="stunning",
    )

    # Copilot proposes sections for each fiber
    proposals = {
        FiberKind.THEME: THEME_PROPOSAL,
        FiberKind.NAVIGATION: NAV_PROPOSAL,
        FiberKind.HTML_STRUCTURE: HTML_PROPOSAL,
        FiberKind.CONTENT: CONTENT_PROPOSAL,
        FiberKind.CSS_STYLING: CSS_PROPOSAL,
        FiberKind.ANIMATION: ANIMATION_PROPOSAL,
        FiberKind.DATA_LAYER: DATA_PROPOSAL,
    }

    # If the JS SPA file exists, use it; otherwise it'll be auto-enriched
    if JS_PROPOSAL.js and "SPA JS will be inlined" not in JS_PROPOSAL.js:
        proposals[FiberKind.JS_INTERACTION] = JS_PROPOSAL

    for fiber, proposal in proposals.items():
        driver.propose(fiber, proposal)
        print(f"  📦 Proposed section for fiber: {fiber.value}")

    # Check descent BEFORE generation
    print()
    print("  🔍 Checking descent (obligation presheaf)...")
    descent = driver.check_descent()
    print(f"  Descent satisfied: {descent.satisfied}")
    if not descent.satisfied and descent.obligation_report:
        print(f"  Unmet obligations ({len(descent.obligation_report.unmet)}):")
        for r in descent.obligation_report.unmet:
            print(f"    ❌ {r.obligation.kind.value}: need {r.obligation.minimum}, have {r.actual}")
        print("  → Enrichment functor will repair obstructions...")
    print()

    # Generate with auto-enrichment
    result = driver.generate(args.outdir, auto_enrich=True, max_rounds=5)

    print(f"  ✅ Generated {len(result.files_created)} files ({result.total_lines} lines)")
    if result.obligation_report:
        print(f"  Enrichment rounds: {result.obligation_report.enrichment_rounds}")
        all_met = result.obligation_report.all_met
        print(f"  All obligations met: {all_met}")
        if not all_met:
            for r in result.obligation_report.unmet:
                print(f"    ❌ {r.obligation.kind.value}: need {r.obligation.minimum}, have {r.actual}")
    print()
    for f in result.files_created:
        rel = os.path.relpath(f, args.outdir)
        size = os.path.getsize(f)
        print(f"    {rel:30s}  {size:>7,} bytes")
    print()
    print(f"  To serve:")
    print(f"    cd {args.outdir} && python3 -m http.server {args.port}")
    print(f"    Then open http://localhost:{args.port}")
    print()


if __name__ == "__main__":
    main()
