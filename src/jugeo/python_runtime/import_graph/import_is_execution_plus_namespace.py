class ImportKind(str, Enum):
    """
    Classifies the syntactic form of a Python import statement.

    theory2.tex Ch19 §1 distinguishes five import forms, each with distinct
    implications for namespace transport and execution semantics:

    ABSOLUTE
        ``import foo`` or ``import foo.bar`` — resolves against sys.path
        from the package root.  Execution of ``foo`` (and its ancestors) is
        triggered the first time.  The name ``foo`` (or ``foo.bar``) is
        added to the importing namespace.

    RELATIVE
        ``from . import sibling`` or ``from ..utils import helper`` — resolved
        relative to the importing package's ``__name__``.  Requires that the
        importing module already has a ``__package__`` attribute set by the
        loader.  Enables refactoring of intra-package references without
        touching absolute paths.

    STAR
        ``from module import *`` — transports every public name from
        ``module.__all__`` (or every non-underscore name if ``__all__`` is
        absent) into the importing namespace.  Provenance of individual names
        is lost unless explicit ``__all__`` is defined in the source module.
        Static analysis tools must inspect the source module to enumerate
        transported names.

    FROM
        ``from module import name`` or ``from module import name as alias`` —
        transports a specific set of names, optionally under aliases.  This is
        the most explicit form and supports fine-grained dependency analysis.
        The source module is still fully executed.

    CONDITIONAL
        A structural classification applied post-hoc by the analyzer when an
        import statement appears inside a ``try/except ImportError`` block,
        an ``if TYPE_CHECKING:`` guard, or inside an ``if sys.platform ==``
        branch.  The import's effect on the runtime namespace is conditional
        on environment state.
    """

    ABSOLUTE = "absolute"
    RELATIVE = "relative"
    STAR = "star"
    FROM = "from"
    CONDITIONAL = "conditional"


