"""
theory2.tex Ch19 §1 — Import is Execution Plus Namespace Transport
===================================================================

This module formalizes the semantics of Python's import system through the lens
of jugeo's site-theoretic judgment framework.  The central thesis (Ch19 §1) is:

    **An import statement is simultaneously**
    1. **Execution** — the interpreter runs the body of the imported module
       (or retrieves the already-executed module object from ``sys.modules``).
    2. **Namespace transport** — selected names (or the whole module object)
       are injected into the importing namespace, constituting a *morphism*
       between two coordinate objects in the site.

This dual character is not merely academic.  It has direct consequences for
reasoning about Python programs:

* **Execution effects are irreversible** by default.  If ``import m`` causes
  ``m`` to register a signal handler, open a socket, or write to disk, that
  effect is observable even if the importing namespace later deletes the name.

* **Namespace transport is selective and order-dependent.**  ``from m import f``
  transports only ``f``, binding it to the caller's namespace under the same
  name (or an alias).  This creates a *fork* in provenance: the caller's ``f``
  and ``m.f`` may diverge after reassignment.

* **Star imports collapse provenance.**  ``from m import *`` transports every
  public name in ``m.__all__`` (or every non-underscore-prefixed name if
  ``__all__`` is absent), making it impossible for static analysis to determine
  the origin of any given name without reading ``m`` itself.

* **Conditional imports introduce branching.**  ``try: import fast_impl except
  ImportError: import slow_impl`` means the effective namespace depends on
  runtime availability of packages, creating a *branching topology* in the
  import graph.

Formalisation (site-theoretic sketch)
--------------------------------------
Let **C** be the category whose objects are Python modules (identified by their
fully-qualified names) and whose morphisms are import relationships.  A morphism
``f : A → B`` exists when module ``B`` imports from module ``A``.

A *covering family* for object ``A`` is a collection of modules that together
"cover" the interface of ``A`` — i.e., every public name in ``A`` is imported
by at least one member of the family.  This mirrors the Grothendieck topology
condition that every object is covered by the sieve generated by its covering
families.

An *import execution record* is a carrier in the judgment sense: it witnesses
that the execution of module ``m`` took place at a specific timestamp, that the
namespace of the importer before and after the import had specific key-sets, and
that the import either succeeded or failed with a given error message.

A *namespace delta record* captures the difference between the importer's
namespace before and after executing an import statement, decomposed into added,
removed, and changed names.  This is the concrete manifestation of the
"namespace transport" half of the thesis.

References
----------
* theory2.tex Ch19 §1 "Import is execution plus namespace transport"
* PEP 302 — New Import Hooks
* PEP 328 — Imports: Multi-Line and Absolute/Relative
* PEP 366 — Main module explicit relative imports
* importlib documentation: https://docs.python.org/3/library/importlib.html
* sys.modules contract: CPython/Lib/importlib/_bootstrap.py

Author: jugeo project — generated with Copilot assistance
"""

