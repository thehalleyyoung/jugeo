@dataclass
class ImportExecutionNamespaceTransportCoordinator:
    """
    Coordinates the analysis of import statements in a Python source file.

    theory2.tex Ch19 §1 — Central coordinator for import execution analysis.

    This class is the primary entry point for the module.  It accepts a path
    to a ``.py`` file, parses its AST, extracts all import statements, and
    produces a list of ``ImportExecutionRecord`` objects.  It also builds
    jugeo ``Judgment`` objects for each import, attaching execution evidence
    and namespace transport morphisms to the site.

    The coordinator maintains mutable state:
    - ``records``: accumulated ``ImportExecutionRecord`` objects from the
      most recent ``run()`` call.
    - ``judgments``: accumulated ``Judgment`` objects built from those records.
    - ``site_builder``: a ``SiteBuilder`` accumulating coordinates and morphisms.

    Usage
    -----
    >>> coord = ImportExecutionNamespaceTransportCoordinator()
    >>> records = coord.run("path/to/module.py")
    >>> judgments = [coord.build_execution_judgment(r) for r in records]

    # copilot: mutable because it accumulates state across calls to run()
    """

    records: list = field(default_factory=list)
    judgments: list = field(default_factory=list)
    site_builder: object = field(default_factory=SiteBuilder)

    # copilot: _source_path is set by run() and used by other methods for context
    _source_path: str = field(default="", repr=False)

    def analyze_import_statement(self, stmt: ast.stmt) -> ImportExecutionRecord:
        """
        Produce an ``ImportExecutionRecord`` from a single AST import node.

        Accepts either ``ast.Import`` or ``ast.ImportFrom`` nodes.  Extracts
        the module name(s), the imported names (if any), and the line number.
        Since this is static analysis (not live execution), ``execution_timestamp``
        is set to the current wall time, ``namespace_before`` and
        ``namespace_after`` are left as empty tuples, and ``execution_succeeded``
        is set to ``True`` (optimistic assumption — the analyzer has no way to
        know whether the import will succeed at runtime).

        Parameters
        ----------
        stmt : ast.stmt
            An ``ast.Import`` or ``ast.ImportFrom`` node extracted from the
            module's AST.  Passing other node types will raise ``TypeError``.

        Returns
        -------
        ImportExecutionRecord
            A fully-populated record.  ``imported_names`` is a sorted tuple of
            the names that will be introduced into the importing namespace.

        Raises
        ------
        TypeError
            If ``stmt`` is not an ``ast.Import`` or ``ast.ImportFrom`` node.

        # copilot: this is static analysis only — no actual import is executed here
        """
        if not isinstance(stmt, (ast.Import, ast.ImportFrom)):
            raise TypeError(
                f"Expected ast.Import or ast.ImportFrom, got {type(stmt).__name__}"
            )

        ts = time.time()

        if isinstance(stmt, ast.Import):
            # copilot: ast.Import has a list of aliases (name, asname pairs)
            module_name = stmt.names[0].name if stmt.names else "<unknown>"
            imported_names = tuple(
                sorted(
                    alias.asname if alias.asname else alias.name.split(".")[0]
                    for alias in stmt.names
                )
            )
        else:
            # copilot: ast.ImportFrom has module, names (aliases), level (relative dots)
            module_name = stmt.module or "<relative>"
            if stmt.names and stmt.names[0].name == "*":
                # star import — we record a sentinel
                imported_names = ("*",)
            else:
                imported_names = tuple(
                    sorted(
                        alias.asname if alias.asname else alias.name
                        for alias in stmt.names
                    )
                )

        log.debug(
            "analyze_import_statement: module=%r names=%r line=%d",
            module_name,
            imported_names,
            getattr(stmt, "lineno", -1),
        )

        return ImportExecutionRecord(
            module_name=module_name,
            imported_names=imported_names,
            execution_timestamp=ts,
            namespace_before=(),
            namespace_after=imported_names,  # optimistic: assume all names land
            execution_succeeded=True,
            error_message="",
        )

    def coordinate_namespace_transport(
        self,
        source_module: str,
        target_module: str,
        names: list[str],
    ) -> NamespaceTransportResult:
        """
        Build a ``NamespaceTransportResult`` representing the morphism from
        ``source_module`` to ``target_module`` transporting ``names``.

        This method also registers the corresponding coordinate and morphism
        objects with the internal ``SiteBuilder`` so that the accumulated site
        can later be retrieved for judgment construction.

        Parameters
        ----------
        source_module : str
            Fully-qualified name of the supplying module.
        target_module : str
            Fully-qualified name of the consuming (importing) module.
        names : list[str]
            Names being transported.  Pass ``["*"]`` for star imports.

        Returns
        -------
        NamespaceTransportResult
            Immutable record of the transport.

        # copilot: registers coords and morphisms in site_builder as a side effect
        """
        src_coord = Coordinate(
            components=(source_module,),
            kind=CoordinateKind.MODULE,
            support_labels=frozenset(names),
        )
        tgt_coord = Coordinate(
            components=(target_module,),
            kind=CoordinateKind.MODULE,
            support_labels=frozenset(),
        )
        morphism_kind = (
            MorphismKind.RESTRICTION.value
            if names and names != ["*"]
            else MorphismKind.INCLUSION.value
        )
        morph = Morphism(
            source=src_coord,
            target=tgt_coord,
            kind=MorphismKind(morphism_kind),
            label=f"transport:{','.join(names)}",
        )
        self.site_builder.add_coordinate(src_coord)
        self.site_builder.add_coordinate(tgt_coord)
        self.site_builder.add_morphism(morph)

        result = NamespaceTransportResult(
            source_module=source_module,
            target_module=target_module,
            transported_names=tuple(sorted(names)),
            morphism_kind=morphism_kind,
            coordinate=tgt_coord,
        )
        log.debug(
            "coordinate_namespace_transport: %r → %r (%d names)",
            source_module,
            target_module,
            len(names),
        )
        return result

    def build_execution_judgment(self, record: ImportExecutionRecord) -> Judgment:
        """
        Construct a jugeo ``Judgment`` from an ``ImportExecutionRecord``.

        The judgment's proposition states that the import of ``record.module_name``
        constitutes an execution event and namespace transport.  Evidence is
        attached from the record's fields.  The trust level is set to
        ``RUNTIME_WITNESSED`` if ``execution_succeeded`` is ``True``, otherwise
        ``COPILOT_SUGGESTED`` (static-analysis-only guess).

        Parameters
        ----------
        record : ImportExecutionRecord
            The execution record to lift into a judgment.

        Returns
        -------
        Judgment
            A fully-populated judgment object.  Appended to ``self.judgments``.

        # copilot: this bridges the import analysis layer to the jugeo judgment layer
        """
        prop = Proposition(
            kind=PropositionKind.STRUCTURAL,
            statement=(
                f"import of '{record.module_name}' is execution plus namespace transport "
                f"(transported: {sorted(record.transported_names)})"
            ),
            label=f"import::{record.module_name}",
        )
        coord = record.as_coordinate()
        carrier = Carrier(
            coordinate=coord,
            payload=record,
            label=f"execution_record::{record.module_name}",
        )
        trust_level = (
            TrustLevel.RUNTIME_WITNESSED
            if record.execution_succeeded
            else TrustLevel.COPILOT_SUGGESTED
        )
        trust = TrustAnnotation(
            level=trust_level,
            rationale=(
                "Execution succeeded with namespace transport"
                if record.execution_succeeded
                else f"Import failed: {record.error_message}"
            ),
        )
        evidence_item = EvidenceItem(
            kind=EvidenceItemKind.STATIC_ANALYSIS,
            payload={
                "module_name": record.module_name,
                "imported_names": record.imported_names,
                "transported_names": sorted(record.transported_names),
                "execution_succeeded": record.execution_succeeded,
            },
            label="import_execution_static_analysis",
        )
        bundle = EvidenceBundle()
        bundle.add(evidence_item)
        prov = Provenance(
            source=self._source_path,
            module=__name__,
            timestamp=str(record.execution_timestamp),
        )
        j = Judgment(
            status=JudgmentStatus.SETTLED if record.execution_succeeded else JudgmentStatus.OBSTRUCTED,
            proposition=prop,
            carrier=carrier,
            evidence=bundle,
            trust=trust,
            provenance=prov,
            label=f"judgment::import::{record.module_name}",
        )
        self.judgments.append(j)
        return j

    def run(self, module_path: str) -> list:
        """
        Parse a ``.py`` file and return ``ImportExecutionRecord`` objects for
        every import statement found at module level.

        Steps:
        1. Read ``module_path`` from disk.
        2. Parse with ``ast.parse``.
        3. Walk the top-level statements looking for ``ast.Import`` and
           ``ast.ImportFrom`` nodes.
        4. Call ``analyze_import_statement`` for each.
        5. Accumulate results into ``self.records``.

        Parameters
        ----------
        module_path : str
            Filesystem path to a ``.py`` source file.

        Returns
        -------
        list[ImportExecutionRecord]
            All records extracted from the file.  Also stored in ``self.records``.

        # copilot: only top-level imports are extracted; nested imports (inside functions) are skipped
        """
        self._source_path = module_path
        self.records.clear()

        log.info("ImportExecutionNamespaceTransportCoordinator.run: reading %r", module_path)

        try:
            with open(module_path, "r", encoding="utf-8") as fh:
                source = fh.read()
        except OSError as exc:
            log.error("run: cannot read %r: %s", module_path, exc)
            return []

        try:
            tree = ast.parse(source, filename=module_path)
        except SyntaxError as exc:
            log.error("run: syntax error in %r: %s", module_path, exc)
            return []

        for node in ast.iter_child_nodes(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                # copilot: extract top-level imports only
                record = self.analyze_import_statement(node)
                self.records.append(record)

        log.info(
            "run: found %d import statements in %r",
            len(self.records),
            module_path,
        )
        return list(self.records)


@dataclass
class ImportExecutionNamespaceTransportAnalyzer:
    """
    Static analyzer for import statements in Python source code.

    theory2.tex Ch19 §1 — Static analysis component of the import graph.

    While the coordinator focuses on producing judgment-ready records,
    this analyzer focuses on structural properties of the import graph:
    dependency graphs, shadowed name detection, and import classification.

    The analyzer is designed to be used on source strings (not live modules),
    making it suitable for offline analysis of large codebases.

    State
    -----
    _cache : dict
        Maps ``(source_hash, operation)`` pairs to results, avoiding redundant
        parsing of the same source.

    # copilot: stateless between different sources, but caches results within a session
    """

    _cache: dict = field(default_factory=dict)

    def extract_import_statements(self, source: str) -> list:
        """
        Parse ``source`` and return all AST import nodes, including those
        nested inside function bodies, class bodies, and try/except blocks.

        Parameters
        ----------
        source : str
            Python source code as a string.

        Returns
        -------
        list[ast.stmt]
            All ``ast.Import`` and ``ast.ImportFrom`` nodes found anywhere
            in the AST (uses ``ast.walk`` for full traversal).

        # copilot: ast.walk visits every node in DFS order — no depth limit
        """
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            log.warning("extract_import_statements: syntax error: %s", exc)
            return []

        result = [
            node
            for node in ast.walk(tree)
            if isinstance(node, (ast.Import, ast.ImportFrom))
        ]
        log.debug("extract_import_statements: found %d import nodes", len(result))
        return result

    def classify_import(self, node: ast.stmt) -> ImportKind:
        """
        Classify a single import AST node into an ``ImportKind`` value.

        Classification rules:
        - ``ast.Import`` → ``ImportKind.ABSOLUTE``
        - ``ast.ImportFrom`` with ``level > 0`` → ``ImportKind.RELATIVE``
        - ``ast.ImportFrom`` with ``names[0].name == '*'`` → ``ImportKind.STAR``
        - ``ast.ImportFrom`` with ``level == 0`` → ``ImportKind.FROM``
        - Any import inside a ``Try`` node → ``ImportKind.CONDITIONAL``
          (this classification requires the parent context, which is set by
          the caller; this method returns the basic form classification).

        Parameters
        ----------
        node : ast.stmt
            An AST import node.

        Returns
        -------
        ImportKind
            The classification of the import form.

        # copilot: CONDITIONAL classification requires caller to check parent context
        """
        if isinstance(node, ast.Import):
            return ImportKind.ABSOLUTE
        if isinstance(node, ast.ImportFrom):
            if node.level and node.level > 0:
                return ImportKind.RELATIVE
            if node.names and node.names[0].name == "*":
                return ImportKind.STAR
            return ImportKind.FROM
        # copilot: fallback — should not be reached for well-formed ASTs
        return ImportKind.ABSOLUTE

    def build_dependency_graph(self, module_name: str) -> dict:
        """
        Build a module dependency graph rooted at ``module_name``.

        Uses ``importlib.util.find_spec`` to locate the source file for
        ``module_name``, reads it, extracts all import statements, and
        recursively processes each imported module (up to a maximum depth
        to prevent infinite recursion on circular imports).

        Parameters
        ----------
        module_name : str
            Fully-qualified module name, e.g., ``"jugeo.geometry.site"``.

        Returns
        -------
        dict[str, list[str]]
            Maps each discovered module name to the list of module names it
            directly imports.  Modules that could not be located are mapped
            to an empty list.

        # copilot: max_depth=3 prevents infinite recursion on circular import graphs
        """
        graph: dict = {}
        self._build_graph_recursive(module_name, graph, depth=0, max_depth=3)
        return graph

    def _build_graph_recursive(
        self,
        module_name: str,
        graph: dict,
        depth: int,
        max_depth: int,
    ) -> None:
        """
        Internal recursive helper for ``build_dependency_graph``.

        Mutates ``graph`` in-place.  Stops recursion when depth exceeds
        ``max_depth`` or when the module has already been processed.

        # copilot: guard against already-visited modules to prevent cycles
        """
        if module_name in graph or depth > max_depth:
            return

        graph[module_name] = []

        spec = importlib.util.find_spec(module_name)
        if spec is None or spec.origin is None:
            log.debug("_build_graph_recursive: no spec for %r", module_name)
            return

        try:
            with open(spec.origin, "r", encoding="utf-8") as fh:
                source = fh.read()
        except OSError:
            log.debug("_build_graph_recursive: cannot read %r", spec.origin)
            return

        stmts = self.extract_import_statements(source)
        for stmt in stmts:
            if isinstance(stmt, ast.ImportFrom) and stmt.module:
                dep = stmt.module
            elif isinstance(stmt, ast.Import) and stmt.names:
                dep = stmt.names[0].name
            else:
                continue
            graph[module_name].append(dep)
            self._build_graph_recursive(dep, graph, depth + 1, max_depth)

    def detect_shadowed_names(self, stmts: list) -> list:
        """
        Detect names that are shadowed by a later import in the same list.

        Iterates through ``stmts`` in order, maintaining a running dict of
        ``name → module`` bindings.  When a later import introduces a name
        that is already bound (from a prior import in the same module), a
        ``ShadowedNameRecord`` is emitted.

        Parameters
        ----------
        stmts : list[ast.stmt]
            A list of AST import nodes (as returned by
            ``extract_import_statements``).  Non-import nodes are silently
            skipped.

        Returns
        -------
        list[ShadowedNameRecord]
            One record per shadowing event.  Empty if no shadowing is detected.

        # copilot: order matters — earlier imports are shadowed by later ones
        """
        # Maps name → (module, lineno)
        seen: dict = {}
        shadows: list = []

        for stmt in stmts:
            if isinstance(stmt, ast.Import):
                for alias in stmt.names:
                    bound_name = alias.asname if alias.asname else alias.name.split(".")[0]
                    module = alias.name
                    lineno = getattr(stmt, "lineno", -1)
                    if bound_name in seen:
                        orig_module, _ = seen[bound_name]
                        shadows.append(
                            ShadowedNameRecord(
                                name=bound_name,
                                original_module=orig_module,
                                shadowing_module=module,
                                line_no=lineno,
                            )
                        )
                        log.debug(
                            "detect_shadowed_names: '%s' shadowed by %r at line %d",
                            bound_name,
                            module,
                            lineno,
                        )
                    seen[bound_name] = (module, lineno)

            elif isinstance(stmt, ast.ImportFrom):
                module = stmt.module or "<relative>"
                lineno = getattr(stmt, "lineno", -1)
                if stmt.names and stmt.names[0].name == "*":
                    # copilot: star imports may shadow anything; record conservatively
                    continue
                for alias in stmt.names:
                    bound_name = alias.asname if alias.asname else alias.name
                    if bound_name in seen:
                        orig_module, _ = seen[bound_name]
                        shadows.append(
                            ShadowedNameRecord(
                                name=bound_name,
                                original_module=orig_module,
                                shadowing_module=module,
                                line_no=lineno,
                            )
                        )
                    seen[bound_name] = (module, lineno)

        return shadows


@dataclass
class ImportExecutionNamespaceTransportWitness:
    """
    Runtime witness for import execution and namespace transport.

    theory2.tex Ch19 §1 — Runtime witnessing of import events.

    Where the coordinator and analyzer operate on source text, this class
    operates at runtime by actually invoking the import machinery and
    recording what happens.  It uses ``importlib.util.find_spec`` to check
    module availability, ``time.time_ns`` for high-resolution timing, and
    ``sys._getframe`` for frame-depth measurement.

    The witness class is the highest-trust analysis component in this
    module.  Its records carry ``TrustLevel.RUNTIME_WITNESSED`` or higher.

    State
    -----
    witnessed_modules : dict[str, ExecutionWitnessRecord]
        Maps module name → most recent ``ExecutionWitnessRecord``.

    witnessed_deltas : list[NamespaceDeltaRecord]
        Accumulated delta records from all ``record_namespace_delta`` calls.

    # copilot: this class performs actual imports — use with caution in production
    """

    witnessed_modules: dict = field(default_factory=dict)
    witnessed_deltas: list = field(default_factory=list)

    def witness_import_execution(self, module_name: str) -> "ExecutionWitnessRecord":
        """
        Witness the import of ``module_name`` using ``importlib.util.find_spec``
        and, if not already cached, ``importlib.import_module``.

        Steps:
        1. Check whether ``module_name`` is already in ``sys.modules``.
        2. Record ``time.time_ns()`` before and after.
        3. Use ``find_spec`` to verify the module exists without loading it.
        4. If not in cache: call ``importlib.import_module``.
        5. Record frame count at the call site.

        Parameters
        ----------
        module_name : str
            Fully-qualified module name to witness.

        Returns
        -------
        ExecutionWitnessRecord
            Populated record.  Also stored in ``self.witnessed_modules``.

        # copilot: importlib.import_module runs the module body if not cached
        """
        already_loaded = module_name in sys.modules
        frame_count = 0
        try:
            frame = sys._getframe(0)
            while frame is not None:
                frame_count += 1
                frame = frame.f_back
        except AttributeError:
            pass

        spec = importlib.util.find_spec(module_name)
        if spec is None:
            # Module doesn't exist — witness level 0 (not found)
            record = ExecutionWitnessRecord(
                module_name=module_name,
                sys_modules_key=module_name,
                load_time_ns=0,
                frame_count=frame_count,
                witness_level=1,
            )
            self.witnessed_modules[module_name] = record
            log.warning("witness_import_execution: spec not found for %r", module_name)
            return record

        if already_loaded:
            # Cache hit — no re-execution
            record = ExecutionWitnessRecord(
                module_name=module_name,
                sys_modules_key=module_name,
                load_time_ns=0,
                frame_count=frame_count,
                witness_level=2,
            )
        else:
            # Fresh import — measure execution time
            t0 = time.time_ns()
            try:
                importlib.import_module(module_name)
                load_time_ns = time.time_ns() - t0
                witness_level = 3
                log.info(
                    "witness_import_execution: loaded %r in %d ns",
                    module_name,
                    load_time_ns,
                )
            except Exception as exc:
                load_time_ns = time.time_ns() - t0
                witness_level = 1
                log.error(
                    "witness_import_execution: failed to import %r: %s",
                    module_name,
                    exc,
                )
            record = ExecutionWitnessRecord(
                module_name=module_name,
                sys_modules_key=module_name,
                load_time_ns=load_time_ns,
                frame_count=frame_count,
                witness_level=witness_level,
            )

        self.witnessed_modules[module_name] = record
        return record

    def record_namespace_delta(
        self,
        before: dict,
        after: dict,
        module_name: str,
    ) -> NamespaceDeltaRecord:
        """
        Compute the namespace delta between two snapshots of a module's globals.

        Parameters
        ----------
        before : dict
            Snapshot of the module's namespace (e.g., ``dict(globals())``)
            taken immediately before executing an import statement.

        after : dict
            Snapshot taken immediately after.

        module_name : str
            Name of the module being analyzed (used as the record's label).

        Returns
        -------
        NamespaceDeltaRecord
            The computed delta.  Also appended to ``self.witnessed_deltas``.

        # copilot: snapshots must be full copies of globals() — not references to the live dict
        """
        before_keys = frozenset(before.keys())
        after_keys = frozenset(after.keys())

        added = after_keys - before_keys
        removed = before_keys - after_keys
        shared = before_keys & after_keys

        # copilot: detect rebindings — same key, different object id
        changed = frozenset(
            k for k in shared if id(before[k]) != id(after[k])
        )

        delta_size = len(added) + len(removed) + len(changed)

        record = NamespaceDeltaRecord(
            module_name=module_name,
            added_names=added,
            removed_names=removed,
            changed_names=changed,
            delta_size=delta_size,
        )
        self.witnessed_deltas.append(record)
        log.debug("record_namespace_delta: %s", record.summary)
        return record

    def build_witness_judgment(self, record: ExecutionWitnessRecord) -> Judgment:
        """
        Construct a jugeo ``Judgment`` from an ``ExecutionWitnessRecord``.

        The proposition states that the module was executed (or retrieved from
        cache) with the recorded timing and frame depth.  The trust level
        corresponds to the ``witness_level`` in the record.

        Parameters
        ----------
        record : ExecutionWitnessRecord
            The witness record to lift into a judgment.

        Returns
        -------
        Judgment
            A fully-populated judgment.

        # copilot: witness judgments carry higher trust than static-analysis judgments
        """
        execution_mode = "cached" if record.was_cache_hit else f"executed in {record.load_time_ns}ns"
        prop = Proposition(
            kind=PropositionKind.BEHAVIORAL,
            statement=(
                f"module '{record.module_name}' import was {execution_mode}, "
                f"witnessed at frame depth {record.frame_count}"
            ),
            label=f"witness::{record.module_name}",
        )
        coord = Coordinate(
            components=(record.module_name,),
            kind=CoordinateKind.MODULE,
            support_labels=frozenset({record.sys_modules_key}),
        )
        carrier = Carrier(
            coordinate=coord,
            payload=record,
            label=f"witness_record::{record.module_name}",
        )
        trust = TrustAnnotation(
            level=record.trust_level,
            rationale=(
                f"Runtime witness at level {record.witness_level}: {execution_mode}"
            ),
        )
        evidence_item = EvidenceItem(
            kind=EvidenceItemKind.RUNTIME_TRACE,
            payload={
                "module_name": record.module_name,
                "load_time_ns": record.load_time_ns,
                "frame_count": record.frame_count,
                "witness_level": record.witness_level,
                "was_cache_hit": record.was_cache_hit,
            },
            label="runtime_witness",
        )
        bundle = EvidenceBundle()
        bundle.add(evidence_item)
        prov = Provenance(
            source=__file__,
            module=__name__,
            timestamp=str(time.time()),
        )
        status = (
            JudgmentStatus.SETTLED
            if record.witness_level >= 2
            else JudgmentStatus.OPEN
        )
        return Judgment(
            status=status,
            proposition=prop,
            carrier=carrier,
            evidence=bundle,
            trust=trust,
            provenance=prov,
            label=f"judgment::witness::{record.module_name}",
        )


