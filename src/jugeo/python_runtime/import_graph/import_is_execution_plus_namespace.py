def analyze_file(path: str) -> tuple:
    """
    Convenience function: parse a file and return (records, judgments).

    Creates a fresh ``ImportExecutionNamespaceTransportCoordinator``, runs it
    on ``path``, and builds a judgment for every record.

    Parameters
    ----------
    path : str
        Filesystem path to a Python source file.

    Returns
    -------
    tuple[list[ImportExecutionRecord], list[Judgment]]
        All records and their corresponding judgments.

    # copilot: shorthand for one-off analysis without managing coordinator state
    """
    coord = ImportExecutionNamespaceTransportCoordinator()
    records = coord.run(path)
    judgments = [coord.build_execution_judgment(r) for r in records]
    return records, judgments


def classify_source_imports(source: str) -> dict:
    """
    Classify all import statements in ``source`` and return a dict mapping
    each ``ImportKind`` to the list of module names imported with that form.

    Parameters
    ----------
    source : str
        Python source code string.

    Returns
    -------
    dict[ImportKind, list[str]]
        Classification result.

    # copilot: useful for quick auditing of import forms in a module
    """
    analyzer = ImportExecutionNamespaceTransportAnalyzer()
    stmts = analyzer.extract_import_statements(source)
    result: dict = {kind: [] for kind in ImportKind}
    for stmt in stmts:
        kind = analyzer.classify_import(stmt)
        if isinstance(stmt, ast.ImportFrom):
            name = stmt.module or "<relative>"
        else:
            name = stmt.names[0].name if stmt.names else "<unknown>"
        result[kind].append(name)
    return result


