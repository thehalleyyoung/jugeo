@dataclass(frozen=True, slots=True)
class ExecutionWitnessRecord:
    """
    Witness that a module's body was executed (or retrieved from cache).

    theory2.tex Ch19 §1 — Execution witness in the judgment sense.

    The CPython import system caches module objects in ``sys.modules``.  After
    the first import of a module, subsequent ``import`` statements retrieve the
    cached object without re-executing the module body.  This record
    distinguishes between a *fresh execution* (module not in ``sys.modules``
    before the import) and a *cache retrieval* (module already present).

    Fields
    ------
    module_name : str
        Fully-qualified name of the module.

    sys_modules_key : str
        The key under which the module is stored in ``sys.modules``.  Usually
        identical to ``module_name`` but can differ for namespace packages or
        modules that manipulate ``sys.modules`` directly.

    load_time_ns : int
        Time in nanoseconds taken to complete the import (0 for cache hits).
        Measured using ``time.time_ns()`` bracketing the import call.

    frame_count : int
        Number of frames on the call stack at the moment the import was
        triggered.  Useful for detecting deeply-nested or circular imports.

    witness_level : int
        Encodes the trust level of this witness:
        1 = spec found by importlib (module exists but not yet loaded),
        2 = module loaded from cache (no re-execution),
        3 = module freshly executed (full execution witness),
        4 = module executed and all assertions passed (verified witness).

    # copilot: load_time_ns=0 means cache hit; load_time_ns>0 means fresh execution
    """

    module_name: str
    sys_modules_key: str
    load_time_ns: int
    frame_count: int
    witness_level: int

    @property
    def was_cache_hit(self) -> bool:
        """
        True if the module was retrieved from ``sys.modules`` without
        re-executing its body.

        A cache hit is identified by ``load_time_ns == 0`` OR by checking
        whether ``sys_modules_key in sys.modules`` was true before the import.
        This property uses only the recorded data (``load_time_ns``).

        # copilot: cache hits have witness_level=2 by convention in this module
        """
        return self.load_time_ns == 0 or self.witness_level == 2

    @property
    def trust_level(self) -> "TrustLevel":
        """
        Map ``witness_level`` to a ``TrustLevel`` enum value for use in
        jugeo judgment construction.

        Mapping:
        - witness_level 1 → TrustLevel.COPILOT_SUGGESTED
        - witness_level 2 → TrustLevel.ORACLE_PROPOSED
        - witness_level 3 → TrustLevel.RUNTIME_WITNESSED
        - witness_level 4 → TrustLevel.VERIFIED

        # copilot: aligns execution witness quality with jugeo's trust hierarchy
        """
        _map = {
            1: TrustLevel.COPILOT_SUGGESTED,
            2: TrustLevel.ORACLE_PROPOSED,
            3: TrustLevel.RUNTIME_WITNESSED,
            4: TrustLevel.VERIFIED,
        }
        return _map.get(self.witness_level, TrustLevel.COPILOT_SUGGESTED)


@dataclass(frozen=True, slots=True)
class NamespaceDeltaRecord:
    """
    Captures the change in a module's public namespace caused by an import.

    theory2.tex Ch19 §1 — Namespace delta as transport measurement.

    A namespace delta is the concrete, observable consequence of the
    "namespace transport" half of the import thesis.  By recording what
    names were added, removed, and changed (i.e., same name but different
    object identity) we obtain a precise accounting of what information
    flowed into the importing namespace.

    Fields
    ------
    module_name : str
        The module whose namespace was altered.  This is the *target* of
        the transport (the importer), not the source.

    added_names : frozenset[str]
        Names that appeared in the namespace after the import that were
        not present before.  These are the successfully transported names.

    removed_names : frozenset[str]
        Names that were present before the import but absent after.
        Non-empty only in unusual cases (e.g., a module body that deletes
        globals, or a ``from m import *`` that shadows then deletes a name).

    changed_names : frozenset[str]
        Names whose binding changed (different ``id()``) without the name
        being added or removed.  Indicates a *rebinding* — typically caused
        by a later ``from m import f`` overwriting a previously imported ``f``.

    delta_size : int
        Total number of name changes: ``len(added) + len(removed) + len(changed)``.
        A convenience field for quick filtering without recomputing set sizes.

    # copilot: delta_size > 0 is a necessary condition for any namespace transport having occurred
    """

    module_name: str
    added_names: frozenset
    removed_names: frozenset
    changed_names: frozenset
    delta_size: int

    @property
    def is_noop(self) -> bool:
        """
        True if this delta represents no observable change to the namespace.

        This can happen when an import is performed purely for its side effects
        (e.g., ``import logging`` when ``logging`` is already in the namespace
        under the same binding) or when ``import m`` is repeated and ``m`` was
        already bound.

        # copilot: noop deltas still represent execution events — the module body ran (or was cached)
        """
        return self.delta_size == 0

    @property
    def summary(self) -> str:
        """
        Human-readable one-liner summarising the delta for log output.

        # copilot: used by the coordinator's logging calls
        """
        return (
            f"NamespaceDelta({self.module_name!r}: "
            f"+{len(self.added_names)} -{len(self.removed_names)} ~{len(self.changed_names)})"
        )


