@dataclass(frozen=True, slots=True)
class ImportExecutionRecord:
    """
    An immutable record of a single import statement's execution.

    theory2.tex Ch19 §1 — Execution witness carrier.

    Each field captures one observable aspect of the import event.  The
    frozen/slots combination ensures that records can be used as dict keys
    and stored in sets without accidental mutation.

    Fields
    ------
    module_name : str
        Fully-qualified name of the module being imported (e.g.,
        ``"jugeo.geometry.site"`` or ``"os.path"``).  For relative imports
        this is the resolved absolute name after package prefix expansion.

    imported_names : tuple[str, ...]
        The specific names extracted into the importing namespace.  Empty
        tuple for ``import foo`` style (the name added is the module's top-
        level identifier, not an attribute).  For ``from m import f, g``
        this would be ``("f", "g")``.

    execution_timestamp : float
        ``time.time()`` value recorded immediately after the import
        completed (or failed).  Useful for reconstructing import ordering
        and detecting import-time races in multi-threaded programs.

    namespace_before : tuple[str, ...]
        Sorted snapshot of ``list(caller_globals.keys())`` taken immediately
        before the import statement was executed.  Stored as a sorted tuple
        for canonical representation and hashability.

    namespace_after : tuple[str, ...]
        Sorted snapshot of ``list(caller_globals.keys())`` taken immediately
        after the import completed.  The delta between this and
        ``namespace_before`` yields the transported names.

    execution_succeeded : bool
        ``True`` if the import completed without raising an exception.
        ``False`` if the import raised ``ImportError``, ``ModuleNotFoundError``,
        or any other exception during module body execution.

    error_message : str
        Empty string when ``execution_succeeded`` is ``True``.  Otherwise
        contains ``str(exc)`` from the caught exception, providing
        diagnostic context.

    # copilot: this record is the central evidence unit for import-execution judgments
    """

    module_name: str
    imported_names: tuple
    execution_timestamp: float
    namespace_before: tuple
    namespace_after: tuple
    execution_succeeded: bool
    error_message: str

    @property
    def transported_names(self) -> frozenset:
        """
        Derive transported names as the set difference between namespace_after
        and namespace_before.

        Returns the frozenset of names that appeared in the namespace after
        the import that were not present before.  This is a pure function of
        the two namespace snapshots and does not require re-execution.

        # copilot: set arithmetic on tuples — convert to frozensets first
        """
        return frozenset(self.namespace_after) - frozenset(self.namespace_before)

    @property
    def removed_names(self) -> frozenset:
        """
        Names that were in namespace_before but not in namespace_after.

        In normal import scenarios this should be empty, but star-imports that
        shadow builtins or ``del`` statements in module bodies can cause names
        to disappear.  This property surfaces such anomalies.

        # copilot: removal of names during import is an anti-pattern worth flagging
        """
        return frozenset(self.namespace_before) - frozenset(self.namespace_after)

    def as_coordinate(self) -> "Coordinate":
        """
        Lift this record to a ``Coordinate`` in the site of modules.

        The coordinate's ``components`` field is set to a one-element tuple
        containing the module name.  The ``kind`` is set to
        ``CoordinateKind.MODULE``.

        # copilot: used by build_execution_judgment to attach records to the site
        """
        return Coordinate(
            components=(self.module_name,),
            kind=CoordinateKind.MODULE,
            support_labels=frozenset(self.imported_names),
        )


@dataclass(frozen=True, slots=True)
class NamespaceTransportResult:
    """
    Immutable record of a namespace transport morphism between two modules.

    theory2.tex Ch19 §1 — Namespace transport morphism.

    When module B imports names from module A, a morphism A → B is created
    in the site of modules.  This record captures the metadata of that
    morphism: what was transported, in which direction, and what coordinate
    object represents the target.

    Fields
    ------
    source_module : str
        Fully-qualified name of the module supplying the names (the domain
        of the morphism, e.g., ``"jugeo.geometry.site"``).

    target_module : str
        Fully-qualified name of the module receiving the names (the codomain,
        e.g., ``"jugeo.python_runtime.import_graph....``).

    transported_names : tuple[str, ...]
        Sorted tuple of the names that were transported.  For a star import
        this is the expansion of ``__all__`` at transport time.

    morphism_kind : str
        String representation of the ``MorphismKind`` value that best
        describes the transport.  Typically ``"inclusion"`` for direct
        imports, ``"restriction"`` for selective (from … import …) imports,
        and ``"transport"`` for aliased imports.

    coordinate : object
        The ``Coordinate`` (or stub equivalent) representing the target module
        in the site.  Used when building judgments to identify the locus of
        the transport event.

    # copilot: this is the dual of ImportExecutionRecord — execution witness vs morphism record
    """

    source_module: str
    target_module: str
    transported_names: tuple
    morphism_kind: str
    coordinate: object

    def as_morphism(self) -> "Morphism":
        """
        Construct a ``Morphism`` site object from this transport result.

        The source coordinate is built from ``source_module`` and the target
        from ``target_module``.  The morphism kind is parsed from the string
        field ``morphism_kind``.

        # copilot: bridges the transport record to the jugeo geometry layer
        """
        src = Coordinate(components=(self.source_module,), kind=CoordinateKind.MODULE)
        tgt = Coordinate(components=(self.target_module,), kind=CoordinateKind.MODULE)
        try:
            mk = MorphismKind(self.morphism_kind)
        except ValueError:
            mk = MorphismKind.INCLUSION
        return Morphism(source=src, target=tgt, kind=mk, label=str(self.transported_names))


