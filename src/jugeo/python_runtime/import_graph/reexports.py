from __future__ import annotations

r"""theory2.tex Ch19 §19.3 — Re-exports and Name Transport Morphisms.

This module implements the re-export analysis pipeline described in theory2.tex
Ch19 §19.3.  The fundamental insight is that ``from X import Y as Z`` is a
*morphism composition* in the import-graph site category: a name ``Y`` is
transported from its defining module ``X`` through the re-exporting module and
re-bound as ``Z`` at the consuming site.  The transport morphism carries trust
metadata so that the trust level of ``Y`` in the consumer is at most the trust
level of the weakest link in the chain.

Architecture
------------
* :class:`ReExportAnalyzer` — entry point; identifies re-export edges in the
  import graph and builds :class:`ReExportMap` objects for each.  The copilot
  evidence channel is consulted when ``__all__`` is absent (the most common
  case) to propose a public API based on naming conventions.
* :class:`StarImportResolver` — resolves ``from X import *`` by looking up
  ``__all__`` in a pre-built table; emits :class:`CoveringFamily` objects
  representing the covering sieve generated by the star import.
* :class:`TrustTransporter` — applies a configurable decay function to
  propagate trust through re-export chains; ensures that a name imported
  through 10 intermediaries cannot reach a higher trust level than a direct
  import.
* :class:`PrivateLeakDetector` — identifies ``_``-prefixed symbols that escape
  through re-exports and converts each leak into an :class:`Obstruction` record
  for the judgment layer.

Theory alignment
----------------
* §19.3.1 — Name transport morphisms and alias composition
* §19.3.2 — ``__all__`` as a covering restriction
* §19.3.3 — Star imports as covering families
* §19.3.4 — Trust transport and decay
* §19.3.5 — Private symbol leakage as cohomological obstruction

The word *copilot* appears throughout because the :class:`CopilotChannel` is
the primary oracle for ``__all__`` inference when ``__all__`` is not explicitly
defined in a module — copilot analyses the module's docstring, naming
conventions, and re-import patterns to propose a public API at
``TrustLevel.COPILOT_SUGGESTED``.
"""

