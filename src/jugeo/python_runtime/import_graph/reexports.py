def _analyze_reexports(
    nodes: list[Any],
    edges: list[Any],
) -> tuple[list[Any], list[Any]]:
    """Analyse re-exports and return ``(maps, leaks)``.

    Creates a :class:`ReExportAnalyzer`, builds all re-export maps, scans for
    private leaks, and returns both results.  Suitable for one-shot copilot-
    assisted re-export analysis.

    Parameters
    ----------
    nodes:
        All :class:`ImportNode` objects.
    edges:
        All :class:`ImportEdge` objects.

    Returns
    -------
    tuple[list[ReExportMap], list[Obstruction]]
        ``(maps, leak_obstructions)``
    """
    analyzer = ReExportAnalyzer(nodes=nodes, edges=edges)
    maps = analyzer.build_reexport_maps()
    detector = PrivateLeakDetector()
    detector.scan_all(maps)
    obstructions = detector.as_obstruction_list()
    return maps, obstructions


def _resolve_all_stars(
    edges: list[Any],
    all_table: dict[str, list[str]],
) -> list[Any]:
    """Resolve all star import edges using *all_table*.

    Creates a :class:`StarImportResolver`, populates it from *all_table*,
    and expands each star edge in *edges*.  Returns the updated edge list with
    star imports replaced by explicit-name edges where possible.

    Parameters
    ----------
    edges:
        All import edges, potentially containing star imports.
    all_table:
        Mapping of module name to ``__all__`` list.

    Returns
    -------
    list[ImportEdge]
        Updated edge list with resolved star imports.
    """
    resolver = StarImportResolver()
    for module_name, names in all_table.items():
        resolver.register_all(module_name, names)
    result: list[Any] = []
    for edge in edges:
        if getattr(edge, "import_kind", "") == "STAR":
            expanded = resolver.expand_star_edge(edge, all_table)
            result.append(expanded)
        else:
            result.append(edge)
    return result


def _transport_trust_through_chain(
    maps: list[Any],
    decay_factor: float = 0.9,
) -> Any:
    """Transport trust through a re-export chain and return the effective level.

    Creates a :class:`TrustTransporter` with *decay_factor* and calls
    :meth:`~TrustTransporter.chain_trust` on *maps*.

    Parameters
    ----------
    maps:
        Ordered re-export chain.
    decay_factor:
        Per-hop trust decay factor.

    Returns
    -------
    TrustLevel
        Effective trust level after transport through the chain.
    """
    transporter = TrustTransporter(decay_factor=decay_factor)
    return transporter.chain_trust(maps)
