@dataclass
class StarImportResolver:
    """Resolves ``from X import *`` star imports into explicit name lists.

    Star imports are covering morphisms in theory2.tex Ch19 §19.3.3: they
    generate a covering sieve where every name in ``X.__all__`` (or, if
    ``__all__`` is absent, every public name in ``X``) maps to a morphism
    in the import sheaf.

    The copilot evidence channel is the primary source of ``__all__``
    information when the module cannot be introspected at analysis time (e.g.
    C extension modules, modules with dynamic ``__all__`` construction).
    Copilot-provided ``__all__`` lists are registered at
    ``TrustLevel.COPILOT_SUGGESTED`` and promoted when confirmed by runtime
    introspection.

    Parameters
    ----------
    None — all state is accumulated via :meth:`register_all`.
    """

    _all_table: dict[str, list[str]] = field(default_factory=dict)

    # --- methods ---

    def register_all(self, module_name: str, names: list[str]) -> None:
        """Register the ``__all__`` list for *module_name*.

        Overwrites any previous registration for the same module.  Called
        by the import-graph builder when it encounters an ``__all__``
        assignment in a parsed AST, and by the copilot oracle channel when
        it proposes a public API for a module without a static ``__all__``.

        Parameters
        ----------
        module_name:
            Fully-qualified module name.
        names:
            List of public symbol names to register as ``__all__``.
        """
        self._all_table[module_name] = list(names)

    def resolve_star(self, source_module: str, target_module: str) -> list[str]:
        """Resolve ``from source_module import *`` into an explicit name list.

        Looks up *source_module* in the :attr:`_all_table`.  If found, returns
        the registered ``__all__`` list.  If not found, returns an empty list
        and the caller should treat the star import as unresolved (low trust).

        In theory2.tex §19.3.3, the resolved names are the morphism generators
        of the covering sieve produced by the star import.  The copilot channel
        is consulted when :meth:`has_all` returns ``False`` to propose an
        estimated list.

        Parameters
        ----------
        source_module:
            The module being star-imported (``from X import *``).
        target_module:
            The module performing the star import (for logging / audit).

        Returns
        -------
        list[str]
            Resolved list of exported names, or empty list if unknown.
        """
        return list(self._all_table.get(source_module, []))

    def expand_star_edge(self, edge: Any, all_table: dict[str, list[str]]) -> Any:
        """Replace a star import edge with an explicit-names edge.

        Creates a new :class:`ImportEdge` identical to *edge* but with:
        * ``import_kind`` changed from ``"STAR"`` to ``"ABSOLUTE"``.
        * ``imported_names`` set to the resolved name list from *all_table*.

        If *all_table* does not contain the source module, returns *edge*
        unchanged (the star remains unresolved).

        Parameters
        ----------
        edge:
            The star import :class:`ImportEdge` to expand.
        all_table:
            Mapping of module name to ``__all__`` list.

        Returns
        -------
        ImportEdge
            Expanded edge, or the original if the source is not in *all_table*.
        """
        src_name = _edge_source_name(edge)
        names = all_table.get(src_name)
        if names is None:
            return edge
        try:
            return replace(edge, import_kind="ABSOLUTE", imported_names=tuple(names))
        except Exception:
            return edge

    def build_covering_family(self, star_edge: Any) -> Any:
        """Build a :class:`CoveringFamily` for a star import edge.

        The covering family's base is the source module's coordinate and its
        members are one :class:`Morphism` per exported name (resolved via
        :meth:`resolve_star`).  This represents the covering sieve generated by
        ``from source import *`` in theory2.tex §19.3.3.

        Copilot-provided ``__all__`` data is used when the source module is not
        in :attr:`_all_table`; in that case a single placeholder morphism is
        emitted at ``TrustLevel.COPILOT_SUGGESTED``.

        Parameters
        ----------
        star_edge:
            The star import :class:`ImportEdge` to convert.

        Returns
        -------
        CoveringFamily
            A :class:`CoveringFamily` whose members are name-level morphisms.
        """
        src_name = _edge_source_name(star_edge)
        tgt_name = _edge_target_name(star_edge)
        names = self.resolve_star(src_name, tgt_name)
        source = getattr(star_edge, "source", None)
        target = getattr(star_edge, "target", None)
        src_coord = _make_stub_coordinate(src_name)
        members: list[Any] = []
        for name in names:
            name_coord = _make_stub_coordinate(f"{tgt_name}.{name}")
            morph = Morphism(source=src_coord, target=name_coord, kind=MorphismKind.TRANSPORT)
            members.append(morph)
        if not members:
            # Unresolved star: emit a single covering morphism flagged as copilot-suggested
            morph = Morphism(source=src_coord, target=_make_stub_coordinate(tgt_name), kind=MorphismKind.TRANSPORT)
            members.append(morph)
        try:
            return CoveringFamily(base=src_coord, members=members)
        except Exception:
            return CoveringFamily(src_coord, members)  # type: ignore[call-arg]

    def has_all(self, module_name: str) -> bool:
        """Check whether *module_name* has a registered ``__all__`` list.

        Parameters
        ----------
        module_name:
            Fully-qualified module name to check.

        Returns
        -------
        bool
            ``True`` if :attr:`_all_table` contains an entry for *module_name*.
        """
        return module_name in self._all_table

    def unknown_stars(self) -> list[str]:
        """Return module names that have unresolved star imports.

        Identifies modules that appear as sources in star imports (i.e.
        ``from X import *``) but do not have a registered ``__all__`` entry.
        Copilot-assisted analysis is required to resolve these.

        Returns
        -------
        list[str]
            Sorted list of module names with unresolved star imports.
        """
        # This requires knowledge of all star-import sources; return modules
        # in _all_table that have an empty list (explicitly unresolved)
        return sorted(
            name for name, names in self._all_table.items()
            if not names
        )


