@dataclass
class TrustTransporter:
    """Transports trust through re-export chains with configurable decay.

    In theory2.tex Ch19 §19.3.4, every re-export hop weakens the trust of the
    transported name.  A name proven at ``RUNTIME_WITNESSED`` in module ``C``
    that reaches module ``A`` through two re-export hops arrives at a trust
    level of at most ``int(3 * 0.9^2) = 2`` (``COPILOT_SUGGESTED``).

    The decay model is simple but conservative: it prevents copilot-suggested
    names from masquerading as runtime-witnessed just because they were
    re-exported through a trusted module.  The copilot display layer uses
    :meth:`explain_trust_path` to render a trust-chain breadcrumb.

    Parameters
    ----------
    decay_factor:
        Multiplicative decay applied to the trust integer per hop.
        Default is 0.9 (10% decay per hop).
    """

    decay_factor: float = 0.9

    # --- methods ---

    def transport(self, source_trust: Any, hops: int) -> Any:
        """Apply trust decay over *hops* re-export steps.

        Computes ``max(1, int(source_trust_value * decay_factor^hops))`` and
        returns the corresponding :class:`TrustLevel`.  The floor at
        ``UNVERIFIED`` (value 1) ensures that a name is never completely
        discarded by the transport mechanism.

        Parameters
        ----------
        source_trust:
            The :class:`TrustLevel` of the name in its defining module.
        hops:
            Number of re-export hops between the defining module and the
            consuming module.

        Returns
        -------
        TrustLevel
            Decayed trust level after *hops* transport steps.
        """
        if hops <= 0:
            return source_trust
        raw_value = _trust_int(source_trust)
        decayed = max(1, int(raw_value * (self.decay_factor ** hops)))
        return _trust_from_int(decayed)

    def chain_trust(self, maps: list[Any]) -> Any:
        """Compute the minimum trust across a chain of :class:`ReExportMap` objects.

        The trust of a name transported through a chain is bounded by the
        weakest link — the map with the lowest trust level.  This corresponds
        to the *infimum* in the trust lattice for the composed morphism.

        Parameters
        ----------
        maps:
            Ordered list of :class:`ReExportMap` objects forming the chain.

        Returns
        -------
        TrustLevel
            The minimum trust level across all maps in the chain.
        """
        if not maps:
            return TrustLevel.UNVERIFIED
        min_trust = _trust_int(getattr(maps[0], "trust", TrustLevel.COPILOT_SUGGESTED))
        for remap in maps[1:]:
            trust_val = _trust_int(getattr(remap, "trust", TrustLevel.COPILOT_SUGGESTED))
            if trust_val < min_trust:
                min_trust = trust_val
        return _trust_from_int(min_trust)

    def annotate_map(self, remap: Any) -> Any:
        """Return a new :class:`ReExportMap` with trust updated by decay.

        Applies :meth:`transport` with ``hops=1`` to the trust level of
        *remap*, producing a new map where trust reflects one re-export step.
        Uses :func:`dataclasses.replace` to preserve all other fields.

        Parameters
        ----------
        remap:
            The :class:`ReExportMap` to annotate.

        Returns
        -------
        ReExportMap
            A new map with decayed trust.
        """
        current_trust = getattr(remap, "trust", TrustLevel.COPILOT_SUGGESTED)
        new_trust = self.transport(current_trust, hops=1)
        try:
            return replace(remap, trust=new_trust)
        except Exception:
            return remap

    def build_trust_annotation(self, maps: list[Any]) -> Any:
        """Build a :class:`TrustAnnotation` for a re-export chain.

        Computes the chain trust via :meth:`chain_trust` and packages it in a
        :class:`TrustAnnotation` record suitable for the jugeo judgment layer.
        The annotation notes that the trust was computed by the copilot
        transport model.

        Parameters
        ----------
        maps:
            Ordered list of :class:`ReExportMap` objects forming the chain.

        Returns
        -------
        TrustAnnotation
            A :class:`TrustAnnotation` recording the chain trust and provenance.
        """
        chain_t = self.chain_trust(maps)
        hop_count = len(maps)
        notes = (
            f"Trust transported through {hop_count} re-export hop(s) "
            f"using copilot decay model (factor={self.decay_factor}). "
            f"Chain trust: {chain_t}."
        )
        try:
            annotation = TrustAnnotation(
                trust_level=chain_t,
                annotated_at=_now_iso(),
                source="copilot_transport_model",
                notes=notes,
            )
        except Exception:
            annotation = TrustAnnotation(
                trust_level=chain_t,
                annotated_at=_now_iso(),
            )
        return annotation

    def max_allowed_trust_for_dynamic(self, loader: str) -> Any:
        """Return the maximum allowed trust for a dynamically-loaded name.

        Dynamic loaders such as ``importlib.import_module``,
        ``__import__``, and ``pkgutil`` cannot be statically analysed, so
        names loaded through them are capped at ``COPILOT_SUGGESTED``.
        Known static loaders (``importlib.util.spec_from_file_location``)
        are allowed up to ``RUNTIME_WITNESSED``.

        The copilot evidence channel uses this method to enforce trust ceilings
        when tagging dynamically-constructed import edges.

        Parameters
        ----------
        loader:
            A string identifier for the loading mechanism (e.g.
            ``"importlib.import_module"``, ``"__import__"``,
            ``"spec_from_file_location"``).

        Returns
        -------
        TrustLevel
            The maximum allowed :class:`TrustLevel` for the loader.
        """
        _STATIC_LOADERS = {
            "spec_from_file_location",
            "importlib.util.spec_from_file_location",
            "importlib.util.find_spec",
        }
        if loader in _STATIC_LOADERS:
            return TrustLevel.RUNTIME_WITNESSED
        return TrustLevel.COPILOT_SUGGESTED

    def explain_trust_path(self, maps: list[Any]) -> list[str]:
        """Return explanation strings for the trust path through *maps*.

        Generates one line per re-export hop describing the source module,
        target module, and trust level after the hop.  The final line
        summarises the overall chain trust.  These explanations are used by
        the copilot display layer to render trust-chain breadcrumbs.

        Parameters
        ----------
        maps:
            Ordered list of :class:`ReExportMap` objects forming the chain.

        Returns
        -------
        list[str]
            Human-readable explanation of the trust path.
        """
        lines: list[str] = []
        current_trust = TrustLevel.VERIFIED_PROOF  # Start at maximum
        for i, remap in enumerate(maps):
            src = _remap_source_name(remap)
            tgt = _remap_target_name(remap)
            hop_trust = getattr(remap, "trust", TrustLevel.COPILOT_SUGGESTED)
            transported = self.transport(current_trust, hops=1)
            effective = _trust_from_int(min(_trust_int(hop_trust), _trust_int(transported)))
            lines.append(
                f"  hop {i+1}: {src} -> {tgt} "
                f"(edge trust={hop_trust}, transported={transported}, "
                f"effective={effective})"
            )
            current_trust = effective
        chain = self.chain_trust(maps)
        lines.append(f"  Final chain trust: {chain}")
        lines.append(
            "  (copilot transport model applied; promote hops to RUNTIME_WITNESSED "
            "to improve chain trust)"
        )
        return lines


