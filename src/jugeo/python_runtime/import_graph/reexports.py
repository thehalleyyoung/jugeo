@dataclass
class ReExportAnalyzer:
    """Analyses re-export patterns in a Python import graph.

    Identifies edges that represent name transports (``from X import Y as Z``),
    builds :class:`ReExportMap` objects for each, and provides utilities for
    tracing a name back to its defining module.

    In theory2.tex Ch19 §19.3.1, re-exports are *morphism compositions*: the
    chain ``A imports Y from B, B imports Y from C`` creates a composed morphism
    from ``A`` to ``C`` via ``B``.  The composed morphism's trust is bounded
    by the weakest trust in the chain.

    The copilot evidence channel (:class:`CopilotChannel`) is queried when an
    edge's ``alias_map`` is empty but its ``imported_names`` is non-empty, to
    infer whether the names are re-exported or merely used locally.  Copilot-
    proposed re-export classifications enter at ``TrustLevel.COPILOT_SUGGESTED``.

    Parameters
    ----------
    nodes:
        All :class:`ImportNode` objects in the project.
    edges:
        All :class:`ImportEdge` objects in the project.
    """

    nodes: list[Any]
    edges: list[Any]

    # --- methods ---

    def find_reexport_edges(self) -> list[Any]:
        """Filter and return edges that represent re-exports.

        An edge is considered a re-export if:
        * :meth:`~ImportEdge.is_re_export` returns ``True``, **or**
        * The edge has a non-empty ``alias_map`` (``from X import Y as Z``), **or**
        * The edge's ``import_kind`` is ``"STAR"`` (all names are re-exported).

        The copilot evidence channel may additionally flag edges as re-exports
        based on module-level ``__all__`` analysis.

        Returns
        -------
        list[ImportEdge]
            All edges in :attr:`edges` that are classified as re-exports.
        """
        result: list[Any] = []
        for edge in self.edges:
            is_reexport = False
            if hasattr(edge, "is_re_export") and callable(edge.is_re_export):
                try:
                    is_reexport = edge.is_re_export()
                except Exception:
                    pass
            if not is_reexport:
                alias_map = getattr(edge, "alias_map", {})
                import_kind = getattr(edge, "import_kind", "ABSOLUTE")
                if alias_map or import_kind == "STAR":
                    is_reexport = True
            if is_reexport:
                result.append(edge)
        return result

    def build_reexport_maps(self) -> list[Any]:
        """Build a :class:`ReExportMap` for each re-export edge.

        Converts the ``alias_map`` and ``imported_names`` of each re-export
        edge into a :class:`ReExportMap` object.  When the ``alias_map`` is
        empty, the identity mapping is used (imported name = exported name).

        Returns
        -------
        list[ReExportMap]
            One :class:`ReExportMap` per re-export edge.
        """
        maps: list[Any] = []
        for edge in self.find_reexport_edges():
            source = edge.source if hasattr(edge, "source") else None
            target = edge.target if hasattr(edge, "target") else None
            if source is None or target is None:
                continue
            alias_map: dict[str, str] = {}
            if hasattr(edge, "alias_map") and edge.alias_map:
                alias_map = dict(edge.alias_map)
            imported_names = tuple(getattr(edge, "imported_names", ()))
            # Build exported_names: alias targets if aliased, else imported names
            if alias_map:
                exported_names = tuple(alias_map.values())
            elif imported_names:
                exported_names = imported_names
            else:
                exported_names = ()
            trust = getattr(edge, "trust", TrustLevel.COPILOT_SUGGESTED)
            is_star = getattr(edge, "import_kind", "") == "STAR"
            remap = ReExportMap(
                source_module=source,
                target_module=target,
                name_map=alias_map,
                exported_names=exported_names,
                trust=trust,
                is_star_import=is_star,
                metadata={
                    "import_kind": getattr(edge, "import_kind", "ABSOLUTE"),
                    "copilot_classified": _trust_int(trust) <= 2,
                },
            )
            maps.append(remap)
        return maps

    def reexports_from(self, module: Any) -> list[Any]:
        """Return all :class:`ReExportMap` objects originating from *module*.

        Parameters
        ----------
        module:
            The source :class:`ImportNode` or module name string.

        Returns
        -------
        list[ReExportMap]
            All re-export maps whose source is *module*.
        """
        target_name = _node_name(module)
        return [
            remap for remap in self.build_reexport_maps()
            if _remap_source_name(remap) == target_name
        ]

    def reexports_to(self, module: Any) -> list[Any]:
        """Return all :class:`ReExportMap` objects targeting *module*.

        Parameters
        ----------
        module:
            The target :class:`ImportNode` or module name string.

        Returns
        -------
        list[ReExportMap]
            All re-export maps whose target is *module*.
        """
        target_name = _node_name(module)
        return [
            remap for remap in self.build_reexport_maps()
            if _remap_target_name(remap) == target_name
        ]

    def public_api_of(
        self,
        module: Any,
        all_names: list[str] | None = None,
    ) -> list[str]:
        """Determine the public API of *module*.

        If *all_names* is provided (the contents of ``__all__``), returns it
        directly.  Otherwise filters all exported names in the re-export maps
        from *module* that do not start with ``_``.  When neither source of
        information is available, the copilot oracle proposes a public API based
        on naming conventions and the module's re-import patterns.

        Parameters
        ----------
        module:
            An :class:`ImportNode` whose public API to determine.
        all_names:
            Explicit ``__all__`` list, or ``None`` to infer from re-exports.

        Returns
        -------
        list[str]
            Sorted list of public API symbol names.
        """
        if all_names is not None:
            return sorted(all_names)
        # Infer from re-export maps
        public: list[str] = []
        for remap in self.reexports_from(module):
            for name in _remap_exported_names(remap):
                if not _is_private_name(name):
                    public.append(name)
        # Also include imported_names from direct edges into this module
        module_name = _node_name(module)
        for edge in self.edges:
            if _edge_source_name(edge) == module_name:
                for name in getattr(edge, "imported_names", ()):
                    if not _is_private_name(name) and name not in public:
                        public.append(name)
        return sorted(set(public))

    def detect_all_stars(self) -> list[Any]:
        """Find all star import edges (``from X import *``).

        Filters :attr:`edges` for those whose ``import_kind`` is ``"STAR"``.
        Star imports generate covering families in the site topology and must
        be resolved by :class:`StarImportResolver` to determine the full set
        of transported names.  Copilot analysis flags unresolved stars as
        low-trust edges.

        Returns
        -------
        list[ImportEdge]
            All star import edges.
        """
        return [
            edge for edge in self.edges
            if getattr(edge, "import_kind", "") == "STAR"
        ]

    def name_origin(
        self,
        name: str,
        module: Any,
        maps: list[Any],
    ) -> Any | None:
        """Trace *name* back to its defining module through re-export chains.

        Performs a backwards BFS through *maps* starting from *module*,
        following each :class:`ReExportMap` that exports *name*, until reaching
        a module that does not import *name* from elsewhere (its defining
        module).  Copilot-assisted tracing provides hints when the chain is
        broken by a star import with an unresolved ``__all__``.

        Parameters
        ----------
        name:
            The symbol name to trace.
        module:
            The :class:`ImportNode` where *name* is currently visible.
        maps:
            All :class:`ReExportMap` objects to search through.

        Returns
        -------
        ImportNode | None
            The :class:`ImportNode` that originally defines *name*, or ``None``
            if the origin cannot be determined.
        """
        module_name = _node_name(module)
        visited: set[str] = {module_name}
        current_name = module_name

        for _ in range(50):  # Limit chain depth to avoid infinite loops
            # Find a map that exports `name` from `current_name`
            candidate = None
            for remap in maps:
                if _remap_target_name(remap) == current_name:
                    exported = _remap_exported_names(remap)
                    # Also check name_map for aliased re-exports
                    name_map = getattr(remap, "name_map", {})
                    original_name = {v: k for k, v in name_map.items()}.get(name, name)
                    if name in exported or original_name in exported:
                        src = _remap_source_name(remap)
                        if src not in visited:
                            candidate = src
                            break
            if candidate is None:
                # Current module is the defining module
                node_by_name = {_node_name(n): n for n in self.nodes}
                return node_by_name.get(current_name)
            visited.add(candidate)
            current_name = candidate
        return None


