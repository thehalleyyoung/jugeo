@dataclass
class PrivateLeakDetector:
    """Detects private symbols that leak through public re-exports.

    In theory2.tex Ch19 §19.3.5, private-symbol leakage is a cohomological
    obstruction: it means the module's public interface does not form a valid
    covering family because it includes names that violate the module's stated
    encapsulation boundary.

    The detector scans all :class:`ReExportMap` objects for names starting
    with ``_`` that appear in exported positions.  Each leak becomes an
    :class:`Obstruction` with ``cohomology_class="PRIVATE_LEAK"`` and
    copilot-generated repair hints.

    The copilot evidence channel contributes to this analysis by flagging
    patterns such as ``from ._internal import _helper`` in a package
    ``__init__.py`` where ``_helper`` appears in ``__all__`` — a common mistake
    in auto-generated code.
    """

    _leaks: list[tuple[Any, str]] = field(default_factory=list)

    # --- methods ---

    def scan_map(self, remap: Any) -> list[str]:
        """Scan a :class:`ReExportMap` for private names in exported positions.

        Returns the list of private names (starting with ``_`` but not dunder)
        that appear in the map's ``exported_names`` list and are marked as
        public (i.e. would appear in ``__all__``).

        Parameters
        ----------
        remap:
            A :class:`ReExportMap` to scan.

        Returns
        -------
        list[str]
            List of private names that are exported.
        """
        exported = _remap_exported_names(remap)
        return [name for name in exported if _is_private_name(name)]

    def scan_all(self, maps: list[Any]) -> None:
        """Scan all :class:`ReExportMap` objects and populate :attr:`_leaks`.

        Calls :meth:`scan_map` for each map and appends
        ``(source_module_node, leaked_name)`` tuples to :attr:`_leaks` for
        every detected leak.  Clears any previous leaks before scanning.

        Parameters
        ----------
        maps:
            All :class:`ReExportMap` objects to scan.
        """
        self._leaks = []
        for remap in maps:
            leaked_names = self.scan_map(remap)
            target = getattr(remap, "target_module", None)
            if target is None:
                continue
            for name in leaked_names:
                self._leaks.append((target, name))

    def leaked_symbols(self) -> list[tuple[Any, str]]:
        """Return all detected ``(module, leaked_name)`` pairs.

        Returns
        -------
        list[tuple[ImportNode, str]]
            All leaks accumulated by :meth:`scan_all`.
        """
        return list(self._leaks)

    def has_leaks(self) -> bool:
        """Return ``True`` if any private leaks were detected.

        Returns
        -------
        bool
            ``True`` when :attr:`_leaks` is non-empty.
        """
        return len(self._leaks) > 0

    def severity_score(self, module: Any) -> float:
        """Compute the leak severity score for *module*.

        Returns the ratio of leaked private names to the total number of
        exported names for *module* across all scanned re-export maps.  A
        score of 0.0 means no leaks; 1.0 means all exported names are private.

        The copilot display layer renders this score as a severity badge on the
        module's import-graph node.

        Parameters
        ----------
        module:
            The :class:`ImportNode` to score.

        Returns
        -------
        float
            Leak severity in [0.0, 1.0].
        """
        module_name = _node_name(module)
        leaked_for_module = [
            name for (mod, name) in self._leaks
            if _node_name(mod) == module_name
        ]
        # Count total exported names for this module across all known leaks
        # We use the leaked count as numerator and estimate denominator
        # from the unique leaked names (conservative lower bound)
        total_leaked = len(leaked_for_module)
        if total_leaked == 0:
            return 0.0
        # Without access to all exported names, use number of unique leaked names
        # as a fraction of itself + an estimated clean export count (heuristic: 5)
        estimated_total = total_leaked + 5
        return total_leaked / estimated_total

    def report(self) -> str:
        """Generate a human-readable report of all detected private leaks.

        Lists each leaked symbol, its module, and a copilot-generated repair
        hint.  Returns ``"No private symbol leaks detected."`` if :attr:`_leaks`
        is empty.

        Returns
        -------
        str
            Multi-line report string.
        """
        if not self._leaks:
            return "No private symbol leaks detected."
        lines: list[str] = [
            "=== Private Symbol Leak Report ===",
            f"Total leaks: {len(self._leaks)}",
            "",
        ]
        by_module: dict[str, list[str]] = {}
        for mod, name in self._leaks:
            key = _node_name(mod)
            by_module.setdefault(key, []).append(name)
        for module_name, leaked_names in sorted(by_module.items()):
            lines.append(f"Module: {module_name}")
            for name in sorted(leaked_names):
                lines.append(f"  LEAK: '{name}' is private but appears in re-exported names.")
                lines.append(
                    f"    Copilot hint: consider removing '{name}' from __all__ or "
                    f"renaming it to a public name."
                )
        lines.append("")
        lines.append(
            "Note: copilot-assisted analysis may flag false positives for "
            "intentionally-exported private symbols (e.g. semi-public APIs). "
            "Review each leak before applying the suggested repair."
        )
        return "\n".join(lines)

    def as_obstruction_list(self) -> list[Any]:
        """Convert each detected leak to an :class:`Obstruction` record.

        Each ``(module, leaked_name)`` pair becomes one :class:`Obstruction`
        with ``cohomology_class="PRIVATE_LEAK"`` and copilot-generated
        ``repair_hints``.  The ``obstruction_id`` is a stable hash of the
        module name and symbol name so that the same leak produces the same ID
        across multiple analysis runs.

        Returns
        -------
        list[Obstruction]
            One :class:`Obstruction` per detected private symbol leak.
        """
        obstructions: list[Any] = []
        for mod, name in self._leaks:
            module_name = _node_name(mod)
            obs_id = _stable_hash(f"PRIVATE_LEAK:{module_name}:{name}")
            repair = (
                f"Remove '{name}' from the public re-export list of '{module_name}', "
                f"or rename it to a public symbol. "
                f"Copilot suggests introducing a public alias: "
                f"'{name.lstrip('_')}' = {name}."
            )
            obs = Obstruction(
                obstruction_id=obs_id,
                violated_condition="private_symbol_leaked",
                coordinate=module_name,
                evidence_at_time=(name,),
                repair_hints=(repair,),
                cohomology_class="PRIVATE_LEAK",
                is_resolved=False,
                resolution_evidence="",
            )
            obstructions.append(obs)
        return obstructions


