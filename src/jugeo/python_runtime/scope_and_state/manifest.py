@dataclass(frozen=True, slots=True)
class ComponentRegistration:
    """Immutable record describing a single component registered with the manifest.

    A *component* is the smallest deployable unit of analytic functionality within
    the ``scope_and_state`` package.  Each component is associated with exactly one
    :class:`Capability` and a *coordinate prefix* that delimits the region of the
    site over which the component operates (cf. theory2.tex Ch15, Definition 15.2:
    \"a component is a local section over an open set of the capability sheaf\").

    The *coordinate prefix* is a slash-separated string such as
    ``"jugeo/python_runtime/scope_and_state"`` that matches the leading path of any
    :class:`~jugeo.geometry.site.Coordinate` key whose analysis is owned by this
    component.  Two components registered for the same capability may not share a
    coordinate prefix (this would violate the separation condition from Lemma 15.6).

    Parameters
    ----------
    name : str
        Unique, human-readable identifier for this component.  Must be a non-empty
        string containing only ASCII letters, digits, underscores, and hyphens.
    capability : Capability
        The single :class:`Capability` this component provides.
    description : str
        A non-empty, human-readable description of what the component does.  Used
        in ``validate()`` output and in generated documentation.
    coordinate_prefix : str
        The slash-separated coordinate prefix string that limits the scope of this
        component.  Must be a non-empty string.
    enabled : bool
        Whether the component is active.  Disabled components are enumerated by
        :meth:`PackageManifest.validate` but excluded from
        :meth:`PackageManifest.enabled_capabilities`.
    metadata : dict[str, Any]
        Arbitrary JSON-serialisable extra data.  Consumers must not depend on the
        structure of this dict for correctness.

    Examples
    --------
    Create a basic registration:

    >>> reg = ComponentRegistration(
    ...     name="legb_resolver",
    ...     capability=Capability.NAME_RESOLUTION,
    ...     description="Implements the LEGB lookup rule for Python name resolution.",
    ...     coordinate_prefix="jugeo/python_runtime",
    ... )
    >>> reg.name
    'legb_resolver'
    >>> reg.enabled
    True

    Serialise and round-trip:

    >>> data = reg.serialize()
    >>> reg2 = ComponentRegistration.parse(data)
    >>> reg == reg2
    True

    Create a disabled placeholder:

    >>> placeholder = ComponentRegistration(
    ...     name="experimental_resolver",
    ...     capability=Capability.NAME_RESOLUTION,
    ...     description="Experimental star-import resolver (not yet ready).",
    ...     coordinate_prefix="jugeo/python_runtime/experimental",
    ...     enabled=False,
    ...     metadata={"author": "research-team", "ticket": "JGO-999"},
    ... )
    >>> placeholder.enabled
    False

    Use ``dataclasses.replace`` to enable it later:

    >>> enabled = replace(placeholder, enabled=True)
    >>> enabled.enabled
    True

    Access metadata:

    >>> placeholder.metadata["ticket"]
    'JGO-999'
    """

    name: str
    capability: Capability
    description: str
    coordinate_prefix: str
    enabled: bool = True
    metadata: dict[str, Any] = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def serialize(self) -> dict[str, Any]:
        """Convert this registration to a JSON-compatible dictionary.

        Returns
        -------
        dict[str, Any]
            A flat mapping with keys ``name``, ``capability``, ``description``,
            ``coordinate_prefix``, ``enabled``, and ``metadata``.  All values are
            JSON-serialisable primitives or dicts.

        Examples
        --------
        >>> reg = ComponentRegistration(
        ...     name="scope_builder",
        ...     capability=Capability.SCOPE_ANALYSIS,
        ...     description="Builds scope trees.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... )
        >>> d = reg.serialize()
        >>> d["capability"]
        'scope_analysis'
        >>> d["enabled"]
        True
        """
        return {
            "name": self.name,
            "capability": self.capability.value,
            "description": self.description,
            "coordinate_prefix": self.coordinate_prefix,
            "enabled": self.enabled,
            "metadata": dict(self.metadata),
        }

    @classmethod
    def parse(cls, data: dict[str, Any]) -> ComponentRegistration:
        """Reconstruct a :class:`ComponentRegistration` from a serialised dictionary.

        Parameters
        ----------
        data : dict[str, Any]
            A mapping previously produced by :meth:`serialize`.  Unknown keys are
            ignored to allow forward-compatible evolution of the schema.

        Returns
        -------
        ComponentRegistration
            The reconstructed instance.

        Raises
        ------
        KeyError
            If any of the required keys (``name``, ``capability``, ``description``,
            ``coordinate_prefix``) are absent from *data*.
        ValueError
            If the ``capability`` value is not a valid :class:`Capability` member.

        Examples
        --------
        >>> raw = {
        ...     "name": "closure_lifter",
        ...     "capability": "closure_lifting",
        ...     "description": "Lifts free variables.",
        ...     "coordinate_prefix": "jugeo/python_runtime",
        ...     "enabled": True,
        ...     "metadata": {},
        ... }
        >>> reg = ComponentRegistration.parse(raw)
        >>> reg.capability
        <Capability.CLOSURE_LIFTING: 'closure_lifting'>
        """
        try:
            capability = Capability(data["capability"])
        except (KeyError, ValueError) as exc:
            raise ValueError(
                f"Invalid capability value in serialised data: {data.get('capability')!r}"
            ) from exc
        return cls(
            name=data["name"],
            capability=capability,
            description=data["description"],
            coordinate_prefix=data["coordinate_prefix"],
            enabled=bool(data.get("enabled", True)),
            metadata=dict(data.get("metadata", {})),
        )


