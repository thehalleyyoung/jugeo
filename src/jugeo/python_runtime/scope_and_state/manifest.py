"""Package manifest for the ``scope_and_state`` sub-package of the JuGeo Python runtime.

This module defines the capability registry and component-registration mechanism for the
``scope_and_state`` package.  Every component that participates in scope analysis, name
resolution, closure lifting, module-state tracking, or binding-map queries declares a
:class:`ComponentRegistration` here, and the singleton :data:`MANIFEST` accumulates the
full set at import time.

Theory connection — theory2.tex Ch15
-------------------------------------
Chapter 15 of *theory2.tex* (\"Sheaves on the Python Runtime Site\") introduces the notion
of a *coordinate-indexed capability lattice*.  Each capability is a "stalk" of a sheaf of
analytic power over the site of Python program points.  The manifest plays the role of the
*cover description*: it enumerates which coordinate prefixes (sheaf opens) are served by
which components, and provides the gluing data that lets the descent machinery compose
cross-component analyses without double-counting.

The five canonical capabilities—:attr:`Capability.NAME_RESOLUTION`,
:attr:`Capability.SCOPE_ANALYSIS`, :attr:`Capability.CLOSURE_LIFTING`,
:attr:`Capability.MODULE_STATE_TRACKING`, and :attr:`Capability.BINDING_MAP_QUERY`—map to
the five stalks of the *scope sheaf* described in §15.3, and the validation rules in
:meth:`PackageManifest.validate` enforce the local-triviality conditions from Lemma 15.7
(no two components may claim the same name, and every component must have a non-empty
description so the sheaf can reconstruct its data from the cover).

Practical usage
---------------
Import :data:`MANIFEST` from this module to discover which capabilities are active:

>>> from jugeo.python_runtime.scope_and_state.manifest import MANIFEST, Capability
>>> caps = MANIFEST.enabled_capabilities()
>>> Capability.SCOPE_ANALYSIS in caps
True

To add a custom component during testing::

    from jugeo.python_runtime.scope_and_state.manifest import (
        MANIFEST, ComponentRegistration, Capability
    )
    reg = ComponentRegistration(
        name="my_custom_resolver",
        capability=Capability.NAME_RESOLUTION,
        description="Prototype resolver for starred imports.",
        coordinate_prefix="jugeo/python_runtime",
    )
    MANIFEST.register(reg)

Generated by copilot tooling; maintained manually.
"""

