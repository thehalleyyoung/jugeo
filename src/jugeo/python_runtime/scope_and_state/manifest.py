class Capability(str, Enum):
    """The five analytic capabilities exported by the ``scope_and_state`` package.

    Each value corresponds to one \"stalk\" of the scope sheaf as described in
    theory2.tex Ch15, §15.3.  The string values are stable identifiers that appear
    in serialised manifests, so they must never be changed without a migration.

    Attributes
    ----------
    NAME_RESOLUTION:
        Resolve an unqualified Python name to a fully-qualified
        :class:`~jugeo.python_runtime.scope_and_state.models.NameCoordinate`.
        Implements the lookup rules from the LEGB rule under sheaf-theoretic framing.
    SCOPE_ANALYSIS:
        Build the complete scope tree for a Python module or function.  Produces a
        sequence of :class:`~jugeo.python_runtime.scope_and_state.models.ScopeSection`
        objects that cover every reachable binding site.
    CLOSURE_LIFTING:
        Detect free variables, compute cell assignments, and emit
        :class:`~jugeo.python_runtime.scope_and_state.models.ClosureRecord` objects
        describing each nested function's capture set.
    MODULE_STATE_TRACKING:
        Snapshot the global-namespace state of a module as a
        :class:`~jugeo.python_runtime.scope_and_state.models.ModuleStateManifest`.
        Tracks dunder attributes and import-side-effects.
    BINDING_MAP_QUERY:
        Provide a snapshot-consistent
        :class:`~jugeo.python_runtime.scope_and_state.models.BindingMap` that can be
        queried by name, merged with other maps, and serialised for offline analysis.

    Examples
    --------
    >>> Capability.NAME_RESOLUTION.value
    'name_resolution'
    >>> list(Capability)  # doctest: +NORMALIZE_WHITESPACE
    [<Capability.NAME_RESOLUTION: 'name_resolution'>, ...]
    """

    NAME_RESOLUTION = "name_resolution"
    SCOPE_ANALYSIS = "scope_analysis"
    CLOSURE_LIFTING = "closure_lifting"
    MODULE_STATE_TRACKING = "module_state_tracking"
    BINDING_MAP_QUERY = "binding_map_query"


