@dataclass(slots=True)
class PackageManifest:
    """Mutable registry of :class:`ComponentRegistration` objects for this package.

    The manifest is the central coordination point for the ``scope_and_state``
    package.  It is responsible for:

    1. Accumulating component registrations at import time via
       :meth:`register`.
    2. Providing O(1) lookup by component name via :meth:`lookup`.
    3. Reporting the set of currently-enabled capabilities via
       :meth:`enabled_capabilities`.
    4. Validating the internal consistency of the registry via
       :meth:`validate`.

    In terms of theory2.tex Ch15, the manifest is the *global sections* object
    of the capability sheaf: it must satisfy the patching axiom (no overlapping
    coverage) and the locality axiom (every claimed coordinate prefix is covered
    by exactly one component per capability).

    The :data:`MANIFEST` module-level singleton is pre-populated by
    :func:`build_manifest` and should be imported directly:

    >>> from jugeo.python_runtime.scope_and_state.manifest import MANIFEST
    >>> isinstance(MANIFEST, PackageManifest)
    True

    Parameters
    ----------
    registrations : list[ComponentRegistration]
        Initial list of registrations.  Typically empty; populated lazily by
        :meth:`register`.

    Examples
    --------
    Build a fresh manifest and register two components:

    >>> m = PackageManifest()
    >>> m.register(ComponentRegistration(
    ...     name="resolver_a",
    ...     capability=Capability.NAME_RESOLUTION,
    ...     description="Primary resolver.",
    ...     coordinate_prefix="jugeo/python_runtime",
    ... ))
    >>> m.register(ComponentRegistration(
    ...     name="scope_a",
    ...     capability=Capability.SCOPE_ANALYSIS,
    ...     description="Primary scope builder.",
    ...     coordinate_prefix="jugeo/python_runtime",
    ... ))
    >>> len(m.registrations)
    2

    Check enabled capabilities:

    >>> Capability.NAME_RESOLUTION in m.enabled_capabilities()
    True

    Validate the manifest:

    >>> errors = m.validate()
    >>> errors
    []

    Serialise and round-trip:

    >>> data = m.serialize()
    >>> m2 = PackageManifest.parse(data)
    >>> len(m2.registrations) == len(m.registrations)
    True
    """

    registrations: list[ComponentRegistration] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Mutation
    # ------------------------------------------------------------------

    def register(self, reg: ComponentRegistration) -> None:
        """Append a new :class:`ComponentRegistration` to this manifest.

        Parameters
        ----------
        reg : ComponentRegistration
            The registration to add.  The manifest does **not** enforce uniqueness
            here (call :meth:`validate` afterwards to detect conflicts); this
            design allows incremental construction without premature failures.

        Examples
        --------
        >>> m = PackageManifest()
        >>> m.register(ComponentRegistration(
        ...     name="x",
        ...     capability=Capability.BINDING_MAP_QUERY,
        ...     description="Query component.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... ))
        >>> m.registrations[0].name
        'x'
        """
        logger.debug("Registering component %r (capability=%s)", reg.name, reg.capability.value)
        self.registrations.append(reg)

    # ------------------------------------------------------------------
    # Queries
    # ------------------------------------------------------------------

    def lookup(self, name: str) -> ComponentRegistration | None:
        """Return the first registration with the given *name*, or ``None``.

        Parameters
        ----------
        name : str
            The component name to search for.

        Returns
        -------
        ComponentRegistration | None
            The matching registration, or ``None`` if no registration with that
            name exists.

        Examples
        --------
        >>> m = PackageManifest()
        >>> m.register(ComponentRegistration(
        ...     name="my_comp",
        ...     capability=Capability.SCOPE_ANALYSIS,
        ...     description="Desc.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... ))
        >>> m.lookup("my_comp") is not None
        True
        >>> m.lookup("nonexistent") is None
        True
        """
        for reg in self.registrations:
            if reg.name == name:
                return reg
        return None

    def enabled_capabilities(self) -> list[Capability]:
        """Return the deduplicated list of capabilities with at least one enabled component.

        Returns
        -------
        list[Capability]
            Sorted by the declaration order of :class:`Capability`.  Contains no
            duplicates.  Only capabilities that have at least one
            :attr:`~ComponentRegistration.enabled` component are included.

        Examples
        --------
        >>> m = PackageManifest()
        >>> m.register(ComponentRegistration(
        ...     name="r",
        ...     capability=Capability.NAME_RESOLUTION,
        ...     description="Resolver.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... ))
        >>> m.enabled_capabilities()
        [<Capability.NAME_RESOLUTION: 'name_resolution'>]
        """
        seen: set[Capability] = set()
        result: list[Capability] = []
        # Preserve declaration order of the Capability enum.
        for cap in Capability:
            if cap in seen:
                continue
            for reg in self.registrations:
                if reg.capability == cap and reg.enabled:
                    seen.add(cap)
                    result.append(cap)
                    break
        return result

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------

    def validate(self) -> list[str]:
        """Validate the internal consistency of the manifest.

        Checks the following conditions (cf. theory2.tex Ch15, Lemma 15.7):

        1. **No duplicate names** — two registrations may not share the same name.
        2. **Non-empty descriptions** — every registration must have a non-empty
           ``description`` field.
        3. **Non-empty coordinate_prefix** — every registration must declare a
           non-empty coordinate prefix.
        4. **Non-empty name** — every registration must have a non-empty name.
        5. **At least one registration** — an empty manifest is considered invalid
           because it cannot satisfy any capability request.

        Returns
        -------
        list[str]
            A list of human-readable error strings.  An empty list means the
            manifest is valid.

        Examples
        --------
        >>> m = PackageManifest()
        >>> m.validate()
        ['Manifest contains no registrations.']

        >>> m.register(ComponentRegistration(
        ...     name="ok",
        ...     capability=Capability.SCOPE_ANALYSIS,
        ...     description="Good component.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... ))
        >>> m.validate()
        []

        Duplicate names trigger an error:

        >>> m.register(ComponentRegistration(
        ...     name="ok",
        ...     capability=Capability.CLOSURE_LIFTING,
        ...     description="Duplicate name.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... ))
        >>> errors = m.validate()
        >>> any("Duplicate" in e for e in errors)
        True
        """
        errors: list[str] = []

        if not self.registrations:
            errors.append("Manifest contains no registrations.")
            return errors

        seen_names: dict[str, int] = {}
        for idx, reg in enumerate(self.registrations):
            # Rule 4: non-empty name
            if not reg.name or not reg.name.strip():
                errors.append(
                    f"Registration at index {idx} has an empty or whitespace-only name."
                )
            else:
                key = reg.name.strip()
                if key in seen_names:
                    errors.append(
                        f"Duplicate component name {reg.name!r}: first seen at index "
                        f"{seen_names[key]}, repeated at index {idx}."
                    )
                else:
                    seen_names[key] = idx

            # Rule 2: non-empty description
            if not reg.description or not reg.description.strip():
                errors.append(
                    f"Registration {reg.name!r} has an empty description.  "
                    "Descriptions are required for the sheaf locality axiom."
                )

            # Rule 3: non-empty coordinate_prefix
            if not reg.coordinate_prefix or not reg.coordinate_prefix.strip():
                errors.append(
                    f"Registration {reg.name!r} has an empty coordinate_prefix.  "
                    "A non-empty prefix is required to delimit the component's open set."
                )

        # Warn about capabilities with no enabled component.
        disabled_caps = [
            cap.value
            for cap in Capability
            if cap not in {r.capability for r in self.registrations if r.enabled}
        ]
        for cap_val in disabled_caps:
            errors.append(
                f"Capability {cap_val!r} has no enabled component registered.  "
                "The scope sheaf will have a missing stalk for this capability."
            )

        if errors:
            logger.warning("PackageManifest.validate() found %d error(s).", len(errors))
        else:
            logger.debug("PackageManifest.validate() passed with no errors.")

        return errors

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def serialize(self) -> dict[str, Any]:
        """Serialise the manifest to a JSON-compatible dictionary.

        Returns
        -------
        dict[str, Any]
            A mapping with keys:

            - ``"package_name"`` — :data:`PACKAGE_NAME`
            - ``"package_version"`` — :data:`PACKAGE_VERSION`
            - ``"registrations"`` — list of serialised :class:`ComponentRegistration`
              dicts.

        Examples
        --------
        >>> m = PackageManifest()
        >>> m.register(ComponentRegistration(
        ...     name="c",
        ...     capability=Capability.MODULE_STATE_TRACKING,
        ...     description="Tracks state.",
        ...     coordinate_prefix="jugeo/python_runtime",
        ... ))
        >>> d = m.serialize()
        >>> d["package_name"]
        'scope_and_state'
        >>> len(d["registrations"])
        1
        """
        return {
            "package_name": PACKAGE_NAME,
            "package_version": PACKAGE_VERSION,
            "registrations": [r.serialize() for r in self.registrations],
        }

    @classmethod
    def parse(cls, data: dict[str, Any]) -> PackageManifest:
        """Reconstruct a :class:`PackageManifest` from a serialised dictionary.

        Parameters
        ----------
        data : dict[str, Any]
            A mapping previously produced by :meth:`serialize`.  The
            ``"package_name"`` and ``"package_version"`` keys are read for
            informational logging but do not affect the constructed object.

        Returns
        -------
        PackageManifest
            The reconstructed manifest.

        Raises
        ------
        KeyError
            If the ``"registrations"`` key is absent from *data*.

        Examples
        --------
        >>> raw = {
        ...     "package_name": "scope_and_state",
        ...     "package_version": "0.1.0",
        ...     "registrations": [],
        ... }
        >>> m = PackageManifest.parse(raw)
        >>> m.registrations
        []
        """
        pkg = data.get("package_name", "<unknown>")
        ver = data.get("package_version", "<unknown>")
        logger.debug("Parsing PackageManifest for package=%r version=%r", pkg, ver)
        regs: list[ComponentRegistration] = [
            ComponentRegistration.parse(r) for r in data["registrations"]
        ]
        manifest = cls()
        for reg in regs:
            manifest.registrations.append(reg)
        return manifest


