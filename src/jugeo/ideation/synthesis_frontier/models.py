from __future__ import annotations
# copilot: synthesis_frontier models — cross-domain integration tournament
"""Synthesis Frontier: Binary Tournament for Cross-Domain Mathematical Integration.

Overview
--------
The Synthesis Frontier is a structured ideation system that operates as a *binary
tournament* over 48 foundational mathematical and computational fields.  In each
round, pairs of fields are merged by an LLM judge into a richer synthetic field
whose proposition pool is roughly the union of both parents, augmented with new
bridge theorems discovered at the interface.  After ⌈log₂ 48⌉ = 6 rounds a single
*final synthesis* node remains; it represents a maximally cross-pollinated view of
the mathematical landscape as interpreted through JuGeo's judgment geometry.

Binary Tournament Structure
---------------------------
Round 0: 48 leaf FieldNodes, each with ~8 seed propositions.
Round 1: 24 merged nodes, each with ~16 propositions.
Round 2: 12 merged nodes, each with ~32 propositions.
Round 3:  6 merged nodes, each with ~64 propositions.
Round 4:  3 merged nodes (one bye), each with ~128 propositions.
Round 5:  2 merged nodes, each with ~256 propositions.
Round 6:  1 final synthesis node, with ~512 propositions.

Each merge is scored by a LLM judge that assigns a SynthesisPair record containing
metaphor links (cross-domain analogies) and bridge theorems (formal connections).

JuGeo Coordinates
-----------------
Each PropositionRecord carries a ``judgment_coordinate`` string encoding its
position in JuGeo's 8-dimensional judgment site::

    (c, φ, A, E, O, B, T, Π)

where:

    c  — concreteness:        0 (purely abstract) … 1 (fully concrete)
    φ  — formality:           0 (informal) … 1 (fully formal/mechanised)
    A  — abstraction level:   0 (elementary) … 1 (highly abstract)
    E  — epistemic status:    ANALYTIC | SYNTHETIC | EMPIRICAL | NORMATIVE
    O  — ontological category: MATHEMATICAL | COMPUTATIONAL | PHYSICAL | SOCIAL
    B  — bridge potential:    0 (field-internal) … 1 (highly cross-domain)
    T  — trust tier:          PROPOSAL | REVIEWED | VERIFIED
    Π  — proof difficulty:    TRIVIAL | EASY | MEDIUM | HARD | OPEN

Trust Tier Lifecycle
--------------------
PROPOSAL  → proposition was generated by an LLM without external validation.
REVIEWED  → proposition was checked against known literature by a domain expert
             or by a second LLM pass with citations.
VERIFIED  → proposition has a machine-checked proof or is a textbook result.

Metaphor Links and Bridge Theorems
-----------------------------------
A MetaphorLink records a cross-domain analogy at the semantic level: e.g.
"monads in category theory correspond to algebraic effect handlers in PL theory".
A BRIDGE_THEOREM PropositionRecord formalises the metaphor: it states a precise
theorem that holds in both (or across) the two fields.

The synthesis process tries to *maximise* the number of BRIDGE_THEOREMs while
*minimising* trivial or tautological connections.  The LLM judge scores each
SynthesisPair on six sub-dimensions: leverage, metaphor_richness,
transportability, proof_density, novelty, and geometry_fit.

Design Principles
-----------------
1. Immutability for record types: PropositionRecord, MetaphorLink, SynthesisPair
   are frozen dataclasses.  FieldNode is mutable so propositions and metaphors
   can accumulate during a tournament round.
2. Serialisation: every class supports ``to_dict()`` / ``from_dict()``.
3. LaTeX export: every class supports ``to_latex()`` / ``to_latex_section()``
   for generating the synthesis paper.
4. JSON checkpointing: TournamentState.save / TournamentState.load allow the
   tournament to be paused and resumed.
"""

