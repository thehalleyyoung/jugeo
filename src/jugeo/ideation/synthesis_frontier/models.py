class DomainArea(str, Enum):
    """Broad intellectual area for a mathematical or computational field.

    These eight domains cover the sweep of foundational and applied mathematics,
    computation, economics, and linguistics that the synthesis tournament draws on.
    """

    MATHEMATICS = "mathematics"
    COMPUTER_SCIENCE = "computer_science"
    THEORETICAL_ECONOMICS = "theoretical_economics"
    PHYSICS = "physics"
    LINGUISTICS = "linguistics"
    PHILOSOPHY_OF_MIND = "philosophy_of_mind"
    LOGIC = "logic"
    STATISTICS = "statistics"

    def display_name(self) -> str:
        return self.value.replace("_", " ").title()

    def is_formal(self) -> bool:
        """Return True for domains with a strong formal/deductive character."""
        return self in (
            DomainArea.MATHEMATICS,
            DomainArea.LOGIC,
            DomainArea.COMPUTER_SCIENCE,
        )


class PropositionKind(str, Enum):
    """The logical category of a proposition in the synthesis frontier.

    These kinds correspond to the standard mathematical vernacular plus
    two synthesis-specific kinds: CONSTRUCTION and BRIDGE_THEOREM.
    """

    DEFINITION = "definition"
    """A stipulative definition of a new concept or notation."""

    THEOREM = "theorem"
    """A major result with a non-trivial proof."""

    PROPOSITION = "proposition"
    """A useful fact with a proof, smaller in scope than a theorem."""

    LEMMA = "lemma"
    """A technical result used as a stepping stone to a theorem."""

    COROLLARY = "corollary"
    """A result that follows easily from a theorem."""

    CONJECTURE = "conjecture"
    """An unproved but plausible claim."""

    EXAMPLE = "example"
    """An illustrative instance of a definition or theorem."""

    REMARK = "remark"
    """An informal observation or heuristic."""

    CONSTRUCTION = "construction"
    """An explicit procedure for building a mathematical object."""

    BRIDGE_THEOREM = "bridge_theorem"
    """A result that formally connects two different fields; the primary
    output of the synthesis tournament."""

    AXIOM = "axiom"
    """A foundational assumption taken as given without proof."""

    SYNTHESIS_RESULT = "synthesis_result"
    """A proposition produced by the synthesis tournament merging two fields."""

    def latex_env(self) -> str:
        """Return the appropriate amsthm environment name."""
        mapping = {
            PropositionKind.DEFINITION: "definition",
            PropositionKind.THEOREM: "theorem",
            PropositionKind.PROPOSITION: "proposition",
            PropositionKind.LEMMA: "lemma",
            PropositionKind.COROLLARY: "corollary",
            PropositionKind.CONJECTURE: "conjecture",
            PropositionKind.EXAMPLE: "example",
            PropositionKind.REMARK: "remark",
            PropositionKind.CONSTRUCTION: "construction",
            PropositionKind.BRIDGE_THEOREM: "theorem",
            PropositionKind.AXIOM: "axiom",
            PropositionKind.SYNTHESIS_RESULT: "theorem",
        }
        return mapping.get(self, "theorem")

    def is_proven(self) -> bool:
        return self in (
            PropositionKind.THEOREM,
            PropositionKind.PROPOSITION,
            PropositionKind.LEMMA,
            PropositionKind.COROLLARY,
            PropositionKind.BRIDGE_THEOREM,
        )

    def is_speculative(self) -> bool:
        return self in (PropositionKind.CONJECTURE, PropositionKind.REMARK)


