@dataclass
class TournamentState:
    """Mutable state of the binary tournament.

    This is the top-level object that tracks the entire tournament.  It is
    serialisable to JSON and can be checkpointed and restored.

    Attributes
    ----------
    round_number : int
        Current tournament round (0 = initial, 6 = final for 48 fields).
    active_nodes : list[FieldNode]
        Nodes still in the tournament (not yet merged or eliminated).
    completed_merges : list[SynthesisPair]
        All merge decisions made so far (one per pair per round).
    all_propositions : list[PropositionRecord]
        Global flat pool of all propositions across all nodes.
    all_metaphors : list[MetaphorLink]
        Global flat pool of all metaphor links discovered so far.
    is_complete : bool
        True when only one FieldNode remains.
    final_synthesis : FieldNode | None
        The single surviving node after all rounds (set when is_complete).
    """

    round_number: int = 0
    active_nodes: list = field(default_factory=list)
    completed_merges: list = field(default_factory=list)
    all_propositions: list = field(default_factory=list)
    all_metaphors: list = field(default_factory=list)
    is_complete: bool = False
    final_synthesis: Optional[FieldNode] = None

    # ------------------------------------------------------------------
    # Convenience accessors
    # ------------------------------------------------------------------

    def node_count(self) -> int:
        return len(self.active_nodes)

    def proposition_count(self) -> int:
        return len(self.all_propositions)

    def metaphor_count(self) -> int:
        return len(self.all_metaphors)

    def get_node(self, field_id: str) -> Optional[FieldNode]:
        return next((n for n in self.active_nodes if n.field_id == field_id), None)

    def advance_round(self) -> None:
        """Increment the round counter."""
        self.round_number += 1
        if len(self.active_nodes) <= 1:
            self.is_complete = True
            if self.active_nodes:
                self.final_synthesis = self.active_nodes[0]

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        """Serialise the entire tournament state to a JSON-compatible dict."""
        return {
            "round_number": self.round_number,
            "active_nodes": [n.to_dict() for n in self.active_nodes],
            "completed_merges": [m.to_dict() for m in self.completed_merges],
            "all_propositions": [p.to_dict() for p in self.all_propositions],
            "all_metaphors": [m.to_dict() for m in self.all_metaphors],
            "is_complete": self.is_complete,
            "final_synthesis": (
                self.final_synthesis.to_dict() if self.final_synthesis else None
            ),
        }

    def save(self, path: str) -> None:
        """Save the tournament state as a JSON checkpoint.

        Parameters
        ----------
        path : str
            File path to write to.  Parent directories must exist.
        """
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(self.to_dict(), fh, indent=2, ensure_ascii=False)

    @classmethod
    def load(cls, path: str) -> "TournamentState":
        """Load a tournament state from a JSON checkpoint.

        Parameters
        ----------
        path : str
            Path to a JSON file previously written by ``save()``.

        Returns
        -------
        TournamentState
        """
        with open(path, encoding="utf-8") as fh:
            d = json.load(fh)
        state = cls(
            round_number=d.get("round_number", 0),
            active_nodes=[FieldNode.from_dict(n) for n in d.get("active_nodes", [])],
            completed_merges=[
                SynthesisPair.from_dict(m) for m in d.get("completed_merges", [])
            ],
            all_propositions=[
                PropositionRecord.from_dict(p) for p in d.get("all_propositions", [])
            ],
            all_metaphors=[
                MetaphorLink.from_dict(m) for m in d.get("all_metaphors", [])
            ],
            is_complete=d.get("is_complete", False),
            final_synthesis=(
                FieldNode.from_dict(d["final_synthesis"])
                if d.get("final_synthesis")
                else None
            ),
        )
        return state

    def summary(self) -> str:
        status = "COMPLETE" if self.is_complete else f"ROUND {self.round_number}"
        return (
            f"TournamentState({status}: {self.node_count()} nodes, "
            f"{self.proposition_count()} propositions, "
            f"{self.metaphor_count()} metaphors, "
            f"{len(self.completed_merges)} merges)"
        )

    # ------------------------------------------------------------------
    # Compatibility methods for new-style tournament code
    # ------------------------------------------------------------------

    @property
    def current_round(self) -> int:
        """Compatibility alias for round_number."""
        return self.round_number

    @current_round.setter
    def current_round(self, value: int) -> None:
        self.round_number = value

    def touch(self) -> None:
        """No-op compatibility stub (used when state was a frozen dataclass)."""

    def total_propositions(self) -> int:
        """Total proposition count across all active nodes."""
        return sum(n.proposition_count() for n in self.active_nodes)

    def register_pair(self, pair: "SynthesisPair") -> None:
        """Append a scored pair to completed_merges."""
        self.completed_merges.append(pair)

    def register_metaphor(self, m: "MetaphorLink") -> None:
        """Append a metaphor to the global pool."""
        self.all_metaphors.append(m)

    def register_node(self, node: "FieldNode") -> None:
        """Track a node in the global node index (bookkeeping only).

        The caller is responsible for updating ``active_nodes`` directly when
        replacing pairs with their merged result.
        """
        # Intentional no-op: active_nodes is managed by TournamentRound.run()
        # which replaces the list wholesale; this exists for API compatibility.

    @property
    def all_nodes(self) -> dict:
        """Dict mapping field_id → FieldNode for all currently active nodes."""
        return {n.field_id: n for n in self.active_nodes}

