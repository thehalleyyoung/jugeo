@dataclass(frozen=True)
class PropositionRecord:
    """A single mathematical proposition within the synthesis frontier.

    A PropositionRecord is the atomic unit of mathematical knowledge in the
    synthesis tournament.  Each field starts with ~8 seed propositions
    (definitions, theorems, bridge theorems) and accumulates more as the
    tournament progresses.

    Attributes
    ----------
    prop_id : str
        Unique identifier; e.g. ``"tt_def_pi_type"`` or ``uuid`` fragment.
    kind : PropositionKind
        The logical category (DEFINITION, THEOREM, BRIDGE_THEOREM, …).
    title : str
        Short descriptive title, e.g. ``"Yoneda Lemma"`` or ``"Π-type"``.
    statement : str
        Full formal-ish statement of the proposition.  May contain inline LaTeX
        using ``$…$`` delimiters.
    proof_sketch : str
        1-3 sentence informal proof idea.  For definitions, write "N/A —
        stipulative definition."
    why_useful : str
        1-2 sentences explaining why this proposition matters for the field
        and/or for cross-domain synthesis.
    source_field : str
        The ``field_id`` of the FieldNode this proposition originates from.
    target_fields : tuple[str, ...]
        ``field_id``s of other fields this proposition directly applies to or
        illuminates.
    metaphor_tags : tuple[str, ...]
        Free-form tags naming metaphorical connections, e.g.
        ``("monad-effect", "free-algebra", "adjunction-comonad")``.
    trust_tier : str
        ``"PROPOSAL"`` | ``"REVIEWED"`` | ``"VERIFIED"``.
    leverage_score : float
        Predicted cross-domain impact in [0, 1].
    proof_difficulty : str
        ``"TRIVIAL"`` | ``"EASY"`` | ``"MEDIUM"`` | ``"HARD"`` | ``"OPEN"``.
    dependencies : tuple[str, ...]
        ``prop_id``s this proposition depends on (for topological ordering).
    judgment_coordinate : str
        The JuGeo coordinate string ``(c=…,φ=…,A=…,E=…,O=…,B=…,T=…,Π=…)``.
    metadata : dict
        Arbitrary extra data (source references, LLM reasoning, etc.).
    """

    prop_id: str
    kind: PropositionKind
    title: str
    statement: str
    proof_sketch: str
    why_useful: str
    source_field: str
    target_fields: tuple[str, ...]
    metaphor_tags: tuple[str, ...]
    trust_tier: str
    leverage_score: float
    proof_difficulty: str
    dependencies: tuple[str, ...]
    judgment_coordinate: str
    metadata: dict = field(default_factory=dict, compare=False, hash=False)

    # ------------------------------------------------------------------
    # LaTeX
    # ------------------------------------------------------------------

    def to_latex(self) -> str:
        """Render this proposition as an amsthm LaTeX environment.

        The environment is chosen based on ``self.kind``.  The title appears
        as an optional label.  The statement is emitted verbatim (assumed to
        contain valid LaTeX math).  The proof sketch (if non-trivial) is
        appended in a \\begin{proof}[Proof sketch] environment.

        Returns
        -------
        str
            A self-contained LaTeX fragment suitable for inclusion in a paper.

        Example
        -------
        ::

            \\begin{theorem}[Yoneda Lemma]
              For any locally small category $\\mathcal{C}$ and functor
              $F:\\mathcal{C}\\to\\mathbf{Set}$, ...
            \\end{theorem}
            \\begin{proof}[Proof sketch]
              Construct the natural bijection by sending ...
            \\end{proof}
        """
        env = self.kind.latex_env()
        title_escaped = _latex_escape(self.title)
        tag = ""
        if self.kind == PropositionKind.BRIDGE_THEOREM:
            tag = " \\textnormal{[Bridge]}"
        lines = [
            f"\\begin{{{env}}}[{title_escaped}{tag}]",
            f"  \\label{{prop:{self.prop_id}}}",
            f"  {self.statement}",
            f"\\end{{{env}}}",
        ]
        trivial_sketches = {"N/A — stipulative definition.", "N/A — definition.", ""}
        if self.proof_sketch and self.proof_sketch not in trivial_sketches:
            if self.kind.is_proven():
                lines += [
                    "\\begin{proof}[Proof sketch]",
                    f"  {self.proof_sketch}",
                    "\\end{proof}",
                ]
        if self.why_useful:
            useful_escaped = _latex_escape(self.why_useful)
            lines.append(f"\\begin{{remark}} {useful_escaped} \\end{{remark}}")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        """Serialise to a JSON-compatible dict."""
        return {
            "prop_id": self.prop_id,
            "kind": self.kind.value,
            "title": self.title,
            "statement": self.statement,
            "proof_sketch": self.proof_sketch,
            "why_useful": self.why_useful,
            "source_field": self.source_field,
            "target_fields": list(self.target_fields),
            "metaphor_tags": list(self.metaphor_tags),
            "trust_tier": self.trust_tier,
            "leverage_score": self.leverage_score,
            "proof_difficulty": self.proof_difficulty,
            "dependencies": list(self.dependencies),
            "judgment_coordinate": self.judgment_coordinate,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "PropositionRecord":
        """Deserialise from a dict produced by ``to_dict()``."""
        return cls(
            prop_id=d["prop_id"],
            kind=PropositionKind(d["kind"]),
            title=d["title"],
            statement=d["statement"],
            proof_sketch=d.get("proof_sketch", ""),
            why_useful=d.get("why_useful", ""),
            source_field=d["source_field"],
            target_fields=tuple(d.get("target_fields", [])),
            metaphor_tags=tuple(d.get("metaphor_tags", [])),
            trust_tier=d.get("trust_tier", "PROPOSAL"),
            leverage_score=float(d.get("leverage_score", 0.5)),
            proof_difficulty=d.get("proof_difficulty", "MEDIUM"),
            dependencies=tuple(d.get("dependencies", [])),
            judgment_coordinate=d.get("judgment_coordinate", ""),
            metadata=d.get("metadata", {}),
        )

    def summary(self) -> str:
        """One-line summary for logging."""
        return f"[{self.kind.value}] {self.title} (leverage={self.leverage_score:.2f}, tier={self.trust_tier})"

    @classmethod
    def make(
        cls,
        title: str,
        statement: str,
        kind: "PropositionKind",
        source_field_id: str = "",
        tags: tuple = (),
        importance: float = 0.5,
        proof_sketch: str = "",
        why_useful: str = "",
        references: tuple = (),
    ) -> "PropositionRecord":
        """Convenience factory — wraps the dataclass constructor with legacy arg names."""
        if isinstance(kind, str):
            kind = PropositionKind(kind)
        sketch = proof_sketch or (
            "N/A — stipulative definition." if kind == PropositionKind.DEFINITION else ""
        )
        return cls(
            prop_id=_uid(),
            kind=kind,
            title=title,
            statement=statement,
            proof_sketch=sketch,
            why_useful=why_useful,
            source_field=source_field_id,
            target_fields=(),
            metaphor_tags=tuple(tags),
            trust_tier="PROPOSAL",
            leverage_score=float(importance),
            proof_difficulty="MEDIUM",
            dependencies=(),
            judgment_coordinate="",
        )

    def site_topology(self):
        """Build a site topology over synthesis propositions."""
        try:
            from jugeo.geometry.site import Site, SiteBuilder, Coordinate, GrothendieckTopology
            from jugeo.geometry.descent import DescentEngine, LocalSection
            from jugeo.judgments.judgment_terms import Judgment, Proposition
            from jugeo.evidence.trust import TrustAlgebra
            return {"topology": "built"}
        except Exception:
            return {"topology": "unavailable"}


@dataclass(frozen=True)
class MetaphorLink:
    """A discovered cross-domain metaphor connecting two FieldNodes.

    A MetaphorLink records the *semantic* level of a cross-domain analogy:
    it names the two concepts being analogised, describes how they correspond,
    and tracks the ``PropositionRecord`` ids that formalise the metaphor as
    bridge theorems.

    The ``kind`` field classifies the strength of the structural correspondence:

    ANALOGY
        Loose conceptual analogy; no precise categorical statement.
    FUNCTOR
        There is a functor (or a functor-like map) from one field's objects
        to the other's.
    ADJUNCTION
        The connection is an adjunction: F ⊣ G with a universal property.
    DUALITY
        The two fields are dual in some sense (e.g. algebra / coalgebra,
        syntax / semantics, programs / specifications).
    ISOMORPHISM
        The two structures are isomorphic or equivalent in a precise sense.
    SPECIALIZATION
        One field is a special case or instantiation of the other.

    Attributes
    ----------
    link_id : str
    source_field : str
        ``field_id`` of the source FieldNode.
    target_field : str
        ``field_id`` of the target FieldNode.
    source_concept : str
        The concept in the source field.
    target_concept : str
        The corresponding concept in the target field.
    metaphor_description : str
        A 2-4 sentence human-readable description of the analogy.
    bridge_propositions : tuple[str, ...]
        ``prop_id``s of PropositionRecords that formalise this metaphor.
    strength : float
        Estimated faithfulness / precision of the metaphor in [0, 1].
    kind : str
        One of ANALOGY / FUNCTOR / ADJUNCTION / DUALITY / ISOMORPHISM /
        SPECIALIZATION.
    llm_judge_score : float
        Score assigned by the LLM judge in [0, 1].
    llm_judge_reasoning : str
        The LLM judge's textual justification for the score.
    """

    link_id: str
    source_field: str
    target_field: str
    source_concept: str
    target_concept: str
    metaphor_description: str
    bridge_propositions: tuple[str, ...]
    strength: float
    kind: str
    llm_judge_score: float
    llm_judge_reasoning: str

    KINDS = frozenset(
        {"ANALOGY", "FUNCTOR", "ADJUNCTION", "DUALITY", "ISOMORPHISM", "SPECIALIZATION"}
    )

    # ------------------------------------------------------------------
    # LaTeX
    # ------------------------------------------------------------------

    def to_latex(self) -> str:
        """Render as a LaTeX \\item in a metaphor enumeration.

        Produces a ``\\item`` block suitable for an ``enumerate`` or
        ``description`` environment in the synthesis paper.

        Returns
        -------
        str
            LaTeX fragment starting with ``\\item``.
        """
        src = _latex_escape(self.source_concept)
        tgt = _latex_escape(self.target_concept)
        desc = _latex_escape(self.metaphor_description)
        return (
            f"\\item[\\textbf{{{self.kind}}}] "
            f"\\textit{{{src}}} $\\leftrightarrow$ \\textit{{{tgt}}} "
            f"({self.source_field} $\\to$ {self.target_field}, "
            f"strength = {self.strength:.2f}): {desc}"
        )

    def to_latex_table_row(self) -> str:
        """One-line LaTeX table row for the metaphor index."""
        src = _latex_escape(self.source_concept)
        tgt = _latex_escape(self.target_concept)
        desc_short = _latex_escape(self.metaphor_description[:60])
        return (
            f"{self.source_field} & {self.target_field} & "
            f"{src} & {tgt} & {self.kind} & {self.strength:.2f} & "
            f"{desc_short}… \\\\"
        )

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        return {
            "link_id": self.link_id,
            "source_field": self.source_field,
            "target_field": self.target_field,
            "source_concept": self.source_concept,
            "target_concept": self.target_concept,
            "metaphor_description": self.metaphor_description,
            "bridge_propositions": list(self.bridge_propositions),
            "strength": self.strength,
            "kind": self.kind,
            "llm_judge_score": self.llm_judge_score,
            "llm_judge_reasoning": self.llm_judge_reasoning,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "MetaphorLink":
        return cls(
            link_id=d["link_id"],
            source_field=d["source_field"],
            target_field=d["target_field"],
            source_concept=d["source_concept"],
            target_concept=d["target_concept"],
            metaphor_description=d["metaphor_description"],
            bridge_propositions=tuple(d.get("bridge_propositions", [])),
            strength=float(d["strength"]),
            kind=d["kind"],
            llm_judge_score=float(d.get("llm_judge_score", 0.0)),
            llm_judge_reasoning=d.get("llm_judge_reasoning", ""),
        )

    def summary(self) -> str:
        return (
            f"MetaphorLink({self.source_field}.{self.source_concept} "
            f"↔ {self.target_field}.{self.target_concept}, "
            f"kind={self.kind}, strength={self.strength:.2f})"
        )

    @classmethod
    def make(
        cls,
        source_field_id: str,
        target_field_id: str,
        source_concept: str,
        target_concept: str,
        description: str = "",
        strength: float = 0.5,
        kind: str = "ANALOGY",
        supporting_propositions: tuple = (),
        is_known_classical: bool = False,  # accepted for compat, not stored
    ) -> "MetaphorLink":
        """Convenience factory — wraps the dataclass constructor with legacy arg names."""
        normalised_kind = kind.upper() if kind.upper() in cls.KINDS else "ANALOGY"
        return cls(
            link_id=_uid(),
            source_field=source_field_id,
            target_field=target_field_id,
            source_concept=source_concept,
            target_concept=target_concept,
            metaphor_description=description,
            bridge_propositions=tuple(supporting_propositions),
            strength=float(strength),
            kind=normalised_kind,
            llm_judge_score=0.0,
            llm_judge_reasoning="",
        )


@dataclass
class FieldNode:
    """The primary node type in the synthesis tournament.

    A FieldNode represents either an original leaf field (round_number=0) or
    a merged synthetic field produced by the tournament (round_number≥1).
    It is *mutable*: propositions and metaphor links are added as the
    tournament progresses.

    Attributes
    ----------
    field_id : str
        Short slug identifier, e.g. ``"type_theory"`` or ``"cat_x_hott_r1"``.
    name : str
        Human-readable full name, e.g. ``"Martin-Löf Type Theory"``.
    domain : DomainArea
        The primary intellectual domain.
    description : str
        2-3 paragraph rich description of the field, its history, objects,
        and open problems.
    core_objects : tuple[str, ...]
        The primary mathematical objects of the field, e.g.
        ``("dependent type", "context", "Π-type", "Σ-type", "identity type")``.
    core_morphisms : tuple[str, ...]
        The primary maps / transformations, e.g.
        ``("substitution", "type-theoretic function", "transport")``.
    key_theorems : tuple[str, ...]
        Names of landmark results, e.g. ``("Curry-Howard Correspondence",
        "Canonicity Theorem", "Normalization")``.
    propositions : list[PropositionRecord]
        Accumulated propositions.  Starts with ~8 seed propositions at
        round 0 and roughly doubles with each merge.
    metaphor_links : list[MetaphorLink]
        Cross-domain metaphor links discovered during tournament rounds.
    judgment_site : dict
        How this field maps to JuGeo's judgment site.  Keys include
        ``"primary_coordinate"``, ``"abstraction_level"``, ``"formality"``,
        ``"bridge_potential"``, ``"notes"``.
    round_number : int
        0 = original leaf; k = merged in tournament round k.
    constituent_fields : tuple[str, ...]
        ``field_id``s of the original leaf fields that were merged into
        this node (by induction over the tournament tree).
    llm_summary : str
        LLM-generated synthesis summary written after a merge.
    trust_tier : str
        Overall trust tier for this node.
    metadata : dict
        Arbitrary extra data.
    """

    field_id: str
    name: str
    domain: DomainArea
    description: str
    core_objects: tuple[str, ...]
    core_morphisms: tuple[str, ...]
    key_theorems: tuple[str, ...]
    propositions: list = field(default_factory=list)
    metaphor_links: list = field(default_factory=list)
    judgment_site: dict = field(default_factory=dict)
    round_number: int = 0
    constituent_fields: tuple = ()
    llm_summary: str = ""
    trust_tier: str = "PROPOSAL"
    metadata: dict = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Proposition management
    # ------------------------------------------------------------------

    def proposition_count(self) -> int:
        """Return the number of propositions currently in this node."""
        return len(self.propositions)

    def add_proposition(self, p: PropositionRecord) -> None:
        """Append a proposition to this node's pool."""
        self.propositions.append(p)

    def add_metaphor(self, m: MetaphorLink) -> None:
        """Append a metaphor link to this node."""
        self.metaphor_links.append(m)

    def bridge_theorems(self) -> list[PropositionRecord]:
        """Return all BRIDGE_THEOREM propositions."""
        return [p for p in self.propositions if p.kind == PropositionKind.BRIDGE_THEOREM]

    def propositions_by_kind(self, kind: PropositionKind) -> list[PropositionRecord]:
        """Return all propositions of a given kind."""
        return [p for p in self.propositions if p.kind == kind]

    def top_propositions(self, n: int = 10) -> list[PropositionRecord]:
        """Return the top-n propositions by leverage score."""
        return sorted(self.propositions, key=lambda p: -p.leverage_score)[:n]

    # ------------------------------------------------------------------
    # LaTeX
    # ------------------------------------------------------------------

    def to_latex_section(self) -> str:
        r"""Render this field as a LaTeX \section{} block.

        The section contains:
        - A \\section heading with the field name.
        - A \\subsection{Description} with the multi-paragraph description.
        - A \\subsection{Core Objects and Morphisms} with itemised lists.
        - A \\subsection{Key Theorems} with an itemised list.
        - A \\subsection{Propositions} with all propositions rendered by
          ``PropositionRecord.to_latex()``.
        - If metaphor links are present, a \\subsection{Metaphor Links}.

        Returns
        -------
        str
            A complete LaTeX section fragment.
        """
        lines: list[str] = []
        name_esc = _latex_escape(self.name)
        lines.append(f"\\section{{{name_esc}}}")
        lines.append(f"\\label{{field:{self.field_id}}}")
        lines.append("")

        if self.round_number > 0:
            constituents = ", ".join(self.constituent_fields)
            lines.append(
                f"\\textit{{Synthesis node from round {self.round_number}. "
                f"Constituent fields: {_latex_escape(constituents)}.}}"
            )
            lines.append("")

        # Description
        lines.append("\\subsection{Description}")
        for para in self.description.split("\n\n"):
            para = para.strip()
            if para:
                lines.append(para)
                lines.append("")

        # Core objects and morphisms
        if self.core_objects or self.core_morphisms:
            lines.append("\\subsection{Core Objects and Morphisms}")
            if self.core_objects:
                lines.append("\\paragraph{Primary objects}")
                lines.append("\\begin{itemize}")
                for obj in self.core_objects:
                    lines.append(f"  \\item {_latex_escape(obj)}")
                lines.append("\\end{itemize}")
            if self.core_morphisms:
                lines.append("\\paragraph{Primary morphisms}")
                lines.append("\\begin{itemize}")
                for m in self.core_morphisms:
                    lines.append(f"  \\item {_latex_escape(m)}")
                lines.append("\\end{itemize}")
            lines.append("")

        # Key theorems
        if self.key_theorems:
            lines.append("\\subsection{Landmark Results}")
            lines.append("\\begin{enumerate}")
            for thm in self.key_theorems:
                lines.append(f"  \\item {_latex_escape(thm)}")
            lines.append("\\end{enumerate}")
            lines.append("")

        # Propositions
        if self.propositions:
            lines.append("\\subsection{Propositions}")
            for p in self.propositions:
                lines.append(p.to_latex())
                lines.append("")

        # Metaphor links
        if self.metaphor_links:
            lines.append("\\subsection{Metaphor Links}")
            lines.append("\\begin{description}")
            for ml in self.metaphor_links:
                lines.append(ml.to_latex())
            lines.append("\\end{description}")
            lines.append("")

        # JuGeo judgment site
        if self.judgment_site:
            lines.append("\\subsection{JuGeo Judgment Site}")
            lines.append("\\begin{description}")
            for k, v in self.judgment_site.items():
                lines.append(f"  \\item[{_latex_escape(str(k))}] {_latex_escape(str(v))}")
            lines.append("\\end{description}")
            lines.append("")

        return "\n".join(lines)

