class ExampleGenerator:
    """Generate illustrative examples for a kind candidate or new kind.

    Produces three categories of examples:
    * **Positive examples** – objects that satisfy the kind's definition
    * **Negative examples** – objects that conspicuously fail one axiom
    * **Boundary examples** – objects on the edge (degenerate / limiting cases)
    """

    def __init__(self, config: BootstrapConfig | None = None) -> None:
        self._config = config or BootstrapConfig()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def generate(self, candidate: KindCandidate) -> list[str]:
        """Return a combined list of positive, negative, and boundary examples."""
        target = max(1, self._config.example_count)
        pos_count = max(1, target - 2)
        neg_count = min(2, target - pos_count)
        boundary_count = max(0, target - pos_count - neg_count)

        positives = self.generate_positive(candidate)[:pos_count]
        negatives = self.generate_negative(candidate)[:neg_count]
        boundaries = self.generate_boundary(candidate)[:boundary_count]
        return positives + negatives + boundaries

    def generate_positive(self, candidate: KindCandidate) -> list[str]:
        """Generate positive examples for *candidate*."""
        examples: list[str] = []
        formal = _formal_name(candidate.name)
        obstruction_types = _candidate_obstruction_types(candidate)

        # One example per obstruction type
        for obs_type in obstruction_types[: self._config.example_count]:
            ex = self._example_from_obstruction(obs_type, formal)
            examples.append(ex)

        # If fewer than requested, generate generic structural examples
        generic_templates = [
            f"The {formal} arising as the limit of the canonical tower in the {candidate.name} domain.",
            f"Any minimal obstruction-free extension of a {candidate.name} is itself a {formal}.",
            f"The colimit of the diagram of {candidate.name} inclusions is a {formal}.",
            f"The pullback of two {formal}s along a common morphism is a {formal}.",
        ]
        for tmpl in generic_templates:
            if len(examples) >= self._config.example_count:
                break
            examples.append(tmpl)
        return examples[: self._config.example_count]

    def generate_negative(self, candidate: KindCandidate) -> list[str]:
        """Generate negative (counter-)examples for *candidate*."""
        formal = _formal_name(candidate.name)
        negatives: list[str] = []
        obstruction_types = _candidate_obstruction_types(candidate)

        for obs_type in obstruction_types[:3]:
            neg = self._negative_example_from_obstruction(obs_type, formal)
            negatives.append(neg)

        # Generic negatives
        missing_vocab = (
            _OBS_TYPE_VOCAB.get(obstruction_types[0], "obstruction")
            if obstruction_types
            else "obstruction witness"
        )
        generic = [
            f"A {formal} with one axiom violated: it lacks a complete {missing_vocab}.",
            f"The empty object is not a {formal} because existence is violated.",
        ]
        negatives.extend(generic)
        return negatives[:3]

    def generate_boundary(self, candidate: KindCandidate) -> list[str]:
        """Generate boundary/degenerate examples for *candidate*."""
        formal = _formal_name(candidate.name)
        return [
            f"The terminal {formal}: admits every obstruction trivially (degenerate).",
            f"The initial {formal}: admits no obstruction; existence axiom is borderline satisfied.",
        ]

    def generate_from_definition(self, definition: str, name: str) -> list[str]:
        """Generate examples based on the definition text and kind name.

        Parses axiom markers in *definition* to produce one example per axiom.
        """
        formal = _formal_name(name)
        axioms = re.findall(r"\[Axiom \d+\]\s+(.*?)(?=\[Axiom|\Z)", definition, re.DOTALL)
        examples: list[str] = []
        for i, axiom_text in enumerate(axioms[:5], start=1):
            axiom_summary = axiom_text.strip().split(".")[0][:80]
            examples.append(
                f"Example {i}: A {formal} satisfying axiom {i} "
                f"({axiom_summary}...)."
            )
        if not examples:
            examples.append(
                f"Canonical example: the free {formal} generated by a single "
                f"element of the base domain."
            )
        return examples

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _example_from_obstruction(self, obs_type: str, formal_name: str) -> str:
        """Construct a positive example sentence for one obstruction type."""
        vocab = _OBS_TYPE_VOCAB.get(obs_type, obs_type)
        evidence = _EVIDENCE_VOCAB.get(obs_type, ())
        ev_phrase = f" (witnessed by a {evidence[0]})" if evidence else ""
        return (
            f"Positive: A {formal_name} exhibiting a canonical {vocab}{ev_phrase}."
        )

    def _negative_example_from_obstruction(self, obs_type: str, formal_name: str) -> str:
        """Construct a negative example sentence for one obstruction type."""
        vocab = _OBS_TYPE_VOCAB.get(obs_type, obs_type)
        return (
            f"Negative: An object that fails to admit a {vocab} and therefore "
            f"is not a {formal_name}."
        )

    def format_examples(self, examples: list[str]) -> str:
        """Format a list of example strings as a numbered markdown list."""
        if not examples:
            return "(no examples)"
        lines = [f"{i}. {ex}" for i, ex in enumerate(examples, start=1)]
        return "\n".join(lines)


