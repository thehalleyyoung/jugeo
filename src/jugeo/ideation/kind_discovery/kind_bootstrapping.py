class KindHypothesizer:
    """Generate KindCandidate hypotheses from recognised patterns.

    The hypothesizer examines one or more :class:`KindPattern` objects and
    proposes :class:`KindCandidate` objects.  Each candidate represents one
    plausible new kind that could be defined to capture the regularity
    expressed by the pattern.

    The hypothesization strategy assigns a confidence score based on:
    * Pattern frequency (higher → more confident)
    * Pattern confidence (inherited directly)
    * Number of distinct obstruction types covered
    * Presence of keywords that suggest a coherent concept
    """

    def __init__(self, config: BootstrapConfig | None = None) -> None:
        self._config = config or BootstrapConfig()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def hypothesize(self, pattern: KindPattern) -> list[KindCandidate]:
        """Generate up to *max_hypotheses_per_pattern* candidates from *pattern*.

        Returns an empty list when the pattern does not meet the minimum
        frequency threshold configured in :attr:`_config`.
        """
        if pattern.frequency < self._config.min_pattern_frequency:
            return []

        limit = self._config.max_hypotheses_per_pattern
        base_confidence = self._compute_confidence(pattern)
        candidates: list[KindCandidate] = []

        # --- Primary hypothesis: direct interpretation of the pattern ---
        primary_name = self._name_from_pattern(pattern)
        primary_desc = self._description_from_pattern(pattern)
        primary_cand = KindCandidate(
            candidate_id=str(uuid.uuid4()),
            name=primary_name,
            description=primary_desc,
            pattern_ids=(pattern.pattern_id,),
            obstruction_types=pattern.obstruction_types,
            field_ids=pattern.field_ids,
            confidence=base_confidence,
            novelty=_clamp(1.0 - base_confidence * 0.5, 0.0, 1.0),
            status=KindStatus.PROPOSED,
            supporting_evidence=tuple(pattern.keywords),
            definition_draft=_candidate_definition_template(
                primary_name,
                pattern.name,
                pattern.obstruction_types,
                depth=self._config.definition_depth,
            ),
            created_at=_now_iso(),
        )
        candidates.append(primary_cand)

        # --- Secondary hypotheses: one per obstruction type (if room) ---
        for obs_type in pattern.obstruction_types[: limit - 1]:
            sec_name = self._name_from_obstruction_type(obs_type, pattern)
            if sec_name == primary_name:
                continue
            sec_confidence = base_confidence * 0.80  # slight penalty
            sec_cand = KindCandidate(
                candidate_id=str(uuid.uuid4()),
                name=sec_name,
                description=self._description_from_obstruction_type(obs_type, pattern),
                pattern_ids=(pattern.pattern_id,),
                obstruction_types=(obs_type,),
                field_ids=pattern.field_ids,
                confidence=sec_confidence,
                novelty=_clamp(1.0 - sec_confidence * 0.4, 0.0, 1.0),
                status=KindStatus.PROPOSED,
                supporting_evidence=tuple(_EVIDENCE_VOCAB.get(obs_type, ())),
                definition_draft=_candidate_definition_template(
                    sec_name,
                    pattern.name,
                    (obs_type,),
                    depth=max(1, self._config.definition_depth - 1),
                ),
                created_at=_now_iso(),
            )
            candidates.append(sec_cand)
            if len(candidates) >= limit:
                break

        # --- Cross-domain hypothesis (if enabled and pattern has keywords) ---
        if self._config.enable_cross_domain and len(candidates) < limit and pattern.keywords:
            cross_name = f"cross-domain {primary_name}"
            cross_conf = base_confidence * 0.65
            cross_cand = KindCandidate(
                candidate_id=str(uuid.uuid4()),
                name=cross_name,
                description=(
                    f"A cross-domain generalisation of {primary_name} "
                    f"arising from the pattern '{pattern.name}' across "
                    f"{len(pattern.field_ids)} fields."
                ),
                pattern_ids=(pattern.pattern_id,),
                obstruction_types=pattern.obstruction_types,
                field_ids=pattern.field_ids,
                confidence=cross_conf,
                novelty=_clamp(1.0 - cross_conf * 0.3, 0.0, 1.0),
                status=KindStatus.PROPOSED,
                supporting_evidence=tuple(pattern.keywords[:3]),
                created_at=_now_iso(),
            )
            candidates.append(cross_cand)

        return candidates[:limit]

    def hypothesize_from_field(self, field: ObstructionField) -> list[KindCandidate]:
        """Generate candidates directly from an :class:`ObstructionField`.

        Creates a synthetic :class:`KindPattern` from the field's obstruction
        types and delegates to :meth:`hypothesize`.
        """
        if not field.obstruction_types:
            return []

        # Build a synthetic pattern from the field
        obs_types = tuple(
            ObstructionType(ot) if isinstance(ot, str) else ot
            for ot in field.obstruction_types
        )
        synthetic_pattern = KindPattern(
            pattern_id=str(uuid.uuid4()),
            name=field.name,
            pattern_type="field_derived",
            frequency=max(1, field.obstruction_count),
            confidence=_clamp(field.weight_per_obstruction() / 10.0, 0.0, 1.0),
            supporting_obstructions=tuple(str(i) for i in range(field.obstruction_count)),
            obstruction_types=obs_types,
            field_ids=(field.field_id,),
            description=f"Pattern derived from obstruction field '{field.name}'",
            keywords=tuple(_tokenize(field.name)[:8]),
            created_at=_now_iso(),
        )
        return self.hypothesize(synthetic_pattern)

    def hypothesize_batch(self, patterns: list[KindPattern]) -> list[KindCandidate]:
        """Generate candidates from a batch of patterns.

        Returns a flat list of all generated candidates across all patterns,
        deduplicated by name similarity.
        """
        all_candidates: list[KindCandidate] = []
        for pattern in patterns:
            new_cands = self.hypothesize(pattern)
            all_candidates.extend(new_cands)
        return self.merge_duplicates(all_candidates)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _name_from_pattern(self, pattern: KindPattern) -> str:
        """Derive a human-readable kind name from a pattern."""
        # Prefer explicit keywords, fall back to pattern name tokens
        tokens = list(pattern.keywords) if pattern.keywords else _tokenize(pattern.name)
        # Take up to 3 tokens that are ≥ 4 characters
        significant = [t for t in tokens if len(t) >= 4][:3]
        if not significant:
            significant = tokens[:2] if tokens else ["unknown"]
        # Pick the obstruction type with highest frequency as qualifier
        obs_qualifier = ""
        if pattern.obstruction_types:
            ot = pattern.obstruction_types[0]
            obs_qualifier = ot.split("_")[0] if isinstance(ot, str) else ot.value.split("_")[0]
        parts = significant if not obs_qualifier else [obs_qualifier] + significant[:2]
        return _title_case(" ".join(parts)) + " Kind"

    def _name_from_obstruction_type(self, obs_type: str, pattern: KindPattern) -> str:
        """Derive a kind name specifically for one obstruction type."""
        qualifier = obs_type.split("_")[0] if isinstance(obs_type, str) else obs_type.value.split("_")[0]
        domain_hint = _tokenize(pattern.name)[:1]
        if domain_hint:
            return _title_case(f"{qualifier} {domain_hint[0]}") + " Kind"
        return _title_case(f"{qualifier}") + " Kind"

    def _description_from_pattern(self, pattern: KindPattern) -> str:
        """Compose a description for a candidate derived from *pattern*."""
        obs_count = len(pattern.obstruction_types)
        field_count = len(pattern.field_ids)
        obs_list = ", ".join(str(ot) for ot in pattern.obstruction_types[:3])
        extra = "..." if obs_count > 3 else ""
        return (
            f"A kind candidate arising from pattern '{pattern.name}' "
            f"(frequency={pattern.frequency}, confidence={pattern.confidence:.2f}). "
            f"Covers {obs_count} obstruction type(s) ({obs_list}{extra}) "
            f"across {field_count} obstruction field(s)."
        )

    def _description_from_obstruction_type(self, obs_type: str, pattern: KindPattern) -> str:
        """Compose a description for a candidate focused on one obstruction type."""
        vocab = _OBS_TYPE_VOCAB.get(obs_type, obs_type)
        return (
            f"A kind candidate focusing on the {vocab} aspect of pattern "
            f"'{pattern.name}'. Derived from {len(pattern.field_ids)} field(s) "
            f"with an original pattern confidence of {pattern.confidence:.2f}."
        )

    def _obstruction_pattern_text(self, pattern: KindPattern) -> str:
        """Return a single-sentence textual summary of the obstruction pattern."""
        type_strs = [str(ot) for ot in pattern.obstruction_types]
        return (
            f"Pattern '{pattern.name}' exhibits {len(type_strs)} obstruction "
            f"type(s): {', '.join(type_strs)}. It appears {pattern.frequency} "
            f"time(s) across the obstruction corpus."
        )

    def _compute_confidence(self, pattern: KindPattern) -> float:
        """Compute a bootstrap confidence score from pattern statistics.

        The formula weights:
        * Pattern's own confidence (60 %)
        * Frequency-derived bonus – log(freq+1) / log(10+1) capped at 20 %
        * Obstruction-type coverage bonus – up to 20 %
        """
        freq_bonus = math.log(pattern.frequency + 1) / math.log(11) * 0.20
        type_coverage = min(len(pattern.obstruction_types) / 5.0, 1.0) * 0.20
        raw = pattern.confidence * 0.60 + freq_bonus + type_coverage
        return _clamp(round(raw, 4), 0.0, 1.0)

    # ------------------------------------------------------------------
    # Filtering / merging
    # ------------------------------------------------------------------

    def filter_viable(self, candidates: list[KindCandidate]) -> list[KindCandidate]:
        """Retain only candidates that meet the minimum confidence threshold."""
        threshold = self._config.min_candidate_confidence
        min_frequency = self._config.min_pattern_frequency
        return [
            c for c in candidates
            if c.confidence >= threshold and getattr(c, "frequency", min_frequency) >= min_frequency
        ]

    def merge_duplicates(self, candidates: list[KindCandidate]) -> list[KindCandidate]:
        """Merge candidates whose names are very similar (Jaccard ≥ 0.80).

        When two candidates are judged duplicates the one with higher
        confidence is kept and the evidence of both is combined.
        """
        if not candidates:
            return []
        result: list[KindCandidate] = []
        used: set[int] = set()

        token_sets = [frozenset(_tokenize(c.name)) for c in candidates]

        for i, cand in enumerate(candidates):
            if i in used:
                continue
            merged = cand
            for j, other in enumerate(candidates):
                if j <= i or j in used:
                    continue
                sim = _jaccard(token_sets[i], token_sets[j])
                if sim >= 0.80:
                    used.add(j)
                    # Merge evidence and keep the higher-confidence candidate
                    combined_evidence = tuple(
                        dict.fromkeys(merged.supporting_evidence + other.supporting_evidence)
                    )
                    combined_counter = tuple(
                        dict.fromkeys(merged.counter_evidence + other.counter_evidence)
                    )
                    combined_patterns = tuple(
                        dict.fromkeys(merged.pattern_ids + other.pattern_ids)
                    )
                    if other.confidence > merged.confidence:
                        merged = replace(
                            other,
                            supporting_evidence=combined_evidence,
                            counter_evidence=combined_counter,
                            pattern_ids=combined_patterns,
                        )
                    else:
                        merged = replace(
                            merged,
                            supporting_evidence=combined_evidence,
                            counter_evidence=combined_counter,
                            pattern_ids=combined_patterns,
                        )
            result.append(merged)
        return result


