class KindBootstrapper:
    """Orchestrate the full kind-bootstrapping pipeline.

    The bootstrapper takes :class:`KindPattern` objects (or
    :class:`KindCandidate` objects) and produces fully-defined
    :class:`NewKind` objects together with :class:`KindBootstrapPlan` objects
    and (optionally) associated :class:`Idea` objects.

    Pipeline stages
    ---------------
    1. Hypothesize candidates from patterns (:class:`KindHypothesizer`)
    2. Build definitions for each viable candidate (:class:`DefinitionBuilder`)
    3. Generate examples (:class:`ExampleGenerator`)
    4. Plan validation (:class:`ValidationPlanner`)
    5. Optionally generate ideas (:class:`IdeaGenerator`)
    6. Assemble :class:`NewKind` and :class:`KindBootstrapPlan` objects
    """

    def __init__(
        self,
        config: BootstrapConfig | None = None,
        generator: IdeaGenerator | None = None,
        evaluator: IdeaEvaluator | None = None,
    ) -> None:
        self._config = config or BootstrapConfig()
        self._hypothesizer = KindHypothesizer(self._config)
        self._def_builder = DefinitionBuilder(self._config)
        self._ex_generator = ExampleGenerator(self._config)
        self._val_planner = ValidationPlanner(self._config)
        self._generator = generator or IdeaGenerator()
        self._evaluator = evaluator or IdeaEvaluator()
        self._bootstrapped_kinds: list[NewKind] = []

    # ------------------------------------------------------------------
    # Public API – main entry points
    # ------------------------------------------------------------------

    def bootstrap(self, patterns: list[KindPattern]) -> list[NewKind]:
        """Bootstrap new kinds from a list of patterns.

        Runs the full pipeline: hypothesize → filter → build → plan → assemble.
        """
        if not patterns:
            return []
        candidates = self._hypothesizer.hypothesize_batch(patterns)
        viable = self._hypothesizer.filter_viable(candidates)
        return self.bootstrap_from_candidates(viable)

    def bootstrap_from_candidates(
        self, candidates: list[KindCandidate]
    ) -> list[NewKind]:
        """Bootstrap new kinds from pre-existing :class:`KindCandidate` objects.

        Unlike :meth:`bootstrap`, this skips the hypothesize step and uses
        the candidates directly.
        """
        new_kinds: list[NewKind] = []
        total_effort = 0.0

        for candidate in candidates:
            if not candidate.is_viable(self._config.min_candidate_confidence):
                continue
            effort = _estimate_effort(candidate, depth=self._config.definition_depth)
            if total_effort + effort > self._config.effort_budget:
                # Skip expensive candidates once we exceed the effort budget
                continue
            kind = self.bootstrap_single(candidate)
            if kind is not None:
                new_kinds.append(kind)
                total_effort += effort

        self._bootstrapped_kinds.extend(new_kinds)
        return new_kinds

    def bootstrap_single(self, candidate: KindCandidate) -> NewKind | None:
        """Bootstrap a single :class:`NewKind` from one candidate.

        Returns ``None`` if the candidate is not viable or if definition
        validation fails.
        """
        if not candidate.is_viable(self._config.min_candidate_confidence):
            return None

        # 1. Build definition
        definition = self._def_builder.build_formal(candidate)
        valid, issues = self._def_builder.validate_definition(definition)
        if not valid and len(issues) > 2:
            # Too many issues – fall back to informal definition
            definition = self._def_builder.build(candidate)

        # 2. Generate examples
        examples = self._ex_generator.generate(candidate)

        # 3. Plan validation
        val_path = self._val_planner.plan(candidate)

        # 4. Assemble NewKind
        kind_id = str(uuid.uuid4())
        now = _now_iso()
        kind = NewKind(
            kind_id=kind_id,
            name=candidate.name,
            formal_name=_formal_name(candidate.name),
            definition=definition,
            formal_definition=definition,
            description=candidate.description,
            domain=" | ".join(candidate.field_ids[:3]) if candidate.field_ids else "general",
            examples=tuple(examples),
            obstruction_types=_candidate_obstruction_types(candidate),
            status=KindStatus.PROVISIONAL,
            confidence=candidate.confidence,
            novelty=candidate.novelty,
            candidate_id=candidate.candidate_id,
            created_at=now,
        )
        return kind

    def create_bootstrap_plan(self, candidate: KindCandidate) -> KindBootstrapPlan:
        """Create a :class:`KindBootstrapPlan` for *candidate*."""
        val_path = self._val_planner.plan(candidate)
        effort = _estimate_effort(candidate, depth=self._config.definition_depth)
        priority = _clamp(
            candidate.confidence * 0.5 + candidate.novelty * 0.5, 0.0, 1.0
        )
        return KindBootstrapPlan(
            plan_id=str(uuid.uuid4()),
            candidate_id=candidate.candidate_id,
            kind_name=candidate.name,
            target_kind=candidate.name,
            steps=val_path.steps,
            required_evidence=val_path.required_evidence,
            success_criteria=val_path.success_criteria,
            effort_estimate=effort,
            estimated_effort=effort,
            priority=priority,
            status=KindStatus.BOOTSTRAP_PENDING,
            created_at=_now_iso(),
        )

    # ------------------------------------------------------------------
    # Idea generation
    # ------------------------------------------------------------------

    def generate_ideas_for_kind(self, kind: NewKind) -> list[Idea]:
        """Generate research ideas motivated by the newly discovered kind.

        Uses the :class:`IdeaGenerator` to propose ideas whose purpose is
        centred on the kind's definition and domain.
        """
        if not self._config.auto_generate_ideas:
            return []
        count = self._config.idea_count_per_kind
        purpose = f"Develop and apply the {kind.name} to problems in {kind.domain}"
        target_area = kind.domain if kind.domain else "ideation"
        observations = tuple(
            f"The {kind.name} exhibits obstruction type: {ot}"
            for ot in kind.obstruction_types[:3]
        )
        try:
            raw = self._generator.generate(
                purpose=purpose,
                target_area=target_area,
                observations=observations,
                count=count,
            )
            return list(raw)
        except Exception:
            return []

    # ------------------------------------------------------------------
    # Evaluation and ranking
    # ------------------------------------------------------------------

    def evaluate_kind(
        self, kind: NewKind, *, portfolio: tuple[Idea, ...] = ()
    ) -> float:
        """Return a composite quality score in [0, 1] for *kind*.

        The score combines:
        * Confidence (30 %)
        * Novelty (30 %)
        * Definition completeness (20 %)
        * Example coverage (20 %)
        """
        conf_score = kind.confidence
        novelty_score = kind.novelty
        # Definition completeness: reward longer, axiom-rich definitions
        def_len = len(kind.definition)
        axiom_count = len(re.findall(r"\[Axiom \d+\]", kind.definition))
        def_score = _clamp(
            (def_len / 800.0) * 0.5 + (axiom_count / 5.0) * 0.5, 0.0, 1.0
        )
        # Example coverage: reward having both positive and negative examples
        has_pos = any("Positive" in e or "example" in e.lower() for e in kind.examples)
        has_neg = any("Negative" in e or "not a" in e.lower() for e in kind.examples)
        ex_score = _clamp(
            len(kind.examples) / max(1.0, self._config.example_count) * 0.6
            + 0.2 * has_pos
            + 0.2 * has_neg,
            0.0,
            1.0,
        )
        composite = (
            0.30 * conf_score
            + 0.30 * novelty_score
            + 0.20 * def_score
            + 0.20 * ex_score
        )
        return _clamp(round(composite, 4), 0.0, 1.0)

    def rank_kinds(self, kinds: list[NewKind]) -> list[tuple[NewKind, float]]:
        """Return kinds sorted by quality score, highest first."""
        scored = [(k, self.evaluate_kind(k)) for k in kinds]
        return sorted(scored, key=lambda x: x[1], reverse=True)

    # ------------------------------------------------------------------
    # Reporting
    # ------------------------------------------------------------------

    def full_report(self, kinds: list[NewKind]) -> dict[str, Any]:
        """Return a comprehensive dict report for a list of new kinds."""
        ranked = self.rank_kinds(kinds)
        by_status: dict[str, int] = Counter(k.status for k in kinds)
        avg_confidence = (
            sum(k.confidence for k in kinds) / len(kinds) if kinds else 0.0
        )
        avg_novelty = (
            sum(k.novelty for k in kinds) / len(kinds) if kinds else 0.0
        )
        obstruction_type_dist: Counter = Counter()
        for k in kinds:
            obstruction_type_dist.update(k.obstruction_types)
        return {
            "total_kinds": len(kinds),
            "by_status": dict(by_status),
            "average_confidence": round(avg_confidence, 4),
            "average_novelty": round(avg_novelty, 4),
            "top_3": [
                {"name": k.name, "score": round(s, 4), "status": k.status}
                for k, s in ranked[:3]
            ],
            "obstruction_type_distribution": dict(obstruction_type_dist),
            "config": self._config.to_dict(),
            "generated_at": _now_iso(),
        }

    def diagnostics(self, kinds: list[NewKind]) -> dict[str, Any]:
        """Return structured diagnostics for a list of new kinds."""
        if not kinds:
            return {
                "total_kinds": 0,
                "ranked_kinds": [],
                "score_stats": {"mean": 0.0, "max": 0.0, "min": 0.0},
                "below_confidence": [],
                "config": self._config.to_dict(),
                "generated_at": _now_iso(),
            }
        ranked = self.rank_kinds(kinds)
        ranked_kinds = []
        for kind, score in ranked:
            ranked_kinds.append(
                {
                    "name": kind.name,
                    "score": score,
                    "confidence": kind.confidence,
                    "novelty": kind.novelty,
                    "obstruction_type_count": len(kind.obstruction_types),
                    "example_count": len(kind.examples),
                    "definition_word_count": len(kind.definition.split()),
                }
            )

        low_conf = [
            {"name": kind.name, "confidence": kind.confidence}
            for kind, _ in ranked
            if kind.confidence < self._config.min_candidate_confidence
        ]
        scores = [s for _, s in ranked]
        mean_score = sum(scores) / len(scores) if scores else 0.0
        max_score = max(scores) if scores else 0.0
        min_score = min(scores) if scores else 0.0
        return {
            "total_kinds": len(kinds),
            "ranked_kinds": ranked_kinds,
            "score_stats": {
                "mean": round(mean_score, 4),
                "max": round(max_score, 4),
                "min": round(min_score, 4),
            },
            "below_confidence": low_conf,
            "config": self._config.to_dict(),
            "generated_at": _now_iso(),
        }
