@dataclass(frozen=True)
class BootstrapConfig:
    """Immutable configuration for the kind-bootstrapping pipeline.

    All numeric thresholds are validated at construction time.  Use the
    ``from_dict`` class method to load configuration from a plain dict.
    """

    min_pattern_frequency: int = 2
    min_candidate_confidence: float = _DEFAULT_MIN_CONFIDENCE
    max_hypotheses_per_pattern: int = _DEFAULT_MAX_HYPOTHESES
    definition_depth: int = _DEFAULT_DEFINITION_DEPTH
    example_count: int = _DEFAULT_EXAMPLE_COUNT
    validation_steps_count: int = _DEFAULT_VALIDATION_STEPS
    effort_budget: float = _DEFAULT_EFFORT_BUDGET
    auto_generate_ideas: bool = True
    idea_count_per_kind: int = _DEFAULT_IDEA_COUNT
    enable_cross_domain: bool = True

    def __post_init__(self) -> None:
        if self.min_pattern_frequency < 1:
            raise ValueError("min_pattern_frequency must be >= 1")
        if not (0.0 <= self.min_candidate_confidence <= 1.0):
            raise ValueError("min_candidate_confidence must be in [0, 1]")
        if self.max_hypotheses_per_pattern < 1:
            raise ValueError("max_hypotheses_per_pattern must be >= 1")
        if self.definition_depth < 1:
            raise ValueError("definition_depth must be >= 1")
        if self.example_count < 0:
            raise ValueError("example_count must be >= 0")
        if self.validation_steps_count < 0:
            raise ValueError("validation_steps_count must be >= 0")
        if self.effort_budget < 0.0:
            raise ValueError("effort_budget must be non-negative")
        if self.idea_count_per_kind < 0:
            raise ValueError("idea_count_per_kind must be >= 0")

    # ------------------------------------------------------------------
    # Mutation helpers (produce new frozen instances)
    # ------------------------------------------------------------------

    def with_effort_budget(self, budget: float) -> BootstrapConfig:
        """Return a new config with a different *budget*."""
        return replace(self, effort_budget=float(budget))

    def with_definition_depth(self, depth: int) -> BootstrapConfig:
        """Return a new config with a different definition *depth*."""
        return replace(self, definition_depth=int(depth))

    def with_confidence_threshold(self, threshold: float) -> BootstrapConfig:
        """Return a new config with a different minimum candidate confidence."""
        return replace(self, min_candidate_confidence=float(threshold))

    def relaxed(self) -> BootstrapConfig:
        """Return a more permissive config useful for exploratory runs."""
        return replace(
            self,
            min_pattern_frequency=1,
            min_candidate_confidence=max(0.1, self.min_candidate_confidence - 0.1),
            max_hypotheses_per_pattern=self.max_hypotheses_per_pattern + 3,
        )

    def strict(self) -> BootstrapConfig:
        """Return a stricter config useful for production runs."""
        return replace(
            self,
            min_pattern_frequency=max(3, self.min_pattern_frequency + 1),
            min_candidate_confidence=min(0.9, self.min_candidate_confidence + 0.15),
            max_hypotheses_per_pattern=max(1, self.max_hypotheses_per_pattern - 2),
        )

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        """Serialise to a plain Python dict."""
        return {
            "_schema": _SCHEMA_VERSION,
            "min_pattern_frequency": self.min_pattern_frequency,
            "min_candidate_confidence": self.min_candidate_confidence,
            "max_hypotheses_per_pattern": self.max_hypotheses_per_pattern,
            "definition_depth": self.definition_depth,
            "example_count": self.example_count,
            "validation_steps_count": self.validation_steps_count,
            "effort_budget": self.effort_budget,
            "auto_generate_ideas": self.auto_generate_ideas,
            "idea_count_per_kind": self.idea_count_per_kind,
            "enable_cross_domain": self.enable_cross_domain,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> BootstrapConfig:
        """Deserialise from a plain Python dict."""
        return cls(
            min_pattern_frequency=int(d.get("min_pattern_frequency", 2)),
            min_candidate_confidence=float(d.get("min_candidate_confidence", _DEFAULT_MIN_CONFIDENCE)),
            max_hypotheses_per_pattern=int(d.get("max_hypotheses_per_pattern", _DEFAULT_MAX_HYPOTHESES)),
            definition_depth=int(d.get("definition_depth", _DEFAULT_DEFINITION_DEPTH)),
            example_count=int(d.get("example_count", _DEFAULT_EXAMPLE_COUNT)),
            validation_steps_count=int(d.get("validation_steps_count", _DEFAULT_VALIDATION_STEPS)),
            effort_budget=float(d.get("effort_budget", _DEFAULT_EFFORT_BUDGET)),
            auto_generate_ideas=bool(d.get("auto_generate_ideas", True)),
            idea_count_per_kind=int(d.get("idea_count_per_kind", _DEFAULT_IDEA_COUNT)),
            enable_cross_domain=bool(d.get("enable_cross_domain", True)),
        )

    def __repr__(self) -> str:
        return (
            f"BootstrapConfig("
            f"min_freq={self.min_pattern_frequency}, "
            f"min_conf={self.min_candidate_confidence:.2f}, "
            f"depth={self.definition_depth}, "
            f"budget={self.effort_budget:.1f}"
            f")"
        )


