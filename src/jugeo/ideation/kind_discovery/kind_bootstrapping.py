class DefinitionBuilder:
    """Build formal textual definitions for kind candidates.

    Definitions are constructed from three main clauses:
    1. *Introduction* – what the object is
    2. *Obstruction characterisation* – which obstructions define it
    3. *Closure / existence* – what properties follow from the definition

    The :meth:`build_formal` method produces a more structured output with
    explicitly labelled axioms.
    """

    def __init__(self, config: BootstrapConfig | None = None) -> None:
        self._config = config or BootstrapConfig()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def build(self, candidate: KindCandidate) -> str:
        """Return an informal textual definition for *candidate*.

        Uses :func:`_candidate_definition_template` as the backbone and
        appends additional context if the candidate already has a draft
        definition.
        """
        depth = self._config.definition_depth
        base = _candidate_definition_template(
            candidate.name,
            " ".join(candidate.field_ids[:2]) if candidate.field_ids else "abstract",
            candidate.obstruction_types,
            depth=depth,
        )
        # Enrich with any existing draft material
        if candidate.definition_draft and len(candidate.definition_draft) > 20:
            extra_tokens = _tokenize(candidate.definition_draft)
            unique_extra = [t for t in extra_tokens if len(t) > 5][:6]
            if unique_extra:
                extra_phrase = ", ".join(unique_extra)
                base += (
                    f" Key structural features include: {extra_phrase}."
                )
        return base

    def build_formal(
        self, candidate: KindCandidate, *, depth: int | None = None
    ) -> str:
        """Return a structured, axiom-style definition for *candidate*.

        The output has the form::

            **Definition** (FormalName).
            [Axiom 1] ...
            [Axiom 2] ...
            ...
            **Remark.** ...
        """
        depth = depth if depth is not None else self._config.definition_depth
        formal = _formal_name(candidate.name)
        lines: list[str] = []
        lines.append(f"**Definition** ({formal}).")
        lines.append(self._intro_clause(candidate))

        # Obstruction axioms
        for idx, obs_type in enumerate(candidate.obstruction_types[:depth + 1], start=1):
            vocab = _OBS_TYPE_VOCAB.get(obs_type, obs_type)
            evidence = _EVIDENCE_VOCAB.get(obs_type, ())
            ev_hint = f" (witnessed by: {', '.join(evidence[:2])})" if evidence else ""
            lines.append(
                f"  [Axiom {idx}] A {formal} admits a {vocab}{ev_hint}."
            )

        lines.append(self._closure_clause(candidate))

        if depth >= 3:
            lines.append(self._existence_clause(candidate))

        # Remark
        remark_parts = []
        if candidate.confidence >= 0.7:
            remark_parts.append(f"This definition has high confidence ({candidate.confidence:.2f})")
        else:
            remark_parts.append(f"This definition is provisional (confidence={candidate.confidence:.2f})")
        if candidate.novelty >= 0.6:
            remark_parts.append(f"and represents a novel contribution (novelty={candidate.novelty:.2f})")
        lines.append("**Remark.** " + "; ".join(remark_parts) + ".")

        return "\n".join(lines)

    def build_from_obstructions(
        self, obstructions: list[ObstructionField | str], name: str
    ) -> str:
        """Build a definition directly from a list of obstruction fields.

        Aggregates the obstruction types across all fields and composes
        a unified definition for the named kind.
        """
        all_types: list[str] = []
        domains: list[str] = []
        for obstruction in obstructions:
            if isinstance(obstruction, str):
                normalized = _normalize_obstruction_type(obstruction)
                if normalized:
                    all_types.append(normalized)
                continue
            domains.append(obstruction.domain)
            all_types.extend(
                _normalize_obstruction_type(ot)
                for ot in getattr(obstruction, "obstruction_types", ())
                if _normalize_obstruction_type(ot)
            )
            if not getattr(obstruction, "obstruction_types", ()) and getattr(
                obstruction, "obstructions", ()
            ):
                all_types.extend(
                    _normalize_obstruction_type(text)
                    for text in obstruction.obstructions
                    if _normalize_obstruction_type(text)
                )
        type_counts = Counter(all_types)
        dominant_types = tuple(t for t, _ in type_counts.most_common(4))
        domain = next((domain for domain in domains if domain), "general")
        return _candidate_definition_template(
            name,
            domain,
            dominant_types,
            depth=self._config.definition_depth,
        )

    # ------------------------------------------------------------------
    # Clause builders
    # ------------------------------------------------------------------

    def _intro_clause(self, candidate: KindCandidate) -> str:
        """Return the introductory clause of a formal definition."""
        formal = _formal_name(candidate.name)
        num_types = len(candidate.obstruction_types)
        return (
            f"A {formal} X is an object satisfying the following {num_types} "
            f"obstruction-derived axioms, arising from the pattern(s) "
            f"{', '.join(candidate.pattern_ids[:3])}."
        )

    def _obstruction_clause(self, candidate: KindCandidate) -> str:
        """Return a clause describing the obstruction structure."""
        if not candidate.obstruction_types:
            return "No specific obstruction structure has been identified."
        type_phrases = [_OBS_TYPE_VOCAB.get(ot, ot) for ot in candidate.obstruction_types]
        joined = "; ".join(type_phrases)
        return (
            f"The obstruction structure of a {candidate.name} comprises: {joined}."
        )

    def _closure_clause(self, candidate: KindCandidate) -> str:
        """Return a closure property clause."""
        formal = _formal_name(candidate.name)
        return (
            f"  [Closure] The class of {formal}s is closed under "
            f"obstruction-resolution: if X is a {formal} and f : X → Y "
            f"resolves all constituent obstructions, then Y is also a {formal}."
        )

    def _existence_clause(self, candidate: KindCandidate) -> str:
        """Return an existence clause."""
        formal = _formal_name(candidate.name)
        return (
            f"  [Existence] There exists at least one non-degenerate {formal}; "
            f"moreover, each of the {len(candidate.obstruction_types)} obstruction "
            f"types is witnessed in this example."
        )

    # ------------------------------------------------------------------
    # Refinement
    # ------------------------------------------------------------------

    def refine_definition(
        self,
        definition: str,
        *,
        extra_constraints: tuple[str, ...] = (),
    ) -> str:
        """Append extra constraints to an existing definition text.

        Each constraint in *extra_constraints* is appended as an additional
        numbered axiom following any existing axioms in the definition.
        """
        if not extra_constraints:
            return definition
        # Count existing axioms
        existing_axioms = len(re.findall(r"\[Axiom \d+\]", definition))
        extra_lines: list[str] = []
        for idx, constraint in enumerate(extra_constraints, start=existing_axioms + 1):
            extra_lines.append(f"  [Axiom {idx}] {constraint}")
        return definition + "\n" + "\n".join(extra_lines)

    def validate_definition(self, definition: str) -> tuple[bool, list[str]]:
        """Perform basic quality checks on a definition string.

        Returns a (valid, issues) tuple where *issues* lists any detected
        problems.  A definition is considered valid when there are no issues.
        """
        issues: list[str] = []
        if len(definition) < 50:
            issues.append("Definition is too short (< 50 characters).")
        if not re.search(r"\bKind\b|\bkind\b", definition):
            issues.append("Definition does not mention 'kind'.")
        if not re.search(r"\baxiom\b|\bAxiom\b|\bsatisfying\b|\bcharacterised by\b", definition, re.IGNORECASE):
            issues.append("Definition lacks an explicit axiom or characterisation clause.")
        if definition.count(".") < 2:
            issues.append("Definition has fewer than 2 sentences.")
        if re.search(r"placeholder|TODO|FIXME|stub", definition, re.IGNORECASE):
            issues.append("Definition contains placeholder text.")
        return len(issues) == 0, issues


