def _clamp(value: float, lo: float, hi: float) -> float:
    """Return *value* clamped to the closed interval [*lo*, *hi*]."""
    return max(lo, min(hi, value))


def _now_iso() -> str:
    """Return the current UTC time as an ISO-8601 string."""
    return datetime.datetime.utcnow().isoformat(timespec="seconds") + "Z"


def _tokenize(text: str) -> list[str]:
    """Split *text* into lowercase alphabetic tokens, stripping stop words."""
    return [
        tok.lower()
        for tok in re.findall(r"[A-Za-z]+", text)
        if tok.lower() not in _STOP_WORDS
    ]


def _jaccard(a: frozenset[str], b: frozenset[str]) -> float:
    """Compute Jaccard similarity between two frozen token sets."""
    if not a and not b:
        return 1.0
    union = a | b
    if not union:
        return 0.0
    return len(a & b) / len(union)


def _title_case(text: str) -> str:
    """Convert *text* to title-case, preserving inner capitals."""
    if not text:
        return text
    words = text.strip().split()
    return " ".join(w.capitalize() for w in words)


def _formal_name(name: str) -> str:
    """Convert a human-readable kind name to a PascalCase formal identifier.

    Examples
    --------
    >>> _formal_name("obstruction field")
    'ObstructionField'
    >>> _formal_name("local-to-global kind")
    'LocalToGlobalKind'
    """
    parts = re.split(r"[\s\-_]+", name.strip())
    return "".join(p.capitalize() for p in parts if p)


def _candidate_definition_template(
    name: str,
    domain: str,
    obstruction_types: tuple[str, ...],
    depth: int = 2,
) -> str:
    """Return a multi-sentence definition template for a kind candidate.

    The template is constructed deterministically from the inputs so that
    repeated calls with identical arguments produce the same string.  The
    *depth* parameter controls the verbosity of the generated text (1 = brief,
    3 = detailed).
    """
    if not name:
        name = "unnamed kind"
    if not domain:
        domain = "general"

    formal = _formal_name(name)
    obs_phrases = [
        _OBS_TYPE_VOCAB.get(ot, ot) for ot in obstruction_types[:4]
    ]

    # Sentence 1 – introductory clause
    intro = (
        f"A {name} is a mathematical object in the domain of {domain} "
        f"characterised by its interaction with {len(obstruction_types)} "
        f"obstruction type(s)."
    )

    # Sentence 2 – obstruction characterisation
    if obs_phrases:
        obs_list = ", ".join(obs_phrases[:-1])
        if len(obs_phrases) > 1:
            obs_clause = f"It is defined by the presence of {obs_list} and {obs_phrases[-1]}."
        else:
            obs_clause = f"It is defined by the presence of {obs_phrases[0]}."
    else:
        obs_clause = "Its obstruction structure has not yet been fully determined."

    # Sentence 3 – closure property (depth ≥ 2)
    closure = ""
    if depth >= 2:
        closure = (
            f"The {formal} is closed under the relevant obstruction-resolving "
            f"operations, meaning that any resolution of a constituent "
            f"obstruction yields another {name} (or a degenerate case thereof)."
        )

    # Sentence 4 – existence clause (depth ≥ 3)
    existence = ""
    if depth >= 3:
        existence = (
            f"Existence of a non-trivial {name} in the {domain} domain implies "
            f"the existence of at least one obstruction of each constituent type, "
            f"and these obstructions are pairwise non-redundant."
        )

    parts = [intro, obs_clause]
    if closure:
        parts.append(closure)
    if existence:
        parts.append(existence)
    return " ".join(parts)


def _estimate_effort(candidate: KindCandidate, depth: int = 2) -> float:
    """Estimate the effort required to bootstrap a kind candidate.

    The estimate is a dimensionless score in [0, 20].  Higher values indicate
    more effort.  The heuristic is based on:

    * Number of obstruction types (more types ⇒ more complex)
    * Depth of the requested definition
    * Inverse of candidate confidence (lower confidence ⇒ more work needed)
    * Whether examples are already provided
    """
    base = 2.0
    # Each distinct obstruction type adds ~1.5 units of effort
    type_penalty = len(candidate.obstruction_types) * 1.5
    # Depth multiplier
    depth_factor = 1.0 + 0.3 * max(0, depth - 1)
    # Confidence discount – higher confidence means less validation work
    confidence_discount = 1.0 - _clamp(candidate.confidence, 0.0, 1.0)
    # Example bonus – existing examples reduce work
    example_discount = 0.5 * min(len(candidate.examples), 4) / 4.0
    # Counter-evidence penalty
    counter_penalty = 0.4 * min(len(candidate.counter_evidence), 5)

    effort = (base + type_penalty) * depth_factor * (1.0 + confidence_discount)
    effort -= example_discount
    effort += counter_penalty
    return _clamp(round(effort, 3), 0.0, 20.0)


def _evidence_keywords(obstruction_types: tuple[str, ...]) -> tuple[str, ...]:
    """Return a de-duplicated tuple of evidence keywords for the given types."""
    seen: set[str] = set()
    result: list[str] = []
    for ot in obstruction_types:
        for kw in _EVIDENCE_VOCAB.get(ot, ()):
            if kw not in seen:
                seen.add(kw)
                result.append(kw)
    return tuple(result)


def _normalize_obstruction_type(value: Any) -> str:
    if hasattr(value, "value"):
        return str(value.value)
    text = str(value or "").strip().lower()
    if not text:
        return ""
    if text in _OBS_TYPE_VOCAB:
        return text

    keyword_map = {
        "algebra": ObstructionType.ALGEBRAIC.value,
        "cohom": ObstructionType.ALGEBRAIC.value,
        "ext^": ObstructionType.ALGEBRAIC.value,
        "module": ObstructionType.ALGEBRAIC.value,
        "struct": ObstructionType.STRUCTURAL.value,
        "defin": ObstructionType.DEFINITIONAL.value,
        "comput": ObstructionType.COMPUTATIONAL.value,
        "logic": ObstructionType.LOGICAL.value,
        "empir": ObstructionType.EMPIRICAL.value,
        "bound": ObstructionType.BOUNDARY.value,
        "categor": ObstructionType.CATEGORICAL.value,
        "relation": ObstructionType.RELATIONAL.value,
        "semantic": ObstructionType.SEMANTIC.value,
        "syntax": ObstructionType.SYNTACTIC.value,
    }
    for needle, normalized in keyword_map.items():
        if needle in text:
            return normalized
    return text


def _candidate_obstruction_types(candidate: KindCandidate) -> tuple[str, ...]:
    normalized = [
        _normalize_obstruction_type(ot)
        for ot in getattr(candidate, "obstruction_types", ())
    ]
    normalized = [ot for ot in normalized if ot]
    if not normalized and getattr(candidate, "obstruction_pattern", ""):
        inferred = _normalize_obstruction_type(candidate.obstruction_pattern)
        if inferred:
            normalized.append(inferred)
    return tuple(dict.fromkeys(normalized))


