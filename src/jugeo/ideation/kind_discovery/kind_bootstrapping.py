class ValidationPlanner:
    """Create :class:`ValidationPath` objects for kind candidates and new kinds.

    The planner constructs ordered validation steps, required evidence, and
    success criteria based on the obstruction types and confidence of the
    candidate.  Higher confidence candidates receive shorter, more targeted
    plans; lower confidence candidates receive more exploratory plans.
    """

    # Templates for validation steps, keyed by validation-phase index
    _PHASE_TEMPLATES: tuple[str, ...] = (
        "Verify the informal definition against at least two known examples.",
        "Formalise the definition within the target proof assistant or framework.",
        "Check that the closure axiom holds for the provided positive examples.",
        "Identify at least one non-trivial negative example and verify exclusion.",
        "Construct the canonical existence witness for the kind.",
        "Verify consistency of the obstruction axioms by checking no pair is contradictory.",
        "Run an automated sanity check (type-checker / solver discharge) on the axioms.",
        "Obtain human attestation from a domain expert.",
    )

    def __init__(self, config: BootstrapConfig | None = None) -> None:
        self._config = config or BootstrapConfig()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def plan(self, candidate: KindCandidate) -> ValidationPath:
        """Create a :class:`ValidationPath` for *candidate*."""
        steps = self._steps_for_candidate(candidate)
        evidence = self._evidence_for_candidate(candidate)
        criteria = self._criteria_for_candidate(candidate)
        return ValidationPath(
            steps=steps,
            required_evidence=evidence,
            success_criteria=criteria,
        )

    def plan_for_new_kind(self, kind: NewKind) -> ValidationPath:
        """Create a validation plan for an already-bootstrapped :class:`NewKind`.

        Produces a more thorough plan than :meth:`plan` since the kind already
        has a definition and examples that can be leveraged.
        """
        # Build base plan from a synthetic candidate
        synthetic = KindCandidate(
            candidate_id=kind.candidate_id or str(uuid.uuid4()),
            name=kind.name,
            description=kind.description,
            obstruction_types=kind.obstruction_types,
            confidence=kind.confidence,
            novelty=kind.novelty,
            examples=kind.examples,
        )
        base_path = self.plan(synthetic)

        # Extend with kind-specific steps
        kind_label = kind.name or kind.formal_name or "this kind"
        extra_steps: list[str] = [
            f"Confirm that {kind_label} is distinct from adjacent notions in the literature."
        ]
        extra_evidence_items: list[str] = [f"named examples of {kind_label}"]
        if kind.examples:
            extra_steps.append(
                f"Validate all {len(kind.examples)} provided examples of {kind_label} individually."
            )
        if kind.theorems:
            extra_steps.append(
                f"Verify the {len(kind.theorems)} stated theorem(s) about {kind_label} hold for all "
                f"positive examples."
            )
        if kind.related_kinds:
            extra_steps.append(
                f"Check that {kind_label} is properly distinct from related kinds: "
                f"{', '.join(kind.related_kinds[:3])}."
            )

        if extra_steps:
            combined_steps = base_path.steps + tuple(extra_steps)
            extra_evidence = tuple(
                dict.fromkeys(
                    list(_evidence_keywords(kind.obstruction_types)) + extra_evidence_items
                )
            )
            combined_evidence = tuple(dict.fromkeys(base_path.required_evidence + extra_evidence))
            return ValidationPath(
                steps=combined_steps,
                required_evidence=combined_evidence,
                success_criteria=base_path.success_criteria,
            )
        return base_path

    def _evidence_for_candidate(self, candidate: KindCandidate) -> tuple[str, ...]:
        """Derive required evidence items from the candidate's obstruction types."""
        kws = _evidence_keywords(candidate.obstruction_types)
        # Add confidence-based evidence requirements
        extra: list[str] = []
        if candidate.confidence < 0.5:
            extra.append("independent corroboration from a second source")
        if candidate.novelty > 0.7:
            extra.append("novelty assessment from a domain expert")
        return tuple(dict.fromkeys(list(kws) + extra))

    def _steps_for_candidate(self, candidate: KindCandidate) -> tuple[str, ...]:
        """Derive validation steps from the candidate's properties."""
        n_steps = self._config.validation_steps_count
        # Choose steps based on confidence
        high_confidence = candidate.confidence >= 0.7
        selected: list[str] = []
        if high_confidence:
            # Targeted steps: focus on formalisation and verification
            indices = [1, 2, 3, 4, 6]
        else:
            # Exploratory steps: start from informal verification
            indices = [0, 1, 2, 3, 4, 5, 7]

        for idx in indices[:n_steps]:
            selected.append(self._PHASE_TEMPLATES[idx])

        # Ensure at least n_steps are returned
        extra_idx = 0
        while len(selected) < n_steps and extra_idx < len(self._PHASE_TEMPLATES):
            tmpl = self._PHASE_TEMPLATES[extra_idx]
            if tmpl not in selected:
                selected.append(tmpl)
            extra_idx += 1

        return tuple(selected[:n_steps])

    def _criteria_for_candidate(self, candidate: KindCandidate) -> tuple[str, ...]:
        """Derive success criteria from the candidate's properties."""
        criteria: list[str] = [
            "All positive examples satisfy every stated axiom.",
            "All negative examples fail at least one axiom.",
            "The closure axiom is verified for a non-trivial morphism.",
        ]
        if candidate.confidence >= 0.6:
            criteria.append("An automated solver discharges the consistency check.")
        if len(candidate.obstruction_types) >= 3:
            criteria.append(
                "Each of the constituent obstruction types is independently witnessed."
            )
        return tuple(criteria)

    def strengthen_plan(
        self,
        path: ValidationPath,
        *,
        extra_evidence: tuple[str, ...] = (),
    ) -> ValidationPath:
        """Return a strengthened plan with additional evidence requirements."""
        combined = tuple(dict.fromkeys(path.required_evidence + extra_evidence))
        extra_step = (
            "Perform a cross-validation check against an independent obstruction corpus.",
        )
        combined_steps = path.steps + extra_step
        extra_criterion = "Cross-validation passes with precision ≥ 0.90."
        combined_criteria = path.success_criteria + (extra_criterion,)
        return ValidationPath(
            steps=combined_steps,
            required_evidence=combined,
            success_criteria=combined_criteria,
        )

    def plan_from_bootstrap(self, plan: KindBootstrapPlan) -> ValidationPath:
        """Extract a :class:`ValidationPath` from a :class:`KindBootstrapPlan`."""
        return ValidationPath(
            steps=plan.steps,
            required_evidence=plan.required_evidence,
            success_criteria=plan.success_criteria,
        )


