"""novel_problem_codegen -- code generation for previously-inarticulable computations.
# copilot: novel problem identification and code generation for previously-inarticulable computations

Philosophical premise
---------------------
The code generated by this module is *not* a reimplementation of a known algorithm
in a new notation, nor a utility library, nor a translation of existing code.

It is code that computes things that had *no name* before the new foundational
mathematics existed -- computations whose problem statements require the new vocabulary
to even be written down.

Three historical archetypes guide this criterion:

1. **Fourier analysis** (1822) let us ask "what is the frequency content of this
   signal?" -- a question that was *inarticulable* before, not merely hard to answer.
   The FFT is not a faster way to compute something old; it is an algorithm whose
   *inputs and outputs are defined by the new mathematics*.

2. **Optimal transport / Wasserstein distance** (Kantorovich, 1942) let us ask
   "how different are these two probability distributions in terms of moving mass?"
   Before optimal transport, no well-founded metric on distributions existed that
   captured *geometric* displacement.  The Sinkhorn algorithm didn't speed up an
   old computation -- it computed something that had no prior expression.

3. **Persistent homology / TDA** (Edelsbrunner et al., 2002) lets us ask "what
   topological features of this dataset persist across scales?"  The barcode of
   a filtered simplicial complex is a mathematical object that *did not exist*
   before this theory -- you couldn't ask for it, let alone compute it.

The NovelProblemCodegen class operates on the *winner* of the synthesis tournament
(a FieldNode synthesising multiple mathematical domains) and asks: **what can we
now compute that we could not ask about before this synthesis existed?**  It then
generates real Python modules implementing those computations.

Structure
---------
- NovelProblemSpec     -- describes a problem that only exists due to the new math
- GeneratedNovelCode   -- a Python module implementing such a computation
- NovelProblemCodegen  -- identifies and implements novel computations for a winner
- write_inarticulable_problems_report -- markdown report of the generated problems
- register_with_foundation_pipeline   -- integration hook for FoundationPipeline

LLM backend
-----------
Three tiers, tried in order:
  1. copilot-cli subprocess  (``copilot --model … -p …``)
  2. Anthropic SDK           (``anthropic.Anthropic()``)
  3. OpenAI SDK              (``openai.OpenAI()``)
If all fail, the heuristic fallback generates structurally valid code from the
winner's constituent fields without any network calls.
"""
