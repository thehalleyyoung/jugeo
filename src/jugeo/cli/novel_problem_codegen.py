@dataclass
class NovelProblemSpec:
    """A computation that only exists because of the new foundational mathematics.

    This is the central epistemic claim of this module: before the synthesis
    encoded in ``winner``, the problem described here could not be *stated*.
    Not "could not be solved efficiently" -- could not be *formulated*.

    Attributes
    ----------
    problem_id
        Unique slug, e.g. ``"cohomological-distribution-distance-001"``.
    title
        Short human-readable name, e.g. "Cohomological Distribution Metric".
    pre_theory_status
        One of ``"inarticulable"`` | ``"unsolvable"`` | ``"misformulated"``.
        - *inarticulable*: the question had no expression in prior vocabulary.
        - *unsolvable*: the question could be asked but had no computational
          answer (e.g. lacked a canonical metric or decision procedure).
        - *misformulated*: the question was asked but in a provably wrong way,
          and the new math corrects the formulation.
    why_new_math_enables_it
        The key conceptual unlock -- what the new synthesis provides that makes
        the computation possible or meaningful.
    formal_statement
        The problem stated using the new math's vocabulary.  May include inline
        mathematical notation.
    computational_signature
        Input/output types in quasi-mathematical notation,
        e.g. ``"(μ: Measure(X), ν: Measure(X)) → ℝ≥0"``.
    expected_output_type
        Python-level output description, e.g. ``"float"`` or ``"list[tuple]"``.
    difficulty
        ``"conceptual"`` | ``"computational"`` | ``"structural"``.
        - *conceptual*: the hard part is understanding what to compute.
        - *computational*: the hard part is the algorithm.
        - *structural*: the hard part is the data-structure design.
    algorithm_sketch
        Informal description of how the computation works.
    source_fields
        Names of constituent fields whose synthesis enabled this problem.
    """

    problem_id: str
    title: str
    pre_theory_status: str           # "inarticulable" | "unsolvable" | "misformulated"
    why_new_math_enables_it: str     # the key insight
    formal_statement: str            # stated in the new math's vocabulary
    computational_signature: str     # input/output in math notation
    expected_output_type: str        # Python output description
    difficulty: str                  # "conceptual" | "computational" | "structural"
    algorithm_sketch: str = ""       # how to solve it
    source_fields: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "problem_id": self.problem_id,
            "title": self.title,
            "pre_theory_status": self.pre_theory_status,
            "why_new_math_enables_it": self.why_new_math_enables_it,
            "formal_statement": self.formal_statement,
            "computational_signature": self.computational_signature,
            "expected_output_type": self.expected_output_type,
            "difficulty": self.difficulty,
            "algorithm_sketch": self.algorithm_sketch,
            "source_fields": self.source_fields,
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> "NovelProblemSpec":
        return cls(
            problem_id=d.get("problem_id", str(uuid.uuid4())[:8]),
            title=d.get("title", "Unnamed Problem"),
            pre_theory_status=d.get("pre_theory_status", "inarticulable"),
            why_new_math_enables_it=d.get("why_new_math_enables_it", ""),
            formal_statement=d.get("formal_statement", ""),
            computational_signature=d.get("computational_signature", "() → ()"),
            expected_output_type=d.get("expected_output_type", "Any"),
            difficulty=d.get("difficulty", "conceptual"),
            algorithm_sketch=d.get("algorithm_sketch", ""),
            source_fields=list(d.get("source_fields", [])),
        )

    def summary(self) -> str:
        return (
            f"[{self.problem_id}] {self.title}\n"
            f"  Status before: {self.pre_theory_status}\n"
            f"  Enabled by: {self.why_new_math_enables_it[:120]}\n"
            f"  Signature: {self.computational_signature}"
        )


@dataclass
class GeneratedNovelCode:
    """A Python module implementing a previously-inarticulable computation.

    This is the output artifact of NovelProblemCodegen.  Each instance
    corresponds to one NovelProblemSpec and contains real, runnable Python
    source code that implements the computation.

    The ``mathematical_justification`` field is as important as the code
    itself -- it explains *why* the code is only possible with the new
    mathematics, and should be written as though explaining to a mathematician
    why this program couldn't have existed before.

    Attributes
    ----------
    spec
        The problem specification this code implements.
    module_name
        Python module name, e.g. ``"cohomological_distribution_metric"``.
    source_code
        Complete, runnable Python source (not a stub -- real implementation).
    mathematical_justification
        Prose explanation of why this code requires the new mathematics.
        Should follow the pattern: "Before [new math], … After [new math], …"
    example_inputs
        List of dicts describing example inputs (for documentation).
    example_outputs
        List of strings describing example outputs (for documentation).
    lines_of_code
        Approximate line count of source_code.
    generated_at
        Unix timestamp of generation.
    llm_used
        Whether an LLM was used (True) or fallback template (False).
    """

    spec: NovelProblemSpec
    module_name: str
    source_code: str
    mathematical_justification: str
    example_inputs: list[dict]
    example_outputs: list[str]
    lines_of_code: int
    generated_at: float = field(default_factory=time.time)
    llm_used: bool = False

    def first_n_lines(self, n: int = 20) -> str:
        """Return the first *n* lines of source_code for preview."""
        lines = self.source_code.splitlines()
        return "\n".join(lines[:n])

    def to_dict(self) -> dict[str, Any]:
        return {
            "spec": self.spec.to_dict(),
            "module_name": self.module_name,
            "source_code": self.source_code,
            "mathematical_justification": self.mathematical_justification,
            "example_inputs": self.example_inputs,
            "example_outputs": self.example_outputs,
            "lines_of_code": self.lines_of_code,
            "generated_at": self.generated_at,
            "llm_used": self.llm_used,
        }


