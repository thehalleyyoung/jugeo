def _title_to_module_name(title: str) -> str:
    """Convert a problem title to a snake_case Python module name.

    Examples
    --------
    >>> _title_to_module_name("Wasserstein Distance on Graphs")
    'wasserstein_distance_on_graphs'
    """
    # Lowercase, replace non-alphanumeric runs with underscores
    name = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")
    # Ensure it starts with a letter
    if name and name[0].isdigit():
        name = "novel_" + name
    return name or "novel_computation"


def _title_to_class_name(title: str) -> str:
    """Convert a problem title to a CamelCase Python class name.

    Examples
    --------
    >>> _title_to_class_name("Wasserstein Distance on Graphs")
    'WassersteinDistanceOnGraphs'
    """
    words = re.sub(r"[^a-zA-Z0-9]+", " ", title).split()
    return "".join(w.capitalize() for w in words) or "NovelComputation"


