def _call_copilot_subprocess(prompt: str, model: str = "claude-sonnet-4.6", timeout: int = 120) -> str:
    """Call the copilot CLI as a subprocess.

    Uses the standard copilot-cli invocation pattern::

        copilot --model <model> --no-auto-accept -p <prompt>

    Returns the stdout text on success, raises RuntimeError on failure.
    """
    try:
        result = subprocess.run(
            ["copilot", "--model", model, "--no-auto-accept", "-p", prompt],
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        if result.returncode == 0 and result.stdout.strip():
            return result.stdout
        # Non-zero exit -- raise so caller can try next backend.
        raise RuntimeError(
            f"copilot subprocess exited {result.returncode}: {result.stderr[:200]}"
        )
    except FileNotFoundError:
        raise RuntimeError("copilot CLI not found in PATH")
    except subprocess.TimeoutExpired:
        raise RuntimeError(f"copilot subprocess timed out after {timeout}s")


def _call_anthropic(prompt: str, model: str = "claude-sonnet-4-5", max_tokens: int = 4096) -> str:
    """Call Anthropic API directly.  Raises ImportError if SDK not installed."""
    import anthropic  # type: ignore[import]
    client = anthropic.Anthropic()
    message = client.messages.create(
        model=model,
        max_tokens=max_tokens,
        messages=[{"role": "user", "content": prompt}],
    )
    return message.content[0].text


def _call_openai(prompt: str, model: str = "gpt-4o", max_tokens: int = 4096) -> str:
    """Call OpenAI API directly.  Raises ImportError if SDK not installed."""
    import openai  # type: ignore[import]
    client = openai.OpenAI()
    response = client.chat.completions.create(
        model=model,
        max_tokens=max_tokens,
        messages=[{"role": "user", "content": prompt}],
        timeout=120,
    )
    return response.choices[0].message.content or ""


def _llm_call(prompt: str, model: str = "claude-sonnet-4.6", timeout: int = 120) -> str:
    """Try copilot subprocess, then Anthropic SDK, then OpenAI SDK.

    Raises RuntimeError if all three backends fail.
    """
    errors: list[str] = []

    # 1. copilot CLI subprocess
    try:
        return _call_copilot_subprocess(prompt, model=model, timeout=timeout)
    except Exception as exc:
        errors.append(f"copilot: {exc}")
        logger.debug("copilot subprocess failed: %s", exc)

    # 2. Anthropic SDK
    try:
        # Map copilot model names to Anthropic names where needed
        anthropic_model = model.replace("claude-sonnet-4.6", "claude-sonnet-4-5")
        return _call_anthropic(prompt, model=anthropic_model)
    except ImportError:
        errors.append("anthropic: SDK not installed")
    except Exception as exc:
        errors.append(f"anthropic: {exc}")
        logger.debug("Anthropic SDK failed: %s", exc)

    # 3. OpenAI SDK
    try:
        return _call_openai(prompt)
    except ImportError:
        errors.append("openai: SDK not installed")
    except Exception as exc:
        errors.append(f"openai: {exc}")
        logger.debug("OpenAI SDK failed: %s", exc)

    raise RuntimeError(
        "All LLM backends failed:\n" + "\n".join(f"  - {e}" for e in errors)
    )


def _extract_json(text: str) -> dict[str, Any] | list[Any]:
    """Extract the first JSON object or array from *text*.

    Attempts in order:
    1. ```json … ``` fenced block
    2. Bare JSON parse of the entire text
    3. Heuristic: find first ``{`` or ``[`` and parse from there

    Raises json.JSONDecodeError if nothing works.
    """
    # 1. Fenced block
    m = re.search(r"```json\s*(.*?)\s*```", text, re.DOTALL)
    if m:
        try:
            return json.loads(m.group(1))
        except json.JSONDecodeError:
            pass

    # 2. Full text
    try:
        return json.loads(text.strip())
    except json.JSONDecodeError:
        pass

    # 3. Heuristic scan
    for start_char, end_char in [("{", "}"), ("[", "]")]:
        idx = text.find(start_char)
        if idx != -1:
            # Find matching end by counting depth
            depth = 0
            in_string = False
            escape = False
            end_idx = -1
            for i, ch in enumerate(text[idx:], start=idx):
                if escape:
                    escape = False
                    continue
                if ch == "\\" and in_string:
                    escape = True
                    continue
                if ch == '"':
                    in_string = not in_string
                    continue
                if in_string:
                    continue
                if ch == start_char:
                    depth += 1
                elif ch == end_char:
                    depth -= 1
                    if depth == 0:
                        end_idx = i
                        break
            if end_idx != -1:
                try:
                    return json.loads(text[idx: end_idx + 1])
                except json.JSONDecodeError:
                    pass

    raise json.JSONDecodeError("No JSON found in text", text, 0)


def _extract_python_code(text: str) -> str:
    """Extract the first ```python … ``` block from *text*, or return *text* itself."""
    m = re.search(r"```python\s*(.*?)\s*```", text, re.DOTALL)
    if m:
        return m.group(1).strip()
    # Try generic code fence
    m = re.search(r"```\s*(.*?)\s*```", text, re.DOTALL)
    if m:
        return m.group(1).strip()
    return text.strip()


