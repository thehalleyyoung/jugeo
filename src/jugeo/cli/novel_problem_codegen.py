def write_inarticulable_problems_report(
    specs: list[NovelProblemSpec],
    codes: list[GeneratedNovelCode],
    output_path: Path,
) -> Path:
    """Write a markdown report: "Problems Previously Without Expression".

    For each problem, the report shows:
    - The pre-theory status (why it was inarticulable)
    - The key unlock (what the new math provides)
    - The formal statement
    - Which generated module implements it
    - The first 20 lines of the generated code

    Parameters
    ----------
    specs
        List of NovelProblemSpec instances (from identify_novel_problems).
    codes
        List of GeneratedNovelCode instances (from generate_all).
    output_path
        Where to write the Markdown file.

    Returns
    -------
    Path
        The path that was written to (same as output_path).
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Build a lookup from problem_id to GeneratedNovelCode
    code_by_id: dict[str, GeneratedNovelCode] = {}
    for c in codes:
        code_by_id[c.spec.problem_id] = c

    # Infer math name from codes or specs
    math_name = "the new foundational mathematics"
    if codes:
        # Try to extract from mathematical_justification
        m = re.search(r"Before (.+?),", codes[0].mathematical_justification)
        if m:
            math_name = m.group(1).strip()

    lines: list[str] = [
        "# Problems Previously Without Expression",
        f"## Made possible by: {math_name}",
        "",
        "> This document records computational problems that could not be *stated* ",
        "> before the new foundational mathematics was developed.  These are not ",
        '> "faster algorithms" or "better implementations" -- they are computations ',
        "> whose *problem statements* require vocabulary that did not exist before.",
        "",
        "---",
        "",
    ]

    for i, spec in enumerate(specs, start=1):
        code = code_by_id.get(spec.problem_id)

        lines += [
            f"### Problem {i}: {spec.title}",
            "",
            f"**Status before {math_name}:** {spec.pre_theory_status}",
            "",
            f"**The unlock:** {spec.why_new_math_enables_it}",
            "",
            f"**Formal statement:** {spec.formal_statement}",
            "",
            f"**Computational signature:** `{spec.computational_signature}`",
            "",
            f"**Difficulty:** {spec.difficulty}",
            "",
        ]

        if spec.algorithm_sketch:
            lines += [
                "**Algorithm sketch:**",
                "",
                spec.algorithm_sketch,
                "",
            ]

        if code:
            module_path = f"src/{code.module_name.replace('.', '/')}.py"
            lines += [
                f"**Implemented in:** `{module_path}`",
                f"**Lines of code:** {code.lines_of_code}",
                f"**LLM generated:** {'yes' if code.llm_used else 'no (heuristic fallback)'}",
                "",
                "**Key excerpt (first 20 lines):**",
                "",
                "```python",
                code.first_n_lines(20),
                "```",
                "",
            ]
        else:
            lines += [
                "*Code not yet generated for this problem.*",
                "",
            ]

        lines += ["---", ""]

    # Appendix: summary table
    lines += [
        "## Summary Table",
        "",
        "| # | Title | Status | Difficulty | Module |",
        "|---|-------|--------|------------|--------|",
    ]
    for i, spec in enumerate(specs, start=1):
        code = code_by_id.get(spec.problem_id)
        module_cell = f"`{code.module_name}`" if code else "--"
        lines.append(
            f"| {i} | {spec.title} | {spec.pre_theory_status} "
            f"| {spec.difficulty} | {module_cell} |"
        )

    lines += [
        "",
        "---",
        "",
        f"*Report generated at {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}*",
        "",
    ]

    output_path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote inarticulable problems report to %s", output_path)
    return output_path


