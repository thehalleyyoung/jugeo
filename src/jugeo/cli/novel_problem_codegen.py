class NovelProblemCodegen:
    """Identify and implement computations made possible by a new foundational mathematics.

    Given the *winner* of a synthesis tournament (a FieldNode that synthesises
    multiple mathematical domains), this class:

    1. Asks an LLM (or falls back to heuristics) to identify 5-8 computational
       problems that were *inarticulable* before this synthesis.
    2. Generates a complete, runnable Python module for each problem.
    3. Writes the modules to ``output_dir``.

    The key epistemic standard: each problem must satisfy the criterion that its
    *problem statement* requires the new mathematical vocabulary -- not just that
    the solution is easier with the new math.

    Parameters
    ----------
    winner
        The FieldNode representing the winning synthesis from the tournament.
    output_dir
        Directory where generated ``.py`` files will be written.
    use_llm
        If True (default), attempt LLM-based generation.  Falls back to
        heuristic if LLM is unavailable.
    model
        LLM model identifier passed to the copilot subprocess / API.
    retry_attempts
        Number of LLM retry attempts before falling back to heuristics.
    """

    def __init__(
        self,
        winner: "FieldNode",
        output_dir: Path,
        use_llm: bool = True,
        model: str = "claude-sonnet-4.6",
        retry_attempts: int = 2,
    ) -> None:
        self.winner = winner
        self.output_dir = Path(output_dir)
        self.use_llm = use_llm
        self.model = model
        self.retry_attempts = retry_attempts
        self._winner_summary: str | None = None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def identify_novel_problems(self) -> list[NovelProblemSpec]:
        """Ask: what computations does this new math uniquely enable?

        Uses LLM to find 5-8 problems of the form:
          "Before [new math], we couldn't even ask [question].
           Now we can compute [thing] by [method]."

        Falls back to heuristic generation if LLM is unavailable.
        """
        summary = self._get_winner_summary()

        if self.use_llm:
            for attempt in range(max(1, self.retry_attempts)):
                try:
                    raw = self._llm_identify_problems(summary)
                    if raw:
                        logger.info(
                            "Identified %d novel problems via LLM (attempt %d)",
                            len(raw), attempt + 1,
                        )
                        return [NovelProblemSpec.from_dict(d) for d in raw]
                except Exception as exc:
                    logger.warning("LLM problem identification attempt %d failed: %s", attempt + 1, exc)

        logger.info("Using heuristic fallback for problem identification")
        return self._fallback_identify_problems(self.winner)

    def generate_code_for_problem(self, spec: NovelProblemSpec) -> GeneratedNovelCode:
        """Generate real Python code implementing the novel computation.

        The LLM prompt explicitly emphasises:
        - Data types should embody the new mathematical structure
        - Algorithm steps should mirror the mathematical construction
        - Docstring must explain what was previously inarticulable

        Falls back to template-based code if LLM is unavailable.
        """
        summary = self._get_winner_summary()
        llm_used = False
        source_code = ""

        if self.use_llm:
            for attempt in range(max(1, self.retry_attempts)):
                try:
                    source_code = self._llm_generate_code(spec, summary)
                    if source_code and len(source_code) > 200:
                        llm_used = True
                        logger.info(
                            "Generated code for '%s' via LLM (%d chars)",
                            spec.title, len(source_code),
                        )
                        break
                except Exception as exc:
                    logger.warning("LLM code generation attempt %d failed: %s", attempt + 1, exc)

        if not source_code:
            source_code = self._fallback_generate_code(spec)
            logger.info("Generated fallback code for '%s'", spec.title)

        loc = len(source_code.splitlines())
        module_name = _title_to_module_name(spec.title)

        justification = (
            f"Before {self.winner.name}, {spec.pre_theory_status}: "
            f"{spec.why_new_math_enables_it}  "
            f"The algorithm implements {spec.formal_statement} "
            f"using the structure of {', '.join(self.winner.constituent_fields[:3])}."
        )

        return GeneratedNovelCode(
            spec=spec,
            module_name=module_name,
            source_code=source_code,
            mathematical_justification=justification,
            example_inputs=[{"description": spec.computational_signature}],
            example_outputs=[spec.expected_output_type],
            lines_of_code=loc,
            llm_used=llm_used,
        )

    def generate_all(self) -> list[GeneratedNovelCode]:
        """Run identify_novel_problems() then generate_code_for_problem() for each.

        Returns a list of GeneratedNovelCode instances, one per identified problem.
        Errors in individual code generation are logged and skipped.
        """
        specs = self.identify_novel_problems()
        results: list[GeneratedNovelCode] = []

        for i, spec in enumerate(specs):
            try:
                code = self.generate_code_for_problem(spec)
                results.append(code)
                logger.info("Generated code %d/%d: %s", i + 1, len(specs), spec.title)
            except Exception as exc:
                logger.error("Failed to generate code for '%s': %s", spec.title, exc)

        return results

    def write_files(self, codes: list[GeneratedNovelCode]) -> list[Path]:
        """Write each GeneratedNovelCode to a .py file in output_dir.

        Returns the list of written file paths.
        """
        self.output_dir.mkdir(parents=True, exist_ok=True)
        written: list[Path] = []

        for code in codes:
            filename = f"{code.module_name}.py"
            path = self.output_dir / filename
            try:
                path.write_text(code.source_code, encoding="utf-8")
                written.append(path)
                logger.info("Wrote %d lines to %s", code.lines_of_code, path)
            except OSError as exc:
                logger.error("Failed to write %s: %s", path, exc)

        return written

    # ------------------------------------------------------------------
    # LLM methods
    # ------------------------------------------------------------------

    def _llm_identify_problems(self, winner_summary: str) -> list[dict]:
        """Call the LLM to identify novel problems.

        System prompt context: mathematical visionary identifying computations
        that only exist because of the new synthesis.

        Returns a list of dicts conforming to NovelProblemSpec.from_dict().
        Raises RuntimeError or json.JSONDecodeError on failure.
        """
        props = self.winner.propositions or []
        prop_lines = []
        for p in props[:8]:  # limit to 8 propositions to keep prompt manageable
            title = getattr(p, "title", str(p))
            stmt = getattr(p, "statement", "")
