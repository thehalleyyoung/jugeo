def register_with_foundation_pipeline(pipeline_instance: Any) -> None:
    """Attach a NovelProblemCodegen instance to a FoundationPipeline.

    This function monkey-patches ``pipeline_instance`` to add:
    - ``pipeline_instance.novel_codegen`` -- a lazy NovelProblemCodegen factory
      (instantiated on first call, once the winner is known)
    - ``pipeline_instance._stage2_generate_novel_code(winner)`` -- a bound
      method that runs the full identify → generate → write pipeline

    If the pipeline already has ``_stage2_generate_code``, this function
    replaces it with the novel-problem version.  The original is saved as
    ``_stage2_generate_code_original``.

    Compatible with ``FoundationPipeline`` as defined in foundation_pipeline.py:
    - Reads ``self._model`` (falls back to ``self.model``) for the model name.
    - Reads ``self._no_llm`` (inverted) or ``self.use_llm`` for LLM flag.
    - ``_stage2_generate_code`` receives ``winner`` as a positional argument.

    Parameters
    ----------
    pipeline_instance
        An instance of FoundationPipeline (or any object with an
        ``output_dir`` attribute and optionally ``_model`` / ``_no_llm``).
    """
    # Resolve attributes -- FoundationPipeline uses underscore-prefixed names
    output_dir = getattr(
        pipeline_instance, "output_dir",
        Path(getattr(pipeline_instance, "_output_dir", "."))
    )
    # Model: check _model first (FoundationPipeline), then model (generic)
    model = getattr(
        pipeline_instance, "_model",
        getattr(pipeline_instance, "model", "claude-sonnet-4.6")
    )
    # LLM flag: FoundationPipeline uses _no_llm (inverted); generic uses use_llm
    if hasattr(pipeline_instance, "_no_llm"):
        use_llm = not pipeline_instance._no_llm
    else:
        use_llm = getattr(pipeline_instance, "use_llm", True)

    def _build_codegen(winner: Any) -> "NovelProblemCodegen":
        """Lazily construct a NovelProblemCodegen once the winner is known."""
        return NovelProblemCodegen(
            winner=winner,
            output_dir=Path(output_dir) / "novel_code",
            use_llm=use_llm,
            model=model,
        )

    # Store a lazy factory so the codegen can be constructed on first call
    pipeline_instance._novel_codegen_factory = _build_codegen
    pipeline_instance.novel_codegen = None  # populated on first call

    def _stage2_generate_novel_code(winner_arg: Any) -> list[GeneratedNovelCode]:
        """Run identify → generate → write for all novel problems.

        Parameters
        ----------
        winner_arg
            The winning FieldNode from the synthesis tournament.
        """
        codegen = _build_codegen(winner_arg)
        pipeline_instance.novel_codegen = codegen

        codes = codegen.generate_all()
        written = codegen.write_files(codes)
        logger.info(
            "Novel code stage complete: %d modules written to %s",
            len(written), codegen.output_dir,
        )
        # Write the problems report alongside the generated code
        report_path = codegen.output_dir / "inarticulable_problems.md"
        write_inarticulable_problems_report(
            specs=[c.spec for c in codes],
            codes=codes,
            output_path=report_path,
        )
        return codes

    # Save original _stage2_generate_code if present
    if hasattr(pipeline_instance, "_stage2_generate_code"):
        pipeline_instance._stage2_generate_code_original = (
            pipeline_instance._stage2_generate_code
        )

    # Replace _stage2_generate_code with a bound method that delegates to
    # _stage2_generate_novel_code.  The FoundationPipeline calls it as:
    #   self._stage2_generate_code(winner)
    import types

    def _patched_stage2(self_inner: Any, winner_arg: Any) -> list[Any]:
        return _stage2_generate_novel_code(winner_arg)

    pipeline_instance._stage2_generate_code = types.MethodType(
        _patched_stage2, pipeline_instance
    )

    logger.info(
        "NovelProblemCodegen registered with pipeline (output_dir=%s, use_llm=%s, model=%s)",
        Path(output_dir) / "novel_code",
        use_llm,
        model,
    )


