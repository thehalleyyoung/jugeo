    def compare_approaches(self, approaches: list[str]) -> str:
        """Return a formatted comparison table for the listed approaches.

        Args:
            approaches: List of solver/approach names to compare.  Must be
                keys in ``EXISTING_SOLVER_SURVEY``.

        Returns:
            A formatted string table with approaches as columns and capabilities
            as rows.

        Raises:
            KeyError: If any name in *approaches* is not in the survey.
        """
        valid = [a for a in approaches if a in EXISTING_SOLVER_SURVEY]
        if not valid:
            return "No valid approaches to compare."

        capabilities = ["string_theory", "regex_support", "length_constraints", "decidable_fragments"]
        col_width = 22
        header = "Capability".ljust(col_width) + "".join(a.ljust(col_width) for a in valid)
        separator = "-" * len(header)
        rows = [header, separator]
        for cap in capabilities:
            row = cap.ljust(col_width)
            for approach in valid:
                val = EXISTING_SOLVER_SURVEY[approach].get(cap, "N/A")
                if isinstance(val, list):
                    val = ", ".join(str(v) for v in val[:2])
                row += str(val)[:col_width - 1].ljust(col_width)
            rows.append(row)
        return "\n".join(rows)

