def get_motivation_summary() -> str:
    """Return a combined summary of all motivation classes.

    Instantiates :class:`WhyTextDeservesStructure`, :class:`StringSolverSurvey`,
    and :class:`SymbolicTextMotivation` and combines their key outputs into a
    single summary string.

    Returns:
        A multi-section string summarising the motivation for symbolic text encoding.

    Example::

        summary = get_motivation_summary()
        assert "NamingLaw" in summary
        assert "DocumentationShadow" in summary
    """
    why = WhyTextDeservesStructure()
    survey = StringSolverSurvey()
    motivation = SymbolicTextMotivation()

    sections: list[str] = [
        "=" * 70,
        "SYMBOLIC TEXT ENCODING — MOTIVATION SUMMARY (Ch28)",
        "=" * 70,
        "",
        why.thesis_statement(),
        "",
        "STRING SOLVER SURVEY",
        "--------------------",
    ]
    for solver_name, desc in why.survey_existing_approaches().items():
        sections.append(f"  {solver_name}: {desc[:120]}...")
    sections += [
        "",
        "GAPS IN EXISTING APPROACHES",
        "---------------------------",
    ]
    for gap in why.identify_gaps():
        sections.append(f"  - {gap}")
    sections += [
        "",
        "MOTIVATIONS FOR NAMING LAWS",
        "---------------------------",
    ]
    for m in motivation.motivate_naming_laws()[:5]:
        sections.append(f"  - {m[:100]}")
    sections += [
        "",
        "MOTIVATIONS FOR DOCUMENTATION SHADOWS",
        "--------------------------------------",
    ]
    for m in motivation.motivate_documentation_shadows()[:5]:
        sections.append(f"  - {m[:100]}")
    sections += [
        "",
        "COST-BENEFIT SUMMARY",
        "--------------------",
    ]
    cba = motivation.cost_benefit_analysis()
    sections.append(f"  Net assessment: {cba['net_assessment'][:150]}")
    sections.append(f"  Recommendation: {cba['recommendation'][:150]}")
    sections.append("")
    sections.append("FUTURE DIRECTIONS")
    sections.append("-----------------")
    for direction in why.future_directions()[:4]:
        sections.append(f"  - {direction[:100]}")

    result = "\n".join(sections)
    _LOGGER.info("Generated motivation summary (%d chars).", len(result))
    return result
