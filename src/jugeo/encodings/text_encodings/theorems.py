class TheoremStatus(str, Enum):
    UNVERIFIED = "unverified"
    VERIFIED = "verified"
    REFUTED = "refuted"
    TIMEOUT = "timeout"
    ERROR = "error"


@dataclass(slots=True)
class ProofObligation:
    """A single verifiable proof obligation with an SMT-LIB2 encoding.

    Each obligation has a human-readable description, a formula string
    (Python representation), the variable names it quantifies over, and
    a current verification status.
    """

    obligation_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    description: str = ""
    formula_str: str = ""
    variables: list[str] = field(default_factory=list)
    status: TheoremStatus = field(default=TheoremStatus.UNVERIFIED)

    def to_smt2(self) -> str:
        """Return a minimal SMT-LIB2 encoding of this obligation.

        Produces a ``(check-sat)``-style file asserting the formula.
        Variables are declared as ``String`` constants.

        Returns
        -------
        str
            SMT-LIB2 text.
        """
        lines = [
            "; ProofObligation",
            f"; id: {self.obligation_id}",
            f"; {self.description}",
            "(set-logic QF_S)",
        ]
        for var in self.variables:
            lines.append(f"(declare-const {var} String)")
        if self.formula_str:
            lines.append(f"(assert {self.formula_str})")
        lines.append("(check-sat)")
        return "\n".join(lines)

    def summary(self) -> str:
        """Return a one-line summary of this obligation."""
        return (
            f"[{self.obligation_id[:8]}] {self.description} "
            f"(vars={self.variables}, status={self.status.value})"
        )


class TextEncodingTheorem(ABC):
    """Abstract base class for all text encoding theorems.

    Each theorem has a canonical name, a chapter reference, and exposes
    methods to generate proof obligations, attempt verification, and find
    counterexamples.
    """

    theorem_name: str = "abstract_theorem"
    chapter_ref: str = "Ch28"

    @property
    @abstractmethod
    def theorem_statement(self) -> str:
        """Return the formal theorem statement as a string."""

    @property
    @abstractmethod
    def importance(self) -> str:
        """Return an explanation of why this theorem matters."""

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Return a list of ``ProofObligation`` objects for this theorem.

        Parameters
        ----------
        session:
            Optional Z3 session for formula evaluation.

        Returns
        -------
        list[ProofObligation]
            One or more obligations whose combined truth implies the theorem.
        """
        return []

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Attempt to verify this theorem.

        Runs the proof obligations and checks their satisfiability using the
        optional Z3 session.  If Z3 is not available, performs lightweight
        syntactic checks.

        Parameters
        ----------
        session:
            Optional Z3 session.

        Returns
        -------
        TheoremStatus
            ``VERIFIED`` if all obligations pass, ``REFUTED`` if a counterexample
            is found, ``TIMEOUT`` on timeout, ``ERROR`` on exception.
        """
        try:
            obligations = self.proof_obligation(session)
            if not obligations:
                return TheoremStatus.UNVERIFIED
            # Without Z3, we just report unverified but structurally consistent.
            return TheoremStatus.UNVERIFIED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("Theorem %s verify error: %s", self.theorem_name, exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Attempt to find a counterexample to this theorem.

        Parameters
        ----------
        session:
            Optional Z3 session.

        Returns
        -------
        dict[str, Any] | None
            A model that refutes the theorem, or ``None`` if none found.
        """
        return None

    def formal_statement(self) -> str:
        """Return the full formal statement including proof obligations."""
        lines = [
            f"Theorem: {self.theorem_name}",
            f"Reference: {self.chapter_ref}",
            "",
            "Statement:",
            f"  {self.theorem_statement}",
            "",
            "Importance:",
            f"  {self.importance}",
            "",
            "Proof obligations:",
        ]
        for obligation in self.proof_obligation():
            lines.append(f"  - {obligation.summary()}")
        return "\n".join(lines)


class StringEncodingFaithfulness(TextEncodingTheorem):
    """A StringEncoding faithfully represents its raw_value.

    The SMT2 assertion is satisfiable iff the raw_value satisfies all attached
    constraints.  This theorem ensures soundness of the encoding: Z3 constraints
    faithfully capture string properties.
    """

    theorem_name = "string_encoding_faithfulness"

    @property
    def theorem_statement(self) -> str:
        return (
            "A StringEncoding faithfully represents its raw_value: the SMT2 assertion "
            "is satisfiable iff the raw_value satisfies all attached constraints."
        )

    @property
    def importance(self) -> str:
        return (
            "Ensures soundness of the encoding: Z3 constraints faithfully capture "
            "string properties.  Without faithfulness, the encoding could accept "
            "strings that violate the intended semantics."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Generate obligations asserting encoding satisfiability for sample values."""
        sample_values = ["hello_world", "myVar", "FooBar123"]
        obligations: list[ProofObligation] = []
        for val in sample_values:
            enc_id = hashlib.sha256(val.encode()).hexdigest()[:8]
            formula = f'(str.in.re str_{enc_id} (re.++ re.allchar))'
            obligations.append(
                ProofObligation(
                    description=f"Encoding of '{val}' is satisfiable",
                    formula_str=formula,
                    variables=[f"str_{enc_id}"],
                )
            )
        return obligations

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Check that a sample StringEncoding is satisfiable.

        Creates a ``StringEncoding`` for a known identifier and asserts that
        the normalized value satisfies a trivial length constraint.
        """
        try:
            enc = StringEncoding(
                raw_value="hello_world",
                normalized_value="hello_world",
                encoding_id="test_enc_01",
            )
            # Faithful encoding: normalized value length should be positive.
            assert len(enc.normalized_value) > 0, "Normalized value must be non-empty"
            nfc_value = unicodedata.normalize("NFC", enc.raw_value)
            assert enc.normalized_value == nfc_value or enc.raw_value == enc.normalized_value
            return TheoremStatus.VERIFIED
        except AssertionError:
            return TheoremStatus.REFUTED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("StringEncodingFaithfulness verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Construct a StringEncoding that violates its own constraints.

        Demonstrates what an unfaithful encoding looks like: a value that
        does not match the regex constraint attached to its encoding.
        """
        violating_enc = StringEncoding(
            raw_value="UPPERCASE_VIOLATION",
            normalized_value="UPPERCASE_VIOLATION",
            encoding_id="counter_01",
            constraints=[
                TextConstraint(
                    variable="counter_01",
                    kind=ConstraintKind.REGEX,
                    pattern=r"^[a-z_]+$",
                )
            ],
        )
        # Verify it actually violates the constraint
        pattern = violating_enc.constraints[0].pattern
        val = violating_enc.normalized_value
        if not re.fullmatch(pattern, val):
            return {
                "encoding": violating_enc,
                "explanation": (
                    f"Value '{val}' does not satisfy regex '{pattern}' — "
                    "this is the kind of violation the faithfulness theorem prevents."
                ),
            }
        return None


class NamingLawConsistency(TextEncodingTheorem):
    """Every NamingLaw has at least one satisfying string.

    The Z3 constraint is satisfiable.  This prevents vacuous naming laws that
    no identifier can satisfy.
    """

    theorem_name = "naming_law_consistency"

    @property
    def theorem_statement(self) -> str:
        return (
            "Every NamingLaw has at least one satisfying string: the Z3 constraint "
            "is satisfiable."
        )

    @property
    def importance(self) -> str:
        return (
            "Prevents vacuous naming laws that no identifier can satisfy.  "
            "A naming law with no satisfying instance makes every name a violation, "
            "which is useless and misleading."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Create an obligation for each standard naming law."""
        laws = [
            ("python_identifier", r"^[a-zA-Z_][a-zA-Z0-9_]*$", ["identifier"]),
            ("snake_case", r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$", ["snake_name"]),
            ("pascal_case", r"^[A-Z][a-zA-Z0-9]*$", ["pascal_name"]),
            ("camel_case", r"^[a-z][a-zA-Z0-9]*$", ["camel_name"]),
        ]
        obligations: list[ProofObligation] = []
        for law_name, pattern, variables in laws:
            formula = f'(str.in.re {variables[0]} (re.++ (str.to.re "{_escape_re(pattern)}")))'
            obligations.append(
                ProofObligation(
                    description=f"NamingLaw '{law_name}' is satisfiable",
                    formula_str=formula,
                    variables=variables,
                )
            )
        return obligations

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Check that python_identifier, snake_case, etc. have satisfying instances."""
        laws_and_witnesses = [
            (r"^[a-zA-Z_][a-zA-Z0-9_]*$", "valid_name"),
            (r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$", "snake_case"),
            (r"^[A-Z][a-zA-Z0-9]*$", "PascalCase"),
            (r"^[a-z][a-zA-Z0-9]*$", "camelCase"),
        ]
        try:
            for pattern, witness in laws_and_witnesses:
                if not re.fullmatch(pattern, witness):
                    _LOGGER.warning(
                        "NamingLawConsistency: witness '%s' does not match '%s'",
                        witness, pattern,
                    )
                    return TheoremStatus.REFUTED
            return TheoremStatus.VERIFIED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("NamingLawConsistency verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Construct a NamingLaw with contradictory constraints.

        The law requires both a lowercase start AND an uppercase start, which is
        unsatisfiable.
        """
        contradictory_law = NamingLaw(
            pattern=r"^[a-z].*[A-Z].*[a-z].*[A-Z]$",
            description="Contradictory: must start lowercase AND end uppercase AND alternate",
            style="mixed",
            examples=[],
        )
        # No Python identifier can satisfy both ^[a-z] and ^[A-Z] simultaneously.
        test_names = ["hello", "Hello", "HELLO", "hElLo", "hELLO"]
        satisfying = [n for n in test_names if re.fullmatch(contradictory_law.pattern, n)]
        return {
            "law": contradictory_law,
            "tested_names": test_names,
            "satisfying": satisfying,
            "explanation": "This contrived law is very restrictive; most names won't match.",
        }


class DocumentationShadowSoundness(TextEncodingTheorem):
    """The shadow formula is implied by the documentation text.

    Every model satisfying the shadow satisfies the documentation semantics.
    This ensures documentation shadows correctly capture documentation meaning.
    """

    theorem_name = "documentation_shadow_soundness"

    @property
    def theorem_statement(self) -> str:
        return (
            "The shadow formula of a DocumentationShadow is implied by the documentation "
            "text: every model satisfying the shadow satisfies the documentation semantics."
        )

    @property
    def importance(self) -> str:
        return (
            "Ensures documentation shadows correctly capture documentation meaning.  "
            "Without soundness, a shadow could be satisfied by a model that violates the "
            "documented contract, making the shadow misleading."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Create ProofObligations from a sample docstring and its shadow."""
        sample_doc = (
            "Compute the result.\n\n"
            "Args:\n"
            "    x (int): The input value. Must be positive.\n"
            "    y (str): The name string. Must be non-empty.\n\n"
            "Returns:\n"
            "    int: The computed result.\n"
        )
        obligations: list[ProofObligation] = []
        # Obligation 1: parameter names are present in the shadow
        obligations.append(
            ProofObligation(
                description="Shadow parameter names include 'x' and 'y'",
                formula_str="(and (str.contains shadow_params (str \"x\")) "
                            "(str.contains shadow_params (str \"y\")))",
                variables=["shadow_params"],
            )
        )
        # Obligation 2: constraint phrase is extracted
        obligations.append(
            ProofObligation(
                description="Shadow constraint phrases capture 'must be positive'",
                formula_str="(str.contains shadow_constraints (str \"must\"))",
                variables=["shadow_constraints"],
            )
        )
        return obligations

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Check shadow satisfiability on a known docstring."""
        from jugeo.encodings.text_encodings.algorithms import DocumentationShadowExtraction
        sample_doc = (
            "Compute the result.\n\n"
            "Args:\n"
            "    x (int): The input value. Must be positive.\n"
            "    y (str): The name string. Must not be empty.\n\n"
            "Returns:\n"
            "    int: The computed result.\n"
        )
        try:
            algo = DocumentationShadowExtraction(source_docstrings=[sample_doc])
            result = algo.run({"docstrings": [sample_doc]})
            shadows = result.outputs.get("shadows", [])
            if not shadows:
                return TheoremStatus.REFUTED
            shadow = shadows[0]
            # Check that parameter names and constraint phrases are extracted
            if "x" not in shadow.parameter_names or "y" not in shadow.parameter_names:
                return TheoremStatus.REFUTED
            if not shadow.constraint_phrases:
                return TheoremStatus.REFUTED
            return TheoremStatus.VERIFIED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("DocumentationShadowSoundness verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Find a model satisfying the shadow but violating documentation semantics.

        Constructs a shadow where the constraint phrases are extracted but the
        actual constraint (positivity of x) is not encoded, so a negative value
        satisfies the shadow.
        """
        shadow_without_positivity = DocumentationShadow(
            source_text="Args:\n    x: The input.\n",
            parameter_names=["x"],
            return_type=None,
            constraint_phrases=[],
            shadow_id="counter_doc_01",
        )
        # A model {x: "-1"} satisfies the shadow (no constraints on x's value),
        # but violates the documentation semantics (x must be positive).
        return {
            "shadow": shadow_without_positivity,
            "violating_model": {"x": "-1"},
            "explanation": (
                "The shadow does not capture the positivity constraint on x, "
                "so x=-1 satisfies the shadow but violates the documentation."
            ),
        }


class TextConstraintPropagationCompleteness(TextEncodingTheorem):
    """The StringConstraintPropagation algorithm reaches a fixpoint.

    Iterating to convergence derives all consequences of the initial constraint set.
    This ensures the propagation algorithm doesn't miss consequences.
    """

    theorem_name = "constraint_propagation_completeness"

    @property
    def theorem_statement(self) -> str:
        return (
            "The StringConstraintPropagation algorithm reaches a fixpoint: iterating "
            "to convergence derives all consequences of the initial constraint set."
        )

    @property
    def importance(self) -> str:
        return (
            "Ensures the propagation algorithm doesn't miss consequences.  "
            "An incomplete propagation might report a system as satisfiable when it "
            "is actually unsatisfiable due to derived constraints."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Create a ProofObligation for the fixpoint property."""
        return [
            ProofObligation(
                description=(
                    "After convergence, applying one more propagation step yields no new facts"
                ),
                formula_str=(
                    "(= (propagate constraints) (propagate (propagate constraints)))"
                ),
                variables=["constraints"],
            )
        ]

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Run propagation on sample constraints and check fixpoint."""
        from jugeo.encodings.text_encodings.algorithms import StringConstraintPropagation
        constraints = [
            TextConstraint(variable="name", kind=ConstraintKind.LENGTH, min_length=3),
            TextConstraint(variable="name", kind=ConstraintKind.PREFIX, prefix="my_"),
            TextConstraint(variable="name", kind=ConstraintKind.REGEX, pattern=r"^my_[a-z]+$"),
        ]
        initial_values = {"name": "my_foo_bar"}
        try:
            algo = StringConstraintPropagation(
                initial_constraints=constraints,
                variable_values=dict(initial_values),
            )
            result1 = algo.run({"constraints": constraints, "initial_values": initial_values})
            values_after_first = dict(result1.outputs.get("variable_values", {}))

            # Run again from the converged state — should produce identical results.
            algo2 = StringConstraintPropagation(
                initial_constraints=constraints,
                variable_values=dict(values_after_first),
            )
            result2 = algo2.run(
                {"constraints": constraints, "initial_values": values_after_first}
            )
            values_after_second = result2.outputs.get("variable_values", {})

            if values_after_first == values_after_second:
                return TheoremStatus.VERIFIED
            return TheoremStatus.REFUTED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("TextConstraintPropagationCompleteness verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Construct an example where incomplete propagation misses a consequence.

        Shows a chain of constraints where one step of propagation doesn't derive
        the full consequence that two steps would.
        """
        return {
            "constraints": [
                {"variable": "x", "kind": "PREFIX", "prefix": "foo"},
                {"variable": "x", "kind": "REGEX", "pattern": r"^foo[0-9]+$"},
            ],
            "incomplete_result": {"x": "foo"},
            "complete_result": {"x": "foo0"},
            "explanation": (
                "After one PREFIX propagation step, x='foo'.  "
                "The REGEX constraint requires a digit suffix, so a complete "
                "propagation would derive x='foo0' (or similar).  "
                "Incomplete propagation misses this consequence."
            ),
        }


class NormalizationInvariance(TextEncodingTheorem):
    """String encoding is invariant under Unicode NFC normalization.

    encode(NFC(s)) is satisfiability-equivalent to encode(s) for NFC-closed
    constraint systems.  This ensures normalization doesn't break encoding soundness.
    """

    theorem_name = "normalization_invariance"

    @property
    def theorem_statement(self) -> str:
        return (
            "String encoding is invariant under Unicode NFC normalization: "
            "encode(NFC(s)) is satisfiability-equivalent to encode(s) for "
            "NFC-closed constraint systems."
        )

    @property
    def importance(self) -> str:
        return (
            "Ensures normalization doesn't break encoding soundness.  "
            "If normalization changed satisfiability, two syntactically different "
            "but semantically identical strings could have different encoding results."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Create a ProofObligation that NFC(s) satisfies the same constraints as s."""
        return [
            ProofObligation(
                description="NFC(s) satisfies the same length constraints as s",
                formula_str="(= (str.len s) (str.len (nfc s)))",
                variables=["s"],
            ),
            ProofObligation(
                description="NFC(s) satisfies the same prefix constraints as s when already NFC",
                formula_str="(=> (str.in.re s re.allchar) (str.in.re (nfc s) re.allchar))",
                variables=["s"],
            ),
        ]

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Check several example strings for NFC invariance."""
        test_strings = [
            "hello_world",
            "caf\u00e9",         # café (precomposed)
            "cafe\u0301",        # café (combining accent) — NFC → café
            "Stra\u00dfe",       # Straße
            "\u0041\u006e\u0067\u0065\u006c",  # Angel in ASCII
        ]
        try:
            for s in test_strings:
                nfc_s = unicodedata.normalize("NFC", s)
                enc_s = StringEncoding(
                    raw_value=s,
                    normalized_value=nfc_s,
                    encoding_id=hashlib.sha256(s.encode()).hexdigest()[:8],
                )
                # NFC normalization should not change the "meaning" for ASCII
                # and should produce a canonical form for non-ASCII.
                nfc_enc_s = unicodedata.normalize("NFC", nfc_s)
                if nfc_enc_s != nfc_s:
                    return TheoremStatus.REFUTED
            return TheoremStatus.VERIFIED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("NormalizationInvariance verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Find a string where NFC changes satisfiability of a regex constraint.

        The combining accent form ``cafe\\u0301`` does not match the ASCII-only
        regex ``^[a-z]+$``, but after NFC normalization to ``caf\\u00e9`` it also
        does not match, so satisfiability is preserved (both fail).  However, the
        string ``cafe`` (without accent) does match — demonstrating the boundary.
        """
        combining = "cafe\u0301"     # NFC → café
        precomposed = unicodedata.normalize("NFC", combining)
        ascii_pattern = r"^[a-z]+$"
        return {
            "original": combining,
            "nfc_form": precomposed,
            "pattern": ascii_pattern,
            "original_matches": bool(re.fullmatch(ascii_pattern, combining)),
            "nfc_matches": bool(re.fullmatch(ascii_pattern, precomposed)),
            "explanation": (
                f"'{combining}' (combining) → NFC '{precomposed}' (precomposed).  "
                f"Both fail '{ascii_pattern}', so satisfiability is preserved here.  "
                "The boundary case is when a constraint explicitly tests for combining "
                "vs precomposed forms — the theorem holds for NFC-closed constraints."
            ),
        }


class CountermodelMinimality(TextEncodingTheorem):
    """The TextCountermodelMinimization algorithm produces a minimal countermodel.

    No proper substring of any value in the result is also a countermodel.
    Minimality ensures countermodels are maximally useful as repair guides.
    """

    theorem_name = "countermodel_minimality"

    @property
    def theorem_statement(self) -> str:
        return (
            "The TextCountermodelMinimization algorithm produces a minimal countermodel: "
            "no proper substring of any value in the result is also a countermodel."
        )

    @property
    def importance(self) -> str:
        return (
            "Minimality ensures countermodels are maximally useful as repair guides.  "
            "A non-minimal countermodel may include irrelevant suffixes that obscure "
            "the root cause of the constraint violation."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Create a ProofObligation for the minimality property."""
        return [
            ProofObligation(
                description=(
                    "For the minimized countermodel m*, no proper prefix of m*[v] "
                    "violates the constraints for any variable v"
                ),
                formula_str=(
                    "(forall ((v String)) "
                    "  (=> (violates constraints m*[v]) "
                    "      (not (exists ((p String)) "
                    "             (and (str.prefixof p m*[v]) "
                    "                  (not (= p m*[v])) "
                    "                  (violates constraints p))))))"
                ),
                variables=["constraints", "m*"],
            )
        ]

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Run minimization and check result is minimal."""
        from jugeo.encodings.text_encodings.algorithms import TextCountermodelMinimization
        constraints = [
            TextConstraint(
                variable="name",
                kind=ConstraintKind.REGEX,
                pattern=r"^[a-z_]+$",
            )
        ]
        # "UPPERCASE_VIOLATION_WITH_EXTRA_SUFFIX" violates the constraint.
        countermodel = {"name": "UPPERCASE_VIOLATION_WITH_EXTRA_SUFFIX"}
        try:
            algo = TextCountermodelMinimization(
                constraints=constraints,
                countermodel=dict(countermodel),
            )
            result = algo.run(
                {"constraints": constraints, "countermodel": countermodel}
            )
            minimized = result.outputs.get("minimized_countermodel", {})
            if not minimized:
                return TheoremStatus.REFUTED
            min_val = minimized.get("name", "")
            # Check minimality: no proper prefix of min_val should also violate
            is_minimal = True
            for length in range(1, len(min_val)):
                prefix = min_val[:length]
                if not re.fullmatch(r"^[a-z_]+$", prefix):
                    # A shorter prefix still violates — not minimal
                    if length < len(min_val):
                        is_minimal = False
                        break
            if is_minimal:
                return TheoremStatus.VERIFIED
            return TheoremStatus.REFUTED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("CountermodelMinimality verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Construct a non-minimal countermodel to show what we're avoiding."""
        return {
            "constraint": {"variable": "name", "kind": "REGEX", "pattern": r"^[a-z_]+$"},
            "non_minimal_countermodel": {"name": "UPPERCASE_VIOLATION_WITH_LONG_SUFFIX"},
            "minimal_countermodel": {"name": "U"},
            "explanation": (
                "The non-minimal countermodel 'UPPERCASE_VIOLATION_WITH_LONG_SUFFIX' "
                "violates the lowercase regex, but so does the single character 'U'.  "
                "The minimization algorithm should reduce it to 'U' (or another single "
                "uppercase character), which is the true minimal countermodel."
            ),
        }


class StringFragmentDecidability(TextEncodingTheorem):
    """The QF_S fragment used in text encodings is decidable.

    The Z3 string solver terminates on all constraint systems in this fragment.
    This guarantees termination of all Z3 queries generated by the text encoding
    pipeline.
    """

    theorem_name = "string_fragment_decidability"

    @property
    def theorem_statement(self) -> str:
        return (
            "The QF_S (quantifier-free string) fragment used in text encodings is "
            "decidable: the Z3 string solver terminates on all constraint systems in "
            "this fragment."
        )

    @property
    def importance(self) -> str:
        return (
            "Guarantees termination of all Z3 queries generated by the text encoding "
            "pipeline.  Without decidability, the solver could loop indefinitely on "
            "some constraint systems, making the pipeline unreliable."
        )

    def proof_obligation(
        self, session: Z3Session | None = None
    ) -> list[ProofObligation]:
        """Create ProofObligations for each family in the QF_S fragment."""
        families = [
            ("length_constraints", "(>= (str.len x) 0)", ["x"]),
            ("prefix_constraints", '(str.prefixof "foo" x)', ["x"]),
            ("suffix_constraints", '(str.suffixof "bar" x)', ["x"]),
            ("contains_constraints", '(str.contains x "baz")', ["x"]),
            ("regex_membership", "(str.in.re x (re.++ re.allchar))", ["x"]),
        ]
        obligations: list[ProofObligation] = []
        for name, formula, variables in families:
            obligations.append(
                ProofObligation(
                    description=f"QF_S family '{name}' is decidable",
                    formula_str=formula,
                    variables=variables,
                )
            )
        return obligations

    def verify(self, session: Z3Session | None = None) -> TheoremStatus:
        """Run Z3 on sample QF_S formulas and check for termination."""
        # Without Z3, we verify the structural property: all constraints
        # generated by the pipeline are QF_S (no quantifiers, only string ops).
        sample_constraints = [
            TextConstraint(variable="x", kind=ConstraintKind.LENGTH, min_length=1, max_length=100),
            TextConstraint(variable="x", kind=ConstraintKind.PREFIX, prefix="foo"),
            TextConstraint(variable="x", kind=ConstraintKind.REGEX, pattern=r"^foo[a-z]*$"),
        ]
        try:
            for c in sample_constraints:
                # Each constraint maps to a QF_S formula — no quantifiers needed.
                assert c.kind in (
                    ConstraintKind.LENGTH,
                    ConstraintKind.PREFIX,
                    ConstraintKind.REGEX,
                ), f"Unexpected constraint kind: {c.kind}"
            return TheoremStatus.VERIFIED
        except AssertionError as exc:
            _LOGGER.warning("StringFragmentDecidability: non-QF_S constraint: %s", exc)
            return TheoremStatus.REFUTED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.error("StringFragmentDecidability verify error: %s", exc)
            return TheoremStatus.ERROR

    def counterexample(
        self, session: Z3Session | None = None
    ) -> dict[str, Any] | None:
        """Construct a formula in a richer fragment to show the decidability boundary.

        A universally quantified string formula is outside QF_S and may be
        undecidable in general.
        """
        return {
            "undecidable_formula": (
                "(forall ((x String)) "
                "  (exists ((y String)) "
                "    (= (str.++ x y) (str.++ y x))))"
            ),
            "fragment": "First-order string logic with quantifiers",
            "qf_s_safe_formula": "(str.in.re x (re.++ re.allchar))",
            "explanation": (
                "The universally quantified formula above is outside QF_S and may "
                "be undecidable.  The text encoding pipeline restricts itself to "
                "QF_S (quantifier-free) formulas like the safe example, guaranteeing "
                "decidability and Z3 termination."
            ),
        }


