class TheoremSuite:
    """Runs all seven text encoding theorems and aggregates results.

    Provides a convenient interface for batch verification and reporting.
    """

    def all_theorems(self) -> list[TextEncodingTheorem]:
        """Return instances of all 7 concrete theorem classes.

        Returns
        -------
        list[TextEncodingTheorem]
            One instance per theorem, in canonical order.
        """
        return [
            StringEncodingFaithfulness(),
            NamingLawConsistency(),
            DocumentationShadowSoundness(),
            TextConstraintPropagationCompleteness(),
            NormalizationInvariance(),
            CountermodelMinimality(),
            StringFragmentDecidability(),
        ]

    def verify_all(
        self, session: Z3Session | None = None
    ) -> dict[str, TheoremStatus]:
        """Verify all theorems and return a status mapping.

        Parameters
        ----------
        session:
            Optional Z3 session to use for verification.

        Returns
        -------
        dict[str, TheoremStatus]
            ``{theorem_name: status}`` for each theorem.
        """
        results: dict[str, TheoremStatus] = {}
        for theorem in self.all_theorems():
            _LOGGER.info("TheoremSuite: verifying %s", theorem.theorem_name)
            status = theorem.verify(session)
            results[theorem.theorem_name] = status
            _LOGGER.info(
                "TheoremSuite: %s → %s", theorem.theorem_name, status.value
            )
        return results

    def report(self, results: dict[str, TheoremStatus]) -> str:
        """Generate a human-readable verification report.

        Parameters
        ----------
        results:
            Mapping from theorem name to status, as returned by
            :meth:`verify_all`.

        Returns
        -------
        str
            Multi-line report text.
        """
        lines = [
            "=" * 60,
            "TextEncoding Theorem Suite Report",
            f"Theorems: {len(results)}",
            "=" * 60,
        ]
        status_counts: dict[str, int] = defaultdict(int)
        for name, status in results.items():
            lines.append(f"  [{status.value:>10}] {name}")
            status_counts[status.value] += 1
        lines.append("")
        lines.append("Summary:")
        for status_val, count in sorted(status_counts.items()):
            lines.append(f"  {status_val}: {count}")
        lines.append("=" * 60)
        return "\n".join(lines)

    def find_failed_theorems(
        self, results: dict[str, TheoremStatus]
    ) -> list[str]:
        """Return the names of theorems that did not verify.

        A theorem "failed" if its status is ``REFUTED``, ``TIMEOUT``, or
        ``ERROR``.

        Parameters
        ----------
        results:
            Mapping from theorem name to status.

        Returns
        -------
        list[str]
            Sorted list of theorem names that failed.
        """
        failed_statuses = {TheoremStatus.REFUTED, TheoremStatus.TIMEOUT, TheoremStatus.ERROR}
        return sorted(name for name, status in results.items() if status in failed_statuses)

    def summary(self) -> str:
        """Return a one-line summary of the theorem suite."""
        theorems = self.all_theorems()
        return (
            f"TheoremSuite: {len(theorems)} theorems across {THEOREM_COUNT} "
            f"categories from {theorems[0].chapter_ref}"
        )


