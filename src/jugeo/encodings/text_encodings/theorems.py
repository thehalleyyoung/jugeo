def get_theorem(name: str) -> TextEncodingTheorem:
    """Look up and instantiate a theorem by name.

    Parameters
    ----------
    name:
        The ``theorem_name`` of the desired theorem class.

    Returns
    -------
    TextEncodingTheorem
        A fresh instance of the theorem.

    Raises
    ------
    KeyError
        If no theorem with *name* is registered.
    """
    if name not in THEOREM_REGISTRY:
        raise KeyError(
            f"No theorem registered under name '{name}'. "
            f"Available: {sorted(THEOREM_REGISTRY)}"
        )
    return THEOREM_REGISTRY[name]()


def verify_theorem(
    name: str, session: Z3Session | None = None
) -> TheoremStatus:
    """Verify the named theorem.

    Parameters
    ----------
    name:
        The ``theorem_name`` of the theorem to verify.
    session:
        Optional Z3 session.

    Returns
    -------
    TheoremStatus
        Verification result.
    """
    theorem = get_theorem(name)
    return theorem.verify(session)


def run_all_theorems(
    session: Z3Session | None = None,
) -> dict[str, TheoremStatus]:
    """Run and verify all theorems in the registry.

    Parameters
    ----------
    session:
        Optional Z3 session to use for all verifications.

    Returns
    -------
    dict[str, TheoremStatus]
        ``{theorem_name: status}`` for every registered theorem.
    """
    suite = TheoremSuite()
    return suite.verify_all(session)


