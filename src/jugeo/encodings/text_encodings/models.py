class ConstraintKind(str, Enum):
    """
    Categories of string constraints recognised by the text_encodings models.

    Values are string-valued so they can be used directly as SMT2 sort names
    or log tags.

    Attributes:
        LENGTH: A constraint on the length of a string.
        PREFIX: A constraint requiring a specific prefix.
        SUFFIX: A constraint requiring a specific suffix.
        REGEX: A regular-expression membership constraint.
        CONTAINS: A substring containment constraint.
        EXCLUDES: A substring exclusion constraint.
        FORMAT: A structural format constraint (e.g. UUID, semver).
        SEMANTIC: A high-level semantic invariant.
    """

    LENGTH = "length"
    PREFIX = "prefix"
    SUFFIX = "suffix"
    REGEX = "regex"
    CONTAINS = "contains"
    EXCLUDES = "excludes"
    FORMAT = "format"
    SEMANTIC = "semantic"


class ConstraintStrength(Enum):
    """
    Strength of a constraint in the Z3 encoding.

    Attributes:
        HARD: Must be satisfied; the solver will report UNSAT if violated.
        SOFT: Optimisation objective; may be violated at a cost.
        INVARIANT: System-wide invariant that holds across all models.
    """

    HARD = auto()
    SOFT = auto()
    INVARIANT = auto()


