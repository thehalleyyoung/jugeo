@dataclass(slots=True)
class DocumentationShadow:
    """
    A ``DocumentationShadow`` extracts formal string constraints from natural-language
    documentation and builds a corresponding SMT2 formula (the "shadow").

    The shadow can then be verified with Z3, revealing under-specification or
    contradictions between the documentation and the actual code constraints.

    Attributes:
        doc_text: The raw documentation string to analyse.
        extracted_constraints: Constraints mined from doc_text.
        string_vars: Named :class:`SymbolicText` variables mentioned in the docs.
        coverage_map: Tracks which constraints have been verified.
        shadow_formula: The compiled SMT2 formula string.

    Example::

        shadow = DocumentationShadow(doc_text="The username must start with a letter.")
        shadow.extract_constraints()
        print(shadow.build_shadow())
    """

    doc_text: str
    extracted_constraints: list[str] = field(default_factory=list)
    string_vars: dict[str, SymbolicText] = field(default_factory=dict)
    coverage_map: dict[str, bool] = field(default_factory=dict)
    shadow_formula: str = ""

    # ------------------------------------------------------------------
    # Extraction
    # ------------------------------------------------------------------

    def extract_constraints(self) -> list[str]:
        """
        Parse :attr:`doc_text` and extract constraint patterns.

        Looks for:
        - Sentences containing "must", "should", "required", "forbidden",
          "must not", "shall", "cannot".
        - Backtick-quoted parameter names followed by length/type hints.
        - Explicit regex-like patterns in the text.

        Returns:
            The updated :attr:`extracted_constraints` list.

        Example::

            shadow.extract_constraints()
            print(shadow.extracted_constraints)
        """
        self.extracted_constraints.clear()

        # Split into sentences (naive)
        sentences = re.split(r"[.!?]\s+", self.doc_text)
        obligation_words = re.compile(
            r"\b(must|should|required|forbidden|shall|cannot|must not|"
            r"needs to|has to|is not allowed)\b",
            re.IGNORECASE,
        )
        backtick_param = re.compile(r"`([^`]+)`")
        length_hint = re.compile(
            r"\b(at (most|least)|between|up to|minimum|maximum)\s+(\d+)\b",
            re.IGNORECASE,
        )

        for sentence in sentences:
            sentence = sentence.strip()
            if not sentence:
                continue

            if obligation_words.search(sentence):
                # Extract backtick-quoted names
                params = backtick_param.findall(sentence)
                length_m = length_hint.search(sentence)

                if params:
                    for param in params:
                        if length_m:
                            qualifier = length_m.group(1).lower()
                            num = int(length_m.group(3))
                            if "most" in qualifier or "maximum" in qualifier:
                                self.extracted_constraints.append(
                                    f"(<= ({_SMT2_STR_LEN} {param}) {num})"
                                )
                            elif "least" in qualifier or "minimum" in qualifier:
                                self.extracted_constraints.append(
                                    f"(>= ({_SMT2_STR_LEN} {param}) {num})"
                                )
                        else:
                            # Generic obligation — record as free-text annotation
                            safe = sentence.replace('"', "'")[:80]
                            self.extracted_constraints.append(
                                f"; obligation on {param!r}: {safe}"
                            )
                else:
                    safe = sentence.replace('"', "'")[:80]
                    self.extracted_constraints.append(f"; {safe}")

            # Also look for explicit pattern markers like "matches <pattern>"
            pattern_m = re.search(r"matches\s+`?([^\s`]+)`?", sentence, re.IGNORECASE)
            if pattern_m:
                raw_pattern = pattern_m.group(1)
                # Find the closest backtick-quoted variable name
                var_candidates = backtick_param.findall(sentence)
                var = var_candidates[0] if var_candidates else _fresh_var_name("doc")
                escaped = raw_pattern.replace("\\", "\\\\").replace('"', '\\"')
                self.extracted_constraints.append(
                    f'({_SMT2_STR_IN_RE} {var} (re.from_str "{escaped}"))'
                )

        _logger.debug(
            "Extracted %d constraints from documentation shadow",
            len(self.extracted_constraints),
        )
        return list(self.extracted_constraints)

    def add_string_var(self, name: str, var: SymbolicText) -> None:
        """
        Register a symbolic text variable with the shadow.

        Args:
            name: The variable name key.
            var: The :class:`SymbolicText` instance.

        Example::

            shadow.add_string_var("username", SymbolicText("username"))
        """
        self.string_vars[name] = var
        self.coverage_map[name] = False
        _logger.debug("Registered string var %r in shadow", name)

    def build_shadow(self) -> str:
        """
        Build the shadow formula from extracted constraints and registered
        string variables.

        Updates :attr:`shadow_formula` and returns it.

        Returns:
            The compiled SMT2 formula string.

        Example::

            formula = shadow.build_shadow()
            print(formula)
        """
        lines: list[str] = [_SMT2_PREAMBLE]

        # Declare all registered variables
        for name, var in self.string_vars.items():
            lines.append(_smt2_declare_const(name, var.sort_name))
            min_l, max_l = var.length_bounds
            lines.append(_smt2_assert_length(name, min_l, max_l))

        # Emit extracted constraints (skip comment-only lines)
        for constraint in self.extracted_constraints:
            stripped = constraint.strip()
            if stripped.startswith(";"):
                lines.append(stripped)
            elif stripped.startswith("("):
                lines.append(f"(assert {stripped})")
            else:
                lines.append(f"; {stripped}")

        lines.append("(check-sat)")
        self.shadow_formula = "\n".join(lines)
        _logger.debug("Shadow formula built (%d chars)", len(self.shadow_formula))
        return self.shadow_formula

    def verify_shadow(self, session: Any | None = None) -> bool:
        """
        Attempt to verify the shadow formula using Z3 (or heuristically).

        If no session is provided, performs a syntactic check: the formula is
        considered satisfiable if no trivially false assertions are present.

        Args:
            session: Optional Z3Session.  Not used in heuristic mode.

        Returns:
            True if verification passes; False otherwise.

        Example::

            ok = shadow.verify_shadow()
        """
        if not self.shadow_formula:
            self.build_shadow()

        # Heuristic: check for contradictory length bounds
        len_ge = re.findall(r"\(>= \(str\.len \S+\) (\d+)\)", self.shadow_formula)
        len_le = re.findall(r"\(<= \(str\.len \S+\) (\d+)\)", self.shadow_formula)

        if len_ge and len_le:
            min_bound = max(int(x) for x in len_ge)
            max_bound = min(int(x) for x in len_le)
            if min_bound > max_bound:
                _logger.warning(
                    "Shadow formula has contradictory length bounds: min=%d > max=%d",
                    min_bound,
                    max_bound,
                )
                return False

        _logger.info("Shadow formula passed heuristic verification")
        return True

    def repair_documentation(self, violations: list[str]) -> str:
        """
        Suggest repairs to :attr:`doc_text` based on *violations*.

        Each violation is mapped to a suggested documentation clarification.

        Args:
            violations: A list of violation strings (e.g. from
                :meth:`NamingLaw.violations_of`).

        Returns:
            A suggested revised documentation string.

        Example::

            revised = shadow.repair_documentation(["Length 0 < min_length 1"])
        """
        if not violations:
            return self.doc_text

        lines = [self.doc_text, "", "--- Suggested documentation repairs ---"]
        for v in violations:
            lines.append(f"  NOTE: Constraint violation detected: {v}")
            # Simple repair suggestions
            if "min_length" in v:
                m = re.search(r"min_length (\d+)", v)
                if m:
                    lines.append(
                        f"  SUGGESTION: Clarify that the value must be at least "
                        f"{m.group(1)} characters long."
                    )
            elif "max_length" in v:
                m = re.search(r"max_length (\d+)", v)
                if m:
                    lines.append(
                        f"  SUGGESTION: Clarify that the value must be at most "
                        f"{m.group(1)} characters long."
                    )
            elif "pattern" in v.lower():
                lines.append(
                    "  SUGGESTION: Add an explicit example showing the expected format."
                )
            else:
                lines.append(f"  SUGGESTION: Add documentation addressing: {v}")

        return "\n".join(lines)

    def to_smt2(self) -> str:
        """
        Return the full SMT2 encoding of this shadow.

        If the formula has not yet been built, :meth:`build_shadow` is called
        first.

        Returns:
            The SMT2 formula string.
        """
        if not self.shadow_formula:
            self.build_shadow()
        return self.shadow_formula

    def summary(self) -> str:
        """
        Return a human-readable summary.

        Returns:
            Multi-line summary string.
        """
        return (
            f"DocumentationShadow(\n"
            f"  doc_length   = {len(self.doc_text)} chars,\n"
            f"  constraints  = {len(self.extracted_constraints)},\n"
            f"  string_vars  = {list(self.string_vars.keys())},\n"
            f"  formula_len  = {len(self.shadow_formula)} chars\n"
            f")"
        )


