def _normalize_nfc(text: str) -> str:
    """
    Apply Unicode NFC normalization to *text*.

    NFC (Canonical Decomposition followed by Canonical Composition) is the
    most common normalization form for string comparison in Z3 encodings.

    Args:
        text: The input string to normalize.

    Returns:
        The NFC-normalized form of *text*.

    Example::

        assert _normalize_nfc("caf\\u0065\\u0301") == "caf\\u00e9"
    """
    return unicodedata.normalize("NFC", text)


def _regex_to_z3_constraint(pattern: str, var_name: str) -> str:
    """
    Convert a Python regex *pattern* to an approximate SMT2 ``str.in_re``
    constraint for variable *var_name*.

    The conversion is best-effort; not all Python regex features have direct
    SMT2 equivalents.  The produced constraint is a valid (though potentially
    imprecise) over-approximation.

    Args:
        pattern: A Python ``re``-style regular expression string.
        var_name: The SMT2 variable name to constrain.

    Returns:
        An SMT2 assertion string of the form
        ``(assert (str.in_re <var_name> (re.from_str "<pattern>")))``.

    Example::

        smt = _regex_to_z3_constraint(r"[a-z]+", "x")
        # smt == '(assert (str.in_re x (re.from_str "[a-z]+")))'
    """
    # Escape double-quotes in the pattern for SMT2 string literals
    escaped = pattern.replace("\\", "\\\\").replace('"', '\\"')
    return f'(assert ({_SMT2_STR_IN_RE} {var_name} (re.from_str "{escaped}")))'


def _compute_string_hash(s: str) -> str:
    """
    Compute the SHA-256 hash of *s* encoded as UTF-8.

    Args:
        s: The string to hash.

    Returns:
        Hexadecimal SHA-256 digest string (64 characters).

    Example::

        h = _compute_string_hash("hello")
        assert len(h) == 64
    """
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def _fresh_var_name(prefix: str = "s") -> str:
    """
    Generate a fresh, collision-free SMT2 variable name.

    Uses a UUID4 suffix to ensure uniqueness across calls within a session.

    Args:
        prefix: Optional prefix for the variable name.  Defaults to ``"s"``.

    Returns:
        A string of the form ``"<prefix>_<uuid4_hex[:8]>"``.

    Example::

        name = _fresh_var_name("x")
        assert name.startswith("x_")
    """
    short_id = uuid.uuid4().hex[:8]
    return f"{prefix}_{short_id}"


def _smt2_declare_const(var_name: str, sort: str = "String") -> str:
    """
    Produce an SMT2 ``(declare-const ...)`` statement.

    Args:
        var_name: The variable name to declare.
        sort: The SMT2 sort.  Defaults to ``"String"``.

    Returns:
        An SMT2 ``(declare-const <var_name> <sort>)`` string.
    """
    return f"(declare-const {var_name} {sort})"


def _smt2_assert_length(var_name: str, min_len: int, max_len: int) -> str:
    """
    Produce SMT2 assertions bounding the length of *var_name*.

    Args:
        var_name: The SMT2 string variable name.
        min_len: Minimum length (inclusive).
        max_len: Maximum length (inclusive).

    Returns:
        Two SMT2 ``(assert ...)`` statements joined by a newline.
    """
    lo = f"(assert (>= ({_SMT2_STR_LEN} {var_name}) {min_len}))"
    hi = f"(assert (<= ({_SMT2_STR_LEN} {var_name}) {max_len}))"
    return f"{lo}\n{hi}"


