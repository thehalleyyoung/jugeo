@dataclass(frozen=True, slots=True)
class NamingLaw:
    """
    A structural naming convention encoded as a Z3 string constraint.

    Instances are immutable.  Each law is defined by a pattern, optional
    forbidden sub-patterns, required affixes, length bounds, and a set of
    logical axioms from theory2.tex.

    Attributes:
        law_name: Human-readable name (e.g. ``"snake_case"``).
        pattern: Primary regex pattern that compliant strings must match.
        forbidden_patterns: Patterns that must NOT appear in compliant strings.
        required_prefixes: At least one of these must be a prefix (if non-empty).
        required_suffixes: At least one of these must be a suffix (if non-empty).
        max_length: Maximum allowed length.
        min_length: Minimum required length.
        axioms: SMT2 axiom strings from the theory.

    Example::

        law = NamingLaw(law_name="snake_case", pattern=r"[a-z][a-z0-9_]*")
        assert law.apply_to_string("good_name")
    """

    law_name: str
    pattern: str
    forbidden_patterns: tuple[str, ...] = field(default_factory=tuple)
    required_prefixes: tuple[str, ...] = field(default_factory=tuple)
    required_suffixes: tuple[str, ...] = field(default_factory=tuple)
    max_length: int = 256
    min_length: int = 1
    axioms: tuple[str, ...] = field(default_factory=tuple)

    def apply_to_string(self, s: str) -> bool:
        """
        Return True if *s* satisfies all constraints of this naming law.

        Args:
            s: The string to test.

        Returns:
            True when *s* passes every check; False on the first violation.

        Example::

            law = NamingLaw("snake_case", r"[a-z][a-z0-9_]*")
            assert law.apply_to_string("my_var")
            assert not law.apply_to_string("MyVar")
        """
        return len(self.check_compliance(s)) == 0

    def check_compliance(self, s: str) -> list[str]:
        """
        Return a list of human-readable violation messages for *s*.

        An empty list means *s* is fully compliant.

        Args:
            s: The string to check.

        Returns:
            A (possibly empty) list of violation description strings.

        Example::

            violations = law.check_compliance("Bad Name")
            if violations:
                print("\\n".join(violations))
        """
        violations: list[str] = []

        # Length checks
        if len(s) < self.min_length:
            violations.append(
                f"Length {len(s)} < min_length {self.min_length}"
            )
        if len(s) > self.max_length:
            violations.append(
                f"Length {len(s)} > max_length {self.max_length}"
            )

        # Pattern check
        try:
            if not re.fullmatch(self.pattern, s):
                violations.append(
                    f"Does not match pattern {self.pattern!r}"
                )
        except re.error as exc:
            violations.append(f"Pattern compile error: {exc}")

        # Forbidden sub-patterns
        for fp in self.forbidden_patterns:
            try:
                if re.search(fp, s):
                    violations.append(f"Contains forbidden pattern {fp!r}")
            except re.error:
                pass

        # Required prefix check (any one suffices)
        if self.required_prefixes:
            if not any(s.startswith(p) for p in self.required_prefixes):
                violations.append(
                    f"Must start with one of {self.required_prefixes}"
                )

        # Required suffix check (any one suffices)
        if self.required_suffixes:
            if not any(s.endswith(sfx) for sfx in self.required_suffixes):
                violations.append(
                    f"Must end with one of {self.required_suffixes}"
                )

        return violations

    def generate_compliant(self, seed: str = "") -> str:
        """
        Generate a string that satisfies this naming law.

        If *seed* is provided and already compliant, it is returned unchanged.
        Otherwise a simple compliant string is constructed heuristically from
        the law's constraints.

        Args:
            seed: An optional candidate string.  Used as-is if compliant.

        Returns:
            A string that passes :meth:`apply_to_string`.

        Example::

            compliant = law.generate_compliant()
            assert law.apply_to_string(compliant)
        """
        if seed and self.apply_to_string(seed):
            return seed

        # Heuristic generation based on law name
        law_defaults: dict[str, str] = {
            "snake_case": "my_variable",
            "camel_case": "MyVariable",
            "pascal_case": "MyClass",
            "kebab_case": "my-value",
            "screaming_snake_case": "MY_CONSTANT",
            "lower_camel_case": "myVariable",
            "upper_camel_case": "MyClass",
            "dot_notation": "com.example.pkg",
            "uuid_format": str(uuid.uuid4()),
            "semver_format": "1.0.0",
            "iso8601_date": "2024-01-01",
            "namespace_qualified": "org.jugeo.text",
            "hex_string": "deadbeef",
            "base64_encoded": "SGVsbG8=",
        }
        candidate = law_defaults.get(self.law_name, "default_value")

        # Apply required prefix if needed
        if self.required_prefixes and not any(
            candidate.startswith(p) for p in self.required_prefixes
        ):
            candidate = self.required_prefixes[0] + candidate

        # Truncate to max_length
        candidate = candidate[: self.max_length]

        _logger.debug("Generated compliant string %r for law %r", candidate, self.law_name)
        return candidate

    def to_regex(self) -> re.Pattern[str]:
        """
        Compile the primary pattern to a :class:`re.Pattern`.

        Returns:
            Compiled regex pattern.

        Raises:
            re.error: If the pattern is invalid.
        """
        return re.compile(self.pattern)

    def to_z3_constraint(self, var_name: str) -> str:
        """
        Return the SMT2 constraint string for variable *var_name*.

        Produces a conjunction of the pattern constraint, length bounds, and
        any forbidden-pattern exclusions.

        Args:
            var_name: The SMT2 variable name to constrain.

        Returns:
            An SMT2 ``(assert ...)`` string.

        Example::

            smt = law.to_z3_constraint("username")
        """
        parts: list[str] = []

        # Pattern
        escaped = self.pattern.replace("\\", "\\\\").replace('"', '\\"')
        parts.append(f'({_SMT2_STR_IN_RE} {var_name} (re.from_str "{escaped}"))')

        # Length bounds
        parts.append(f"(>= ({_SMT2_STR_LEN} {var_name}) {self.min_length})")
        parts.append(f"(<= ({_SMT2_STR_LEN} {var_name}) {self.max_length})")

        # Forbidden patterns (negated containment, simplified)
        for fp in self.forbidden_patterns:
            escaped_fp = fp.replace("\\", "\\\\").replace('"', '\\"')
            parts.append(
                f'(not ({_SMT2_STR_IN_RE} {var_name} (re.from_str "{escaped_fp}")))'
            )

        if len(parts) == 1:
            return f"(assert {parts[0]})"
        conjunction = " ".join(parts)
        return f"(assert (and {conjunction}))"

    def violations_of(self, s: str) -> list[str]:
        """
        Return detailed violation messages for every constraint *s* fails.

        This is an alias for :meth:`check_compliance` with richer formatting.

        Args:
            s: The string to check.

        Returns:
            List of detailed violation strings.
        """
        raw = self.check_compliance(s)
        return [f"[NamingLaw {self.law_name!r}] {msg}" for msg in raw]

    def summary(self) -> str:
        """
        Return a one-line human-readable summary of this law.

        Returns:
            Summary string.
        """
        return (
            f"NamingLaw({self.law_name!r}, pattern={self.pattern!r}, "
            f"len=[{self.min_length},{self.max_length}], "
            f"forbidden={len(self.forbidden_patterns)}, "
            f"axioms={len(self.axioms)})"
        )


