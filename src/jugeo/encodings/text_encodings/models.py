@dataclass(frozen=True, slots=True)
class StringEncoding:
    """
    Immutable record associating a raw string value with its Z3 encoding.

    Because this dataclass is frozen, all mutation returns a new instance.
    This allows safe sharing between solver sessions.

    Attributes:
        raw_value: The concrete string value being encoded.
        z3_var_name: The SMT2 variable name used to represent this string.
        length_constraint: Optional explicit length constraint expression.
        prefix_constraints: Tuple of required prefix strings.
        suffix_constraints: Tuple of required suffix strings.
        regex_constraints: Tuple of regex patterns the string must match.
        provenance: Free-form provenance tag for debugging.

    Example::

        enc = StringEncoding(raw_value="hello", z3_var_name="s0")
        print(enc.to_smt2())
    """

    raw_value: str
    z3_var_name: str
    length_constraint: str | None = None
    prefix_constraints: tuple[str, ...] = field(default_factory=tuple)
    suffix_constraints: tuple[str, ...] = field(default_factory=tuple)
    regex_constraints: tuple[str, ...] = field(default_factory=tuple)
    provenance: str = ""

    # ------------------------------------------------------------------
    # Z3 / SMT2 generation
    # ------------------------------------------------------------------

    def to_z3_assertion(self) -> str:
        """
        Build a single SMT2 assertion string combining all constraints.

        The result is a conjunction of length, prefix, suffix, and regex
        constraints expressed in the SMT2 string theory.

        Returns:
            An SMT2 ``(assert (and ...))`` string, or ``""`` if no constraints
            are defined.

        Example::

            enc = StringEncoding("foo", "s", prefix_constraints=("fo",))
            print(enc.to_z3_assertion())
        """
        parts: list[str] = []

        if self.length_constraint:
            parts.append(self.length_constraint)

        for pfx in self.prefix_constraints:
            escaped = pfx.replace('"', '\\"')
            parts.append(f'({_SMT2_STR_PREFIXOF} "{escaped}" {self.z3_var_name})')

        for sfx in self.suffix_constraints:
            escaped = sfx.replace('"', '\\"')
            parts.append(f'({_SMT2_STR_SUFFIXOF} "{escaped}" {self.z3_var_name})')

        for rgx in self.regex_constraints:
            escaped = rgx.replace("\\", "\\\\").replace('"', '\\"')
            parts.append(
                f'({_SMT2_STR_IN_RE} {self.z3_var_name} (re.from_str "{escaped}"))'
            )

        if not parts:
            return ""
        if len(parts) == 1:
            return f"(assert {parts[0]})"
        conjunction = " ".join(parts)
        return f"(assert (and {conjunction}))"

    def add_constraint(self, kind: ConstraintKind, constraint: str) -> StringEncoding:
        """
        Return a new :class:`StringEncoding` with *constraint* added under *kind*.

        Because this dataclass is frozen, a new instance is constructed.

        Args:
            kind: The :class:`ConstraintKind` category to add the constraint to.
            constraint: The constraint string (pattern, literal, or expression).

        Returns:
            A new :class:`StringEncoding` with the constraint appended.

        Raises:
            ValueError: If *kind* is not supported for direct addition.

        Example::

            enc2 = enc.add_constraint(ConstraintKind.PREFIX, "usr_")
        """
        if kind is ConstraintKind.PREFIX:
            return StringEncoding(
                raw_value=self.raw_value,
                z3_var_name=self.z3_var_name,
                length_constraint=self.length_constraint,
                prefix_constraints=self.prefix_constraints + (constraint,),
                suffix_constraints=self.suffix_constraints,
                regex_constraints=self.regex_constraints,
                provenance=self.provenance,
            )
        if kind is ConstraintKind.SUFFIX:
            return StringEncoding(
                raw_value=self.raw_value,
                z3_var_name=self.z3_var_name,
                length_constraint=self.length_constraint,
                prefix_constraints=self.prefix_constraints,
                suffix_constraints=self.suffix_constraints + (constraint,),
                regex_constraints=self.regex_constraints,
                provenance=self.provenance,
            )
        if kind is ConstraintKind.REGEX:
            return StringEncoding(
                raw_value=self.raw_value,
                z3_var_name=self.z3_var_name,
                length_constraint=self.length_constraint,
                prefix_constraints=self.prefix_constraints,
                suffix_constraints=self.suffix_constraints,
                regex_constraints=self.regex_constraints + (constraint,),
                provenance=self.provenance,
            )
        if kind is ConstraintKind.LENGTH:
            return StringEncoding(
                raw_value=self.raw_value,
                z3_var_name=self.z3_var_name,
                length_constraint=constraint,
                prefix_constraints=self.prefix_constraints,
                suffix_constraints=self.suffix_constraints,
                regex_constraints=self.regex_constraints,
                provenance=self.provenance,
            )
        raise ValueError(f"add_constraint does not support kind={kind!r}")

    def verify_satisfiable(self, session: Any | None = None) -> bool:
        """
        Check whether the constraints on this encoding are satisfiable.

        If *session* is a live :class:`Z3Session` (or compatible object), it is
        used for the check.  Otherwise a heuristic check is performed by testing
        the raw_value against all regex constraints and prefix/suffix literals.

        Args:
            session: An optional Z3Session to use.  If None, heuristic check.

        Returns:
            True if the constraints appear satisfiable; False otherwise.

        Example::

            enc = StringEncoding("hello", "s", regex_constraints=(r"h.*",))
            assert enc.verify_satisfiable()
        """
        # Heuristic: test raw_value against all constraints
        s = self.raw_value

        for pfx in self.prefix_constraints:
            if not s.startswith(pfx):
                _logger.debug(
                    "verify_satisfiable: raw_value %r does not start with %r", s, pfx
                )
                return False

        for sfx in self.suffix_constraints:
            if not s.endswith(sfx):
                _logger.debug(
                    "verify_satisfiable: raw_value %r does not end with %r", s, sfx
                )
                return False

        for rgx in self.regex_constraints:
            try:
                if not re.fullmatch(rgx, s):
                    _logger.debug(
                        "verify_satisfiable: raw_value %r does not match regex %r", s, rgx
                    )
                    return False
            except re.error as exc:
                _logger.warning("Invalid regex %r: %s", rgx, exc)

        return True

    def project_prefix(self, length: int) -> str:
        """
        Return the first *length* characters of raw_value.

        Args:
            length: Number of characters to return.

        Returns:
            Prefix string of at most *length* characters.
        """
        return self.raw_value[:length]

    def project_suffix(self, length: int) -> str:
        """
        Return the last *length* characters of raw_value.

        Args:
            length: Number of characters to return.

        Returns:
            Suffix string of at most *length* characters.
        """
        return self.raw_value[-length:] if length > 0 else ""

    def to_smt2(self) -> str:
        """
        Produce a complete SMT2 snippet declaring the variable and asserting all
        constraints.

        Returns:
            A multi-line SMT2 string including ``(declare-const ...)`` and any
            ``(assert ...)`` statements.

        Example::

            print(enc.to_smt2())
        """
        lines: list[str] = [
            _smt2_declare_const(self.z3_var_name),
            f'(assert (= {self.z3_var_name} "{self.raw_value.replace(chr(34), chr(92)+chr(34))}"))',
        ]
        assertion = self.to_z3_assertion()
        if assertion:
            lines.append(assertion)
        return "\n".join(lines)

    def summary(self) -> str:
        """
        Return a human-readable one-line summary.

        Returns:
            A summary string describing the variable name, raw value, and
            constraint counts.
        """
        return (
            f"StringEncoding({self.z3_var_name!r}, "
            f"raw={self.raw_value!r}, "
            f"prefixes={len(self.prefix_constraints)}, "
            f"suffixes={len(self.suffix_constraints)}, "
            f"regexes={len(self.regex_constraints)})"
        )


