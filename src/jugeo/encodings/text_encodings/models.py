@dataclass(slots=True)
class SymbolicText:
    """
    A symbolic (unconstrained) string variable with associated constraints.

    Unlike :class:`StringEncoding`, ``SymbolicText`` does not carry a concrete
    raw value — it represents a Z3 string variable with attached invariants.
    Constraints are accumulated incrementally and compiled to SMT2 on demand.

    Attributes:
        variable_name: The SMT2 variable name.
        sort_name: The SMT2 sort (default: ``"String"``).
        naming_law: Optional name of the :class:`NamingLaw` applied.
        character_class_constraints: Regex-style character-class patterns.
        length_bounds: ``(min_length, max_length)`` pair.
        semantic_constraints: High-level semantic assertion strings.

    Example::

        st = SymbolicText("username")
        st.constrain_length(3, 32)
        print(st.to_z3_formula())
    """

    variable_name: str
    sort_name: str = "String"
    naming_law: str | None = None
    character_class_constraints: list[str] = field(default_factory=list)
    length_bounds: tuple[int, int] = (0, 256)
    semantic_constraints: list[str] = field(default_factory=list)

    def add_naming_law(self, law_name: str) -> None:
        """
        Apply a named naming law to this symbolic text variable.

        Sets :attr:`naming_law` and injects corresponding character-class and
        length constraints derived from the law name.

        Args:
            law_name: A name from :data:`STANDARD_NAMING_LAWS`.

        Example::

            st.add_naming_law("snake_case")
        """
        self.naming_law = law_name
        _logger.debug("Applying naming law %r to variable %r", law_name, self.variable_name)

        law_constraints: dict[str, list[str]] = {
            "snake_case": [SNAKE_CASE_PATTERN],
            "camel_case": [CAMEL_CASE_PATTERN],
            "pascal_case": [CAMEL_CASE_PATTERN],
            "kebab_case": [r"[a-z][a-z0-9\-]*"],
            "screaming_snake_case": [r"[A-Z][A-Z0-9_]*"],
            "lower_camel_case": [r"[a-z][a-zA-Z0-9]*"],
            "upper_camel_case": [CAMEL_CASE_PATTERN],
            "dot_notation": [r"[a-z][a-z0-9\.]*"],
            "uuid_format": [
                r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"
            ],
            "semver_format": [r"[0-9]+\.[0-9]+\.[0-9]+"],
            "iso8601_date": [r"[0-9]{4}-[0-9]{2}-[0-9]{2}"],
            "namespace_qualified": [r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+"],
            "hex_string": [r"[0-9a-fA-F]+"],
            "base64_encoded": [r"[A-Za-z0-9+/]+=*"],
        }
        for pattern in law_constraints.get(law_name, []):
            if pattern not in self.character_class_constraints:
                self.character_class_constraints.append(pattern)

    def constrain_length(self, min_len: int, max_len: int) -> None:
        """
        Update the length bounds for this variable.

        Args:
            min_len: New minimum length (inclusive, non-negative).
            max_len: New maximum length (inclusive).

        Raises:
            ValueError: If min_len > max_len or min_len < 0.

        Example::

            st.constrain_length(1, 64)
        """
        if min_len < 0:
            raise ValueError(f"min_len must be non-negative, got {min_len}")
        if min_len > max_len:
            raise ValueError(
                f"min_len ({min_len}) must not exceed max_len ({max_len})"
            )
        self.length_bounds = (min_len, max_len)
        _logger.debug(
            "Length bounds for %r updated to [%d, %d]",
            self.variable_name,
            min_len,
            max_len,
        )

    def constrain_characters(self, char_class: str) -> None:
        """
        Add a character-class constraint (regex pattern) to this variable.

        Args:
            char_class: A regex pattern expressing the allowed character set.

        Example::

            st.constrain_characters(r"[a-zA-Z0-9_]")
        """
        if char_class not in self.character_class_constraints:
            self.character_class_constraints.append(char_class)
            _logger.debug(
                "Added char class constraint %r to %r", char_class, self.variable_name
            )

    def to_z3_formula(self) -> str:
        """
        Compile all constraints to a multi-line SMT2 formula string.

        Returns:
            SMT2 text including ``(declare-const ...)`` and all ``(assert ...)``
            statements derived from the accumulated constraints.

        Example::

            formula = st.to_z3_formula()
            print(formula)
        """
        lines: list[str] = [_smt2_declare_const(self.variable_name, self.sort_name)]
        min_len, max_len = self.length_bounds
        lines.append(_smt2_assert_length(self.variable_name, min_len, max_len))
        for pattern in self.character_class_constraints:
            lines.append(_regex_to_z3_constraint(pattern, self.variable_name))
        for sem in self.semantic_constraints:
            lines.append(f"(assert {sem})")
        return "\n".join(lines)

    def verify_law(self, law: NamingLaw) -> bool:
        """
        Check whether this variable satisfies *law* when the variable name
        itself is used as a test string.

        This is a heuristic check intended for debugging; the variable_name
        is not necessarily the value that the symbolic variable will take at
        solve time.

        Args:
            law: The :class:`NamingLaw` to verify against.

        Returns:
            True if variable_name satisfies the law; False otherwise.
        """
        return law.apply_to_string(self.variable_name)

    def instantiate(self, value: str) -> StringEncoding:
        """
        Create a :class:`StringEncoding` that fixes this variable to *value*.

        All character-class constraints are propagated as regex constraints on
        the new encoding.

        Args:
            value: The concrete string value to assign.

        Returns:
            A :class:`StringEncoding` with raw_value=*value* and the accumulated
            regex constraints.

        Example::

            enc = st.instantiate("my_identifier")
        """
        return StringEncoding(
            raw_value=value,
            z3_var_name=self.variable_name,
            regex_constraints=tuple(self.character_class_constraints),
            provenance=f"instantiated from SymbolicText({self.variable_name!r})",
        )

    def summary(self) -> str:
        """
        Return a human-readable summary of this symbolic text variable.

        Returns:
            A multi-line string describing the variable's constraints.
        """
        law_tag = f", law={self.naming_law!r}" if self.naming_law else ""
        return (
            f"SymbolicText({self.variable_name!r}, sort={self.sort_name!r}{law_tag}, "
            f"length=[{self.length_bounds[0]},{self.length_bounds[1]}], "
            f"char_classes={len(self.character_class_constraints)}, "
            f"semantic={len(self.semantic_constraints)})"
        )


