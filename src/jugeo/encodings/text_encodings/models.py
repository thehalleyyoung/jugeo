@dataclass(slots=True)
class TextConstraint:
    """
    A named, typed string constraint with associated metadata.

    ``TextConstraint`` wraps a single SMT2 formula string together with the list
    of free variables it mentions, its kind, strength, and provenance.

    Attributes:
        constraint_name: Human-readable name for this constraint.
        formula_str: The SMT2 formula (without outer ``(assert ...)``.
        variables: List of SMT2 variable names appearing in the formula.
        kind: :class:`ConstraintKind` classification.
        strength: :class:`ConstraintStrength` classification.
        provenance: Free-form provenance string.

    Example::

        tc = TextConstraint(
            constraint_name="min_len",
            formula_str="(>= (str.len username) 3)",
            variables=["username"],
            kind=ConstraintKind.LENGTH,
        )
        print(tc.to_smt2())
    """

    constraint_name: str
    formula_str: str
    variables: list[str] = field(default_factory=list)
    kind: ConstraintKind = ConstraintKind.FORMAT
    strength: ConstraintStrength = ConstraintStrength.HARD
    provenance: str = ""

    def apply(self, values: dict[str, str]) -> bool:
        """
        Substitute *values* into the formula and evaluate it heuristically.

        Variable names appearing in :attr:`formula_str` are replaced by their
        quoted string literals, and the result is checked for obvious truth /
        falsity using regex matching.  This is a best-effort heuristic.

        Args:
            values: Mapping from variable name to concrete string value.

        Returns:
            True if the substituted formula appears satisfied; False otherwise.

        Example::

            ok = tc.apply({"username": "alice"})
        """
        formula = self.formula_str
        for var, val in values.items():
            escaped_val = val.replace('"', '\\"')
            formula = formula.replace(var, f'"{escaped_val}"')

        # Heuristic evaluation of length constraints
        len_ge_m = re.search(r'\(>=\s+\(str\.len\s+"([^"]*)"\)\s+(\d+)\)', formula)
        if len_ge_m:
            return len(len_ge_m.group(1)) >= int(len_ge_m.group(2))

        len_le_m = re.search(r'\(<=\s+\(str\.len\s+"([^"]*)"\)\s+(\d+)\)', formula)
        if len_le_m:
            return len(len_le_m.group(1)) <= int(len_le_m.group(2))

        # Heuristic evaluation of prefix constraints
        pfx_m = re.search(
            r'\(str\.prefixof\s+"([^"]*)"\s+"([^"]*)"\)', formula
        )
        if pfx_m:
            return pfx_m.group(2).startswith(pfx_m.group(1))

        # Heuristic evaluation of suffix constraints
        sfx_m = re.search(
            r'\(str\.suffixof\s+"([^"]*)"\s+"([^"]*)"\)', formula
        )
        if sfx_m:
            return sfx_m.group(2).endswith(sfx_m.group(1))

        # Default: assume satisfied if no falsity detected
        return True

    def negate(self) -> TextConstraint:
        """
        Return a new :class:`TextConstraint` that is the logical negation of this one.

        Returns:
            A new :class:`TextConstraint` with ``formula_str = "(not <original>)"``.

        Example::

            neg = tc.negate()
            print(neg.formula_str)
        """
        return TextConstraint(
            constraint_name=f"not_{self.constraint_name}",
            formula_str=f"(not {self.formula_str})",
            variables=list(self.variables),
            kind=self.kind,
            strength=self.strength,
            provenance=f"negation of {self.constraint_name!r}",
        )

    def compose_with(self, other: TextConstraint) -> TextConstraint:
        """
        Return a new :class:`TextConstraint` that is the AND-composition of
        this constraint and *other*.

        Variables are merged (deduplicating by name order).

        Args:
            other: Another :class:`TextConstraint` to conjoin.

        Returns:
            A new :class:`TextConstraint` with ``formula_str = "(and <self> <other>)"``.

        Example::

            combined = tc1.compose_with(tc2)
        """
        merged_vars = list(self.variables)
        for v in other.variables:
            if v not in merged_vars:
                merged_vars.append(v)

        return TextConstraint(
            constraint_name=f"{self.constraint_name}_and_{other.constraint_name}",
            formula_str=f"(and {self.formula_str} {other.formula_str})",
            variables=merged_vars,
            kind=self.kind,
            strength=(
                ConstraintStrength.HARD
                if ConstraintStrength.HARD in (self.strength, other.strength)
                else other.strength
            ),
            provenance=(
                f"composed from {self.constraint_name!r} and {other.constraint_name!r}"
            ),
        )

    def check_consistency(self, session: Any | None = None) -> bool:
        """
        Check whether the formula is syntactically and heuristically consistent.

        A formula is considered inconsistent if it contains a trivially false
        expression (e.g. ``(not true)`` or contradictory length bounds).

        Args:
            session: Optional Z3Session (unused in heuristic mode).

        Returns:
            True if the formula appears consistent; False if obviously false.

        Example::

            assert tc.check_consistency()
        """
        if "(not true)" in self.formula_str:
            return False
        if "(= false true)" in self.formula_str:
            return False

        # Look for obviously contradictory (not (= x x)) pattern
        if re.search(r"\(not \(=\s+\S+\s+\1\s*\)\)", self.formula_str):
            return False

        return True

    def to_smt2(self) -> str:
        """
        Return the SMT2 assertion wrapping :attr:`formula_str`.

        Returns:
            ``(assert <formula_str>)``
        """
        return f"(assert {self.formula_str})"

    def explain(self) -> str:
        """
        Return a human-readable explanation of this constraint.

        Returns:
            A multi-line explanation string.

        Example::

            print(tc.explain())
        """
        return (
            f"Constraint : {self.constraint_name!r}\n"
            f"Kind       : {self.kind.value}\n"
            f"Strength   : {self.strength.name}\n"
            f"Variables  : {', '.join(self.variables) or '(none)'}\n"
            f"Formula    : {self.formula_str}\n"
            f"Provenance : {self.provenance or '(none)'}"
        )

    def summary(self) -> str:
        """
        Return a one-line summary.

        Returns:
            A concise summary string.
        """
        return (
            f"TextConstraint({self.constraint_name!r}, "
            f"kind={self.kind.value}, strength={self.strength.name}, "
            f"vars={self.variables})"
        )


