def _default_naming_laws() -> list[NamingLaw]:
    """Return a small set of default naming laws for common Python conventions."""
    return [
        NamingLaw(
            pattern=r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$",
            description="snake_case identifier law",
            style="snake_case",
            examples=["my_var", "foo_bar", "x"],
        ),
        NamingLaw(
            pattern=r"^[A-Z][a-zA-Z0-9]*$",
            description="PascalCase class name law",
            style="PascalCase",
            examples=["MyClass", "FooBar"],
        ),
    ]


def _syntactic_satisfiability_check(constraints: list[TextConstraint]) -> bool:
    """Perform a lightweight syntactic satisfiability check on *constraints*.

    Detects obvious contradictions such as ``min_length > max_length``.

    Parameters
    ----------
    constraints:
        List of constraints to check.

    Returns
    -------
    bool
        False if an obvious contradiction is detected, True otherwise.
    """
    min_len: int | None = None
    max_len: int | None = None
    for c in constraints:
        if c.kind == ConstraintKind.LENGTH:
            if c.min_length is not None:
                min_len = max(min_len or 0, c.min_length)
            if c.max_length is not None:
                max_len = min(max_len if max_len is not None else 10**9, c.max_length)
    if min_len is not None and max_len is not None and min_len > max_len:
        return False
    return True


def _escape_smt2(s: str) -> str:
    """Escape *s* for use inside SMT-LIB2 string literals."""
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _constraint_to_smt2(c: TextConstraint, var_name: str) -> str | None:
    """Convert *c* to an SMT-LIB2 assertion string for *var_name*."""
    if c.kind == ConstraintKind.LENGTH:
        parts: list[str] = []
        if c.min_length is not None:
            parts.append(f"(>= (str.len {var_name}) {c.min_length})")
        if c.max_length is not None:
            parts.append(f"(<= (str.len {var_name}) {c.max_length})")
        if len(parts) == 1:
            return parts[0]
        if parts:
            return "(and " + " ".join(parts) + ")"
    elif c.kind == ConstraintKind.PREFIX and c.prefix is not None:
        escaped = _escape_smt2(c.prefix)
        return f'(str.prefixof "{escaped}" {var_name})'
    elif c.kind == ConstraintKind.REGEX and c.pattern is not None:
        escaped = _escape_smt2(c.pattern)
        return f'(str.in.re {var_name} (re.++ (str.to.re "{escaped}")))'
    return None


