@dataclass(slots=True)
class TextEncodingSession:
    """An active text encoding session accumulating encodings and shadows.

    Each session is identified by a UUID and wraps a ``NormalizedTextEnvironment``
    plus lists of ``StringEncoding`` and ``DocumentationShadow`` objects produced
    during the session.  The session can export its entire state to SMT-LIB2.
    """

    session_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    environment: NormalizedTextEnvironment | None = None
    encodings: list[StringEncoding] = field(default_factory=list)
    shadows: list[DocumentationShadow] = field(default_factory=list)
    _z3_session: Z3Session | None = field(default=None, repr=False)
    started_at: float = field(default_factory=time.time)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def encode_identifiers(self, names: list[str]) -> list[StringEncoding]:
        """Encode all identifiers in *names* as ``StringEncoding`` instances.

        Each identifier is wrapped in a ``StringEncoding``.  The results are
        appended to ``self.encodings`` and also returned.

        Parameters
        ----------
        names:
            List of raw identifier strings to encode.

        Returns
        -------
        list[StringEncoding]
            Freshly created encodings, one per input name.
        """
        new_encodings: list[StringEncoding] = []
        for name in names:
            enc = StringEncoding(
                raw_value=name,
                normalized_value=unicodedata.normalize("NFC", name),
                encoding_id=hashlib.sha256(name.encode()).hexdigest()[:16],
            )
            new_encodings.append(enc)
            self.encodings.append(enc)
        _LOGGER.debug(
            "TextEncodingSession[%s]: encoded %d identifiers",
            self.session_id[:8],
            len(new_encodings),
        )
        return new_encodings

    def encode_documentation(self, docstrings: list[str]) -> list[DocumentationShadow]:
        """Encode all *docstrings* as ``DocumentationShadow`` instances.

        Extracts parameter names, return types, and constraint phrases from each
        docstring, then wraps the result in a ``DocumentationShadow``.  The
        shadows are appended to ``self.shadows`` and also returned.

        Parameters
        ----------
        docstrings:
            List of raw docstring texts.

        Returns
        -------
        list[DocumentationShadow]
            Freshly created shadows, one per input docstring.
        """
        algo = DocumentationShadowExtraction(source_docstrings=docstrings)
        result = algo.run({"docstrings": docstrings})
        new_shadows: list[DocumentationShadow] = result.outputs.get("shadows", [])
        self.shadows.extend(new_shadows)
        _LOGGER.debug(
            "TextEncodingSession[%s]: encoded %d docstrings → %d shadows",
            self.session_id[:8],
            len(docstrings),
            len(new_shadows),
        )
        return new_shadows

    def apply_naming_laws(self, laws: list[NamingLaw]) -> dict[str, bool]:
        """Apply *laws* to all currently encoded identifiers.

        Returns a mapping from each identifier's raw value to a bool indicating
        whether it is compliant with all supplied laws.

        Parameters
        ----------
        laws:
            Naming laws to enforce.

        Returns
        -------
        dict[str, bool]
            ``{identifier: compliant}`` for every encoding in the session.
        """
        names = [enc.raw_value for enc in self.encodings]
        algo = NamingLawCompliance(codebase_names=names, laws=laws)
        result = algo.run({"names": names, "laws": laws})
        violated = {v.variable for v in result.outputs.get("violations", [])}
        compliance: dict[str, bool] = {name: name not in violated for name in names}
        return compliance

    def summarize_encoding(self) -> str:
        """Return a multi-paragraph summary of all encodings in the session.

        Covers encoding count, shadow count, and per-encoding details for up to
        the first ten encodings.
        """
        lines = [
            f"TextEncodingSession {self.session_id[:8]}",
            f"  Started: {time.strftime('%Y-%m-%dT%H:%M:%S', time.localtime(self.started_at))}",
            f"  Encodings: {len(self.encodings)}",
            f"  Shadows: {len(self.shadows)}",
            "",
            "Encodings (first 10):",
        ]
        for enc in self.encodings[:10]:
            lines.append(f"  [{enc.encoding_id}] {enc.raw_value!r} → {enc.normalized_value!r}")
        if len(self.encodings) > 10:
            lines.append(f"  ... and {len(self.encodings) - 10} more.")
        lines.append("")
        lines.append(f"Shadows: {len(self.shadows)} extracted")
        for shadow in self.shadows[:5]:
            lines.append(
                f"  [{shadow.shadow_id}] params={shadow.parameter_names}, "
                f"return={shadow.return_type}"
            )
        if len(self.shadows) > 5:
            lines.append(f"  ... and {len(self.shadows) - 5} more.")
        return "\n".join(lines)

    def get_all_constraints(self) -> list[TextConstraint]:
        """Collect all constraints from all encodings in the session.

        Returns
        -------
        list[TextConstraint]
            Flat list of every ``TextConstraint`` attached to every
            ``StringEncoding`` in the session.
        """
        constraints: list[TextConstraint] = []
        for enc in self.encodings:
            if hasattr(enc, "constraints") and enc.constraints:
                constraints.extend(enc.constraints)
        return constraints

    def verify_all(self) -> dict[str, bool]:
        """Verify that all constraints across all encodings are satisfiable.

        Uses the Z3 session if available; otherwise performs a lightweight
        syntactic check.

        Returns
        -------
        dict[str, bool]
            ``{encoding_id: satisfiable}`` for every encoding.
        """
        results: dict[str, bool] = {}
        for enc in self.encodings:
            # Lightweight check: encoding is satisfiable if no contradictory constraints
            constraints = getattr(enc, "constraints", []) or []
            consistent = _syntactic_satisfiability_check(constraints)
            results[enc.encoding_id] = consistent
        return results

    def to_smt2(self) -> str:
        """Export the entire session state to an SMT-LIB2 string.

        Produces a self-contained ``.smt2`` file with declarations and assertions
        for every constraint in the session.

        Returns
        -------
        str
            SMT-LIB2 text encoding all session constraints.
        """
        lines = [
            "; SMT-LIB2 export — TextEncodingSession",
            f"; session_id: {self.session_id}",
            "(set-logic QF_S)",
            "(set-option :produce-models true)",
            "",
        ]
        for enc in self.encodings:
            var_name = f"str_{enc.encoding_id}"
            lines.append(f"(declare-const {var_name} String)")
            lines.append(f'(assert (= {var_name} "{_escape_smt2(enc.normalized_value)}"))')
            for c in (getattr(enc, "constraints", []) or []):
                smt2 = _constraint_to_smt2(c, var_name)
                if smt2:
                    lines.append(f"(assert {smt2})")
        lines.append("")
        lines.append("(check-sat)")
        lines.append("(get-model)")
        return "\n".join(lines)

    def add_encoding(self, encoding: StringEncoding) -> None:
        """Append *encoding* to the session's encoding list."""
        self.encodings.append(encoding)

    def add_shadow(self, shadow: DocumentationShadow) -> None:
        """Append *shadow* to the session's shadow list."""
        self.shadows.append(shadow)


@dataclass(slots=True)
class TextEncoderRegistry:
    """Registry mapping encoder names to encoder classes.

    Provides a central lookup table for all encoder types used in the
    text encoding pipeline.  Encoders are registered by name and can be
    instantiated on demand via :meth:`create`.
    """

    _registry: dict[str, type] = field(default_factory=dict)
    _descriptions: dict[str, str] = field(default_factory=dict)

    def __post_init__(self) -> None:
        """Register built-in encoders."""
        self.register(
            NamingLawInference,
            "naming_law_inference",
            "Infers NamingLaw objects from a corpus of identifier strings.",
        )
        self.register(
            DocumentationShadowExtraction,
            "documentation_shadow_extraction",
            "Extracts DocumentationShadow objects from raw docstring text.",
        )
        self.register(
            StringConstraintPropagation,
            "string_constraint_propagation",
            "Propagates string constraints to derive new variable facts.",
        )
        self.register(
            TextCountermodelMinimization,
            "text_countermodel_minimization",
            "Minimizes a string countermodel by shortening variable values.",
        )
        self.register(
            NamingLawCompliance,
            "naming_law_compliance",
            "Checks identifier names against NamingLaw objects and repairs violations.",
        )

    def register(self, encoder_class: type, name: str, description: str = "") -> None:
        """Register *encoder_class* under *name*.

        Parameters
        ----------
        encoder_class:
            The class to register.
        name:
            Unique string key for this encoder.
        description:
            Optional human-readable description.
        """
        self._registry[name] = encoder_class
        self._descriptions[name] = description

    def lookup(self, name: str) -> type:
        """Return the encoder class registered under *name*.

        Raises
        ------
        KeyError
            If no encoder with *name* is registered.
        """
        if name not in self._registry:
            raise KeyError(f"No encoder registered under name '{name}'.")
        return self._registry[name]

    def list_encoders(self) -> list[str]:
        """Return a sorted list of all registered encoder names."""
        return sorted(self._registry)

    def describe(self, name: str) -> str:
        """Return the description for the encoder registered as *name*.

        Returns an empty string if no description was provided.
        """
        return self._descriptions.get(name, "")

    def create(self, name: str, **kwargs: Any) -> Any:
        """Instantiate the encoder registered under *name* with *kwargs*.

        Parameters
        ----------
        name:
            Registered encoder name.
        **kwargs:
            Keyword arguments forwarded to the encoder's constructor.

        Returns
        -------
        Any
            A new instance of the registered encoder class.
        """
        cls = self.lookup(name)
        return cls(**kwargs)

    def unregister(self, name: str) -> None:
        """Remove the encoder registered under *name*.

        No-op if *name* is not registered.
        """
        self._registry.pop(name, None)
        self._descriptions.pop(name, None)

    def is_registered(self, name: str) -> bool:
        """Return True if *name* is currently registered."""
        return name in self._registry


@dataclass(slots=True)
class PipelineResult:
    """Result produced by a completed ``TextEncodingPipeline`` run.

    Collects the encoding session, individual algorithm results, validity flag,
    elapsed time, any errors, and the final SMT-LIB2 output.
    """

    pipeline_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    session: TextEncodingSession | None = None
    algorithm_results: list[AlgorithmResult] = field(default_factory=list)
    valid: bool = False
    elapsed_time: float = 0.0
    error_messages: list[str] = field(default_factory=list)
    output_smt2: str = ""

    def add_algorithm_result(self, result: AlgorithmResult) -> None:
        """Append *result* to the list of algorithm results."""
        self.algorithm_results.append(result)

    def summary(self) -> str:
        """Return a human-readable summary of the pipeline result."""
        lines = [
            f"PipelineResult [{self.pipeline_id[:8]}]",
            f"  Valid: {self.valid}",
            f"  Elapsed: {self.elapsed_time:.3f}s",
            f"  Algorithm results: {len(self.algorithm_results)}",
            f"  Error messages: {len(self.error_messages)}",
            f"  SMT2 output length: {len(self.output_smt2)} chars",
        ]
        for algo_res in self.algorithm_results:
            lines.append(f"  [{algo_res.algorithm_name}] {algo_res.status.value}")
        if self.error_messages:
            lines.append("  Errors:")
            for err in self.error_messages:
                lines.append(f"    - {err}")
        return "\n".join(lines)

    def is_complete(self) -> bool:
        """Return True if the pipeline produced a valid session."""
        return self.session is not None and self.valid


@dataclass(slots=True)
class TextEncodingPipeline:
    """End-to-end pipeline orchestrating all text encoding components.

    Runs a sequence of stages: normalize → extract names → extract docstrings
    → encode names → encode docs → apply laws → propagate constraints →
    generate SMT2.  Results are accumulated in a ``PipelineResult``.
    """

    config: dict[str, Any] = field(default_factory=dict)
    _registry: TextEncoderRegistry = field(default_factory=TextEncoderRegistry)
    _current_result: PipelineResult | None = field(default=None)

    def __post_init__(self) -> None:
        # Merge with defaults
        merged = dict(DEFAULT_PIPELINE_CONFIG)
        merged.update(self.config)
        object.__setattr__(self, "config", merged)

    def run(
        self, source_text: str, z3_session: Z3Session | None = None
    ) -> PipelineResult:
        """Run the full text encoding pipeline on *source_text*.

        Stages:

        1. Normalize source text.
        2. Extract identifier-like names.
        3. Extract docstring-like blocks.
        4. Encode names as ``StringEncoding`` objects.
        5. Encode docs as ``DocumentationShadow`` objects.
        6. Apply naming laws.
        7. Propagate constraints.
        8. Generate SMT-LIB2 output.

        Parameters
        ----------
        source_text:
            Raw source text (Python module, docstring, etc.).
        z3_session:
            Optional Z3 session for constraint solving.

        Returns
        -------
        PipelineResult
            A fully populated result object.
        """
        start = time.monotonic()
        result = PipelineResult()
        session = TextEncodingSession()
        if z3_session is not None:
            object.__setattr__(session, "_z3_session", z3_session)

        _LOGGER.info("TextEncodingPipeline: starting run [%s]", result.pipeline_id[:8])

        try:
            # Stage 1 — normalize
            normalized = self._stage_normalize(source_text)

            # Stage 2 — extract names
            names = self._stage_extract_names(normalized)
            _LOGGER.debug("Extracted %d names", len(names))

            # Stage 3 — extract docstrings
            docs = self._stage_extract_docstrings(normalized)
            _LOGGER.debug("Extracted %d docstrings", len(docs))

            # Stage 4 — encode names
            encodings = self._stage_encode_names(names, session)
            result.add_algorithm_result(
                AlgorithmResult(
                    algorithm_name="encode_names",
                    status=__import__(
                        "jugeo.encodings.text_encodings.algorithms",
                        fromlist=["AlgorithmStatus"],
                    ).AlgorithmStatus.CONVERGED,
                    outputs={"encodings_count": len(encodings)},
                )
            )

            # Stage 5 — encode docs
            shadows = self._stage_encode_docs(docs, session)
            result.add_algorithm_result(
                AlgorithmResult(
                    algorithm_name="encode_docs",
                    status=__import__(
                        "jugeo.encodings.text_encodings.algorithms",
                        fromlist=["AlgorithmStatus"],
                    ).AlgorithmStatus.CONVERGED,
                    outputs={"shadows_count": len(shadows)},
                )
            )

            # Stage 6 — apply naming laws
            if self.config.get("apply_default_laws", True):
                from jugeo.encodings.text_encodings.algorithms import AlgorithmStatus
                laws = _default_naming_laws()
                compliance = self._stage_apply_laws(session, laws)
                compliant_count = sum(1 for v in compliance.values() if v)
                result.add_algorithm_result(
                    AlgorithmResult(
                        algorithm_name="apply_laws",
                        status=AlgorithmStatus.CONVERGED,
                        outputs={
                            "compliance": compliance,
                            "compliant_count": compliant_count,
                            "total_names": len(compliance),
                        },
                    )
                )

            # Stage 7 — propagate constraints
            if self.config.get("propagate_constraints", True):
                from jugeo.encodings.text_encodings.algorithms import AlgorithmStatus
                all_constraints = session.get_all_constraints()
                propagation_algo = StringConstraintPropagation(
                    initial_constraints=all_constraints
                )
                prop_result = propagation_algo.run({"constraints": all_constraints})
                result.add_algorithm_result(prop_result)

            # Stage 8 — generate SMT2
            if self.config.get("generate_smt2", True):
                from jugeo.encodings.text_encodings.algorithms import AlgorithmStatus
                smt2 = self._stage_generate_smt2(session)
                object.__setattr__(result, "output_smt2", smt2)
                result.add_algorithm_result(
                    AlgorithmResult(
                        algorithm_name="generate_smt2",
                        status=AlgorithmStatus.CONVERGED,
                        outputs={"smt2_length": len(smt2)},
                    )
                )

            object.__setattr__(result, "session", session)
            object.__setattr__(result, "valid", True)

        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("TextEncodingPipeline failed: %s", exc)
            result.error_messages.append(str(exc))
            object.__setattr__(result, "valid", False)

        object.__setattr__(result, "elapsed_time", time.monotonic() - start)
        object.__setattr__(self, "_current_result", result)
        _LOGGER.info(
            "TextEncodingPipeline: completed in %.3fs [valid=%s]",
            result.elapsed_time,
            result.valid,
        )
        return result

    def validate(self, pipeline_result: PipelineResult) -> bool:
        """Validate *pipeline_result* for completeness and consistency.

        Checks that a session exists, at least one encoding was produced, and
        no fatal error messages were recorded.

        Parameters
        ----------
        pipeline_result:
            The result to validate.

        Returns
        -------
        bool
            True if the result is valid, False otherwise.
        """
        if pipeline_result.session is None:
            return False
        if not pipeline_result.valid:
            return False
        if pipeline_result.error_messages:
            return False
        return True

    def report(self, pipeline_result: PipelineResult) -> str:
        """Generate a detailed human-readable report for *pipeline_result*.

        Includes stage-by-stage summaries, encoding statistics, and SMT2 size.

        Parameters
        ----------
        pipeline_result:
            The result to report on.

        Returns
        -------
        str
            Multi-line report text.
        """
        lines = [
            "=" * 60,
            "TextEncodingPipeline Report",
            "=" * 60,
            pipeline_result.summary(),
            "",
        ]
        if pipeline_result.session is not None:
            lines.append("--- Session Summary ---")
            lines.append(pipeline_result.session.summarize_encoding())
            lines.append("")
        if pipeline_result.output_smt2:
            lines.append(f"--- SMT2 Output ({len(pipeline_result.output_smt2)} chars) ---")
            preview = pipeline_result.output_smt2[:500]
            lines.append(preview)
            if len(pipeline_result.output_smt2) > 500:
                lines.append("... (truncated)")
        lines.append("=" * 60)
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Pipeline stages (private)
    # ------------------------------------------------------------------

    def _stage_normalize(self, text: str) -> str:
        """Normalize *text* to Unicode NFC form.

        Strips leading/trailing whitespace and collapses internal whitespace
        runs to a single space.

        Parameters
        ----------
        text:
            Raw input text.

        Returns
        -------
        str
            Normalized text.
        """
        strategy = self.config.get("normalization_strategy", "NFC")
        normalized = unicodedata.normalize(strategy, text)
        return normalized.strip()

    def _stage_extract_names(self, text: str) -> list[str]:
        """Extract identifier-like names from *text*.

        Finds tokens that look like Python identifiers (``[A-Za-z_][A-Za-z0-9_]*``)
        and de-duplicates them, preserving order of first appearance.

        Parameters
        ----------
        text:
            Normalized source text.

        Returns
        -------
        list[str]
            De-duplicated list of identifier-like tokens.
        """
        pattern = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]{0,255})\b")
        seen: set[str] = set()
        names: list[str] = []
        for match in pattern.finditer(text):
            name = match.group(1)
            if name not in seen:
                seen.add(name)
                names.append(name)
        return names

    def _stage_extract_docstrings(self, text: str) -> list[str]:
        """Extract docstring-like text blocks from *text*.

        Looks for triple-quoted strings (``\"\"\"...\"\"\"`` or ``'''...'''``).

        Parameters
        ----------
        text:
            Normalized source text.

        Returns
        -------
        list[str]
            List of docstring contents (without surrounding quotes).
        """
        pattern = re.compile(
            r'"""(.*?)"""|\'\'\'(.*?)\'\'\'', re.DOTALL
        )
        docs: list[str] = []
        for match in pattern.finditer(text):
            content = match.group(1) or match.group(2) or ""
            content = content.strip()
            if content:
                docs.append(content)
        return docs

    def _stage_encode_names(
        self, names: list[str], session: TextEncodingSession
    ) -> list[StringEncoding]:
        """Encode *names* as ``StringEncoding`` instances in *session*.

        Parameters
        ----------
        names:
            Identifier strings to encode.
        session:
            Target session for the encodings.

        Returns
        -------
        list[StringEncoding]
            The newly created encodings.
        """
        return session.encode_identifiers(names)

    def _stage_encode_docs(
        self, docs: list[str], session: TextEncodingSession
    ) -> list[DocumentationShadow]:
        """Encode *docs* as ``DocumentationShadow`` instances in *session*.

        Parameters
        ----------
        docs:
            Docstring strings to encode.
        session:
            Target session for the shadows.

        Returns
        -------
        list[DocumentationShadow]
            The newly created shadows.
        """
        return session.encode_documentation(docs)

    def _stage_apply_laws(
        self, session: TextEncodingSession, laws: list[NamingLaw]
    ) -> dict[str, bool]:
        """Apply *laws* to all names in *session*.

        Parameters
        ----------
        session:
            The current encoding session.
        laws:
            Naming laws to enforce.

        Returns
        -------
        dict[str, bool]
            Compliance dict from ``session.apply_naming_laws``.
        """
        return session.apply_naming_laws(laws)

    def _stage_generate_smt2(self, session: TextEncodingSession) -> str:
        """Generate the SMT-LIB2 export for all session encodings.

        Parameters
        ----------
        session:
            The current encoding session.

        Returns
        -------
        str
            SMT-LIB2 text.
        """
        return session.to_smt2()


