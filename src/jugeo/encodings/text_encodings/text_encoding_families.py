class StringFragmentClassifier:
    """Classifies TextConstraint objects by the Z3 theory fragment they use.

    The classifier inspects the ``formula_str`` of each constraint to detect
    which primitive string operations are present and maps that to the
    appropriate SMT fragment and complexity class.
    """

    # ------------------------------------------------------------------
    # Operation detection helpers
    # ------------------------------------------------------------------

    def uses_regex(self, constraint: TextConstraint) -> bool:
        """Return ``True`` if *constraint* uses regex operations.

        Detects ``re.`` or ``str.in_re`` in the formula string.
        """
        return "re." in constraint.formula_str or "str.in_re" in constraint.formula_str

    def uses_length(self, constraint: TextConstraint) -> bool:
        """Return ``True`` if *constraint* contains a length operation.

        Detects ``str.len`` in the formula string.
        """
        return "str.len" in constraint.formula_str

    def uses_concatenation(self, constraint: TextConstraint) -> bool:
        """Return ``True`` if *constraint* uses string concatenation.

        Detects both SMT-LIB ``str.++`` and ``str.concat`` variants.
        """
        return "str.++" in constraint.formula_str or "str.concat" in constraint.formula_str

    def uses_contains(self, constraint: TextConstraint) -> bool:
        """Return ``True`` if *constraint* uses ``str.contains``."""
        return "str.contains" in constraint.formula_str

    # ------------------------------------------------------------------
    # Classification
    # ------------------------------------------------------------------

    def classify_by_operations(self, constraint: TextConstraint) -> str:
        """Map a constraint to its primary family name by operation inspection.

        Examines the formula string for SMT-LIB primitives and returns the
        name of the best-matching family from ``FAMILY_NAMES``.

        Parameters
        ----------
        constraint:
            The constraint to classify.
        """
        if self.uses_regex(constraint) and self.uses_length(constraint):
            return "mixed"
        if self.uses_regex(constraint):
            return "regex_intersection"
        if self.uses_length(constraint) and not self.uses_concatenation(constraint):
            return "length_only"
        if self.uses_concatenation(constraint):
            return "concatenation"
        if self.uses_contains(constraint):
            return "contains_excludes"
        formula = constraint.formula_str
        if "str.prefixof" in formula or "str.suffixof" in formula:
            return "prefix_suffix"
        return "mixed"

    def classify_by_quantifiers(self, constraint: TextConstraint) -> str:
        """Identify the quantifier level of a constraint formula.

        Returns ``"forall"``, ``"exists"``, or ``"quantifier_free"``
        by scanning the formula string for quantifier keywords.

        Parameters
        ----------
        constraint:
            The constraint to inspect.
        """
        formula = constraint.formula_str
        if "forall" in formula:
            return "forall"
        if "exists" in formula:
            return "exists"
        return "quantifier_free"

    def estimate_complexity(self, constraint: TextConstraint) -> int:
        """Score the estimated solving complexity of *constraint* on a 1–5 scale.

        The score is computed by summing penalty points for each expensive
        operation present in the formula:

        * +1 for length operations
        * +1 for prefix/suffix checks
        * +2 for regex / in_re
        * +2 for concatenation
        * +1 for contains
        * +1 for non-trivial quantifiers

        The result is clamped to the range ``[1, 5]``.

        Parameters
        ----------
        constraint:
            The constraint to score.
        """
        score = 1
        if self.uses_length(constraint):
            score += 1
        if "str.prefixof" in constraint.formula_str or "str.suffixof" in constraint.formula_str:
            score += 1
        if self.uses_regex(constraint):
            score += 2
        if self.uses_concatenation(constraint):
            score += 2
        if self.uses_contains(constraint):
            score += 1
        if self.classify_by_quantifiers(constraint) != "quantifier_free":
            score += 1
        return max(1, min(5, score))

    def recommend_tactic(self, constraint: TextConstraint) -> str:
        """Return the name of the Z3 tactic best suited for *constraint*.

        The recommendation is derived from the family the constraint is
        classified into via ``classify_by_operations`` and the module-level
        ``STANDARD_TACTICS`` lookup table.

        Parameters
        ----------
        constraint:
            The constraint to advise on.
        """
        family = self.classify_by_operations(constraint)
        return STANDARD_TACTICS.get(family, "default")

    def classify_batch(
        self, constraints: list[TextConstraint]
    ) -> dict[str, str]:
        """Classify multiple constraints in a single call.

        Returns a dict mapping each constraint's ``name`` to its family
        string, as returned by ``classify_by_operations``.

        Parameters
        ----------
        constraints:
            The constraints to classify.
        """
        return {c.name: self.classify_by_operations(c) for c in constraints}


