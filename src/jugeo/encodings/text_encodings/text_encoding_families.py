@dataclass(frozen=True, slots=True)
class NamingLawFamily:
    """An immutable collection of NamingLaw objects grouped by context.

    Attributes
    ----------
    name:
        Human-readable identifier for this family, e.g. ``"python_stdlib"``.
    laws:
        Tuple of NamingLaw instances comprising this family.
    description:
        Optional extended description of the family's intended use.
    """

    name: str
    laws: tuple[NamingLaw, ...]
    description: str = ""

    # ------------------------------------------------------------------
    # Standard law factories
    # ------------------------------------------------------------------

    @staticmethod
    def python_identifiers() -> NamingLaw:
        """Return a NamingLaw for valid Python identifiers.

        Matches any name starting with a letter or underscore followed by
        any combination of letters, digits, and underscores.
        """
        return NamingLaw(
            name="python_identifier",
            pattern=r"[a-zA-Z_][a-zA-Z0-9_]*",
            description="Valid Python identifier (PEP 3131 ASCII subset)",
            context="identifier",
        )

    @staticmethod
    def snake_case() -> NamingLaw:
        """Return a NamingLaw enforcing PEP 8 snake_case for variables and functions."""
        return NamingLaw(
            name="snake_case",
            pattern=SNAKE_CASE_PATTERN,
            description="PEP 8 snake_case: lowercase words separated by underscores",
            context="function",
        )

    @staticmethod
    def camel_case() -> NamingLaw:
        """Return a NamingLaw for camelCase identifiers used in some APIs."""
        return NamingLaw(
            name="camel_case",
            pattern=CAMEL_CASE_PATTERN,
            description="camelCase: first word lowercase, subsequent words title-case",
            context="method",
        )

    @staticmethod
    def screaming_snake() -> NamingLaw:
        """Return a NamingLaw for SCREAMING_SNAKE_CASE module-level constants."""
        return NamingLaw(
            name="screaming_snake",
            pattern=r"[A-Z][A-Z0-9_]*",
            description="SCREAMING_SNAKE_CASE for module-level constants (PEP 8)",
            context="constant",
        )

    @staticmethod
    def module_names() -> NamingLaw:
        """Return a NamingLaw for Python module names.

        Module names must be all lowercase, may contain underscores, and
        must not start with a digit.
        """
        return NamingLaw(
            name="module_name",
            pattern=r"[a-z][a-z0-9_]*",
            description="Python module name: lowercase, underscores allowed (PEP 8)",
            context="module",
        )

    @staticmethod
    def class_names() -> NamingLaw:
        """Return a NamingLaw for Python class names (CapWords / PascalCase)."""
        return NamingLaw(
            name="class_name",
            pattern=r"[A-Z][a-zA-Z0-9]*",
            description="CapWords (PascalCase) for class names (PEP 8)",
            context="class",
        )

    # ------------------------------------------------------------------
    # Instance methods
    # ------------------------------------------------------------------

    def all_laws(self) -> list[NamingLaw]:
        """Return all laws in this family as a plain list."""
        return list(self.laws)

    def law_for_context(self, context: str) -> NamingLaw:
        """Return the most appropriate law for the given naming context.

        Parameters
        ----------
        context:
            One of ``"function"``, ``"class"``, ``"constant"``,
            ``"module"``, or ``"variable"``.  An unknown context falls
            back to the ``python_identifiers`` law.
        """
        context_map: dict[str, Callable[[], NamingLaw]] = {
            "function": NamingLawFamily.snake_case,
            "variable": NamingLawFamily.snake_case,
            "class": NamingLawFamily.class_names,
            "constant": NamingLawFamily.screaming_snake,
            "module": NamingLawFamily.module_names,
        }
        factory = context_map.get(context, NamingLawFamily.python_identifiers)
        return factory()

    def check_compliance_all(self, name: str) -> dict[str, bool]:
        """Check *name* against every law in this family.

        Returns a dict mapping each law's ``name`` attribute to a boolean
        indicating whether *name* satisfies that law's pattern.

        Parameters
        ----------
        name:
            The identifier string to test.
        """
        results: dict[str, bool] = {}
        for law in self.laws:
            try:
                results[law.name] = bool(re.fullmatch(law.pattern, name))
            except re.error as exc:
                _LOGGER.warning(
                    "check_compliance_all: invalid pattern in law %r: %s", law.name, exc
                )
                results[law.name] = False
        return results


def create_standard_naming_law_family() -> NamingLawFamily:
    """Build a NamingLawFamily containing the standard Python naming laws.

    Returns a frozen ``NamingLawFamily`` instance pre-populated with the
    six standard laws (identifier, snake_case, camelCase, SCREAMING_SNAKE,
    module, class).
    """
    laws = (
        NamingLawFamily.python_identifiers(),
        NamingLawFamily.snake_case(),
        NamingLawFamily.camel_case(),
        NamingLawFamily.screaming_snake(),
        NamingLawFamily.module_names(),
        NamingLawFamily.class_names(),
    )
    return NamingLawFamily(
        name="python_stdlib",
        laws=laws,
        description=(
            "Standard Python naming conventions as specified by PEP 8, "
            "PEP 3131, and common community practice."
        ),
    )


