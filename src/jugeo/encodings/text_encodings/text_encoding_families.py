@dataclass(slots=True)
class DocumentationConstraintFamily:
    """Groups DocumentationShadow patterns for docstring compliance checking.

    This dataclass acts as both a factory for common documentation patterns
    and a checker for whether a given docstring satisfies them.

    Attributes
    ----------
    patterns:
        The collection of DocumentationShadow patterns managed by this
        instance.
    """

    patterns: list[DocumentationShadow] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Pattern factories
    # ------------------------------------------------------------------

    def docstring_format_pattern(self) -> DocumentationShadow:
        """Return a DocumentationShadow for well-formed docstrings.

        The pattern requires a non-empty first line (summary), optionally
        followed by a blank line and extended description.
        """
        return DocumentationShadow(
            name="docstring_format",
            pattern=r'"""[^\n]{10,}',
            description="Docstring must begin with a non-trivial summary of at least 10 chars",
            required=True,
        )

    def parameter_docs_pattern(self) -> DocumentationShadow:
        """Return a DocumentationShadow requiring parameter documentation.

        Checks for a ``Parameters`` or ``Args`` section in the docstring,
        consistent with both NumPy and Google docstring conventions.
        """
        return DocumentationShadow(
            name="parameter_docs",
            pattern=r"(Parameters\s*[-]+|Args\s*:)",
            description="Docstring must include a Parameters / Args section",
            required=False,
        )

    def return_docs_pattern(self) -> DocumentationShadow:
        """Return a DocumentationShadow requiring return value documentation.

        Checks for a ``Returns`` or ``Return`` section in the docstring.
        """
        return DocumentationShadow(
            name="return_docs",
            pattern=r"(Returns\s*[-]+|Returns\s*:)",
            description="Docstring must include a Returns section for non-void functions",
            required=False,
        )

    def all_families(self) -> list[DocumentationShadow]:
        """Return all patterns stored in this family.

        If no patterns have been registered yet, auto-generates the three
        standard patterns (format, parameters, returns) before returning.
        """
        if not self.patterns:
            self.patterns = [
                self.docstring_format_pattern(),
                self.parameter_docs_pattern(),
                self.return_docs_pattern(),
            ]
        return list(self.patterns)

    # ------------------------------------------------------------------
    # Compliance checks
    # ------------------------------------------------------------------

    def check_coverage(self, docstring: str) -> dict[str, bool]:
        """Check how many standard sections are present in *docstring*.

        Returns a dict with boolean values for the following keys:

        * ``has_summary`` — first line is non-empty and >= 10 chars
        * ``has_args`` — contains a Parameters/Args section
        * ``has_returns`` — contains a Returns section
        * ``has_raises`` — contains a Raises section
        * ``has_example`` — contains an Examples or Example section

        Parameters
        ----------
        docstring:
            The docstring text to analyse.
        """
        stripped = docstring.strip().strip('"""').strip("'''").strip()
        lines = stripped.splitlines()
        first_line = lines[0].strip() if lines else ""

        return {
            "has_summary": len(first_line) >= 10,
            "has_args": bool(
                re.search(r"(Parameters\s*[-]+|Args\s*:)", docstring, re.IGNORECASE)
            ),
            "has_returns": bool(
                re.search(r"Returns\s*([-]+|:)", docstring, re.IGNORECASE)
            ),
            "has_raises": bool(
                re.search(r"Raises\s*([-]+|:)", docstring, re.IGNORECASE)
            ),
            "has_example": bool(
                re.search(r"Examples?\s*([-]+|:)", docstring, re.IGNORECASE)
            ),
        }

    def generate_compliant_template(self, context: str) -> str:
        """Generate a compliant docstring template for *context*.

        Parameters
        ----------
        context:
            One of ``"function"``, ``"class"``, or ``"module"``.  An
            unrecognised context defaults to the function template.
        """
        if context == "module":
            return (
                '"""\n'
                "Module summary — replace this with a real description.\n\n"
                "Extended description of the module's purpose, contents, and\n"
                "any important usage notes.\n"
                '"""\n'
            )
        if context == "class":
            return (
                '"""\n'
                "Class summary — replace this with a real description.\n\n"
                "Attributes\n"
                "----------\n"
                "attr_name : type\n"
                "    Description of attr_name.\n"
                '"""\n'
            )
        # Default: function template
        return (
            '"""\n'
            "Function summary — replace this with a real description.\n\n"
            "Parameters\n"
            "----------\n"
            "param_name : type\n"
            "    Description of param_name.\n\n"
            "Returns\n"
            "-------\n"
            "type\n"
            "    Description of the return value.\n\n"
            "Raises\n"
            "------\n"
            "ExceptionType\n"
            "    Conditions under which this exception is raised.\n"
            '"""\n'
        )

    def compliance_score(self, docstring: str) -> float:
        """Compute a compliance score for *docstring* in the range ``[0.0, 1.0]``.

        The score is the fraction of coverage keys in ``check_coverage``
        that evaluate to ``True``.  A score of ``1.0`` means the docstring
        satisfies all checked criteria.

        Parameters
        ----------
        docstring:
            The docstring text to score.
        """
        coverage = self.check_coverage(docstring)
        if not coverage:
            return 0.0
        passing = sum(1 for v in coverage.values() if v)
        return passing / len(coverage)
