@dataclass(slots=True)
class TextEncodingManifest:
    """
    Central manifest for the JuGeo text_encodings package.

    Holds the chapter reference, list of section modules, theorem targets,
    capability flags, and provenance metadata.  Instances are mutable; use
    :meth:`add_section` and :meth:`flag_capability` to extend them.

    Attributes:
        chapter_ref: The canonical chapter tag (should equal CHAPTER_TAG).
        section_names: Ordered list of section module names.
        theorem_targets: List of theorem identifiers from theory2.tex Ch28.
        capability_flags: Mutable dict of capability boolean flags.
        generated_at: Unix timestamp of manifest creation.
        provenance: Metadata dict describing the manifest's origin.

    Example::

        m = build_manifest()
        print(m.summary())
    """

    chapter_ref: str
    section_names: list[str]
    theorem_targets: list[str]
    capability_flags: dict[str, bool]
    generated_at: float = field(default_factory=time.time)
    provenance: Mapping[str, str | int] = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Enumeration helpers
    # ------------------------------------------------------------------

    def enumerate_sections(self) -> list[tuple[int, str]]:
        """
        Return a numbered list of sections (1-based).

        Returns:
            List of (index, section_name) tuples.

        Example::

            for idx, name in manifest.enumerate_sections():
                print(f"{idx}. {name}")
        """
        return list(enumerate(self.section_names, start=1))

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------

    def validate(self) -> list[str]:
        """
        Validate this manifest and return a list of error strings.

        Returns:
            Empty list if the manifest is valid; otherwise a list of
            human-readable error messages.

        Example::

            errors = manifest.validate()
            assert errors == []
        """
        validator = ManifestValidator()
        errors = validator.run_all(self)
        if errors:
            _logger.warning("Manifest validation found %d error(s)", len(errors))
            for e in errors:
                _logger.debug("  %s", e)
        return errors

    # ------------------------------------------------------------------
    # Serialization
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        """
        Export this manifest as a plain Python dict.

        Returns:
            A JSON-serializable dict representation.
        """
        return ManifestSerializer().to_dict(self)

    # ------------------------------------------------------------------
    # Display helpers
    # ------------------------------------------------------------------

    def summary(self) -> str:
        """
        Return a concise human-readable summary of the manifest.

        Returns:
            A multi-line string describing the manifest's key attributes.

        Example::

            print(manifest.summary())
        """
        lines = ManifestSerializer().to_summary_lines(self)
        return "\n".join(lines)

    def capability_summary(self) -> str:
        """
        Return a one-line string summarising which capabilities are enabled.

        Returns:
            A comma-separated list of ``flag=True/False`` entries.
        """
        parts = [f"{k}={'on' if v else 'off'}" for k, v in self.capability_flags.items()]
        return ", ".join(parts)

    def theorem_count(self) -> int:
        """
        Return the number of theorem targets registered.

        Returns:
            Integer count of theorem_targets entries.
        """
        return len(self.theorem_targets)

    # ------------------------------------------------------------------
    # Completeness check
    # ------------------------------------------------------------------

    def is_complete(self) -> bool:
        """
        Return True if the manifest passes all validations and every declared
        section is present in the global SECTION_REGISTRY.

        Returns:
            True when no validation errors are found.
        """
        errors = self.validate()
        return len(errors) == 0

    # ------------------------------------------------------------------
    # Mutation helpers
    # ------------------------------------------------------------------

    def add_section(self, name: str, file_name: str) -> None:
        """
        Add a new section to the manifest.

        If *name* is already in section_names it is not added again, but the
        global SECTION_REGISTRY is updated (module-level dict is immutable via
        Final, so this logs a warning instead).

        Args:
            name: Logical section name (e.g. ``"new_section"``).
            file_name: Python file name for the section (e.g. ``"new_section.py"``).

        Example::

            manifest.add_section("extra", "extra.py")
        """
        if name not in self.section_names:
            self.section_names.append(name)
            _logger.debug("Added section %r -> %r to manifest", name, file_name)
        else:
            _logger.debug("Section %r already present in manifest", name)

    def flag_capability(self, name: str, value: bool) -> None:
        """
        Set or update a capability flag.

        Args:
            name: Capability flag key (e.g. ``"z3_strings"``).
            value: Boolean flag value.

        Example::

            manifest.flag_capability("repair_engine", False)
        """
        self.capability_flags[name] = value
        _logger.debug("Set capability flag %r = %r", name, value)

    # ------------------------------------------------------------------
    # Merge
    # ------------------------------------------------------------------

    def merge_with(self, other: TextEncodingManifest) -> TextEncodingManifest:
        """
        Merge this manifest with *other*, producing a new manifest.

        Section names and theorem targets are union-merged (preserving order
        from self first, then any additions from other).  Capability flags from
        *other* override those in self when keys collide.

        Args:
            other: Another :class:`TextEncodingManifest` to merge in.

        Returns:
            A new :class:`TextEncodingManifest` that combines both manifests.

        Raises:
            ValueError: If the two manifests have differing chapter_ref values.

        Example::

            merged = m1.merge_with(m2)
        """
        if self.chapter_ref != other.chapter_ref:
            raise ValueError(
                f"Cannot merge manifests with differing chapter_ref: "
                f"{self.chapter_ref!r} vs {other.chapter_ref!r}"
            )
        merged_sections = list(self.section_names)
        for s in other.section_names:
            if s not in merged_sections:
                merged_sections.append(s)

        merged_theorems = list(self.theorem_targets)
        for t in other.theorem_targets:
            if t not in merged_theorems:
                merged_theorems.append(t)

        merged_flags = {**self.capability_flags, **other.capability_flags}

        merged_prov: dict[str, str | int] = {**self.provenance, **other.provenance}

        result = TextEncodingManifest(
            chapter_ref=self.chapter_ref,
            section_names=merged_sections,
            theorem_targets=merged_theorems,
            capability_flags=merged_flags,
            generated_at=time.time(),
            provenance=merged_prov,
        )
        _logger.debug(
            "Merged manifest: %d sections, %d theorems",
            len(merged_sections),
            len(merged_theorems),
        )
        return result


