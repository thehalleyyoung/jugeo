class ManifestSerializer:
    """
    Serializes and deserializes :class:`TextEncodingManifest` objects to and from
    plain Python dicts, making them suitable for JSON or YAML persistence.

    Example::

        s = ManifestSerializer()
        d = s.to_dict(manifest)
        m2 = s.from_dict(d)
    """

    def to_dict(self, manifest: TextEncodingManifest) -> dict[str, Any]:
        """
        Convert a manifest to a JSON-serializable dict.

        Args:
            manifest: The manifest to serialize.

        Returns:
            A plain dict representation of the manifest.
        """
        return {
            "chapter_ref": manifest.chapter_ref,
            "section_names": list(manifest.section_names),
            "theorem_targets": list(manifest.theorem_targets),
            "capability_flags": dict(manifest.capability_flags),
            "generated_at": manifest.generated_at,
            "provenance": dict(manifest.provenance),
        }

    def from_dict(self, data: dict[str, Any]) -> TextEncodingManifest:
        """
        Reconstruct a :class:`TextEncodingManifest` from a plain dict.

        Args:
            data: Dict previously produced by :meth:`to_dict`.

        Returns:
            A new :class:`TextEncodingManifest` instance.

        Raises:
            KeyError: If a required key is absent from *data*.
        """
        return TextEncodingManifest(
            chapter_ref=data["chapter_ref"],
            section_names=list(data["section_names"]),
            theorem_targets=list(data["theorem_targets"]),
            capability_flags=dict(data["capability_flags"]),
            generated_at=float(data.get("generated_at", time.time())),
            provenance=dict(data.get("provenance", {})),
        )

    def to_summary_lines(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Return a list of human-readable summary lines for display.

        Args:
            manifest: The manifest to summarize.

        Returns:
            A list of strings, one per attribute.
        """
        return [
            f"Chapter : {manifest.chapter_ref}",
            f"Sections: {', '.join(manifest.section_names)}",
            f"Theorems: {manifest.theorem_count()} target(s)",
            f"Capabilities: {manifest.capability_summary()}",
            f"Generated at: {manifest.generated_at:.3f}",
            f"Valid: {manifest.is_complete()}",
        ]


