class ManifestValidator:
    """
    Validates a :class:`TextEncodingManifest` against the invariants described
    in theory2.tex Ch28.

    Instances are stateless; all methods accept the manifest as an argument.

    Example::

        validator = ManifestValidator()
        errors = validator.run_all(manifest)
        if errors:
            for e in errors:
                print(e)
    """

    def check_sections(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Verify that the manifest's section_names list is non-empty, contains no
        duplicates, and that every entry also appears in the section registry.

        Args:
            manifest: The manifest to inspect.

        Returns:
            A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        seen: set[str] = set()
        for name in manifest.section_names:
            if name in seen:
                errors.append(f"[E007] Duplicate section name: {name!r}")
            seen.add(name)
        for name in manifest.section_names:
            if name not in SECTION_REGISTRY:
                errors.append(f"[E001] Section {name!r} not in global SECTION_REGISTRY")
        return errors

    def check_theorems(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Ensure that theorem_targets is non-empty and contains no duplicates.

        Args:
            manifest: The manifest to inspect.

        Returns:
            A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        if not manifest.theorem_targets:
            errors.append("[E002] theorem_targets must not be empty")
        seen: set[str] = set()
        for t in manifest.theorem_targets:
            if t in seen:
                errors.append(f"[E008] Duplicate theorem target: {t!r}")
            seen.add(t)
        return errors

    def check_capabilities(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Verify that all required capability keys are present and hold boolean values.

        Args:
            manifest: The manifest to inspect.

        Returns:
            A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        for key in _REQUIRED_CAPABILITY_KEYS:
            if key not in manifest.capability_flags:
                errors.append(f"[E003] Missing capability flag: {key!r}")
            elif not isinstance(manifest.capability_flags[key], bool):
                errors.append(f"[E009] Capability flag {key!r} must be bool")
        return errors

    def check_provenance(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Check that the manifest provenance dict contains all required keys.

        Args:
            manifest: The manifest to inspect.

        Returns:
            A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        for key in _REQUIRED_PROVENANCE_KEYS:
            if key not in manifest.provenance:
                errors.append(f"[E005] Missing provenance key: {key!r}")
        return errors

    def check_chapter_ref(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Verify that chapter_ref matches the module-level CHAPTER_TAG.

        Args:
            manifest: The manifest to inspect.

        Returns:
            A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        if manifest.chapter_ref != CHAPTER_TAG:
            errors.append(
                f"[E004] chapter_ref {manifest.chapter_ref!r} != CHAPTER_TAG {CHAPTER_TAG!r}"
            )
        return errors

    def check_timestamp(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Warn if generated_at is in the future.

        Args:
            manifest: The manifest to inspect.

        Returns:
            A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        now = time.time()
        if manifest.generated_at > now + 60:
            errors.append(
                f"[E010] generated_at ({manifest.generated_at:.1f}) is more than 60 s in the future"
            )
        return errors

    def run_all(self, manifest: TextEncodingManifest) -> list[str]:
        """
        Run all validation checks and aggregate results.

        Args:
            manifest: The manifest to validate.

        Returns:
            A flat list of all error strings found across all checks.
        """
        errors: list[str] = []
        errors.extend(self.check_sections(manifest))
        errors.extend(self.check_theorems(manifest))
        errors.extend(self.check_capabilities(manifest))
        errors.extend(self.check_provenance(manifest))
        errors.extend(self.check_chapter_ref(manifest))
        errors.extend(self.check_timestamp(manifest))
        return errors


