def list_active_capabilities(manifest: TextEncodingManifest) -> list[str]:
    """
    Return the names of all capability flags that are currently enabled.

    Args:
        manifest: The manifest whose capability_flags to inspect.

    Returns:
        A list of flag names whose value is True.

    Example::

        active = list_active_capabilities(MANIFEST)
        print("Active:", active)
    """
    return [k for k, v in manifest.capability_flags.items() if v]


def list_inactive_capabilities(manifest: TextEncodingManifest) -> list[str]:
    """
    Return the names of all capability flags that are currently disabled.

    Args:
        manifest: The manifest whose capability_flags to inspect.

    Returns:
        A list of flag names whose value is False.
    """
    return [k for k, v in manifest.capability_flags.items() if not v]


