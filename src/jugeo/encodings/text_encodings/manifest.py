def build_manifest() -> TextEncodingManifest:
    """
    Construct and return the canonical :class:`TextEncodingManifest` for the
    text_encodings package.

    The manifest is populated from the module-level constants defined in this
    file and represents the complete, authoritative description of the package
    contents as generated by the JuGeo copilot encoding pipeline.

    Returns:
        A fully populated :class:`TextEncodingManifest` instance.

    Example::

        m = build_manifest()
        assert m.is_complete()
    """
    _logger.debug("Building text_encodings manifest for chapter %r", CHAPTER_TAG)
    manifest = TextEncodingManifest(
        chapter_ref=CHAPTER_TAG,
        section_names=list(SECTION_NAMES),
        theorem_targets=list(THEOREM_TARGETS),
        capability_flags=dict(CAPABILITY_FLAGS),
        generated_at=time.time(),
        provenance=dict(MANIFEST_SPEC_PROVENANCE),
    )
    _logger.info(
        "text_encodings manifest built: %d sections, %d theorems",
        len(manifest.section_names),
        manifest.theorem_count(),
    )
    return manifest


def validate_manifest(manifest: TextEncodingManifest) -> bool:
    """
    Validate *manifest* and log any errors found.

    This is a convenience wrapper around :meth:`TextEncodingManifest.validate`
    that logs at WARNING level when errors are present and returns a simple
    boolean result.

    Args:
        manifest: The manifest to validate.

    Returns:
        True if the manifest passes all checks; False otherwise.

    Example::

        ok = validate_manifest(MANIFEST)
        assert ok, "Manifest is invalid — check logs for details"
    """
    errors = manifest.validate()
    if errors:
        _logger.warning(
            "Manifest validation failed with %d error(s):", len(errors)
        )
        for i, err in enumerate(errors, start=1):
            _logger.warning("  [%d] %s", i, err)
        return False
    _logger.info("Manifest validation passed (chapter=%r)", manifest.chapter_ref)
    return True


