class CountermodelInterpreter:
    """Translates raw countermodel data into human-readable diagnostics.

    This class is the presentation layer of the countermodel pipeline: it
    takes the raw output of the solver (a dict mapping variable names to
    string values) and the violated constraints, and produces clear,
    actionable explanations for developers.
    """

    def __init__(self) -> None:
        """Initialise the interpreter with an empty internal state."""
        self._format_cache: dict[str, str] = {}

    # ------------------------------------------------------------------
    # Violation interpreters
    # ------------------------------------------------------------------

    def interpret_naming_violation(
        self, model: dict[str, str], law: NamingLaw
    ) -> str:
        """Return a detailed explanation of a naming law violation.

        Describes which aspect of the naming law is violated and provides
        a concrete example of a compliant name.

        Parameters
        ----------
        model:
            Countermodel mapping variable names to observed values.
        law:
            The NamingLaw that is violated.
        """
        observed = next(iter(model.values()), "<unknown>")
        var = next(iter(model.keys()), "x")
        try:
            matches = bool(re.fullmatch(law.pattern, observed))
        except re.error:
            matches = False

        status = "satisfies" if matches else "violates"
        lines = [
            f"Naming law {law.name!r} ({law.description})",
            f"Variable {var!r} has value {observed!r} which {status} the pattern {law.pattern!r}.",
        ]
        if not matches:
            lines.append(
                f"Context: {law.context!r}.  "
                f"A compliant example would be: {self._example_for_pattern(law.pattern)!r}."
            )
            lines.append(
                "Apply one of the following transforms to bring the name into compliance:\n"
                "  • to_snake_case: " + re.sub(r"(?<!^)(?=[A-Z])", "_", observed).lower() + "\n"
                "  • to_capwords:   " + "".join(w.title() for w in re.split(r"[_\s-]", observed))
            )
        return "\n".join(lines)

    def interpret_doc_violation(
        self, model: dict[str, str], shadow: DocumentationShadow
    ) -> str:
        """Return a detailed explanation of a documentation constraint violation.

        Parameters
        ----------
        model:
            Countermodel mapping variable names to observed docstring values.
        shadow:
            The DocumentationShadow pattern that is violated.
        """
        observed = next(iter(model.values()), "")
        var = next(iter(model.keys()), "docstring")

        try:
            matches = bool(re.search(shadow.pattern, observed))
        except re.error:
            matches = False

        status = "satisfies" if matches else "violates"
        lines = [
            f"Documentation shadow {shadow.name!r}: {shadow.description}",
            f"Variable {var!r} {status} the required pattern.",
        ]
        if not matches:
            lines.append(
                f"The pattern {shadow.pattern!r} was not found in the docstring.\n"
                "Add the missing section.  A compliant docstring template:\n\n"
                '    """\n'
                "    Summary line.\n\n"
                "    Parameters\n"
                "    ----------\n"
                "    param : type\n"
                "        Description.\n\n"
                "    Returns\n"
                "    -------\n"
                "    type\n"
                "        Description.\n"
                '    """\n'
            )
        return "\n".join(lines)

    def interpret_length_violation(
        self, model: dict[str, str], constraint: TextConstraint
    ) -> str:
        """Return a human-readable explanation of a length violation.

        Parameters
        ----------
        model:
            Countermodel.
        constraint:
            The length constraint that is violated.
        """
        observed = next(iter(model.values()), "")
        var = next(iter(model.keys()), "x")
        formula = constraint.formula_str

        min_m = re.search(r"\(>\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
        max_m = re.search(r"\(<=\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)

        parts = [
            f"Length constraint {constraint.name!r} is violated.",
            f"Observed: {var!r} = {observed!r} (length={len(observed)})",
        ]
        if min_m:
            min_len = int(min_m.group(1)) + 1
            parts.append(f"Minimum required length: {min_len}")
            if len(observed) < min_len:
                parts.append(
                    f"The string is {min_len - len(observed)} character(s) too short.  "
                    f"Extend it by appending meaningful content."
                )
        if max_m:
            max_len = int(max_m.group(1))
            parts.append(f"Maximum allowed length: {max_len}")
            if len(observed) > max_len:
                parts.append(
                    f"The string is {len(observed) - max_len} character(s) too long.  "
                    f"Truncate it or use an abbreviation."
                )
        return "\n".join(parts)

    def interpret_pattern_violation(
        self, model: dict[str, str], constraint: TextConstraint
    ) -> str:
        """Return a human-readable explanation of a regex/pattern violation.

        Parameters
        ----------
        model:
            Countermodel.
        constraint:
            The regex constraint that is violated.
        """
        observed = next(iter(model.values()), "")
        var = next(iter(model.keys()), "x")

        illegal_chars = re.findall(r"[^a-zA-Z0-9_\s\-.]", observed)
        parts = [
            f"Pattern constraint {constraint.name!r} is violated.",
            f"Observed: {var!r} = {observed!r}",
            f"Formula: {constraint.formula_str}",
        ]
        if illegal_chars:
            parts.append(
                f"Potentially offending characters: {set(illegal_chars)!r}.  "
                f"Remove or replace them."
            )
        parts.append(
            "Review the regex embedded in the formula and adjust the string so that it "
            "matches the intended character class."
        )
        return "\n".join(parts)

    # ------------------------------------------------------------------
    # Repair messaging and utility
    # ------------------------------------------------------------------

    def generate_repair_message(self, violation: ConstraintViolation) -> str:
        """Generate a user-facing repair message for *violation*.

        The message is intended to be displayed directly in developer-facing
        output such as CI logs, IDE squiggles, or review comments.

        Parameters
        ----------
        violation:
            The violation to generate a message for.
        """
        severity_desc = SEVERITY_DESCRIPTIONS.get(violation.severity, "Unknown severity")
        hints_block = ""
        if violation.repair_hints:
            hints_block = "\n".join(f"  → {h}" for h in violation.repair_hints)
            hints_block = "\nRepair hints:\n" + hints_block

        return (
            f"⚠ [{violation.violation_type.value.upper()}] {violation.variable_name!r}\n"
            f"  Severity: {violation.severity}/5 — {severity_desc}\n"
            f"  Observed: {violation.observed_value!r}\n"
            f"  Constraint: {violation.constraint.name!r}\n"
            f"  Formula: {violation.constraint.formula_str}"
            + hints_block
        )

    def severity_of(self, violation: ConstraintViolation) -> int:
        """Return a severity score 1–5 for *violation* based on its type.

        Severity mapping:

        * ``LENGTH_TOO_SHORT`` → 2
        * ``LENGTH_TOO_LONG`` → 2
        * ``MISSING_PREFIX`` → 3
        * ``MISSING_SUFFIX`` → 2
        * ``FORBIDDEN_PATTERN`` → 4
        * ``INVALID_CHARACTERS`` → 4
        * ``CASE_VIOLATION`` → 2
        * ``FORMAT_VIOLATION`` → 3
        * ``SEMANTIC_VIOLATION`` → 5

        Parameters
        ----------
        violation:
            The violation to score.
        """
        severity_map: dict[ViolationType, int] = {
            ViolationType.LENGTH_TOO_SHORT: 2,
            ViolationType.LENGTH_TOO_LONG: 2,
            ViolationType.MISSING_PREFIX: 3,
            ViolationType.MISSING_SUFFIX: 2,
            ViolationType.FORBIDDEN_PATTERN: 4,
            ViolationType.INVALID_CHARACTERS: 4,
            ViolationType.CASE_VIOLATION: 2,
            ViolationType.FORMAT_VIOLATION: 3,
            ViolationType.SEMANTIC_VIOLATION: 5,
        }
        return severity_map.get(violation.violation_type, 3)

    def format_model_diff(
        self, model: dict[str, str], expected: dict[str, str]
    ) -> str:
        """Format a textual diff between an observed model and expected values.

        Each variable present in either dict is shown with its observed and
        expected values side by side.  Variables that match are marked with
        ``✓``; mismatches are marked with ``✗``.

        Parameters
        ----------
        model:
            The observed (countermodel) values.
        expected:
            The expected (compliant) values.
        """
        all_keys = sorted(set(model) | set(expected))
        if not all_keys:
            return "(no variables to compare)"

        rows: list[str] = ["Variable          Observed                Expected"]
        rows.append("-" * 65)
        for key in all_keys:
            obs = model.get(key, "<missing>")
            exp = expected.get(key, "<missing>")
            mark = "✓" if obs == exp else "✗"
            obs_disp = (obs[:20] + "…") if len(obs) > 21 else obs
            exp_disp = (exp[:20] + "…") if len(exp) > 21 else exp
            rows.append(f"{mark} {key:<17} {obs_disp:<23} {exp_disp}")
        return "\n".join(rows)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _example_for_pattern(self, pattern: str) -> str:
        """Return a short hard-coded example string for well-known patterns."""
        known: dict[str, str] = {
            IDENTIFIER_PATTERN: "my_variable",
            SNAKE_CASE_PATTERN: "my_function_name",
            CAMEL_CASE_PATTERN: "myMethodName",
            r"[A-Z][A-Z0-9_]*": "MY_CONSTANT",
            r"[a-z][a-z0-9_]*": "my_module",
            r"[A-Z][a-zA-Z0-9]*": "MyClassName",
        }
        return known.get(pattern, "valid_example")
