@dataclass(slots=True)
class TextCountermodels:
    """Finds and interprets counterexamples for string constraint systems.

    When a set of TextConstraint objects is declared to be satisfiable but
    a specific string value violates one or more of them, this class
    orchestrates the search for a countermodel, its interpretation, and the
    generation of repair suggestions.

    Attributes
    ----------
    _violations:
        Accumulated list of ConstraintViolation objects discovered during
        the current session.
    _repair_history:
        List of (repaired_constraint, success) pairs tracking which repairs
        were attempted and whether they succeeded.
    """

    _violations: list[ConstraintViolation] = field(default_factory=list)
    _repair_history: list[tuple[TextConstraint, bool]] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Countermodel search
    # ------------------------------------------------------------------

    def find_countermodel(
        self,
        constraints: list[TextConstraint],
        session: Z3Session | None = None,
    ) -> dict[str, str] | None:
        """Attempt to find a string assignment that violates *constraints*.

        When a live Z3Session is available, the method negates the conjunction
        of all constraints and asks Z3 for a satisfying assignment.  If Z3
        is unavailable, a heuristic generator produces short candidate strings
        and tests them against each constraint's pattern.

        Parameters
        ----------
        constraints:
            The constraints to test.  Each must expose a ``formula_str`` and
            a ``name``.
        session:
            Optional Z3Session.  When ``None``, the heuristic fallback is used.

        Returns
        -------
        dict[str, str] | None
            A mapping from variable name to string value that violates at
            least one constraint, or ``None`` if no countermodel was found
            within the search budget.
        """
        _LOGGER.debug("find_countermodel: searching over %d constraints", len(constraints))

        if session is not None and _Z3_AVAILABLE:
            return self._find_countermodel_z3(constraints, session)

        return self._find_countermodel_heuristic(constraints)

    def _find_countermodel_z3(
        self,
        constraints: list[TextConstraint],
        session: Z3Session,
    ) -> dict[str, str] | None:
        """Z3-backed countermodel search.

        Negates the conjunction of all constraint formulas and runs the
        Z3 solver.  If SAT, extracts the string values from the model.
        """
        try:
            negated_formulas = [f"(not {c.formula_str})" for c in constraints]
            combined = "(or " + " ".join(negated_formulas) + ")" if len(negated_formulas) > 1 else negated_formulas[0]
            outcome = session.check_sat(combined)
            if outcome == SolveOutcome.SAT:
                raw_model = session.get_model()
                return self.extract_string_witnesses(session)
        except Exception as exc:
            _LOGGER.warning("_find_countermodel_z3: Z3 error: %s", exc)
        return None

    def _find_countermodel_heuristic(
        self,
        constraints: list[TextConstraint],
    ) -> dict[str, str] | None:
        """Heuristic countermodel search used when Z3 is unavailable.

        Generates a small catalogue of candidate strings that are known to
        violate common constraint patterns and tests each against the
        constraint set.  Returns the first matching candidate.
        """
        candidates = [
            "",           # empty string — violates most length constraints
            " ",          # whitespace-only
            "a" * 300,    # very long string
            "1invalid",   # starts with digit — violates identifier constraints
            "CamelCase",  # violates snake_case
            "snake_case", # violates CapWords
            "with space", # contains space
            "has-hyphen", # contains hyphen
            "__dunder__", # double underscores
        ]
        for candidate in candidates:
            for c in constraints:
                if self._heuristic_violates(candidate, c):
                    _LOGGER.debug(
                        "_find_countermodel_heuristic: found violating candidate %r for %r",
                        candidate, c.name,
                    )
                    return {"x": candidate}
        return None

    def _heuristic_violates(self, value: str, constraint: TextConstraint) -> bool:
        """Return ``True`` if *value* appears to violate *constraint* heuristically."""
        formula = constraint.formula_str
        # Length checks
        m = re.search(r"\(>\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
        if m and len(value) <= int(m.group(1)):
            return True
        m = re.search(r"\(<=\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
        if m and len(value) > int(m.group(1)):
            return True
        # Pattern checks via embedded regex (best-effort)
        if "str.in_re" in formula and constraint.kind == ConstraintKind.REGEX:
            if hasattr(constraint, "python_pattern") and constraint.python_pattern:
                try:
                    return not bool(re.fullmatch(constraint.python_pattern, value))
                except re.error:
                    pass
        return False

    # ------------------------------------------------------------------
    # Interpretation
    # ------------------------------------------------------------------

    def interpret_countermodel(
        self,
        model: dict[str, str],
        constraints: list[TextConstraint],
    ) -> str:
        """Produce a human-readable interpretation of a countermodel.

        Inspects the model values against each constraint and builds a
        multi-paragraph explanation of what went wrong.

        Parameters
        ----------
        model:
            Mapping from variable name to the offending string value.
        constraints:
            The full set of constraints under which the countermodel was found.
        """
        paragraphs: list[str] = []
        paragraphs.append(
            "== Countermodel Interpretation ==\n"
            f"The solver found {len(model)} variable assignment(s) that collectively "
            f"violate the constraint system.\n"
        )

        for var, value in model.items():
            paragraphs.append(
                f"Variable {var!r} has value {value!r} (length={len(value)})."
            )

        violated: list[str] = []
        for c in constraints:
            for var, value in model.items():
                vtype = self.classify_violation(model, c)
                violated.append(
                    f"  • [{vtype.value}] Constraint {c.name!r} (kind={c.kind.value}, "
                    f"strength={c.strength.value})"
                )

        if violated:
            paragraphs.append(
                "\nViolated constraints:\n" + "\n".join(violated)
            )

        paragraphs.append(
            "\nTo repair these violations, consider applying one or more of the "
            "repair strategies listed in REPAIR_STRATEGIES_REGISTRY.  The "
            "suggest_repair() method can generate specific repair candidates "
            "tailored to each violated constraint."
        )

        return "\n".join(paragraphs)

    # ------------------------------------------------------------------
    # Repair suggestion
    # ------------------------------------------------------------------

    def suggest_repair(
        self,
        model: dict[str, str],
        violated_constraint: TextConstraint,
    ) -> list[str]:
        """Return 3–5 specific repair suggestions for a violated constraint.

        The suggestions are string descriptions of concrete actions the
        developer can take to bring a string value into compliance with
        the constraint.

        Parameters
        ----------
        model:
            The countermodel containing the violating assignment.
        violated_constraint:
            The specific constraint that is violated.
        """
        suggestions: list[str] = []
        vtype = self.classify_violation(model, violated_constraint)
        formula = violated_constraint.formula_str
        observed = next(iter(model.values()), "")

        if vtype == ViolationType.LENGTH_TOO_SHORT:
            min_len_m = re.search(r"\(>\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
            needed = int(min_len_m.group(1)) + 1 if min_len_m else 1
            suggestions.append(
                f"Extend the string to at least {needed} characters, "
                f"e.g. by appending descriptive words."
            )
            suggestions.append(
                "Consider relaxing the minimum-length bound if the short form is intentional."
            )
        elif vtype == ViolationType.LENGTH_TOO_LONG:
            max_len_m = re.search(r"\(<=\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
            limit = int(max_len_m.group(1)) if max_len_m else 64
            suggestions.append(
                f"Truncate the string to at most {limit} characters."
            )
            suggestions.append("Use an abbreviation for long compound names.")
        elif vtype == ViolationType.CASE_VIOLATION:
            suggestions.append(
                f"Apply snake_case transformation: {re.sub(r'(?<!^)(?=[A-Z])', '_', observed).lower()!r}"
            )
            suggestions.append(
                f"Apply CapWords transformation: {''.join(w.title() for w in re.split(r'[_-]', observed))!r}"
            )
        elif vtype == ViolationType.INVALID_CHARACTERS:
            cleaned = re.sub(r"[^a-zA-Z0-9_]", "_", observed)
            suggestions.append(
                f"Remove or replace invalid characters, e.g. {cleaned!r}."
            )
            suggestions.append("Apply unicodedata.normalize('NFKC', name) to canonicalise Unicode.")
        elif vtype == ViolationType.MISSING_PREFIX:
            suggestions.append("Prepend the required prefix to the string.")
            suggestions.append("Check the prefix requirement in the constraint formula.")
        elif vtype == ViolationType.MISSING_SUFFIX:
            suggestions.append("Append the required suffix to the string.")
        else:
            suggestions.append("Review the constraint formula and adjust the string accordingly.")
            suggestions.append(
                "Use the StringRepairEngine to auto-generate a compliant alternative."
            )

        suggestions.append(
            f"Run verify_repair() with the repaired constraint to confirm satisfiability."
        )
        return suggestions[:5]

    # ------------------------------------------------------------------
    # Repair verification
    # ------------------------------------------------------------------

    def verify_repair(
        self,
        repair: TextConstraint,
        session: Z3Session | None = None,
    ) -> bool:
        """Verify that *repair* is satisfiable (i.e., the repair is valid).

        When a Z3Session is available, the check is delegated to Z3.
        Otherwise a syntactic sanity check is performed: constraints with a
        top-level ``(not (= x x))`` shape are considered unsatisfiable.

        Parameters
        ----------
        repair:
            The repaired constraint to verify.
        session:
            Optional Z3 session for formal checking.
        """
        if session is not None and _Z3_AVAILABLE:
            try:
                outcome = session.check_sat(repair.formula_str)
                sat = outcome in (SolveOutcome.SAT, SolveOutcome.UNKNOWN)
                self._repair_history.append((repair, sat))
                return sat
            except Exception as exc:
                _LOGGER.warning("verify_repair: Z3 error: %s", exc)

        # Heuristic: trivially unsat pattern
        stripped = repair.formula_str.strip()
        is_unsat = stripped == "(false)" or stripped.startswith("(not (= x x))")
        result = not is_unsat
        self._repair_history.append((repair, result))
        return result

    # ------------------------------------------------------------------
    # Witness extraction
    # ------------------------------------------------------------------

    def extract_string_witnesses(
        self, session: Z3Session | None = None
    ) -> dict[str, str]:
        """Extract string variable values from the current Z3 model.

        When a Z3 session with an available model is provided the method
        queries each string variable declared in the session and returns
        its concrete string value.  Without a session, returns an empty dict.

        Parameters
        ----------
        session:
            The Z3 session whose model to query.
        """
        if session is None or not _Z3_AVAILABLE:
            return {}
        try:
            return session.get_string_model()
        except Exception as exc:
            _LOGGER.warning("extract_string_witnesses: failed: %s", exc)
            return {}

    # ------------------------------------------------------------------
    # Minimal countermodel
    # ------------------------------------------------------------------

    def find_minimal_countermodel(
        self,
        constraints: list[TextConstraint],
        session: Z3Session | None = None,
    ) -> dict[str, str] | None:
        """Find the shortest-length string counterexample.

        Uses an iterative length-bounded search: the solver is queried with
        an additional ``(= (str.len x) k)`` constraint for k = 0, 1, 2, …
        up to a maximum of 32.  The first satisfying assignment is returned.

        When Z3 is unavailable, falls back to the heuristic search in
        ``find_countermodel`` and returns its result.

        Parameters
        ----------
        constraints:
            Constraints to violate.
        session:
            Optional Z3 session.
        """
        _LOGGER.debug("find_minimal_countermodel: starting iterative length search")

        if session is None or not _Z3_AVAILABLE:
            return self.find_countermodel(constraints, session)

        for length in range(0, 33):
            length_constraint = TextConstraint(
                name=f"_len_bound_{length}",
                kind=ConstraintKind.LENGTH,
                formula_str=f"(= (str.len x) {length})",
                strength=ConstraintStrength.MANDATORY,
            )
            probe = list(constraints) + [length_constraint]
            result = self.find_countermodel(probe, session)
            if result is not None:
                _LOGGER.debug("find_minimal_countermodel: found at length %d", length)
                return result

        return None

    # ------------------------------------------------------------------
    # Violation classification
    # ------------------------------------------------------------------

    def classify_violation(
        self,
        model: dict[str, str],
        constraint: TextConstraint,
    ) -> ViolationType:
        """Determine the type of violation encoded by *model* for *constraint*.

        Applies a priority-ordered set of pattern checks against the
        constraint formula and the observed values in *model*.

        Parameters
        ----------
        model:
            The countermodel mapping variable names to string values.
        constraint:
            The constraint being violated.
        """
        formula = constraint.formula_str
        observed = next(iter(model.values()), "")

        # Length violations
        min_m = re.search(r"\(>\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
        if min_m and len(observed) <= int(min_m.group(1)):
            return ViolationType.LENGTH_TOO_SHORT

        max_m = re.search(r"\(<=\s*\(str\.len\s+\w+\)\s+(\d+)\)", formula)
        if max_m and len(observed) > int(max_m.group(1)):
            return ViolationType.LENGTH_TOO_LONG

        # Structural violations
        if "str.prefixof" in formula:
            return ViolationType.MISSING_PREFIX
        if "str.suffixof" in formula:
            return ViolationType.MISSING_SUFFIX
        if "str.in_re" in formula or "re." in formula:
            # Determine if it's a case or character issue
            if re.search(r"[A-Z]", observed) and "lower" in formula.lower():
                return ViolationType.CASE_VIOLATION
            if re.search(r"[^a-zA-Z0-9_\s-]", observed):
                return ViolationType.INVALID_CHARACTERS
            return ViolationType.FORBIDDEN_PATTERN

        if constraint.kind == ConstraintKind.NAMING:
            return ViolationType.CASE_VIOLATION
        if constraint.kind == ConstraintKind.DOCUMENTATION:
            return ViolationType.FORMAT_VIOLATION

        return ViolationType.SEMANTIC_VIOLATION

    # ------------------------------------------------------------------
    # Repair generation
    # ------------------------------------------------------------------

    def generate_repair_candidates(
        self,
        model: dict[str, str],
        constraint: TextConstraint,
    ) -> list[TextConstraint]:
        """Generate 3–5 candidate repair constraints for a violation.

        Each candidate is a new TextConstraint that is slightly more
        permissive than the original so that the observed value would
        satisfy it.

        Parameters
        ----------
        model:
            The countermodel containing the violating value.
        constraint:
            The violated constraint to repair.
        """
        observed = next(iter(model.values()), "x")
        candidates: list[TextConstraint] = []
        vtype = self.classify_violation(model, constraint)

        if vtype == ViolationType.LENGTH_TOO_SHORT:
            for min_len in [1, 2, 3]:
                candidates.append(
                    TextConstraint(
                        name=f"{constraint.name}_relax_min_{min_len}",
                        kind=ConstraintKind.LENGTH,
                        formula_str=f"(>= (str.len x) {min_len})",
                        strength=ConstraintStrength.RECOMMENDED,
                    )
                )
        elif vtype == ViolationType.LENGTH_TOO_LONG:
            for extra in [10, 50, 100]:
                candidates.append(
                    TextConstraint(
                        name=f"{constraint.name}_relax_max_plus{extra}",
                        kind=ConstraintKind.LENGTH,
                        formula_str=f"(<= (str.len x) {len(observed) + extra})",
                        strength=ConstraintStrength.RECOMMENDED,
                    )
                )
        else:
            # Generic relaxation candidates
            candidates.append(
                TextConstraint(
                    name=f"{constraint.name}_weakened",
                    kind=constraint.kind,
                    formula_str=f"(or {constraint.formula_str} (= (str.len x) 0))",
                    strength=ConstraintStrength.OPTIONAL,
                )
            )
            candidates.append(
                TextConstraint(
                    name=f"{constraint.name}_ascii_only",
                    kind=ConstraintKind.REGEX,
                    formula_str='(str.in_re x (re.* (re.range "\\x20" "\\x7e")))',
                    strength=ConstraintStrength.RECOMMENDED,
                )
            )
            candidates.append(
                TextConstraint(
                    name=f"{constraint.name}_nonempty",
                    kind=ConstraintKind.LENGTH,
                    formula_str="(> (str.len x) 0)",
                    strength=ConstraintStrength.MANDATORY,
                )
            )

        return candidates[:5]

    def rank_repairs(
        self,
        candidates: list[TextConstraint],
        session: Z3Session | None = None,
    ) -> list[tuple[TextConstraint, float]]:
        """Rank repair candidates by estimated quality.

        Each candidate is scored 0.0–1.0 based on:

        * **Satisfiability** (+0.4): the candidate is verified satisfiable.
        * **Strength** (+0.3): MANDATORY > RECOMMENDED > OPTIONAL.
        * **Simplicity** (+0.3): shorter formula strings score higher.

        The list is returned sorted in descending score order.

        Parameters
        ----------
        candidates:
            The repair constraints to rank.
        session:
            Optional Z3 session for satisfiability checking.
        """
        strength_scores = {
            ConstraintStrength.MANDATORY: 0.3,
            ConstraintStrength.RECOMMENDED: 0.2,
            ConstraintStrength.OPTIONAL: 0.1,
        }
        ranked: list[tuple[TextConstraint, float]] = []
        for c in candidates:
            score = 0.0
            # Satisfiability component
            if session is not None and _Z3_AVAILABLE:
                try:
                    outcome = session.check_sat(c.formula_str)
                    if outcome == SolveOutcome.SAT:
                        score += 0.4
                    elif outcome == SolveOutcome.UNKNOWN:
                        score += 0.2
                except Exception:
                    score += 0.1
            else:
                # Heuristic: assume satisfiable unless trivially unsat
                if "(not (= x x))" not in c.formula_str:
                    score += 0.35

            # Strength component
            score += strength_scores.get(c.strength, 0.1)

            # Simplicity component: shorter formula = higher score (max 0.3)
            max_len = 200
            simplicity = max(0.0, 1.0 - len(c.formula_str) / max_len) * 0.3
            score += simplicity

            ranked.append((c, min(1.0, round(score, 3))))

        return sorted(ranked, key=lambda t: t[1], reverse=True)

    def explain_violation(
        self,
        model: dict[str, str],
        constraint: TextConstraint,
    ) -> str:
        """Produce a detailed multi-paragraph explanation of a violation.

        The explanation covers: what value was found, which constraint was
        violated, why it is a violation, and what can be done about it.

        Parameters
        ----------
        model:
            The countermodel.
        constraint:
            The violated constraint.
        """
        vtype = self.classify_violation(model, constraint)
        observed = next(iter(model.values()), "<unknown>")
        var = next(iter(model.keys()), "x")
        severity_desc = SEVERITY_DESCRIPTIONS.get(3, "Moderate")

        explanation_parts: list[str] = [
            f"=== Violation Explanation for constraint {constraint.name!r} ===\n",
            f"Variable: {var!r}",
            f"Observed value: {observed!r} (length={len(observed)})",
            f"Violated constraint: {constraint.name!r}",
            f"  Kind: {constraint.kind.value}",
            f"  Strength: {constraint.strength.value}",
            f"  Formula: {constraint.formula_str}\n",
            f"Violation type: {vtype.value}",
            f"Severity: 3/5 — {severity_desc}\n",
        ]

        # Type-specific explanation
        if vtype == ViolationType.LENGTH_TOO_SHORT:
            explanation_parts.append(
                f"The string {observed!r} is too short.  The constraint requires a "
                f"minimum length that the observed value does not satisfy.  "
                f"Extend the string by appending meaningful characters."
            )
        elif vtype == ViolationType.LENGTH_TOO_LONG:
            explanation_parts.append(
                f"The string {observed!r} exceeds the maximum permitted length.  "
                f"The constraint imposes an upper bound that has been surpassed.  "
                f"Shorten the string or relax the upper-length bound."
            )
        elif vtype == ViolationType.CASE_VIOLATION:
            explanation_parts.append(
                f"The string {observed!r} does not conform to the required case convention.  "
                f"Check whether snake_case, CapWords, or SCREAMING_SNAKE is expected and "
                f"apply the appropriate transformation."
            )
        elif vtype == ViolationType.INVALID_CHARACTERS:
            bad_chars = set(re.findall(r"[^a-zA-Z0-9_\s]", observed))
            explanation_parts.append(
                f"The string {observed!r} contains characters that are not permitted: "
                f"{bad_chars!r}.  Remove or replace these characters with underscores "
                f"or appropriate ASCII equivalents."
            )
        elif vtype == ViolationType.MISSING_PREFIX:
            explanation_parts.append(
                f"The constraint requires a specific prefix that is absent from {observed!r}.  "
                f"Prepend the required prefix as specified in the constraint formula."
            )
        elif vtype == ViolationType.MISSING_SUFFIX:
            explanation_parts.append(
                f"The constraint requires a specific suffix that is absent from {observed!r}.  "
                f"Append the required suffix as specified in the constraint formula."
            )
        else:
            explanation_parts.append(
                f"The string {observed!r} violates the constraint in a way that requires "
                f"manual inspection.  Review the formula {constraint.formula_str!r} and "
                f"adjust the string accordingly."
            )

        suggestions = self.suggest_repair(model, constraint)
        explanation_parts.append("\nRepair suggestions:")
        for i, s in enumerate(suggestions, 1):
            explanation_parts.append(f"  {i}. {s}")

        return "\n".join(explanation_parts)


