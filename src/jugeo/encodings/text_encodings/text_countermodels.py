@dataclass(slots=True)
class ConstraintViolation:
    """Records a single constraint violation together with repair metadata.

    Attributes
    ----------
    variable_name:
        The symbolic variable whose value violates the constraint.
    constraint:
        The TextConstraint that is violated.
    violation_type:
        Categorical classification of the violation.
    observed_value:
        The string value that was found to violate the constraint.
    expected_pattern:
        Optional human-readable description of what value was expected.
    severity:
        Integer in the range 1–5 indicating how serious the violation is.
    repair_hints:
        A (possibly empty) list of actionable repair suggestion strings.
    """

    variable_name: str
    constraint: TextConstraint
    violation_type: ViolationType
    observed_value: str
    expected_pattern: str = ""
    severity: int = 3
    repair_hints: list[str] = field(default_factory=list)

    def to_message(self) -> str:
        """Return a human-readable description of the violation.

        The message includes the variable name, the observed value, the
        type of violation, and any repair hints that have been registered.
        """
        hints_text = ""
        if self.repair_hints:
            hints_joined = "; ".join(self.repair_hints)
            hints_text = f"  Hints: {hints_joined}"
        return (
            f"Violation [{self.violation_type.value}] on variable {self.variable_name!r}: "
            f"observed {self.observed_value!r}"
            + (f", expected {self.expected_pattern!r}" if self.expected_pattern else "")
            + f" (severity={self.severity})."
            + hints_text
        )

    def to_smt2_witness(self) -> str:
        """Return a minimal SMT-LIB2 string that witnesses the violation.

        The witness declares the variable and asserts its observed value,
        then asserts the negation of the violated constraint, followed by
        ``(check-sat)`` to confirm satisfiability of the witness.
        """
        safe_value = self.observed_value.replace('"', '\\"')
        return (
            f"; SMT-LIB2 witness for violation of {self.constraint.name!r}\n"
            f"(declare-const {self.variable_name} String)\n"
            f'(assert (= {self.variable_name} "{safe_value}"))\n'
            f"(assert (not {self.constraint.formula_str}))\n"
            f"(check-sat)\n"
            f"; Expected: sat (confirming the violation)"
        )

    def summary(self) -> str:
        """Return a single-line summary of the violation.

        Useful for log output or tabular display.
        """
        return (
            f"{self.variable_name}: {self.violation_type.value} "
            f"(severity {self.severity}) — {self.observed_value!r}"
        )


