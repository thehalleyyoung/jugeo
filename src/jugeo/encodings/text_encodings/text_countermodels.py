@dataclass(slots=True)
class StringRepairEngine:
    """Applies named repair strategies to ConstraintViolation objects.

    The engine maintains a log of all repair actions taken in the current
    session, enabling retrospective analysis of which strategies proved
    most effective.

    Attributes
    ----------
    _repair_log:
        Chronological list of human-readable log entries describing each
        repair action.
    max_repair_attempts:
        Maximum number of repair attempts before the engine gives up.
    """

    _repair_log: list[str] = field(default_factory=list)
    max_repair_attempts: int = 10

    REPAIR_STRATEGIES: dict[str, str] = field(
        default_factory=lambda: dict(REPAIR_STRATEGIES_REGISTRY)
    )

    # ------------------------------------------------------------------
    # Strategy dispatch
    # ------------------------------------------------------------------

    def apply_strategy(
        self,
        strategy_name: str,
        violation: ConstraintViolation,
    ) -> TextConstraint | None:
        """Apply the named repair strategy to *violation*.

        Dispatches to the appropriate ``add_prefix_repair``,
        ``add_suffix_repair``, ``relax_constraint``, or other strategy
        implementation.

        Parameters
        ----------
        strategy_name:
            One of the keys in ``REPAIR_STRATEGIES``.
        violation:
            The violation to repair.

        Returns
        -------
        TextConstraint | None
            A new TextConstraint representing the repair, or ``None`` if
            the strategy is not applicable.
        """
        _LOGGER.debug("apply_strategy: %r on %r", strategy_name, violation.variable_name)
        entry = f"[{time.strftime('%H:%M:%S')}] apply_strategy({strategy_name!r}) on {violation.summary()}"
        self._repair_log.append(entry)

        dispatch: dict[str, Callable[[], TextConstraint | None]] = {
            "add_prefix": lambda: self.add_prefix_repair(violation, "_"),
            "add_suffix": lambda: self.add_suffix_repair(violation, "_end"),
            "relax_constraint": lambda: self.relax_constraint(violation.constraint),
            "tighten_constraint": lambda: self.tighten_constraint(violation.constraint),
            "case_transform": lambda: self._case_transform_repair(violation),
            "strip_forbidden": lambda: self._strip_forbidden_repair(violation),
            "truncate": lambda: self._truncate_repair(violation),
            "pad": lambda: self._pad_repair(violation),
        }
        factory = dispatch.get(strategy_name)
        if factory is None:
            _LOGGER.warning("apply_strategy: unknown strategy %r", strategy_name)
            return None
        return factory()

    # ------------------------------------------------------------------
    # Individual strategy implementations
    # ------------------------------------------------------------------

    def add_prefix_repair(
        self, violation: ConstraintViolation, prefix: str
    ) -> TextConstraint:
        """Create a constraint that requires *prefix* to be prepended.

        Parameters
        ----------
        violation:
            The violation context.
        prefix:
            The prefix string to require.
        """
        safe_prefix = prefix.replace('"', '\\"')
        return TextConstraint(
            name=f"{violation.constraint.name}_prefix_{hashlib.md5(prefix.encode()).hexdigest()[:6]}",
            kind=ConstraintKind.PREFIX,
            formula_str=f'(str.prefixof "{safe_prefix}" {violation.variable_name})',
            strength=ConstraintStrength.RECOMMENDED,
        )

    def add_suffix_repair(
        self, violation: ConstraintViolation, suffix: str
    ) -> TextConstraint:
        """Create a constraint that requires *suffix* to be appended.

        Parameters
        ----------
        violation:
            The violation context.
        suffix:
            The suffix string to require.
        """
        safe_suffix = suffix.replace('"', '\\"')
        return TextConstraint(
            name=f"{violation.constraint.name}_suffix_{hashlib.md5(suffix.encode()).hexdigest()[:6]}",
            kind=ConstraintKind.SUFFIX,
            formula_str=f'(str.suffixof "{safe_suffix}" {violation.variable_name})',
            strength=ConstraintStrength.RECOMMENDED,
        )

    def relax_constraint(
        self, constraint: TextConstraint, tolerance: float = 0.1
    ) -> TextConstraint:
        """Return a relaxed version of *constraint* with looser bounds.

        For length constraints, increases the upper bound by
        ``ceil(current_upper * tolerance)`` and decreases the lower bound
        by the same amount (clamped to 0).

        For non-length constraints, wraps the formula in an ``(or ...)``
        with a trivially-true alternative.

        Parameters
        ----------
        constraint:
            The constraint to relax.
        tolerance:
            Fraction by which to widen length bounds.  Default is 0.1.
        """
        formula = constraint.formula_str

        # Try to relax an upper-length bound
        def _relax_upper(m: re.Match) -> str:
            import math
            current = int(m.group(1))
            new_val = current + max(1, math.ceil(current * tolerance))
            return m.group(0).replace(str(current), str(new_val), 1)

        new_formula = re.sub(
            r"\(<=\s*\(str\.len\s+\w+\)\s+(\d+)\)", _relax_upper, formula
        )

        if new_formula == formula:
            # Wrap with a trivial OR to create a logically weaker formula
            new_formula = f"(or {formula} (= (str.len {constraint.name}) 0))"

        return TextConstraint(
            name=f"{constraint.name}_relaxed",
            kind=constraint.kind,
            formula_str=new_formula,
            strength=ConstraintStrength.OPTIONAL,
        )

    def tighten_constraint(self, constraint: TextConstraint) -> TextConstraint:
        """Return a tightened version of *constraint* with stricter bounds.

        For length constraints, decreases the upper bound by 10% and
        increases the lower bound by 1.  For non-length constraints,
        wraps the formula in an ``(and ...)`` with the original formula
        and an additional non-empty check.

        Parameters
        ----------
        constraint:
            The constraint to tighten.
        """
        formula = constraint.formula_str

        def _tighten_upper(m: re.Match) -> str:
            import math
            current = int(m.group(1))
            new_val = max(1, current - max(1, math.ceil(current * 0.1)))
            return m.group(0).replace(str(current), str(new_val), 1)

        new_formula = re.sub(
            r"\(<=\s*\(str\.len\s+\w+\)\s+(\d+)\)", _tighten_upper, formula
        )

        if new_formula == formula:
            new_formula = f"(and {formula} (> (str.len x) 0))"

        return TextConstraint(
            name=f"{constraint.name}_tightened",
            kind=constraint.kind,
            formula_str=new_formula,
            strength=ConstraintStrength.MANDATORY,
        )

    def compose_repairs(
        self, repairs: list[TextConstraint]
    ) -> list[TextConstraint]:
        """Return a de-duplicated, composed list of repair constraints.

        Duplicate detection is by constraint name; only the first occurrence
        of each name is retained.

        Parameters
        ----------
        repairs:
            The list of repair constraints to compose.
        """
        seen: set[str] = set()
        composed: list[TextConstraint] = []
        for r in repairs:
            if r.name not in seen:
                seen.add(r.name)
                composed.append(r)
        self._repair_log.append(
            f"compose_repairs: {len(repairs)} → {len(composed)} after deduplication"
        )
        return composed

    def verify_all_repairs(
        self,
        repairs: list[TextConstraint],
        session: Z3Session | None = None,
    ) -> dict[int, bool]:
        """Verify each repair constraint, returning a pass/fail dict.

        Keys are integer indices into *repairs*; values are booleans
        indicating whether the repair was found to be satisfiable.

        Parameters
        ----------
        repairs:
            Repair constraints to verify.
        session:
            Optional Z3 session for formal checking.
        """
        results: dict[int, bool] = {}
        for i, repair in enumerate(repairs):
            if session is not None and _Z3_AVAILABLE:
                try:
                    outcome = session.check_sat(repair.formula_str)
                    results[i] = outcome in (SolveOutcome.SAT, SolveOutcome.UNKNOWN)
                    continue
                except Exception as exc:
                    _LOGGER.warning("verify_all_repairs[%d]: Z3 error: %s", i, exc)
            # Heuristic fallback
            stripped = repair.formula_str.strip()
            results[i] = stripped != "(false)" and "(not (= x x))" not in stripped
        return results

    def repair_naming_violation(
        self, name: str, law: NamingLaw
    ) -> str | None:
        """Attempt to repair a naming violation by transforming *name*.

        Tries a sequence of normalisation transforms until the result
        satisfies *law*.  Returns the repaired string or ``None`` if no
        transform succeeds within the attempt budget.

        Parameters
        ----------
        name:
            The offending identifier.
        law:
            The NamingLaw that *name* violates.
        """
        transforms: list[Callable[[str], str]] = [
            str.lower,
            str.upper,
            lambda s: re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower(),  # to snake_case
            lambda s: "".join(w.title() for w in re.split(r"[_\s-]", s)),  # to CapWords
            lambda s: re.sub(r"[^a-zA-Z0-9_]", "_", s),  # strip invalid chars
            lambda s: s.lstrip("0123456789"),  # remove leading digits
            lambda s: unicodedata.normalize("NFKC", s),
            lambda s: re.sub(r"_+", "_", s).strip("_"),  # collapse underscores
        ]
        for i, transform in enumerate(transforms[: self.max_repair_attempts]):
            candidate = transform(name)
            try:
                if re.fullmatch(law.pattern, candidate):
                    self._repair_log.append(
                        f"repair_naming_violation: transform[{i}] fixed {name!r} → {candidate!r}"
                    )
                    return candidate
            except re.error:
                continue
        self._repair_log.append(
            f"repair_naming_violation: all transforms failed for {name!r}"
        )
        return None

    def get_repair_log(self) -> list[str]:
        """Return the full chronological repair log for this session."""
        return list(self._repair_log)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _case_transform_repair(self, violation: ConstraintViolation) -> TextConstraint:
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", violation.observed_value).lower()
        safe_val = snake.replace('"', '\\"')
        return TextConstraint(
            name=f"{violation.constraint.name}_case_fixed",
            kind=ConstraintKind.NAMING,
            formula_str=f'(= {violation.variable_name} "{safe_val}")',
            strength=ConstraintStrength.RECOMMENDED,
        )

    def _strip_forbidden_repair(self, violation: ConstraintViolation) -> TextConstraint:
        cleaned = re.sub(r"[^a-zA-Z0-9_]", "_", violation.observed_value)
        safe_val = cleaned.replace('"', '\\"')
        return TextConstraint(
            name=f"{violation.constraint.name}_stripped",
            kind=ConstraintKind.REGEX,
            formula_str=f'(= {violation.variable_name} "{safe_val}")',
            strength=ConstraintStrength.RECOMMENDED,
        )

    def _truncate_repair(self, violation: ConstraintViolation) -> TextConstraint:
        return TextConstraint(
            name=f"{violation.constraint.name}_truncate",
            kind=ConstraintKind.LENGTH,
            formula_str=f"(<= (str.len {violation.variable_name}) 64)",
            strength=ConstraintStrength.MANDATORY,
        )

    def _pad_repair(self, violation: ConstraintViolation) -> TextConstraint:
        return TextConstraint(
            name=f"{violation.constraint.name}_pad",
            kind=ConstraintKind.LENGTH,
            formula_str=f"(>= (str.len {violation.variable_name}) 1)",
            strength=ConstraintStrength.MANDATORY,
        )


