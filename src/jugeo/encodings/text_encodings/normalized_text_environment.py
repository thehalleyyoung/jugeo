"""
normalized_text_environment — Canonical text encoding with Unicode normalization.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch28: Exact Z3 encodings III: strings, symbolic text, naming laws,
documentation shadows.

Part of the JuGeo judgment-geometry framework.

This module implements the NormalizedTextEnvironment and its builder, providing
a canonical environment for encoding Python strings into Z3 string constraints
after Unicode NFC normalization.

Key insight (Ch28 §2): two Python strings that are Unicode-equivalent (same
sequence of characters after NFC normalization) should map to the same Z3
encoding.  The NormalizedTextEnvironment enforces this invariant by normalizing
all strings before encoding, ensuring that constraint systems built from
equivalent strings are identical.

The copilot encoding pipeline uses NFC as the default normalization form because:
  1. NFC is the most common normalization form used in Python source code.
  2. Python's str comparison is NFC-compatible for most practical strings.
  3. NFC is idempotent: applying NFC twice is the same as applying it once.
"""
