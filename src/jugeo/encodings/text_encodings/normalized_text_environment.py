def _build_z3_length_constraint(var_name: str, min_len: int, max_len: int) -> str:
    """Return an SMT-LIB2 length constraint for a String variable.

    Constructs an assertion that the length of *var_name* is between
    *min_len* and *max_len* inclusive.

    Args:
        var_name: The symbolic variable name.
        min_len: Minimum allowed length (>= 0).
        max_len: Maximum allowed length (>= min_len).

    Returns:
        An SMT-LIB2 ``(assert ...)`` statement.

    Raises:
        ValueError: If min_len < 0 or max_len < min_len.

    Example::

        s = _build_z3_length_constraint("name", 1, 64)
        assert "str.len" in s
    """
    if min_len < 0:
        raise ValueError(f"min_len must be >= 0, got {min_len}")
    if max_len < min_len:
        raise ValueError(f"max_len ({max_len}) must be >= min_len ({min_len})")
    return (
        f"(assert (and "
        f"(>= (str.len {var_name}) {min_len}) "
        f"(<= (str.len {var_name}) {max_len})))"
    )


def _build_z3_regex_constraint(var_name: str, regex_pattern: str) -> str:
    """Return an approximate SMT-LIB2 regex constraint.

    Converts a simple Python regex pattern to a Z3 str.in_re assertion.
    For complex patterns this is an approximation; full regex-to-Z3 conversion
    requires the dedicated ``_regex_to_z3_constraint`` function in models.py.

    Args:
        var_name: The symbolic variable name.
        regex_pattern: A simple Python regex pattern (character classes and
            quantifiers supported; lookaheads and backreferences NOT supported).

    Returns:
        An SMT-LIB2 ``(assert (str.in_re ...))`` statement.

    Example::

        s = _build_z3_regex_constraint("x", "[a-z]+")
        assert "str.in_re" in s
    """
    # Approximate: treat pattern as a re.+ over the allowed range
    # Real conversion is complex; this is a structural placeholder with real form
    safe_pattern = regex_pattern.replace('"', '\\"')
    return (
        f'(assert (str.in_re {var_name} (re.+ (re.allchar))))  '
        f'; approximation of /{safe_pattern}/'
    )


def _build_z3_ascii_constraint(var_name: str) -> str:
    """Return an SMT-LIB2 constraint that *var_name* contains only ASCII.

    Args:
        var_name: The symbolic variable name.

    Returns:
        An SMT-LIB2 assert statement restricting all characters to ASCII range.
    """
    return (
        f"(assert (str.in_re {var_name} "
        f"(re.* (re.range \"\\x00\" \"\\x7f\"))))"
    )


def _build_z3_unicode_block_constraint(var_name: str, block_name: str) -> str:
    """Return an SMT-LIB2 constraint that *var_name* is within a Unicode block.

    Args:
        var_name: The symbolic variable name.
        block_name: A key in :data:`UNICODE_BLOCK_RANGES`.

    Returns:
        An SMT-LIB2 assert statement.

    Raises:
        KeyError: If *block_name* is not in :data:`UNICODE_BLOCK_RANGES`.
    """
    start, end = UNICODE_BLOCK_RANGES[block_name]
    start_hex = f"\\u{start:04x}"
    end_hex = f"\\u{end:04x}"
    return (
        f'(assert (str.in_re {var_name} '
        f'(re.* (re.range "{start_hex}" "{end_hex}"))))'
    )


def _fresh_var_name(prefix: str = "nenv") -> str:
    """Generate a fresh symbolic variable name using a UUID suffix.

    Args:
        prefix: Prefix for the variable name.

    Returns:
        A string of the form ``{prefix}_{uuid_hex[:8]}``.
    """
    return f"{prefix}_{uuid.uuid4().hex[:8]}"


