def _normalize_nfc(text: str) -> str:
    """Apply Unicode NFC normalization to *text*.

    NFC (Canonical Decomposition followed by Canonical Composition) is the
    most widely used Unicode normalization form and is the default for the
    jugeo text encoding pipeline.

    Args:
        text: The raw string to normalize.

    Returns:
        The NFC-normalized form of *text*.  If *text* is already NFC, returns
        *text* unchanged (the operation is idempotent).

    Example::

        assert _normalize_nfc("café") == _normalize_nfc("cafe\u0301")
    """
    return unicodedata.normalize("NFC", text)


def _normalize_nfkc(text: str) -> str:
    """Apply Unicode NFKC normalization to *text*.

    NFKC additionally decomposes compatibility characters (e.g., fullwidth
    digits to ASCII digits, ligatures to constituent letters).

    Args:
        text: The raw string to normalize.

    Returns:
        The NFKC-normalized form of *text*.

    Example::

        assert _normalize_nfkc("ＡＢＣ") == "ABC"  # fullwidth → ASCII
    """
    return unicodedata.normalize("NFKC", text)


def _normalize_nfd(text: str) -> str:
    """Apply Unicode NFD normalization to *text*.

    NFD (Canonical Decomposition) decomposes composed characters into their
    canonical base character plus combining marks.

    Args:
        text: The raw string to normalize.

    Returns:
        The NFD-normalized form of *text*.
    """
    return unicodedata.normalize("NFD", text)


def _is_in_unicode_block(char: str, block_name: str) -> bool:
    """Check whether *char* falls within the named Unicode block.

    Args:
        char: A single character (len == 1).
        block_name: A key in :data:`UNICODE_BLOCK_RANGES`.

    Returns:
        ``True`` if the code point of *char* is within the block range,
        ``False`` otherwise.

    Raises:
        KeyError: If *block_name* is not in :data:`UNICODE_BLOCK_RANGES`.
        ValueError: If *char* is not a single character.

    Example::

        assert _is_in_unicode_block("A", "Basic Latin") is True
        assert _is_in_unicode_block("α", "Greek and Coptic") is True
    """
    if len(char) != 1:
        raise ValueError(f"Expected a single character, got {len(char)}-char string: {char!r}")
    start, end = UNICODE_BLOCK_RANGES[block_name]
    cp = ord(char)
    return start <= cp <= end


