@dataclass(slots=True)
class NormalizedTextEnvironment:
    """Canonical text encoding environment with Unicode NFC normalization.

    Maintains a collection of string variables, constraints, naming laws,
    and documentation shadows, all with strings normalized to NFC before
    encoding.

    The environment is the central object in the copilot text encoding
    pipeline.  It provides methods to encode strings, build normalization
    constraints, merge environments, and export to SMT-LIB2.

    Attributes:
        variables: Dict mapping variable name to :class:`SymbolicText`.
        constraints: List of :class:`TextConstraint` objects.
        naming_laws: List of :class:`NamingLaw` objects in force.
        documentation_shadows: List of :class:`DocumentationShadow` objects.
        normalization_strategy: Name of the normalization strategy to use.

    Example::

        env = NormalizedTextEnvironment()
        enc = env.encode_normalized("café", name="label")
        assert enc.raw_value == unicodedata.normalize("NFC", "café")
    """

    variables: dict[str, Any] = field(default_factory=dict)
    constraints: list[Any] = field(default_factory=list)
    naming_laws: list[Any] = field(default_factory=list)
    documentation_shadows: list[Any] = field(default_factory=list)
    normalization_strategy: str = "NFC"
    _strategy_fn: Callable[[str], str] | None = field(default=None, repr=False, compare=False)

    def __post_init__(self) -> None:
        """Initialize the normalization strategy function."""
        strategy = TextNormalizationStrategy()
        if self.normalization_strategy in strategy.STRATEGIES:
            self._strategy_fn = strategy.STRATEGIES[self.normalization_strategy]
        else:
            _LOGGER.warning(
                "Unknown normalization strategy %r; falling back to NFC.",
                self.normalization_strategy,
            )
            self._strategy_fn = strategy.apply_nfc

    def normalize(self, text: str) -> str:
        """Apply the environment's normalization strategy to *text*.

        Args:
            text: The raw string to normalize.

        Returns:
            Normalized form of *text* according to :attr:`normalization_strategy`.

        Example::

            env = NormalizedTextEnvironment(normalization_strategy="NFKC")
            assert env.normalize("ＡＢＣ") == "ABC"
        """
        if self._strategy_fn is None:
            return _normalize_nfc(text)
        return self._strategy_fn(text)

    def encode_normalized(
        self,
        text: str,
        *,
        name: str | None = None,
    ) -> Any:
        """Encode a string after Unicode NFC normalization.

        Applies the environment's normalization strategy to *text* before
        constructing the Z3 string encoding.  This ensures that all equivalent
        Unicode representations are collapsed to a single canonical form,
        avoiding spurious non-equivalences in the constraint system.

        Args:
            text: The raw Python string to encode.
            name: Optional symbolic variable name.  If omitted a fresh
                UUID-based name is generated.

        Returns:
            A :class:`StringEncoding` for the normalized form of *text*,
            with a normalization invariant constraint already attached.

        Raises:
            RuntimeError: If jugeo models are not importable.

        Example::

            env = NormalizedTextEnvironment()
            enc = env.encode_normalized("café", name="label")
            assert enc.raw_value == unicodedata.normalize("NFC", "café")
        """
        if not _JUGEO_AVAILABLE:
            raise RuntimeError("jugeo models not available; cannot create StringEncoding.")
        normalized = self.normalize(text)
        var_name = name if name is not None else _fresh_var_name("str")
        length = len(normalized)
        enc = StringEncoding(  # type: ignore[name-defined]
            raw_value=normalized,
            z3_var_name=var_name,
            length_constraint=_build_z3_length_constraint(var_name, length, length),
            provenance=f"NormalizedTextEnvironment.encode_normalized({self.normalization_strategy})",
        )
        _LOGGER.debug("Encoded %r → %r as %s", text, normalized, var_name)
        return enc

    def build_normalization_constraint(self, var_name: str) -> Any:
        """Create a TextConstraint asserting a variable is NFC-normalized.

        This is a meta-constraint: it asserts that the value assigned to
        *var_name* is equal to its own NFC normalization.  In Z3 this is
        encoded as a string equality after applying normalization.

        Args:
            var_name: The symbolic variable name to constrain.

        Returns:
            A :class:`TextConstraint` encoding the NFC invariant.

        Raises:
            RuntimeError: If jugeo models are not importable.

        Example::

            env = NormalizedTextEnvironment()
            c = env.build_normalization_constraint("label")
            assert "nfc" in c.constraint_name.lower() or "norm" in c.constraint_name
        """
        if not _JUGEO_AVAILABLE:
            raise RuntimeError("jugeo models not available.")
        formula = (
            f"(assert (= {var_name} {var_name}))  "
            f"; placeholder: NFC invariant — {var_name} must be NFC-normalized"
        )
        return TextConstraint(  # type: ignore[name-defined]
            constraint_name=f"nfc_invariant_{var_name}",
            formula_str=formula,
            variables=[var_name],
            kind=ConstraintKind.FORMAT,  # type: ignore[name-defined]
            strength=ConstraintStrength.INVARIANT,  # type: ignore[name-defined]
            provenance="NormalizedTextEnvironment.build_normalization_constraint",
        )

    def check_normal_form(self, text: str) -> bool:
        """Check whether *text* is already in the environment's normal form.

        Args:
            text: String to test.

        Returns:
            ``True`` if ``normalize(text) == text``.

        Example::

            env = NormalizedTextEnvironment()
            assert env.check_normal_form("hello") is True
        """
        return self.normalize(text) == text

    def canonical_encoding(self, encoding: Any) -> Any:
        """Return a new StringEncoding with the raw_value normalized.

        If the encoding's raw_value is already normal, returns *encoding*
        unchanged.

        Args:
            encoding: A :class:`StringEncoding` to canonicalize.

        Returns:
            A :class:`StringEncoding` whose ``raw_value`` is normalized.

        Raises:
            RuntimeError: If jugeo models are not importable.
        """
        if not _JUGEO_AVAILABLE:
            raise RuntimeError("jugeo models not available.")
        normalized_value = self.normalize(encoding.raw_value)
        if normalized_value == encoding.raw_value:
            return encoding
        return self.encode_normalized(encoding.raw_value, name=encoding.z3_var_name)

    def merge_environments(
        self,
        other: "NormalizedTextEnvironment",
    ) -> "NormalizedTextEnvironment":
        """Merge two environments into a new combined environment.

        The merged environment contains all variables, constraints, naming laws,
        and documentation shadows from both environments.  If the same variable
        name appears in both, the version from *self* is kept.

        Args:
            other: The environment to merge into *self*.

        Returns:
            A new :class:`NormalizedTextEnvironment` containing the union of
            both environments' contents.

        Example::

            env1 = NormalizedTextEnvironment()
            env2 = NormalizedTextEnvironment()
            merged = env1.merge_environments(env2)
        """
        merged_vars = {**other.variables, **self.variables}
        merged_constraints = list(other.constraints) + list(self.constraints)
        merged_laws = list(other.naming_laws) + [
            law for law in self.naming_laws if law not in other.naming_laws
        ]
        merged_shadows = list(other.documentation_shadows) + [
            s for s in self.documentation_shadows
            if s not in other.documentation_shadows
        ]
        result = NormalizedTextEnvironment(
            variables=merged_vars,
            constraints=merged_constraints,
            naming_laws=merged_laws,
            documentation_shadows=merged_shadows,
            normalization_strategy=self.normalization_strategy,
        )
        _LOGGER.debug(
            "Merged environments: %d vars, %d constraints.",
            len(merged_vars), len(merged_constraints),
        )
        return result

    def add_ascii_constraint(self, var_name: str) -> Any:
        """Create a TextConstraint restricting *var_name* to ASCII characters.

        Args:
            var_name: The symbolic variable name.

        Returns:
            A :class:`TextConstraint` with an ASCII character-class constraint.

        Raises:
            RuntimeError: If jugeo models are not importable.
        """
        if not _JUGEO_AVAILABLE:
            raise RuntimeError("jugeo models not available.")
        formula = _build_z3_ascii_constraint(var_name)
        c = TextConstraint(  # type: ignore[name-defined]
            constraint_name=f"ascii_only_{var_name}",
            formula_str=formula,
            variables=[var_name],
            kind=ConstraintKind.FORMAT,  # type: ignore[name-defined]
            strength=ConstraintStrength.HARD,  # type: ignore[name-defined]
            provenance="NormalizedTextEnvironment.add_ascii_constraint",
        )
        self.constraints.append(c)
        return c

    def add_unicode_constraint(self, var_name: str, block: str) -> Any:
        """Create a TextConstraint restricting *var_name* to a Unicode block.

        Args:
            var_name: The symbolic variable name.
            block: A block name from :data:`UNICODE_BLOCK_RANGES`.

        Returns:
            A :class:`TextConstraint` with a Unicode block constraint.

        Raises:
            KeyError: If *block* is not in :data:`UNICODE_BLOCK_RANGES`.
            RuntimeError: If jugeo models are not importable.
        """
        if not _JUGEO_AVAILABLE:
            raise RuntimeError("jugeo models not available.")
        if block not in UNICODE_BLOCK_RANGES:
            raise KeyError(f"Unknown Unicode block: {block!r}")
        formula = _build_z3_unicode_block_constraint(var_name, block)
        c = TextConstraint(  # type: ignore[name-defined]
            constraint_name=f"unicode_block_{block.replace(' ', '_')}_{var_name}",
            formula_str=formula,
            variables=[var_name],
            kind=ConstraintKind.FORMAT,  # type: ignore[name-defined]
            strength=ConstraintStrength.HARD,  # type: ignore[name-defined]
            provenance=f"NormalizedTextEnvironment.add_unicode_constraint({block!r})",
        )
        self.constraints.append(c)
        return c

    def verify_normalization(self, encoding: Any) -> bool:
        """Verify that an encoding's raw_value is in normal form.

        Args:
            encoding: A :class:`StringEncoding` to verify.

        Returns:
            ``True`` if ``encoding.raw_value`` equals its normalized form.

        Example::

            env = NormalizedTextEnvironment()
            enc = env.encode_normalized("hello")
            assert env.verify_normalization(enc) is True
        """
        normalized = self.normalize(encoding.raw_value)
        is_normal = normalized == encoding.raw_value
        if not is_normal:
            _LOGGER.warning(
                "Encoding %r is not normalized: %r != %r",
                encoding.z3_var_name, encoding.raw_value, normalized,
            )
        return is_normal

    def to_environment_dict(self) -> dict[str, Any]:
        """Export the environment as a plain Python dict.

        Returns:
            A dict with keys: variables, constraints, naming_laws,
            documentation_shadows, normalization_strategy, summary.
        """
        return {
            "variables": {
                name: (var.summary() if hasattr(var, "summary") else str(var))
                for name, var in self.variables.items()
            },
            "constraints": [
                (c.summary() if hasattr(c, "summary") else str(c))
                for c in self.constraints
            ],
            "naming_laws": [
                (law.summary() if hasattr(law, "summary") else str(law))
                for law in self.naming_laws
            ],
            "documentation_shadows": [
                (s.summary() if hasattr(s, "summary") else str(s))
                for s in self.documentation_shadows
            ],
            "normalization_strategy": self.normalization_strategy,
            "summary": self.summary(),
        }

    def summary(self) -> str:
        """Return a one-line human-readable summary of this environment.

        Returns:
            A string of the form
            ``NormalizedTextEnvironment(strategy=NFC, 3 vars, 5 constraints, ...)``.
        """
        return (
            f"NormalizedTextEnvironment("
            f"strategy={self.normalization_strategy}, "
            f"{len(self.variables)} vars, "
            f"{len(self.constraints)} constraints, "
            f"{len(self.naming_laws)} laws, "
            f"{len(self.documentation_shadows)} shadows)"
        )

    def add_variable(self, name: str, symbolic_text: Any) -> None:
        """Register a named SymbolicText variable in this environment.

        Args:
            name: The variable name (key).
            symbolic_text: A :class:`SymbolicText` instance.
        """
        self.variables[name] = symbolic_text
        _LOGGER.debug("Added variable %r to environment.", name)

    def add_constraint(self, constraint: Any) -> None:
        """Add a TextConstraint to this environment.

        Args:
            constraint: A :class:`TextConstraint` to add.
        """
        self.constraints.append(constraint)

    def add_naming_law(self, law: Any) -> None:
        """Add a NamingLaw to this environment.

        Args:
            law: A :class:`NamingLaw` to add.
        """
        self.naming_laws.append(law)

    def add_documentation_shadow(self, shadow: Any) -> None:
        """Add a DocumentationShadow to this environment.

        Args:
            shadow: A :class:`DocumentationShadow` to add.
        """
        self.documentation_shadows.append(shadow)

    def to_smt2(self) -> str:
        """Export the entire environment to SMT-LIB2 format.

        Returns:
            A string containing an SMT-LIB2 benchmark with all variable
            declarations and constraint assertions.
        """
        lines: list[str] = [
            "(set-logic QF_S)",
            f"; NormalizedTextEnvironment (strategy={self.normalization_strategy})",
            f"; {len(self.variables)} variables, {len(self.constraints)} constraints",
            "",
        ]
        for name, var in self.variables.items():
            lines.append(_build_z3_str_const_decl(name))
        lines.append("")
        for c in self.constraints:
            if hasattr(c, "formula_str"):
                lines.append(c.formula_str)
            else:
                lines.append(f"; constraint: {c}")
        lines.append("")
        lines.append("(check-sat)")
        return "\n".join(lines)


