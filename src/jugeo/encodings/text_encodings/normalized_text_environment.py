@dataclass(slots=True)
class EncodingEnvironmentBuilder:
    """Builder for :class:`NormalizedTextEnvironment`.

    Provides a fluent interface for constructing environments with variables,
    constraints, naming laws, and documentation shadows.

    Example::

        env = (
            EncodingEnvironmentBuilder()
            .add_variable("func_name", "String")
            .set_normalization("NFC")
            .build()
        )
    """

    _variables: dict[str, str] = field(default_factory=dict)
    _constraints: list[Any] = field(default_factory=list)
    _naming_laws: list[Any] = field(default_factory=list)
    _doc_shadows: list[Any] = field(default_factory=list)
    _normalization_strategy: str = "NFC"

    def add_variable(
        self,
        name: str,
        sort: str = "String",
    ) -> "EncodingEnvironmentBuilder":
        """Add a string variable declaration to the environment under construction.

        Args:
            name: The symbolic variable name.
            sort: The SMT-LIB2 sort name (default ``"String"``).

        Returns:
            *self* for method chaining.

        Example::

            builder = EncodingEnvironmentBuilder().add_variable("x", "String")
        """
        self._variables[name] = sort
        return self

    def add_constraint(self, constraint: Any) -> "EncodingEnvironmentBuilder":
        """Add a TextConstraint to the environment under construction.

        Args:
            constraint: A :class:`TextConstraint` instance.

        Returns:
            *self* for method chaining.
        """
        self._constraints.append(constraint)
        return self

    def add_naming_law(self, law: Any) -> "EncodingEnvironmentBuilder":
        """Add a NamingLaw to the environment under construction.

        Args:
            law: A :class:`NamingLaw` instance.

        Returns:
            *self* for method chaining.
        """
        self._naming_laws.append(law)
        return self

    def add_documentation_shadow(self, shadow: Any) -> "EncodingEnvironmentBuilder":
        """Add a DocumentationShadow to the environment under construction.

        Args:
            shadow: A :class:`DocumentationShadow` instance.

        Returns:
            *self* for method chaining.
        """
        self._doc_shadows.append(shadow)
        return self

    def set_normalization(self, strategy: str) -> "EncodingEnvironmentBuilder":
        """Set the normalization strategy for the environment.

        Args:
            strategy: A strategy name (must be in :data:`NORMALIZATION_FORMS`
                or a custom strategy registered in :class:`TextNormalizationStrategy`).

        Returns:
            *self* for method chaining.

        Raises:
            ValueError: If *strategy* is not a recognized normalization form.
        """
        if strategy not in STRATEGY_DESCRIPTIONS:
            _LOGGER.warning(
                "Normalization strategy %r is not in known strategies; proceeding anyway.",
                strategy,
            )
        self._normalization_strategy = strategy
        return self

    def build(self) -> NormalizedTextEnvironment:
        """Build and return the :class:`NormalizedTextEnvironment`.

        Creates :class:`SymbolicText` instances for each variable, then
        assembles the environment.

        Returns:
            A fully constructed :class:`NormalizedTextEnvironment`.

        Raises:
            RuntimeError: If validation errors are present (call :meth:`validate`
                first to see errors without raising).
        """
        errors = self.validate()
        if errors:
            _LOGGER.warning(
                "Building environment despite %d validation error(s): %s",
                len(errors), errors,
            )

        variables: dict[str, Any] = {}
        if _JUGEO_AVAILABLE:
            for name, sort in self._variables.items():
                variables[name] = SymbolicText(  # type: ignore[name-defined]
                    variable_name=name,
                    sort_name=sort,
                )
        else:
            variables = dict(self._variables)

        env = NormalizedTextEnvironment(
            variables=variables,
            constraints=list(self._constraints),
            naming_laws=list(self._naming_laws),
            documentation_shadows=list(self._doc_shadows),
            normalization_strategy=self._normalization_strategy,
        )
        _LOGGER.info("Built environment: %s", env.summary())
        return env

    def validate(self) -> list[str]:
        """Validate the builder state before calling :meth:`build`.

        Returns:
            A list of error messages.  Empty list means the builder is valid.

        Example::

            builder = EncodingEnvironmentBuilder()
            errors = builder.validate()
            assert isinstance(errors, list)
        """
        errors: list[str] = []
        if self._normalization_strategy not in STRATEGY_DESCRIPTIONS:
            errors.append(
                f"Unknown normalization strategy: {self._normalization_strategy!r}.  "
                f"Known: {list(STRATEGY_DESCRIPTIONS.keys())}"
            )
        for name, sort in self._variables.items():
            if not name.isidentifier():
                errors.append(f"Variable name {name!r} is not a valid Python identifier.")
            if sort not in ("String", "Int", "Bool", "Real"):
                errors.append(
                    f"Variable {name!r} has unusual sort {sort!r}; "
                    f"expected 'String' for text encoding variables."
                )
        return errors

    def to_smt2(self) -> str:
        """Export the builder state to SMT-LIB2 format without building.

        Returns:
            An SMT-LIB2 string with all declarations and constraints.
        """
        lines: list[str] = [
            "(set-logic QF_S)",
            f"; EncodingEnvironmentBuilder state (strategy={self._normalization_strategy})",
            "",
        ]
        for name, sort in self._variables.items():
            lines.append(f"(declare-const {name} {sort})")
        lines.append("")
        for c in self._constraints:
            if hasattr(c, "formula_str"):
                lines.append(c.formula_str)
            else:
                lines.append(f"; {c}")
        lines.append("")
        lines.append("(check-sat)")
        return "\n".join(lines)

    def summary(self) -> str:
        """Return a human-readable summary of the builder state.

        Returns:
            A summary string.
        """
        return (
            f"EncodingEnvironmentBuilder("
            f"strategy={self._normalization_strategy}, "
            f"{len(self._variables)} vars, "
            f"{len(self._constraints)} constraints, "
            f"{len(self._naming_laws)} laws, "
            f"{len(self._doc_shadows)} shadows)"
        )


