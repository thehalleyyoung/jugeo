def create_default_environment() -> NormalizedTextEnvironment:
    """Create a default NormalizedTextEnvironment with common setup.

    Returns a minimal environment with NFC normalization and no
    pre-populated variables.  Use :class:`EncodingEnvironmentBuilder` for
    more complex configurations.

    Returns:
        A :class:`NormalizedTextEnvironment` with NFC normalization.

    Example::

        env = create_default_environment()
        assert env.normalization_strategy == "NFC"
    """
    env = NormalizedTextEnvironment(normalization_strategy="NFC")
    _LOGGER.info("Created default NormalizedTextEnvironment.")
    return env


def create_python_identifier_environment() -> NormalizedTextEnvironment:
    """Create an environment tuned for Python identifier encoding.

    Configures NFC normalization and registers the standard Python identifier
    naming law if jugeo models are available.

    Returns:
        A :class:`NormalizedTextEnvironment` suitable for identifier encoding.

    Example::

        env = create_python_identifier_environment()
        enc = env.encode_normalized("compute_support")
        assert enc.raw_value == "compute_support"
    """
    builder = EncodingEnvironmentBuilder().set_normalization("NFC")

    if _JUGEO_AVAILABLE:
        try:
            python_law = NamingLaw(  # type: ignore[name-defined]
                law_name="python_identifier",
                pattern=IDENTIFIER_PATTERN,  # type: ignore[name-defined]
                min_length=1,
                max_length=128,
            )
            builder.add_naming_law(python_law)
        except Exception as exc:
            _LOGGER.debug("Could not add python_identifier law: %s", exc)

    env = builder.build()
    _LOGGER.info("Created Python identifier NormalizedTextEnvironment.")
    return env


def create_documentation_environment() -> NormalizedTextEnvironment:
    """Create an environment tuned for documentation string encoding.

    Configures NFC normalization and registers common documentation constraints.

    Returns:
        A :class:`NormalizedTextEnvironment` suitable for docstring encoding.
    """
    builder = (
        EncodingEnvironmentBuilder()
        .set_normalization("NFC")
    )

    if _JUGEO_AVAILABLE:
        try:
            # Add a length constraint on the "doc" variable if added
            length_constraint = TextConstraint(  # type: ignore[name-defined]
                constraint_name="doc_non_empty",
                formula_str="(assert (>= (str.len doc) 10))",
                variables=["doc"],
                kind=ConstraintKind.LENGTH,  # type: ignore[name-defined]
                strength=ConstraintStrength.SOFT,  # type: ignore[name-defined]
                provenance="create_documentation_environment",
            )
            builder.add_constraint(length_constraint)
        except Exception as exc:
            _LOGGER.debug("Could not add documentation constraint: %s", exc)

    return builder.build()
