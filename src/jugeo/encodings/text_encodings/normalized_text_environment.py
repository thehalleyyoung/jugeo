class TextNormalizationStrategy:
    """Strategy for normalizing text before Z3 string encoding.

    Provides a collection of named normalization strategies that can be
    applied individually or composed.  The strategy is selected based on
    the intended use of the string (identifier vs. documentation vs. raw data).

    Class attribute :attr:`STRATEGIES` maps strategy names to callables.

    Example::

        strategy = TextNormalizationStrategy()
        normalized = strategy.apply_nfc("café")
        assert strategy.check_idempotent("NFC", "café")
    """

    STRATEGIES: dict[str, Callable[[str], str]] = {}

    def __init__(self) -> None:
        """Initialise the strategy registry."""
        self.STRATEGIES = {
            "NFC": self.apply_nfc,
            "NFKC": self.apply_nfkc,
            "NFD": self.apply_nfd,
            "casefold": self.apply_casefold,
            "strip": self.apply_strip,
            "lower": self.apply_lower,
            "nfc_strip": self.apply_nfc_strip,
            "nfkc_casefold": self.apply_nfkc_casefold,
            "ascii_only": self.apply_ascii_only,
            "identifier_safe": self.apply_identifier_safe,
        }

    def apply_nfc(self, text: str) -> str:
        """Apply Unicode NFC normalization.

        Args:
            text: Input string.

        Returns:
            NFC-normalized form of *text*.

        Example::

            s = TextNormalizationStrategy()
            assert s.apply_nfc("café") == s.apply_nfc("cafe\u0301")
        """
        return _normalize_nfc(text)

    def apply_nfkc(self, text: str) -> str:
        """Apply Unicode NFKC normalization.

        NFKC folds compatibility characters (fullwidth digits, ligatures) to
        their ASCII equivalents.

        Args:
            text: Input string.

        Returns:
            NFKC-normalized form of *text*.
        """
        return _normalize_nfkc(text)

    def apply_nfd(self, text: str) -> str:
        """Apply Unicode NFD normalization (canonical decomposition).

        Args:
            text: Input string.

        Returns:
            NFD-normalized form of *text*.
        """
        return _normalize_nfd(text)

    def apply_casefold(self, text: str) -> str:
        """Apply case folding for case-insensitive normalization.

        Uses Python's ``str.casefold()`` which is more aggressive than
        ``str.lower()`` for Unicode strings.

        Args:
            text: Input string.

        Returns:
            Case-folded string.
        """
        return text.casefold()

    def apply_strip(self, text: str) -> str:
        """Strip leading and trailing whitespace.

        Args:
            text: Input string.

        Returns:
            String with leading/trailing whitespace removed.
        """
        return text.strip()

    def apply_lower(self, text: str) -> str:
        """Convert to lowercase.

        Args:
            text: Input string.

        Returns:
            Lowercase version of *text*.
        """
        return text.lower()

    def apply_nfc_strip(self, text: str) -> str:
        """Apply NFC normalization then strip whitespace.

        Args:
            text: Input string.

        Returns:
            NFC-normalized, stripped string.
        """
        return _normalize_nfc(text).strip()

    def apply_nfkc_casefold(self, text: str) -> str:
        """Apply NFKC normalization then case fold.

        This is the recommended strategy for case-insensitive identifier
        comparison per Unicode TR#36.

        Args:
            text: Input string.

        Returns:
            NFKC-normalized, case-folded string.
        """
        return _normalize_nfkc(text).casefold()

    def apply_ascii_only(self, text: str) -> str:
        """Remove all non-ASCII characters from *text*.

        Args:
            text: Input string.

        Returns:
            String containing only ASCII characters (code points 0–127).
        """
        return "".join(c for c in text if ord(c) <= 0x7F)

    def apply_identifier_safe(self, text: str) -> str:
        """Apply NFC, strip, and replace non-identifier characters.

        Converts *text* to a form safe for use as a Python identifier:
        NFC normalize, strip, replace spaces with underscores, remove
        remaining non-identifier characters, ensure starts with a letter.

        Args:
            text: Input string.

        Returns:
            A Python-identifier-safe string derived from *text*.
        """
        s = _normalize_nfc(text).strip()
        s = _WHITESPACE_RE.sub("_", s)
        s = _NON_IDENTIFIER_RE.sub("", s)
        s = _LEADING_DIGITS_RE.sub("", s)
        if not s:
            s = "var_" + uuid.uuid4().hex[:4]
        return s

    def compose_strategies(self, strategies: list[str]) -> Callable[[str], str]:
        """Compose a list of named strategies into a single function.

        Applies strategies left-to-right.

        Args:
            strategies: List of strategy names.  Each must be a key in
                :attr:`STRATEGIES`.

        Returns:
            A callable that applies all named strategies in order.

        Raises:
            KeyError: If any name in *strategies* is not registered.

        Example::

            s = TextNormalizationStrategy()
            fn = s.compose_strategies(["NFC", "strip", "lower"])
            assert fn("  CAFÉ  ") == "café"
        """
        fns = [self.STRATEGIES[name] for name in strategies]

        def composed(text: str) -> str:
            result = text
            for fn in fns:
                result = fn(result)
            return result

        return composed

    def best_for_identifiers(self) -> Callable[[str], str]:
        """Return the best normalization strategy for Python identifiers.

        Composes NFC + strip for identifiers.  NFKC would be more aggressive
        but may change the meaning of Unicode identifiers.

        Returns:
            A callable that normalizes a string for use as an identifier.
        """
        return self.compose_strategies(["NFC", "strip"])

    def best_for_documentation(self) -> Callable[[str], str]:
        """Return the best normalization strategy for documentation strings.

        Applies NFC + strip for documentation.  Case folding is NOT applied
        because documentation strings are case-sensitive.

        Returns:
            A callable that normalizes a string for documentation encoding.
        """
        return self.compose_strategies(["NFC", "strip"])

    def list_strategies(self) -> list[str]:
        """List all available normalization strategy names.

        Returns:
            List of strategy names (keys of :attr:`STRATEGIES`).
        """
        return list(self.STRATEGIES.keys())

    def check_idempotent(self, strategy_name: str, text: str) -> bool:
        """Check that applying *strategy_name* twice equals applying it once.

        Args:
            strategy_name: A strategy name from :attr:`STRATEGIES`.
            text: Input string to test.

        Returns:
            ``True`` if the strategy is idempotent on *text*.
        """
        fn = self.STRATEGIES[strategy_name]
        once = fn(text)
        twice = fn(once)
        return once == twice

    def describe(self, strategy_name: str) -> str:
        """Return a human-readable description of a strategy.

        Args:
            strategy_name: A strategy name from :attr:`STRATEGIES`.

        Returns:
            Description string from :data:`STRATEGY_DESCRIPTIONS`, or a
            generic message if not found.
        """
        return STRATEGY_DESCRIPTIONS.get(
            strategy_name,
            f"Custom normalization strategy: {strategy_name!r}."
        )


