class AlgorithmStatus(str, Enum):
    NOT_STARTED = "not_started"
    RUNNING = "running"
    CONVERGED = "converged"
    FAILED = "failed"
    TIMEOUT = "timeout"


@dataclass(slots=True)
class AlgorithmResult:
    """Result returned by a TextEncodingAlgorithm after execution."""

    algorithm_name: str
    status: AlgorithmStatus
    outputs: dict[str, Any] = field(default_factory=dict)
    iterations: int = 0
    elapsed_time: float = 0.0
    error_message: str = ""
    convergence_delta: float = 0.0

    def is_success(self) -> bool:
        """Returns True if the algorithm converged successfully."""
        return self.status == AlgorithmStatus.CONVERGED

    def summary(self) -> str:
        """Returns a human-readable summary of the algorithm result."""
        lines = [
            f"Algorithm: {self.algorithm_name}",
            f"Status: {self.status.value}",
            f"Iterations: {self.iterations}",
            f"Elapsed time: {self.elapsed_time:.4f}s",
            f"Convergence delta: {self.convergence_delta:.2e}",
        ]
        if self.error_message:
            lines.append(f"Error: {self.error_message}")
        if self.outputs:
            lines.append(f"Outputs: {list(self.outputs.keys())}")
        return "\n".join(lines)


class TextEncodingAlgorithm(ABC):
    """Abstract base class for all text encoding algorithms."""

    name: str = "base_algorithm"
    description: str = "Abstract text encoding algorithm."

    def __init__(self) -> None:
        self._status: AlgorithmStatus = AlgorithmStatus.NOT_STARTED
        self._start_time: float = 0.0
        self._timeout: float | None = None

    @abstractmethod
    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Execute the algorithm with given inputs and return a result."""

    @abstractmethod
    def step(self) -> bool:
        """Perform one step. Returns True if the algorithm should continue."""

    @abstractmethod
    def is_converged(self) -> bool:
        """Return True when the algorithm has reached a fixed point."""

    @abstractmethod
    def summarize(self) -> str:
        """Return a human-readable multi-line summary of current state."""

    def reset(self) -> None:
        """Reset algorithm state so it can be re-run."""
        self._status = AlgorithmStatus.NOT_STARTED
        self._start_time = 0.0

    def get_status(self) -> AlgorithmStatus:
        """Return current algorithm status."""
        return self._status

    def elapsed_time(self) -> float:
        """Return elapsed seconds since the algorithm started."""
        if self._start_time == 0.0:
            return 0.0
        return time.monotonic() - self._start_time

    def set_timeout(self, seconds: float) -> None:
        """Set a wall-clock timeout for the algorithm."""
        self._timeout = seconds

    def _is_timed_out(self) -> bool:
        if self._timeout is None:
            return False
        return self.elapsed_time() > self._timeout


@dataclass(slots=True)
class NamingLawInference(TextEncodingAlgorithm):
    """Infers NamingLaw objects from a corpus of identifier strings.

    Analyzes patterns across the corpus to determine dominant case styles,
    common prefixes, and common suffixes, then constructs NamingLaw instances
    encoding those conventions.
    """

    corpus: list[str] = field(default_factory=list)
    inferred_laws: list[NamingLaw] = field(default_factory=list)
    _status: AlgorithmStatus = field(default=AlgorithmStatus.NOT_STARTED)
    _start_time: float = field(default=0.0)
    _iteration: int = field(default=0)

    name: str = field(default="naming_law_inference", init=False, repr=False)
    description: str = field(
        default="Infers NamingLaw objects from a corpus of identifier strings.",
        init=False,
        repr=False,
    )

    def __post_init__(self) -> None:
        # TextEncodingAlgorithm.__init__ sets _timeout; we skip super().__init__
        # because dataclass handles slot initialization.
        object.__setattr__(self, "_timeout", None)

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Infer NamingLaw objects from ``inputs['corpus']``.

        Parameters
        ----------
        inputs:
            Must contain ``'corpus'`` key with a list of identifier strings.

        Returns
        -------
        AlgorithmResult
            Contains ``'laws'`` key in outputs with the list of inferred laws.
        """
        self._start_time = time.monotonic()
        self._status = AlgorithmStatus.RUNNING
        self._iteration = 0
        self.inferred_laws = []

        corpus: list[str] = inputs.get("corpus", [])
        if corpus:
            self.corpus = list(corpus)

        if not self.corpus:
            self._status = AlgorithmStatus.CONVERGED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                outputs={"laws": []},
                iterations=0,
                elapsed_time=self.elapsed_time(),
            )

        _LOGGER.debug("NamingLawInference: corpus size=%d", len(self.corpus))

        try:
            style = self._detect_case_style(self.corpus)
            prefix = self._infer_prefix_pattern(self.corpus)
            suffix = self._infer_suffix_pattern(self.corpus)
            law = self._build_law_from_samples(self.corpus, style)
            self.inferred_laws.append(law)
            self._iteration = len(self.corpus)
            self._status = AlgorithmStatus.CONVERGED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("NamingLawInference failed: %s", exc)
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=self._iteration,
                elapsed_time=self.elapsed_time(),
                error_message=str(exc),
            )

        return AlgorithmResult(
            algorithm_name=self.name,
            status=self._status,
            outputs={"laws": self.inferred_laws, "style": style, "prefix": prefix, "suffix": suffix},
            iterations=self._iteration,
            elapsed_time=self.elapsed_time(),
        )

    def step(self) -> bool:
        """Process the next item in the corpus.

        Returns True if there are more items to process.
        """
        if self._iteration >= len(self.corpus):
            return False
        self._iteration += 1
        return self._iteration < len(self.corpus)

    def is_converged(self) -> bool:
        """Return True when all corpus items have been processed."""
        return self._iteration >= len(self.corpus)

    def summarize(self) -> str:
        """Return multi-line summary of inferred laws."""
        lines = [
            f"NamingLawInference — corpus size: {len(self.corpus)}",
            f"  Inferred laws: {len(self.inferred_laws)}",
            f"  Status: {self._status.value}",
        ]
        for i, law in enumerate(self.inferred_laws):
            lines.append(f"  Law[{i}]: {law!r}")
        return "\n".join(lines)

    def _detect_case_style(self, names: list[str]) -> str:
        """Determine the dominant case style across *names*.

        Returns one of ``'snake_case'``, ``'camelCase'``, ``'PascalCase'``,
        or ``'mixed'``.
        """
        snake = sum(1 for n in names if re.fullmatch(r"[a-z][a-z0-9]*(_[a-z0-9]+)*", n))
        camel = sum(1 for n in names if re.fullmatch(r"[a-z][a-zA-Z0-9]*", n) and any(c.isupper() for c in n))
        pascal = sum(1 for n in names if re.fullmatch(r"[A-Z][a-zA-Z0-9]*", n))
        total = len(names)
        if total == 0:
            return "mixed"
        threshold = 0.6 * total
        if snake >= threshold:
            return "snake_case"
        if camel >= threshold:
            return "camelCase"
        if pascal >= threshold:
            return "PascalCase"
        return "mixed"

    def _infer_prefix_pattern(self, names: list[str]) -> str | None:
        """Find the longest common prefix shared by all names, if any."""
        if not names:
            return None
        prefix = names[0]
        for name in names[1:]:
            while not name.startswith(prefix):
                prefix = prefix[:-1]
                if not prefix:
                    return None
        return prefix if len(prefix) >= 2 else None

    def _infer_suffix_pattern(self, names: list[str]) -> str | None:
        """Find the longest common suffix shared by all names, if any."""
        if not names:
            return None
        reversed_names = [n[::-1] for n in names]
        suffix_rev = reversed_names[0]
        for name in reversed_names[1:]:
            while not name.startswith(suffix_rev):
                suffix_rev = suffix_rev[:-1]
                if not suffix_rev:
                    return None
        suffix = suffix_rev[::-1]
        return suffix if len(suffix) >= 2 else None

    def _build_law_from_samples(self, samples: list[str], style: str) -> NamingLaw:
        """Construct a NamingLaw from analyzed samples and detected style.

        Parameters
        ----------
        samples:
            The identifier corpus.
        style:
            Case style detected by ``_detect_case_style``.
        """
        description = f"Inferred {style} naming law from {len(samples)} samples."
        if style == "snake_case":
            pattern = r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$"
        elif style == "camelCase":
            pattern = r"^[a-z][a-zA-Z0-9]*$"
        elif style == "PascalCase":
            pattern = r"^[A-Z][a-zA-Z0-9]*$"
        else:
            pattern = r"^[a-zA-Z_][a-zA-Z0-9_]*$"
        return NamingLaw(
            pattern=pattern,
            description=description,
            style=style,
            examples=samples[:5],
        )

    def add_to_corpus(self, names: list[str]) -> None:
        """Append *names* to the current corpus."""
        self.corpus.extend(names)

    def get_inferred_laws(self) -> list[NamingLaw]:
        """Return the list of inferred NamingLaw objects."""
        return list(self.inferred_laws)


@dataclass(slots=True)
class DocumentationShadowExtraction(TextEncodingAlgorithm):
    """Extracts DocumentationShadow objects from raw docstring text.

    Parses parameter names, return types, and constraint phrases from
    Google-style docstrings, then constructs DocumentationShadow instances
    encoding the extracted semantics.
    """

    source_docstrings: list[str] = field(default_factory=list)
    extracted_shadows: list[DocumentationShadow] = field(default_factory=list)
    _status: AlgorithmStatus = field(default=AlgorithmStatus.NOT_STARTED)
    _start_time: float = field(default=0.0)
    _iteration: int = field(default=0)

    name: str = field(default="documentation_shadow_extraction", init=False, repr=False)
    description: str = field(
        default="Extracts DocumentationShadow objects from raw docstring text.",
        init=False,
        repr=False,
    )

    def __post_init__(self) -> None:
        object.__setattr__(self, "_timeout", None)

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Extract DocumentationShadow objects from ``inputs['docstrings']``.

        Parameters
        ----------
        inputs:
            Must contain ``'docstrings'`` key with a list of docstring strings.

        Returns
        -------
        AlgorithmResult
            Contains ``'shadows'`` key in outputs with extracted shadows.
        """
        self._start_time = time.monotonic()
        self._status = AlgorithmStatus.RUNNING
        self._iteration = 0
        self.extracted_shadows = []

        docstrings: list[str] = inputs.get("docstrings", [])
        if docstrings:
            self.source_docstrings = list(docstrings)

        if not self.source_docstrings:
            self._status = AlgorithmStatus.CONVERGED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                outputs={"shadows": []},
                iterations=0,
                elapsed_time=self.elapsed_time(),
            )

        _LOGGER.debug(
            "DocumentationShadowExtraction: processing %d docstrings",
            len(self.source_docstrings),
        )

        try:
            for doc in self.source_docstrings:
                if self._is_timed_out():
                    self._status = AlgorithmStatus.TIMEOUT
                    break
                shadow = self._build_shadow_for_doc(doc)
                self.extracted_shadows.append(shadow)
                self._iteration += 1
            else:
                self._status = AlgorithmStatus.CONVERGED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("DocumentationShadowExtraction failed: %s", exc)
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=self._iteration,
                elapsed_time=self.elapsed_time(),
                error_message=str(exc),
            )

        return AlgorithmResult(
            algorithm_name=self.name,
            status=self._status,
            outputs={"shadows": self.extracted_shadows},
            iterations=self._iteration,
            elapsed_time=self.elapsed_time(),
        )

    def step(self) -> bool:
        """Process the next docstring.

        Returns True if there are more docstrings to process.
        """
        if self._iteration >= len(self.source_docstrings):
            return False
        doc = self.source_docstrings[self._iteration]
        shadow = self._build_shadow_for_doc(doc)
        self.extracted_shadows.append(shadow)
        self._iteration += 1
        return self._iteration < len(self.source_docstrings)

    def is_converged(self) -> bool:
        """Return True when all docstrings have been processed."""
        return self._iteration >= len(self.source_docstrings)

    def summarize(self) -> str:
        """Return a summary of the extracted documentation shadows."""
        total_params = sum(len(s.parameter_names) for s in self.extracted_shadows)
        total_constraints = sum(len(s.constraint_phrases) for s in self.extracted_shadows)
        lines = [
            f"DocumentationShadowExtraction — processed: {self._iteration}/{len(self.source_docstrings)}",
            f"  Extracted shadows: {len(self.extracted_shadows)}",
            f"  Total parameter names found: {total_params}",
            f"  Total constraint phrases found: {total_constraints}",
            f"  Status: {self._status.value}",
        ]
        return "\n".join(lines)

    def _extract_parameter_names(self, doc: str) -> list[str]:
        """Find parameter names from the ``Args:`` section of *doc*."""
        params: list[str] = []
        in_args = False
        for line in doc.splitlines():
            stripped = line.strip()
            if stripped.lower().startswith("args:"):
                in_args = True
                continue
            if in_args:
                if stripped and not stripped[0].isspace() and stripped.endswith(":"):
                    # New top-level section started
                    break
                match = re.match(r"^\s+(\w+)\s*(?:\(.*?\))?\s*:", stripped)
                if match:
                    params.append(match.group(1))
        return params

    def _extract_return_type(self, doc: str) -> str | None:
        """Find the return type annotation from the ``Returns:`` section of *doc*."""
        in_returns = False
        for line in doc.splitlines():
            stripped = line.strip()
            if stripped.lower().startswith("returns:"):
                in_returns = True
                continue
            if in_returns and stripped:
                # First non-empty line after Returns: header
                match = re.match(r"^(\w[\w\[\], |]*)", stripped)
                if match:
                    return match.group(1).strip()
                break
        return None

    def _extract_constraint_phrases(self, doc: str) -> list[str]:
        """Find constraint-bearing phrases containing must/should/required/etc."""
        constraint_keywords = re.compile(
            r"\b(must|should|required|shall|may not|cannot|always|never|only|at least|at most)\b",
            re.IGNORECASE,
        )
        phrases: list[str] = []
        for sentence in re.split(r"[.!?]", doc):
            if constraint_keywords.search(sentence):
                phrases.append(sentence.strip())
        return phrases

    def _build_shadow_for_doc(self, doc: str) -> DocumentationShadow:
        """Build a DocumentationShadow from a single docstring."""
        param_names = self._extract_parameter_names(doc)
        return_type = self._extract_return_type(doc)
        constraint_phrases = self._extract_constraint_phrases(doc)
        doc_hash = hashlib.sha256(doc.encode()).hexdigest()[:16]
        return DocumentationShadow(
            source_text=doc,
            parameter_names=param_names,
            return_type=return_type,
            constraint_phrases=constraint_phrases,
            shadow_id=doc_hash,
        )

    def get_coverage_statistics(self) -> dict[str, float]:
        """Return coverage statistics across all extracted shadows.

        Returns
        -------
        dict
            Keys: ``'param_coverage'``, ``'return_coverage'``, ``'constraint_coverage'``,
            ``'mean_params_per_doc'``, ``'mean_constraints_per_doc'``.
        """
        if not self.extracted_shadows:
            return {
                "param_coverage": 0.0,
                "return_coverage": 0.0,
                "constraint_coverage": 0.0,
                "mean_params_per_doc": 0.0,
                "mean_constraints_per_doc": 0.0,
            }
        n = len(self.extracted_shadows)
        param_coverage = sum(1 for s in self.extracted_shadows if s.parameter_names) / n
        return_coverage = sum(1 for s in self.extracted_shadows if s.return_type) / n
        constraint_coverage = sum(1 for s in self.extracted_shadows if s.constraint_phrases) / n
        mean_params = sum(len(s.parameter_names) for s in self.extracted_shadows) / n
        mean_constraints = sum(len(s.constraint_phrases) for s in self.extracted_shadows) / n
        return {
            "param_coverage": param_coverage,
            "return_coverage": return_coverage,
            "constraint_coverage": constraint_coverage,
            "mean_params_per_doc": mean_params,
            "mean_constraints_per_doc": mean_constraints,
        }


@dataclass(slots=True)
class StringConstraintPropagation(TextEncodingAlgorithm):
    """Propagates string constraints to derive new facts about variable values.

    Starting from an initial set of TextConstraint objects and optional initial
    string values, iteratively applies each constraint kind (length, prefix, regex)
    to narrow down or extend known facts until a fixpoint is reached.
    """

    initial_constraints: list[TextConstraint] = field(default_factory=list)
    propagated_constraints: list[TextConstraint] = field(default_factory=list)
    variable_values: dict[str, str] = field(default_factory=dict)
    _status: AlgorithmStatus = field(default=AlgorithmStatus.NOT_STARTED)
    _start_time: float = field(default=0.0)
    _iteration: int = field(default=0)
    _converged: bool = field(default=False)

    name: str = field(default="string_constraint_propagation", init=False, repr=False)
    description: str = field(
        default="Propagates string constraints to derive new facts about variables.",
        init=False,
        repr=False,
    )

    def __post_init__(self) -> None:
        object.__setattr__(self, "_timeout", None)

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Propagate constraints from ``inputs``.

        Parameters
        ----------
        inputs:
            ``'constraints'``: list[TextConstraint] — initial constraint set.
            ``'initial_values'``: dict[str, str] — optional seed variable values.

        Returns
        -------
        AlgorithmResult
            Contains ``'propagated_constraints'``, ``'variable_values'``,
            ``'derived_facts'``, and ``'consistent'`` keys in outputs.
        """
        self._start_time = time.monotonic()
        self._status = AlgorithmStatus.RUNNING
        self._iteration = 0
        self._converged = False
        self.propagated_constraints = []

        constraints: list[TextConstraint] = inputs.get("constraints", [])
        initial_values: dict[str, str] = inputs.get("initial_values", {})
        if constraints:
            self.initial_constraints = list(constraints)
        if initial_values:
            self.variable_values = dict(initial_values)

        self.propagated_constraints = list(self.initial_constraints)

        _LOGGER.debug(
            "StringConstraintPropagation: %d constraints, %d initial values",
            len(self.initial_constraints),
            len(self.variable_values),
        )

        try:
            for _ in range(MAX_ITERATIONS):
                if self._is_timed_out():
                    self._status = AlgorithmStatus.TIMEOUT
                    break
                changed = self.step()
                self._iteration += 1
                if not changed:
                    self._converged = True
                    self._status = AlgorithmStatus.CONVERGED
                    break
            else:
                self._status = AlgorithmStatus.CONVERGED

            consistent = self._check_consistency()
        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("StringConstraintPropagation failed: %s", exc)
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=self._iteration,
                elapsed_time=self.elapsed_time(),
                error_message=str(exc),
            )

        return AlgorithmResult(
            algorithm_name=self.name,
            status=self._status,
            outputs={
                "propagated_constraints": self.propagated_constraints,
                "variable_values": self.variable_values,
                "derived_facts": self.get_derived_facts(),
                "consistent": consistent,
            },
            iterations=self._iteration,
            elapsed_time=self.elapsed_time(),
        )

    def step(self) -> bool:
        """Perform one propagation pass across all constraint kinds.

        Returns True if any new fact was derived (algorithm should continue).
        """
        new_facts = 0
        new_facts += self._propagate_length_constraints()
        new_facts += self._propagate_prefix_constraints()
        new_facts += self._propagate_regex_constraints()
        return new_facts > 0

    def is_converged(self) -> bool:
        """Return True when no new information was added in the last step."""
        return self._converged

    def summarize(self) -> str:
        """Return a summary of propagation results."""
        lines = [
            f"StringConstraintPropagation — iterations: {self._iteration}",
            f"  Initial constraints: {len(self.initial_constraints)}",
            f"  Propagated constraints: {len(self.propagated_constraints)}",
            f"  Known variable values: {len(self.variable_values)}",
            f"  Status: {self._status.value}",
            f"  Converged: {self._converged}",
        ]
        return "\n".join(lines)

    def _propagate_length_constraints(self) -> int:
        """Propagate length constraints; return count of new facts derived."""
        new_facts = 0
        for c in self.propagated_constraints:
            if c.kind == ConstraintKind.LENGTH:
                var = c.variable
                if var in self.variable_values:
                    val = self.variable_values[var]
                    # Derive min/max length facts
                    if c.min_length is not None and len(val) < c.min_length:
                        self.variable_values[var] = val.ljust(c.min_length, "_")
                        new_facts += 1
                    if c.max_length is not None and len(val) > c.max_length:
                        self.variable_values[var] = val[: c.max_length]
                        new_facts += 1
        return new_facts

    def _propagate_prefix_constraints(self) -> int:
        """Propagate prefix constraints; return count of new facts derived."""
        new_facts = 0
        for c in self.propagated_constraints:
            if c.kind == ConstraintKind.PREFIX and c.prefix is not None:
                var = c.variable
                current = self.variable_values.get(var, "")
                if not current.startswith(c.prefix):
                    self.variable_values[var] = c.prefix + current
                    new_facts += 1
        return new_facts

    def _propagate_regex_constraints(self) -> int:
        """Propagate regex constraints; return count of new facts derived."""
        new_facts = 0
        for c in self.propagated_constraints:
            if c.kind == ConstraintKind.REGEX and c.pattern is not None:
                var = c.variable
                current = self.variable_values.get(var, "")
                if current and not re.fullmatch(c.pattern, current):
                    # Generate a minimal matching example
                    try:
                        match = re.search(c.pattern, current)
                        if match:
                            self.variable_values[var] = match.group(0)
                            new_facts += 1
                    except re.error:
                        pass
        return new_facts

    def _check_consistency(self) -> bool:
        """Check that all known variable values satisfy all constraints."""
        for c in self.propagated_constraints:
            var = c.variable
            val = self.variable_values.get(var)
            if val is None:
                continue
            if c.kind == ConstraintKind.LENGTH:
                if c.min_length is not None and len(val) < c.min_length:
                    return False
                if c.max_length is not None and len(val) > c.max_length:
                    return False
            elif c.kind == ConstraintKind.PREFIX and c.prefix is not None:
                if not val.startswith(c.prefix):
                    return False
            elif c.kind == ConstraintKind.REGEX and c.pattern is not None:
                try:
                    if not re.fullmatch(c.pattern, val):
                        return False
                except re.error:
                    pass
        return True

    def get_derived_facts(self) -> dict[str, list[str]]:
        """Return derived facts per variable as lists of fact strings."""
        facts: dict[str, list[str]] = defaultdict(list)
        for var, val in self.variable_values.items():
            facts[var].append(f"value={val!r}")
            facts[var].append(f"length={len(val)}")
        for c in self.propagated_constraints:
            var = c.variable
            facts[var].append(f"constraint:{c.kind.value}")
        return dict(facts)


@dataclass(slots=True)
class TextCountermodelMinimization(TextEncodingAlgorithm):
    """Minimizes a string countermodel using iterative shortening.

    Given a set of TextConstraint objects and a model (dict mapping variable
    names to string values) that violates those constraints, tries to shorten
    each value while preserving the violation, producing a minimal witness.
    """

    constraints: list[TextConstraint] = field(default_factory=list)
    countermodel: dict[str, str] | None = field(default=None)
    minimized_countermodel: dict[str, str] | None = field(default=None)
    _status: AlgorithmStatus = field(default=AlgorithmStatus.NOT_STARTED)
    _start_time: float = field(default=0.0)
    _iteration: int = field(default=0)

    name: str = field(default="text_countermodel_minimization", init=False, repr=False)
    description: str = field(
        default="Minimizes a string countermodel by shortening values.",
        init=False,
        repr=False,
    )

    def __post_init__(self) -> None:
        object.__setattr__(self, "_timeout", None)

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Minimize the countermodel from ``inputs``.

        Parameters
        ----------
        inputs:
            ``'constraints'``: list[TextConstraint].
            ``'countermodel'``: dict[str, str] — initial countermodel.

        Returns
        -------
        AlgorithmResult
            Contains ``'minimized_countermodel'`` in outputs.
        """
        self._start_time = time.monotonic()
        self._status = AlgorithmStatus.RUNNING
        self._iteration = 0

        constraints: list[TextConstraint] = inputs.get("constraints", [])
        countermodel: dict[str, str] = inputs.get("countermodel", {})
        if constraints:
            self.constraints = list(constraints)
        if countermodel:
            self.countermodel = dict(countermodel)

        if not self.countermodel:
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=0,
                elapsed_time=self.elapsed_time(),
                error_message="No countermodel provided.",
            )

        if not self._violates_constraints(self.countermodel):
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=0,
                elapsed_time=self.elapsed_time(),
                error_message="Provided model does not violate constraints.",
            )

        self.minimized_countermodel = dict(self.countermodel)

        _LOGGER.debug(
            "TextCountermodelMinimization: %d variables", len(self.countermodel)
        )

        try:
            for _ in range(MAX_ITERATIONS):
                if self._is_timed_out():
                    self._status = AlgorithmStatus.TIMEOUT
                    break
                if not self.step():
                    self._status = AlgorithmStatus.CONVERGED
                    break
                self._iteration += 1
            else:
                self._status = AlgorithmStatus.CONVERGED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("TextCountermodelMinimization failed: %s", exc)
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=self._iteration,
                elapsed_time=self.elapsed_time(),
                error_message=str(exc),
            )

        return AlgorithmResult(
            algorithm_name=self.name,
            status=self._status,
            outputs={"minimized_countermodel": self.minimized_countermodel},
            iterations=self._iteration,
            elapsed_time=self.elapsed_time(),
        )

    def step(self) -> bool:
        """Try to shorten one value in the minimized countermodel.

        Returns True if a shortening was achieved (continue), False otherwise.
        """
        if self.minimized_countermodel is None:
            return False
        for var, value in list(self.minimized_countermodel.items()):
            shorter = self._try_shorten_value(var, value)
            if shorter is not None and shorter != value:
                self.minimized_countermodel[var] = shorter
                return True
        return False

    def is_converged(self) -> bool:
        """Return True when no further shortening is possible."""
        return self._status in (AlgorithmStatus.CONVERGED, AlgorithmStatus.FAILED)

    def summarize(self) -> str:
        """Return a summary of the minimization result."""
        orig_total = sum(len(v) for v in (self.countermodel or {}).values())
        min_total = sum(len(v) for v in (self.minimized_countermodel or {}).values())
        lines = [
            f"TextCountermodelMinimization — iterations: {self._iteration}",
            f"  Original total length: {orig_total}",
            f"  Minimized total length: {min_total}",
            f"  Reduction: {orig_total - min_total} characters",
            f"  Status: {self._status.value}",
        ]
        return "\n".join(lines)

    def _try_shorten_value(self, var: str, value: str) -> str | None:
        """Attempt to find a shorter value for *var* that still violates constraints."""
        if len(value) <= 1:
            return None
        candidate = value[: len(value) // 2]
        test_model = dict(self.minimized_countermodel or {})
        test_model[var] = candidate
        if self._violates_constraints(test_model):
            return candidate
        # Try removing one character at a time from the end
        for length in range(len(value) - 1, 0, -1):
            candidate = value[:length]
            test_model[var] = candidate
            if self._violates_constraints(test_model):
                return candidate
        return None

    def _violates_constraints(self, model: dict[str, str]) -> bool:
        """Return True if *model* violates at least one constraint."""
        for c in self.constraints:
            var = c.variable
            val = model.get(var, "")
            if c.kind == ConstraintKind.LENGTH:
                if c.min_length is not None and len(val) < c.min_length:
                    return True
                if c.max_length is not None and len(val) > c.max_length:
                    return True
            elif c.kind == ConstraintKind.PREFIX and c.prefix is not None:
                if not val.startswith(c.prefix):
                    return True
            elif c.kind == ConstraintKind.REGEX and c.pattern is not None:
                try:
                    if not re.fullmatch(c.pattern, val):
                        return True
                except re.error:
                    pass
        return False

    def _find_minimal_prefix(self, var: str, constraints: list[TextConstraint]) -> str:
        """Find the minimal prefix of var's current value that still triggers a violation."""
        value = (self.minimized_countermodel or {}).get(var, "")
        for length in range(1, len(value) + 1):
            prefix = value[:length]
            test_model = dict(self.minimized_countermodel or {})
            test_model[var] = prefix
            if self._violates_constraints(test_model):
                return prefix
        return value


@dataclass(slots=True)
class NamingLawCompliance(TextEncodingAlgorithm):
    """Checks identifier names against NamingLaw objects and generates repairs.

    For each name in the codebase, checks all supplied NamingLaw objects for
    violations, then uses StringRepairEngine to suggest corrected names.
    """

    codebase_names: list[str] = field(default_factory=list)
    laws: list[NamingLaw] = field(default_factory=list)
    violations: list[ConstraintViolation] = field(default_factory=list)
    repairs: dict[str, str] = field(default_factory=dict)
    _status: AlgorithmStatus = field(default=AlgorithmStatus.NOT_STARTED)
    _start_time: float = field(default=0.0)
    _iteration: int = field(default=0)

    name: str = field(default="naming_law_compliance", init=False, repr=False)
    description: str = field(
        default="Checks identifier names against NamingLaw objects and repairs violations.",
        init=False,
        repr=False,
    )

    def __post_init__(self) -> None:
        object.__setattr__(self, "_timeout", None)

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Check compliance and generate repairs from ``inputs``.

        Parameters
        ----------
        inputs:
            ``'names'``: list[str] — identifiers to check.
            ``'laws'``: list[NamingLaw] — naming laws to enforce.

        Returns
        -------
        AlgorithmResult
            Contains ``'violations'``, ``'repairs'``, and ``'report'`` in outputs.
        """
        self._start_time = time.monotonic()
        self._status = AlgorithmStatus.RUNNING
        self._iteration = 0
        self.violations = []
        self.repairs = {}

        names: list[str] = inputs.get("names", [])
        laws: list[NamingLaw] = inputs.get("laws", [])
        if names:
            self.codebase_names = list(names)
        if laws:
            self.laws = list(laws)

        _LOGGER.debug(
            "NamingLawCompliance: %d names, %d laws",
            len(self.codebase_names),
            len(self.laws),
        )

        try:
            for name in self.codebase_names:
                if self._is_timed_out():
                    self._status = AlgorithmStatus.TIMEOUT
                    break
                viols = self._check_name_against_laws(name)
                self.violations.extend(viols)
                if viols:
                    repair = self._generate_repair_for_name(name, viols)
                    if repair is not None:
                        self.repairs[name] = repair
                self._iteration += 1
            else:
                self._status = AlgorithmStatus.CONVERGED
        except Exception as exc:  # noqa: BLE001
            _LOGGER.exception("NamingLawCompliance failed: %s", exc)
            self._status = AlgorithmStatus.FAILED
            return AlgorithmResult(
                algorithm_name=self.name,
                status=self._status,
                iterations=self._iteration,
                elapsed_time=self.elapsed_time(),
                error_message=str(exc),
            )

        return AlgorithmResult(
            algorithm_name=self.name,
            status=self._status,
            outputs={
                "violations": self.violations,
                "repairs": self.repairs,
                "report": self.get_compliance_report(),
            },
            iterations=self._iteration,
            elapsed_time=self.elapsed_time(),
        )

    def step(self) -> bool:
        """Process the next name in the codebase list.

        Returns True if there are more names to process.
        """
        if self._iteration >= len(self.codebase_names):
            return False
        name = self.codebase_names[self._iteration]
        viols = self._check_name_against_laws(name)
        self.violations.extend(viols)
        if viols:
            repair = self._generate_repair_for_name(name, viols)
            if repair is not None:
                self.repairs[name] = repair
        self._iteration += 1
        return self._iteration < len(self.codebase_names)

    def is_converged(self) -> bool:
        """Return True when all names have been checked."""
        return self._iteration >= len(self.codebase_names)

    def summarize(self) -> str:
        """Return a multi-line compliance summary report."""
        lines = [
            f"NamingLawCompliance — checked: {self._iteration}/{len(self.codebase_names)}",
            f"  Laws applied: {len(self.laws)}",
            f"  Total violations: {len(self.violations)}",
            f"  Names with repairs: {len(self.repairs)}",
            f"  Compliance rate: {self._compliance_rate():.1%}",
            f"  Status: {self._status.value}",
        ]
        return "\n".join(lines)

    def _compliance_rate(self) -> float:
        if not self.codebase_names:
            return 1.0
        violated_names = {v.variable for v in self.violations}
        compliant = sum(1 for n in self.codebase_names if n not in violated_names)
        return compliant / len(self.codebase_names)

    def _check_name_against_laws(self, name: str) -> list[ConstraintViolation]:
        """Check *name* against all laws; return list of violations."""
        violations: list[ConstraintViolation] = []
        for law in self.laws:
            if law.pattern and not re.fullmatch(law.pattern, name):
                violations.append(
                    ConstraintViolation(
                        variable=name,
                        violation_type=ViolationType.PATTERN_MISMATCH,
                        description=f"Name '{name}' does not match law pattern '{law.pattern}'.",
                        offending_value=name,
                    )
                )
        return violations

    def _generate_repair_for_name(
        self, name: str, violations: list[ConstraintViolation]
    ) -> str | None:
        """Generate a repaired identifier for *name* based on its violations."""
        if not violations:
            return None
        # Determine the required style from the first violated law
        for law in self.laws:
            style = getattr(law, "style", "snake_case")
            if style == "snake_case":
                return self._to_snake_case(name)
            if style == "camelCase":
                return self._to_camel_case(name)
        return self._to_snake_case(name)

    def _to_snake_case(self, name: str) -> str:
        """Convert *name* to snake_case."""
        # Insert underscores before uppercase letters
        s1 = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
        result = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s1).lower()
        # Replace non-alphanumeric characters with underscores
        result = re.sub(r"[^a-z0-9_]", "_", result)
        result = re.sub(r"_+", "_", result).strip("_")
        return result

    def _to_camel_case(self, name: str) -> str:
        """Convert *name* to camelCase."""
        parts = re.split(r"[_\-\s]+", name)
        if not parts:
            return name
        return parts[0].lower() + "".join(p.capitalize() for p in parts[1:])

    def get_compliance_report(self) -> dict[str, Any]:
        """Return a full compliance report dictionary."""
        violated_names = {v.variable for v in self.violations}
        return {
            "total_names": len(self.codebase_names),
            "total_laws": len(self.laws),
            "total_violations": len(self.violations),
            "violated_names": sorted(violated_names),
            "repairs": dict(self.repairs),
            "compliance_rate": self._compliance_rate(),
            "violations_by_type": self._violations_by_type(),
        }

    def _violations_by_type(self) -> dict[str, int]:
        counts: dict[str, int] = defaultdict(int)
        for v in self.violations:
            counts[v.violation_type.value] += 1
        return dict(counts)

    def get_violations_for_name(self, name: str) -> list[ConstraintViolation]:
        """Return all violations recorded for *name*."""
        return [v for v in self.violations if v.variable == name]


