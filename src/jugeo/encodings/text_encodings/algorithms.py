def text_encoding_from_program(program: Any) -> dict[str, Any]:
    """Produce a text encoding from a loaded program.

    Bridges the python-runtime program-loader subsystem into the
    text-encoding pipeline by extracting source text and metadata from a
    loaded program object.

    Parameters
    ----------
    program:
        A loaded program from ``jugeo.python_runtime.program_loader``.

    Returns
    -------
    dict[str, Any]
        A dict with ``"program"``, ``"source_text"``, and ``"encoding"``
        keys.
    """
    if _program_loader is None:
        raise RuntimeError("jugeo.python_runtime.program_loader is not available")
    source = _program_loader.get_source(program) if hasattr(_program_loader, "get_source") else str(program)
    return {
        "program": program,
        "source_text": source,
        "encoding": {"raw_text": source},
    }


def text_evidence_encoding(evidence: Any) -> dict[str, Any]:
    """Encode evidence channel data as a text encoding.

    Bridges the evidence-channels subsystem into the text-encoding
    pipeline by serialising channel data into a text-compatible format.

    Parameters
    ----------
    evidence:
        An evidence channel from ``jugeo.evidence.channels``.

    Returns
    -------
    dict[str, Any]
        A dict with ``"evidence"``, ``"channel_id"``, and
        ``"text_payload"`` keys.
    """
    if _channels_mod is None:
        raise RuntimeError("jugeo.evidence.channels is not available")
    channel_id = _channels_mod.channel_id(evidence) if hasattr(_channels_mod, "channel_id") else str(id(evidence))
    payload = _channels_mod.serialize(evidence) if hasattr(_channels_mod, "serialize") else str(evidence)
    return {
        "evidence": evidence,
        "channel_id": channel_id,
        "text_payload": payload,
    }
