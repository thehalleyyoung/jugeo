# §31.3.3 — RecognizerPredicate
# ---------------------------------------------------------------------------


@dataclass
class RecognizerPredicate:
    """A recognizer predicate associated with a single ADT constructor.

    Recognizers are the boolean-valued functions ``is-c_i : T → Bool``
    generated by ``declare-datatypes``.  This class provides a thin
    wrapper that allows recognizers to be composed with guards, negated,
    and emitted as SMT-LIB 2 assertions.

    Parameters
    ----------
    constructor_name:
        The constructor whose values this recognizer identifies.
    sort_name:
        The ADT sort name that owns this constructor.
    predicate_smt2:
        The SMT-LIB 2 function identifier for the recognizer.  If empty,
        the default ``is-{constructor_name}`` is used (set in
        ``__post_init__``).
    pred_id:
        UUID string uniquely identifying this recognizer instance.

    Notes
    -----
    Recognizer predicates are always *total*: they return ``true`` exactly
    for values built by their corresponding constructor, and ``false`` for
    all other constructor variants.
    """

    constructor_name: str
    sort_name: str
    predicate_smt2: str = ""
    pred_id: str = field(default_factory=lambda: str(uuid.uuid4()))

    def __post_init__(self) -> None:
        """Populate ``predicate_smt2`` from the constructor name if not supplied."""
        if not self.predicate_smt2:
            # Standard SMT-LIB 2 recognizer naming convention.
            self.predicate_smt2 = f"is-{self.constructor_name}"

    # ------------------------------------------------------------------
    # Application helpers
    # ------------------------------------------------------------------

    def apply_to(self, term: str) -> str:
        """Apply this recognizer to an SMT-LIB 2 term expression.

        Parameters
        ----------
        term:
            An SMT-LIB 2 expression denoting a value of ``sort_name``.

        Returns
        -------
        str
            The application expression, e.g. ``"(is-cons x)"``.
        """
        return f"({self.predicate_smt2} {term})"

    def negate(self) -> RecognizerPredicate:
        """Return a new recognizer predicate that is logically negated.

        The negated recognizer is true for every value of the sort that
        was *not* built by ``constructor_name``.  This is useful when
        constructing case-split complements.

        Returns
        -------
        RecognizerPredicate
            A fresh instance whose ``predicate_smt2`` wraps the original
            in ``(not …)``.
        """
        negated_smt2 = f"(not (is-{self.constructor_name} x))"
        return RecognizerPredicate(
            constructor_name=self.constructor_name,
            sort_name=self.sort_name,
            predicate_smt2=negated_smt2,
            pred_id=str(uuid.uuid4()),
        )

    def to_smt2_assert(self, term: str) -> str:
        """Emit this recognizer as a top-level ``(assert …)`` statement.

        Parameters
        ----------
        term:
            The term to be asserted as satisfying this recognizer.

        Returns
        -------
        str
            A complete SMT-LIB 2 assertion, e.g.
            ``"(assert (is-cons x))"``.
        """
        return f"(assert ({self.predicate_smt2} {term}))"

    def compose_with_guard(self, guard: str) -> str:
        """Produce a conjunction of this recognizer and an external guard.

        This is used to build conditional projections: the recognizer
        ensures we are looking at the right constructor, and the guard
        encodes additional semantic constraints.

        Parameters
        ----------
        guard:
            An SMT-LIB 2 Boolean expression (may reference variable
            ``x`` which is the implicit subject of this recognizer).

        Returns
        -------
        str
            An SMT-LIB 2 ``(and …)`` expression combining both conditions.
        """
        return f"(and ({self.predicate_smt2} x) {guard})"

    def is_trivial(self) -> bool:
        """Return ``True`` if this recognizer is the constant ``true`` or ``false``.

        Trivial recognizers arise when placeholder predicates are used
        during construction, before the actual recognizer name is known.

        Returns
        -------
        bool
            ``True`` iff ``predicate_smt2`` (stripped) is ``"true"`` or
            ``"false"``.
        """
        return self.predicate_smt2.strip() in ("true", "false")


