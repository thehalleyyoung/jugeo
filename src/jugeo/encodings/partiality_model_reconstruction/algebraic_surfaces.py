def build_constructor_spec(
    name: str,
    fields: list[tuple[str, str]],
) -> ConstructorSpec:
    """Build a :class:`ConstructorSpec` from a list of ``(field_name, sort)`` pairs.

    This convenience function is the primary entry point for constructing
    :class:`ConstructorSpec` instances when the fields are supplied as
    a list of name-sort pairs rather than separate tuples.

    Parameters
    ----------
    name:
        Constructor identifier.
    fields:
        Ordered list of ``(field_name, sort_name)`` pairs.

    Returns
    -------
    ConstructorSpec
        A freshly created spec instance.

    Examples
    --------
    >>> spec = build_constructor_spec("cons", [("head", "Int"), ("tail", "List_Int")])
    >>> spec.arity()
    2
    >>> spec.field_at(0)
    ('head', 'Int')
    """
    if not fields:
        return ConstructorSpec(name=name)
    field_names = tuple(f[0] for f in fields)
    field_sorts = tuple(f[1] for f in fields)
    return ConstructorSpec(name=name, field_sorts=field_sorts, field_names=field_names)


def declare_algebraic_surface(
    sort_name: str,
    specs: list[ConstructorSpec],
) -> str:
    """Produce a complete SMT-LIB 2 ``declare-datatypes`` command for *sort_name*.

    The resulting declaration is well-formed for a single non-parametric
    algebraic sort with the given constructors.

    Parameters
    ----------
    sort_name:
        The sort identifier to declare.
    specs:
        All constructors for the sort, in declaration order.

    Returns
    -------
    str
        A ``(declare-datatypes …)`` command string.

    Examples
    --------
    >>> nil = ConstructorSpec(name="nil")
    >>> cons = build_constructor_spec("cons", [("head", "Int"), ("tail", "List_Int")])
    >>> print(declare_algebraic_surface("List_Int", [nil, cons]))
    (declare-datatypes ((List_Int 0)) (((nil) (cons (head Int) (tail List_Int)))))
    """
    constructor_clauses = " ".join(spec.to_smt2_constructor() for spec in specs)
    return f"(declare-datatypes (({sort_name} 0)) (({constructor_clauses})))"


def fold_over_surface(
    surface_sort: str,
    fold: AlgebraicFold,
    term: str,
    cases: dict[str, str],
) -> str:
    """Compute the SMT-LIB 2 fold expression for *term* over *surface_sort*.

    Delegates to :meth:`AlgebraicFold.build_match_expression` after
    verifying that *fold* targets the correct sort.

    Parameters
    ----------
    surface_sort:
        The sort name; used for a consistency assertion.
    fold:
        The :class:`AlgebraicFold` whose match expression is used.
    term:
        The SMT-LIB 2 term being folded over.
    cases:
        Per-constructor case expressions.

    Returns
    -------
    str
        The nested ``ite`` expression for the fold.

    Raises
    ------
    ValueError
        When ``fold.sort_name`` does not match ``surface_sort``.
    """
    if fold.sort_name != surface_sort:
        raise ValueError(
            f"fold_over_surface: fold is for sort '{fold.sort_name}' "
            f"but surface_sort is '{surface_sort}'."
        )
    return fold.build_match_expression(term, cases)


def project_surface_field(
    sort_name: str,
    constructor: str,
    field_idx: int,
    term: str,
) -> str:
    """Produce the SMT-LIB 2 expression that projects field *field_idx*.

    This is a low-level helper that emits the accessor application
    following the JuGeo naming convention ``{constructor}-field-{field_idx}``.

    Parameters
    ----------
    sort_name:
        The ADT sort name (used for documentation / error messages).
    constructor:
        The constructor name whose field is being projected.
    field_idx:
        Zero-based field index.
    term:
        The SMT-LIB 2 term of sort *sort_name* to project from.

    Returns
    -------
    str
        An accessor application expression, e.g. ``"(cons-field-0 x)"``.
    """
    accessor = f"{constructor}-field-{field_idx}"
    return f"({accessor} {term})"


