# §31.3.4 — SurfaceProjection
# ---------------------------------------------------------------------------


@dataclass
class SurfaceProjection:
    """A single projection (accessor) function from an algebraic sort.

    A :class:`SurfaceProjection` represents the accessor function
    :math:`\\pi^{(i)}_j : T \\to A^{(i)}_j` that extracts the *j*-th field
    of a value built by the *i*-th constructor.

    Because SMT-LIB 2 accessors are *total* (they return an unspecified
    but type-correct value when applied to the wrong constructor), this
    class tracks whether the projection is safe to apply unconditionally
    (``TOTAL``), requires a recognizer guard (``PARTIAL``), or has been
    explicitly totalized with a supplied guard condition (``CONDITIONAL``).

    Parameters
    ----------
    source_sort:
        The ADT sort being projected from.
    target_sort:
        The sort of the field value extracted.
    projection_name:
        The SMT-LIB 2 accessor function name.
    mode:
        :class:`ProjectionMode` indicating totality.
    projection_id:
        UUID string uniquely identifying this projection instance.
    guard_condition:
        An SMT-LIB 2 Boolean guard that must hold before applying the
        projection (relevant only for ``CONDITIONAL`` mode).
    """

    source_sort: str
    target_sort: str
    projection_name: str
    mode: ProjectionMode = ProjectionMode.TOTAL
    projection_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    guard_condition: str = "true"

    # ------------------------------------------------------------------
    # Application
    # ------------------------------------------------------------------

    def apply(self, term: str) -> str:
        """Apply this projection to an SMT-LIB 2 term.

        Parameters
        ----------
        term:
            The term of sort ``source_sort`` to project from.

        Returns
        -------
        str
            The application expression, e.g. ``"(head x)"``.
        """
        return f"({self.projection_name} {term})"

    def is_total_projection(self) -> bool:
        """Return ``True`` iff this projection can be applied without a guard.

        Returns
        -------
        bool
            ``True`` iff ``self.mode == ProjectionMode.TOTAL``.
        """
        return self.mode == ProjectionMode.TOTAL

    def compose_with(self, other: SurfaceProjection) -> SurfaceProjection:
        """Compose this projection with *other*, yielding a new projection.

        The composed projection applies ``self`` first, then ``other``.
        The resulting mode is ``PARTIAL`` if either operand is partial;
        otherwise it is ``TOTAL``.

        Parameters
        ----------
        other:
            The projection to apply after ``self``.

        Returns
        -------
        SurfaceProjection
            A fresh :class:`SurfaceProjection` representing the composition.
        """
        composed_name = f"{self.projection_name}_then_{other.projection_name}"
        composed_mode = (
            ProjectionMode.PARTIAL
            if self.mode == ProjectionMode.PARTIAL
            or other.mode == ProjectionMode.PARTIAL
            else ProjectionMode.TOTAL
        )
        return SurfaceProjection(
            source_sort=self.source_sort,
            target_sort=other.target_sort,
            projection_name=composed_name,
            mode=composed_mode,
            projection_id=str(uuid.uuid4()),
            guard_condition="true",
        )

    def to_smt2_definition(self, body: str) -> str:
        """Emit an SMT-LIB 2 ``define-fun`` for this projection with a given body.

        Parameters
        ----------
        body:
            The body expression; this will be used verbatim as the
            return expression of the define-fun.

        Returns
        -------
        str
            A complete ``(define-fun …)`` definition.
        """
        return (
            f"(define-fun {self.projection_name}"
            f" ((x {self.source_sort}))"
            f" {self.target_sort}"
            f" {body})"
        )

    def partial_to_total(self, default: str) -> SurfaceProjection:
        """Totalize a partial projection by supplying a default value.

        When a partial projection is applied outside its valid domain, the
        totalized version returns *default* instead of an unspecified
        value.

        Parameters
        ----------
        default:
            An SMT-LIB 2 expression of sort ``target_sort`` to use as the
            default value.

        Returns
        -------
        SurfaceProjection
            A new ``TOTAL`` projection whose name is annotated with
            ``_totalized``.
        """
        totalized_name = f"{self.projection_name}_totalized"
        return SurfaceProjection(
            source_sort=self.source_sort,
            target_sort=self.target_sort,
            projection_name=totalized_name,
            mode=ProjectionMode.TOTAL,
            projection_id=str(uuid.uuid4()),
            guard_condition=default,  # store default as guard_condition for reference
        )

    def copilot_suggest_guard(self, sort_info: dict[str, Any]) -> str:
        """Suggest a recognizer guard for this projection based on sort metadata.

        Inspects *sort_info* for a ``"constructors"`` key containing
        constructor names, and builds an ``(or …)`` of recognizer
        applications that scope the projection to valid constructors.

        Parameters
        ----------
        sort_info:
            A dictionary that may contain ``"constructors": list[str]``
            listing all constructor names for ``source_sort``.

        Returns
        -------
        str
            An SMT-LIB 2 Boolean expression, e.g.
            ``"(or (is-cons x) (is-pair x))"``.  Falls back to ``"true"``
            when no constructor information is available.
        """
        constructors: list[str] = sort_info.get("constructors", [])
        if not constructors:
            # No constructor information available; use trivially-true guard.
            return "true"
        if len(constructors) == 1:
            # Single constructor — recognizer is always true; guard is trivial.
            return f"(is-{constructors[0]} x)"
        # Build an or-expression over all recognizers.
        recognizer_apps = " ".join(f"(is-{c} x)" for c in constructors)
        return f"(or {recognizer_apps})"


