r"""theory2.tex Ch31 §31.3 — Algebraic Data Type Surfaces in Z3.

An *algebraic surface* is the interface of a Z3 algebraic datatype: the
set of constructors, recognizers, and accessor functions that define how
values of the sort are created and destructed.

Given a sort :math:`T` with constructors :math:`c_1, \\ldots, c_n`, the
surface consists of:

.. math::

   \\text{Surface}(T)
   = \\bigl\\{c_i : A^{(i)}_1 \\times \\cdots \\times A^{(i)}_{k_i} \\to T\\bigr\\}_{i=1}^{n}
   \\cup \\bigl\\{\\mathrm{is}\\text{-}c_i : T \\to \\mathbb{B}\\bigr\\}_{i=1}^{n}
   \\cup \\bigl\\{\\pi^{(i)}_j : T \\to A^{(i)}_j\\bigr\\}_{i,j}

Fold/unfold (§31.3.2):

.. math::

   \\mathrm{fold}_{T}(f_1, \\ldots, f_n)(\\mathrm{c}_i(x_1, \\ldots, x_{k_i}))
   = f_i(x_1, \\ldots, x_{k_i})

The surface abstraction is central to the partiality-model reconstruction
pipeline because each algebraic datatype produced by the Z3 encoder must
be disassembled by traversing its surface.  Without a uniform surface
API, the reconstruction layer would need bespoke destructuring logic for
every distinct algebraic sort, which would be fragile and non-compositional.

§31.3.1 — Constructor specifications
--------------------------------------
Each constructor :math:`c_i` carries an *arity* :math:`k_i \\ge 0`, a list
of *field sorts* :math:`A^{(i)}_1, \\ldots, A^{(i)}_{k_i}`, and optional
*field names* that become the accessor (projection) function names in SMT-LIB 2.

§31.3.3 — Recognizer predicates
---------------------------------
The recognizer :math:`\\mathrm{is}\\text{-}c_i : T \\to \\mathbb{B}` is the
unique predicate generated by ``declare-datatypes`` for every constructor.
Composing recognizers with Boolean guards yields conditional projections.

§31.3.4 — Fold combinators
----------------------------
A *fold* over sort :math:`T` is a function
:math:`\\text{fold}_T : (A^{(1)} \\to R) \\times \\cdots \\times (A^{(n)} \\to R) \\to T \\to R`
that eliminates a value of sort :math:`T` by dispatching on its constructor.
"""
