@dataclass
class AlgebraicFold:
    """Fold combinator for a single algebraic sort.

    An :class:`AlgebraicFold` captures the *elimination principle* of an
    algebraic datatype: given one case expression per constructor, it
    dispatches on the outermost constructor of a value and evaluates the
    corresponding case.

    In SMT-LIB 2, folds are realized as nested ``(ite (is-c_i x) e_i …)``
    chains because SMT-LIB 2 (prior to the ``match`` extension) lacks
    native pattern matching.

    Parameters
    ----------
    sort_name:
        The ADT sort being folded over, e.g. ``"List_Int"``.
    constructors:
        An ordered list of :class:`ConstructorSpec` instances for all
        constructors of ``sort_name``.  The ordering determines the
        nesting order of the generated ``ite`` chain.
    result_sort:
        The SMT-LIB 2 sort of the fold's result.  Defaults to ``"Bool"``.
    fold_id:
        UUID string uniquely identifying this fold instance.
    """

    sort_name: str
    constructors: list[ConstructorSpec] = field(default_factory=list)
    result_sort: str = "Bool"
    fold_id: str = field(default_factory=lambda: str(uuid.uuid4()))

    # ------------------------------------------------------------------
    # Mutation
    # ------------------------------------------------------------------

    def add_case(self, constructor: ConstructorSpec) -> None:
        """Add a constructor to this fold if not already present.

        Deduplication is by constructor *name*; two specs with the same
        name are considered the same constructor regardless of their
        ``spec_id`` values.

        Parameters
        ----------
        constructor:
            The :class:`ConstructorSpec` to register.
        """
        existing_names = {c.name for c in self.constructors}
        if constructor.name not in existing_names:
            self.constructors.append(constructor)

    # ------------------------------------------------------------------
    # SMT-LIB 2 code generation
    # ------------------------------------------------------------------

    def build_fold_function(self, case_exprs: dict[str, str]) -> str:
        """Generate an SMT-LIB 2 ``define-fun`` that realizes this fold.

        The generated function takes a single argument ``x`` of sort
        ``sort_name`` and returns a value of sort ``result_sort`` by
        dispatching on ``x``'s outermost constructor using a nested
        ``ite`` chain.

        Parameters
        ----------
        case_exprs:
            Mapping from constructor name to the SMT-LIB 2 expression
            that should be returned for that constructor.  Missing
            constructors default to ``"undefined"`` (a free constant).

        Returns
        -------
        str
            A multi-line SMT-LIB 2 ``(define-fun …)`` definition.
        """
        fold_name = f"fold_{self.sort_name}_{self.fold_id[:8]}"
        match_body = self.build_match_expression("x", case_exprs)
        lines = [
            f"; Fold over algebraic sort {self.sort_name}",
            f"(define-fun {fold_name}",
            f"  ((x {self.sort_name}))",
            f"  {self.result_sort}",
            f"  {match_body})",
        ]
        return "\n".join(lines)

    def build_induction_scheme(self) -> str:
        """Emit a multi-line SMT-LIB 2 comment describing the induction scheme.

        The induction scheme for a simple inductive ADT states that a
        property ``P`` holds for all values of the sort if it holds for
        each constructor case (with the induction hypothesis applied to
        recursive sub-terms).

        Returns
        -------
        str
            A block comment string suitable for inclusion in a ``.smt2``
            file as documentation.
        """
        lines: list[str] = [
            f"; ── Induction scheme for sort: {self.sort_name} ──────────────────",
            f"; To prove (forall ((x {self.sort_name})) (P x)), it suffices to show:",
        ]
        for spec in self.constructors:
            if spec.arity() == 0:
                lines.append(f";   Base case: (P ({spec.name}))")
            else:
                hyps = " ".join(
                    f"(P ({spec.accessor_name(i)} x))"
                    for i in range(spec.arity())
                    if spec.field_sorts[i] == self.sort_name  # only recursive fields
                )
                if hyps:
                    lines.append(
                        f";   Inductive case for {spec.name}: "
                        f"assuming {hyps}, prove (P ({spec.name} …))"
                    )
                else:
                    lines.append(
                        f";   Constructor case for {spec.name}: prove (P ({spec.name} …))"
                    )
        lines.append("; ─────────────────────────────────────────────────────────────")
        return "\n".join(lines)

    def build_match_expression(self, term: str, cases: dict[str, str]) -> str:
        """Build a nested SMT-LIB 2 ``ite`` chain for constructor dispatch.

        The chain has the form::

            (ite (is-c1 term) e1
              (ite (is-c2 term) e2
                …
                  eN))

        where ``eN`` is the last case (used without a guard to ensure the
        expression is always defined).

        Parameters
        ----------
        term:
            The SMT-LIB 2 term being dispatched on.
        cases:
            Mapping from constructor name to result expression.

        Returns
        -------
        str
            Nested ``ite`` expression as a string.
        """
        if not self.constructors:
            return "undefined"

        # Build the chain from the inside out (right-to-left).
        # The last constructor acts as the default (else) branch.
        specs = self.constructors
        # Innermost (last) case — used as the default else.
        last = specs[-1]
        result = cases.get(last.name, "undefined")

        # Wrap each preceding constructor in an ite.
        for spec in reversed(specs[:-1]):
            cond = f"(is-{spec.name} {term})"
            then_expr = cases.get(spec.name, "undefined")
            result = f"(ite {cond} {then_expr} {result})"

        # If there is only one constructor, return its expression directly.
        if len(specs) == 1:
            result = cases.get(specs[0].name, "undefined")

        return result

    def validate_cases(self, cases: dict[str, str]) -> list[str]:
        """Return error messages for any constructors missing from *cases*.

        Parameters
        ----------
        cases:
            The case-expression mapping to validate.

        Returns
        -------
        list[str]
            One error string per missing constructor.  Empty when all
            constructors are covered.
        """
        errors: list[str] = []
        for spec in self.constructors:
            if spec.name not in cases:
                errors.append(
                    f"AlgebraicFold: missing case expression for constructor "
                    f"'{spec.name}' in sort '{self.sort_name}'."
                )
        return errors

    def to_recursive_definition(self, func_name: str, cases: dict[str, str]) -> str:
        """Emit a named recursive-style ``define-fun`` for this fold.

        Unlike :meth:`build_fold_function` (which auto-generates a name),
        this method uses the caller-supplied *func_name* directly.

        Parameters
        ----------
        func_name:
            The SMT-LIB 2 function identifier to declare.
        cases:
            Per-constructor case expressions.

        Returns
        -------
        str
            A ``(define-fun …)`` definition string.
        """
        match_expr = self.build_match_expression("x", cases)
        return (
            f"(define-fun {func_name}\n"
            f"  ((x {self.sort_name}))\n"
            f"  {self.result_sort}\n"
            f"  {match_expr})"
        )


