# §31.3 Enumerations
# ---------------------------------------------------------------------------


class ConstructorArity(str, Enum):
    """Classifies a constructor by its number of fields.

    This mirrors the standard arity hierarchy used in type-theoretic
    presentations of algebraic data types.  Nullary constructors
    correspond to constants / atoms; unary constructors act as wrappers;
    binary and n-ary constructors are proper product types.
    """

    NULLARY = "nullary"
    """No fields — a constant/atom constructor (e.g. ``nil``, ``true``)."""

    UNARY = "unary"
    """Exactly one field — a wrapper or coercion constructor."""

    BINARY = "binary"
    """Exactly two fields — a pair-like constructor."""

    NARY = "nary"
    """Three or more fields — a general product constructor."""


class SurfaceKind(str, Enum):
    """Characterizes the recursion structure of an algebraic sort's surface.

    The distinction between inductive and coinductive surfaces matters for
    the fold/unfold semantics: inductive surfaces support structural
    recursion that provably terminates, whereas coinductive surfaces
    support corecursion / stream-like infinite values.
    """

    INDUCTIVE = "inductive"
    """Standard inductive / well-founded ADT (e.g. lists, trees)."""

    COINDUCTIVE = "coinductive"
    """Coinductive / potentially-infinite ADT (e.g. streams, lazy trees)."""

    RECURSIVE = "recursive"
    """Self-referential ADT without a coinductive type annotation."""

    MUTUAL = "mutual"
    """Two or more sorts defined by mutual recursion."""

    SIMPLE = "simple"
    """Non-recursive enum or product — no recursion at all."""


class ProjectionMode(str, Enum):
    """Indicates whether a surface projection is total or may be undefined.

    Totality is critical in Z3 because SMT-LIB 2 projections (accessors)
    are technically total functions; however, applying an accessor from
    constructor :math:`c_i` to a value built by :math:`c_j \\neq c_i`
    yields an unspecified (but semantically valid) value.  Marking
    projections as PARTIAL or CONDITIONAL lets downstream code insert
    recognizer guards before applying them.
    """

    TOTAL = "total"
    """Safe to apply to any value of the sort without a guard."""

    PARTIAL = "partial"
    """Should only be applied after a recognizer check."""

    CONDITIONAL = "conditional"
    """Totalized by a supplied Boolean guard expression."""


