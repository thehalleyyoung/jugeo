@dataclass(frozen=True, slots=True)
class ConstructorSpec:
    """Specification of a single algebraic datatype constructor.

    A :class:`ConstructorSpec` captures the complete *signature* of one
    constructor within a ``declare-datatypes`` declaration in SMT-LIB 2.
    It stores the constructor name, the sorts of each field, and optional
    human-readable names for the fields (which become the accessor
    function identifiers).

    Parameters
    ----------
    name:
        The constructor identifier, e.g. ``"cons"`` or ``"leaf"``.
    field_sorts:
        A tuple of sort-name strings for each field, in declaration order,
        e.g. ``("Int", "List_Int")``.
    field_names:
        A tuple of accessor-function names corresponding positionally to
        ``field_sorts``.  May be shorter than ``field_sorts`` or empty,
        in which case auto-generated names of the form ``field_i`` are used.
    spec_id:
        A UUID string that uniquely identifies this constructor spec
        instance, used for caching and equality checks across serialization
        boundaries.

    Examples
    --------
    >>> spec = ConstructorSpec(name="cons", field_sorts=("Int", "List_Int"),
    ...                        field_names=("head", "tail"))
    >>> spec.arity()
    2
    >>> spec.arity_kind()
    <ConstructorArity.BINARY: 'binary'>
    >>> spec.to_smt2_constructor()
    '(cons (head Int) (tail List_Int))'
    """

    name: str
    field_sorts: tuple[str, ...] = ()
    field_names: tuple[str, ...] = ()
    spec_id: str = field(default_factory=lambda: str(uuid.uuid4()))

    # ------------------------------------------------------------------
    # Arity helpers
    # ------------------------------------------------------------------

    def arity(self) -> int:
        """Return the number of fields (arguments) this constructor takes.

        For a nullary constructor (constant) this is 0; for a binary
        constructor it is 2, etc.

        Returns
        -------
        int
            ``len(self.field_sorts)``
        """
        return len(self.field_sorts)

    def arity_kind(self) -> ConstructorArity:
        """Classify this constructor's arity as a :class:`ConstructorArity` variant.

        Returns
        -------
        ConstructorArity
            - ``NULLARY`` when :meth:`arity` is 0
            - ``UNARY``   when :meth:`arity` is 1
            - ``BINARY``  when :meth:`arity` is 2
            - ``NARY``    when :meth:`arity` is ≥ 3
        """
        n = self.arity()
        if n == 0:
            return ConstructorArity.NULLARY
        if n == 1:
            return ConstructorArity.UNARY
        if n == 2:
            return ConstructorArity.BINARY
        return ConstructorArity.NARY

    # ------------------------------------------------------------------
    # Field accessors
    # ------------------------------------------------------------------

    def field_at(self, idx: int) -> tuple[str, str]:
        """Return the ``(field_name, sort_name)`` pair at position *idx*.

        If the ``field_names`` tuple is shorter than ``field_sorts`` at
        position *idx*, a synthetic name ``field_{idx}`` is substituted.

        Parameters
        ----------
        idx:
            Zero-based index into the field list.

        Returns
        -------
        tuple[str, str]
            ``(name, sort)`` pair for the requested field.

        Raises
        ------
        IndexError
            When *idx* is out of range for ``field_sorts``.
        """
        if idx < 0 or idx >= len(self.field_sorts):
            raise IndexError(
                f"ConstructorSpec '{self.name}': field index {idx} is out of range "
                f"(arity={self.arity()})"
            )
        sort = self.field_sorts[idx]
        if idx < len(self.field_names):
            name = self.field_names[idx]
        else:
            name = f"field_{idx}"
        return (name, sort)

    # ------------------------------------------------------------------
    # SMT-LIB 2 emission
    # ------------------------------------------------------------------

    def to_smt2_constructor(self) -> str:
        """Render this constructor as an SMT-LIB 2 constructor clause.

        For a nullary constructor this produces ``(name)``.
        For constructors with fields it produces
        ``(name (field0_name field0_sort) … (fieldN_name fieldN_sort))``.

        Returns
        -------
        str
            Well-formed SMT-LIB 2 constructor clause fragment, suitable
            for embedding inside a ``declare-datatypes`` expression.
        """
        if self.arity() == 0:
            return f"({self.name})"
        field_parts: list[str] = []
        for i in range(self.arity()):
            fname, fsort = self.field_at(i)
            field_parts.append(f"({fname} {fsort})")
        fields_str = " ".join(field_parts)
        return f"({self.name} {fields_str})"

    def recognizer_name(self) -> str:
        """Return the SMT-LIB 2 recognizer function name for this constructor.

        By the SMT-LIB 2 standard for algebraic datatypes, the recognizer
        is named ``is-<constructor>``.

        Returns
        -------
        str
            e.g. ``"is-cons"`` for a constructor named ``"cons"``.
        """
        return f"is-{self.name}"

    def accessor_name(self, field_idx: int) -> str:
        """Return the accessor (projection) function name for field *field_idx*.

        If the field has an explicit name in ``field_names``, that name is
        returned directly (as it will be the declared accessor name).
        Otherwise, a synthetic accessor name ``{constructor_name}-{field_idx}``
        is returned following the JuGeo naming convention.

        Parameters
        ----------
        field_idx:
            Zero-based index of the field whose accessor name is requested.

        Returns
        -------
        str
            Accessor function name.
        """
        if field_idx < len(self.field_names):
            return self.field_names[field_idx]
        return f"{self.name}-{field_idx}"

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------

    def validate(self) -> list[str]:
        """Check the internal consistency of this constructor specification.

        Validation rules:

        1. ``name`` must be a non-empty string.
        2. If ``field_names`` is non-empty it must have the same length as
           ``field_sorts`` (extra names are ignored upstream, but mismatches
           indicate caller bugs).
        3. Each element of ``field_sorts`` must be a non-empty string.

        Returns
        -------
        list[str]
            A list of human-readable error messages.  An empty list means
            the spec is valid.
        """
        errors: list[str] = []
        if not self.name or not self.name.strip():
            errors.append("ConstructorSpec: 'name' must be a non-empty string.")
        if self.field_names and len(self.field_names) != len(self.field_sorts):
            errors.append(
                f"ConstructorSpec '{self.name}': field_names length "
                f"({len(self.field_names)}) != field_sorts length "
                f"({len(self.field_sorts)})."
            )
        for i, s in enumerate(self.field_sorts):
            if not s or not s.strip():
                errors.append(
                    f"ConstructorSpec '{self.name}': field_sorts[{i}] is empty."
                )
        return errors

    def to_dict(self) -> dict[str, Any]:
        """Serialize this spec to a JSON-compatible dictionary.

        Tuples are converted to lists so the result round-trips cleanly
        through ``json.dumps`` / ``json.loads``.

        Returns
        -------
        dict[str, Any]
            Dictionary with keys ``name``, ``field_sorts``, ``field_names``,
            ``spec_id``, and ``arity``.
        """
        return {
            "name": self.name,
            "field_sorts": list(self.field_sorts),
            "field_names": list(self.field_names),
            "spec_id": self.spec_id,
            "arity": self.arity(),
            "arity_kind": self.arity_kind().value,
        }


