class HeapKind(str, Enum):
    """Enumeration of separation-logic heap forms.

    Each member corresponds to one of the structural heap forms defined in
    §27.7–§27.11 of theory2.tex.

    Members
    -------
    EMPTY
        The empty heap ``emp``.  Identity element for separating conjunction.
        Has an empty footprint and makes no assertions.
    POINTS_TO
        A single points-to cell ``loc ↦ val``.  The canonical atomic heap form.
        Footprint is the singleton ``{loc}``.
    STAR
        Separating conjunction ``h1 ∗ h2``.  Requires disjoint footprints.
        Footprint is ``fp(h1) ∪ fp(h2)``.
    FRAME
        A heap with an explicit frame predicate.  The heap is valid in any
        extension of its footprint that satisfies the frame condition.
    QUANTIFIED
        A heap described by a universally or existentially quantified formula.
        Typically arises from list-segment or tree-segment predicates.
    ALLOCATED
        A location that has been freshly allocated (value unconstrained).
    DEALLOCATED
        A location that has been freed.  Any subsequent dereference is undefined.
    """

    EMPTY = "empty"
    POINTS_TO = "points_to"
    STAR = "star"
    FRAME = "frame"
    QUANTIFIED = "quantified"
    ALLOCATED = "allocated"
    DEALLOCATED = "deallocated"


