@dataclass(frozen=True, slots=True)
class SeparationLogicFragment:
    """Tracks which separation-logic fragment a heap summary inhabits.

    Immutable value object; safe as a dict key and in sets.

    Fields
    ------
    heap_id : str
        The ``heap_id`` of the :class:`HeapSummary` this record describes.
    kind : HeapKind
        The top-level structural form of the heap.
    pointer_count : int
        The number of distinct pointer locations in the heap's footprint.
    has_quantifiers : bool
        Whether any separating conjunct contains a quantifier (``forall``
        or ``exists``).
    has_frame : bool
        Whether a frame predicate has been attached to the heap.

    Example
    -------
    >>> frag = SeparationLogicFragment(
    ...     heap_id="h_abc",
    ...     kind=HeapKind.POINTS_TO,
    ...     pointer_count=1,
    ...     has_quantifiers=False,
    ...     has_frame=False,
    ... )
    >>> frag.kind
    <HeapKind.POINTS_TO: 'points_to'>
    """

    heap_id: str
    kind: HeapKind
    pointer_count: int
    has_quantifiers: bool
    has_frame: bool

    def classify_heap(self, heap: HeapSummary) -> str:
        """Return a short string classification for *heap*.

        Args:
            heap: The :class:`HeapSummary` to classify.

        Returns:
            One of ``"emp"``, ``"points-to"``, ``"star"``, ``"frame"``,
            ``"quantified"``, ``"allocated"``, ``"deallocated"``.

        Example:
            >>> frag = SeparationLogicFragment("h", HeapKind.EMPTY, 0, False, False)
            >>> encoder = HeapSummaryEncoder()
            >>> emp = encoder.encode_empty_heap(name="ce")
            >>> frag.classify_heap(emp)
            'emp'
        """
        hk = heap.metadata.get("heap_kind", "empty")
        mapping = {
            "empty": "emp",
            "points_to": "points-to",
            "star": "star",
            "frame": "frame",
            "quantified": "quantified",
            "allocated": "allocated",
            "deallocated": "deallocated",
        }
        return mapping.get(hk, str(hk))

    def is_symbolic_heap(self, heap: HeapSummary) -> bool:
        """Return True when *heap* is a symbolic heap (quantifier-free SL).

        A symbolic heap is a separating conjunction of points-to cells and
        pure propositional conjuncts, with no nested quantifiers.

        Args:
            heap: The :class:`HeapSummary` to test.

        Returns:
            ``True`` when the heap is in the symbolic heap fragment.
        """
        for conjunct in heap.separating_conjuncts:
            if "forall" in conjunct or "exists" in conjunct:
                return False
        hk = heap.metadata.get("heap_kind", "empty")
        return hk in ("empty", "points_to", "star")

    def count_pointers(self, heap: HeapSummary) -> int:
        """Count the number of distinct pointer locations in *heap*.

        Args:
            heap: The :class:`HeapSummary` to inspect.

        Returns:
            The size of ``heap.footprint``.

        Example:
            >>> frag = SeparationLogicFragment("h", HeapKind.STAR, 2, False, False)
            >>> encoder = HeapSummaryEncoder()
            >>> h1 = encoder.encode_points_to("0", "1")
            >>> h2 = encoder.encode_points_to("1", "2")
            >>> star = encoder.encode_star(h1, h2)
            >>> frag.count_pointers(star)
            2
        """
        return len(heap.footprint)

    def estimate_complexity(self, heap: HeapSummary) -> int:
        """Estimate the SMT proof complexity for *heap* on a 0–100 scale.

        The score accounts for pointer count, quantifiers, and frame
        annotations.

        Args:
            heap: The :class:`HeapSummary` to evaluate.

        Returns:
            Integer complexity in ``[0, 100]``.

        Example:
            >>> frag = SeparationLogicFragment("h", HeapKind.STAR, 3, False, False)
            >>> encoder = HeapSummaryEncoder()
            >>> h1 = encoder.encode_points_to("0", "1")
            >>> h2 = encoder.encode_points_to("1", "2")
            >>> star = encoder.encode_star(h1, h2)
            >>> 0 <= frag.estimate_complexity(star) <= 100
            True
        """
        ptrs = self.count_pointers(heap)
        base = min(ptrs * 5, 50)
        q_pen = 30 if self.has_quantifiers else 0
        f_pen = 10 if self.has_frame else 0
        hk = heap.metadata.get("heap_kind", "empty")
        hk_pen = {
            "empty": 0, "points_to": 0, "star": 5, "frame": 15,
            "quantified": 35, "allocated": 5, "deallocated": 5,
        }.get(hk, 10)
        return min(base + q_pen + f_pen + hk_pen, 100)

    def to_fragment_tag(self, heap: HeapSummary) -> str:
        """Map *heap* to a fragment tag string used by the solver router.

        Args:
            heap: The :class:`HeapSummary` to tag.

        Returns:
            A string such as ``"QF_SL_PTRS"``, ``"QF_SL_STAR"``, or
            ``"SL_QUANTIFIED"``.

        Example:
            >>> frag = SeparationLogicFragment("h", HeapKind.EMPTY, 0, False, False)
            >>> encoder = HeapSummaryEncoder()
            >>> emp = encoder.encode_empty_heap(name="ftag_test")
            >>> frag.to_fragment_tag(emp)
            'QF_SL_EMP'
        """
        if self.has_quantifiers:
            return "SL_QUANTIFIED"
        hk = heap.metadata.get("heap_kind", "empty")
        return {
            "empty": "QF_SL_EMP",
            "points_to": "QF_SL_PTRS",
            "star": "QF_SL_STAR",
            "allocated": "QF_SL_STAR",
            "deallocated": "QF_SL_STAR",
            "frame": "QF_SL_FRAME",
        }.get(hk, "QF_SL")


