@dataclass(slots=True)
class HeapCompositionEngine:
    """Higher-level combinators for composing multiple heap summaries.

    Wraps a :class:`HeapSummaryEncoder` to provide safe composition,
    fold-with-star, overlap detection, and summary formatting.

    Example
    -------
    >>> engine = HeapCompositionEngine()
    >>> h1 = engine._encoder.encode_points_to("10", "1")
    >>> h2 = engine._encoder.encode_points_to("11", "2")
    >>> composed = engine.compose_all([h1, h2])
    >>> composed.metadata["heap_kind"]
    'star'
    """

    _encoder: HeapSummaryEncoder = field(default_factory=HeapSummaryEncoder)

    def safe_compose(
        self, h1: HeapSummary, h2: HeapSummary
    ) -> HeapSummary | None:
        """Compose *h1* and *h2* if their footprints are disjoint.

        Returns the star-composition if footprints are disjoint, or ``None``
        if they overlap (indicating a potential alias violation).

        Args:
            h1: First heap.
            h2: Second heap.

        Returns:
            A star-composed :class:`HeapSummary`, or ``None`` on overlap.

        Example:
            >>> engine = HeapCompositionEngine()
            >>> ha = engine._encoder.encode_points_to("0", "1")
            >>> hb = engine._encoder.encode_points_to("1", "2")
            >>> result = engine.safe_compose(ha, hb)
            >>> result is not None
            True
        """
        if h1.footprint & h2.footprint:
            overlap = sorted(h1.footprint & h2.footprint)
            logger.info(
                "safe_compose: footprints overlap at %s; returning None", overlap
            )
            return None
        return self._encoder.encode_star(h1, h2)

    def compose_all(self, heaps: list[HeapSummary]) -> HeapSummary:
        """Fold a list of heap summaries with separating conjunction.

        Left-folds: ``heaps[0] ∗ heaps[1] ∗ … ∗ heaps[n-1]``.  If *heaps*
        is empty, returns the empty heap.

        Args:
            heaps: List of :class:`HeapSummary` objects to compose.

        Returns:
            The star-composed heap.

        Raises:
            ValueError: If any consecutive pair has overlapping footprints.

        Example:
            >>> engine = HeapCompositionEngine()
            >>> h1 = engine._encoder.encode_points_to("20", "1")
            >>> h2 = engine._encoder.encode_points_to("21", "2")
            >>> h3 = engine._encoder.encode_points_to("22", "3")
            >>> result = engine.compose_all([h1, h2, h3])
            >>> len(result.footprint)
            3
        """
        if not heaps:
            return self._encoder.encode_empty_heap()
        result = heaps[0]
        for heap in heaps[1:]:
            composed = self.safe_compose(result, heap)
            if composed is None:
                overlap = sorted(result.footprint & heap.footprint)
                raise ValueError(
                    f"compose_all: aliasing detected at locations {overlap}"
                )
            result = composed
        return result

    def check_frame_condition(
        self, heap: HeapSummary, frame: str
    ) -> bool:
        """Check whether *frame* is syntactically present in the heap.

        Returns ``True`` if ``heap.frame_condition == frame`` or if *frame*
        appears as a substring of any separating conjunct.  For semantic
        frame checking use :meth:`HeapInvariantChecker.verify_frame_rule`.

        Args:
            heap: The :class:`HeapSummary` to inspect.
            frame: The frame predicate string to look for.

        Returns:
            ``True`` if the frame condition is present.

        Example:
            >>> engine = HeapCompositionEngine()
            >>> h = engine._encoder.encode_empty_heap()
            >>> engine.check_frame_condition(h, "some_pred")
            False
        """
        if heap.frame_condition == frame:
            return True
        return any(frame in conj for conj in heap.separating_conjuncts)

    def summarize_composition(self, heaps: list[HeapSummary]) -> str:
        """Produce a human-readable summary of a list of heaps.

        Args:
            heaps: List of :class:`HeapSummary` objects.

        Returns:
            A multi-line summary string with footprint sizes and kinds.

        Example:
            >>> engine = HeapCompositionEngine()
            >>> h = engine._encoder.encode_empty_heap(name="sum_test")
            >>> summary = engine.summarize_composition([h])
            >>> "emp" in summary
            True
        """
        if not heaps:
            return "No heaps to summarize."
        lines: list[str] = [f"Composition summary ({len(heaps)} heaps):"]
        total_locs: set[str] = set()
        for i, heap in enumerate(heaps):
            hk = heap.metadata.get("heap_kind", "?")
            name = heap.metadata.get("name", heap.heap_id[:8])
            n_conj = len(heap.separating_conjuncts)
            fp_size = len(heap.footprint)
            lines.append(
                f"  [{i}] {name}: kind={hk}  "
                f"footprint_size={fp_size}  conjuncts={n_conj}"
            )
            total_locs |= heap.footprint
        lines.append(f"  Total unique locations: {len(total_locs)}")
        # Overlap detection
        seen: set[str] = set()
        overlaps: set[str] = set()
        for heap in heaps:
            overlaps |= seen & heap.footprint
            seen |= heap.footprint
        if overlaps:
            lines.append(f"  ⚠  Aliased locations: {sorted(overlaps)}")
        else:
            lines.append("  ✓  No aliasing detected.")
        return "\n".join(lines)

    def find_overlap(
        self, h1: HeapSummary, h2: HeapSummary
    ) -> frozenset[str]:
        """Return the set of locations that appear in both footprints.

        Args:
            h1: First heap.
            h2: Second heap.

        Returns:
            ``frozenset`` of aliased location strings.

        Example:
            >>> engine = HeapCompositionEngine()
            >>> ha = engine._encoder.encode_points_to("5", "0")
            >>> hb = engine._encoder.encode_points_to("5", "1")
            >>> engine.find_overlap(ha, hb)
            frozenset({'5'})
        """
        return h1.footprint & h2.footprint


