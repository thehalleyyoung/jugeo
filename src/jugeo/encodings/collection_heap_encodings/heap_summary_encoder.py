@dataclass(slots=True)
class HeapInvariantChecker:
    """Verify structural invariants of heap summaries.

    Integrates with a Z3Session to check dangling-pointer freedom,
    single-ownership, and frame-rule correctness.

    Example
    -------
    >>> checker = HeapInvariantChecker()
    >>> encoder = HeapSummaryEncoder()
    >>> h = encoder.encode_points_to("0", "1")
    >>> checker.check_no_dangling(h, frozenset({"0"}))
    True
    """

    _encoder: HeapSummaryEncoder = field(default_factory=HeapSummaryEncoder)

    def check_no_dangling(
        self,
        heap: HeapSummary,
        allocated_set: frozenset[str],
    ) -> bool:
        """Check that every location in the footprint is in *allocated_set*.

        A "dangling" location appears in the footprint but not in
        *allocated_set*, corresponding to a use-after-free or uninitialised
        pointer dereference.

        Args:
            heap: The :class:`HeapSummary` to check.
            allocated_set: The set of currently allocated location strings.

        Returns:
            ``True`` if no dangling pointers are found; ``False`` otherwise.

        Example:
            >>> checker = HeapInvariantChecker()
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_points_to("loc0", "5")
            >>> checker.check_no_dangling(h, frozenset({"loc0"}))
            True
            >>> checker.check_no_dangling(h, frozenset())
            False
        """
        dangling = heap.footprint - allocated_set
        if dangling:
            logger.warning(
                "check_no_dangling: dangling locations %s in heap %r",
                sorted(dangling),
                heap.metadata.get("name", heap.heap_id[:8]),
            )
            return False
        return True

    def check_single_ownership(
        self, heaps: list[HeapSummary]
    ) -> bool:
        """Verify that no location appears in more than one heap's footprint.

        Args:
            heaps: List of :class:`HeapSummary` objects to check.

        Returns:
            ``True`` if all footprints are pairwise disjoint.

        Example:
            >>> checker = HeapInvariantChecker()
            >>> encoder = HeapSummaryEncoder()
            >>> h1 = encoder.encode_points_to("0", "1")
            >>> h2 = encoder.encode_points_to("1", "2")
            >>> checker.check_single_ownership([h1, h2])
            True
        """
        seen: set[str] = set()
        for heap in heaps:
            overlap = seen & heap.footprint
            if overlap:
                logger.warning(
                    "check_single_ownership: location(s) %s owned by multiple heaps",
                    sorted(overlap),
                )
                return False
            seen |= heap.footprint
        return True

    def verify_frame_rule(
        self,
        heap: HeapSummary,
        session: Any,
    ) -> Any:
        """Verify that the frame condition of *heap* is satisfiable.

        Constructs a Z3 query from the heap's declarations, separating
        conjuncts, and frame condition assertion.  Returns SAT if the
        heap-plus-frame is consistent.

        Args:
            heap: The :class:`HeapSummary` with a frame condition to check.
            session: A Z3Session-compatible object.

        Returns:
            A :class:`~jugeo.solver.z3_session.Z3Result`.

        Raises:
            RuntimeError: If *session* is ``None``.
            ValueError: If the heap has no frame condition set.
        """
        if session is None:
            raise RuntimeError("Z3 session required for verify_frame_rule")
        if not heap.frame_condition:
            raise ValueError(
                f"Heap {heap.metadata.get('name', heap.heap_id)!r} has no "
                "frame condition; use encode_frame() first"
            )
        smt2 = self._encoder.to_smt2(heap)
        logger.debug(
            "verify_frame_rule: %r query size %d",
            heap.metadata.get("name", heap.heap_id[:8]),
            len(smt2),
        )
        if hasattr(session, "check_smt2"):
            return session.check_smt2(smt2)
        return session.check(smt2)

    def summarize_invariants(self, heap: HeapSummary) -> str:
        """Produce a human-readable summary of the heap's structural invariants.

        Args:
            heap: The :class:`HeapSummary` to summarize.

        Returns:
            A multi-line string listing footprint, points-to map, and frame.

        Example:
            >>> checker = HeapInvariantChecker()
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_empty_heap(name="inv_sum")
            >>> summary = checker.summarize_invariants(h)
            >>> "empty" in summary or "emp" in summary
            True
        """
        hk = heap.metadata.get("heap_kind", "?")
        name = heap.metadata.get("name", heap.heap_id[:8])
        n_conj = len(heap.separating_conjuncts)

        lines: list[str] = [
            f"Heap invariant summary for {name!r}:",
            f"  heap_kind     : {hk}",
            f"  footprint     : {{{', '.join(sorted(heap.footprint))}}}",
            f"  pointer count : {len(heap.points_to_map)}",
            f"  conjuncts     : {n_conj}",
            f"  frame cond    : {heap.frame_condition or 'none'}",
        ]
        if heap.points_to_map:
            lines.append("  points-to map :")
            for loc, val in sorted(heap.points_to_map.items()):
                lines.append(f"    {loc} ↦ {val}")
        sl_formula = self._encoder.to_separation_formula(heap)
        lines.append(f"  SL formula    : {sl_formula}")
        return "\n".join(lines)


