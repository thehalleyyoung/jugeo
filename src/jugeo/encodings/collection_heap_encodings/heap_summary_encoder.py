"""
heap_summary_encoder — Heap points-to constraints in separation logic style.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch27: Exact Z3 encodings II: collections, finite maps, heap summaries,
alias partitions, interface abstractions.

Encodes heap memory as Z3 arrays of location→value with separation logic structure.
Supports the points-to predicate (loc ↦ val), separating conjunction (∗),
the empty heap (emp), and the frame rule.  Footprint tracking ensures that
composed heaps have disjoint footprints.

Part of the JuGeo judgment-geometry framework.

Background
----------
Chapter 27 §27.7–§27.10 of theory2.tex develops the encoding of heap memory in
separation logic (SL) into Z3 array constraints.  The central insight is that
a *symbolic heap* — a conjunction of points-to predicates ``l₁↦v₁ ∗ … ∗ lₙ↦vₙ``
— is satisfiable iff the locations ``l₁, …, lₙ`` are pairwise distinct, which
reduces to a set of disequality constraints over integers (or uninterpreted
location sorts).

Points-to encoding (§27.7)
    ``loc ↦ val`` is represented by declaring a heap array
    ``(declare-fun heap (Int) Int)`` and asserting ``(= (heap loc) val)``.
    The footprint is the singleton set ``{loc}``.

Separating conjunction (§27.8)
    ``h1 ∗ h2`` requires the footprints of ``h1`` and ``h2`` to be disjoint.
    The encoding merges both separating conjuncts and adds the disjointness
    constraint ``(not (= loc1 loc2))`` for every pair (loc1 ∈ fp1, loc2 ∈ fp2).

Frame rule (§27.9)
    A heap ``h`` satisfies the frame rule for frame predicate ``F`` when
    behaviour restricted to its footprint is unaffected by arbitrary heap
    extensions outside the footprint.  We encode this as an extra free-
    variable assertion over the frame region.

Empty heap (§27.10)
    ``emp`` is the unit for ∗.  It has an empty footprint and makes no
    assertions about the heap array.

Allocation / deallocation (§27.11)
    Allocation adds a fresh location (unconstrained value) to the footprint.
    Deallocation removes a location from the footprint and invalidates
    prior assertions about its value.

All encodings produce a :class:`~jugeo.encodings.collection_heap_encodings.models.HeapSummary`
with:
  * ``points_to_map``        — dict mapping location names to value expressions.
  * ``footprint``            — frozenset of owned location names.
  * ``separating_conjuncts`` — list of SMT-LIB2 ``(assert ...)`` strings.
  * ``frame_condition``      — optional frame predicate string.
  * ``metadata``             — stores ``heap_kind``, ``name``, ``declarations``,
                               and ``composition_log`` for downstream stages.

The :class:`HeapSummaryEncoder` is the primary entry point.
"""

