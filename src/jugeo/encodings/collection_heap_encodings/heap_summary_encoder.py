def encode_points_to_quick(loc: str, val: str) -> HeapSummary:
    """Convenience wrapper: encode a points-to cell with a fresh encoder.

    Equivalent to ``HeapSummaryEncoder().encode_points_to(loc, val)``.

    Args:
        loc: Location identifier.
        val: Value string.

    Returns:
        A :class:`HeapSummary` with ``metadata["heap_kind"] == "points_to"``.

    Example:
        >>> h = encode_points_to_quick("0", "42")
        >>> h.metadata["heap_kind"]
        'points_to'
        >>> "0" in h.footprint
        True
    """
    return HeapSummaryEncoder().encode_points_to(loc, val)
