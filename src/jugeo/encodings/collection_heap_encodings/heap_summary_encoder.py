@dataclass(slots=True)
class HeapSummaryEncoder:
    """Encode separation-logic heaps as Z3 array constraints.

    This is the primary entry point for Ch27 heap encoding.  It maintains
    a footprint tracker (location → heap_id) and a composition log for
    auditing separating conjunctions.

    Each produced :class:`~jugeo.encodings.collection_heap_encodings.models.HeapSummary`
    stores auxiliary data in its ``metadata`` dict under the keys:

    * ``"heap_kind"``        — ``"empty"`` / ``"points_to"`` / ``"star"`` / …
    * ``"name"``             — the symbolic name used for the Z3 array symbol
    * ``"declarations"``     — list of SMT-LIB2 ``declare-*`` strings
    * ``"heap_array_decl"``  — the main ``(declare-fun heap (...) ...)`` string

    Fields
    ------
    _heap_cache : dict
        Maps heap_id → HeapSummary for deduplication.
    _footprint_tracker : dict
        Maps location string → heap_id to detect aliasing.
    _composition_log : list
        Records (h1_name, op, h2_name) entries for each compose call.

    Example
    -------
    >>> encoder = HeapSummaryEncoder()
    >>> h = encoder.encode_points_to("0", "42", heap_name="h0")
    >>> h.metadata["heap_kind"]
    'points_to'
    >>> "0" in h.footprint
    True
    """

    _heap_cache: dict[str, HeapSummary] = field(default_factory=dict)
    _footprint_tracker: dict[str, str] = field(default_factory=dict)
    _composition_log: list[tuple[str, str, str]] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _make_heap_id(self, name: str, kind: str) -> str:
        """Compute a stable heap ID from name and kind.

        Args:
            name: Heap symbol name.
            kind: HeapKind string.

        Returns:
            A 16-character hex digest.
        """
        return hashlib.sha256(f"{name}:{kind}".encode()).hexdigest()[:16]

    def _make_heap_name(self, base: str) -> str:
        """Generate a unique heap array symbol name.

        Args:
            base: Human-readable base (e.g. ``"heap"``).

        Returns:
            A collision-resistant name string.
        """
        return f"{base}_{uuid.uuid4().hex[:8]}"

    def _check_disjoint_footprints(
        self, h1: HeapSummary, h2: HeapSummary
    ) -> bool:
        """Return True when h1 and h2 have disjoint footprints.

        Args:
            h1: First heap summary.
            h2: Second heap summary.

        Returns:
            ``True`` iff ``h1.footprint ∩ h2.footprint = ∅``.
        """
        return len(h1.footprint & h2.footprint) == 0

    def _merge_points_to(
        self,
        d1: dict[str, str],
        d2: dict[str, str],
    ) -> dict[str, str]:
        """Merge two points-to dicts, keeping the first value on conflict.

        Args:
            d1: First points-to dict.
            d2: Second points-to dict.

        Returns:
            A merged dict with no duplicate keys.
        """
        merged: dict[str, str] = dict(d1)
        for loc, val in d2.items():
            if loc not in merged:
                merged[loc] = val
            else:
                logger.warning(
                    "_merge_points_to: location %r already present; "
                    "keeping first value %r",
                    loc, merged[loc],
                )
        return merged

    def _disjointness_assertion(
        self,
        fp1: frozenset[str],
        fp2: frozenset[str],
    ) -> str:
        """Build an SMT-LIB2 assertion that all cross-pairs (loc1, loc2) differ.

        For every ``loc1 ∈ fp1`` and ``loc2 ∈ fp2`` we assert
        ``(not (= loc1_lit loc2_lit))``.  When either footprint is empty
        the assertion is ``(assert true)`` (trivially satisfied).

        Args:
            fp1: First footprint.
            fp2: Second footprint.

        Returns:
            A single SMT-LIB2 ``(assert ...)`` string.
        """
        if not fp1 or not fp2:
            return "(assert true)"
        parts: list[str] = []
        for l1 in sorted(fp1):
            for l2 in sorted(fp2):
                ll1 = self._loc_to_smt2(l1)
                ll2 = self._loc_to_smt2(l2)
                parts.append(f"(not (= {ll1} {ll2}))")
        if len(parts) == 1:
            return f"(assert {parts[0]})"
        return f"(assert (and {' '.join(parts)}))"

    def _loc_to_smt2(self, loc: str) -> str:
        """Normalise a location identifier to an SMT-LIB2 integer literal.

        If *loc* is already a numeric string, return it as-is (abs value).
        Otherwise hash to a non-negative integer.

        Args:
            loc: Location identifier string.

        Returns:
            SMT-LIB2 integer literal string.
        """
        try:
            return str(abs(int(loc)))
        except ValueError:
            return str(int(hashlib.sha256(loc.encode()).hexdigest(), 16) % (2**30))

    def _val_to_smt2(self, val: str) -> str:
        """Normalise a value string to an SMT-LIB2 literal.

        Wraps negative integers in Z3 negation form; hashes non-numeric strings.

        Args:
            val: Value string.

        Returns:
            SMT-LIB2 literal string.
        """
        try:
            int_val = int(val)
            if int_val < 0:
                return f"(- {abs(int_val)})"
            return str(int_val)
        except ValueError:
            return str(int(hashlib.sha256(val.encode()).hexdigest(), 16) % (2**30))

    # ------------------------------------------------------------------
    # Public encoding API
    # ------------------------------------------------------------------

    def encode_points_to(
        self,
        loc: str,
        val: str,
        *,
        heap_name: str | None = None,
    ) -> HeapSummary:
        """Build a HeapSummary for the points-to predicate ``loc ↦ val``.

        Declares a Z3 array ``(declare-fun <heap_name> (Int) Int)`` and
        asserts ``(= (<heap_name> <loc_lit>) <val_lit>)``.  The footprint is
        the singleton set ``{loc}``.

        The ``metadata`` dict will contain:
        * ``"heap_kind"``     → ``"points_to"``
        * ``"name"``          → the heap array symbol name
        * ``"declarations"``  → ``["(declare-fun <name> (Int) Int)"]``

        Args:
            loc: The heap location identifier (string; will be converted to an
                integer literal via :meth:`_loc_to_smt2`).
            val: The value stored at *loc* (string; converted via
                :meth:`_val_to_smt2`).
            heap_name: Optional name for the Z3 heap array.  Auto-generated
                if ``None``.

        Returns:
            A :class:`HeapSummary` with a singleton footprint, one
            separating conjunct, and ``metadata["heap_kind"] == "points_to"``.

        Raises:
            ValueError: If *loc* is empty.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_points_to("0", "42", heap_name="h0")
            >>> h.metadata["heap_kind"]
            'points_to'
            >>> "0" in h.footprint
            True
            >>> len(h.separating_conjuncts)
            1
        """
        if not loc:
            raise ValueError("loc must be a non-empty location identifier")

        t0 = time.monotonic()
        name = heap_name if heap_name is not None else self._make_heap_name("heap")
        loc_lit = self._loc_to_smt2(loc)
        val_lit = self._val_to_smt2(val)

        heap_id = self._make_heap_id(name, "points_to")
        if heap_id in self._heap_cache:
            logger.debug("encode_points_to: cache hit for %r", name)
            return self._heap_cache[heap_id]

        heap_decl = f"(declare-fun {name} (Int) Int)"
        assertion = _POINTS_TO_TEMPLATE.format(
            heap=name, loc=loc_lit, val=val_lit
        )

        if loc in self._footprint_tracker:
            logger.warning(
                "encode_points_to: location %r already in footprint of heap %r",
                loc, self._footprint_tracker[loc],
            )
        self._footprint_tracker[loc] = heap_id

        heap = HeapSummary(
            location_sort=_DEFAULT_LOCATION_SORT,
            value_sort=_DEFAULT_VALUE_SORT,
            points_to_map={loc: val},
            footprint=frozenset({loc}),
            separating_conjuncts=[assertion],
            frame_condition=None,
            heap_id=heap_id,
            metadata={
                "heap_kind": "points_to",
                "name": name,
                "declarations": [heap_decl],
            },
        )
        self._heap_cache[heap_id] = heap
        elapsed_ms = (time.monotonic() - t0) * 1000.0
        logger.debug(
            "encode_points_to %r: loc=%r val=%r %.2f ms",
            name, loc, val, elapsed_ms,
        )
        return heap

    def encode_empty_heap(self, *, name: str | None = None) -> HeapSummary:
        """Build a HeapSummary for the empty heap ``emp``.

        The empty heap has an empty footprint and contributes no assertions.
        It is the unit element for the separating conjunction (∗).

        The ``metadata`` dict will contain:
        * ``"heap_kind"`` → ``"empty"``
        * ``"name"``      → the given or generated name

        Args:
            name: Optional logical name for the empty heap record.  Defaults
                to a generated name prefixed with ``"emp_"``.

        Returns:
            A :class:`HeapSummary` with empty footprint, empty
            ``separating_conjuncts``, and ``metadata["heap_kind"] == "empty"``.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_empty_heap(name="emp0")
            >>> h.metadata["heap_kind"]
            'empty'
            >>> len(h.footprint)
            0
            >>> len(h.separating_conjuncts)
            0
        """
        heap_name = name if name is not None else self._make_heap_name("emp")
        heap_id = self._make_heap_id(heap_name, "empty")
        if heap_id in self._heap_cache:
            return self._heap_cache[heap_id]

        heap = HeapSummary(
            location_sort=_DEFAULT_LOCATION_SORT,
            value_sort=_DEFAULT_VALUE_SORT,
            points_to_map={},
            footprint=frozenset(),
            separating_conjuncts=[],
            frame_condition=None,
            heap_id=heap_id,
            metadata={"heap_kind": "empty", "name": heap_name, "declarations": []},
        )
        self._heap_cache[heap_id] = heap
        logger.debug("encode_empty_heap: created %r", heap_name)
        return heap

    def encode_star(
        self, h1: HeapSummary, h2: HeapSummary
    ) -> HeapSummary:
        """Build the separating conjunction ``h1 ∗ h2``.

        Checks that the footprints of *h1* and *h2* are disjoint (logs a
        warning if not).  The composed heap:
        * Merges ``declarations`` from both inputs.
        * Merges ``separating_conjuncts`` from both inputs.
        * Adds a disjointness assertion for every cross-product pair.
        * Unions the footprints.
        * Merges the ``points_to_map`` dicts.

        Args:
            h1: Left heap operand.
            h2: Right heap operand.

        Returns:
            A :class:`HeapSummary` with ``metadata["heap_kind"] == "star"``.

        Raises:
            TypeError: If *h1* or *h2* are not :class:`HeapSummary` instances.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h1 = encoder.encode_points_to("0", "10", heap_name="ha")
            >>> h2 = encoder.encode_points_to("1", "20", heap_name="hb")
            >>> star = encoder.encode_star(h1, h2)
            >>> star.metadata["heap_kind"]
            'star'
            >>> len(star.footprint)
            2
        """
        t0 = time.monotonic()
        overlap = h1.footprint & h2.footprint
        if overlap:
            logger.warning(
                "encode_star: footprints overlap at %s — encoding may be UNSAT",
                sorted(overlap),
            )

        h1_name = h1.metadata.get("name", h1.heap_id[:8])
        h2_name = h2.metadata.get("name", h2.heap_id[:8])
        star_name = f"star_{h1_name}_{h2_name}"
        heap_id = self._make_heap_id(star_name, "star")
        if heap_id in self._heap_cache:
            self._composition_log.append((h1_name, "*", h2_name))
            return self._heap_cache[heap_id]

        # Merge declarations (deduplicate)
        seen_decls: set[str] = set()
        merged_decls: list[str] = []
        for d in (
            *h1.metadata.get("declarations", []),
            *h2.metadata.get("declarations", []),
        ):
            if d not in seen_decls:
                merged_decls.append(d)
                seen_decls.add(d)

        # Disjointness assertion
        disj = self._disjointness_assertion(h1.footprint, h2.footprint)

        merged_conjuncts = (
            list(h1.separating_conjuncts)
            + list(h2.separating_conjuncts)
            + [disj]
        )
        merged_pts = self._merge_points_to(h1.points_to_map, h2.points_to_map)
        merged_fp = h1.footprint | h2.footprint

        heap = HeapSummary(
            location_sort=h1.location_sort,
            value_sort=h1.value_sort,
            points_to_map=merged_pts,
            footprint=merged_fp,
            separating_conjuncts=merged_conjuncts,
            frame_condition=None,
            heap_id=heap_id,
            metadata={
                "heap_kind": "star",
                "name": star_name,
                "declarations": merged_decls,
                "operands": [h1_name, h2_name],
            },
        )
        self._heap_cache[heap_id] = heap
        self._composition_log.append((h1_name, "*", h2_name))
        elapsed_ms = (time.monotonic() - t0) * 1000.0
        logger.debug(
            "encode_star %r: fp_size=%d %.2f ms",
            star_name, len(merged_fp), elapsed_ms,
        )
        return heap

    def encode_frame(
        self, heap: HeapSummary, frame_pred: str
    ) -> HeapSummary:
        """Apply the frame rule to *heap* with frame predicate *frame_pred*.

        The resulting heap asserts everything in *heap* plus an extra
        assertion ``(assert <frame_pred>)`` representing the frame condition.
        The footprint is unchanged (the frame is outside the footprint by
        definition of the frame rule).

        Args:
            heap: The heap to frame.
            frame_pred: An SMT-LIB2 formula string for the frame condition
                (without the outer ``(assert ...)`` wrapper).

        Returns:
            A new :class:`HeapSummary` with ``metadata["heap_kind"] == "frame"``
            and ``frame_condition == frame_pred``.

        Raises:
            ValueError: If *frame_pred* is empty.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_points_to("0", "7", heap_name="hf")
            >>> framed = encoder.encode_frame(h, "(> fv 0)")
            >>> framed.metadata["heap_kind"]
            'frame'
            >>> framed.frame_condition
            '(> fv 0)'
        """
        if not frame_pred.strip():
            raise ValueError("frame_pred must be a non-empty formula string")

        frame_assertion = f"(assert {frame_pred.strip()})"
        h_name = heap.metadata.get("name", heap.heap_id[:8])
        framed_name = f"frame_{h_name}"
        heap_id = self._make_heap_id(framed_name, "frame")
        if heap_id in self._heap_cache:
            return self._heap_cache[heap_id]

        new_conjuncts = list(heap.separating_conjuncts) + [frame_assertion]

        framed = HeapSummary(
            location_sort=heap.location_sort,
            value_sort=heap.value_sort,
            points_to_map=dict(heap.points_to_map),
            footprint=heap.footprint,
            separating_conjuncts=new_conjuncts,
            frame_condition=frame_pred.strip(),
            heap_id=heap_id,
            metadata={
                "heap_kind": "frame",
                "name": framed_name,
                "declarations": list(heap.metadata.get("declarations", [])),
                "parent": h_name,
            },
        )
        self._heap_cache[heap_id] = framed
        logger.debug("encode_frame %r: frame_pred=%r", framed_name, frame_pred)
        return framed

    def encode_allocation(
        self, heap: HeapSummary, loc: str
    ) -> HeapSummary:
        """Return a new heap with location *loc* freshly allocated.

        Allocation adds *loc* to the footprint with an unconstrained value.
        A note assertion ``(assert true) ; freshly allocated <loc>`` is
        appended to the conjuncts to mark the event in the proof trace.

        Args:
            heap: The existing heap.
            loc: Location identifier to allocate.

        Returns:
            A new :class:`HeapSummary` with ``metadata["heap_kind"] == "allocated"``
            and *loc* added to the footprint.

        Raises:
            ValueError: If *loc* is already in the heap's footprint
                (double allocation).

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> emp = encoder.encode_empty_heap(name="alloc_test")
            >>> allocated = encoder.encode_allocation(emp, "loc5")
            >>> "loc5" in allocated.footprint
            True
        """
        if loc in heap.footprint:
            raise ValueError(
                f"Location {loc!r} is already in the footprint of heap "
                f"{heap.metadata.get('name', heap.heap_id)!r}; "
                f"cannot allocate twice"
            )

        h_name = heap.metadata.get("name", heap.heap_id[:8])
        alloc_name = f"alloc_{h_name}_{loc}"
        heap_id = self._make_heap_id(alloc_name, "allocated")
        if heap_id in self._heap_cache:
            return self._heap_cache[heap_id]

        alloc_note = f"(assert true) ; freshly allocated {loc}"
        new_conjuncts = list(heap.separating_conjuncts) + [alloc_note]
        new_fp = heap.footprint | {loc}

        allocated = HeapSummary(
            location_sort=heap.location_sort,
            value_sort=heap.value_sort,
            points_to_map=dict(heap.points_to_map),
            footprint=new_fp,
            separating_conjuncts=new_conjuncts,
            frame_condition=heap.frame_condition,
            heap_id=heap_id,
            metadata={
                "heap_kind": "allocated",
                "name": alloc_name,
                "declarations": list(heap.metadata.get("declarations", [])),
                "allocated_loc": loc,
                "parent": h_name,
            },
        )
        self._heap_cache[heap_id] = allocated
        logger.debug(
            "encode_allocation: allocated %r in heap %r", loc, h_name
        )
        return allocated

    def encode_deallocation(
        self, heap: HeapSummary, loc: str
    ) -> HeapSummary:
        """Return a new heap with location *loc* removed from the footprint.

        Deallocation invalidates the points-to assertion for *loc* and
        removes it from the footprint.  A note is added to the conjuncts to
        record the event.

        Args:
            heap: The existing heap.
            loc: Location identifier to deallocate.

        Returns:
            A new :class:`HeapSummary` with ``metadata["heap_kind"] == "deallocated"``
            and *loc* removed from the footprint.

        Raises:
            ValueError: If *loc* is not in the heap's footprint.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_points_to("3", "99", heap_name="hd")
            >>> freed = encoder.encode_deallocation(h, "3")
            >>> "3" not in freed.footprint
            True
        """
        if loc not in heap.footprint:
            raise ValueError(
                f"Location {loc!r} is not in the footprint of heap "
                f"{heap.metadata.get('name', heap.heap_id)!r}; cannot deallocate"
            )

        h_name = heap.metadata.get("name", heap.heap_id[:8])
        dealloc_name = f"dealloc_{h_name}_{loc}"
        heap_id = self._make_heap_id(dealloc_name, "deallocated")
        if heap_id in self._heap_cache:
            return self._heap_cache[heap_id]

        dealloc_note = f"(assert true) ; deallocated {loc}"
        new_conjuncts = list(heap.separating_conjuncts) + [dealloc_note]
        new_fp = heap.footprint - {loc}
        new_pts = {l: v for l, v in heap.points_to_map.items() if l != loc}
        self._footprint_tracker.pop(loc, None)

        deallocated = HeapSummary(
            location_sort=heap.location_sort,
            value_sort=heap.value_sort,
            points_to_map=new_pts,
            footprint=new_fp,
            separating_conjuncts=new_conjuncts,
            frame_condition=heap.frame_condition,
            heap_id=heap_id,
            metadata={
                "heap_kind": "deallocated",
                "name": dealloc_name,
                "declarations": list(heap.metadata.get("declarations", [])),
                "freed_loc": loc,
                "parent": h_name,
            },
        )
        self._heap_cache[heap_id] = deallocated
        logger.debug(
            "encode_deallocation: freed %r from heap %r", loc, h_name
        )
        return deallocated

    def verify_separation(
        self,
        h1: HeapSummary,
        h2: HeapSummary,
        session: Any,
    ) -> Any:
        """Build and check a Z3 query asserting h1 and h2 have disjoint footprints.

        Constructs an SMT-LIB2 script that declares integer constants for
        every location in both footprints, then asserts that all cross-product
        pairs are distinct.  Returns SAT if separation holds.

        Args:
            h1: First heap summary.
            h2: Second heap summary.
            session: A Z3Session-compatible object with a ``check`` method.

        Returns:
            A :class:`~jugeo.solver.z3_session.Z3Result` — SAT means disjoint,
            UNSAT means aliases exist.

        Raises:
            RuntimeError: If *session* is ``None``.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h1 = encoder.encode_points_to("0", "1")
            >>> h2 = encoder.encode_points_to("1", "2")
            >>> # result = encoder.verify_separation(h1, h2, session)
        """
        if session is None:
            raise RuntimeError("Z3 session required for verify_separation")

        all_locs = h1.footprint | h2.footprint
        lines: list[str] = ["(set-logic QF_LIA)"]
        for loc in sorted(all_locs):
            loc_lit = self._loc_to_smt2(loc)
            lines.append(f"(declare-const loc_{loc_lit} Int)")
            lines.append(f"(assert (= loc_{loc_lit} {loc_lit}))")

        for l1 in sorted(h1.footprint):
            for l2 in sorted(h2.footprint):
                ll1 = self._loc_to_smt2(l1)
                ll2 = self._loc_to_smt2(l2)
                lines.append(f"(assert (not (= {ll1} {ll2})))")

        lines.append("(check-sat)")
        smt2 = "\n".join(lines)
        logger.debug(
            "verify_separation: %d locs, query size %d", len(all_locs), len(smt2)
        )
        if hasattr(session, "check_smt2"):
            return session.check_smt2(smt2)
        return session.check(smt2)

    def verify_entailment(
        self,
        premise: HeapSummary,
        conclusion: HeapSummary,
        session: Any,
    ) -> Any:
        """Check that *premise* logically entails *conclusion*.

        Builds an SMT-LIB2 query asserting all conjuncts of *premise* and the
        negation of the conclusion's conjuncts.  UNSAT means the entailment is
        valid (premise ⊨ conclusion).

        Args:
            premise: The antecedent heap.
            conclusion: The consequent heap.
            session: A Z3Session-compatible object.

        Returns:
            A :class:`~jugeo.solver.z3_session.Z3Result` — UNSAT iff valid.

        Raises:
            RuntimeError: If *session* is ``None``.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_points_to("0", "5", heap_name="ent_h")
            >>> # result = encoder.verify_entailment(h, h, session)
            >>> # UNSAT means h ⊨ h (reflexivity)
        """
        if session is None:
            raise RuntimeError("Z3 session required for verify_entailment")

        all_decls = list(dict.fromkeys(
            premise.metadata.get("declarations", [])
            + conclusion.metadata.get("declarations", [])
        ))

        # Negate each conclusion conjunct in turn
        neg_parts: list[str] = []
        for conj in conclusion.separating_conjuncts:
            inner = conj.strip()
            if inner.startswith("(assert "):
                inner = inner[len("(assert "):-1]
            if inner.strip() in {"true", "(assert true)"}:
                continue
            neg_parts.append(f"(not {inner})")

        if not neg_parts:
            lines = ["(set-logic QF_AUFLIA)", *all_decls,
                     *premise.separating_conjuncts, "(check-sat)"]
        else:
            neg_disj = (
                f"(or {' '.join(neg_parts)})"
                if len(neg_parts) > 1 else neg_parts[0]
            )
            lines = [
                "(set-logic QF_AUFLIA)",
                *all_decls,
                *premise.separating_conjuncts,
                f"(assert {neg_disj})",
                "(check-sat)",
            ]
        smt2 = "\n".join(lines)
        logger.debug("verify_entailment: query size %d", len(smt2))
        if hasattr(session, "check_smt2"):
            return session.check_smt2(smt2)
        return session.check(smt2)

    def extract_footprint(self, heap: HeapSummary) -> frozenset[str]:
        """Return the footprint of *heap*.

        Args:
            heap: The :class:`HeapSummary` to inspect.

        Returns:
            The ``footprint`` frozenset.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_points_to("loc0", "0")
            >>> fp = encoder.extract_footprint(h)
            >>> "loc0" in fp
            True
        """
        return heap.footprint

    def to_separation_formula(self, heap: HeapSummary) -> str:
        """Produce a human-readable separation-logic formula for *heap*.

        Returns a string like ``"loc0 ↦ 42 * loc1 ↦ 7"`` or ``"emp"`` for
        the empty heap.

        Args:
            heap: The :class:`HeapSummary` to render.

        Returns:
            A Unicode separation-logic formula string.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_empty_heap(name="sl_empty")
            >>> encoder.to_separation_formula(h)
            'emp'
        """
        pts = heap.points_to_map
        if not pts:
            return _EMP_HEAP_EXPR
        parts = [f"{loc} ↦ {val}" for loc, val in sorted(pts.items())]
        formula = _STAR_SEPARATOR.join(parts)
        if heap.frame_condition:
            formula = f"({formula}) * frame({heap.frame_condition})"
        return formula

    def to_smt2(self, heap: HeapSummary) -> str:
        """Serialize the complete heap encoding to an SMT-LIB2 string.

        The output is a valid SMT-LIB2 script containing:
        * A header comment with encoding metadata.
        * A ``(set-logic QF_AUFLIA)`` directive.
        * All declarations.
        * All separating conjuncts.
        * A ``(check-sat)`` footer.

        Args:
            heap: The :class:`HeapSummary` to serialize.

        Returns:
            A multi-line SMT-LIB2 string.

        Example:
            >>> encoder = HeapSummaryEncoder()
            >>> h = encoder.encode_empty_heap(name="smt2_test")
            >>> smt = encoder.to_smt2(h)
            >>> "(check-sat)" in smt
            True
        """
        hk = heap.metadata.get("heap_kind", "?")
        name = heap.metadata.get("name", heap.heap_id[:8])
        lines: list[str] = [
            f"; JuGeo heap encoding v{_HEAP_ENCODING_VERSION}",
            f"; heap_kind={hk}  name={name}",
            f"; footprint_size={len(heap.footprint)}",
            "(set-logic QF_AUFLIA)",
            "",
            "; --- Declarations ---",
        ]
        for decl in heap.metadata.get("declarations", []):
            lines.append(decl)
        lines.append("")
        lines.append("; --- Separating Conjuncts ---")
        for conj in heap.separating_conjuncts:
            lines.append(conj)
        if heap.frame_condition:
            lines.append("")
            lines.append("; --- Frame Condition ---")
            lines.append(f"(assert {heap.frame_condition})")
        lines.append("")
        lines.append("(check-sat)")
        lines.append("(get-model)")
        return "\n".join(lines)

    def clear_cache(self) -> None:
        """Invalidate the internal heap cache and footprint tracker."""
        self._heap_cache.clear()
        self._footprint_tracker.clear()
        logger.debug("HeapSummaryEncoder: cache cleared")

    def get_composition_log(self) -> list[tuple[str, str, str]]:
        """Return the composition log as a list of (h1_name, op, h2_name) tuples.

        Returns:
            A copy of the internal composition log.
        """
        return list(self._composition_log)


