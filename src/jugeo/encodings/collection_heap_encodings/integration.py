class CollectionHeapEncodingSession:
    """Orchestrates all five encoder modules (s01–s05) in a coherent session.

    The session accumulates encoded artifacts—collections, heap summaries,
    aliasing obligations, and interface abstractions—and exposes verification
    entry-points that delegate to the appropriate sub-encoder.

    Typical usage::

        sess = CollectionHeapEncodingSession()
        enc = sess.add_collection("xs", [1, 2, 3], "Int")
        hsumm = sess.add_heap_entry("p", "node")
        sess.add_alias_pair("p", "q", must_alias=False)
        iface = sess.add_interface("Stack", {"push": (["Int"], "Unit")})
        results = sess.verify_program_state(z3_session)
    """

    def __init__(self) -> None:
        self.logger = logging.getLogger(f"{__name__}.{type(self).__name__}")
        self._session_id: str = str(uuid.uuid4())
        self._collection_encoder = CollectionEncoder()
        self._heap_encoder = HeapSummaryEncoder()
        self._alias_builder = AliasPartitionBuilder()
        self._disjointness_checker = DisjointnessChecker()
        self._interface_encoder = InterfaceSummaryEncoder()
        self._boundary_encoder = ExactBoundaryEncoder()

        self._encoded_collections: list[CollectionEncoding] = []
        self._heap_summaries: list[HeapSummary] = []
        self._aliasing_obligations: list[AliasingObligation] = []
        self._interface_abstractions: list[InterfaceAbstraction] = []
        self._z3_session: Z3Session | None = None
        self._monitor = _PipelineMonitor(self._session_id)

    # ------------------------------------------------------------------
    # Main encoding entry-points
    # ------------------------------------------------------------------

    def encode_program_state(
        self,
        collections: dict[str, tuple[list, str]],
        heap: dict[str, str],
        aliases: list[tuple[str, str]],
    ) -> tuple[list[CollectionEncoding], list[HeapSummary], AliasingObligation]:
        """Encode a complete program state description.

        Parameters
        ----------
        collections:
            Mapping from collection name to ``(items, element_type)`` pairs.
        heap:
            Mapping from heap location name to value type.
        aliases:
            List of ``(ptr1, ptr2)`` pairs declaring potential aliasing.

        Returns
        -------
        tuple
            ``(encoded_collections, heap_summaries, aliasing_obligation)``
        """
        self.logger.info(
            "session=%s encoding program state: %d collections, %d heap entries, "
            "%d alias pairs",
            self._session_id[:8],
            len(collections),
            len(heap),
            len(aliases),
        )

        # --- Encode collections via s01 ---
        encoded: list[CollectionEncoding] = []
        for name, (items, elt_type) in collections.items():
            enc = self._collection_encoder.encode(name, items, elt_type)
            self._encoded_collections.append(enc)
            encoded.append(enc)
            self.logger.debug("Encoded collection %r (%d items, type=%s)", name, len(items), elt_type)

        # --- Encode heap entries via s02 ---
        summaries: list[HeapSummary] = []
        for loc, val_type in heap.items():
            summ = self._heap_encoder.encode_entry(loc, val_type)
            self._heap_summaries.append(summ)
            summaries.append(summ)
            self.logger.debug("Encoded heap entry %r -> %s", loc, val_type)

        # --- Accumulate aliasing obligations via s03 ---
        for p1, p2 in aliases:
            self._alias_builder.add_pair(p1, p2)
        obligation = self._alias_builder.build()
        self._aliasing_obligations.append(obligation)
        self.logger.debug("Built aliasing obligation for %d pairs", len(aliases))

        return encoded, summaries, obligation

    def verify_program_state(self, session: Z3Session) -> dict[str, Z3Result]:
        """Verify all encoded invariants against the given Z3Session.

        Checks collection invariants, heap separation obligations, and
        aliasing consistency in sequence.

        Parameters
        ----------
        session:
            An active Z3Session to use for verification.

        Returns
        -------
        dict[str, Z3Result]
            Mapping from check name (e.g. ``"collection_inv[xs]"``) to result.
        """
        self._z3_session = session
        results: dict[str, Z3Result] = {}

        # -- Collection invariants --
        inv_checker = CollectionInvariantChecker()
        for enc in self._encoded_collections:
            key = f"collection_inv[{enc.name}]"
            results[key] = inv_checker.check(enc, session)
            self.logger.debug("Collection invariant check %r -> %s", key, results[key])

        # -- Heap separation --
        heap_checker = HeapInvariantChecker()
        if self._heap_summaries:
            key = "heap_separation"
            results[key] = heap_checker.check_separation(self._heap_summaries, session)
            self.logger.debug("Heap separation check -> %s", results[key])

        # -- Aliasing consistency --
        for i, obl in enumerate(self._aliasing_obligations):
            key = f"alias_consistency[{i}]"
            results[key] = self._disjointness_checker.check(obl, session)
            self.logger.debug("Aliasing check %r -> %s", key, results[key])

        # -- Interface conformance --
        ref_checker = InterfaceRefinementChecker()
        for iface in self._interface_abstractions:
            key = f"interface_conformance[{iface.name}]"
            results[key] = ref_checker.check(iface, session)
            self.logger.debug("Interface check %r -> %s", key, results[key])

        return results

    def add_collection(
        self, name: str, items: list, element_type: str
    ) -> CollectionEncoding:
        """Encode a single collection and register it in the session.

        Parameters
        ----------
        name:
            Logical name of the collection (used in Z3 sorts and assertions).
        items:
            Python list of concrete element values.
        element_type:
            SMT-LIB2 sort name for the elements (e.g. ``"Int"``, ``"Bool"``).

        Returns
        -------
        CollectionEncoding
            The encoded collection artefact.
        """
        enc = self._collection_encoder.encode(name, items, element_type)
        self._encoded_collections.append(enc)
        self.logger.debug(
            "add_collection: name=%r items=%d type=%s", name, len(items), element_type
        )
        return enc

    def add_heap_entry(self, loc: str, val: str) -> HeapSummary:
        """Add a points-to heap entry to the session heap.

        Parameters
        ----------
        loc:
            Heap location identifier (e.g. pointer variable name).
        val:
            Value type or concrete value stored at *loc*.

        Returns
        -------
        HeapSummary
            The heap summary artefact for this entry.
        """
        summ = self._heap_encoder.encode_entry(loc, val)
        self._heap_summaries.append(summ)
        self.logger.debug("add_heap_entry: loc=%r val=%s", loc, val)
        return summ

    def add_alias_pair(self, p1: str, p2: str, must_alias: bool = False) -> None:
        """Record an aliasing constraint between two pointer names.

        Parameters
        ----------
        p1, p2:
            Pointer variable names.
        must_alias:
            If *True*, the constraint asserts *p1 == p2*; otherwise it asserts
            a may-alias relationship that must be resolved by the solver.
        """
        self._alias_builder.add_pair(p1, p2, must_alias=must_alias)
        self.logger.debug(
            "add_alias_pair: p1=%r p2=%r must_alias=%s", p1, p2, must_alias
        )

    def add_interface(
        self, name: str, methods: dict[str, tuple[list, str]]
    ) -> InterfaceAbstraction:
        """Encode an interface abstraction and register it in the session.

        Parameters
        ----------
        name:
            Interface name (e.g. ``"Stack"``, ``"Map"``).
        methods:
            Mapping from method name to ``(parameter_types, return_type)``.

        Returns
        -------
        InterfaceAbstraction
            The encoded interface abstraction.
        """
        iface = self._interface_encoder.encode(name, methods)
        self._interface_abstractions.append(iface)
        self.logger.debug(
            "add_interface: name=%r methods=%s", name, list(methods)
        )
        return iface

    def summarize_encoding(self) -> str:
        """Return a human-readable summary of all encoded state held in this session."""
        lines = [
            f"CollectionHeapEncodingSession [{self._session_id[:8]}]",
            f"  Collections ({len(self._encoded_collections)}):",
        ]
        for enc in self._encoded_collections:
            lines.append(f"    - {enc.name}: {enc.element_type}, size={enc.size}")
        lines.append(f"  Heap summaries ({len(self._heap_summaries)}):")
        for hs in self._heap_summaries:
            lines.append(f"    - {hs.location} -> {hs.value_type}")
        lines.append(f"  Aliasing obligations ({len(self._aliasing_obligations)}):")
        for i, obl in enumerate(self._aliasing_obligations):
            lines.append(f"    [{i}] {obl!s}")
        lines.append(f"  Interface abstractions ({len(self._interface_abstractions)}):")
        for iface in self._interface_abstractions:
            lines.append(f"    - {iface.name}: {list(iface.methods)}")
        return "\n".join(lines)

    def reset(self) -> None:
        """Clear all encoded state, returning the session to its initial condition."""
        self._encoded_collections.clear()
        self._heap_summaries.clear()
        self._aliasing_obligations.clear()
        self._interface_abstractions.clear()
        self._alias_builder = AliasPartitionBuilder()
        self._z3_session = None
        self.logger.info("session=%s reset", self._session_id[:8])

    def to_smt2(self) -> str:
        """Serialize all encoded constraints to an SMT-LIB2 string.

        The output is suitable for consumption by any SMT solver that
        understands the SMT-LIB2 standard (e.g., Z3, CVC5).
        """
        ser = Z3Serializer()
        chunks: list[str] = ["(set-logic ALL)", ""]

        # Collections
        for enc in self._encoded_collections:
            chunks.append(f"; Collection: {enc.name}")
            chunks.append(ser.collection_to_smt2(enc))

        # Heap summaries
        for hs in self._heap_summaries:
            chunks.append(f"; Heap entry: {hs.location}")
            chunks.append(ser.heap_summary_to_smt2(hs))

        # Aliasing obligations
        for obl in self._aliasing_obligations:
            chunks.append("; Aliasing obligation")
            chunks.append(ser.aliasing_to_smt2(obl))

        # Interface abstractions
        for iface in self._interface_abstractions:
            chunks.append(f"; Interface: {iface.name}")
            chunks.append(ser.interface_to_smt2(iface))

        chunks.append("(check-sat)")
        return "\n".join(chunks)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _ensure_session(self) -> Z3Session:
        """Return the cached Z3Session, creating a new one if necessary."""
        if self._z3_session is None:
            self._z3_session = Z3Session()
        return self._z3_session

    def _combine_results(self, results: list[Z3Result]) -> Z3Result:
        """Combine a list of Z3Results into a single aggregate result.

        The combined result is SAT only if every individual result is SAT.
        If any result is UNSAT, the combined result is UNSAT.  UNKNOWN
        propagates if no UNSAT is found.
        """
        if not results:
            return Z3Result(outcome=SolveOutcome.UNKNOWN, model=None, reason="no checks")
        outcomes = [r.outcome for r in results]
        if SolveOutcome.UNSAT in outcomes:
            return Z3Result(outcome=SolveOutcome.UNSAT, model=None, reason="combined")
        if SolveOutcome.UNKNOWN in outcomes:
            return Z3Result(outcome=SolveOutcome.UNKNOWN, model=None, reason="combined")
        return Z3Result(outcome=SolveOutcome.SAT, model=None, reason="combined")


