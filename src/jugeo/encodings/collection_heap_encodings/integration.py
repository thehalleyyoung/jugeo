class EncoderRegistry:
    """Dynamic registry mapping encoder names to their implementation classes.

    The registry is the single source of truth for which encoder classes are
    available in the pipeline.  It supports lazy instantiation so that encoder
    objects are only created when first requested.

    Example
    -------
    .. code-block:: python

        reg = EncoderRegistry.default_registry()
        cls = reg.lookup("CollectionEncoder")
        inst = reg.get_instance("CollectionEncoder")
    """

    def __init__(self) -> None:
        self._registry: dict[str, type] = {}
        self._instances: dict[str, Any] = {}
        self.logger = logging.getLogger(f"{__name__}.{type(self).__name__}")

    # ------------------------------------------------------------------
    # Registration
    # ------------------------------------------------------------------

    def register(self, encoder_class: type, name: str) -> None:
        """Register *encoder_class* under the given *name*.

        Parameters
        ----------
        encoder_class:
            The encoder class to register.  Must be instantiable with no
            required constructor arguments.
        name:
            Unique string key used to look up this encoder.
        """
        if name in self._registry:
            self.logger.warning(
                "Overwriting existing registration for %r with %s", name, encoder_class
            )
        self._registry[name] = encoder_class
        # Invalidate any cached instance.
        self._instances.pop(name, None)
        self.logger.debug("Registered encoder %r -> %s", name, encoder_class.__name__)

    def unregister(self, name: str) -> None:
        """Remove an encoder registration.

        Parameters
        ----------
        name:
            The name to deregister.

        Raises
        ------
        KeyError
            If *name* is not registered.
        """
        if name not in self._registry:
            raise KeyError(f"Encoder {name!r} is not registered")
        del self._registry[name]
        self._instances.pop(name, None)
        self.logger.debug("Unregistered encoder %r", name)

    # ------------------------------------------------------------------
    # Lookup
    # ------------------------------------------------------------------

    def lookup(self, name: str) -> type:
        """Return the encoder class registered under *name*.

        Raises
        ------
        KeyError
            If *name* has not been registered.
        """
        try:
            return self._registry[name]
        except KeyError:
            available = ", ".join(sorted(self._registry))
            raise KeyError(
                f"Encoder {name!r} not found. Available: {available}"
            ) from None

    def get_instance(self, name: str) -> Any:
        """Return a cached instance of the encoder registered under *name*.

        The instance is created lazily on first access and reused thereafter.

        Raises
        ------
        KeyError
            If *name* has not been registered.
        TypeError
            If the encoder class cannot be instantiated with zero arguments.
        """
        if name not in self._instances:
            cls = self.lookup(name)
            self._instances[name] = cls()
            self.logger.debug("Instantiated encoder %r", name)
        return self._instances[name]

    def list_encoders(self) -> list[str]:
        """Return a sorted list of all registered encoder names."""
        return sorted(self._registry)

    def is_registered(self, name: str) -> bool:
        """Return *True* iff *name* is currently registered."""
        return name in self._registry

    # ------------------------------------------------------------------
    # Class-level factory
    # ------------------------------------------------------------------

    @classmethod
    def default_registry(cls) -> EncoderRegistry:
        """Create and return a registry pre-populated with all built-in encoders.

        The built-in encoders are the five sub-modules (s01–s05) plus the
        composition helpers.

        Returns
        -------
        EncoderRegistry
            Registry with all built-in encoders registered.
        """
        reg = cls()
        _builtins: list[tuple[type, str]] = [
            (CollectionEncoder, "CollectionEncoder"),
            (CollectionInvariantChecker, "CollectionInvariantChecker"),
            (CollectionFragmentClassifier, "CollectionFragmentClassifier"),
            (HeapSummaryEncoder, "HeapSummaryEncoder"),
            (HeapCompositionEngine, "HeapCompositionEngine"),
            (HeapInvariantChecker, "HeapInvariantChecker"),
            (AliasPartitionBuilder, "AliasPartitionBuilder"),
            (DisjointnessChecker, "DisjointnessChecker"),
            (InterfaceSummaryEncoder, "InterfaceSummaryEncoder"),
            (InterfaceRefinementChecker, "InterfaceRefinementChecker"),
            (AbstractSortBuilder, "AbstractSortBuilder"),
            (ExactBoundaryEncoder, "ExactBoundaryEncoder"),
            (BoundaryVerifier, "BoundaryVerifier"),
            (NonAliasingLawLibrary, "NonAliasingLawLibrary"),
        ]
        for enc_cls, name in _builtins:
            reg.register(enc_cls, name)
        reg.logger.info("Default registry created with %d encoders", len(_builtins))
        return reg


