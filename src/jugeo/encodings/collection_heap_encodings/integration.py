@dataclass(slots=True)
class PipelineResult:
    """Result produced by a completed or partially-completed pipeline run.

    Attributes
    ----------
    stage:
        The pipeline stage at which this result was captured.
    success:
        Whether the pipeline completed successfully up to this stage.
    collections_encoded:
        Number of collections that were encoded by s01.
    heap_summaries:
        Number of heap summaries produced by s02.
    aliases_verified:
        Whether aliasing obligations were successfully discharged.
    interface_abstractions:
        Number of interface abstractions encoded by s04.
    boundary_conditions:
        Number of boundary conditions encoded by s05.
    z3_results:
        Mapping from check names to their Z3Result objects.
    error_message:
        Optional error message if the pipeline failed.
    wall_time_ms:
        Total wall-clock time consumed by the pipeline run in milliseconds.
    metadata:
        Arbitrary additional metadata attached during the run.
    """

    stage: PipelineStage
    success: bool
    collections_encoded: int
    heap_summaries: int
    aliases_verified: bool
    interface_abstractions: int
    boundary_conditions: int
    z3_results: dict[str, Z3Result]
    error_message: str | None
    wall_time_ms: float
    metadata: dict[str, Any]

    def is_complete(self) -> bool:
        """Return True iff the pipeline reached the COMPLETE stage successfully."""
        return self.stage is PipelineStage.COMPLETE and self.success

    def summary(self) -> str:
        """Return a concise human-readable summary of the pipeline result."""
        status_str = "SUCCESS" if self.success else "FAILURE"
        parts = [
            f"PipelineResult[{self.stage.value}] {status_str}",
            f"  collections_encoded : {self.collections_encoded}",
            f"  heap_summaries      : {self.heap_summaries}",
            f"  aliases_verified    : {self.aliases_verified}",
            f"  interface_abs       : {self.interface_abstractions}",
            f"  boundary_conds      : {self.boundary_conditions}",
            f"  z3_checks           : {len(self.z3_results)}",
            f"  wall_time_ms        : {self.wall_time_ms:.2f}",
        ]
        if self.error_message:
            parts.append(f"  error               : {self.error_message}")
        return "\n".join(parts)

    def to_dict(self) -> dict[str, Any]:
        """Serialise this result to a plain dictionary."""
        return {
            "stage": self.stage.value,
            "success": self.success,
            "collections_encoded": self.collections_encoded,
            "heap_summaries": self.heap_summaries,
            "aliases_verified": self.aliases_verified,
            "interface_abstractions": self.interface_abstractions,
            "boundary_conditions": self.boundary_conditions,
            "z3_results": {k: str(v) for k, v in self.z3_results.items()},
            "error_message": self.error_message,
            "wall_time_ms": self.wall_time_ms,
            "metadata": self.metadata,
        }


# ---------------------------------------------------------------------------
# _StageTimer — context manager
# ---------------------------------------------------------------------------


class _StageTimer:
    """Context manager that measures elapsed wall-clock time for a pipeline stage.

    Usage::

        with _StageTimer("collection_encoding") as t:
            do_work()
        print(t.elapsed_ms)
    """

    def __init__(self, stage_name: str) -> None:
        self.stage_name = stage_name
        self._start: float = 0.0
        self.elapsed_ms: float = 0.0

    def __enter__(self) -> _StageTimer:
        self._start = time.perf_counter()
        return self

    def __exit__(self, *_: object) -> None:
        self.elapsed_ms = (time.perf_counter() - self._start) * 1_000.0


# ---------------------------------------------------------------------------
# _PipelineMonitor — timing and logging helper
# ---------------------------------------------------------------------------


class _PipelineMonitor:
    """Lightweight timing and structured-logging helper for pipeline stages.

    Each pipeline instance owns a monitor; stages call ``begin`` / ``end``
    to record durations.  The monitor also emits structured log records at
    DEBUG level so that external log aggregators can track stage performance.
    """

    def __init__(self, pipeline_id: str) -> None:
        self._pipeline_id = pipeline_id
        self._stage_times: dict[str, float] = {}
        self._stage_order: list[str] = []
        self._logger = logging.getLogger(f"{__name__}.monitor.{pipeline_id[:8]}")

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    @contextmanager
    def timed_stage(self, stage: PipelineStage) -> Generator[_StageTimer, None, None]:
        """Context manager that times *stage* and records the duration."""
        self._logger.debug(
            "pipeline=%s stage=%s action=begin", self._pipeline_id, stage.value
        )
        with _StageTimer(stage.value) as timer:
            yield timer
        self._stage_times[stage.value] = timer.elapsed_ms
        self._stage_order.append(stage.value)
        self._logger.debug(
            "pipeline=%s stage=%s action=end elapsed_ms=%.2f",
            self._pipeline_id,
            stage.value,
            timer.elapsed_ms,
        )

    def total_ms(self) -> float:
        """Total elapsed milliseconds across all timed stages."""
        return sum(self._stage_times.values())

    def stage_breakdown(self) -> dict[str, float]:
        """Return a copy of the per-stage timing dictionary."""
        return dict(self._stage_times)

    def report(self) -> str:
        """Return a formatted timing report for all recorded stages."""
        lines = [f"Pipeline timing report [{self._pipeline_id[:8]}]"]
        for stage_name in self._stage_order:
            ms = self._stage_times[stage_name]
            lines.append(f"  {stage_name:<30} {ms:>10.2f} ms")
        lines.append(f"  {'TOTAL':<30} {self.total_ms():>10.2f} ms")
        return "\n".join(lines)

    def log_event(self, event: str, **kwargs: Any) -> None:
        """Emit a structured DEBUG log event with arbitrary key-value context."""
        kv = " ".join(f"{k}={v!r}" for k, v in kwargs.items())
        self._logger.debug("pipeline=%s event=%s %s", self._pipeline_id, event, kv)


