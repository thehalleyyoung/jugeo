class HeapCollectionPipeline:
    """End-to-end encoding and verification pipeline for collection-heap states.

    The pipeline accepts a high-level ``source_state`` dictionary and drives
    all five encoder modules to produce a verified Z3 encoding.  Results are
    captured in a :class:`PipelineResult` that records both the Z3 outcomes and
    timing metadata.

    Typical usage::

        pipeline = create_pipeline()
        result = pipeline.run(source_state, z3_session)
        if result.is_complete():
            print(pipeline.report(result))

    ``source_state`` schema::

        {
            "collections": {<name>: [<items>, <element_type>], ...},
            "heap":        {<location>: <value_type>, ...},
            "aliases":     [[<ptr1>, <ptr2>], ...],
            "interfaces":  {<name>: {<method>: [[<param_types>], <ret_type>]}, ...},
        }
    """

    def __init__(
        self,
        session: CollectionHeapEncodingSession | None = None,
        registry: EncoderRegistry | None = None,
    ) -> None:
        self.logger = logging.getLogger(f"{__name__}.{type(self).__name__}")
        self._session = session or CollectionHeapEncodingSession()
        self._registry = registry or EncoderRegistry.default_registry()
        self._stages_completed: list[PipelineStage] = []
        self._current_stage: PipelineStage = PipelineStage.COLLECTION_ENCODING
        self._result: PipelineResult | None = None
        self._stage_data: dict[PipelineStage, Any] = {}
        self._pipeline_id = str(uuid.uuid4())
        self._monitor = _PipelineMonitor(self._pipeline_id)

    # ------------------------------------------------------------------
    # Main entry-point
    # ------------------------------------------------------------------

    def run(
        self, source_state: dict[str, Any], z3_session: Z3Session
    ) -> PipelineResult:
        """Execute the full pipeline for the given *source_state*.

        The pipeline runs the following stages in order:
        1. COLLECTION_ENCODING (s01)
        2. HEAP_SUMMARIZATION (s02)
        3. ALIAS_ANALYSIS (s03)
        4. INTERFACE_ABSTRACTION (s04)
        5. BOUNDARY_ENCODING (s05)
        6. VERIFICATION

        If any stage fails, the pipeline transitions to FAILED and returns
        a partial result with the error message.

        Parameters
        ----------
        source_state:
            High-level program state description; see class docstring.
        z3_session:
            Active Z3Session to use for constraint checking.

        Returns
        -------
        PipelineResult
            Final result of the pipeline run.
        """
        self.reset()
        self._monitor.log_event("run_start", pipeline_id=self._pipeline_id[:8])
        overall_start = time.perf_counter()

        try:
            # Parse
            collections, heap, aliases, interfaces = self._parse_source_state(source_state)

            # Stage 1 — collection encoding
            self._current_stage = PipelineStage.COLLECTION_ENCODING
            with self._monitor.timed_stage(PipelineStage.COLLECTION_ENCODING):
                ok = self._run_collection_stage(collections)
            if not ok:
                return self._fail("Collection encoding stage failed")
            self._stages_completed.append(PipelineStage.COLLECTION_ENCODING)

            # Stage 2 — heap summarization
            self._current_stage = PipelineStage.HEAP_SUMMARIZATION
            with self._monitor.timed_stage(PipelineStage.HEAP_SUMMARIZATION):
                ok = self._run_heap_stage(heap)
            if not ok:
                return self._fail("Heap summarization stage failed")
            self._stages_completed.append(PipelineStage.HEAP_SUMMARIZATION)

            # Stage 3 — alias analysis
            self._current_stage = PipelineStage.ALIAS_ANALYSIS
            with self._monitor.timed_stage(PipelineStage.ALIAS_ANALYSIS):
                ok = self._run_alias_stage(aliases)
            if not ok:
                return self._fail("Alias analysis stage failed")
            self._stages_completed.append(PipelineStage.ALIAS_ANALYSIS)

            # Stage 4 — interface abstraction
            self._current_stage = PipelineStage.INTERFACE_ABSTRACTION
            with self._monitor.timed_stage(PipelineStage.INTERFACE_ABSTRACTION):
                ok = self._run_interface_stage(interfaces)
            if not ok:
                return self._fail("Interface abstraction stage failed")
            self._stages_completed.append(PipelineStage.INTERFACE_ABSTRACTION)

            # Stage 5 — boundary encoding
            self._current_stage = PipelineStage.BOUNDARY_ENCODING
            with self._monitor.timed_stage(PipelineStage.BOUNDARY_ENCODING):
                ok = self._run_boundary_stage()
            if not ok:
                return self._fail("Boundary encoding stage failed")
            self._stages_completed.append(PipelineStage.BOUNDARY_ENCODING)

            # Stage 6 — verification
            self._current_stage = PipelineStage.VERIFICATION
            with self._monitor.timed_stage(PipelineStage.VERIFICATION):
                ok, z3_results = self._run_verification_stage(z3_session)
            if not ok:
                return self._fail("Verification stage failed", z3_results=z3_results)
            self._stages_completed.append(PipelineStage.VERIFICATION)

        except Exception as exc:  # noqa: BLE001
            self.logger.exception("Pipeline %r raised an unexpected exception", self._pipeline_id[:8])
            return self._fail(str(exc))

        wall_ms = (time.perf_counter() - overall_start) * 1_000.0
        self._result = PipelineResult(
            stage=PipelineStage.COMPLETE,
            success=True,
            collections_encoded=len(self._session._encoded_collections),
            heap_summaries=len(self._session._heap_summaries),
            aliases_verified=True,
            interface_abstractions=len(self._session._interface_abstractions),
            boundary_conditions=len(self._stage_data.get(PipelineStage.BOUNDARY_ENCODING, [])),
            z3_results=z3_results,
            error_message=None,
            wall_time_ms=wall_ms,
            metadata=self._monitor.stage_breakdown(),
        )
        self._stages_completed.append(PipelineStage.COMPLETE)
        self._monitor.log_event("run_complete", success=True, wall_ms=f"{wall_ms:.2f}")
        return self._result

    # ------------------------------------------------------------------
    # Stage runners
    # ------------------------------------------------------------------

    def _parse_source_state(
        self, state: dict
    ) -> tuple[dict, dict, list, dict]:
        """Decompose a raw *source_state* dict into typed sub-dicts.

        Returns ``(collections, heap, aliases, interfaces)``.
        """
        collections = state.get("collections", {})
        heap = state.get("heap", {})
        raw_aliases = state.get("aliases", [])
        interfaces = state.get("interfaces", {})

        # Normalise aliases — accept both lists and tuples
        aliases: list[tuple[str, str]] = []
        for pair in raw_aliases:
            if len(pair) == 2:
                aliases.append((str(pair[0]), str(pair[1])))
            else:
                self.logger.warning("Skipping malformed alias entry: %r", pair)

        self.logger.debug(
            "Parsed source_state: %d collections, %d heap, %d aliases, %d interfaces",
            len(collections), len(heap), len(aliases), len(interfaces),
        )
        return collections, heap, aliases, interfaces

    def _run_collection_stage(
        self, collections: dict[str, Any]
    ) -> bool:
        """Encode all collections in *collections*."""
        encoded = []
        for name, spec in collections.items():
            try:
                if isinstance(spec, (list, tuple)) and len(spec) == 2:
                    items, elt_type = spec
                else:
                    items, elt_type = list(spec), "Any"
                enc = self._session.add_collection(name, items, elt_type)
                encoded.append(enc)
            except Exception as exc:  # noqa: BLE001
                self.logger.error("Failed to encode collection %r: %s", name, exc)
                return False
        self._stage_data[PipelineStage.COLLECTION_ENCODING] = encoded
        self.logger.info("Collection stage: encoded %d collections", len(encoded))
        return True

    def _run_heap_stage(self, heap: dict[str, str]) -> bool:
        """Encode all heap entries in *heap*."""
        summaries = []
        for loc, val_type in heap.items():
            try:
                summ = self._session.add_heap_entry(loc, val_type)
                summaries.append(summ)
            except Exception as exc:  # noqa: BLE001
                self.logger.error("Failed to encode heap entry %r: %s", loc, exc)
                return False
        self._stage_data[PipelineStage.HEAP_SUMMARIZATION] = summaries
        self.logger.info("Heap stage: encoded %d entries", len(summaries))
        return True

    def _run_alias_stage(self, aliases: list[tuple[str, str]]) -> bool:
        """Process all alias pairs."""
        try:
            for p1, p2 in aliases:
                self._session.add_alias_pair(p1, p2)
            self._stage_data[PipelineStage.ALIAS_ANALYSIS] = aliases
            self.logger.info("Alias stage: processed %d pairs", len(aliases))
            return True
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Alias stage error: %s", exc)
            return False

    def _run_interface_stage(self, interfaces: dict[str, Any]) -> bool:
        """Encode all interface abstractions."""
        ifaces = []
        for name, methods_spec in interfaces.items():
            try:
                methods: dict[str, tuple[list, str]] = {}
                for mname, mspec in methods_spec.items():
                    if isinstance(mspec, (list, tuple)) and len(mspec) == 2:
                        param_types, ret_type = mspec
                    else:
                        param_types, ret_type = [], "Unit"
                    methods[mname] = (list(param_types), str(ret_type))
                iface = self._session.add_interface(name, methods)
                ifaces.append(iface)
            except Exception as exc:  # noqa: BLE001
                self.logger.error("Failed to encode interface %r: %s", name, exc)
                return False
        self._stage_data[PipelineStage.INTERFACE_ABSTRACTION] = ifaces
        self.logger.info("Interface stage: encoded %d interfaces", len(ifaces))
        return True

    def _run_boundary_stage(self) -> bool:
        """Encode boundary conditions using the ExactBoundaryEncoder."""
        try:
            enc = self._session._boundary_encoder
            conditions = enc.encode_all(
                self._session._encoded_collections,
                self._session._heap_summaries,
            )
            self._stage_data[PipelineStage.BOUNDARY_ENCODING] = conditions
            self.logger.info("Boundary stage: encoded %d conditions", len(conditions))
            return True
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Boundary stage error: %s", exc)
            return False

    def _run_verification_stage(
        self, z3_session: Z3Session
    ) -> tuple[bool, dict[str, Z3Result]]:
        """Run all Z3 verification checks and return ``(success, results)``."""
        try:
            results = self._session.verify_program_state(z3_session)
            all_ok = all(
                r.outcome is SolveOutcome.SAT
                for r in results.values()
                if r is not None
            )
            self.logger.info(
                "Verification stage: %d checks, all_ok=%s", len(results), all_ok
            )
            return all_ok, results
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Verification stage error: %s", exc)
            return False, {}

    # ------------------------------------------------------------------
    # Control
    # ------------------------------------------------------------------

    def run_stage(self, stage: PipelineStage, z3_session: Z3Session) -> bool:
        """Run a single named pipeline stage against the already-loaded session state.

        This is useful for re-running a specific stage after modifying encoded
        state without re-running the whole pipeline.

        Parameters
        ----------
        stage:
            The stage to execute.
        z3_session:
            Z3Session for verification stages.

        Returns
        -------
        bool
            Whether the stage succeeded.
        """
        self._current_stage = stage
        stage_map = {
            PipelineStage.COLLECTION_ENCODING: lambda: self._run_collection_stage({}),
            PipelineStage.HEAP_SUMMARIZATION: lambda: self._run_heap_stage({}),
            PipelineStage.ALIAS_ANALYSIS: lambda: self._run_alias_stage([]),
            PipelineStage.INTERFACE_ABSTRACTION: lambda: self._run_interface_stage({}),
            PipelineStage.BOUNDARY_ENCODING: self._run_boundary_stage,
            PipelineStage.VERIFICATION: lambda: self._run_verification_stage(z3_session)[0],
        }
        fn = stage_map.get(stage)
        if fn is None:
            self.logger.warning("run_stage: no handler for stage %s", stage)
            return False
        return fn()

    def reset(self) -> None:
        """Reset pipeline state and clear all accumulated session data."""
        self._session.reset()
        self._stages_completed.clear()
        self._stage_data.clear()
        self._result = None
        self._current_stage = PipelineStage.COLLECTION_ENCODING
        self._monitor = _PipelineMonitor(self._pipeline_id)
        self.logger.debug("Pipeline %r reset", self._pipeline_id[:8])

    def validate(self, pipeline_result: PipelineResult) -> bool:
        """Check that *pipeline_result* is complete and internally consistent.

        A result is considered valid if:
        - The stage is COMPLETE.
        - ``success`` is True.
        - There are no UNSAT results in ``z3_results``.
        - ``collections_encoded`` ≥ 0, etc.
        """
        if not pipeline_result.is_complete():
            self.logger.debug("validate: result is not complete (stage=%s)", pipeline_result.stage)
            return False
        bad_checks = [
            k for k, v in pipeline_result.z3_results.items()
            if v is not None and v.outcome is SolveOutcome.UNSAT
        ]
        if bad_checks:
            self.logger.debug("validate: UNSAT checks: %s", bad_checks)
            return False
        return True

    def report(self, pipeline_result: PipelineResult) -> str:
        """Generate a human-readable pipeline execution report."""
        lines = [
            "=" * 60,
            "HeapCollectionPipeline Execution Report",
            f"Pipeline ID : {self._pipeline_id[:8]}",
            "=" * 60,
            pipeline_result.summary(),
            "",
            "Stage timing:",
        ]
        for stage_name, ms in pipeline_result.metadata.items():
            lines.append(f"  {stage_name:<32} {ms:>8.2f} ms")
        lines.append("")
        lines.append("Z3 check results:")
        for check, result in pipeline_result.z3_results.items():
            outcome = result.outcome.value if result else "N/A"
            lines.append(f"  {check:<40} {outcome}")
        lines.append("=" * 60)
        return "\n".join(lines)

    def get_stage_result(self, stage: PipelineStage) -> Any | None:
        """Return the data artefact produced by *stage*, or None if not yet run."""
        return self._stage_data.get(stage)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _fail(
        self,
        message: str,
        z3_results: dict[str, Z3Result] | None = None,
    ) -> PipelineResult:
        """Construct a failure PipelineResult and cache it."""
        self.logger.error("Pipeline %r failed at stage %s: %s",
                          self._pipeline_id[:8], self._current_stage, message)
        self._result = PipelineResult(
            stage=PipelineStage.FAILED,
            success=False,
            collections_encoded=len(self._session._encoded_collections),
            heap_summaries=len(self._session._heap_summaries),
            aliases_verified=False,
            interface_abstractions=len(self._session._interface_abstractions),
            boundary_conditions=0,
            z3_results=z3_results or {},
            error_message=message,
            wall_time_ms=self._monitor.total_ms(),
            metadata=self._monitor.stage_breakdown(),
        )
        return self._result


