class PipelineStage(str, Enum):
    """Enumeration of all stages in the collection-heap encoding pipeline.

    Each stage corresponds to a logical phase of the verification workflow,
    from initial collection encoding through to final Z3 verification.  Stages
    progress monotonically; a FAILED stage can only transition to COMPLETE after
    a reset-and-retry.
    """

    COLLECTION_ENCODING = "collection_encoding"
    HEAP_SUMMARIZATION = "heap_summarization"
    ALIAS_ANALYSIS = "alias_analysis"
    INTERFACE_ABSTRACTION = "interface_abstraction"
    BOUNDARY_ENCODING = "boundary_encoding"
    VERIFICATION = "verification"
    COMPLETE = "complete"
    FAILED = "failed"


