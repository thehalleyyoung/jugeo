_DEFAULT_REGISTRY: EncoderRegistry = EncoderRegistry.default_registry()
"""Default :class:`EncoderRegistry` pre-populated with all built-in encoders."""


def create_pipeline(
    session: CollectionHeapEncodingSession | None = None,
    registry: EncoderRegistry | None = None,
) -> HeapCollectionPipeline:
    """Convenience factory that creates a ready-to-use :class:`HeapCollectionPipeline`.

    Parameters
    ----------
    session:
        Optional pre-existing session; defaults to a fresh one.
    registry:
        Optional encoder registry; defaults to :data:`_DEFAULT_REGISTRY`.

    Returns
    -------
    HeapCollectionPipeline
        A pipeline instance ready for :meth:`~HeapCollectionPipeline.run`.

    Example
    -------
    .. code-block:: python

        from jugeo.solver.z3_session import Z3Session
        from jugeo.encodings.collection_heap_encodings.integration import create_pipeline

        pipeline = create_pipeline()
        result = pipeline.run(
            {
                "collections": {"xs": [[1, 2, 3], "Int"]},
                "heap": {"p": "node"},
                "aliases": [["p", "q"]],
                "interfaces": {"Stack": {"push": [["Int"], "Unit"]}},
            },
            Z3Session(),
        )
        print(result.summary())
    """
    return HeapCollectionPipeline(
        session=session,
        registry=registry or _DEFAULT_REGISTRY,
    )


