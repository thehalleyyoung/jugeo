def encode_list_quick(
    items: Sequence[Any],
    element_type: str,
) -> CollectionEncoding:
    """Convenience wrapper: encode a list with a fresh :class:`CollectionEncoder`.

    Args:
        items: Python list to encode.
        element_type: Python type name for elements.

    Returns:
        A :class:`CollectionEncoding`.

    Example:
        >>> enc = encode_list_quick([1, 2, 3], "int")
        >>> enc.metadata["kind"]
        'list'
    """
    return CollectionEncoder().encode_list(items, element_type)


