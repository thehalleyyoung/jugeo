class CollectionKind(str, Enum):
    """Enumeration of supported Python collection kinds.

    Each member corresponds to a distinct encoding strategy as described in
    §27.2–§27.6 of theory2.tex.

    Members
    -------
    LIST
        Ordered sequence with integer-indexed access.  Encoded as
        ``(Array Int S)``.
    SET
        Unordered collection with uniqueness invariant.  Encoded as a
        characteristic function ``(Array S Bool)``.
    DICT
        Finite map from keys to values.  Encoded as ``(Array KS VS)``.
    MULTISET
        Like a set but allows repeated elements.  Encoded as a multiplicity
        function ``(Array S Int)`` where the integer is the count.
    SEQUENCE
        Infinite or variable-length sequence.  Encoded as ``(Array Int S)``
        with an explicit length bound.
    """

    LIST = "list"
    SET = "set"
    DICT = "dict"
    MULTISET = "multiset"
    SEQUENCE = "sequence"


