@dataclass(frozen=True, slots=True)
class ElementTypeInfo:
    """Metadata about the Z3 sort and invariants for a single element type.

    This frozen dataclass records everything the encoder needs to know about
    a particular element type: what Z3 sort to use, what invariant template
    to enforce, and what comparison operations are supported.

    Fields
    ------
    type_name : str
        The Python-level type name (e.g. ``"int"``, ``"str"``).
    z3_sort_name : str
        The SMT-LIB2 sort identifier (e.g. ``"Int"``, ``"Real"``, ``"Bool"``).
    invariant_template : str
        An SMT-LIB2 formula template with ``{var}`` as the placeholder for
        the element variable name.  An empty string means "no additional
        invariant".
    supports_equality : bool
        Whether the Z3 sort supports a decidable equality predicate.
    supports_ordering : bool
        Whether the Z3 sort supports ``<``, ``<=``, ``>=``, ``>`` comparisons.
        True for ``Int``, ``Real``, and bit-vectors; False for ``Bool`` and
        uninterpreted sorts.

    Example
    -------
    >>> info = ElementTypeInfo(
    ...     type_name="int",
    ...     z3_sort_name="Int",
    ...     invariant_template="(>= {var} 0)",
    ...     supports_equality=True,
    ...     supports_ordering=True,
    ... )
    >>> info.format_invariant("x")
    '(>= x 0)'
    >>> info.is_numeric()
    True
    """

    type_name: str
    z3_sort_name: str
    invariant_template: str
    supports_equality: bool
    supports_ordering: bool

    def format_invariant(self, var_name: str) -> str:
        """Substitute *var_name* into the invariant template.

        Args:
            var_name: The SMT-LIB2 identifier to use in place of ``{var}``.

        Returns:
            The instantiated invariant formula string, or ``"true"`` when
            the template is empty.

        Example:
            >>> info = ElementTypeInfo("int","Int","(>= {var} 0)",True,True)
            >>> info.format_invariant("elem_0")
            '(>= elem_0 0)'
        """
        if not self.invariant_template:
            return "true"
        return self.invariant_template.replace("{var}", var_name)

    def is_numeric(self) -> bool:
        """Return True when the sort supports numeric arithmetic.

        Returns:
            ``True`` for ``Int``, ``Real``, and bit-vector sorts.

        Example:
            >>> ElementTypeInfo("int","Int","",True,True).is_numeric()
            True
            >>> ElementTypeInfo("str","Int","",True,False).is_numeric()
            True
        """
        return self.z3_sort_name in {"Int", "Real"} or self.z3_sort_name.startswith(
            "(_ BitVec"
        )

    def is_comparable(self) -> bool:
        """Return True when the sort supports ordering comparisons.

        Returns:
            The value of :attr:`supports_ordering`.

        Example:
            >>> ElementTypeInfo("float","Real","",True,True).is_comparable()
            True
        """
        return self.supports_ordering


