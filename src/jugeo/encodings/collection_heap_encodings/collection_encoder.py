@dataclass(slots=True)
class CollectionInvariantChecker:
    """Verify invariants of :class:`CollectionEncoding` objects via Z3.

    Uses a Z3Session to run satisfiability checks over the encoding's
    invariant list.

    Example
    -------
    >>> checker = CollectionInvariantChecker()
    >>> # results = checker.check_all_elements(enc, session)
    """

    _encoder: CollectionEncoder = field(default_factory=CollectionEncoder)

    def check_all_elements(
        self,
        encoding: CollectionEncoding,
        session: Any,
    ) -> list[Any]:
        """Check that every invariant in *encoding* is independently satisfiable.

        Each invariant is checked in a separate Z3 query to isolate any
        contradicting constraint.

        Args:
            encoding: The :class:`CollectionEncoding` to check.
            session: A Z3Session-compatible object with a ``check`` method.

        Returns:
            A list of :class:`~jugeo.solver.z3_session.Z3Result` objects,
            one per invariant.

        Raises:
            RuntimeError: If *session* is ``None``.
        """
        if session is None:
            raise RuntimeError("Z3 session required")
        results = []
        decls = encoding.metadata.get("declarations", [])
        for inv in encoding.invariants:
            smt2 = "\n".join([*decls, inv, "(check-sat)"])
            if hasattr(session, "check_smt2"):
                results.append(session.check_smt2(smt2))
            elif hasattr(session, "check"):
                results.append(session.check(smt2))
        return results

    def check_bounded_cardinality(
        self,
        encoding: CollectionEncoding,
        bound: int,
        session: Any,
    ) -> Any:
        """Check that the encoding's cardinality is consistent with *bound*.

        Args:
            encoding: The :class:`CollectionEncoding` to check.
            bound: The maximum allowed cardinality.
            session: A Z3Session-compatible object.

        Returns:
            A :class:`~jugeo.solver.z3_session.Z3Result`.

        Raises:
            RuntimeError: If *session* is ``None``.
        """
        if session is None:
            raise RuntimeError("Z3 session required")
        n = encoding.metadata.get("cardinality", 0)
        len_const = f"len_{encoding.name}"
        decls = encoding.metadata.get("declarations", [])
        extra = [
            f"(declare-const {len_const} Int)",
            f"(assert (>= {len_const} 0))",
            f"(assert (<= {len_const} {bound}))",
            f"(assert (= {len_const} {n}))",
        ]
        smt2 = "\n".join([*decls, *extra, "(check-sat)"])
        if hasattr(session, "check_smt2"):
            return session.check_smt2(smt2)
        return session.check(smt2)

    def infer_invariants(
        self,
        encoding: CollectionEncoding,
        session: Any,
    ) -> list[str]:
        """Attempt to infer additional invariants for the encoding.

        Implements a simple heuristic: for numeric sorts, adds lower/upper
        bound invariants derived from the concrete element values encoded in
        the raw assertions.

        Args:
            encoding: The :class:`CollectionEncoding` to analyse.
            session: A Z3Session (currently unused; included for API
                consistency with future implementations).

        Returns:
            A list of SMT-LIB2 formula strings for inferred invariants.
        """
        inferred: list[str] = []
        if encoding.element_sort not in {"Int", "Real"}:
            return inferred
        values: list[float] = []
        for assertion in encoding.metadata.get("raw_assertions", []):
            parts = assertion.replace("(assert ", "").strip("()").split()
            for part in parts:
                try:
                    values.append(float(part))
                except ValueError:
                    pass
        if not values:
            return inferred
        mn = min(values)
        mx = max(values)
        n = encoding.metadata.get("cardinality", 0)
        if encoding.metadata.get("kind") in ("list", "sequence"):
            for i in range(n):
                if encoding.element_sort == "Int":
                    inferred.append(f"(>= ({encoding.name} {i}) {int(mn)})")
                    inferred.append(f"(<= ({encoding.name} {i}) {int(mx)})")
                else:
                    inferred.append(f"(>= ({encoding.name} {i}) {mn})")
                    inferred.append(f"(<= ({encoding.name} {i}) {mx})")
        return inferred

    def counterexample_element(
        self,
        encoding: CollectionEncoding,
        session: Any,
    ) -> dict[str, Any] | None:
        """Attempt to find a counterexample to one of the encoding's invariants.

        Negates each invariant in turn and queries the solver for a model.
        Returns the first satisfying model found (a witness to the violation),
        or ``None`` if all invariants hold.

        Args:
            encoding: The :class:`CollectionEncoding` to test.
            session: A Z3Session-compatible object.

        Returns:
            A dict of variable bindings from the counterexample model, or
            ``None`` if no counterexample was found.
        """
        if session is None:
            return None
        decls = encoding.metadata.get("declarations", [])
        for inv in encoding.invariants:
            inner = inv.strip()
            if inner.startswith("(assert "):
                inner = inner[len("(assert "):-1]
            if inner.strip() in {"true", "(assert true)"}:
                continue
            negated = f"(assert (not {inner}))"
            smt2 = "\n".join([*decls, negated, "(check-sat)", "(get-model)"])
            try:
                result = (
                    session.check_smt2(smt2)
                    if hasattr(session, "check_smt2")
                    else session.check(smt2)
                )
                if hasattr(result, "model") and result.model:
                    return dict(result.model)
                if hasattr(result, "status") and "sat" in str(result.status).lower():
                    return {"witness": "sat — model unavailable"}
            except Exception as exc:
                logger.debug("counterexample_element query failed: %s", exc)
        return None

    def summarize_checks(self, results: list[Any]) -> str:
        """Produce a human-readable summary of a list of Z3 results.

        Args:
            results: List of objects with a ``.status`` attribute.

        Returns:
            A summary string with pass/fail counts.

        Example:
            >>> checker = CollectionInvariantChecker()
            >>> checker.summarize_checks([])
            'Checked 0 assertions: 0 SAT, 0 UNSAT, 0 UNKNOWN'
        """
        sat_count = unsat_count = unknown_count = 0
        for r in results:
            status = str(getattr(r, "status", "unknown")).lower()
            if "unsat" in status:
                unsat_count += 1
            elif "sat" in status:
                sat_count += 1
            else:
                unknown_count += 1
        total = len(results)
        return (
            f"Checked {total} assertions: "
            f"{sat_count} SAT, {unsat_count} UNSAT, {unknown_count} UNKNOWN"
        )


