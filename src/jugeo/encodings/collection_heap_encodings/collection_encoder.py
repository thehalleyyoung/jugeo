@dataclass(slots=True)
class CollectionFragmentClassifier:
    """Classify :class:`CollectionEncoding` objects into SMT-LIB2 fragments.

    Determines the appropriate SMT-LIB2 logic string and provides complexity
    estimates for tactic selection.

    Example
    -------
    >>> clf = CollectionFragmentClassifier()
    >>> encoder = CollectionEncoder()
    >>> enc = encoder.encode_list([], "int", name="empty")
    >>> clf.supports_quantifier_free(enc)
    True
    """

    def classify(self, encoding: CollectionEncoding) -> Any:
        """Map *encoding* to a :class:`~jugeo.solver.fragments.Fragment` value.

        Args:
            encoding: The :class:`CollectionEncoding` to classify.

        Returns:
            A :class:`~jugeo.solver.fragments.Fragment` enum member, or a
            logic-name string when the fragments module is unavailable.
        """
        tag = self._fragment_tag(encoding)
        if _FRAGMENTS_AVAILABLE and Fragment is not None:
            try:
                return Fragment[tag.replace("QF_", "QF_")]
            except (KeyError, AttributeError):
                pass
        return tag

    def _fragment_tag(self, encoding: CollectionEncoding) -> str:
        """Compute the SMT-LIB2 logic name for *encoding*.

        Args:
            encoding: The :class:`CollectionEncoding` to classify.

        Returns:
            SMT-LIB2 logic string such as ``"QF_ALIA"``.
        """
        kind = encoding.metadata.get("kind", "list")
        sort = encoding.element_sort
        has_quantifiers = any(
            "forall" in inv or "exists" in inv for inv in encoding.invariants
        )
        if kind in ("list", "sequence"):
            if sort == "Int" and not has_quantifiers:
                return "QF_ALIA"
            if sort == "Real" and not has_quantifiers:
                return "QF_ALRA"
            return "AUFLIA" if has_quantifiers else "QF_AUFLIA"
        if kind == "set":
            return "QF_AX"
        if kind == "dict":
            return "QF_ALIA" if sort == "Int" else "QF_AX"
        return "QF_AX"

    def supports_quantifier_free(self, encoding: CollectionEncoding) -> bool:
        """Return True if the encoding fits a quantifier-free fragment.

        Args:
            encoding: The :class:`CollectionEncoding` to test.

        Returns:
            ``True`` when no ``forall`` or ``exists`` appear in invariants.

        Example:
            >>> clf = CollectionFragmentClassifier()
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([], "int", name="qf_test")
            >>> clf.supports_quantifier_free(enc)
            True
        """
        return not any(
            "forall" in inv or "exists" in inv for inv in encoding.invariants
        )

    def suggest_tactic(self, encoding: CollectionEncoding) -> str:
        """Suggest a Z3 tactic name for the given encoding.

        Args:
            encoding: The :class:`CollectionEncoding` to advise on.

        Returns:
            A Z3 tactic string such as ``"qflia"``, ``"qfax"``, ``"default"``.

        Example:
            >>> clf = CollectionFragmentClassifier()
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([], "int", name="tac_test")
            >>> clf.suggest_tactic(enc)
            'qflia'
        """
        tag = self._fragment_tag(encoding)
        return {
            "QF_ALIA": "qflia",
            "QF_ALRA": "qflra",
            "QF_AX": "qfax",
            "QF_AUFLIA": "default",
            "AUFLIA": "default",
        }.get(tag, "default")

    def fragment_complexity(self, encoding: CollectionEncoding) -> int:
        """Estimate proof complexity on a 0–100 scale.

        Args:
            encoding: The :class:`CollectionEncoding` to evaluate.

        Returns:
            Integer complexity score in ``[0, 100]``.

        Example:
            >>> clf = CollectionFragmentClassifier()
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([1,2,3,4,5], "int", name="cx_test")
            >>> 0 <= clf.fragment_complexity(enc) <= 100
            True
        """
        card = encoding.metadata.get("cardinality", 0)
        base = min(card * 2, 40)
        q_pen = 30 if not self.supports_quantifier_free(encoding) else 0
        sort_pen = {"Int": 0, "Real": 5, "Bool": 0}.get(encoding.element_sort, 10)
        return min(base + q_pen + sort_pen, 100)


