"""
collection_encoder — Encoding Python lists, sets, and dicts as Z3 arrays.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch27: Exact Z3 encodings II: collections, finite maps, heap summaries,
alias partitions, interface abstractions.

Encodes Python collection types (list, set, dict) as Z3 array expressions with
element-type invariants, cardinality constraints, and membership predicates.
The encoding is faithful: satisfiability of the Z3 constraints corresponds to
satisfiability of the original collection constraint.

Part of the JuGeo judgment-geometry framework.

Background
----------
Chapter 27 of theory2.tex extends the scalar-sort encodings of Chapter 26 to
compound collection types.  The key insight (§27.2) is that Python's built-in
collections can be faithfully represented in SMT-LIB2 using the theory of
extensional arrays (QF_AX) combined with linear integer arithmetic for length
and cardinality reasoning (QF_ALIA → QF_AUFLIA when uninterpreted functions are
needed for element-type invariants).

List encoding (§27.3)
    A Python ``list[T]`` of length ``n`` is encoded as a Z3 array
    ``(Array Int S)`` where ``S`` is the Z3 sort for type ``T``, together with
    a cardinality constant ``(len_<name> Int)`` and the assertion
    ``(= len_<name> <n>)``.  Element constraints are added as individual
    assertions ``(= (<name> <i>) <v_i>)`` for each concrete value.

Set encoding (§27.4)
    A Python ``set[T]`` is encoded as a *characteristic function*
    ``(Array S Bool)`` where membership of ``x`` is ``(= (<name> x) true)``.
    The uniqueness invariant is vacuously satisfied by the array semantics.

Dict encoding (§27.5)
    A Python ``dict[K, V]`` is encoded as a Z3 array ``(Array KS VS)`` where
    ``KS`` and ``VS`` are the Z3 sorts for key type ``K`` and value type ``V``.
    Key-value pairs are added as individual assertions.

All encodings produce a :class:`~jugeo.encodings.collection_heap_encodings.models.CollectionEncoding`
with:
  * ``array_expr`` — the SMT-LIB2 ``declare-fun`` string for the backing array.
  * ``invariants`` — a list of SMT-LIB2 ``(assert ...)`` strings covering
    element constraints, cardinality constraints, and type invariants.
  * ``metadata`` — a free-form dict storing ``kind``, ``cardinality``,
    ``element_type``, ``declarations``, and ``raw_assertions`` for downstream
    pipeline stages.

The :class:`CollectionEncoder` class is the primary entry point.  It caches
intermediate encodings by a (name, kind, element_sort) key and records encoding
statistics for later introspection.
"""

