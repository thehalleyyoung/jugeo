@dataclass(slots=True)
class CollectionEncoder:
    """Encode Python collection types as Z3 array expressions.

    This is the primary entry point for Ch27 collection encoding.  It caches
    intermediate encodings, maintains an invariant library for reuse, and
    records encoding statistics.

    The encoder is *stateful*: repeated calls to :meth:`encode_list` etc.
    with the same *name*, *kind*, and *element_type* triple return cached
    results and do not rebuild the SMT-LIB2 strings.  Use :meth:`clear_cache`
    to invalidate the cache when testing.

    Each returned :class:`~jugeo.encodings.collection_heap_encodings.models.CollectionEncoding`
    stores auxiliary data in its ``metadata`` dict under the keys:

    * ``"kind"``          — ``"list"`` / ``"set"`` / ``"dict"`` / …
    * ``"cardinality"``   — number of concrete elements encoded
    * ``"element_type"``  — Python type name of the elements
    * ``"declarations"``  — list of SMT-LIB2 ``declare-*`` strings
    * ``"raw_assertions"``— list of concrete element ``(assert ...)`` strings

    Fields
    ------
    _encoding_cache : dict
        Internal cache mapping a content-hash key to a CollectionEncoding.
    _invariant_library : dict
        Named reusable invariant predicates.
    _stats : dict
        Runtime statistics: ``encode_calls``, ``cache_hits``, ``encode_ms``.

    Example
    -------
    >>> encoder = CollectionEncoder()
    >>> enc = encoder.encode_list([1, 2, 3], "int", name="my_list")
    >>> enc.metadata["kind"]
    'list'
    >>> enc.metadata["cardinality"]
    3
    """

    _encoding_cache: dict[str, CollectionEncoding] = field(default_factory=dict)
    _invariant_library: dict[str, str] = field(default_factory=dict)
    _stats: dict[str, Any] = field(default_factory=lambda: {
        "encode_calls": 0,
        "cache_hits": 0,
        "encode_ms": 0.0,
        "invariant_checks": 0,
    })

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _get_z3_sort(self, element_type: str) -> str:
        """Return the SMT-LIB2 sort string for a Python type name.

        Looks up *element_type* in :data:`_SORT_MAP`.  Falls back to ``"Int"``
        with a warning when the type is not known.

        Args:
            element_type: Python type name (e.g. ``"int"``, ``"str"``).

        Returns:
            SMT-LIB2 sort string (e.g. ``"Int"``, ``"Real"``).
        """
        sort = _SORT_MAP.get(element_type)
        if sort is None:
            logger.warning(
                "_get_z3_sort: unknown element type %r — falling back to Int",
                element_type,
            )
            sort = "Int"
        return sort

    def _make_array_name(self, base: str) -> str:
        """Construct a unique SMT-LIB2 array symbol name from *base*.

        Appends an 8-character hex suffix so that auto-generated names do not
        collide across encoder instances or calls.

        Args:
            base: Human-readable base name (e.g. ``"arr"``, ``"coll"``).

        Returns:
            A collision-resistant identifier string.

        Example:
            >>> enc = CollectionEncoder()
            >>> name = enc._make_array_name("my_list")
            >>> name.startswith("my_list_")
            True
        """
        suffix = uuid.uuid4().hex[:8]
        return f"{base}_{suffix}"

    def _build_element_constraint(
        self, name: str, idx: int, val: Any, sort: str
    ) -> str:
        """Build an SMT-LIB2 assertion pinning array element *idx* to *val*.

        For list/sequence encodings the array is indexed by ``Int``, so the
        assertion has the form ``(assert (= (name idx) val_literal))``.

        Args:
            name: The Z3 array symbol name.
            idx: Integer index (for list/sequence encodings).
            val: Concrete Python value to encode.
            sort: The SMT-LIB2 sort of the array range.

        Returns:
            Complete ``(assert ...)`` string.

        Raises:
            ValueError: If *val* cannot be converted to a literal for *sort*.
        """
        literal = self._py_val_to_smt2(val, sort)
        return f"(assert (= ({name} {idx}) {literal}))"

    def _py_val_to_smt2(self, val: Any, sort: str) -> str:
        """Translate a Python value to an SMT-LIB2 literal string.

        Args:
            val: The Python value to convert.
            sort: The target SMT-LIB2 sort (used for sign-extension, etc.).

        Returns:
            An SMT-LIB2 literal string compatible with *sort*.

        Raises:
            ValueError: If *val* is ``None`` and sort is not ``"Bool"``.
        """
        if isinstance(val, bool):
            return "true" if val else "false"
        if isinstance(val, int):
            if val < 0:
                return f"(- {abs(val)})"
            return str(val)
        if isinstance(val, float):
            if math.isnan(val):
                logger.warning("_py_val_to_smt2: NaN encoded as 0.0")
                return "0.0"
            if math.isinf(val):
                return "(/ 1.0 0.0)" if val > 0 else "(/ (- 1.0) 0.0)"
            return repr(val)
        if isinstance(val, str):
            hval = int(hashlib.sha256(val.encode()).hexdigest(), 16) % (2**31)
            return str(hval)
        if val is None:
            if sort == "Bool":
                return "false"
            raise ValueError(f"Cannot encode None for sort {sort!r}")
        return str(val)

    def _cache_key(self, name: str, kind: str, element_type: str) -> str:
        """Compute a stable cache key from encoding metadata.

        Args:
            name: Encoding symbol name.
            kind: Collection kind string.
            element_type: Python element type name.

        Returns:
            A 16-character hex digest usable as a dict key.
        """
        payload = f"{name}:{kind}:{element_type}"
        return hashlib.sha256(payload.encode()).hexdigest()[:16]

    def _format_array_decl(self, name: str, index_sort: str, element_sort: str) -> str:
        """Format an SMT-LIB2 ``declare-fun`` for a Z3 array.

        Args:
            name: Array symbol name.
            index_sort: Index sort string.
            element_sort: Element sort string.

        Returns:
            ``(declare-fun <name> (<index_sort>) <element_sort>)``
        """
        return f"(declare-fun {name} ({index_sort}) {element_sort})"

    # ------------------------------------------------------------------
    # Public encoding API
    # ------------------------------------------------------------------

    def encode_list(
        self,
        items: Sequence[Any],
        element_type: str,
        *,
        name: str | None = None,
    ) -> CollectionEncoding:
        """Encode a Python list as a Z3 ``(Array Int S)`` expression.

        Builds the complete SMT-LIB2 artefact for an ordered, integer-indexed
        sequence.  The encoding populates ``array_expr`` with the array
        declaration, adds element constraints and cardinality constraints to
        ``invariants``, and stores auxiliary data in ``metadata``.

        The ``metadata`` dict will contain:
        * ``"kind"``           → ``"list"``
        * ``"cardinality"``    → ``n``
        * ``"element_type"``   → *element_type*
        * ``"declarations"``   → list of ``declare-*`` strings
        * ``"raw_assertions"`` → list of concrete element assertions

        The result is cached so repeated calls with the same name / kind /
        element_type triple return the cached encoding.

        Args:
            items: The Python list to encode.  May be empty.
            element_type: Python type name for the element sort (e.g. ``"int"``).
            name: Optional symbol name for the Z3 array.  If ``None``, a unique
                name is auto-generated.

        Returns:
            A :class:`~jugeo.encodings.collection_heap_encodings.models.CollectionEncoding`
            with fully populated ``array_expr``, ``invariants``, and ``metadata``.

        Raises:
            TypeError: If *items* is not iterable.
            ValueError: If any element cannot be encoded as an SMT-LIB2 literal.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([10, 20, 30], "int", name="xs")
            >>> enc.metadata["cardinality"]
            3
            >>> enc.metadata["kind"]
            'list'
            >>> enc.element_sort
            'Int'
        """
        t0 = time.monotonic()
        self._stats["encode_calls"] += 1

        array_name = name if name is not None else self._make_array_name("list")
        element_sort = self._get_z3_sort(element_type)
        index_sort = "Int"

        cache_key = self._cache_key(array_name, "list", element_type)
        if cache_key in self._encoding_cache:
            self._stats["cache_hits"] += 1
            logger.debug("encode_list cache hit for %r", array_name)
            return self._encoding_cache[cache_key]

        items_seq = list(items)
        n = len(items_seq)

        # SMT-LIB2 array declaration
        array_decl = self._format_array_decl(array_name, index_sort, element_sort)

        # Length constant declaration + assertion
        len_name = f"len_{array_name}"
        len_decl = f"(declare-const {len_name} Int)"
        declarations: list[str] = [array_decl, len_decl]
        len_assertion = f"(assert (= {len_name} {n}))"

        invariants: list[str] = []
        raw_assertions: list[str] = [len_assertion]

        # Non-negative length
        invariants.append(f"(assert (>= {len_name} 0))")

        # Element constraints + type invariants
        type_info = _ELEMENT_TYPE_REGISTRY.get(element_type)
        for i, item in enumerate(items_seq):
            elem_assert = self._build_element_constraint(
                array_name, i, item, element_sort
            )
            raw_assertions.append(elem_assert)
            # Type invariant for this element
            if type_info is not None:
                var_expr = f"({array_name} {i})"
                inv_str = type_info.format_invariant(var_expr)
                if inv_str != "true":
                    invariants.append(f"(assert {inv_str})")

        # All invariants include the length assertion
        all_invariants = [len_assertion] + invariants

        encoding = CollectionEncoding(
            name=array_name,
            element_sort=element_sort,
            index_sort=index_sort,
            array_expr=array_decl,
            invariants=all_invariants,
            provenance={"encoder": "CollectionEncoder.encode_list", "version": _ENCODING_VERSION},
            encoding_id=cache_key,
            metadata={
                "kind": "list",
                "cardinality": n,
                "element_type": element_type,
                "declarations": declarations,
                "raw_assertions": raw_assertions,
            },
        )
        self._encoding_cache[cache_key] = encoding
        elapsed = (time.monotonic() - t0) * 1000.0
        self._stats["encode_ms"] = self._stats["encode_ms"] + elapsed
        logger.debug(
            "encode_list %r: %d items, %d invariants, %.2f ms",
            array_name, n, len(all_invariants), elapsed,
        )
        return encoding

    def encode_set(
        self,
        items: Sequence[Any],
        element_type: str,
        *,
        name: str | None = None,
    ) -> CollectionEncoding:
        """Encode a Python set as a Z3 characteristic function ``(Array S Bool)``.

        A set is encoded as a Boolean-valued array: membership of element ``x``
        is represented by ``(= (<name> x) true)``.  The encoding includes one
        assertion per element and stores uniqueness information in ``metadata``.

        The ``metadata`` dict will contain:
        * ``"kind"``           → ``"set"``
        * ``"cardinality"``    → number of unique elements
        * ``"element_type"``   → *element_type*
        * ``"declarations"``   → list of ``declare-*`` strings
        * ``"raw_assertions"`` → membership assertions
        * ``"unique_elements"``→ list of SMT-LIB2 element literals

        Args:
            items: The Python collection of set members.  Duplicates are
                silently deduplicated before encoding.
            element_type: Python type name for the element sort.
            name: Optional symbol name.  Auto-generated if ``None``.

        Returns:
            A :class:`~jugeo.encodings.collection_heap_encodings.models.CollectionEncoding`
            with ``metadata["kind"] == "set"``.

        Raises:
            ValueError: If any element cannot be represented as a literal.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_set([1, 2, 3], "int", name="my_set")
            >>> enc.metadata["kind"]
            'set'
            >>> enc.metadata["cardinality"]
            3
        """
        t0 = time.monotonic()
        self._stats["encode_calls"] += 1

        set_name = name if name is not None else self._make_array_name("set")
        element_sort = self._get_z3_sort(element_type)
        index_sort = element_sort  # characteristic function: S → Bool

        # Deduplicate preserving deterministic ordering
        seen: dict[str, Any] = {}
        for item in items:
            lit = self._py_val_to_smt2(item, element_sort)
            seen[lit] = item
        unique_literals = list(seen.keys())
        n = len(unique_literals)

        cache_key = self._cache_key(set_name, "set", element_type)
        if cache_key in self._encoding_cache:
            self._stats["cache_hits"] += 1
            return self._encoding_cache[cache_key]

        # Characteristic function: (declare-fun <name> (S) Bool)
        char_decl = f"(declare-fun {set_name} ({element_sort}) Bool)"
        card_name = f"card_{set_name}"
        card_decl = f"(declare-const {card_name} Int)"
        declarations: list[str] = [char_decl, card_decl]

        raw_assertions: list[str] = []
        invariants: list[str] = []

        # Membership assertions
        for lit in unique_literals:
            raw_assertions.append(f"(assert (= ({set_name} {lit}) true))")

        # Cardinality
        card_assert = f"(assert (= {card_name} {n}))"
        raw_assertions.append(card_assert)
        invariants.append(f"(assert (>= {card_name} 0))")

        # Pairwise inequality hints for concrete numeric elements
        for i, li in enumerate(unique_literals):
            for lj in unique_literals[i + 1:]:
                if li != lj and element_sort in {"Int", "Real"}:
                    invariants.append(f"(assert (not (= {li} {lj})))")

        all_invariants = raw_assertions + invariants

        encoding = CollectionEncoding(
            name=set_name,
            element_sort=element_sort,
            index_sort=index_sort,
            array_expr=char_decl,
            invariants=all_invariants,
            provenance={"encoder": "CollectionEncoder.encode_set", "version": _ENCODING_VERSION},
            encoding_id=cache_key,
            metadata={
                "kind": "set",
                "cardinality": n,
                "element_type": element_type,
                "declarations": declarations,
                "raw_assertions": raw_assertions,
                "unique_elements": unique_literals,
            },
        )
        self._encoding_cache[cache_key] = encoding
        elapsed = (time.monotonic() - t0) * 1000.0
        self._stats["encode_ms"] = self._stats["encode_ms"] + elapsed
        logger.debug(
            "encode_set %r: %d unique items, %.2f ms", set_name, n, elapsed
        )
        return encoding

    def encode_dict(
        self,
        mapping: Mapping[Any, Any],
        key_type: str,
        value_type: str,
        *,
        name: str | None = None,
    ) -> CollectionEncoding:
        """Encode a Python dict as a Z3 ``(Array KS VS)`` expression.

        The dictionary is represented as a Z3 array indexed by the key sort,
        with each key-value pair asserted as a concrete constraint.

        The ``metadata`` dict will contain:
        * ``"kind"``           → ``"dict"``
        * ``"cardinality"``    → number of key-value pairs
        * ``"element_type"``   → *value_type*
        * ``"key_type"``       → *key_type*
        * ``"declarations"``   → list of ``declare-*`` strings
        * ``"raw_assertions"`` → concrete key-value assertions

        Args:
            mapping: The Python dict (or any ``Mapping``) to encode.
            key_type: Python type name for the key sort.
            value_type: Python type name for the value sort.
            name: Optional symbol name.  Auto-generated if ``None``.

        Returns:
            A :class:`~jugeo.encodings.collection_heap_encodings.models.CollectionEncoding`
            with ``metadata["kind"] == "dict"``.

        Raises:
            ValueError: If any key or value cannot be encoded.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_dict({"a": 1, "b": 2}, "str", "int")
            >>> enc.metadata["kind"]
            'dict'
            >>> enc.metadata["cardinality"]
            2
        """
        t0 = time.monotonic()
        self._stats["encode_calls"] += 1

        dict_name = name if name is not None else self._make_array_name("dict")
        key_sort = self._get_z3_sort(key_type)
        val_sort = self._get_z3_sort(value_type)

        cache_key = self._cache_key(dict_name, "dict", f"{key_type}:{value_type}")
        if cache_key in self._encoding_cache:
            self._stats["cache_hits"] += 1
            return self._encoding_cache[cache_key]

        # Array declaration: (declare-fun <name> (KS) VS)
        array_decl = self._format_array_decl(dict_name, key_sort, val_sort)
        size_name = f"size_{dict_name}"
        size_decl = f"(declare-const {size_name} Int)"
        declarations: list[str] = [array_decl, size_decl]

        items_list = list(mapping.items())
        n = len(items_list)
        raw_assertions: list[str] = []
        invariants: list[str] = []

        # Key-value pair assertions
        val_type_info = _ELEMENT_TYPE_REGISTRY.get(value_type)
        for k, v in items_list:
            k_lit = self._py_val_to_smt2(k, key_sort)
            v_lit = self._py_val_to_smt2(v, val_sort)
            raw_assertions.append(
                f"(assert (= ({dict_name} {k_lit}) {v_lit}))"
            )
            if val_type_info is not None:
                var_expr = f"({dict_name} {k_lit})"
                inv_str = val_type_info.format_invariant(var_expr)
                if inv_str != "true":
                    invariants.append(f"(assert {inv_str})")

        # Cardinality
        size_assert = f"(assert (= {size_name} {n}))"
        raw_assertions.append(size_assert)
        invariants.append(f"(assert (>= {size_name} 0))")

        all_invariants = raw_assertions + invariants

        encoding = CollectionEncoding(
            name=dict_name,
            element_sort=val_sort,
            index_sort=key_sort,
            array_expr=array_decl,
            invariants=all_invariants,
            provenance={"encoder": "CollectionEncoder.encode_dict", "version": _ENCODING_VERSION},
            encoding_id=cache_key,
            metadata={
                "kind": "dict",
                "cardinality": n,
                "element_type": value_type,
                "key_type": key_type,
                "declarations": declarations,
                "raw_assertions": raw_assertions,
            },
        )
        self._encoding_cache[cache_key] = encoding
        elapsed = (time.monotonic() - t0) * 1000.0
        self._stats["encode_ms"] = self._stats["encode_ms"] + elapsed
        logger.debug(
            "encode_dict %r: %d entries, %.2f ms", dict_name, n, elapsed
        )
        return encoding

    def add_invariant(
        self,
        encoding: CollectionEncoding,
        predicate: str,
    ) -> CollectionEncoding:
        """Return a new encoding with *predicate* appended to the invariant list.

        Since :class:`CollectionEncoding` from ``models.py`` is a *mutable*
        dataclass (``slots=True``, not frozen), this method mutates
        ``encoding.invariants`` in-place and returns the same object for API
        consistency.

        Args:
            encoding: The :class:`CollectionEncoding` to extend.
            predicate: An SMT-LIB2 formula string (without the outer
                ``(assert ...)`` wrapper).  The wrapper is added automatically.

        Returns:
            The same :class:`CollectionEncoding` with the new invariant appended.

        Raises:
            ValueError: If *predicate* is empty.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([1, 2], "int", name="xs")
            >>> enc2 = encoder.add_invariant(enc, "(> (xs 0) 0)")
            >>> enc2 is enc
            True
            >>> any("(> (xs 0) 0)" in inv for inv in enc.invariants)
            True
        """
        if not predicate.strip():
            raise ValueError("predicate must be a non-empty SMT-LIB2 formula string")
        new_inv = f"(assert {predicate.strip()})"
        encoding.invariants.append(new_inv)
        self._stats["invariant_checks"] = self._stats.get("invariant_checks", 0) + 1
        logger.debug(
            "add_invariant: appended to encoding %r", encoding.name
        )
        return encoding

    def verify_encoding(
        self,
        encoding: CollectionEncoding,
        session: Any,
    ) -> Any:
        """Check that all invariants in *encoding* are satisfiable together.

        Assembles a Z3 query containing all declarations and invariants, then
        delegates to *session* for checking.

        Args:
            encoding: The :class:`CollectionEncoding` to verify.
            session: A :class:`~jugeo.solver.z3_session.Z3Session` instance
                (or any object with a ``check`` / ``check_smt2`` method).

        Returns:
            A :class:`~jugeo.solver.z3_session.Z3Result` with
            ``status == SolveOutcome.SAT`` if all invariants hold together,
            ``UNSAT`` if they are contradictory.

        Raises:
            RuntimeError: If *session* is ``None``.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([1, 2], "int", name="xs")
            >>> # result = encoder.verify_encoding(enc, session)
            >>> # assert result.status == SolveOutcome.SAT
        """
        if session is None:
            raise RuntimeError("Z3 session required for verify_encoding")
        smt2 = self.to_smt2(encoding)
        logger.debug(
            "verify_encoding %r: sending %d chars to solver",
            encoding.name, len(smt2),
        )
        if hasattr(session, "check_smt2"):
            return session.check_smt2(smt2)
        if hasattr(session, "check"):
            return session.check(smt2)
        raise RuntimeError(
            f"session of type {type(session).__name__!r} has no check method"
        )

    def project_subarray(
        self,
        encoding: CollectionEncoding,
        start: int,
        end: int,
    ) -> CollectionEncoding:
        """Project a list/sequence encoding to the sub-range ``[start, end)``.

        Returns a new encoding that:
        * Declares a new sub-array symbol.
        * Re-indexes elements: ``sub[i] = original[start + i]``.
        * Has a new cardinality of ``end - start``.
        * Adds bounds-checking invariants.

        Args:
            encoding: A list or sequence :class:`CollectionEncoding`.
            start: Inclusive start index (must be ≥ 0).
            end: Exclusive end index (must be ≤ encoding's cardinality).

        Returns:
            A new :class:`CollectionEncoding` for the projected subarray.

        Raises:
            ValueError: If *start* or *end* are out of bounds, or ``start ≥ end``.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([10, 20, 30, 40], "int", name="xs")
            >>> sub = encoder.project_subarray(enc, 1, 3)
            >>> sub.metadata["cardinality"]
            2
        """
        orig_n = encoding.metadata.get("cardinality", 0)
        if start < 0:
            raise ValueError(f"start must be >= 0, got {start}")
        if end > orig_n:
            raise ValueError(
                f"end ({end}) exceeds cardinality ({orig_n})"
            )
        if start >= end:
            raise ValueError(f"start ({start}) must be < end ({end})")

        sub_len = end - start
        sub_name = f"{encoding.name}_sub_{start}_{end}"
        element_sort = encoding.element_sort
        index_sort = encoding.index_sort

        sub_decl = self._format_array_decl(sub_name, index_sort, element_sort)
        len_name = f"len_{sub_name}"
        len_decl = f"(declare-const {len_name} Int)"
        declarations = [sub_decl, len_decl]

        invariants: list[str] = [
            f"(assert (= {len_name} {sub_len}))",
            f"(assert (>= {len_name} 0))",
        ]
        # Re-index: sub[i] = original[start+i]
        for i in range(sub_len):
            orig_idx = start + i
            invariants.append(
                f"(assert (= ({sub_name} {i}) ({encoding.name} {orig_idx})))"
            )

        cache_key = self._cache_key(sub_name, "list", encoding.metadata.get("element_type", "int"))
        return CollectionEncoding(
            name=sub_name,
            element_sort=element_sort,
            index_sort=index_sort,
            array_expr=sub_decl,
            invariants=invariants,
            provenance={"encoder": "CollectionEncoder.project_subarray", "parent": encoding.name},
            encoding_id=cache_key,
            metadata={
                "kind": encoding.metadata.get("kind", "list"),
                "cardinality": sub_len,
                "element_type": encoding.metadata.get("element_type", "int"),
                "declarations": declarations,
                "raw_assertions": invariants,
                "parent_name": encoding.name,
                "parent_start": start,
                "parent_end": end,
            },
        )

    def merge_collections(
        self,
        enc1: CollectionEncoding,
        enc2: CollectionEncoding,
    ) -> CollectionEncoding:
        """Combine two encodings into a union encoding.

        The union encoding retains all invariants from both inputs and declares
        both underlying array symbols.  The resulting cardinality is the sum of
        both.

        Args:
            enc1: First :class:`CollectionEncoding`.
            enc2: Second :class:`CollectionEncoding` (must have same element_sort).

        Returns:
            A merged :class:`CollectionEncoding`.

        Raises:
            ValueError: If enc1 and enc2 have incompatible element sorts.

        Example:
            >>> encoder = CollectionEncoder()
            >>> e1 = encoder.encode_list([1, 2], "int", name="a")
            >>> e2 = encoder.encode_list([3, 4, 5], "int", name="b")
            >>> merged = encoder.merge_collections(e1, e2)
            >>> merged.metadata["cardinality"]
            5
        """
        if enc1.element_sort != enc2.element_sort:
            raise ValueError(
                f"Cannot merge encodings with different element sorts: "
                f"{enc1.element_sort!r} vs {enc2.element_sort!r}"
            )
        merged_name = f"merge_{enc1.name}_{enc2.name}"
        c1 = enc1.metadata.get("cardinality", 0)
        c2 = enc2.metadata.get("cardinality", 0)
        merged_card = c1 + c2
        cache_key = self._cache_key(merged_name, "list", enc1.element_sort)

        merged_decls = (
            enc1.metadata.get("declarations", [])
            + enc2.metadata.get("declarations", [])
        )
        merged_invariants = list(enc1.invariants) + list(enc2.invariants)

        return CollectionEncoding(
            name=merged_name,
            element_sort=enc1.element_sort,
            index_sort=enc1.index_sort,
            array_expr=enc1.array_expr,
            invariants=merged_invariants,
            provenance={"encoder": "CollectionEncoder.merge_collections"},
            encoding_id=cache_key,
            metadata={
                "kind": enc1.metadata.get("kind", "list"),
                "cardinality": merged_card,
                "element_type": enc1.metadata.get("element_type", "int"),
                "declarations": merged_decls,
                "merged_from": [enc1.name, enc2.name],
            },
        )

    def cardinality_constraint(
        self,
        encoding: CollectionEncoding,
        size: int,
    ) -> str:
        """Return an SMT-LIB2 assertion pinning the collection's cardinality.

        Args:
            encoding: The :class:`CollectionEncoding` to constrain.
            size: The exact cardinality to assert.

        Returns:
            A complete ``(assert ...)`` string.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([1, 2, 3], "int", name="xs")
            >>> encoder.cardinality_constraint(enc, 3)
            '(assert (= len_xs 3))'
        """
        return f"(assert (= len_{encoding.name} {size}))"

    def element_constraint(
        self,
        encoding: CollectionEncoding,
        idx: int,
        value: Any,
    ) -> str:
        """Return an SMT-LIB2 assertion for element equality at *idx*.

        Args:
            encoding: The :class:`CollectionEncoding` containing the array.
            idx: The integer index.
            value: The Python value to assert at position *idx*.

        Returns:
            A complete ``(assert ...)`` string.

        Raises:
            ValueError: If *value* cannot be encoded for the encoding's sort.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([10], "int", name="xs")
            >>> encoder.element_constraint(enc, 0, 42)
            '(assert (= (xs 0) 42))'
        """
        literal = self._py_val_to_smt2(value, encoding.element_sort)
        return f"(assert (= ({encoding.name} {idx}) {literal}))"

    def to_smt2(self, encoding: CollectionEncoding) -> str:
        """Serialize the complete encoding to an SMT-LIB2 string.

        The output is a valid SMT-LIB2 script that can be fed directly to
        ``z3 -in`` or any compliant SMT solver.  It includes a ``set-logic``
        header, declarations, invariants, and a ``(check-sat)`` footer.

        Args:
            encoding: The :class:`CollectionEncoding` to serialise.

        Returns:
            A multi-line SMT-LIB2 string.

        Example:
            >>> encoder = CollectionEncoder()
            >>> enc = encoder.encode_list([1, 2], "int", name="xs")
            >>> smt = encoder.to_smt2(enc)
            >>> "(check-sat)" in smt
            True
        """
        kind = encoding.metadata.get("kind", "list")
        logic = (
            "QF_ALIA" if kind in ("list", "sequence", "dict") else "QF_AX"
        )
        lines: list[str] = [
            f"; JuGeo collection encoding v{_ENCODING_VERSION}",
            f"; kind={kind}  element_sort={encoding.element_sort}",
            f"; cardinality={encoding.metadata.get('cardinality', '?')}  id={encoding.encoding_id}",
            f"(set-logic {logic})",
            "",
            "; --- Declarations ---",
        ]
        for decl in encoding.metadata.get("declarations", []):
            lines.append(decl)
        lines.append("")
        lines.append("; --- Invariants ---")
        for inv in encoding.invariants:
            lines.append(inv)
        lines.append("")
        lines.append("(check-sat)")
        lines.append("(get-model)")
        return "\n".join(lines)

    def clear_cache(self) -> None:
        """Invalidate the internal encoding cache."""
        self._encoding_cache.clear()
        logger.debug("CollectionEncoder: cache cleared")

    def get_stats(self) -> dict[str, Any]:
        """Return a snapshot of encoding statistics.

        Returns:
            Dict with ``encode_calls``, ``cache_hits``, ``encode_ms``,
            ``cache_size``.
        """
        return {**self._stats, "cache_size": len(self._encoding_cache)}


