def create_encoder(
    *,
    log_name: str | None = None,
) -> InterfaceSummaryEncoder:
    """Create and return a fresh :class:`InterfaceSummaryEncoder`.

    Args
    ----
    log_name:
        Optional logger name override.  Defaults to ``__name__``.

    Returns
    -------
    InterfaceSummaryEncoder
        A newly constructed encoder with empty registries.

    Example
    -------
    >>> encoder = create_encoder()
    """
    logger_instance = logging.getLogger(log_name or __name__)
    enc = InterfaceSummaryEncoder(logger=logger_instance)
    _log.debug("create_encoder: created new InterfaceSummaryEncoder.")
    return enc


def fingerprint_abstraction(abstraction: InterfaceAbstraction) -> str:
    """Compute a stable SHA-256 fingerprint of an :class:`InterfaceAbstraction`.

    The fingerprint is based on the sort name, method signatures, and
    axiom strings.

    Args
    ----
    abstraction:
        The abstraction to fingerprint.

    Returns
    -------
    str
        A 16-character hex string (first 64 bits of SHA-256).

    Example
    -------
    >>> fp = fingerprint_abstraction(abstraction)
    >>> len(fp)
    16
    """
    parts = [abstraction.sort_name]
    for method_name in sorted(abstraction.method_signatures.keys()):
        sig = abstraction.method_signatures[method_name]
        parts.append(sig.summary())
    for axiom in sorted(abstraction.axioms):
        parts.append(axiom)
    raw = "|".join(parts).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:16]


def build_simple_interface(
    name: str,
    method_names: list[str],
    *,
    param_sort: str = _DEFAULT_PARAM_SORT,
    return_sort: str = _DEFAULT_RETURN_SORT,
) -> InterfaceAbstraction:
    """Build a simple interface with uniform method signatures.

    All methods take a single parameter of *param_sort* and return
    *return_sort*.  Useful for quick prototyping and testing.

    Args
    ----
    name:
        Interface name.
    method_names:
        List of method names to declare.
    param_sort:
        SMT sort for each method's single parameter.  Defaults to
        ``"Int"``.
    return_sort:
        SMT sort for each method's return value.  Defaults to ``"Bool"``.

    Returns
    -------
    InterfaceAbstraction
        The constructed abstraction.

    Example
    -------
    >>> abs_ = build_simple_interface("Cache", ["get", "put", "clear"])
    """
    encoder = create_encoder()
    methods: dict[str, tuple[list[str], str]] = {
        m: ([param_sort], return_sort) for m in method_names
    }
    abstraction = encoder.encode_interface(name, methods)
    _log.debug(
        "build_simple_interface: created %r with %d methods.",
        name,
        len(method_names),
    )
    return abstraction


def describe_abstraction(abstraction: InterfaceAbstraction) -> str:
    """Return a detailed, multi-line description of an abstraction.

    Includes all declarations and axioms formatted for readability.

    Args
    ----
    abstraction:
        The abstraction to describe.

    Returns
    -------
    str
        Formatted description.

    Example
    -------
    >>> print(describe_abstraction(abstraction))
    """
    encoder = create_encoder()
    return encoder.summary(abstraction)


def compose_two_interfaces(
    name1: str,
    name2: str,
    methods1: Mapping[str, tuple[list[str], str]],
    methods2: Mapping[str, tuple[list[str], str]],
) -> InterfaceAbstraction:
    """Encode and compose two interfaces into one product abstraction.

    Args
    ----
    name1:
        Name of the first interface.
    name2:
        Name of the second interface.
    methods1:
        Methods for the first interface.
    methods2:
        Methods for the second interface.

    Returns
    -------
    InterfaceAbstraction
        The composed abstraction.

    Example
    -------
    >>> composed = compose_two_interfaces(
    ...     "Stack", "Queue",
    ...     {"push": (["Int"], "Bool")},
    ...     {"enqueue": (["Int"], "Bool")},
    ... )
    """
    encoder = create_encoder()
    abs1 = encoder.encode_interface(name1, methods1)
    abs2 = encoder.encode_interface(name2, methods2)
    return encoder.compose_interfaces(abs1, abs2)


def smt2_sort_for_interface(
    name: str,
    methods: Mapping[str, tuple[list[str], str]],
) -> str:
    """Return the full SMT-LIB 2 theory string for an interface.

    Convenience wrapper around :meth:`InterfaceSummaryEncoder.to_smt2`.

    Args
    ----
    name:
        Interface name.
    methods:
        Method signatures map.

    Returns
    -------
    str
        Complete SMT-LIB 2 theory file string.

    Example
    -------
    >>> theory = smt2_sort_for_interface("Set", {"member": (["Int"], "Bool")})
    """
    encoder = create_encoder()
    abstraction = encoder.encode_interface(name, methods)
    return encoder.to_smt2(abstraction)
