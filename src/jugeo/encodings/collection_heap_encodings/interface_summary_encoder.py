# 1. RefinementStatus  —  lifecycle of an interface refinement
# ===========================================================================


class RefinementStatus(str, Enum):
    """Lifecycle status of an interface abstraction's refinement.

    Tracks the verification state of the refinement map from an abstract
    sort to a concrete sort.

    Values
    ------
    UNREFINED:
        No refinement map has been provided yet.  The abstraction has only
        sort and method declarations.
    PARTIAL:
        A refinement witness function has been declared but the totality
        and injectivity axioms have not yet been verified.
    COMPLETE:
        All refinement axioms have been emitted and are syntactically
        well-formed.  Solver verification has not yet been attempted.
    VERIFIED:
        The refinement axioms have been checked by the solver and found
        satisfiable.  The abstraction is considered sound.
    INVALID:
        The solver returned UNSAT for the refinement axioms, meaning the
        refinement is unsound.  A counterexample may be available.

    Example
    -------
    >>> RefinementStatus.UNREFINED.value
    'unrefined'
    >>> RefinementStatus("verified") is RefinementStatus.VERIFIED
    True
    """

    UNREFINED = "unrefined"
    PARTIAL = "partial"
    COMPLETE = "complete"
    VERIFIED = "verified"
    INVALID = "invalid"

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def is_sound(self) -> bool:
        """Return ``True`` iff the refinement is known to be sound.

        Returns
        -------
        bool
            ``True`` only for :attr:`VERIFIED`.

        Example
        -------
        >>> RefinementStatus.VERIFIED.is_sound()
        True
        >>> RefinementStatus.COMPLETE.is_sound()
        False
        """
        return self == RefinementStatus.VERIFIED

    def can_be_verified(self) -> bool:
        """Return ``True`` iff the solver can be called to verify this status.

        Returns
        -------
        bool
            ``True`` for :attr:`PARTIAL` and :attr:`COMPLETE`.
        """
        return self in (RefinementStatus.PARTIAL, RefinementStatus.COMPLETE)

    def transition_to_verified(self) -> RefinementStatus:
        """Return the :attr:`VERIFIED` status regardless of current state.

        Returns
        -------
        RefinementStatus
            :attr:`VERIFIED`.
        """
        return RefinementStatus.VERIFIED

    def transition_to_invalid(self) -> RefinementStatus:
        """Return the :attr:`INVALID` status regardless of current state.

        Returns
        -------
        RefinementStatus
            :attr:`INVALID`.
        """
        return RefinementStatus.INVALID


