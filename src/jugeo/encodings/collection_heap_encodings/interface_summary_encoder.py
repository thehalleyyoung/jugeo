# 2. MethodSignature  —  immutable record for an interface method
# ===========================================================================


@dataclass(frozen=True, slots=True)
class MethodSignature:
    """Immutable record capturing the SMT signature of an interface method.

    A :class:`MethodSignature` stores everything needed to emit a
    ``(declare-fun ...)`` statement in SMT-LIB 2 format, as well as
    optional pre/post condition strings that can be asserted as axioms.

    Attributes
    ----------
    method_name:
        The method's Python (and SMT) name, e.g. ``"get"``, ``"insert"``.
    param_sorts:
        Ordered tuple of SMT sort names for each parameter (excluding the
        implicit ``self`` / receiver, which is the abstract sort itself).
        E.g. ``("Int", "Bool")``.
    return_sort:
        The SMT sort name of the return value, e.g. ``"Bool"``, ``"Int"``.
    is_pure:
        When ``True`` the method has no observable side effects and its
        return value is a deterministic function of its inputs.  Pure
        methods are modelled as uninterpreted functions.  Impure methods
        may be modelled as relations.
    has_precondition:
        Whether a precondition string has been provided.
    precondition_str:
        Optional SMT-LIB 2 formula string for the method's precondition.
    postcondition_str:
        Optional SMT-LIB 2 formula string for the method's postcondition.

    Example
    -------
    >>> sig = MethodSignature(
    ...     method_name="get",
    ...     param_sorts=("Int",),
    ...     return_sort="Bool",
    ...     is_pure=True,
    ...     has_precondition=False,
    ...     precondition_str=None,
    ...     postcondition_str=None,
    ... )
    >>> sig.arity()
    1
    """

    method_name: str
    param_sorts: tuple[str, ...]
    return_sort: str
    is_pure: bool
    has_precondition: bool
    precondition_str: str | None
    postcondition_str: str | None

    # ------------------------------------------------------------------
    # Derived methods
    # ------------------------------------------------------------------

    def to_smt2_declaration(self, sort_name: str) -> str:
        """Return the SMT-LIB 2 ``(declare-fun ...)`` string for this method.

        The receiver (``self``) is prepended as the first argument with
        sort *sort_name*.

        Args
        ----
        sort_name:
            The name of the abstract sort that owns this method.

        Returns
        -------
        str
            A complete ``(declare-fun ...)`` statement.

        Example
        -------
        >>> sig.to_smt2_declaration("MyInterface")
        '(declare-fun MyInterface__get (MyInterface Int) Bool)'
        """
        fn_name = self.to_z3_function_name(sort_name)
        all_params = [sort_name] + list(self.param_sorts)
        params_str = " ".join(all_params)
        return _SMT2_DECLARE_FUN.format(
            name=fn_name,
            params=params_str,
            ret=self.return_sort,
        )

    def to_z3_function_name(self, sort_name: str) -> str:
        """Return the fully-qualified Z3 function name.

        The convention is ``{sort_name}__{method_name}`` (double underscore
        separator) to avoid name clashes across different abstract sorts.

        Args
        ----
        sort_name:
            The name of the abstract sort.

        Returns
        -------
        str
            The qualified function name.

        Example
        -------
        >>> sig.to_z3_function_name("Stack")
        'Stack__get'
        """
        return f"{sort_name}__{self.method_name}"

    def arity(self) -> int:
        """Return the number of non-receiver parameters.

        Returns
        -------
        int
            Length of :attr:`param_sorts`.

        Example
        -------
        >>> sig.arity()
        1
        """
        return len(self.param_sorts)

    def summary(self) -> str:
        """Return a one-line human-readable signature summary.

        Returns
        -------
        str
            E.g. ``"get(Int) -> Bool [pure]"``.

        Example
        -------
        >>> sig.summary()
        'get(Int) -> Bool [pure]'
        """
        params_str = ", ".join(self.param_sorts) if self.param_sorts else "()"
        purity_tag = "pure" if self.is_pure else "effectful"
        pre_tag = " pre" if self.has_precondition else ""
        post_tag = " post" if self.postcondition_str else ""
        return f"{self.method_name}({params_str}) -> {self.return_sort} [{purity_tag}{pre_tag}{post_tag}]"

    def has_postcondition(self) -> bool:
        """Return ``True`` iff a postcondition string is present.

        Returns
        -------
        bool
        """
        return self.postcondition_str is not None


