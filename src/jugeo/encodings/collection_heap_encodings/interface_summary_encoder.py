# 5. AbstractSortBuilder  —  low-level SMT-LIB 2 sort/function builder
# ===========================================================================


@dataclass(slots=True)
class AbstractSortBuilder:
    """Low-level builder for SMT-LIB 2 sort and function declarations.

    :class:`AbstractSortBuilder` accumulates sort declarations, function
    declarations, and axioms and can emit them as a complete SMT-LIB 2
    theory file.  It is used internally by :class:`InterfaceSummaryEncoder`
    and can also be used directly for custom theory construction.

    Attributes
    ----------
    _registered_sorts:
        Map from sort name to its ``(declare-sort ...)`` string.
    _declared_functions:
        Map from sort name to a list of ``(declare-fun ...)`` strings.
    _axioms:
        Map from sort name to a list of axiom strings.

    Example
    -------
    >>> builder = AbstractSortBuilder()
    >>> decl = builder.register_sort("MySort")
    >>> fn_decl = builder.declare_function("MySort", "myFn", ["Int"], "Bool")
    """

    _registered_sorts: dict[str, str] = field(default_factory=dict)
    _declared_functions: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))
    _axioms: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def register_sort(self, name: str) -> str:
        """Declare an uninterpreted sort and return the declaration string.

        Idempotent: if *name* is already registered, the existing
        declaration is returned unchanged.

        Args
        ----
        name:
            The sort name (must be a valid SMT-LIB 2 identifier).

        Returns
        -------
        str
            The ``(declare-sort name 0)`` string.

        Example
        -------
        >>> builder.register_sort("NodeSort")
        '(declare-sort NodeSort 0)'
        """
        if name in self._registered_sorts:
            return self._registered_sorts[name]
        decl = _SMT2_DECLARE_SORT.format(name=name)
        self._registered_sorts[name] = decl
        _log.debug("AbstractSortBuilder.register_sort: registered %r.", name)
        return decl

    def declare_function(
        self,
        sort_name: str,
        fn_name: str,
        param_sorts: list[str],
        return_sort: str,
    ) -> str:
        """Declare an uninterpreted function associated with *sort_name*.

        If *sort_name* is not yet registered, it is registered automatically.

        Args
        ----
        sort_name:
            The owning sort name.
        fn_name:
            The function name.
        param_sorts:
            SMT sort names for each parameter.
        return_sort:
            SMT sort name for the return value.

        Returns
        -------
        str
            The ``(declare-fun ...)`` string.

        Example
        -------
        >>> builder.declare_function("Stack", "push", ["Int"], "Bool")
        '(declare-fun push (Int) Bool)'
        """
        if sort_name not in self._registered_sorts:
            self.register_sort(sort_name)
        params_str = " ".join(param_sorts) if param_sorts else ""
        decl = _SMT2_DECLARE_FUN.format(
            name=fn_name,
            params=params_str,
            ret=return_sort,
        )
        self._declared_functions[sort_name].append(decl)
        _log.debug(
            "AbstractSortBuilder.declare_function: [%s] %s.", sort_name, fn_name
        )
        return decl

    def get_axioms_for(self, sort_name: str) -> list[str]:
        """Return all axioms associated with *sort_name*.

        Args
        ----
        sort_name:
            The sort name to query.

        Returns
        -------
        list[str]
            Axiom strings; empty list if no axioms are registered.

        Example
        -------
        >>> axioms = builder.get_axioms_for("Stack")
        """
        return list(self._axioms[sort_name])

    def build_theory_file(self, sorts: list[str]) -> str:
        """Build a complete SMT-LIB 2 theory file for the given *sorts*.

        Includes all sort declarations, function declarations, and axioms
        for each named sort.

        Args
        ----
        sorts:
            Ordered list of sort names to include.  Sorts not present in
            :attr:`_registered_sorts` are silently skipped.

        Returns
        -------
        str
            A complete SMT-LIB 2 theory file.

        Example
        -------
        >>> theory = builder.build_theory_file(["Stack", "Queue"])
        """
        header = _THEORY_FILE_HEADER.format(
            timestamp=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            encoder_id=_ENCODER_ID_PREFIX + uuid.uuid4().hex[:10],
        )
        parts: list[str] = [header]
        for sort_name in sorts:
            if sort_name not in self._registered_sorts:
                _log.warning(
                    "build_theory_file: sort %r not registered — skipping.", sort_name
                )
                continue
            parts.append(f";; --- Sort: {sort_name} ---")
            parts.append(self._registered_sorts[sort_name])
            for fn_decl in self._declared_functions.get(sort_name, []):
                parts.append(fn_decl)
            for axiom in self._axioms.get(sort_name, []):
                parts.append(axiom)
            parts.append("")
        parts.append("(check-sat)")
        parts.append("(get-model)")
        return "\n".join(parts) + "\n"

    def add_axiom(self, sort_name: str, axiom: str) -> None:
        """Add an axiom string to *sort_name*'s axiom list.

        The axiom is expected to be a complete ``(assert ...)`` string.
        If *sort_name* is not yet registered, it is registered first.

        Args
        ----
        sort_name:
            The sort this axiom belongs to.
        axiom:
            A well-formed SMT-LIB 2 assertion string.

        Example
        -------
        >>> builder.add_axiom("Stack", "(assert (forall ((s Stack)) (>= (size s) 0)))")
        """
        if sort_name not in self._registered_sorts:
            self.register_sort(sort_name)
        self._axioms[sort_name].append(axiom)
        _log.debug("AbstractSortBuilder.add_axiom: [%s] added axiom.", sort_name)

    def list_sorts(self) -> list[str]:
        """Return a sorted list of all registered sort names.

        Returns
        -------
        list[str]
            Alphabetically sorted sort names.

        Example
        -------
        >>> builder.list_sorts()
        ['Queue', 'Stack']
        """
        return sorted(self._registered_sorts.keys())

    def function_count_for(self, sort_name: str) -> int:
        """Return the number of declared functions for *sort_name*.

        Args
        ----
        sort_name:
            The sort name to query.

        Returns
        -------
        int
            Number of declared functions; 0 if sort is not registered.

        Example
        -------
        >>> builder.function_count_for("Stack")
        3
        """
        return len(self._declared_functions.get(sort_name, []))

    def axiom_count_for(self, sort_name: str) -> int:
        """Return the number of axioms registered for *sort_name*.

        Args
        ----
        sort_name:
            The sort name to query.

        Returns
        -------
        int
            Number of axioms; 0 if sort is not registered or has no axioms.
        """
        return len(self._axioms.get(sort_name, []))

    def total_declaration_count(self) -> int:
        """Return the total number of function declarations across all sorts.

        Returns
        -------
        int
            Sum of function declaration counts.
        """
        return sum(len(decls) for decls in self._declared_functions.values())

    def summary(self) -> str:
        """Return a human-readable summary of the builder state.

        Returns
        -------
        str
            Multi-line summary.

        Example
        -------
        >>> print(builder.summary())
        """
        lines = [
            "AbstractSortBuilder state:",
            f"  Registered sorts : {len(self._registered_sorts)}",
            f"  Total functions  : {self.total_declaration_count()}",
        ]
        for sort_name in self.list_sorts():
            lines.append(
                f"    {sort_name}: {self.function_count_for(sort_name)} fns, "
                f"{self.axiom_count_for(sort_name)} axioms"
            )
        return "\n".join(lines)


