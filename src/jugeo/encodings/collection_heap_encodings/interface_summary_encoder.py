# 3. InterfaceSummaryEncoder  —  main encoding engine
# ===========================================================================


@dataclass(slots=True)
class InterfaceSummaryEncoder:
    """Encodes Python interfaces as abstract Z3 sorts with method declarations.

    The encoder maintains registries of known abstract sorts, declared
    uninterpreted functions, and their associated axioms.  It produces
    :class:`~jugeo.encodings.collection_heap_encodings.models.InterfaceAbstraction`
    instances that carry all SMT-LIB 2 declarations.

    Attributes
    ----------
    logger:
        Module-level logger.
    _abstraction_cache:
        Map from interface name to the most recently produced
        :class:`InterfaceAbstraction`.
    _sort_registry:
        Map from sort name to its ``(declare-sort ...)`` string.
    _axiom_library:
        Map from sort name to a list of axiom strings.

    Example
    -------
    >>> encoder = InterfaceSummaryEncoder()
    >>> abstraction = encoder.encode_interface(
    ...     "Stack",
    ...     methods={"push": (["Int"], "Bool"), "pop": ([], "Int")},
    ... )
    """

    logger: logging.Logger = field(default_factory=lambda: logging.getLogger(__name__))
    _abstraction_cache: dict[str, InterfaceAbstraction] = field(default_factory=dict)
    _sort_registry: dict[str, str] = field(default_factory=dict)
    _axiom_library: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def encode_interface(
        self,
        name: str,
        methods: Mapping[str, tuple[list[str], str]],
    ) -> InterfaceAbstraction:
        """Create an :class:`InterfaceAbstraction` for an interface.

        Declares an abstract SMT sort ``{name}Sort`` and an uninterpreted
        function for each method.  An extensionality axiom is appended that
        asserts two abstract values are equal iff all their method results
        agree.

        Args
        ----
        name:
            The interface name (e.g. ``"Stack"``).  Used as a prefix for
            the sort name and all function names.
        methods:
            A mapping from method name to ``(param_sort_list, return_sort)``
            tuple.  The sort strings must be valid SMT-LIB 2 sort names.

        Returns
        -------
        InterfaceAbstraction
            The resulting abstraction, also stored in
            :attr:`_abstraction_cache`.

        Raises
        ------
        ValueError
            If *name* is empty or *methods* contains more than
            :attr:`MAX_METHODS_PER_INTERFACE` entries.
        OverflowError
            If the total number of interfaces would exceed
            :attr:`MAX_INTERFACES_PER_ENCODER`.

        Example
        -------
        >>> abs_ = encoder.encode_interface("Queue", {"enqueue": (["Int"], "Bool")})
        >>> abs_.sort_name
        'QueueSort'
        """
        if not name:
            raise ValueError("encode_interface: interface name must not be empty.")
        if len(methods) > MAX_METHODS_PER_INTERFACE:
            raise ValueError(
                f"encode_interface: method count {len(methods)} exceeds "
                f"MAX_METHODS_PER_INTERFACE ({MAX_METHODS_PER_INTERFACE})."
            )
        if len(self._abstraction_cache) >= MAX_INTERFACES_PER_ENCODER:
            raise OverflowError(
                f"MAX_INTERFACES_PER_ENCODER ({MAX_INTERFACES_PER_ENCODER}) exceeded."
            )
        sort_name = f"{name}Sort"
        sort_decl = self._declare_abstract_sort(sort_name)
        self._sort_registry[sort_name] = sort_decl

        declarations: list[str] = [sort_decl]
        signatures: list[MethodSignature] = []

        for method_name, (param_sorts, return_sort) in methods.items():
            sig = MethodSignature(
                method_name=method_name,
                param_sorts=tuple(param_sorts),
                return_sort=return_sort,
                is_pure=True,
                has_precondition=False,
                precondition_str=None,
                postcondition_str=None,
            )
            fn_decl = self._declare_method_fn(sort_name, sig)
            declarations.append(fn_decl)
            signatures.append(sig)
            self.logger.debug(
                "[%s] encode_interface: declared method %r → %s",
                name,
                method_name,
                fn_decl,
            )

        # Extensionality axiom.
        if len(signatures) > 0:
            ext_axiom = self._extensionality_axiom(sort_name, signatures)
            declarations.append(ext_axiom)
            self._axiom_library[sort_name].append(ext_axiom)

        abstraction = InterfaceAbstraction(
            name=name,
            sort_name=sort_name,
            method_signatures={sig.method_name: sig for sig in signatures},
            smt2_declarations=declarations,
            refinement_status=RefinementStatus.UNREFINED.value,
            axioms=list(self._axiom_library[sort_name]),
            metadata={
                "encoder_id": _ENCODER_ID_PREFIX + uuid.uuid4().hex[:10],
                "created_at": time.time(),
            },
        )
        self._abstraction_cache[name] = abstraction
        self.logger.info(
            "encode_interface: created abstraction for %r  "
            "(sort=%r, methods=%d, declarations=%d).",
            name,
            sort_name,
            len(signatures),
            len(declarations),
        )
        return abstraction

    def add_method_signature(
        self,
        abstraction: InterfaceAbstraction,
        method_name: str,
        param_sorts: list[str],
        return_sort: str,
    ) -> InterfaceAbstraction:
        """Add a new method to an existing :class:`InterfaceAbstraction`.

        A new :class:`MethodSignature` is created and its ``(declare-fun
        ...)`` statement is appended to the abstraction's declaration list.
        The extensionality axiom is regenerated to cover the new method.

        Args
        ----
        abstraction:
            The existing abstraction to extend.
        method_name:
            Name of the new method.
        param_sorts:
            SMT sort names for each parameter (excluding receiver).
        return_sort:
            SMT sort name for the return value.

        Returns
        -------
        InterfaceAbstraction
            A new :class:`InterfaceAbstraction` instance incorporating the
            additional method.

        Raises
        ------
        ValueError
            If *method_name* already exists in *abstraction*.

        Example
        -------
        >>> extended = encoder.add_method_signature(abs_, "size", [], "Int")
        """
        if method_name in abstraction.method_signatures:
            raise ValueError(
                f"add_method_signature: method {method_name!r} already "
                f"declared in abstraction {abstraction.name!r}."
            )
        sig = MethodSignature(
            method_name=method_name,
            param_sorts=tuple(param_sorts),
            return_sort=return_sort,
            is_pure=True,
            has_precondition=False,
            precondition_str=None,
            postcondition_str=None,
        )
        fn_decl = self._declare_method_fn(abstraction.sort_name, sig)
        new_sigs = dict(abstraction.method_signatures)
        new_sigs[method_name] = sig
        new_decls = list(abstraction.smt2_declarations) + [fn_decl]
        # Regenerate extensionality axiom.
        ext_axiom = self._extensionality_axiom(abstraction.sort_name, list(new_sigs.values()))
        # Replace old extensionality axiom if present.
        new_decls = [d for d in new_decls if _EXTENSIONALITY_AXIOM_TAG not in d]
        new_decls.append(ext_axiom)
        updated = InterfaceAbstraction(
            name=abstraction.name,
            sort_name=abstraction.sort_name,
            method_signatures=new_sigs,
            smt2_declarations=new_decls,
            refinement_status=abstraction.refinement_status,
            axioms=list(abstraction.axioms) + [ext_axiom],
            metadata=dict(abstraction.metadata),
        )
        self._abstraction_cache[abstraction.name] = updated
        self.logger.debug(
            "add_method_signature: added %r to %r  (total methods=%d).",
            method_name,
            abstraction.name,
            len(new_sigs),
        )
        return updated

    def encode_refinement(
        self,
        abstraction: InterfaceAbstraction,
        concrete_sort: str,
        witness_fn: str,
    ) -> InterfaceAbstraction:
        """Declare a refinement witness from the abstract sort to *concrete_sort*.

        Appends:

        1. A ``(declare-fun witness_fn (AbstractSort) ConcreteSort)``
           declaration.
        2. A totality axiom asserting that every abstract value maps to
           some concrete value.
        3. A refinement-consistency comment in the declaration list.

        Args
        ----
        abstraction:
            The abstract interface to refine.
        concrete_sort:
            The SMT sort name of the concrete implementation.
        witness_fn:
            The SMT function name for the refinement map.  If empty,
            defaults to ``{sort_name}_witness``.

        Returns
        -------
        InterfaceAbstraction
            Updated abstraction with refinement declarations.

        Raises
        ------
        ValueError
            If *concrete_sort* is empty.

        Example
        -------
        >>> refined = encoder.encode_refinement(abs_, "LinkedList", "")
        """
        if not concrete_sort:
            raise ValueError("encode_refinement: concrete_sort must not be empty.")
        if not witness_fn:
            witness_fn = abstraction.sort_name + _WITNESS_FN_SUFFIX
        witness_decl = _SMT2_DECLARE_FUN.format(
            name=witness_fn,
            params=abstraction.sort_name,
            ret=concrete_sort,
        )
        # Totality axiom: forall x:AbstractSort. exists y:ConcreteSort. witness(x) = y
        # Simplified (since declare-fun is already total): just assert it is
        # a function (trivially true).  We assert a round-trip property instead.
        totality_comment = _REFINEMENT_TOTALITY_TAG
        totality_axiom = (
            f"{totality_comment}\n"
            f"(assert {_SMT2_FORALL.format(var='__x__', sort=abstraction.sort_name, body='(exists ((__y__ ' + concrete_sort + ')) (= (' + witness_fn + ' __x__) __y__))')})"
        )
        new_decls = list(abstraction.smt2_declarations) + [witness_decl, totality_axiom]
        new_axioms = list(abstraction.axioms) + [totality_axiom]
        new_metadata = dict(abstraction.metadata)
        new_metadata["concrete_sort"] = concrete_sort
        new_metadata["witness_fn"] = witness_fn
        new_metadata["refinement_added_at"] = time.time()
        updated = InterfaceAbstraction(
            name=abstraction.name,
            sort_name=abstraction.sort_name,
            method_signatures=abstraction.method_signatures,
            smt2_declarations=new_decls,
            refinement_status=RefinementStatus.PARTIAL.value,
            axioms=new_axioms,
            metadata=new_metadata,
        )
        self._abstraction_cache[abstraction.name] = updated
        self.logger.debug(
            "encode_refinement: added witness %r (%s -> %s)  for %r.",
            witness_fn,
            abstraction.sort_name,
            concrete_sort,
            abstraction.name,
        )
        return updated

    def verify_refinement(
        self,
        abstraction: InterfaceAbstraction,
        session: Z3Session,
    ) -> Z3Result:
        """Check that the refinement axioms are satisfiable.

        Assembles all declarations and axioms from *abstraction* into a
        :class:`~jugeo.solver.z3_session.Z3QueryBuilder` and runs a
        satisfiability check.

        Args
        ----
        abstraction:
            The abstraction to verify.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        Z3Result
            The solver outcome.  :attr:`~jugeo.solver.z3_session.Z3Result.outcome`
            is ``SAT`` iff the refinement axioms are consistent.

        Raises
        ------
        ValueError
            If the abstraction's refinement status is :attr:`RefinementStatus.UNREFINED`.

        Example
        -------
        >>> result = encoder.verify_refinement(abstraction, session)
        >>> assert result.outcome == SolveOutcome.SAT
        """
        if abstraction.refinement_status == RefinementStatus.UNREFINED.value:
            raise ValueError(
                f"verify_refinement: abstraction {abstraction.name!r} has no "
                "refinement map declared; call encode_refinement first."
            )
        builder = Z3QueryBuilder(session=session)
        for stmt in abstraction.smt2_declarations:
            for line in stmt.split("\n"):
                line = line.strip()
                if line.startswith("(assert") or line.startswith("(declare"):
                    builder.add_assertion(line)
        result = builder.check()
        if result.outcome == SolveOutcome.SAT:
            self.logger.info(
                "verify_refinement [%r]: SAT — refinement is consistent.",
                abstraction.name,
            )
        elif result.outcome == SolveOutcome.UNSAT:
            self.logger.warning(
                "verify_refinement [%r]: UNSAT — refinement axioms are contradictory.",
                abstraction.name,
            )
        else:
            self.logger.info(
                "verify_refinement [%r]: %s.",
                abstraction.name,
                result.outcome.value,
            )
        return result

    def project_to_method(
        self,
        abstraction: InterfaceAbstraction,
        method_name: str,
    ) -> str | None:
        """Return the SMT-LIB 2 declaration string for a specific method.

        Args
        ----
        abstraction:
            The abstraction to query.
        method_name:
            The method name to look up.

        Returns
        -------
        str | None
            The ``(declare-fun ...)`` string, or ``None`` if the method is
            not declared.

        Example
        -------
        >>> decl = encoder.project_to_method(abs_, "push")
        """
        sig = abstraction.method_signatures.get(method_name)
        if sig is None:
            return None
        return sig.to_smt2_declaration(abstraction.sort_name)

    def abstract_value_for(
        self,
        abstraction: InterfaceAbstraction,
        concrete_val: str,
    ) -> str:
        """Apply the abstraction map to a concrete value.

        Returns the SMT expression ``(witness_fn concrete_val)``.  If no
        witness function has been declared, returns a placeholder comment.

        Args
        ----
        abstraction:
            The abstraction with a refinement map.
        concrete_val:
            An SMT term of the concrete sort.

        Returns
        -------
        str
            An SMT expression applying the witness function.

        Example
        -------
        >>> expr = encoder.abstract_value_for(refined_abs, "linked_list_0")
        """
        witness_fn = abstraction.metadata.get("witness_fn")
        if witness_fn is None:
            self.logger.warning(
                "abstract_value_for [%r]: no witness function declared.",
                abstraction.name,
            )
            return f"; no-witness-for {concrete_val}"
        return f"({witness_fn} {concrete_val})"

    def compose_interfaces(
        self,
        abs1: InterfaceAbstraction,
        abs2: InterfaceAbstraction,
    ) -> InterfaceAbstraction:
        """Create a combined interface with methods from both *abs1* and *abs2*.

        The composed interface has a fresh sort name
        ``{abs1.name}_{abs2.name}Sort`` and declares all methods from both
        abstractions (qualified with their original sort names to avoid
        name clashes).

        Args
        ----
        abs1:
            First interface abstraction.
        abs2:
            Second interface abstraction.

        Returns
        -------
        InterfaceAbstraction
            A new abstraction representing the product interface.

        Raises
        ------
        ValueError
            If *abs1* and *abs2* have the same name.

        Example
        -------
        >>> combined = encoder.compose_interfaces(stack_abs, queue_abs)
        """
        if abs1.name == abs2.name:
            raise ValueError(
                f"compose_interfaces: cannot compose interface with itself ({abs1.name!r})."
            )
        composed_name = f"{abs1.name}_{abs2.name}"
        composed_sort = f"{composed_name}Sort"
        sort_decl = self._declare_abstract_sort(composed_sort)
        declarations: list[str] = [sort_decl]
        merged_sigs: dict[str, MethodSignature] = {}
        # Methods from abs1 — re-qualified.
        for method_name, sig in abs1.method_signatures.items():
            qualified_name = f"{abs1.name}_{method_name}"
            new_sig = MethodSignature(
                method_name=qualified_name,
                param_sorts=sig.param_sorts,
                return_sort=sig.return_sort,
                is_pure=sig.is_pure,
                has_precondition=sig.has_precondition,
                precondition_str=sig.precondition_str,
                postcondition_str=sig.postcondition_str,
            )
            merged_sigs[qualified_name] = new_sig
            declarations.append(new_sig.to_smt2_declaration(composed_sort))
        # Methods from abs2 — re-qualified.
        for method_name, sig in abs2.method_signatures.items():
            qualified_name = f"{abs2.name}_{method_name}"
            new_sig = MethodSignature(
                method_name=qualified_name,
                param_sorts=sig.param_sorts,
                return_sort=sig.return_sort,
                is_pure=sig.is_pure,
                has_precondition=sig.has_precondition,
                precondition_str=sig.precondition_str,
                postcondition_str=sig.postcondition_str,
            )
            merged_sigs[qualified_name] = new_sig
            declarations.append(new_sig.to_smt2_declaration(composed_sort))
        # Extensionality for the composed sort.
        if merged_sigs:
            ext_axiom = self._extensionality_axiom(composed_sort, list(merged_sigs.values()))
            declarations.append(ext_axiom)
        composed = InterfaceAbstraction(
            name=composed_name,
            sort_name=composed_sort,
            method_signatures=merged_sigs,
            smt2_declarations=declarations,
            refinement_status=RefinementStatus.UNREFINED.value,
            axioms=[],
            metadata={
                "composed_from": [abs1.name, abs2.name],
                "created_at": time.time(),
            },
        )
        self._abstraction_cache[composed_name] = composed
        self.logger.info(
            "compose_interfaces: composed %r + %r → %r  (methods=%d).",
            abs1.name,
            abs2.name,
            composed_name,
            len(merged_sigs),
        )
        return composed

    def check_behavioral_equivalence(
        self,
        abs1: InterfaceAbstraction,
        abs2: InterfaceAbstraction,
        session: Z3Session,
    ) -> Z3Result:
        """Check if *abs1* and *abs2* satisfy the same Z3 constraints.

        Two interfaces are behaviourally equivalent iff they have the same
        set of method names, the same method sorts, and their combined
        axiom sets are jointly satisfiable.

        Args
        ----
        abs1:
            First interface abstraction.
        abs2:
            Second interface abstraction.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        Z3Result
            ``SAT`` if a model exists satisfying both axiom sets;
            ``UNSAT`` if they are jointly contradictory.

        Example
        -------
        >>> result = encoder.check_behavioral_equivalence(abs1, abs2, session)
        """
        # Check structural signature equivalence first.
        sig1_keys = set(abs1.method_signatures.keys())
        sig2_keys = set(abs2.method_signatures.keys())
        if sig1_keys != sig2_keys:
            self.logger.info(
                "check_behavioral_equivalence: %r and %r have different method sets "
                "(%r vs %r) — UNSAT by structural mismatch.",
                abs1.name,
                abs2.name,
                sig1_keys,
                sig2_keys,
            )
            return Z3Result.make_unsat(
                query_id=f"beq_{abs1.name}_{abs2.name}",
                elapsed_ms=0.0,
                reason="Method sets differ — structural non-equivalence.",
            )
        builder = Z3QueryBuilder(session=session)
        for stmt in abs1.smt2_declarations + abs2.smt2_declarations:
            for line in stmt.split("\n"):
                line = line.strip()
                if line.startswith("(assert") or line.startswith("(declare"):
                    builder.add_assertion(line)
        result = builder.check()
        self.logger.info(
            "check_behavioral_equivalence [%r vs %r]: %s.",
            abs1.name,
            abs2.name,
            result.outcome.value,
        )
        return result

    def to_smt2(self, abstraction: InterfaceAbstraction) -> str:
        """Return a complete SMT-LIB 2 theory file for *abstraction*.

        The file includes the set-logic preamble, all declarations, all
        axioms, and a check-sat command.

        Args
        ----
        abstraction:
            The abstraction to serialise.

        Returns
        -------
        str
            A complete SMT-LIB 2 file as a string.

        Example
        -------
        >>> theory = encoder.to_smt2(abstraction)
        >>> print(theory[:60])
        ;; Theory file generated by JuGeo interface_summary_encoder
        """
        encoder_id = abstraction.metadata.get("encoder_id", "unknown")
        header = _THEORY_FILE_HEADER.format(
            timestamp=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            encoder_id=encoder_id,
        )
        body_parts: list[str] = []
        body_parts.append(f";; Abstract sort: {abstraction.sort_name}")
        body_parts.append(f";; Interface    : {abstraction.name}")
        body_parts.append(f";; Methods      : {len(abstraction.method_signatures)}")
        body_parts.append(f";; Status       : {abstraction.refinement_status}")
        body_parts.append("")
        for decl in abstraction.smt2_declarations:
            body_parts.append(decl)
        body_parts.append("")
        body_parts.append("(check-sat)")
        body_parts.append("(get-model)")
        return header + "\n".join(body_parts) + "\n"

    def summary(self, abstraction: InterfaceAbstraction) -> str:
        """Return a human-readable summary of *abstraction*.

        Args
        ----
        abstraction:
            The abstraction to summarise.

        Returns
        -------
        str
            A multi-line string suitable for log output or documentation.

        Example
        -------
        >>> print(encoder.summary(abstraction))
        """
        lines = [
            f"InterfaceAbstraction {abstraction.name!r}",
            f"  Sort            : {abstraction.sort_name}",
            f"  Methods         : {len(abstraction.method_signatures)}",
            f"  Declarations    : {len(abstraction.smt2_declarations)}",
            f"  Axioms          : {len(abstraction.axioms)}",
            f"  Refinement      : {abstraction.refinement_status}",
        ]
        if abstraction.method_signatures:
            lines.append("  Method signatures:")
            for sig in sorted(abstraction.method_signatures.values(), key=lambda s: s.method_name):
                lines.append(f"    {sig.summary()}")
        concrete = abstraction.metadata.get("concrete_sort")
        if concrete:
            witness = abstraction.metadata.get("witness_fn", "(unknown)")
            lines.append(f"  Concrete sort   : {concrete}")
            lines.append(f"  Witness fn      : {witness}")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _declare_abstract_sort(self, name: str) -> str:
        """Return the ``(declare-sort name 0)`` SMT-LIB 2 string.

        Args
        ----
        name:
            The sort name to declare.

        Returns
        -------
        str
            The sort declaration string.
        """
        return _SMT2_DECLARE_SORT.format(name=name)

    def _declare_method_fn(self, sort_name: str, sig: MethodSignature) -> str:
        """Return the ``(declare-fun ...)`` SMT-LIB 2 string for *sig*.

        The receiver sort is prepended to the parameter list.

        Args
        ----
        sort_name:
            The abstract sort that owns this method.
        sig:
            The method signature.

        Returns
        -------
        str
            The function declaration string.
        """
        return sig.to_smt2_declaration(sort_name)

    def _extensionality_axiom(
        self,
        sort_name: str,
        signatures: list[MethodSignature],
    ) -> str:
        """Construct an extensionality axiom for *sort_name*.

        The axiom states: two values *x* and *y* of *sort_name* are equal iff
        they return the same result for every method when applied to identical
        arguments.  For simplicity, the axiom is generated for nullary (zero
        non-receiver parameter) methods only; methods with parameters use a
        universally quantified form.

        Args
        ----
        sort_name:
            The abstract sort.
        signatures:
            All method signatures for the sort.

        Returns
        -------
        str
            A multi-line SMT-LIB 2 assertion string.
        """
        # Build the conjunction of per-method equalities for nullary methods.
        nullary_sigs = [s for s in signatures if s.arity() == 0]
        if not nullary_sigs:
            # Emit a trivial comment — no testable methods.
            return (
                f"{_EXTENSIONALITY_AXIOM_TAG}\n"
                f"; no nullary methods in {sort_name} — extensionality not generated"
            )
        eq_parts: list[str] = []
        for sig in nullary_sigs:
            fn = sig.to_z3_function_name(sort_name)
            eq_parts.append(f"(= ({fn} __x__) ({fn} __y__))")
        body_conj: str
        if len(eq_parts) == 1:
            body_conj = eq_parts[0]
        else:
            body_conj = "(and " + " ".join(eq_parts) + ")"
        impl = _SMT2_IMPLIES.format(
            antecedent=body_conj,
            consequent=_SMT2_EQ.format(lhs="__x__", rhs="__y__"),
        )
        inner = (
            f"(forall ((__x__ {sort_name}) (__y__ {sort_name}))\n"
            f"  {impl})"
        )
        return (
            f"{_EXTENSIONALITY_AXIOM_TAG}\n"
            f"(assert {inner})"
        )


