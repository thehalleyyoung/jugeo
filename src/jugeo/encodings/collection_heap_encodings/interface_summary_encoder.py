# 4. InterfaceRefinementChecker
# ===========================================================================


@dataclass(slots=True)
class InterfaceRefinementChecker:
    """Verifies that a concrete sort faithfully refines an abstract interface.

    For each method in the abstraction, a dedicated solver check is run
    to confirm that the method's pre/postcondition holds when the witness
    function is substituted.

    Attributes
    ----------
    _result_cache:
        Map from ``(method_name, abstraction_id)`` to a cached
        :class:`~jugeo.solver.z3_session.Z3Result`.

    Example
    -------
    >>> checker = InterfaceRefinementChecker()
    >>> results = checker.check_all_methods(abstraction, session)
    """

    _result_cache: dict[tuple[str, str], Z3Result] = field(default_factory=dict)

    def check_method_refinement(
        self,
        method: str,
        abstraction: InterfaceAbstraction,
        concrete: str,
        session: Z3Session,
    ) -> Z3Result:
        """Check that method *method* is correctly refined in *concrete*.

        Builds a query that declares the abstract sort, the concrete sort,
        and the witness function, then asserts the method's postcondition
        (if any) and checks satisfiability.

        Args
        ----
        method:
            The method name to check.
        abstraction:
            The abstract interface.
        concrete:
            The SMT sort name of the concrete implementation.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        Z3Result
            Solver outcome for this method's refinement check.

        Raises
        ------
        KeyError
            If *method* is not declared in *abstraction*.

        Example
        -------
        >>> result = checker.check_method_refinement("push", abs_, "Stack", session)
        """
        if method not in abstraction.method_signatures:
            raise KeyError(
                f"check_method_refinement: method {method!r} not in "
                f"abstraction {abstraction.name!r}."
            )
        cache_key = (method, abstraction.name + "_" + concrete)
        if cache_key in self._result_cache:
            _log.debug("InterfaceRefinementChecker: cache hit (%s, %s).", method, concrete)
            return self._result_cache[cache_key]
        builder = Z3QueryBuilder(session=session)
        # Inject all declarations from the abstraction.
        for decl in abstraction.smt2_declarations:
            for line in decl.split("\n"):
                line = line.strip()
                if line.startswith("(declare"):
                    builder.add_assertion(line)
        # Declare witness function if not already present.
        witness_fn = abstraction.metadata.get("witness_fn")
        if witness_fn:
            builder.add_assertion(
                _SMT2_DECLARE_FUN.format(
                    name=witness_fn,
                    params=abstraction.sort_name,
                    ret=concrete,
                )
            )
        # Assert postcondition if present.
        sig = abstraction.method_signatures[method]
        if sig.postcondition_str:
            builder.add_assertion(_SMT2_ASSERT.format(body=sig.postcondition_str))
        result = builder.check()
        self._result_cache[cache_key] = result
        _log.debug(
            "InterfaceRefinementChecker.check_method_refinement [%s / %s / %s]: %s.",
            method,
            abstraction.name,
            concrete,
            result.outcome.value,
        )
        return result

    def check_all_methods(
        self,
        abstraction: InterfaceAbstraction,
        session: Z3Session,
    ) -> dict[str, Z3Result]:
        """Check every method in *abstraction*.

        Args
        ----
        abstraction:
            The abstraction to check.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        dict[str, Z3Result]
            Map from method name to its solver result.

        Example
        -------
        >>> results = checker.check_all_methods(abstraction, session)
        """
        concrete = abstraction.metadata.get("concrete_sort", "ConcreteSort")
        results: dict[str, Z3Result] = {}
        for method_name in abstraction.method_signatures:
            try:
                result = self.check_method_refinement(
                    method_name, abstraction, concrete, session
                )
            except Exception as exc:
                _log.error(
                    "check_all_methods [%s]: error checking %r: %s",
                    abstraction.name,
                    method_name,
                    exc,
                )
                result = Z3Result.make_unknown(
                    query_id=method_name,
                    elapsed_ms=0.0,
                    reason=str(exc),
                )
            results[method_name] = result
        _log.info(
            "check_all_methods [%s]: %d/%d SAT.",
            abstraction.name,
            sum(1 for r in results.values() if r.outcome == SolveOutcome.SAT),
            len(results),
        )
        return results

    def find_counterexample(
        self,
        method: str,
        session: Z3Session,
    ) -> dict[str, Any] | None:
        """Return a counterexample for a failed method check, or ``None``.

        Args
        ----
        method:
            Method name (used as a lookup key in the result cache).
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        dict[str, Any] | None
            Model assignments if a counterexample exists; ``None`` if the
            result is SAT or has no model.

        Example
        -------
        >>> cex = checker.find_counterexample("push", session)
        """
        matching = [
            (key, result)
            for key, result in self._result_cache.items()
            if key[0] == method and result.outcome == SolveOutcome.UNSAT
        ]
        if not matching:
            return None
        _, result = matching[0]
        if result.model is not None:
            return dict(result.model)
        return {"_unsat_no_model": True, "method": method}

    def refine_abstraction(
        self,
        abstraction: InterfaceAbstraction,
        counterexample: dict[str, Any],
    ) -> InterfaceAbstraction:
        """Strengthen *abstraction* to exclude a known counterexample.

        Adds a negation axiom blocking the specific model assignments
        provided in *counterexample*.  This drives a CEGAR (counterexample-
        guided abstraction refinement) loop.

        Args
        ----
        abstraction:
            The abstraction to strengthen.
        counterexample:
            A model dict from :meth:`find_counterexample`.

        Returns
        -------
        InterfaceAbstraction
            An updated abstraction with a blocking axiom.

        Example
        -------
        >>> stronger = checker.refine_abstraction(abstraction, cex)
        """
        if not counterexample or counterexample.get("_unsat_no_model"):
            _log.debug("refine_abstraction: no concrete counterexample to block.")
            return abstraction
        # Build a blocking clause.
        block_parts: list[str] = []
        for var, val in sorted(counterexample.items()):
            if var.startswith("_"):
                continue
            block_parts.append(f"(= {var} {val!r})")
        if not block_parts:
            return abstraction
        if len(block_parts) == 1:
            blocking_body = f"(not {block_parts[0]})"
        else:
            blocking_body = "(not (and " + " ".join(block_parts) + "))"
        blocking_axiom = _SMT2_ASSERT.format(body=blocking_body)
        new_decls = list(abstraction.smt2_declarations) + [
            f"; CEGAR blocking axiom\n{blocking_axiom}"
        ]
        new_axioms = list(abstraction.axioms) + [blocking_axiom]
        updated = InterfaceAbstraction(
            name=abstraction.name,
            sort_name=abstraction.sort_name,
            method_signatures=abstraction.method_signatures,
            smt2_declarations=new_decls,
            refinement_status=RefinementStatus.PARTIAL.value,
            axioms=new_axioms,
            metadata=dict(abstraction.metadata),
        )
        _log.info(
            "refine_abstraction [%r]: added blocking axiom for counterexample %r.",
            abstraction.name,
            counterexample,
        )
        return updated

    def summarize_refinement(
        self,
        abstraction: InterfaceAbstraction,
        results: dict[str, Z3Result],
    ) -> str:
        """Return a human-readable summary of all method refinement results.

        Args
        ----
        abstraction:
            The abstraction that was checked.
        results:
            The dict returned by :meth:`check_all_methods`.

        Returns
        -------
        str
            A multi-line summary string.

        Example
        -------
        >>> print(checker.summarize_refinement(abstraction, results))
        """
        n_total = len(results)
        n_sat = sum(1 for r in results.values() if r.outcome == SolveOutcome.SAT)
        n_unsat = sum(1 for r in results.values() if r.outcome == SolveOutcome.UNSAT)
        n_other = n_total - n_sat - n_unsat
        lines = [
            f"RefinementChecker summary for {abstraction.name!r}",
            f"  Concrete sort : {abstraction.metadata.get('concrete_sort', '(none)')}",
            f"  Methods total : {n_total}",
            f"  SAT           : {n_sat}",
            f"  UNSAT         : {n_unsat}",
            f"  UNKNOWN       : {n_other}",
        ]
        if n_unsat > 0:
            failed = [m for m, r in results.items() if r.outcome == SolveOutcome.UNSAT]
            lines.append(f"  ⚠ Failed methods: {', '.join(sorted(failed))}")
        return "\n".join(lines)


