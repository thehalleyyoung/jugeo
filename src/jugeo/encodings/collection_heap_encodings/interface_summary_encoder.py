r"""interface_summary_encoder — Abstract interface as Z3 sort with refinement.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch27: Exact Z3 encodings II: collections, finite maps, heap summaries,
alias partitions, interface abstractions.

Encodes Python interfaces (abstract base classes, protocols) as abstract Z3 sorts
with method signatures declared as uninterpreted functions.  Refinement maps
connect the abstract sort to a concrete Z3 sort via a witness function.
Behavioral equivalence checks verify that two interface implementations satisfy
the same Z3 constraints.

Part of the JuGeo judgment-geometry framework.

Architecture overview
---------------------
This module is built around three collaborating classes:

* :class:`InterfaceSummaryEncoder` -- the primary encoding engine that
  translates Python-level interface descriptions into SMT-LIB 2 sort
  declarations and uninterpreted function declarations.

* :class:`InterfaceRefinementChecker` -- verifies that a concrete sort
  faithfully refines an abstract interface sort by checking all method
  contracts against a live Z3 session.

* :class:`AbstractSortBuilder` -- low-level builder that manages the
  accumulation of sort declarations, function declarations, and axioms
  into a complete SMT-LIB 2 theory file.

Supporting infrastructure:

* :class:`MethodSignature` -- immutable record capturing the name,
  parameter sorts, return sort, purity flag, and optional pre/post
  conditions of an interface method.

Design principles
-----------------
* Abstract sorts are declared with ``(declare-sort SortName 0)`` to
  avoid committing to any cardinality or structural constraints beyond
  those implied by the method axioms.
* Method uninterpreted functions are declared as
  ``(declare-fun method_name (SortName arg1Sort ...) RetSort)``
  and are initially unconstrained.  Behavioural constraints are layered
  on top as axioms.
* Refinement witnesses are total functions from the abstract sort to a
  concrete sort, asserting that every abstract value has a concrete
  representative.
* Extensionality axioms assert that two abstract values that agree on all
  method results are equal.

Glossary
--------
abstract sort
    An uninterpreted SMT sort ``(declare-sort S 0)`` that represents the
    carrier set of an interface without committing to its structure.
uninterpreted function
    A Z3 ``(declare-fun f (...) r)`` declaration that is axiom-free
    and therefore universally satisfiable.
refinement witness
    A function ``w : AbstractSort -> ConcreteSort`` asserting that every
    abstract value maps to some concrete representative.
behavioral equivalence
    Two interface abstractions are behaviorally equivalent iff they satisfy
    the same set of Z3 axioms.
"""

