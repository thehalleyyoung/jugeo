def create_empty_obligations(
    sort: str = _DEFAULT_SORT,
    metadata: dict[str, Any] | None = None,
) -> AliasingObligation:
    """Create and return a fresh, empty :class:`AliasingObligation`.

    Args
    ----
    sort:
        The SMT sort name for pointer constants.  Defaults to ``"Ptr"``.
    metadata:
        Optional initial metadata dict.

    Returns
    -------
    AliasingObligation
        A newly constructed, empty obligation set.

    Example
    -------
    >>> obl = create_empty_obligations()
    >>> len(obl.must_alias_pairs)
    0
    """
    obl = AliasingObligation(pointer_sort=sort)
    if metadata:
        obl.metadata.update(metadata)
    _log.debug("create_empty_obligations: created %r.", obl.obligation_id)
    return obl


def obligations_from_pointer_list(
    pointers: list[str],
    sort: str = _DEFAULT_SORT,
    *,
    all_disjoint: bool = False,
) -> AliasingObligation:
    """Create an :class:`AliasingObligation` from a flat list of pointer names.

    Registers each pointer as an unknown-type pointer in the obligation's
    registry.  If *all_disjoint* is ``True``, every pair of pointers is
    added as a disjointness obligation.

    Args
    ----
    pointers:
        List of pointer names to register.
    sort:
        SMT sort name.  Defaults to ``"Ptr"``.
    all_disjoint:
        If ``True``, emit disjointness obligations for every pair.
        Defaults to ``False``.

    Returns
    -------
    AliasingObligation
        The populated obligation.

    Raises
    ------
    ValueError
        If *pointers* is empty.

    Example
    -------
    >>> obl = obligations_from_pointer_list(["p", "q", "r"], all_disjoint=True)
    >>> len(obl.disjointness_pairs)
    3
    """
    if not pointers:
        raise ValueError("obligations_from_pointer_list: pointer list must not be empty.")
    obl = AliasingObligation(pointer_sort=sort)
    for name in pointers:
        info = PointerInfo(
            name=name,
            pointer_type=_UNKNOWN_POINTER_TYPE,
            is_null_possible=True,
            is_stack=False,
            alias_class_hint=None,
        )
        obl.pointer_registry[name] = info
    if all_disjoint:
        for i in range(len(pointers)):
            for j in range(i + 1, len(pointers)):
                obl.add_disjointness(pointers[i], pointers[j])
    _log.debug(
        "obligations_from_pointer_list: created %r with %d pointers, all_disjoint=%s.",
        obl.obligation_id,
        len(pointers),
        all_disjoint,
    )
    return obl


def fingerprint_obligations(obl: AliasingObligation) -> str:
    """Compute a stable SHA-256 fingerprint of an :class:`AliasingObligation`.

    The fingerprint is based on the sorted string representations of all
    must-alias pairs, disjointness pairs, and the pointer sort.  It is
    stable across process restarts.

    Args
    ----
    obl:
        The obligation to fingerprint.

    Returns
    -------
    str
        A 16-character hex string (first 64 bits of SHA-256).

    Example
    -------
    >>> fp = fingerprint_obligations(obl)
    >>> len(fp)
    16
    """
    parts = [obl.pointer_sort]
    for p1, p2 in sorted(obl.must_alias_pairs):
        parts.append(f"=('{p1}','{p2}')")
    for p1, p2 in sorted(obl.disjointness_pairs):
        parts.append(f"!=('{p1}','{p2}')")
    raw = "|".join(parts).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:16]


def describe_obligations(obl: AliasingObligation) -> str:
    """Return a multi-line human-readable description of an obligation.

    Args
    ----
    obl:
        The obligation to describe.

    Returns
    -------
    str
        A formatted description suitable for log output or error messages.

    Example
    -------
    >>> print(describe_obligations(obl))
    """
    lines = [
        f"AliasingObligation {obl.obligation_id!r}",
        f"  Pointer sort : {obl.pointer_sort}",
        f"  Created at   : {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(obl.created_at))}",
        f"  Must-alias   : {len(obl.must_alias_pairs)} pairs",
        f"  Disjoint     : {len(obl.disjointness_pairs)} pairs",
        f"  Classes      : {len(obl.partition_classes)}",
        f"  Registered   : {len(obl.pointer_registry)} pointers",
        f"  Predicate    : {obl.to_separation_predicate()}",
    ]
    if obl.pointer_registry:
        lines.append("  Pointer registry:")
        for info in sorted(obl.pointer_registry.values(), key=lambda i: i.name):
            lines.append(f"    {info.summary()}")
    if obl.metadata:
        lines.append(f"  Metadata     : {obl.metadata!r}")
    return "\n".join(lines)
