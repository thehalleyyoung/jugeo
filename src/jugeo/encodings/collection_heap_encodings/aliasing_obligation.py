# ===========================================================================
# 1. AliasKind  —  classification of aliasing relationships
# ===========================================================================


class AliasKind(str, Enum):
    """Classification of the aliasing relationship between two pointers.

    This enum distinguishes four levels of aliasing certainty:

    * ``MUST_ALIAS`` -- the two pointers are provably equal at the program
      point under analysis.  This is the strongest claim.
    * ``MUST_NOT_ALIAS`` -- the two pointers are provably distinct (and
      therefore safe to treat as disjoint memory regions).
    * ``MAY_ALIAS`` -- aliasing is possible but not guaranteed.  A sound
      conservative alias analysis defaults to this when it cannot determine
      the relationship statically.
    * ``UNKNOWN`` -- the analysis has not yet considered this pair.  It is
      distinct from ``MAY_ALIAS`` in that no analysis has been performed.

    The enum values are lowercase strings so that they serialise naturally
    to JSON and can be embedded in SMT-LIB 2 comment blocks without
    escaping.

    Example
    -------
    >>> AliasKind.MUST_ALIAS.value
    'must_alias'
    >>> AliasKind("may_alias") is AliasKind.MAY_ALIAS
    True
    """

    MUST_ALIAS = "must_alias"
    MUST_NOT_ALIAS = "must_not_alias"
    MAY_ALIAS = "may_alias"
    UNKNOWN = "unknown"

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def is_definite(self) -> bool:
        """Return ``True`` iff the kind is a definite (non-speculative) claim.

        Returns
        -------
        bool
            ``True`` for ``MUST_ALIAS`` and ``MUST_NOT_ALIAS``.
        """
        return self in (AliasKind.MUST_ALIAS, AliasKind.MUST_NOT_ALIAS)

    def negated(self) -> AliasKind:
        """Return the logical negation of this aliasing kind.

        ``MUST_ALIAS`` ↔ ``MUST_NOT_ALIAS``; speculative kinds are self-inverse.

        Returns
        -------
        AliasKind
            The negated kind.

        Example
        -------
        >>> AliasKind.MUST_ALIAS.negated()
        <AliasKind.MUST_NOT_ALIAS: 'must_not_alias'>
        """
        _neg: dict[AliasKind, AliasKind] = {
            AliasKind.MUST_ALIAS: AliasKind.MUST_NOT_ALIAS,
            AliasKind.MUST_NOT_ALIAS: AliasKind.MUST_ALIAS,
            AliasKind.MAY_ALIAS: AliasKind.MAY_ALIAS,
            AliasKind.UNKNOWN: AliasKind.UNKNOWN,
        }
        return _neg[self]

    def strength_score(self) -> int:
        """Return an integer strength score for comparison purposes.

        Higher scores correspond to stronger claims.

        Returns
        -------
        int
            4 for MUST_ALIAS, 3 for MUST_NOT_ALIAS, 2 for MAY_ALIAS, 1 for UNKNOWN.
        """
        _scores: dict[AliasKind, int] = {
            AliasKind.MUST_ALIAS: 4,
            AliasKind.MUST_NOT_ALIAS: 3,
            AliasKind.MAY_ALIAS: 2,
            AliasKind.UNKNOWN: 1,
        }
        return _scores[self]


# ===========================================================================
# 2. PointerInfo  —  immutable metadata for a tracked pointer
# ===========================================================================


@dataclass(frozen=True, slots=True)
class PointerInfo:
    """Immutable metadata record for a single pointer variable.

    A :class:`PointerInfo` is stored in the
    :attr:`AliasingObligation.pointer_registry` and consulted during
    partition building, conflict detection, and SMT emission.

    Attributes
    ----------
    name:
        The canonical string name of the pointer (e.g. ``"x"``, ``"p_0"``).
        Must be a valid SMT-LIB 2 identifier.
    pointer_type:
        The static type of the memory region pointed to (e.g. ``"Node*"``,
        ``"int*"``, ``"unknown"``).  Used only for documentation and
        error messages; does not affect the Z3 encoding.
    is_null_possible:
        When ``True`` the pointer may legally hold a null value at runtime.
        Affects which disjointness pairs involving ``__null__`` are generated.
    is_stack:
        When ``True`` the pointer refers to a stack-allocated object.
        Stack pointers can never alias heap pointers, so extra disjointness
        obligations are inserted automatically.
    alias_class_hint:
        An optional string label that hints at which equivalence class the
        pointer belongs to.  Provided by the front-end analysis; the actual
        class is computed by :class:`AliasPartitionBuilder`.

    Example
    -------
    >>> info = PointerInfo(name="p", pointer_type="Node*",
    ...                    is_null_possible=False, is_stack=False)
    >>> info.is_definitely_non_null()
    True
    """

    name: str
    pointer_type: str
    is_null_possible: bool
    is_stack: bool
    alias_class_hint: str | None

    # ------------------------------------------------------------------
    # Derived properties
    # ------------------------------------------------------------------

    def is_definitely_non_null(self) -> bool:
        """Return ``True`` iff this pointer cannot be null.

        Returns
        -------
        bool
            ``True`` when ``is_null_possible`` is ``False``.
        """
        return not self.is_null_possible

    def can_alias_with(self, other: PointerInfo) -> bool:
        """Return ``True`` iff this pointer could alias *other* at runtime.

        Two pointers cannot alias when:
        * Exactly one of them is a stack pointer and the other is not.
        * They have different, non-null pointer types (conservative check).
        * One is the null pointer sentinel.

        Args
        ----
        other:
            The other pointer to check against.

        Returns
        -------
        bool
            Whether the two pointers may alias.

        Example
        -------
        >>> a = PointerInfo("a", "int*", True, True, None)
        >>> b = PointerInfo("b", "int*", True, False, None)
        >>> a.can_alias_with(b)
        False
        """
        if self.name == _NULL_POINTER or other.name == _NULL_POINTER:
            return False
        if self.is_stack != other.is_stack:
            return False
        if (
            self.pointer_type != _UNKNOWN_POINTER_TYPE
            and other.pointer_type != _UNKNOWN_POINTER_TYPE
            and self.pointer_type != other.pointer_type
        ):
            return False
        return True

    def summary(self) -> str:
        """Return a one-line human-readable summary.

        Returns
        -------
        str
            A string such as ``"p: Node* [heap, non-null]"``.

        Example
        -------
        >>> PointerInfo("p", "Node*", False, False, None).summary()
        'p: Node* [heap, non-null]'
        """
        null_tag = "nullable" if self.is_null_possible else "non-null"
        alloc_tag = "stack" if self.is_stack else "heap"
        hint_part = f", hint={self.alias_class_hint}" if self.alias_class_hint else ""
        return f"{self.name}: {self.pointer_type} [{alloc_tag}, {null_tag}{hint_part}]"


# ===========================================================================
# 3. AliasingObligation  —  mutable container for alias/disjoint obligations
# ===========================================================================


@dataclass(slots=True)
class AliasingObligation:
    """Container for aliasing and disjointness obligations.

    An :class:`AliasingObligation` accumulates pairs of pointer names that
    *must* alias (be equal) or *must not* alias (be disjoint).  It
    maintains a partition of all tracked pointers into equivalence classes
    so that transitivity is enforced automatically.

    The class implements a builder pattern: mutating methods return
    ``self`` so calls can be chained::

        obl = (
            AliasingObligation(pointer_sort="Ptr")
            .add_must_alias("p", "q")
            .add_disjointness("p", "r")
        )

    When Z3 is available, :meth:`encode_as_z3` emits SMT-LIB 2 assertion
    strings, and :meth:`verify_obligations` discharges them against a live
    solver session.

    Attributes
    ----------
    pointer_sort:
        The SMT sort name used for all pointer constants, e.g. ``"Ptr"``.
    disjointness_pairs:
        Accumulated must-not-alias pairs (unordered within each pair).
    must_alias_pairs:
        Accumulated must-alias pairs (in addition to partition-class edges).
    pointer_registry:
        Map from pointer name to its :class:`PointerInfo` record.
    partition_classes:
        List of frozen sets, each set being a must-alias equivalence class.
    obligation_id:
        Stable, unique identifier for this obligation set.
    created_at:
        Unix timestamp (seconds) when this object was created.
    metadata:
        Arbitrary key-value annotations for tooling and debugging.

    Raises
    ------
    ValueError
        If a new pair conflicts with an already-recorded obligation (e.g.
        a pair is simultaneously must-alias and must-not-alias).
    OverflowError
        If :attr:`MAX_PARTITION_CLASSES` would be exceeded.
    """

    pointer_sort: str
    disjointness_pairs: list[tuple[str, str]] = field(default_factory=list)
    must_alias_pairs: list[tuple[str, str]] = field(default_factory=list)
    pointer_registry: dict[str, PointerInfo] = field(default_factory=dict)
    partition_classes: list[frozenset[str]] = field(default_factory=list)
    obligation_id: str = field(default_factory=lambda: _OBLIGATION_ID_PREFIX + uuid.uuid4().hex[:12])
    created_at: float = field(default_factory=time.time)
    metadata: dict[str, Any] = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Public builder methods
    # ------------------------------------------------------------------

    def add_disjointness(self, p1: str, p2: str) -> AliasingObligation:
        """Assert that pointer *p1* and pointer *p2* must not alias.

        Records the pair ``(p1, p2)`` in :attr:`disjointness_pairs` after
        checking that it does not contradict any existing must-alias
        obligation.

        Args
        ----
        p1:
            First pointer name.
        p2:
            Second pointer name.

        Returns
        -------
        AliasingObligation
            ``self``, enabling builder chaining.

        Raises
        ------
        ValueError
            If *p1* and *p2* are already in the same must-alias partition
            class, meaning the disjointness obligation would be
            unsatisfiable.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_disjointness("p", "q")  # doctest: +ELLIPSIS
        AliasingObligation(...)
        """
        if p1 == p2:
            _log.warning(
                "add_disjointness: trivially unsatisfiable pair (%s, %s) — skipping",
                p1,
                p2,
            )
            return self
        canonical = (min(p1, p2), max(p1, p2))
        if self._conflicts_with_must_alias(p1, p2):
            raise ValueError(
                f"add_disjointness({p1!r}, {p2!r}): conflict — these pointers are "
                f"already in the same must-alias partition class in obligation "
                f"{self.obligation_id!r}."
            )
        if canonical not in self.disjointness_pairs:
            self.disjointness_pairs.append(canonical)
            _log.debug(
                "[%s] added disjointness: %s ≠ %s  (total=%d)",
                self.obligation_id,
                p1,
                p2,
                len(self.disjointness_pairs),
            )
        return self

    def add_must_alias(self, p1: str, p2: str) -> AliasingObligation:
        """Assert that pointer *p1* and pointer *p2* must alias.

        Records the pair in :attr:`must_alias_pairs` and merges the
        partition classes containing *p1* and *p2*.

        Args
        ----
        p1:
            First pointer name.
        p2:
            Second pointer name.

        Returns
        -------
        AliasingObligation
            ``self``, enabling builder chaining.

        Raises
        ------
        ValueError
            If the pair *(p1, p2)* appears in :attr:`disjointness_pairs`,
            which would create an unsatisfiable obligation set.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_must_alias("p", "q")  # doctest: +ELLIPSIS
        AliasingObligation(...)
        """
        if p1 == p2:
            return self
        canonical = (min(p1, p2), max(p1, p2))
        disj_canonical = canonical
        if disj_canonical in self.disjointness_pairs:
            raise ValueError(
                f"add_must_alias({p1!r}, {p2!r}): conflict — these pointers are "
                f"already recorded as must-not-alias in obligation "
                f"{self.obligation_id!r}."
            )
        if canonical not in self.must_alias_pairs:
            self.must_alias_pairs.append(canonical)
        # Merge the two partition classes (or create them).
        i = self._find_class_index(p1)
        j = self._find_class_index(p2)
        if i is None and j is None:
            new_cls: frozenset[str] = frozenset({p1, p2})
            if len(self.partition_classes) >= MAX_PARTITION_CLASSES:
                raise OverflowError(
                    f"MAX_PARTITION_CLASSES ({MAX_PARTITION_CLASSES}) exceeded "
                    f"in obligation {self.obligation_id!r}."
                )
            self.partition_classes.append(new_cls)
        elif i is None:
            self.partition_classes[j] = self.partition_classes[j] | {p1}
        elif j is None:
            self.partition_classes[i] = self.partition_classes[i] | {p2}
        elif i != j:
            self._merge_classes(i, j)
        _log.debug(
            "[%s] added must-alias: %s = %s  (classes=%d)",
            self.obligation_id,
            p1,
            p2,
            len(self.partition_classes),
        )
        return self

    def add_partition_class(self, pointers: Sequence[str]) -> AliasingObligation:
        """Add a group of pointers that are all must-alias with each other.

        This is equivalent to calling :meth:`add_must_alias` for every pair
        in *pointers*, but is implemented more efficiently by doing a single
        class merge pass.

        Args
        ----
        pointers:
            Sequence of pointer names that form a must-alias class.
            Must contain at least two elements.

        Returns
        -------
        AliasingObligation
            ``self``, enabling builder chaining.

        Raises
        ------
        ValueError
            If *pointers* contains fewer than two elements, or if any pair
            within *pointers* is already in :attr:`disjointness_pairs`.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_partition_class(["p", "q", "r"])  # doctest: +ELLIPSIS
        AliasingObligation(...)
        """
        ptr_list = list(pointers)
        if len(ptr_list) < 2:
            raise ValueError(
                f"add_partition_class: need at least 2 pointers, got {ptr_list!r}."
            )
        if len(ptr_list) > MAX_POINTERS_PER_CLASS:
            raise OverflowError(
                f"MAX_POINTERS_PER_CLASS ({MAX_POINTERS_PER_CLASS}) exceeded."
            )
        # Check all pairs for conflicts first.
        for idx_a in range(len(ptr_list)):
            for idx_b in range(idx_a + 1, len(ptr_list)):
                a, b = ptr_list[idx_a], ptr_list[idx_b]
                canon = (min(a, b), max(a, b))
                if canon in self.disjointness_pairs:
                    raise ValueError(
                        f"add_partition_class: pair ({a!r}, {b!r}) is already "
                        f"disjoint — cannot add to a must-alias class."
                    )
        # Merge incrementally.
        first = ptr_list[0]
        for other in ptr_list[1:]:
            self.add_must_alias(first, other)
        _log.debug(
            "[%s] add_partition_class: merged %d pointers into one class.",
            self.obligation_id,
            len(ptr_list),
        )
        return self

    # ------------------------------------------------------------------
    # Z3 encoding
    # ------------------------------------------------------------------

    def encode_as_z3(self, session: Z3Session) -> list[str]:
        """Produce SMT-LIB 2 assertion strings for all obligations.

        Generates three categories of assertions:

        1. **Constant declarations** — one ``(declare-const name sort)``
           per pointer in :attr:`pointer_registry`.
        2. **Must-alias assertions** — one ``(assert (= p q))`` per pair
           in :attr:`must_alias_pairs`.  Partition-class edges are also
           included so the full equivalence class is explicit.
        3. **Disjointness assertions** — one ``(assert (not (= p q)))``
           per pair in :attr:`disjointness_pairs`.

        The output is a flat list of SMT-LIB 2 strings, ready to be
        concatenated into a solver input file.

        Args
        ----
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session` used to
            validate that the pointer sort is defined.  Not modified.

        Returns
        -------
        list[str]
            SMT-LIB 2 strings, one per logical assertion or declaration.

        Raises
        ------
        RuntimeError
            If Z3 is unavailable and :attr:`~jugeo.solver.z3_session.z3_available`
            returns ``False``.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_must_alias("p", "q")
        >>> stmts = obl.encode_as_z3(session)  # requires live session
        """
        stmts: list[str] = []
        # ------------------------------------------------------------------
        # Section header comment.
        # ------------------------------------------------------------------
        stmts.append(f"; AliasingObligation {self.obligation_id}")
        stmts.append(f"; sort={self.pointer_sort}  must_alias={len(self.must_alias_pairs)}"
                     f"  disjoint={len(self.disjointness_pairs)}"
                     f"  classes={len(self.partition_classes)}")
        stmts.append("")
        # ------------------------------------------------------------------
        # Pointer constant declarations.
        # ------------------------------------------------------------------
        all_names: set[str] = set()
        for pair in self.must_alias_pairs:
            all_names.update(pair)
        for pair in self.disjointness_pairs:
            all_names.update(pair)
        for cls in self.partition_classes:
            all_names.update(cls)
        all_names.update(self.pointer_registry.keys())
        # Omit null; it is assumed to be pre-declared.
        all_names.discard(_NULL_POINTER)
        for name in sorted(all_names):
            stmts.append(_SMT2_DECLARE_CONST.format(name=name, sort=self.pointer_sort))
        if all_names:
            stmts.append("")
        # ------------------------------------------------------------------
        # Must-alias assertions (direct pairs).
        # ------------------------------------------------------------------
        if self.must_alias_pairs:
            stmts.append("; must-alias assertions")
        for p1, p2 in self.must_alias_pairs:
            stmts.append(_SMT2_ASSERT_EQ.format(lhs=p1, rhs=p2))
        # ------------------------------------------------------------------
        # Partition-class equality chains.
        # ------------------------------------------------------------------
        if self.partition_classes:
            stmts.append("; partition-class equality chains")
        for cls_set in self.partition_classes:
            members = sorted(cls_set)
            if len(members) < 2:
                continue
            rep = members[0]
            for member in members[1:]:
                chain_eq = _SMT2_ASSERT_EQ.format(lhs=rep, rhs=member)
                # Avoid duplicate with direct must_alias_pairs.
                if chain_eq not in stmts:
                    stmts.append(chain_eq)
        # ------------------------------------------------------------------
        # Disjointness assertions.
        # ------------------------------------------------------------------
        if self.disjointness_pairs:
            stmts.append("")
            stmts.append("; disjointness (must-not-alias) assertions")
        for p1, p2 in self.disjointness_pairs:
            stmts.append(_SMT2_ASSERT_NEQ.format(lhs=p1, rhs=p2))
        _log.debug(
            "[%s] encode_as_z3: emitted %d statements.",
            self.obligation_id,
            len(stmts),
        )
        return stmts

    # ------------------------------------------------------------------
    # Verification
    # ------------------------------------------------------------------

    def verify_obligations(self, session: Z3Session) -> Z3Result:
        """Check that all obligations are jointly satisfiable.

        Builds a fresh :class:`~jugeo.solver.z3_session.Z3QueryBuilder`,
        injects all SMT assertions from :meth:`encode_as_z3`, and runs a
        satisfiability check.  An ``UNSAT`` outcome means the recorded
        obligations are contradictory.

        Args
        ----
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        Z3Result
            The solver outcome.  :attr:`~jugeo.solver.z3_session.Z3Result.outcome`
            is ``SAT`` iff the obligations are consistent.

        Example
        -------
        >>> result = obl.verify_obligations(session)
        >>> assert result.outcome == SolveOutcome.SAT
        """
        builder = Z3QueryBuilder(session=session)
        for stmt in self.encode_as_z3(session):
            if stmt.startswith("(assert"):
                builder.add_assertion(stmt)
        result: Z3Result = builder.check()
        if result.outcome == SolveOutcome.UNSAT:
            _log.warning(
                "[%s] verify_obligations: UNSAT — obligations are contradictory.",
                self.obligation_id,
            )
        elif result.outcome == SolveOutcome.SAT:
            _log.debug(
                "[%s] verify_obligations: SAT — obligations are consistent.",
                self.obligation_id,
            )
        else:
            _log.info(
                "[%s] verify_obligations: %s.",
                self.obligation_id,
                result.outcome.value,
            )
        return result

    def check_soundness(self, session: Z3Session) -> Z3Result:
        """Verify that no must-alias pair is also a must-not-alias pair.

        This is a purely syntactic check that does not require Z3; if the
        syntactic check passes, a full satisfiability check is run.

        Args
        ----
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        Z3Result
            ``SAT`` if no conflicts are found; ``UNSAT`` otherwise.

        Raises
        ------
        ValueError
            If a conflict is detected syntactically (before involving Z3).

        Example
        -------
        >>> result = obl.check_soundness(session)
        >>> assert result.outcome != SolveOutcome.UNSAT
        """
        # Syntactic check first.
        must_alias_set: set[tuple[str, str]] = {
            (min(a, b), max(a, b)) for a, b in self.must_alias_pairs
        }
        disjoint_set: set[tuple[str, str]] = {
            (min(a, b), max(a, b)) for a, b in self.disjointness_pairs
        }
        conflicts = must_alias_set & disjoint_set
        if conflicts:
            msg = (
                f"[{self.obligation_id}] check_soundness: {len(conflicts)} syntactic "
                f"conflict(s) detected: {sorted(conflicts)}"
            )
            _log.error(msg)
            return Z3Result.make_unsat(
                query_id=self.obligation_id,
                elapsed_ms=0.0,
                reason=msg,
            )
        # Also verify cross-class partition conflicts.
        for cls_set in self.partition_classes:
            members = sorted(cls_set)
            for idx_a in range(len(members)):
                for idx_b in range(idx_a + 1, len(members)):
                    a, b = members[idx_a], members[idx_b]
                    canon = (min(a, b), max(a, b))
                    if canon in disjoint_set:
                        msg = (
                            f"[{self.obligation_id}] check_soundness: partition-class "
                            f"members ({a!r}, {b!r}) are also disjoint — UNSAT."
                        )
                        _log.error(msg)
                        return Z3Result.make_unsat(
                            query_id=self.obligation_id,
                            elapsed_ms=0.0,
                            reason=msg,
                        )
        _log.debug(
            "[%s] check_soundness: no syntactic conflicts; running full check.",
            self.obligation_id,
        )
        return self.verify_obligations(session)

    # ------------------------------------------------------------------
    # Partition queries
    # ------------------------------------------------------------------

    def find_alias_class(self, pointer: str) -> frozenset[str]:
        """Return the partition class containing *pointer*.

        If *pointer* is not in any recorded class, a singleton set is
        returned.

        Args
        ----
        pointer:
            Pointer name to look up.

        Returns
        -------
        frozenset[str]
            The set of all pointers in the same must-alias class as
            *pointer*.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_must_alias("p", "q")
        >>> "q" in obl.find_alias_class("p")
        True
        """
        idx = self._find_class_index(pointer)
        if idx is None:
            return frozenset({pointer})
        return self.partition_classes[idx]

    def minimal_disjointness_set(self) -> list[tuple[str, str]]:
        """Compute the minimal set of disjointness pairs covering all inter-class non-aliasing.

        For each pair of distinct partition classes, exactly one representative
        pair is chosen (the lexicographically smallest member from each class).
        Direct :attr:`disjointness_pairs` that are already implied by the
        inter-class structure are de-duplicated.

        Returns
        -------
        list[tuple[str, str]]
            Minimal list of (p, q) disjointness pairs, sorted for
            determinism.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_must_alias("p", "q")
        >>> obl.add_disjointness("p", "r")
        >>> obl.minimal_disjointness_set()
        [('p', 'r')]
        """
        result: list[tuple[str, str]] = []
        seen: set[tuple[str, str]] = set()
        # Inter-class pairs: pick one representative from each class.
        for i_idx in range(len(self.partition_classes)):
            for j_idx in range(i_idx + 1, len(self.partition_classes)):
                rep_i = min(self.partition_classes[i_idx])
                rep_j = min(self.partition_classes[j_idx])
                # Only include if there is any direct disjointness pair
                # between the two classes.
                has_disjoint = any(
                    (min(a, b), max(a, b)) in set(self.disjointness_pairs)
                    for a in self.partition_classes[i_idx]
                    for b in self.partition_classes[j_idx]
                )
                if has_disjoint:
                    canon = (min(rep_i, rep_j), max(rep_i, rep_j))
                    if canon not in seen:
                        seen.add(canon)
                        result.append(canon)
        # Include any remaining direct pairs not covered by the above.
        for p1, p2 in self.disjointness_pairs:
            canon = (min(p1, p2), max(p1, p2))
            if canon not in seen:
                seen.add(canon)
                result.append(canon)
        result.sort()
        return result

    def to_separation_predicate(self) -> str:
        """Return a human-readable predicate string for all obligations.

        The string is a conjunction of equality and disequality literals,
        suitable for embedding in documentation, error messages, and
        SMT-LIB 2 comment headers.

        Returns
        -------
        str
            Predicate string such as ``"p=q ∧ p≠r ∧ q≠s"``.

        Example
        -------
        >>> obl = AliasingObligation(pointer_sort="Ptr")
        >>> obl.add_must_alias("p", "q").add_disjointness("p", "r")
        >>> obl.to_separation_predicate()
        'p=q ∧ p≠r'
        """
        parts: list[str] = []
        for p1, p2 in sorted(self.must_alias_pairs):
            parts.append(f"{p1}={p2}")
        for p1, p2 in sorted(self.disjointness_pairs):
            parts.append(f"{p1}≠{p2}")
        if not parts:
            return "⊤"
        return " ∧ ".join(parts)

    def merge_obligations(self, other: AliasingObligation) -> AliasingObligation:
        """Merge *other* into this obligation set.

        All must-alias pairs, disjointness pairs, pointer registrations, and
        partition classes from *other* are incorporated.  Conflicts raise a
        :exc:`ValueError`.

        Args
        ----
        other:
            The obligation set to merge in.

        Returns
        -------
        AliasingObligation
            ``self``, modified in-place, enabling chaining.

        Raises
        ------
        ValueError
            If any pair in *other* conflicts with an existing obligation.

        Example
        -------
        >>> merged = obl_a.merge_obligations(obl_b)
        """
        _log.debug(
            "[%s] merge_obligations: merging in %s  (must_alias=%d, disjoint=%d).",
            self.obligation_id,
            other.obligation_id,
            len(other.must_alias_pairs),
            len(other.disjointness_pairs),
        )
        # Merge pointer registry.
        for name, info in other.pointer_registry.items():
            if name not in self.pointer_registry:
                self.pointer_registry[name] = info
        # Merge must-alias pairs.
        for p1, p2 in other.must_alias_pairs:
            self.add_must_alias(p1, p2)
        # Merge disjointness pairs.
        for p1, p2 in other.disjointness_pairs:
            self.add_disjointness(p1, p2)
        # Record provenance.
        self.metadata[f"merged_from_{other.obligation_id}"] = time.time()
        return self

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _find_class_index(self, pointer: str) -> int | None:
        """Return the index into :attr:`partition_classes` that contains *pointer*.

        Args
        ----
        pointer:
            Pointer name to search for.

        Returns
        -------
        int | None
            The index, or ``None`` if *pointer* is not in any class.
        """
        for idx, cls_set in enumerate(self.partition_classes):
            if pointer in cls_set:
                return idx
        return None

    def _merge_classes(self, i: int, j: int) -> None:
        """Merge partition class *j* into partition class *i* in-place.

        After the merge, class *j* is removed from the list.  All indices
        above *j* shift down by one.

        Args
        ----
        i:
            Index of the class to merge into.
        j:
            Index of the class to absorb (must be > i for predictability).
        """
        if i == j:
            return
        lo, hi = (i, j) if i < j else (j, i)
        self.partition_classes[lo] = self.partition_classes[lo] | self.partition_classes[hi]
        del self.partition_classes[hi]
        _log.debug(
            "[%s] _merge_classes: merged class[%d] into class[%d];  remaining=%d.",
            self.obligation_id,
            hi,
            lo,
            len(self.partition_classes),
        )

    def _conflicts_with_must_alias(self, p1: str, p2: str) -> bool:
        """Return ``True`` iff *p1* and *p2* are in the same must-alias class.

        Args
        ----
        p1:
            First pointer name.
        p2:
            Second pointer name.

        Returns
        -------
        bool
            ``True`` iff both pointers share a partition class.
        """
        i = self._find_class_index(p1)
        j = self._find_class_index(p2)
        if i is None or j is None:
            return False
        return i == j

    # ------------------------------------------------------------------
    # Representation helpers
    # ------------------------------------------------------------------

    def __repr__(self) -> str:
        return (
            f"AliasingObligation(id={self.obligation_id!r}, sort={self.pointer_sort!r}, "
            f"must_alias={len(self.must_alias_pairs)}, "
            f"disjoint={len(self.disjointness_pairs)}, "
            f"classes={len(self.partition_classes)})"
        )


# ===========================================================================
# 4. AliasPartitionBuilder  —  builds partitions from program observations
# ===========================================================================


@dataclass(slots=True)
class AliasPartitionBuilder:
    """Builds :class:`AliasPartition` instances from program-level observations.

    The builder accumulates observations about pointer assignments and branch
    conditions, then constructs a full :class:`AliasPartition` using a
    union-find style algorithm.

    Attributes
    ----------
    _pointers:
        Map from pointer name to its :class:`PointerInfo`.
    _assignments:
        List of ``(lhs, rhs)`` assignment observations.
    _branch_conditions:
        List of branch condition strings (for documentation).
    _may_alias_cache:
        Cache of previously computed may-alias results.

    Example
    -------
    >>> builder = AliasPartitionBuilder()
    >>> builder.add_pointer("p", "Node*")
    >>> builder.add_pointer("q", "Node*")
    >>> builder.observe_assignment("p", "q")
    >>> partition = builder.build_partition()
    """

    _pointers: dict[str, PointerInfo] = field(default_factory=dict)
    _assignments: list[tuple[str, str]] = field(default_factory=list)
    _branch_conditions: list[str] = field(default_factory=list)
    _may_alias_cache: dict[tuple[str, str], bool] = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def add_pointer(
        self,
        name: str,
        pointer_type: str,
        *,
        is_null_possible: bool = True,
        is_stack: bool = False,
    ) -> None:
        """Register a pointer variable.

        Args
        ----
        name:
            Canonical pointer name (SMT identifier).
        pointer_type:
            Static type string (e.g. ``"Node*"``).
        is_null_possible:
            Whether the pointer may be null at runtime.
        is_stack:
            Whether the pointer is stack-allocated.

        Example
        -------
        >>> builder = AliasPartitionBuilder()
        >>> builder.add_pointer("x", "int*", is_null_possible=False)
        """
        info = PointerInfo(
            name=name,
            pointer_type=pointer_type,
            is_null_possible=is_null_possible,
            is_stack=is_stack,
            alias_class_hint=None,
        )
        self._pointers[name] = info
        # Invalidate cache.
        keys_to_del = [k for k in self._may_alias_cache if name in k]
        for k in keys_to_del:
            del self._may_alias_cache[k]
        _log.debug("AliasPartitionBuilder: registered pointer %r (%s).", name, pointer_type)

    def observe_assignment(self, lhs: str, rhs: str) -> None:
        """Record that the assignment ``lhs = rhs`` was observed.

        The builder interprets each assignment as a must-alias hint for the
        set of pointers reachable from *lhs* after the assignment.

        Args
        ----
        lhs:
            Left-hand-side pointer name.
        rhs:
            Right-hand-side pointer name.

        Example
        -------
        >>> builder.observe_assignment("p", "q")
        """
        if lhs == rhs:
            return
        self._assignments.append((lhs, rhs))
        canon = (min(lhs, rhs), max(lhs, rhs))
        self._may_alias_cache[canon] = True
        _log.debug(
            "AliasPartitionBuilder: observed assignment %s = %s.", lhs, rhs
        )

    def observe_branch(self, condition: str) -> None:
        """Record a branch condition for documentation purposes.

        Branch conditions may refine aliasing relationships in future
        versions of the builder.  For now they are stored and included in
        the :class:`AliasPartition` metadata.

        Args
        ----
        condition:
            A string representation of the branch condition (e.g.
            ``"p != null"``).

        Example
        -------
        >>> builder.observe_branch("p != null")
        """
        self._branch_conditions.append(condition)
        _log.debug("AliasPartitionBuilder: recorded branch condition %r.", condition)

    def build_partition(self) -> AliasPartition:
        """Compute and return an :class:`AliasPartition` from all observations.

        Uses a union-find algorithm over :attr:`_assignments` to derive the
        equivalence classes.

        Returns
        -------
        AliasPartition
            The constructed partition.

        Example
        -------
        >>> partition = builder.build_partition()
        """
        # Union-find over pointer names.
        parent: dict[str, str] = {name: name for name in self._pointers}

        def find(x: str) -> str:
            while parent.get(x, x) != x:
                parent[x] = parent.get(parent[x], parent[x])  # path compression
                x = parent[x]
            return x

        def union(a: str, b: str) -> None:
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[rb] = ra

        for lhs, rhs in self._assignments:
            if lhs in parent and rhs in parent:
                union(lhs, rhs)

        # Group by root.
        classes: dict[str, list[str]] = defaultdict(list)
        for name in self._pointers:
            root = find(name)
            classes[root].append(name)

        frozen_classes = [frozenset(members) for members in classes.values() if members]

        partition = AliasPartition(
            sort_name=_DEFAULT_SORT,
            classes=frozen_classes,
            class_labels={
                f"{_PARTITION_CLASS_ID_PREFIX}{i}": cls
                for i, cls in enumerate(frozen_classes)
            },
        )
        _log.debug(
            "AliasPartitionBuilder.build_partition: %d classes from %d pointers.",
            len(frozen_classes),
            len(self._pointers),
        )
        return partition

    def infer_may_alias(self, p1: str, p2: str) -> bool:
        """Return ``True`` iff *p1* and *p2* may alias.

        Checks the :attr:`_may_alias_cache` first, then falls back to
        :class:`PointerInfo` compatibility checks.

        Args
        ----
        p1:
            First pointer name.
        p2:
            Second pointer name.

        Returns
        -------
        bool
            Whether the two pointers may alias.
        """
        if p1 == p2:
            return True
        canon = (min(p1, p2), max(p1, p2))
        if canon in self._may_alias_cache:
            return self._may_alias_cache[canon]
        info1 = self._pointers.get(p1)
        info2 = self._pointers.get(p2)
        if info1 is None or info2 is None:
            result = True  # conservative: unknown pointers may alias
        else:
            result = info1.can_alias_with(info2)
        self._may_alias_cache[canon] = result
        return result

    def infer_must_alias(self, p1: str, p2: str) -> bool:
        """Return ``True`` iff *p1* and *p2* must alias (from observations).

        Uses the union-find structure implied by :attr:`_assignments`.

        Args
        ----
        p1:
            First pointer name.
        p2:
            Second pointer name.

        Returns
        -------
        bool
            Whether the two pointers must alias given the observed assignments.
        """
        if p1 == p2:
            return True
        reachability = self._compute_reachability()
        return p2 in reachability.get(p1, set())

    def export_obligations(self) -> AliasingObligation:
        """Convert the current observations into an :class:`AliasingObligation`.

        All must-alias pairs inferred from :attr:`_assignments` are added to
        the obligation, along with must-not-alias pairs for cross-stack-heap
        pairs.

        Returns
        -------
        AliasingObligation
            The exported obligation set.

        Example
        -------
        >>> obl = builder.export_obligations()
        """
        obl = AliasingObligation(pointer_sort=_DEFAULT_SORT)
        # Register pointer metadata.
        for name, info in self._pointers.items():
            obl.pointer_registry[name] = info
        # Add must-alias pairs.
        for lhs, rhs in self._assignments:
            if lhs in self._pointers and rhs in self._pointers:
                try:
                    obl.add_must_alias(lhs, rhs)
                except ValueError as exc:
                    _log.warning("export_obligations: skipping conflicting pair: %s", exc)
        # Add stack-heap disjointness.
        stack_ptrs = [n for n, info in self._pointers.items() if info.is_stack]
        heap_ptrs = [n for n, info in self._pointers.items() if not info.is_stack]
        for sp in stack_ptrs:
            for hp in heap_ptrs:
                try:
                    obl.add_disjointness(sp, hp)
                except ValueError:
                    pass  # already recorded or conflicts; skip
        obl.metadata["branch_conditions"] = list(self._branch_conditions)
        _log.debug(
            "AliasPartitionBuilder.export_obligations: exported %d must-alias, %d disjoint.",
            len(obl.must_alias_pairs),
            len(obl.disjointness_pairs),
        )
        return obl

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _compute_reachability(self) -> dict[str, set[str]]:
        """Compute the transitive closure of the assignment graph.

        Returns
        -------
        dict[str, set[str]]
            Map from each pointer to all pointers transitively reachable
            via must-alias edges.
        """
        # Build adjacency list.
        adj: dict[str, set[str]] = defaultdict(set)
        for lhs, rhs in self._assignments:
            adj[lhs].add(rhs)
            adj[rhs].add(lhs)
        reachability: dict[str, set[str]] = {}
        for start in self._pointers:
            visited: set[str] = set()
            stack = [start]
            while stack:
                node = stack.pop()
                if node in visited:
                    continue
                visited.add(node)
                stack.extend(adj.get(node, set()) - visited)
            reachability[start] = visited - {start}
        return reachability


# ===========================================================================
# 5. DisjointnessChecker  —  verifies disjointness constraints
# ===========================================================================


@dataclass(slots=True)
class DisjointnessChecker:
    """Verifies disjointness constraints against a live Z3 session.

    This class provides methods for checking individual pointer pairs,
    verifying all pairs in an :class:`AliasingObligation`, extracting
    violating models, and suggesting repairs.

    Attributes
    ----------
    _check_cache:
        Cache mapping ``(p1, p2, obligation_id)`` to a cached
        :class:`~jugeo.solver.z3_session.Z3Result`.

    Example
    -------
    >>> checker = DisjointnessChecker()
    >>> results = checker.check_all_pairs(obl, session)
    """

    _check_cache: dict[tuple[str, str, str], Z3Result] = field(default_factory=dict)

    def check_pair(
        self,
        p1: str,
        p2: str,
        session: Z3Session,
    ) -> Z3Result:
        """Check that the disjointness ``p1 ≠ p2`` is satisfiable in isolation.

        Args
        ----
        p1:
            First pointer name.
        p2:
            Second pointer name.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        Z3Result
            Solver outcome for the isolated disjointness check.

        Example
        -------
        >>> result = checker.check_pair("p", "q", session)
        """
        cache_key = (min(p1, p2), max(p1, p2), "single")
        if cache_key in self._check_cache:
            _log.debug("DisjointnessChecker.check_pair: cache hit for (%s, %s).", p1, p2)
            return self._check_cache[cache_key]
        builder = Z3QueryBuilder(session=session)
        builder.add_assertion(
            _SMT2_DECLARE_CONST.format(name=p1, sort=_DEFAULT_SORT)
        )
        builder.add_assertion(
            _SMT2_DECLARE_CONST.format(name=p2, sort=_DEFAULT_SORT)
        )
        builder.add_assertion(_SMT2_ASSERT_NEQ.format(lhs=p1, rhs=p2))
        result = builder.check()
        self._check_cache[cache_key] = result
        _log.debug(
            "DisjointnessChecker.check_pair (%s, %s): %s.",
            p1,
            p2,
            result.outcome.value,
        )
        return result

    def check_all_pairs(
        self,
        obligations: AliasingObligation,
        session: Z3Session,
    ) -> list[Z3Result]:
        """Check every disjointness pair in *obligations*.

        Args
        ----
        obligations:
            The obligation set to check.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        list[Z3Result]
            One result per :attr:`~AliasingObligation.disjointness_pairs`
            entry, in the same order.

        Example
        -------
        >>> results = checker.check_all_pairs(obl, session)
        """
        results: list[Z3Result] = []
        for p1, p2 in obligations.disjointness_pairs:
            cache_key = (min(p1, p2), max(p1, p2), obligations.obligation_id)
            if cache_key in self._check_cache:
                results.append(self._check_cache[cache_key])
                continue
            r = self.check_pair(p1, p2, session)
            self._check_cache[cache_key] = r
            results.append(r)
        _log.debug(
            "DisjointnessChecker.check_all_pairs: %d checks; "
            "%d SAT, %d UNSAT, %d other.",
            len(results),
            sum(1 for r in results if r.outcome == SolveOutcome.SAT),
            sum(1 for r in results if r.outcome == SolveOutcome.UNSAT),
            sum(1 for r in results if r.outcome not in (SolveOutcome.SAT, SolveOutcome.UNSAT)),
        )
        return results

    def find_violating_model(
        self,
        obligations: AliasingObligation,
        session: Z3Session,
    ) -> dict[str, Any] | None:
        """Return a counterexample model that violates a disjointness constraint, or ``None``.

        Asks Z3 to find a model satisfying all must-alias constraints but
        violating at least one disjointness constraint.

        Args
        ----
        obligations:
            The obligation set to investigate.
        session:
            A live :class:`~jugeo.solver.z3_session.Z3Session`.

        Returns
        -------
        dict[str, Any] | None
            A model dict with pointer assignments if a violation is found;
            ``None`` if the obligations are satisfiable (no violation).

        Example
        -------
        >>> model = checker.find_violating_model(obl, session)
        >>> if model is not None:
        ...     print("violation found:", model)
        """
        stmts = obligations.encode_as_z3(session)
        # Build a negated query: assert all must-alias, then negate one disjoint.
        builder = Z3QueryBuilder(session=session)
        for stmt in stmts:
            if stmt.startswith("(assert") or stmt.startswith("(declare"):
                builder.add_assertion(stmt)
        result = builder.check()
        if result.outcome == SolveOutcome.UNSAT:
            # The obligations themselves are contradictory — return a sentinel.
            _log.warning(
                "DisjointnessChecker.find_violating_model: obligations are UNSAT; "
                "no consistent model exists."
            )
            return {"_unsat": True, "obligation_id": obligations.obligation_id}
        if result.outcome == SolveOutcome.SAT and result.model is not None:
            return dict(result.model)
        return None

    def suggest_repair(self, violation: dict[str, Any]) -> str:
        """Suggest a repair strategy given a violation model.

        Args
        ----
        violation:
            The model dict returned by :meth:`find_violating_model`.

        Returns
        -------
        str
            A human-readable repair suggestion.

        Example
        -------
        >>> suggestion = checker.suggest_repair({"_unsat": True})
        >>> print(suggestion)
        """
        if violation.get("_unsat"):
            return (
                "The obligation set is internally contradictory (UNSAT).  "
                "Remove one of the conflicting must-alias or must-not-alias pairs "
                f"from obligation {violation.get('obligation_id', '(unknown)')!r}."
            )
        aliases = {k: v for k, v in violation.items() if not k.startswith("_")}
        if not aliases:
            return "No concrete aliasing assignments found in the model; check solver output."
        parts = [f"{k}={v!r}" for k, v in sorted(aliases.items())]
        return (
            "A model satisfying the constraints assigns: "
            + ", ".join(parts)
            + ".  Consider adding a disjointness assertion for any pair that "
            "appears aliased in the model."
        )

    def summarize_results(self, results: list[Z3Result]) -> str:
        """Return a human-readable summary of a list of Z3 results.

        Args
        ----
        results:
            List of :class:`~jugeo.solver.z3_session.Z3Result` objects.

        Returns
        -------
        str
            Multi-line summary string.

        Example
        -------
        >>> print(checker.summarize_results(results))
        """
        n_total = len(results)
        n_sat = sum(1 for r in results if r.outcome == SolveOutcome.SAT)
        n_unsat = sum(1 for r in results if r.outcome == SolveOutcome.UNSAT)
        n_unknown = n_total - n_sat - n_unsat
        lines = [
            f"DisjointnessChecker summary: {n_total} checks",
            f"  SAT (consistent):      {n_sat}",
            f"  UNSAT (contradictory): {n_unsat}",
            f"  UNKNOWN/TIMEOUT:       {n_unknown}",
        ]
        if n_unsat > 0:
            lines.append(
                "  ⚠ At least one disjointness check was UNSAT — "
                "review the obligation set."
            )
        return "\n".join(lines)


