r"""aliasing_obligation — Disjointness and aliasing constraints as Z3 obligations.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch27: Exact Z3 encodings II: collections, finite maps, heap summaries,
alias partitions, interface abstractions.

Manages aliasing and disjointness obligations as Z3 uninterpreted function
constraints.  Alias partitions group pointers into must-alias classes and
must-not-alias pairs.  The encoding maps partition classes to Z3 equality
constraints and disjointness to inequality assertions.

Part of the JuGeo judgment-geometry framework.

Architecture overview
---------------------
This module is built around two central abstractions:

* :class:`AliasingObligation` -- a mutable container that accumulates
  ``must-alias`` and ``must-not-alias`` pairs, manages the partition of
  pointer names into equivalence classes, and can emit those obligations
  as SMT-LIB 2 assertion strings.

* :class:`AliasPartitionBuilder` -- a higher-level helper that observes
  program-level events (assignments, branch conditions) and infers which
  aliasing obligations should be generated.

Supporting infrastructure:

* :class:`PointerInfo` -- immutable metadata record for a single pointer
  variable tracked in the obligation system.
* :class:`DisjointnessChecker` -- verifies disjointness constraints against
  a live :class:`~jugeo.solver.z3_session.Z3Session`.

Design principles
-----------------
* All state mutation in :class:`AliasingObligation` is gated behind
  consistency checks that detect conflicts early and raise
  :exc:`ValueError` with a descriptive message.
* The builder pattern used by :meth:`AliasingObligation.add_disjointness`
  and :meth:`AliasingObligation.add_must_alias` enables fluent chains such
  as ``obl.add_must_alias("p", "q").add_disjointness("p", "r")``.
* SMT-LIB 2 emission is pure and deterministic: the same obligation set
  always produces the same sequence of assertion strings.

Glossary
--------
alias class
    A maximal set of pointers that must all point to the same memory
    location.  Within a class every pair is a *must-alias* pair.
disjointness pair
    A pair *(p, q)* for which the obligation asserts ``p ≠ q``.
separation predicate
    The conjunction of all aliasing and disjointness obligations expressed
    as a human-readable string.
"""

