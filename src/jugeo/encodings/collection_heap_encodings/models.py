def _fresh_id() -> str:
    """Generate a fresh UUID4 string.

    Returns
    -------
    str
        Lowercase hyphenated UUID4 string.
    """
    return str(uuid.uuid4())


def _timestamp() -> float:
    """Return the current UNIX timestamp.

    Returns
    -------
    float
        ``time.time()`` result.
    """
    return time.time()


def _validate_sort_name(name: str) -> bool:
    """Check that *name* is a valid Z3 sort identifier.

    A valid sort name starts with a letter or underscore and contains only
    letters, digits, and underscores.

    Parameters
    ----------
    name:
        The candidate sort name.

    Returns
    -------
    bool
        ``True`` if the name is valid.
    """
    return bool(_SORT_NAME_RE.match(name))


def _format_smt2_array(name: str, index_sort: str, elem_sort: str) -> str:
    """Format an SMT-LIB2 array declaration.

    Parameters
    ----------
    name:
        Name of the array constant.
    index_sort:
        Sort of the array index.
    elem_sort:
        Sort of the array elements.

    Returns
    -------
    str
        SMT-LIB2 declaration string, e.g.
        ``"(declare-const arr (Array Int Int))"``.
    """
    return _SMT2_ARRAY_TMPL.format(name=name, idx=index_sort, elem=elem_sort)


def _checksum(data: str) -> str:
    """Compute a short SHA-256 hex checksum of *data*.

    Parameters
    ----------
    data:
        Arbitrary string to hash.

    Returns
    -------
    str
        First 16 characters of the SHA-256 hex digest.
    """
    return hashlib.sha256(data.encode()).hexdigest()[:16]


def _smt2_assert(expr: str) -> str:
    """Wrap *expr* in an SMT-LIB2 ``assert`` command.

    Parameters
    ----------
    expr:
        Boolean SMT-LIB2 expression.

    Returns
    -------
    str
        ``"(assert <expr>)"``
    """
    return f"(assert {expr})"


def _smt2_comment(text: str) -> str:
    """Wrap *text* in an SMT-LIB2 line comment.

    Parameters
    ----------
    text:
        Comment text (no leading ``;;`` needed).

    Returns
    -------
    str
        ``;; <text>``
    """
    return f";; {text}"


