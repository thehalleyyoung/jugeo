@dataclass(slots=True)
class FiniteMapEncoding:
    """Z3 partial-function encoding with domain and range axioms.

    A ``FiniteMapEncoding`` models a finite partial map ``f : D ⇀ R`` as a
    Z3 uninterpreted function plus a ``defined`` predicate restricting its
    domain.

    Parameters
    ----------
    domain_sort:
        Z3 sort for the domain.
    range_sort:
        Z3 sort for the range.
    map_fn:
        Name of the Z3 uninterpreted function.
    defined_set:
        List of domain values for which the map is defined.
    undefinedness_axiom:
        SMT-LIB2 axiom expressing that the map is undefined outside ``defined_set``.
    update_axioms:
        SMT-LIB2 axioms capturing functional-update semantics.
    map_id:
        UUID4.
    created_at:
        UNIX timestamp.
    metadata:
        Free-form metadata.
    """

    domain_sort: Z3SortName = "Int"
    range_sort: Z3SortName = "Int"
    map_fn: str = "f"
    defined_set: list[str] = field(default_factory=list)
    undefinedness_axiom: str = ""
    update_axioms: list[str] = field(default_factory=list)
    map_id: str = field(default_factory=_fresh_id)
    created_at: float = field(default_factory=_timestamp)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.undefinedness_axiom:
            self.undefinedness_axiom = self._default_undefinedness_axiom()
        ModelRegistry.instance().register("FiniteMapEncoding", self)
        _log.debug("FiniteMapEncoding created: fn=%r id=%s", self.map_fn, self.map_id[:8])

    def _default_undefinedness_axiom(self) -> str:
        """Generate a default undefinedness axiom.

        The default axiom asserts that the map function returns a
        distinguished ``undefined`` value for inputs outside the
        defined set.

        Returns
        -------
        str
            SMT-LIB2 string.
        """
        return (
            f"(forall ((x {self.domain_sort})) "
            f"(=> (not (defined_{self.map_fn} x)) "
            f"(= ({self.map_fn} x) undefined_{self.range_sort})))"
        )

    # ------------------------------------------------------------------
    # Map operations
    # ------------------------------------------------------------------

    def lookup(self, key: str) -> str | None:
        """Look up *key* in the finite map.

        Parameters
        ----------
        key:
            Domain value to look up.

        Returns
        -------
        str | None
            SMT-LIB2 expression ``"(<map_fn> <key>)"`` if *key* is in
            ``defined_set``, else ``None``.
        """
        if key in self.defined_set:
            result = f"({self.map_fn} {key})"
            _log.debug("lookup: key=%r → %r in map %s", key, result, self.map_id[:8])
            return result
        _log.debug("lookup: key=%r is undefined in map %s", key, self.map_id[:8])
        return None

    def update(self, key: str, value: str) -> "FiniteMapEncoding":
        """Return a new encoding with the functional update ``map[key := value]``.

        Generates a fresh ``update`` axiom of the form::

            (forall ((x Domain))
              (= (f_updated x)
                 (ite (= x key) value (f x))))

        Parameters
        ----------
        key:
            Domain key to update.
        value:
            New range value.

        Returns
        -------
        FiniteMapEncoding
            New encoding with the update axiom added.
        """
        new_fn = f"{self.map_fn}_upd_{key}"
        update_axiom = (
            f"(forall ((x {self.domain_sort})) "
            f"(= ({new_fn} x) "
            f"(ite (= x {key}) {value} ({self.map_fn} x))))"
        )
        new_defined = list(dict.fromkeys(self.defined_set + [key]))
        new_axioms = list(self.update_axioms) + [update_axiom]
        result = FiniteMapEncoding(
            domain_sort=self.domain_sort,
            range_sort=self.range_sort,
            map_fn=new_fn,
            defined_set=new_defined,
            undefinedness_axiom=self.undefinedness_axiom,
            update_axioms=new_axioms,
            metadata={**self.metadata, "updated_from": self.map_id, "update_key": key},
        )
        _log.debug(
            "update: key=%r value=%r → new map %s from %s",
            key, value, result.map_id[:8], self.map_id[:8],
        )
        return result

    def domain_constraint(self) -> str:
        """Return an SMT-LIB2 constraint enumerating the defined domain.

        Returns
        -------
        str
            Assertion of the form ``(assert (or (= x d1) (= x d2) ...))``.
        """
        if not self.defined_set:
            return _smt2_assert("false")
        disjuncts = " ".join(
            f"(= x {d})" for d in self.defined_set
        )
        constraint = f"(forall ((x {self.domain_sort})) (=> (defined_{self.map_fn} x) (or {disjuncts})))"
        _log.debug("domain_constraint: %d defined values for map %s", len(self.defined_set), self.map_id[:8])
        return _smt2_assert(constraint)

    def range_constraint(self) -> str:
        """Return an SMT-LIB2 constraint asserting range membership.

        Returns
        -------
        str
        """
        constraint = (
            f"(forall ((x {self.domain_sort})) "
            f"(=> (defined_{self.map_fn} x) "
            f"(exists ((y {self.range_sort})) (= ({self.map_fn} x) y))))"
        )
        return _smt2_assert(constraint)

    def compose_maps(self, other: "FiniteMapEncoding") -> "FiniteMapEncoding":
        """Compose *self* and *other* as partial functions (``other ∘ self``).

        The composed map is defined at ``x`` iff ``self`` is defined at ``x``
        and ``other`` is defined at ``self(x)``.

        Parameters
        ----------
        other:
            The outer partial function.

        Returns
        -------
        FiniteMapEncoding
            New encoding representing the composition.
        """
        composed_fn = f"{other.map_fn}_comp_{self.map_fn}"
        composition_axiom = (
            f"(forall ((x {self.domain_sort})) "
            f"(=> (defined_{self.map_fn} x) "
            f"(= ({composed_fn} x) ({other.map_fn} ({self.map_fn} x)))))"
        )
        composed_defined = [
            d for d in self.defined_set
            if self.lookup(d) is not None
        ]
        result = FiniteMapEncoding(
            domain_sort=self.domain_sort,
            range_sort=other.range_sort,
            map_fn=composed_fn,
            defined_set=composed_defined,
            undefinedness_axiom=self.undefinedness_axiom,
            update_axioms=list(self.update_axioms) + list(other.update_axioms) + [composition_axiom],
            metadata={"composed_from": [self.map_id, other.map_id]},
        )
        _log.debug(
            "compose_maps: %s ∘ %s → %s",
            other.map_fn, self.map_fn, composed_fn,
        )
        return result

    def to_z3_constraints(self) -> list[str]:
        """Return all constraints for this finite map as a list of SMT-LIB2 strings.

        Includes the undefinedness axiom, domain constraint, range constraint,
        and all update axioms.

        Returns
        -------
        list[str]
        """
        constraints: list[str] = [
            _smt2_assert(self.undefinedness_axiom),
            self.domain_constraint(),
            self.range_constraint(),
        ]
        for axiom in self.update_axioms:
            constraints.append(_smt2_assert(axiom))
        return constraints

    def summary(self) -> str:
        """Return a compact human-readable summary.

        Returns
        -------
        str
        """
        return (
            f"FiniteMapEncoding(fn={self.map_fn!r}, "
            f"domain={self.domain_sort}, range={self.range_sort}, "
            f"defined={len(self.defined_set)}, "
            f"id={self.map_id[:8]})"
        )

    def defined_at(self, key: str) -> bool:
        """Check whether *key* is in the defined set.

        Parameters
        ----------
        key:
            Domain value to test.

        Returns
        -------
        bool
        """
        return key in self.defined_set

    def domain_size(self) -> int:
        """Return the number of defined domain values.

        Returns
        -------
        int
        """
        return len(self.defined_set)


# ---------------------------------------------------------------------------
# InterfaceAbstraction
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class InterfaceAbstraction:
    """Abstract Z3 sort encoding for a program interface.

    An ``InterfaceAbstraction`` introduces a new Z3 sort for an interface,
    declares method-signature uninterpreted functions, and optionally
    provides a refinement map witnessing that a concrete sort implements
    the interface.

    Parameters
    ----------
    interface_name:
        Name of the interface, e.g. ``"ICollection"``.
    abstract_sort:
        Z3 sort name for the abstract interface, e.g. ``"ICollection_Sort"``.
    method_signatures:
        Dict mapping method name to ``(param_sorts, return_sort)``.
    refinement_map:
        Dict mapping abstract method names to concrete implementations.
    abstraction_axioms:
        SMT-LIB2 axioms that the abstract sort must satisfy.
    concrete_sort:
        Optional concrete Z3 sort that realises the interface.
    abstraction_id:
        UUID4.
    created_at:
        UNIX timestamp.
    metadata:
        Free-form metadata.
    """

    interface_name: str
    abstract_sort: Z3SortName = ""
    method_signatures: dict[str, tuple[list[str], str]] = field(default_factory=dict)
    refinement_map: dict[str, str] = field(default_factory=dict)
    abstraction_axioms: list[str] = field(default_factory=list)
    concrete_sort: str | None = None
    abstraction_id: str = field(default_factory=_fresh_id)
    created_at: float = field(default_factory=_timestamp)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.abstract_sort:
            self.abstract_sort = f"{self.interface_name}_Sort"
        ModelRegistry.instance().register("InterfaceAbstraction", self)
        _log.debug(
            "InterfaceAbstraction created: interface=%r id=%s",
            self.interface_name, self.abstraction_id[:8],
        )

    # ------------------------------------------------------------------
    # Method management
    # ------------------------------------------------------------------

    def add_method(
        self,
        name: str,
        param_sorts: list[str],
        return_sort: str,
    ) -> None:
        """Declare a method on this interface.

        Adds the method to ``method_signatures`` and auto-generates an
        SMT-LIB2 function declaration axiom.

        Parameters
        ----------
        name:
            Method name.
        param_sorts:
            List of parameter sort names.
        return_sort:
            Return sort name.
        """
        self.method_signatures[name] = (list(param_sorts), return_sort)
        params_str = " ".join(param_sorts)
        decl = f"(declare-fun {self.interface_name}_{name} ({self.abstract_sort} {params_str}) {return_sort})"
        if decl not in self.abstraction_axioms:
            self.abstraction_axioms.append(decl)
        _log.debug(
            "add_method: added %r to interface %r", name, self.interface_name
        )

    def refine_to_concrete(
        self,
        concrete_sort: str,
        witness_fn: str,
    ) -> "InterfaceAbstraction":
        """Produce a new abstraction refined to a concrete sort.

        The refinement is witnessed by an injective function
        ``witness_fn : abstract_sort → concrete_sort``.

        Parameters
        ----------
        concrete_sort:
            Concrete Z3 sort name.
        witness_fn:
            Name of the witness (abstraction) function.

        Returns
        -------
        InterfaceAbstraction
            New abstraction with ``concrete_sort`` set and refinement axioms added.
        """
        refinement_axiom = (
            f"(forall ((x {self.abstract_sort})) "
            f"(exists ((y {concrete_sort})) "
            f"(= ({witness_fn} x) y)))"
        )
        new_axioms = list(self.abstraction_axioms) + [refinement_axiom]
        new_refmap = dict(self.refinement_map)
        new_refmap[self.abstract_sort] = concrete_sort

        result = InterfaceAbstraction(
            interface_name=self.interface_name,
            abstract_sort=self.abstract_sort,
            method_signatures={k: (list(v[0]), v[1]) for k, v in self.method_signatures.items()},
            refinement_map=new_refmap,
            abstraction_axioms=new_axioms,
            concrete_sort=concrete_sort,
            metadata={**self.metadata, "witness_fn": witness_fn, "refined_from": self.abstraction_id},
        )
        _log.debug(
            "refine_to_concrete: refined %r to %r in abstraction %s",
            self.abstract_sort, concrete_sort, self.abstraction_id[:8],
        )
        return result

    def check_refinement(self) -> bool:
        """Check that the refinement map is consistent.

        Consistency means every key in ``refinement_map`` is the abstract
        sort or a known method name, and every value is a non-empty string.

        Returns
        -------
        bool
            ``True`` if consistent.
        """
        for key, val in self.refinement_map.items():
            if not val:
                _log.debug(
                    "check_refinement: empty value for key %r in abstraction %s",
                    key, self.abstraction_id[:8],
                )
                return False
        return True

    def project_method(self, method_name: str) -> str | None:
        """Return the SMT-LIB2 signature string for *method_name*.

        Parameters
        ----------
        method_name:
            The method to project.

        Returns
        -------
        str | None
            Signature string of the form ``"(m : sort1 ... → return_sort)"``,
            or ``None`` if the method does not exist.
        """
        if method_name not in self.method_signatures:
            _log.debug(
                "project_method: %r not in interface %r",
                method_name, self.interface_name,
            )
            return None
        params, ret = self.method_signatures[method_name]
        param_str = " ".join(params) if params else "()"
        return f"({method_name} : {param_str} → {ret})"

    def abstract_value(self, concrete_val: str) -> str:
        """Apply the abstraction map to a concrete value expression.

        Returns the SMT-LIB2 expression for the abstract representative
        of *concrete_val*.

        Parameters
        ----------
        concrete_val:
            Concrete value SMT-LIB2 expression.

        Returns
        -------
        str
            Abstract value expression.
        """
        if self.concrete_sort and self.abstract_sort:
            return f"(abstract_{self.interface_name} {concrete_val})"
        return concrete_val

    def to_smt2(self) -> str:
        """Serialise this interface abstraction to SMT-LIB2.

        Returns
        -------
        str
            Complete SMT-LIB2 fragment with sort declarations, function
            declarations, and all axioms.
        """
        parts: list[str] = [
            _smt2_comment(f"InterfaceAbstraction: {self.interface_name} [{self.abstraction_id[:8]}]"),
            f"(declare-sort {self.abstract_sort} 0)",
        ]
        if self.concrete_sort:
            parts.append(f"(declare-sort {self.concrete_sort} 0)")
            parts.append(
                f"(declare-fun abstract_{self.interface_name} "
                f"({self.concrete_sort}) {self.abstract_sort})"
            )
        for axiom in self.abstraction_axioms:
            # Method declarations are emitted as-is; assert others
            if axiom.startswith("(declare"):
                parts.append(axiom)
            else:
                parts.append(_smt2_assert(axiom))
        parts.append("(check-sat)")
        return "\n".join(parts)

    def summary(self) -> str:
        """Return a compact human-readable summary.

        Returns
        -------
        str
        """
        return (
            f"InterfaceAbstraction(interface={self.interface_name!r}, "
            f"abstract_sort={self.abstract_sort!r}, "
            f"methods={self.num_methods()}, "
            f"concrete={self.concrete_sort!r}, "
            f"id={self.abstraction_id[:8]})"
        )

    def num_methods(self) -> int:
        """Return the number of declared methods.

        Returns
        -------
        int
        """
        return len(self.method_signatures)

    def is_refined(self) -> bool:
        """Check whether this abstraction has a concrete refinement.

        Returns
        -------
        bool
            ``True`` if ``concrete_sort`` is set and the refinement map is
            non-empty.
        """
        return self.concrete_sort is not None and bool(self.refinement_map)


