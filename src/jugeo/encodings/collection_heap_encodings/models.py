"""
models — Core data models for collection_heap_encodings.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch27: Exact Z3 encodings II: collections, finite maps, heap summaries,
alias partitions, interface abstractions.

Part of the JuGeo judgment-geometry framework.

This module defines the five central dataclasses that represent the semantic
objects manipulated by the collection-heap encoding pipeline:

* ``CollectionEncoding``  — Z3 encoding of a Python list/set/dict collection.
* ``HeapSummary``         — Separation-logic heap encoding with footprint tracking.
* ``AliasPartition``      — Alias-class partition expressed as Z3 constraints.
* ``FiniteMapEncoding``   — Partial-function encoding with domain/range axioms.
* ``InterfaceAbstraction``— Abstract Z3 sort for a program interface.

Each dataclass carries a unique ``*_id`` field (UUID4), a ``created_at``
timestamp, and a free-form ``metadata`` dict for pipeline annotations.

Design notes
------------
* Z3 is imported lazily so that the module can be loaded even when Z3 is not
  installed (e.g. during static analysis or documentation builds).
* All Z3-dependent methods guard their body with an ``_Z3_AVAILABLE`` check and
  fall back gracefully to string-based representations.
* A ``ModelRegistry`` singleton tracks every instance created so that the
  pipeline can enumerate all live objects without holding external references.
"""

