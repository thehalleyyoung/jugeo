# AliasPartition
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class AliasPartition:
    """Alias-partition encoding using Z3 uninterpreted function constraints.

    An ``AliasPartition`` captures must-alias and must-not-alias relations
    between program pointers and encodes them as Z3 constraints over an
    uninterpreted ``alias_class`` function.

    Parameters
    ----------
    pointer_sort:
        Z3 sort name for pointer values.
    alias_class_fn:
        Name of the Z3 uninterpreted function mapping pointers to alias classes.
    disjointness_axioms:
        SMT-LIB2 axioms asserting that distinct classes are disjoint.
    must_alias_pairs:
        List of ``(p, q)`` pairs asserted to be aliases.
    must_not_alias_pairs:
        List of ``(p, q)`` pairs asserted to be non-aliases.
    partition_classes:
        List of frozensets, each grouping pointers in the same alias class.
    partition_id:
        UUID4 uniquely identifying this partition.
    created_at:
        UNIX timestamp.
    """

    pointer_sort: Z3SortName = _DEFAULT_POINTER_SORT
    alias_class_fn: str = "alias_class"
    disjointness_axioms: list[str] = field(default_factory=list)
    must_alias_pairs: list[tuple[str, str]] = field(default_factory=list)
    must_not_alias_pairs: list[tuple[str, str]] = field(default_factory=list)
    partition_classes: list[frozenset[str]] = field(default_factory=list)
    partition_id: str = field(default_factory=_fresh_id)
    created_at: float = field(default_factory=_timestamp)

    def __post_init__(self) -> None:
        ModelRegistry.instance().register("AliasPartition", self)
        _log.debug("AliasPartition created: id=%s", self.partition_id[:8])

    # ------------------------------------------------------------------
    # Mutation helpers
    # ------------------------------------------------------------------

    def add_must_alias(self, p1: str, p2: str) -> None:
        """Assert that *p1* and *p2* must alias.

        Updates ``must_alias_pairs`` and merges the partition classes of
        *p1* and *p2*.

        Parameters
        ----------
        p1, p2:
            Pointer names.
        """
        if (p1, p2) not in self.must_alias_pairs and (p2, p1) not in self.must_alias_pairs:
            self.must_alias_pairs.append((p1, p2))
        # Merge partition classes
        cls1 = self.alias_class_of(p1)
        cls2 = self.alias_class_of(p2)
        if cls1 is None and cls2 is None:
            self.partition_classes.append(frozenset({p1, p2}))
        elif cls1 is None:
            idx = self.partition_classes.index(cls2)
            self.partition_classes[idx] = cls2 | {p1}
        elif cls2 is None:
            idx = self.partition_classes.index(cls1)
            self.partition_classes[idx] = cls1 | {p2}
        elif cls1 is not cls2:
            self.partition_classes.remove(cls1)
            self.partition_classes.remove(cls2)
            self.partition_classes.append(cls1 | cls2)
        _log.debug("add_must_alias: (%r, %r) in partition %s", p1, p2, self.partition_id[:8])

    def add_must_not_alias(self, p1: str, p2: str) -> None:
        """Assert that *p1* and *p2* must not alias.

        Parameters
        ----------
        p1, p2:
            Pointer names.
        """
        if (p1, p2) not in self.must_not_alias_pairs and (p2, p1) not in self.must_not_alias_pairs:
            self.must_not_alias_pairs.append((p1, p2))
        _log.debug(
            "add_must_not_alias: (%r, %r) in partition %s", p1, p2, self.partition_id[:8]
        )

    # ------------------------------------------------------------------
    # Z3 constraint generation
    # ------------------------------------------------------------------

    def to_z3_constraints(self) -> list[str]:
        """Format all alias constraints as SMT-LIB2 assertion strings.

        Generates:
        * ``(assert (= (alias_class p) (alias_class q)))`` for must-alias pairs.
        * ``(assert (not (= (alias_class p) (alias_class q))))`` for must-not-alias.
        * All ``disjointness_axioms``.

        Returns
        -------
        list[str]
            List of SMT-LIB2 assertion strings.
        """
        constraints: list[str] = []
        for p, q in self.must_alias_pairs:
            constraints.append(
                _smt2_assert(
                    f"(= ({self.alias_class_fn} {p}) ({self.alias_class_fn} {q}))"
                )
            )
        for p, q in self.must_not_alias_pairs:
            constraints.append(
                _smt2_assert(
                    f"(not (= ({self.alias_class_fn} {p}) ({self.alias_class_fn} {q})))"
                )
            )
        for axiom in self.disjointness_axioms:
            constraints.append(_smt2_assert(axiom))
        _log.debug(
            "to_z3_constraints: %d constraints for partition %s",
            len(constraints), self.partition_id[:8],
        )
        return constraints

    # ------------------------------------------------------------------
    # Partition queries
    # ------------------------------------------------------------------

    def alias_class_of(self, pointer: str) -> frozenset[str] | None:
        """Find the partition class containing *pointer*.

        Parameters
        ----------
        pointer:
            Pointer name to look up.

        Returns
        -------
        frozenset[str] | None
            The class set, or ``None`` if *pointer* is not in any class.
        """
        for cls in self.partition_classes:
            if pointer in cls:
                return cls
        return None

    def verify_partition(self) -> bool:
        """Check that the partition is consistent with must/must-not constraints.

        A partition is consistent when:
        * Every must-alias pair ``(p, q)`` has ``p`` and ``q`` in the same class.
        * Every must-not-alias pair ``(p, q)`` has ``p`` and ``q`` in different classes.

        Returns
        -------
        bool
            ``True`` if consistent.
        """
        for p, q in self.must_alias_pairs:
            cp = self.alias_class_of(p)
            cq = self.alias_class_of(q)
            if cp is None or cq is None or cp != cq:
                _log.debug(
                    "verify_partition: must-alias (%r, %r) violated in %s", p, q, self.partition_id[:8]
                )
                return False
        for p, q in self.must_not_alias_pairs:
            cp = self.alias_class_of(p)
            cq = self.alias_class_of(q)
            if cp is not None and cq is not None and cp == cq:
                _log.debug(
                    "verify_partition: must-not-alias (%r, %r) violated in %s",
                    p, q, self.partition_id[:8],
                )
                return False
        _log.debug("verify_partition: partition %s is consistent", self.partition_id[:8])
        return True

    def merge_partitions(self, other: "AliasPartition") -> "AliasPartition":
        """Return a new partition that is the union of *self* and *other*.

        Parameters
        ----------
        other:
            Partition to merge with.

        Returns
        -------
        AliasPartition
            New partition combining all must-alias, must-not-alias, and
            disjointness axioms from both.
        """
        result = AliasPartition(
            pointer_sort=self.pointer_sort,
            alias_class_fn=self.alias_class_fn,
            disjointness_axioms=list(
                dict.fromkeys(self.disjointness_axioms + other.disjointness_axioms)
            ),
            must_alias_pairs=list(
                dict.fromkeys(self.must_alias_pairs + other.must_alias_pairs)
            ),
            must_not_alias_pairs=list(
                dict.fromkeys(self.must_not_alias_pairs + other.must_not_alias_pairs)
            ),
            partition_classes=list(self.partition_classes + other.partition_classes),
        )
        _log.debug(
            "merge_partitions: merged %s and %s → %s",
            self.partition_id[:8], other.partition_id[:8], result.partition_id[:8],
        )
        return result

    def summary(self) -> str:
        """Return a compact human-readable summary.

        Returns
        -------
        str
        """
        return (
            f"AliasPartition(classes={self.num_classes()}, "
            f"must_alias={len(self.must_alias_pairs)}, "
            f"must_not_alias={len(self.must_not_alias_pairs)}, "
            f"id={self.partition_id[:8]})"
        )

    def num_classes(self) -> int:
        """Return the number of distinct alias classes.

        Returns
        -------
        int
        """
        return len(self.partition_classes)

    def is_consistent(self) -> bool:
        """Alias for ``verify_partition()``.

        Returns
        -------
        bool
        """
        return self.verify_partition()


