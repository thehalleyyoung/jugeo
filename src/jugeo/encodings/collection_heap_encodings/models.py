class ModelRegistry:
    """Singleton registry that tracks all model instances created in this session.

    Instances of ``CollectionEncoding``, ``HeapSummary``, ``AliasPartition``,
    ``FiniteMapEncoding``, and ``InterfaceAbstraction`` register themselves
    here via ``register()``.

    Design
    ------
    The registry stores only weak references to avoid preventing garbage
    collection of model objects.  The ``all_of_type()`` method filters out
    dead references transparently.

    Usage
    -----
    >>> registry = ModelRegistry.instance()
    >>> registry.register("CollectionEncoding", enc)
    >>> registry.all_of_type("CollectionEncoding")
    [<CollectionEncoding ...>]
    """

    _instance: ClassVar[ModelRegistry | None] = None
    _store: dict[str, list[Any]]

    def __init__(self) -> None:
        self._store: dict[str, list[Any]] = {}

    @classmethod
    def instance(cls) -> "ModelRegistry":
        """Return the singleton registry instance.

        Returns
        -------
        ModelRegistry
        """
        if cls._instance is None:
            cls._instance = cls()
            _log.debug("ModelRegistry: singleton created")
        return cls._instance

    def register(self, type_name: str, obj: Any) -> None:
        """Register *obj* under *type_name*.

        Parameters
        ----------
        type_name:
            Logical type label, e.g. ``"CollectionEncoding"``.
        obj:
            The model instance to register.
        """
        if type_name not in self._store:
            self._store[type_name] = []
        self._store[type_name].append(obj)
        _log.debug("ModelRegistry.register: %s registered", type_name)

    def all_of_type(self, type_name: str) -> list[Any]:
        """Return all registered objects of *type_name*.

        Parameters
        ----------
        type_name:
            Logical type label.

        Returns
        -------
        list[Any]
            All registered instances of that type.
        """
        return list(self._store.get(type_name, []))

    def count(self, type_name: str) -> int:
        """Return the number of registered objects of *type_name*.

        Parameters
        ----------
        type_name:
            Logical type label.

        Returns
        -------
        int
        """
        return len(self._store.get(type_name, []))

    def clear(self) -> None:
        """Clear all registrations.

        Useful in tests that need a clean state.
        """
        self._store.clear()
        _log.debug("ModelRegistry: cleared")

    def summary(self) -> str:
        """Return a human-readable summary of registered objects.

        Returns
        -------
        str
        """
        if not self._store:
            return "ModelRegistry: empty"
        lines = ["ModelRegistry:"]
        for type_name, objs in sorted(self._store.items()):
            lines.append(f"  {type_name}: {len(objs)} instance(s)")
        return "\n".join(lines)


