@dataclass(slots=True)
class CollectionEncoding:
    """Z3 encoding of a Python collection (list, set, or dict).

    A ``CollectionEncoding`` holds the SMT-LIB2 array declaration that models
    the collection, together with a list of invariant strings that constrain
    the array's contents.

    Parameters
    ----------
    name:
        Logical name of the collection, e.g. ``"my_list"``.
    element_sort:
        Z3 sort of the collection's elements, e.g. ``"Int"``.
    index_sort:
        Z3 sort of the collection's indices, e.g. ``"Int"`` for lists.
    array_expr:
        SMT-LIB2 expression for the backing array constant.
    invariants:
        List of SMT-LIB2 boolean strings constraining the collection.
    provenance:
        Free-form provenance dict (source file, line number, etc.).
    encoding_id:
        UUID4 uniquely identifying this encoding instance.
    created_at:
        UNIX timestamp when this encoding was created.
    metadata:
        Free-form metadata dict for pipeline annotations.
    """

    name: str
    element_sort: Z3SortName = _DEFAULT_ELEMENT_SORT
    index_sort: Z3SortName = _DEFAULT_INDEX_SORT
    array_expr: Z3ExprStr = ""
    invariants: list[str] = field(default_factory=list)
    provenance: dict[str, Any] = field(default_factory=dict)
    encoding_id: str = field(default_factory=_fresh_id)
    created_at: float = field(default_factory=_timestamp)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.array_expr:
            self.array_expr = _format_smt2_array(self.name, self.index_sort, self.element_sort)
        ModelRegistry.instance().register("CollectionEncoding", self)
        _log.debug(
            "CollectionEncoding created: name=%r id=%s", self.name, self.encoding_id[:8]
        )

    # ------------------------------------------------------------------
    # Z3 / SMT-LIB2 methods
    # ------------------------------------------------------------------

    def to_z3_assertion(self) -> str:
        """Format all invariants as a conjunction of SMT-LIB2 assertions.

        If there are no invariants the returned string is the SMT-LIB2
        ``true`` assertion.

        Returns
        -------
        str
            One or more ``(assert ...)`` commands joined by newlines.
        """
        if not self.invariants:
            _log.debug("to_z3_assertion: no invariants for %r", self.name)
            return _smt2_assert("true")
        assertions = "\n".join(_smt2_assert(inv) for inv in self.invariants)
        _log.debug(
            "to_z3_assertion: %d invariant(s) for %r", len(self.invariants), self.name
        )
        return assertions

    def validate_element(self, idx: int, value: Any) -> bool:
        """Check whether *value* at index *idx* plausibly satisfies the invariants.

        This is a lightweight syntactic check: it looks for ``select``
        expressions referencing the backing array and tries to evaluate
        simple numeric constraints.

        Parameters
        ----------
        idx:
            Array index to check.
        value:
            Candidate element value.

        Returns
        -------
        bool
            ``True`` if no invariant is syntactically violated.
        """
        select_expr = f"(select {self.name} {idx})"
        for inv in self.invariants:
            if select_expr not in inv:
                continue
            # Very simple bound checks encoded as (>= (select ...) 0) etc.
            if f"(>= {select_expr} 0)" in inv and isinstance(value, (int, float)):
                if value < 0:
                    _log.debug(
                        "validate_element: idx=%d value=%r fails non-negativity", idx, value
                    )
                    return False
        _log.debug("validate_element: idx=%d value=%r passes all invariants", idx, value)
        return True

    def project_invariant(self, predicate_name: str) -> str | None:
        """Find the first invariant string containing *predicate_name*.

        Parameters
        ----------
        predicate_name:
            The predicate symbol to search for, e.g. ``"sorted"``.

        Returns
        -------
        str | None
            The first matching invariant, or ``None``.
        """
        for inv in self.invariants:
            if predicate_name in inv:
                _log.debug(
                    "project_invariant: found %r in encoding %r", predicate_name, self.name
                )
                return inv
        _log.debug(
            "project_invariant: %r not found in encoding %r", predicate_name, self.name
        )
        return None

    def merge_encodings(self, other: "CollectionEncoding") -> "CollectionEncoding":
        """Produce a new encoding that is the union of *self* and *other*.

        The merged encoding uses the name ``"<self.name>_merged_<other.name>"``,
        inherits ``self``'s sort declarations, and combines the invariant lists
        from both encodings (deduplicating by value).

        Parameters
        ----------
        other:
            The encoding to merge with.

        Returns
        -------
        CollectionEncoding
            A new (non-frozen) encoding with combined invariants.
        """
        if self.element_sort != other.element_sort or self.index_sort != other.index_sort:
            _log.warning(
                "merge_encodings: sort mismatch (%s/%s vs %s/%s)",
                self.element_sort, self.index_sort,
                other.element_sort, other.index_sort,
            )
        merged_name = f"{self.name}_merged_{other.name}"
        merged_invariants = list(dict.fromkeys(self.invariants + other.invariants))
        merged_provenance = {**self.provenance, **other.provenance, "merged": True}
        result = CollectionEncoding(
            name=merged_name,
            element_sort=self.element_sort,
            index_sort=self.index_sort,
            array_expr=_format_smt2_array(merged_name, self.index_sort, self.element_sort),
            invariants=merged_invariants,
            provenance=merged_provenance,
            metadata={**self.metadata, "merged_from": [self.encoding_id, other.encoding_id]},
        )
        _log.debug(
            "merge_encodings: produced %r with %d invariants",
            merged_name,
            len(merged_invariants),
        )
        return result

    def to_smt2(self) -> str:
        """Serialise this encoding to a complete SMT-LIB2 fragment.

        The fragment includes:
        1. A ``set-logic`` command.
        2. The array declaration.
        3. All invariant assertions.
        4. A ``check-sat`` command.

        Returns
        -------
        str
            Complete SMT-LIB2 string.
        """
        parts: list[str] = [
            _smt2_comment(f"CollectionEncoding: {self.name} [{self.encoding_id[:8]}]"),
            _smt2_comment(f"element_sort={self.element_sort} index_sort={self.index_sort}"),
            "(set-logic QF_ALIA)",
            self.array_expr,
        ]
        for inv in self.invariants:
            parts.append(_smt2_assert(inv))
        parts.append("(check-sat)")
        result = "\n".join(parts)
        _log.debug("to_smt2: %d bytes for encoding %r", len(result), self.name)
        return result

    @classmethod
    def from_smt2(cls, smt2_str: str) -> "CollectionEncoding":
        """Parse a ``CollectionEncoding`` from an SMT-LIB2 fragment.

        This parser handles the format produced by ``to_smt2()``.  It
        extracts the array name and sorts from the ``declare-const`` line and
        collects all ``assert`` bodies as invariants.

        Parameters
        ----------
        smt2_str:
            SMT-LIB2 string to parse.

        Returns
        -------
        CollectionEncoding
            Reconstructed encoding (encoding_id and created_at are fresh).

        Raises
        ------
        ValueError
            If the required ``declare-const`` line cannot be found.
        """
        name = "unknown"
        index_sort = _DEFAULT_INDEX_SORT
        element_sort = _DEFAULT_ELEMENT_SORT
        array_expr = ""
        invariants: list[str] = []

        declare_pat = re.compile(
            r"\(declare-const\s+(\S+)\s+\(Array\s+(\S+)\s+(\S+)\)\)"
        )
        assert_pat = re.compile(r"\(assert\s+(.+)\)\s*$")

        for line in smt2_str.splitlines():
            line = line.strip()
            m = declare_pat.match(line)
            if m:
                name, index_sort, element_sort = m.group(1), m.group(2), m.group(3)
                array_expr = line
                continue
            m2 = assert_pat.match(line)
            if m2:
                body = m2.group(1).strip()
                if body != "true":
                    invariants.append(body)

        if not array_expr:
            raise ValueError(
                "from_smt2: could not find a (declare-const ... (Array ...)) declaration"
            )

        enc = cls(
            name=name,
            element_sort=element_sort,
            index_sort=index_sort,
            array_expr=array_expr,
            invariants=invariants,
            provenance={"source": "from_smt2"},
        )
        _log.debug("from_smt2: reconstructed CollectionEncoding %r", name)
        return enc

    def summary(self) -> str:
        """Return a compact human-readable summary line.

        Returns
        -------
        str
        """
        return (
            f"CollectionEncoding(name={self.name!r}, "
            f"sorts={self.index_sort}/{self.element_sort}, "
            f"invariants={len(self.invariants)}, "
            f"id={self.encoding_id[:8]})"
        )

    def add_invariant(self, inv: str) -> None:
        """Append *inv* to the invariants list if not already present.

        Parameters
        ----------
        inv:
            SMT-LIB2 boolean expression to add as an invariant.
        """
        if inv not in self.invariants:
            self.invariants.append(inv)
            _log.debug("add_invariant: added %r to encoding %r", inv[:40], self.name)

    def cardinality(self) -> int:
        """Return the number of elements if the cardinality is encoded, else -1.

        Looks for an invariant of the form
        ``(= (card <name>) <n>)`` and parses ``n``.

        Returns
        -------
        int
            Cardinality value, or ``-1`` if unknown.
        """
        card_pat = re.compile(rf"\(=\s+\(card\s+{re.escape(self.name)}\)\s+(\d+)\)")
        for inv in self.invariants:
            m = card_pat.search(inv)
            if m:
                return int(m.group(1))
        return -1


