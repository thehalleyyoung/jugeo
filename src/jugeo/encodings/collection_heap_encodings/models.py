@dataclass(slots=True)
class HeapSummary:
    """Separation-logic heap summary encoding.

    A ``HeapSummary`` models a portion of program heap as a Z3 partial map
    from locations to values, together with a ``footprint`` set, a list of
    separating conjuncts, and an optional frame condition.

    Parameters
    ----------
    location_sort:
        Z3 sort for heap locations.
    value_sort:
        Z3 sort for heap values.
    points_to_map:
        Dict mapping location names to value expressions (``loc ↦ val``).
    footprint:
        Frozenset of location names that this heap owns.
    separating_conjuncts:
        List of SMT-LIB2 strings, each representing one heap conjunct.
    frame_condition:
        Optional SMT-LIB2 string representing the frame formula.
    heap_id:
        UUID4 uniquely identifying this heap summary.
    created_at:
        UNIX timestamp.
    metadata:
        Free-form metadata dict.
    """

    location_sort: Z3SortName = _DEFAULT_LOCATION_SORT
    value_sort: Z3SortName = _DEFAULT_VALUE_SORT
    points_to_map: dict[str, str] = field(default_factory=dict)
    footprint: frozenset[str] = field(default_factory=frozenset)
    separating_conjuncts: list[str] = field(default_factory=list)
    frame_condition: str | None = None
    heap_id: str = field(default_factory=_fresh_id)
    created_at: float = field(default_factory=_timestamp)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        ModelRegistry.instance().register("HeapSummary", self)
        _log.debug("HeapSummary created: id=%s", self.heap_id[:8])

    # ------------------------------------------------------------------
    # Separation logic operations
    # ------------------------------------------------------------------

    def entails_points_to(self, loc: str, val: str) -> bool:
        """Check whether ``loc ↦ val`` is directly entailed by this heap.

        Parameters
        ----------
        loc:
            Location name.
        val:
            Value expression.

        Returns
        -------
        bool
            ``True`` if ``self.points_to_map[loc] == val``.
        """
        result = self.points_to_map.get(loc) == val
        _log.debug(
            "entails_points_to: loc=%r val=%r → %s (heap %s)",
            loc, val, result, self.heap_id[:8],
        )
        return result

    def disjoint_from(self, other: "HeapSummary") -> bool:
        """Check whether *self* and *other* have disjoint footprints.

        Parameters
        ----------
        other:
            Another heap summary.

        Returns
        -------
        bool
            ``True`` if the footprints are disjoint.
        """
        result = self.footprint.isdisjoint(other.footprint)
        _log.debug(
            "disjoint_from: heap %s and %s → %s",
            self.heap_id[:8], other.heap_id[:8], result,
        )
        return result

    def frame_rule_apply(self, frame: str) -> "HeapSummary":
        """Apply the frame rule to extend this heap with a frame formula.

        The frame rule in separation logic states that if a command is safe
        in heap ``h``, it is also safe in ``h * F`` for any frame ``F``.
        This method returns a new ``HeapSummary`` with ``frame`` added as
        the frame condition.

        Parameters
        ----------
        frame:
            SMT-LIB2 string representing the frame formula.

        Returns
        -------
        HeapSummary
            New heap summary with the frame condition set.
        """
        new_conjuncts = list(self.separating_conjuncts) + [frame]
        result = HeapSummary(
            location_sort=self.location_sort,
            value_sort=self.value_sort,
            points_to_map=dict(self.points_to_map),
            footprint=self.footprint,
            separating_conjuncts=new_conjuncts,
            frame_condition=frame,
            metadata={**self.metadata, "frame_applied": frame},
        )
        _log.debug(
            "frame_rule_apply: created framed heap %s from %s",
            result.heap_id[:8], self.heap_id[:8],
        )
        return result

    def compose_heaps(self, other: "HeapSummary") -> "HeapSummary":
        """Form the separating conjunction ``self * other``.

        Combines points-to maps, unions footprints, and merges conjuncts.
        Raises ``ValueError`` if the footprints are not disjoint.

        Parameters
        ----------
        other:
            The right-hand heap.

        Returns
        -------
        HeapSummary
            New heap representing ``self * other``.

        Raises
        ------
        ValueError
            If the footprints overlap.
        """
        if not self.disjoint_from(other):
            overlap = self.footprint & other.footprint
            raise ValueError(
                f"compose_heaps: footprints overlap at locations {overlap}"
            )
        merged_ptm = {**self.points_to_map, **other.points_to_map}
        merged_footprint = self.footprint | other.footprint
        merged_conjuncts = self.separating_conjuncts + other.separating_conjuncts
        result = HeapSummary(
            location_sort=self.location_sort,
            value_sort=self.value_sort,
            points_to_map=merged_ptm,
            footprint=merged_footprint,
            separating_conjuncts=merged_conjuncts,
            frame_condition=None,
            metadata={
                "composed_from": [self.heap_id, other.heap_id],
            },
        )
        _log.debug(
            "compose_heaps: composed %s * %s → %s",
            self.heap_id[:8], other.heap_id[:8], result.heap_id[:8],
        )
        return result

    def check_alias(self, loc1: str, loc2: str) -> bool:
        """Check whether *loc1* and *loc2* are the same location.

        This is a syntactic equality check on location names; it does not
        perform pointer analysis.

        Parameters
        ----------
        loc1, loc2:
            Location names to compare.

        Returns
        -------
        bool
            ``True`` if they are syntactically equal.
        """
        result = loc1 == loc2
        _log.debug("check_alias: %r and %r → %s", loc1, loc2, result)
        return result

    def to_smtlib(self) -> str:
        """Serialise this heap summary to an SMT-LIB2 fragment.

        Returns
        -------
        str
            SMT-LIB2 string with declarations and assertions.
        """
        parts: list[str] = [
            _smt2_comment(f"HeapSummary [{self.heap_id[:8]}]"),
            _smt2_comment(f"location_sort={self.location_sort} value_sort={self.value_sort}"),
            f"(declare-sort {self.location_sort} 0)",
            f"(declare-sort {self.value_sort} 0)",
            "(declare-const heap (Array {loc} {val}))".format(
                loc=self.location_sort, val=self.value_sort
            ),
        ]
        for loc, val in self.points_to_map.items():
            parts.append(
                _smt2_assert(
                    f"(= (select heap {loc}) {val})"
                )
            )
        for conjunct in self.separating_conjuncts:
            parts.append(_smt2_assert(conjunct))
        if self.frame_condition:
            parts.append(_smt2_assert(self.frame_condition))
        parts.append("(check-sat)")
        return "\n".join(parts)

    def summary(self) -> str:
        """Return a compact human-readable summary.

        Returns
        -------
        str
        """
        return (
            f"HeapSummary(locs={list(self.footprint)[:3]}..., "
            f"ptm={len(self.points_to_map)}, "
            f"conjuncts={len(self.separating_conjuncts)}, "
            f"frame={'yes' if self.frame_condition else 'no'}, "
            f"id={self.heap_id[:8]})"
        )

    def is_empty(self) -> bool:
        """Check whether this heap is the empty heap (``emp``).

        Returns
        -------
        bool
            ``True`` if there are no points-to entries and no conjuncts.
        """
        result = not self.points_to_map and not self.separating_conjuncts
        _log.debug("is_empty: heap %s → %s", self.heap_id[:8], result)
        return result

    def footprint_size(self) -> int:
        """Return the number of locations in the footprint.

        Returns
        -------
        int
        """
        return len(self.footprint)


