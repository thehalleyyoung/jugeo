class _ManifestSerializer:
    """Internal helper for serialising and deserialising manifests.

    This class is not part of the public API and should not be imported
    directly by external code.  It provides:

    * JSON round-trip via ``to_json`` / ``from_json``.
    * SMT-LIB2 comment-block generation via ``to_smt2_comment``.
    * SHA-256 checksum of the manifest content via ``checksum``.

    All methods are instance methods so that a single serializer can be
    configured (e.g. with a custom JSON encoder) and reused.
    """

    def __init__(self, indent: int = 2) -> None:
        """Initialise the serializer.

        Parameters
        ----------
        indent:
            JSON indentation level (default 2 spaces).
        """
        self._indent = indent
        _log.debug("_ManifestSerializer created with indent=%d", indent)

    def to_json(self, manifest: CollectionHeapManifest) -> str:
        """Serialise *manifest* to a JSON string.

        Parameters
        ----------
        manifest:
            The manifest to serialise.

        Returns
        -------
        str
            Pretty-printed JSON string.
        """
        data = manifest.to_dict()
        result = json.dumps(data, indent=self._indent, sort_keys=True, default=str)
        _log.debug(
            "to_json: serialised manifest %s (%d bytes)",
            manifest.manifest_id[:8],
            len(result),
        )
        return result

    def from_json(self, json_str: str) -> dict[str, Any]:
        """Deserialise a JSON string to a plain dictionary.

        Parameters
        ----------
        json_str:
            JSON string previously produced by ``to_json``.

        Returns
        -------
        dict[str, Any]
            Plain Python dictionary; the caller is responsible for
            reconstructing a ``CollectionHeapManifest`` from it.

        Raises
        ------
        json.JSONDecodeError
            If *json_str* is not valid JSON.
        """
        data: dict[str, Any] = json.loads(json_str)
        _log.debug("from_json: deserialised manifest %s", data.get("manifest_id", "?")[:8])
        return data

    def to_smt2_comment(self, manifest: CollectionHeapManifest) -> str:
        """Generate an SMT-LIB2 comment block embedding key manifest metadata.

        The comment block can be prepended to a ``.smt2`` file so that
        solver logs are self-describing.

        Parameters
        ----------
        manifest:
            The manifest to embed.

        Returns
        -------
        str
            Multi-line string where every line starts with ``;; ``.
        """
        lines: list[str] = [
            ";; ================================================================",
            f";; JuGeo manifest: {CHAPTER_TAG}",
            f";; manifest_id : {manifest.manifest_id}",
            f";; chapter_ref : {manifest.chapter_ref}",
            f";; version     : {MODULE_VERSION}",
            f";; created_at  : {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(manifest.created_at))}",
            f";; sections    : {', '.join(manifest.section_names)}",
            f";; theorems    : {', '.join(manifest.theorem_targets[:3])} ...",
            ";; ================================================================",
        ]
        return "\n".join(lines)

    def checksum(self, manifest: CollectionHeapManifest) -> str:
        """Compute a SHA-256 checksum of the serialised manifest.

        Parameters
        ----------
        manifest:
            The manifest to checksum.

        Returns
        -------
        str
            Lowercase hex-encoded SHA-256 digest of the JSON representation.
        """
        json_str = self.to_json(manifest)
        digest = hashlib.sha256(json_str.encode()).hexdigest()
        _log.debug(
            "checksum: manifest %s → %s", manifest.manifest_id[:8], digest[:16]
        )
        return digest


