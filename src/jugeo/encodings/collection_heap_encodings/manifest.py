def build_manifest() -> CollectionHeapManifest:
    """Construct and return the default ``CollectionHeapManifest``.

    This factory probes for Z3 availability at runtime and overrides the
    ``z3_available`` capability flag accordingly.

    Returns
    -------
    CollectionHeapManifest
        A fully populated, validated manifest for the
        ``collection_heap_encodings`` package.

    Notes
    -----
    This function is called once at module import time to populate
    ``_DEFAULT_MANIFEST``.  Subsequent calls return freshly constructed
    manifests (new ``manifest_id`` and ``created_at``), which is useful
    for testing.
    """
    _log.debug("build_manifest: probing runtime capabilities …")

    # Probe Z3 availability
    z3_flag: bool
    try:
        import z3 as _z3_probe  # noqa: F401
        z3_flag = True
        _log.debug("build_manifest: Z3 is available")
    except ImportError:
        z3_flag = False
        _log.debug("build_manifest: Z3 is NOT available")

    runtime_flags: dict[str, bool] = dict(CAPABILITY_FLAGS)
    runtime_flags["z3_available"] = z3_flag

    manifest = CollectionHeapManifest(
        chapter_ref="theory2.tex Ch27",
        section_names=tuple(SECTION_REGISTRY.keys()),
        theorem_targets=tuple(THEOREM_TARGETS),
        capability_flags=runtime_flags,
        provenance=MANIFEST_SPEC_PROVENANCE,
        created_at=time.time(),
        manifest_id=str(uuid.uuid4()),
    )
    _log.info(
        "build_manifest: created manifest %s with %d sections",
        manifest.manifest_id[:8],
        len(manifest.section_names),
    )
    return manifest


def validate_manifest(manifest: CollectionHeapManifest) -> bool:
    """Validate *manifest* and raise ``ManifestValidationError`` if invalid.

    Parameters
    ----------
    manifest:
        The manifest to validate.

    Returns
    -------
    bool
        ``True`` if validation passes (no errors).

    Raises
    ------
    ManifestValidationError
        If any validation errors are found.
    """
    errors = manifest.validate()
    if errors:
        _log.error(
            "validate_manifest: %d error(s) in manifest %s",
            len(errors),
            manifest.manifest_id[:8],
        )
        raise ManifestValidationError(errors)
    _log.info("validate_manifest: manifest %s is valid", manifest.manifest_id[:8])
    return True


def manifest_summary() -> str:
    """Return a formatted summary of the default manifest.

    Returns
    -------
    str
        Multi-line human-readable summary string.
    """
    return _DEFAULT_MANIFEST.summary()


