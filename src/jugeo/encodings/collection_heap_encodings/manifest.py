def _section_entry_by_name(name: str) -> SectionEntry | None:
    """Look up a ``SectionEntry`` by name from the static registry.

    Parameters
    ----------
    name:
        Logical section name.

    Returns
    -------
    SectionEntry | None
        Matching entry or ``None``.
    """
    for entry in _SECTION_ENTRIES:
        if entry.name == name:
            return entry
    return None


def _all_encoder_sections() -> list[SectionEntry]:
    """Return all ``SectionEntry`` objects with ``kind == SectionKind.ENCODER``.

    Returns
    -------
    list[SectionEntry]
    """
    return [e for e in _SECTION_ENTRIES if e.kind == SectionKind.ENCODER]


def _all_section_names() -> tuple[str, ...]:
    """Return a tuple of all known section names.

    Returns
    -------
    tuple[str, ...]
    """
    return tuple(e.name for e in _SECTION_ENTRIES)


def _provenance_as_comment() -> str:
    """Format ``MANIFEST_SPEC_PROVENANCE`` as a Python block comment.

    Returns
    -------
    str
        Multi-line string.
    """
    lines = ["# Provenance:"]
    for key, value in MANIFEST_SPEC_PROVENANCE.items():
        lines.append(f"#   {key}: {value!r}")
    return "\n".join(lines)


def _capability_report(flags: Mapping[str, bool]) -> str:
    """Format a capability flag mapping as a human-readable report string.

    Parameters
    ----------
    flags:
        Mapping of flag names to boolean values.

    Returns
    -------
    str
        Multi-line formatted string.
    """
    enabled = sorted(k for k, v in flags.items() if v)
    disabled = sorted(k for k, v in flags.items() if not v)
    parts: list[str] = ["Enabled capabilities:"]
    parts.extend(f"  + {k}" for k in enabled)
    parts.append("Disabled capabilities:")
    parts.extend(f"  - {k}" for k in disabled)
    return "\n".join(parts)


