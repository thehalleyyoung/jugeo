def _detect_cycles(entries: tuple[SectionEntry, ...]) -> list[str]:
    """Detect cycles in the dependency graph using iterative DFS.

    Parameters
    ----------
    entries:
        All section entries to inspect.

    Returns
    -------
    list[str]
        Error message strings, one per detected cycle.  Empty if acyclic.
    """
    adjacency: dict[str, set[str]] = {e.name: set(e.depends_on) for e in entries}
    visited: set[str] = set()
    in_stack: set[str] = set()
    errors: list[str] = []

    def _dfs(node: str, path: list[str]) -> None:
        visited.add(node)
        in_stack.add(node)
        for neighbour in adjacency.get(node, set()):
            if neighbour not in visited:
                _dfs(neighbour, path + [neighbour])
            elif neighbour in in_stack:
                cycle_str = " → ".join(path + [neighbour])
                errors.append(f"Dependency cycle detected: {cycle_str}")
        in_stack.discard(node)

    for entry in entries:
        if entry.name not in visited:
            _dfs(entry.name, [entry.name])

    return errors


def _topological_sort(adjacency: dict[str, frozenset[str]]) -> list[str]:
    """Kahn's algorithm for topological sorting.

    Parameters
    ----------
    adjacency:
        Mapping from node name to the frozenset of nodes it *depends on*
        (i.e. must come before it).

    Returns
    -------
    list[str]
        Topologically sorted node names (dependencies first).

    Raises
    ------
    ManifestValidationError
        If a cycle is detected.
    """
    in_degree: dict[str, int] = {n: 0 for n in adjacency}
    dependents: dict[str, list[str]] = {n: [] for n in adjacency}

    for node, deps in adjacency.items():
        for dep in deps:
            if dep in adjacency:
                in_degree[node] += 1
                dependents[dep].append(node)

    queue = [n for n, d in in_degree.items() if d == 0]
    queue.sort()  # deterministic output
    result: list[str] = []

    while queue:
        node = queue.pop(0)
        result.append(node)
        for dep_node in sorted(dependents.get(node, [])):
            in_degree[dep_node] -= 1
            if in_degree[dep_node] == 0:
                queue.append(dep_node)

    if len(result) != len(adjacency):
        cycle_nodes = sorted(set(adjacency) - set(result))
        raise ManifestValidationError(
            [f"Cycle detected involving nodes: {cycle_nodes}"]
        )

    return result


