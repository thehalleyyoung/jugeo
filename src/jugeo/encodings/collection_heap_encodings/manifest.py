"""
manifest — Package manifest for collection_heap_encodings.

Generated by the JuGeo copilot encoding pipeline.
theory2.tex Ch27: Exact Z3 encodings II: collections, finite maps, heap summaries,
alias partitions, interface abstractions.

Part of the JuGeo judgment-geometry framework.

This module provides a structured manifest that enumerates all encoding modules
within the collection_heap_encodings package, their declared dependencies, section
kinds, and capability flags.  It is intended to be the authoritative, machine-readable
description of this sub-package and is consumed by the JuGeo encoding pipeline, test
harnesses, and documentation generators.

Design notes
------------
* All manifest data is stored in frozen dataclasses and module-level ``Final``
  constants so that the manifest cannot be mutated at runtime.
* The ``build_manifest()`` factory combines the static section registry with
  live capability probing so that the returned manifest faithfully reflects the
  runtime environment.
* ``validate_manifest()`` performs a topological-consistency check, verifying
  that every ``depends_on`` edge refers to a known section and that the
  dependency graph is acyclic.
* ``_ManifestSerializer`` provides JSON round-trip and SMT-LIB2 comment-block
  serialisation for embedding manifests in solver input files.
"""

