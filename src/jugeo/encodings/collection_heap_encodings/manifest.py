class ManifestValidationError(Exception):
    """Raised when manifest validation detects an inconsistency.

    Attributes
    ----------
    errors:
        A list of human-readable error strings describing each individual
        inconsistency found during validation.  May contain more than one
        entry when multiple problems are detected in a single pass.

    Examples
    --------
    >>> raise ManifestValidationError(["missing section 'models'", "cycle: a -> b -> a"])
    Traceback (most recent call last):
        ...
    jugeo.encodings.collection_heap_encodings.manifest.ManifestValidationError: ...
    """

    def __init__(self, errors: list[str]) -> None:
        self.errors: list[str] = errors
        msg = "Manifest validation failed with {} error(s):\n{}".format(
            len(errors), "\n".join(f"  • {e}" for e in errors)
        )
        super().__init__(msg)

    def __repr__(self) -> str:  # noqa: D105
        return f"ManifestValidationError(errors={self.errors!r})"


