@dataclass(frozen=True, slots=True)
class SectionEntry:
    """Describes a single source file (section) within the package.

    Parameters
    ----------
    name:
        Logical section name, matching a key in ``SECTION_REGISTRY``.
    filename:
        Basename of the Python source file.
    kind:
        Role classification from ``SectionKind``.
    description:
        One-sentence human-readable description of the section's purpose.
    line_count_estimate:
        Approximate expected line count.  Used by documentation generators
        and the test runner to flag suspiciously short files.
    depends_on:
        Frozenset of section *names* (not filenames) that must be loaded
        before this section can be used.
    """

    name: str
    filename: str
    kind: SectionKind
    description: str
    line_count_estimate: int
    depends_on: frozenset[str]

    # ------------------------------------------------------------------
    # Public methods
    # ------------------------------------------------------------------

    def validate(self) -> list[str]:
        """Validate the internal consistency of this entry.

        Checks
        ------
        * ``name`` is a non-empty string.
        * ``filename`` ends with ``.py``.
        * ``line_count_estimate`` is positive.
        * ``depends_on`` does not contain ``name`` itself (self-loop).

        Returns
        -------
        list[str]
            A list of error messages.  Empty list means the entry is valid.
        """
        errors: list[str] = []
        if not self.name:
            errors.append("SectionEntry.name must be non-empty")
        if not self.filename.endswith(".py"):
            errors.append(
                f"SectionEntry({self.name!r}).filename must end with '.py', got {self.filename!r}"
            )
        if self.line_count_estimate <= 0:
            errors.append(
                f"SectionEntry({self.name!r}).line_count_estimate must be positive"
            )
        if self.name in self.depends_on:
            errors.append(
                f"SectionEntry({self.name!r}) has a self-dependency"
            )
        return errors

    def to_dict(self) -> dict[str, Any]:
        """Serialise to a plain Python dictionary.

        Returns
        -------
        dict[str, Any]
            JSON-serialisable representation of this entry.  The
            ``depends_on`` frozenset is converted to a sorted list.
        """
        return {
            "name": self.name,
            "filename": self.filename,
            "kind": self.kind.value,
            "description": self.description,
            "line_count_estimate": self.line_count_estimate,
            "depends_on": sorted(self.depends_on),
        }

    def summary(self) -> str:
        """Return a compact human-readable summary line.

        Returns
        -------
        str
            A single line of the form ``"<name> (<kind>) — <description>"``.
        """
        return f"{self.name} ({self.kind.value}) — {self.description}"


