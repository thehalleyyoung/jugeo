@dataclass(frozen=True, slots=True)
class CollectionHeapManifest:
    """Authoritative manifest for the ``collection_heap_encodings`` package.

    This frozen dataclass holds all declarative metadata about the package:
    which sections exist, what theorems they target, what capabilities are
    available, and when the manifest was created.

    Parameters
    ----------
    chapter_ref:
        Human-readable reference such as ``"theory2.tex Ch27"``.
    section_names:
        Ordered tuple of all logical section names.
    theorem_targets:
        Tuple of theorem identifiers targeted by this package.
    capability_flags:
        Feature availability flags (see ``CAPABILITY_FLAGS``).
    provenance:
        Bibliographic and toolchain provenance (see ``MANIFEST_SPEC_PROVENANCE``).
    created_at:
        UNIX timestamp (``time.time()``) when this manifest was built.
    manifest_id:
        UUID4 string uniquely identifying this manifest instance.
    """

    chapter_ref: str
    section_names: tuple[str, ...]
    theorem_targets: tuple[str, ...]
    capability_flags: Mapping[str, bool]
    provenance: Mapping[str, str | int]
    created_at: float
    manifest_id: str

    # ------------------------------------------------------------------
    # Section enumeration
    # ------------------------------------------------------------------

    def enumerate_sections(self) -> tuple[SectionEntry, ...]:
        """Return all ``SectionEntry`` objects for this manifest.

        The entries are taken from the module-level ``_SECTION_ENTRIES``
        constant, filtered to those whose names appear in
        ``self.section_names``.

        Returns
        -------
        tuple[SectionEntry, ...]
            Immutable tuple of section entries in the declared order.
        """
        name_set = set(self.section_names)
        entries = tuple(e for e in _SECTION_ENTRIES if e.name in name_set)
        _log.debug(
            "enumerate_sections: returning %d entries for manifest %s",
            len(entries),
            self.manifest_id,
        )
        return entries

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------

    def validate(self) -> list[str]:
        """Validate the manifest for internal consistency.

        Checks performed
        ----------------
        1. Every ``section_names`` entry maps to a ``SectionEntry`` in
           ``_SECTION_ENTRIES``.
        2. Every ``SectionEntry.depends_on`` reference is itself a known
           section name.
        3. The dependency graph is acyclic (no cycles).
        4. Every entry passes its own ``SectionEntry.validate()`` check.
        5. ``capability_flags`` contains at least the keys from
           ``CAPABILITY_FLAGS``.

        Returns
        -------
        list[str]
            Possibly empty list of error messages.
        """
        errors: list[str] = []
        known_names = {e.name for e in _SECTION_ENTRIES}

        # Check 1: all section_names are known
        for sname in self.section_names:
            if sname not in known_names:
                errors.append(f"Unknown section name: {sname!r}")

        # Check 2 & 4: per-entry validation + dependency references
        for entry in self.enumerate_sections():
            errors.extend(entry.validate())
            for dep in entry.depends_on:
                if dep not in known_names:
                    errors.append(
                        f"Section {entry.name!r} depends on unknown section {dep!r}"
                    )

        # Check 3: acyclicity via DFS
        cycle_errors = _detect_cycles(self.enumerate_sections())
        errors.extend(cycle_errors)

        # Check 5: capability flags completeness
        for flag in CAPABILITY_FLAGS:
            if flag not in self.capability_flags:
                errors.append(f"Missing capability flag: {flag!r}")

        _log.debug(
            "validate: found %d error(s) for manifest %s",
            len(errors),
            self.manifest_id,
        )
        return errors

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        """Serialise the manifest to a plain Python dictionary.

        Returns
        -------
        dict[str, Any]
            A JSON-serialisable dictionary capturing the full manifest state,
            including serialised section entries.
        """
        return {
            "manifest_id": self.manifest_id,
            "chapter_ref": self.chapter_ref,
            "module_version": MODULE_VERSION,
            "chapter_tag": CHAPTER_TAG,
            "section_names": list(self.section_names),
            "theorem_targets": list(self.theorem_targets),
            "capability_flags": dict(self.capability_flags),
            "provenance": dict(self.provenance),
            "created_at": self.created_at,
            "sections": [e.to_dict() for e in self.enumerate_sections()],
        }

    # ------------------------------------------------------------------
    # Human-readable summary
    # ------------------------------------------------------------------

    def summary(self) -> str:
        """Return a multi-line human-readable summary of the manifest.

        Returns
        -------
        str
            Formatted string suitable for printing to a terminal or
            embedding in a log message.
        """
        lines: list[str] = [
            f"CollectionHeapManifest [{self.manifest_id[:8]}]",
            f"  chapter_ref : {self.chapter_ref}",
            f"  version     : {MODULE_VERSION}",
            f"  sections    : {len(self.section_names)}",
            f"  theorems    : {len(self.theorem_targets)}",
            f"  created_at  : {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(self.created_at))}",
            "  capabilities:",
        ]
        for flag, value in sorted(self.capability_flags.items()):
            mark = "✓" if value else "✗"
            lines.append(f"    {mark} {flag}")
        lines.append("  sections:")
        for entry in self.enumerate_sections():
            lines.append(f"    • {entry.summary()}")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Lookup helpers
    # ------------------------------------------------------------------

    def find_section(self, name: str) -> SectionEntry | None:
        """Find a section entry by logical name.

        Parameters
        ----------
        name:
            Logical section name to look up.

        Returns
        -------
        SectionEntry | None
            The matching entry, or ``None`` if not found.
        """
        for entry in self.enumerate_sections():
            if entry.name == name:
                return entry
        _log.debug("find_section: %r not found in manifest %s", name, self.manifest_id)
        return None

    def sections_by_kind(self, kind: SectionKind) -> list[SectionEntry]:
        """Return all sections of a given ``SectionKind``.

        Parameters
        ----------
        kind:
            The ``SectionKind`` to filter by.

        Returns
        -------
        list[SectionEntry]
            Possibly empty list of entries with the requested kind.
        """
        result = [e for e in self.enumerate_sections() if e.kind == kind]
        _log.debug(
            "sections_by_kind(%s): %d result(s) in manifest %s",
            kind.value,
            len(result),
            self.manifest_id,
        )
        return result

    # ------------------------------------------------------------------
    # Topological ordering
    # ------------------------------------------------------------------

    def dependency_order(self) -> list[str]:
        """Return section names in a valid topological (dependency-first) order.

        This allows the build system to load or compile modules in the
        correct order so that no section is processed before its
        dependencies.

        Returns
        -------
        list[str]
            Section names sorted such that for every edge
            ``a → b`` (``b depends_on a``), ``a`` appears before ``b``.

        Raises
        ------
        ManifestValidationError
            If the dependency graph contains a cycle.
        """
        entries = self.enumerate_sections()
        adjacency: dict[str, frozenset[str]] = {e.name: e.depends_on for e in entries}
        order = _topological_sort(adjacency)
        _log.debug(
            "dependency_order: %d sections ordered for manifest %s",
            len(order),
            self.manifest_id,
        )
        return order


