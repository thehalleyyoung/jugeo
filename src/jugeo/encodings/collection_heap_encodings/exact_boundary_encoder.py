class BoundaryVerifier:
    """High-level verifier for boundary conditions.

    Wraps an :class:`ExactBoundaryEncoder` and provides higher-level
    verification operations including approximate checks with tolerance,
    violation finding, and tightening suggestions.
    """

    def __init__(
        self,
        encoder: ExactBoundaryEncoder | None = None,
    ) -> None:
        self.logger = logging.getLogger(__name__ + ".BoundaryVerifier")
        self._encoder = encoder if encoder is not None else ExactBoundaryEncoder()

    def verify_exact(
        self,
        condition: BoundaryCondition,
        session: Z3Session,
    ) -> Z3Result:
        """Verify that *condition* holds exactly (SAT check with negation).

        An exact boundary condition is valid iff both it and its negation
        are non-trivially constrained — i.e., the condition is satisfiable
        and the negation is also satisfiable (the boundary actually carves
        out a non-trivial region).

        Parameters
        ----------
        condition
            The exact boundary condition to verify.
        session
            An active Z3Session.

        Returns
        -------
        Z3Result
            SAT with a model means the exact boundary has a witness.
        """
        self.logger.info("Exact verification of condition %s", condition.condition_id[:8])
        return self._encoder.verify_boundary_condition(condition, session)

    def verify_approximate(
        self,
        condition: BoundaryCondition,
        session: Z3Session,
        tolerance: float = 0.01,
    ) -> Z3Result:
        """Verify an approximate boundary condition with a slack tolerance.

        The tolerance is used to generate a relaxed formula: we allow the
        boundary to be slightly imprecise by adding a slack variable whose
        magnitude is bounded by *tolerance*.

        Parameters
        ----------
        condition
            The approximate boundary condition.
        session
            An active Z3Session.
        tolerance
            Maximum allowed slack (default: 0.01 = 1%).

        Returns
        -------
        Z3Result
            Result of checking the relaxed formula.
        """
        slack_constraint = f"(<= slack_var {tolerance})"
        relaxed_formula = _conjoin_constraints([
            condition.formula_str,
            "(>= slack_var 0)",
            slack_constraint,
        ])
        self.logger.debug(
            "Approximate verification with tolerance=%.4f for %s",
            tolerance,
            condition.condition_id[:8],
        )
        try:
            return session.check(relaxed_formula)
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Approximate verification failed: %s", exc)
            return Z3Result(
                outcome=SolveOutcome.UNKNOWN,
                model=None,
                unsat_core=None,
                elapsed_ms=0.0,
                metadata={"error": str(exc), "tolerance": tolerance},
            )

    def find_boundary_violation(
        self,
        condition: BoundaryCondition,
        session: Z3Session,
    ) -> dict[str, Any] | None:
        """Attempt to find a concrete violation of *condition*.

        A violation is a concrete assignment of free variables that falsifies
        the boundary condition, i.e., a model of ``¬condition``.

        Parameters
        ----------
        condition
            The boundary condition to check for violations.
        session
            An active Z3Session.

        Returns
        -------
        dict[str, Any] | None
            A dictionary with ``"violation_formula"``, ``"model"``,
            ``"condition_id"``; or None if no violation was found.
        """
        negated = condition.negate()
        self.logger.debug(
            "Searching for boundary violation for %s", condition.condition_id[:8]
        )
        try:
            result = session.check(negated)
            if result.outcome is SolveOutcome.SAT:
                model_assignments = {}
                if result.model is not None:
                    try:
                        model_assignments = dict(result.model.assignments or {})
                    except Exception:  # noqa: BLE001
                        pass
                return {
                    "violation_formula": negated,
                    "model": model_assignments,
                    "condition_id": condition.condition_id,
                    "region_name": condition.region_name,
                }
            return None
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Violation search failed: %s", exc)
            return None

    def suggest_tightening(
        self,
        violation: dict[str, Any],
        session: Z3Session,
    ) -> BoundaryCondition:
        """Suggest a tighter boundary condition that rules out *violation*.

        Given a concrete violation dictionary (as returned by
        :meth:`find_boundary_violation`), synthesise an additional conjunct
        that excludes the violating assignment.

        Parameters
        ----------
        violation
            Violation dictionary from :meth:`find_boundary_violation`.
        session
            An active Z3Session.

        Returns
        -------
        BoundaryCondition
            A new approximate BoundaryCondition that excludes the violation.
        """
        model: dict[str, Any] = violation.get("model", {})
        exclusion_clauses: list[str] = []
        for var, val in model.items():
            exclusion_clauses.append(f"(not (= {var} {val}))")

        if not exclusion_clauses:
            # Fallback: negate the entire violation formula
            exclusion_clauses = [f"(not {violation['violation_formula']})"]

        tighter_formula = _conjoin_constraints(exclusion_clauses)
        region_name = f"tightened_{violation.get('region_name', 'unknown')}"
        condition_id = _make_condition_id(region_name, tighter_formula)

        suggestion = BoundaryCondition(
            formula_str=tighter_formula,
            kind=BoundaryKind.APPROXIMATE,
            region_name=region_name,
            law_name=None,
            condition_id=condition_id,
            created_at=time.time(),
        )
        self.logger.info(
            "Suggested tightening for region '%s': %s",
            violation.get("region_name", "?"),
            tighter_formula[:60],
        )
        return suggestion

    def summarize_verification(self, results: list[Z3Result]) -> str:
        """Return a textual summary of a list of Z3Results.

        Parameters
        ----------
        results
            A list of Z3Result objects from verification runs.

        Returns
        -------
        str
            Multi-line summary with counts and timing statistics.
        """
        if not results:
            return "No verification results."

        counts: dict[str, int] = defaultdict(int)
        total_ms = 0.0
        for r in results:
            counts[r.outcome.value] += 1
            total_ms += r.elapsed_ms if r.elapsed_ms else 0.0

        avg_ms = total_ms / len(results) if results else 0.0
        lines = [
            f"Verification Summary ({len(results)} checks):",
            f"  SAT    : {counts.get('sat', 0)}",
            f"  UNSAT  : {counts.get('unsat', 0)}",
            f"  UNKNOWN: {counts.get('unknown', 0)}",
            f"  TIMEOUT: {counts.get('timeout', 0)}",
            f"  Total time : {total_ms:.1f} ms",
            f"  Average    : {avg_ms:.1f} ms/check",
        ]
        return "\n".join(lines)


