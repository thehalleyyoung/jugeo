def encode_disjoint_regions(
    encoder: ExactBoundaryEncoder,
    region_a: str,
    region_b: str,
) -> BoundaryCondition:
    """Convenience wrapper: encode disjointness of two named regions.

    Parameters
    ----------
    encoder
        An active ExactBoundaryEncoder.
    region_a, region_b
        Names of the two regions to separate.

    Returns
    -------
    BoundaryCondition
        Exact boundary condition encoding disjointness.
    """
    formula = _disjoint_formula(region_a, region_b)
    region_name = f"disjoint_{region_a}_{region_b}"
    condition_id = _make_condition_id(region_name, formula)
    condition = BoundaryCondition(
        formula_str=formula,
        kind=BoundaryKind.EXACT,
        region_name=region_name,
        law_name=None,
        condition_id=condition_id,
        created_at=time.time(),
    )
    return condition


def batch_verify_laws(
    library: NonAliasingLawLibrary,
    session: Z3Session,
) -> dict[str, Z3Result]:
    """Verify all standard laws in *library* against *session*.

    Parameters
    ----------
    library
        The NonAliasingLawLibrary to verify.
    session
        An active Z3Session.

    Returns
    -------
    dict[str, Z3Result]
        Map from law name to its verification result.
    """
    results: dict[str, Z3Result] = {}
    for name, _ in library.get_all_laws():
        results[name] = library.verify_law(name, session)
    return results


