@dataclass(frozen=True, slots=True)
class BoundaryCondition:
    """Immutable record of a single boundary condition for a memory region.

    A BoundaryCondition bundles the SMT-LIB2 formula string with enough
    metadata to reconstruct its provenance, verify it independently, and
    combine it with other conditions.

    Fields
    ------
    formula_str
        The SMT-LIB2 formula as a string, ready for injection into a Z3
        session.  Must be a well-formed Boolean expression.
    kind
        The precision classification of this condition (see BoundaryKind).
    region_name
        Human-readable name of the memory region this condition constrains.
    law_name
        If this condition was derived from a named non-aliasing law, its
        name; otherwise None.
    condition_id
        Globally unique identifier for this condition, used for caching and
        dependency tracking.
    created_at
        Unix timestamp (seconds since epoch) at construction time.
    """

    formula_str: str
    kind: BoundaryKind
    region_name: str
    law_name: str | None
    condition_id: str
    created_at: float

    # ------------------------------------------------------------------
    # Predicate helpers
    # ------------------------------------------------------------------

    def is_exact(self) -> bool:
        """Return True iff this condition is classified as EXACT."""
        return self.kind is BoundaryKind.EXACT

    def to_z3_assertion(self) -> str:
        """Return the formula wrapped as an SMT-LIB2 assert statement.

        The result is suitable for direct inclusion in an SMT-LIB2 script
        or for passing to Z3Session.add_assertion().

        Returns
        -------
        str
            ``(assert <formula>)``
        """
        return f"(assert {self.formula_str})"

    def negate(self) -> str:
        """Return the SMT-LIB2 negation of this formula.

        Negation is used during unsat-core minimization: to check whether
        a sub-condition is redundant we check satisfiability of the
        negation of the remaining conditions.

        Returns
        -------
        str
            ``(not <formula>)``
        """
        return f"(not {self.formula_str})"

    def summary(self) -> str:
        """Return a short human-readable summary of this condition.

        Returns
        -------
        str
            A one-liner with kind, region, law (if any), and a truncated
            formula preview.
        """
        law_part = f", law={self.law_name}" if self.law_name else ""
        preview = self.formula_str[:60] + ("…" if len(self.formula_str) > 60 else "")
        return (
            f"BoundaryCondition(id={self.condition_id[:8]}, "
            f"kind={self.kind.value}, region='{self.region_name}'"
            f"{law_part}, formula='{preview}')"
        )


