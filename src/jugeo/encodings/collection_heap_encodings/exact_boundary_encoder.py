class BoundaryKind(str, Enum):
    """Classifies the precision of a boundary condition.

    Values
    ------
    EXACT
        The boundary formula characterises the memory region with no
        over- or under-approximation.  This is the strongest guarantee and
        is required for precision lemmas.
    APPROXIMATE
        The boundary formula may admit extra models; it is sound but not
        complete.  Used when an exact formula is too expensive to compute.
    MINIMAL
        The boundary formula is the weakest possible formula still entailed
        by the exact characterisation.  Useful for frame inference.
    MAXIMAL
        The boundary formula is the strongest possible formula implied by
        the available facts.  Used for conservative safety checks.
    UNKNOWN
        The precision of this boundary condition has not been determined.
        Treat as APPROXIMATE for safety.
    """

    EXACT = "exact"
    APPROXIMATE = "approximate"
    MINIMAL = "minimal"
    MAXIMAL = "maximal"
    UNKNOWN = "unknown"


class NonAliasingLawName(str, Enum):
    """Names for the canonical non-aliasing laws in the law library.

    Values
    ------
    STACK_HEAP
        Stack-allocated locations never alias heap-allocated locations.
        This relies on the disjointness of the stack and heap address ranges.
    FRESH_ALLOCATION
        A freshly allocated pointer is disjoint from all existing pointers
        in the current heap state.
    READ_ONLY
        Read-only memory locations may be aliased freely, but write targets
        must be disjoint from all other write targets in the same frame.
    SEPARATION
        The star-composition law: two heap predicates are separating iff
        their footprints are disjoint.
    FRAME_DISJOINT
        A frame predicate's footprint is disjoint from the modified region.
    NULL_DISJOINT
        The null pointer is disjoint from every validly dereferenceable
        location in the heap.
    """

    STACK_HEAP = "stack_heap"
    FRESH_ALLOCATION = "fresh_allocation"
    READ_ONLY = "read_only"
    SEPARATION = "separation"
    FRAME_DISJOINT = "frame_disjoint"
    NULL_DISJOINT = "null_disjoint"


