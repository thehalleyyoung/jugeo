class ExactBoundaryEncoder:
    """Encode exact boundary conditions for memory regions.

    ExactBoundaryEncoder is the primary API for constructing and verifying
    boundary conditions.  It works at the level of SMT-LIB2 formula strings
    so that it can operate with or without a live Z3 installation.

    Parameters
    ----------
    law_library
        An optional pre-built :class:`NonAliasingLawLibrary`.  If None, a
        fresh library is constructed.

    Attributes
    ----------
    logger
        Module logger.
    _boundary_cache
        Cache of previously computed BoundaryConditions keyed on
        condition_id.
    _law_library
        The non-aliasing law library used by this encoder.
    _stats
        Runtime statistics dictionary.
    """

    def __init__(
        self,
        law_library: NonAliasingLawLibrary | None = None,
    ) -> None:
        self.logger = logging.getLogger(__name__ + ".ExactBoundaryEncoder")
        self._boundary_cache: dict[str, BoundaryCondition] = {}
        self._law_library = law_library if law_library is not None else NonAliasingLawLibrary()
        self._stats: dict[str, int | float] = defaultdict(int)
        self._minimizer = _FormulaMinimizer()

    # ------------------------------------------------------------------
    # Core encoding methods
    # ------------------------------------------------------------------

    def encode_boundary(
        self,
        region: str,
        constraints: list[str],
        *,
        kind: BoundaryKind = BoundaryKind.EXACT,
    ) -> BoundaryCondition:
        """Build a boundary condition for *region* from *constraints*.

        The method conjoins all constraints into a single SMT-LIB2 formula,
        appends the region-membership assertions, and wraps the result in
        a :class:`BoundaryCondition`.

        Parameters
        ----------
        region
            Name of the memory region being constrained.
        constraints
            List of SMT-LIB2 Boolean expressions that together define the
            boundary.  Each expression may reference symbolic locations and
            region predicates.
        kind
            Precision classification for the result (default: EXACT).

        Returns
        -------
        BoundaryCondition
            The constructed boundary condition, cached on condition_id.

        Algorithm
        ---------
        1. Compute membership assertion: ``(in_region region anchor_point)``.
        2. Conjoin all constraints with the membership assertion.
        3. Build condition_id from (region, formula) hash.
        4. Return cached entry if already computed; otherwise construct and
           cache a new BoundaryCondition.
        """
        membership = _region_membership(region, "anchor_point")
        all_parts = [membership] + constraints
        formula = _conjoin_constraints(all_parts)

        condition_id = _make_condition_id(region, formula)
        if condition_id in self._boundary_cache:
            self._stats["cache_hits"] = int(self._stats["cache_hits"]) + 1
            return self._boundary_cache[condition_id]

        condition = BoundaryCondition(
            formula_str=formula,
            kind=kind,
            region_name=region,
            law_name=None,
            condition_id=condition_id,
            created_at=time.time(),
        )
        self._boundary_cache[condition_id] = condition
        self._stats["encode_boundary_calls"] = (
            int(self._stats["encode_boundary_calls"]) + 1
        )
        self.logger.debug("Encoded boundary for region '%s': %s", region, condition.summary())
        return condition

    def encode_non_aliasing_law(
        self,
        p1: str,
        p2: str,
        context: str,
    ) -> BoundaryCondition:
        """Build a non-aliasing boundary condition for pointers *p1* and *p2*.

        The resulting formula asserts that *p1* and *p2* point to different
        locations: ``(not (= p1 p2))``.  The *context* string is embedded in
        the condition's region_name for traceability.

        Parameters
        ----------
        p1
            Name of the first pointer symbol.
        p2
            Name of the second pointer symbol.
        context
            Human-readable description of the program point or rule that
            requires this non-aliasing constraint (e.g. ``"loop body"``,
            ``"function call site"``).

        Returns
        -------
        BoundaryCondition
            A BoundaryCondition with kind=EXACT encoding the disjointness.
        """
        formula = f"(not (= {p1} {p2}))"
        region_name = f"non_alias_{p1}_{p2}__{context.replace(' ', '_')}"
        condition_id = _make_condition_id(region_name, formula)

        if condition_id in self._boundary_cache:
            self._stats["cache_hits"] = int(self._stats["cache_hits"]) + 1
            return self._boundary_cache[condition_id]

        condition = BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name=region_name,
            law_name=None,
            condition_id=condition_id,
            created_at=time.time(),
        )
        self._boundary_cache[condition_id] = condition
        self._stats["non_aliasing_laws"] = int(self._stats["non_aliasing_laws"]) + 1
        self.logger.debug(
            "Encoded non-aliasing law for (%s, %s) in context '%s'", p1, p2, context
        )
        return condition

    def encode_ownership_transfer(
        self,
        src: str,
        dst: str,
        heap: HeapSummary,
    ) -> HeapSummary:
        """Transfer ownership of *src*'s points-to entries to *dst*.

        Produces a new :class:`HeapSummary` where every location that was
        owned by *src* is now owned by *dst*.  The original *heap* is not
        mutated.

        Parameters
        ----------
        src
            Source owner name whose points-to entries will be transferred.
        dst
            Destination owner name.
        heap
            The current heap summary.

        Returns
        -------
        HeapSummary
            Updated heap summary with ownership transferred.

        Algorithm
        ---------
        1. Collect all entries in ``heap.points_to_map`` whose key begins
           with *src*.
        2. For each such entry, create a new entry keyed by the same path
           with *src* replaced by *dst*.
        3. Remove the *src* entries and add the *dst* entries.
        4. Update the footprint to reflect the new ownership labels.
        """
        new_points_to: dict[str, Any] = {}

        for key, value in heap.points_to_map.items():
            if key.startswith(src):
                new_key = dst + key[len(src):]
                new_points_to[new_key] = value
                self.logger.debug(
                    "Transferring ownership: %s → %s (value=%r)", key, new_key, value
                )
            else:
                new_points_to[key] = value

        # Rebuild the footprint with the new key space
        new_footprint = frozenset(
            (dst + loc[len(src):] if loc.startswith(src) else loc)
            for loc in heap.footprint
        )

        new_heap = HeapSummary(
            summary_id=f"ht_{uuid.uuid4().hex[:8]}",
            points_to_map=new_points_to,
            footprint=new_footprint,
            alias_classes=heap.alias_classes,
            frame_condition=heap.frame_condition,
            is_empty=len(new_points_to) == 0,
            created_at=time.time(),
        )
        self._stats["ownership_transfers"] = int(self._stats["ownership_transfers"]) + 1
        return new_heap

    def verify_boundary_condition(
        self,
        condition: BoundaryCondition,
        session: Z3Session,
    ) -> Z3Result:
        """Check satisfiability of *condition* in *session*.

        Parameters
        ----------
        condition
            The BoundaryCondition whose formula will be checked.
        session
            An active Z3Session.

        Returns
        -------
        Z3Result
            SAT implies the condition is feasible; UNSAT implies the boundary
            is over-constrained (vacuously true and unusable); UNKNOWN
            indicates a timeout or incomplete reasoning.
        """
        self.logger.debug("Verifying boundary condition %s", condition.condition_id[:8])
        t0 = time.perf_counter()
        try:
            result = session.check(condition.formula_str)
            elapsed = (time.perf_counter() - t0) * 1000
            self.logger.debug(
                "Verification of %s: %s (%.1f ms)",
                condition.condition_id[:8],
                result.outcome.value,
                elapsed,
            )
            self._stats["verify_calls"] = int(self._stats["verify_calls"]) + 1
            return result
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Verification failed: %s", exc)
            return Z3Result(
                outcome=SolveOutcome.UNKNOWN,
                model=None,
                unsat_core=None,
                elapsed_ms=0.0,
                metadata={"error": str(exc), "condition_id": condition.condition_id},
            )

    def check_exact_frame(
        self,
        heap: HeapSummary,
        boundary: BoundaryCondition,
        session: Z3Session,
    ) -> Z3Result:
        """Verify that the frame condition in *heap* matches *boundary* exactly.

        The check is: ``boundary.formula ∧ ¬(footprint_formula)`` is UNSAT,
        i.e., the boundary entails the heap footprint and vice versa.

        Parameters
        ----------
        heap
            Heap summary whose frame_condition will be compared.
        boundary
            The exact boundary condition to verify against.
        session
            An active Z3Session.

        Returns
        -------
        Z3Result
            UNSAT means the frame matches exactly; SAT means a discrepancy
            was found (the model is a counterexample).
        """
        # Encode the heap's footprint as an SMT formula
        footprint_locs = sorted(heap.footprint)
        if footprint_locs:
            member_formulas = [_region_membership("frame_footprint", loc) for loc in footprint_locs]
            footprint_formula = _conjoin_constraints(member_formulas)
        else:
            footprint_formula = "false"  # empty footprint

        # The check: boundary does NOT entail the footprint → find a counterexample
        check_formula = _conjoin_constraints([
            boundary.formula_str,
            f"(not {footprint_formula})",
        ])
        self.logger.debug(
            "Checking exact frame for heap %s against boundary %s",
            heap.summary_id,
            boundary.condition_id[:8],
        )
        try:
            result = session.check(check_formula)
            self._stats["frame_checks"] = int(self._stats["frame_checks"]) + 1
            return result
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Frame check failed: %s", exc)
            return Z3Result(
                outcome=SolveOutcome.UNKNOWN,
                model=None,
                unsat_core=None,
                elapsed_ms=0.0,
                metadata={"error": str(exc)},
            )

    def encode_precision_lemma(
        self,
        heap: HeapSummary,
        predicate: str,
        session: Z3Session,
    ) -> BoundaryCondition:
        """Encode that *predicate* precisely determines the heap footprint.

        A predicate *P* is *precise* if whenever both *P(h1)* and *P(h2)*
        hold for heaps *h1* and *h2* that are sub-heaps of a common heap,
        then *h1 = h2*.  This method encodes this as:

        .. code-block:: smt

            (forall ((h1 Heap) (h2 Heap))
              (=> (and (P h1) (P h2) (sub_heap h1 h) (sub_heap h2 h))
                  (= (footprint h1) (footprint h2))))

        Parameters
        ----------
        heap
            The ambient heap context.
        predicate
            SMT-LIB2 expression for the predicate (a function from Heap
            to Bool, represented as a string with the heap variable ``h``
            free).
        session
            An active Z3Session (not used in formula construction, but
            available for future verification passes).

        Returns
        -------
        BoundaryCondition
            The precision lemma as a BoundaryCondition with kind=EXACT.
        """
        precision_formula = (
            "(forall ((h1 Heap) (h2 Heap)) "
            f"(=> (and ({predicate} h1) ({predicate} h2) "
            "(sub_heap h1 ambient_heap) (sub_heap h2 ambient_heap)) "
            "(= (footprint h1) (footprint h2))))"
        )
        region_name = f"precision_lemma_{predicate.replace(' ', '_')[:30]}"
        condition_id = _make_condition_id(region_name, precision_formula)

        condition = BoundaryCondition(
            formula_str=precision_formula,
            kind=BoundaryKind.EXACT,
            region_name=region_name,
            law_name=None,
            condition_id=condition_id,
            created_at=time.time(),
        )
        self._boundary_cache[condition_id] = condition
        self._stats["precision_lemmas"] = int(self._stats["precision_lemmas"]) + 1
        self.logger.debug("Encoded precision lemma for predicate '%s'", predicate[:40])
        return condition

    def compose_boundary_conditions(
        self,
        bc1: BoundaryCondition,
        bc2: BoundaryCondition,
    ) -> BoundaryCondition:
        """Return the conjunction of *bc1* and *bc2* as a new BoundaryCondition.

        The kind of the result is determined by the weaker of the two inputs:
        EXACT ∧ EXACT → EXACT, EXACT ∧ APPROXIMATE → APPROXIMATE, etc.

        Parameters
        ----------
        bc1
            First boundary condition.
        bc2
            Second boundary condition.

        Returns
        -------
        BoundaryCondition
            Conjunction of the two conditions.
        """
        _kind_order = {
            BoundaryKind.EXACT: 4,
            BoundaryKind.MAXIMAL: 3,
            BoundaryKind.MINIMAL: 2,
            BoundaryKind.APPROXIMATE: 1,
            BoundaryKind.UNKNOWN: 0,
        }
        # Result kind is the weaker of the two
        result_kind = (
            bc1.kind
            if _kind_order[bc1.kind] <= _kind_order[bc2.kind]
            else bc2.kind
        )

        combined_formula = _conjoin_constraints([bc1.formula_str, bc2.formula_str])
        region_name = f"composed_{bc1.region_name}_{bc2.region_name}"
        condition_id = _make_condition_id(region_name, combined_formula)

        result = BoundaryCondition(
            formula_str=combined_formula,
            kind=result_kind,
            region_name=region_name,
            law_name=None,
            condition_id=condition_id,
            created_at=time.time(),
        )
        self._boundary_cache[condition_id] = result
        self._stats["compose_calls"] = int(self._stats["compose_calls"]) + 1
        return result

    def extract_boundary_witnesses(
        self,
        session: Z3Session,
    ) -> list[dict[str, Any]]:
        """Extract concrete witness assignments from the current solver model.

        After a SAT result, the Z3 model provides concrete values for all
        free variables.  This method retrieves those assignments and packages
        them as a list of dictionaries suitable for inspection and logging.

        Parameters
        ----------
        session
            An active Z3Session with a SAT model available.

        Returns
        -------
        list[dict[str, Any]]
            Each element is a dict with keys ``"variable"``, ``"value"``,
            ``"sort"``.  Returns an empty list if no model is available.
        """
        self.logger.debug("Extracting boundary witnesses from session model")
        witnesses: list[dict[str, Any]] = []
        try:
            model_data = session.get_model()
            if model_data is None:
                return witnesses
            for var_name, value in (model_data.assignments or {}).items():
                witnesses.append({
                    "variable": var_name,
                    "value": value,
                    "sort": model_data.sorts.get(var_name, "unknown"),
                })
        except Exception as exc:  # noqa: BLE001
            self.logger.warning("Could not extract witnesses: %s", exc)
        self._stats["witness_extractions"] = int(self._stats["witness_extractions"]) + 1
        return witnesses

    def minimize_boundary(
        self,
        condition: BoundaryCondition,
        session: Z3Session,
    ) -> BoundaryCondition:
        """Remove redundant conjuncts from *condition* using unsat-core simulation.

        Delegates to :class:`_FormulaMinimizer`.  Returns a new
        BoundaryCondition with kind=MINIMAL and the reduced formula.

        Parameters
        ----------
        condition
            The boundary condition to minimize.
        session
            An active Z3Session used for satisfiability queries.

        Returns
        -------
        BoundaryCondition
            A new BoundaryCondition with a minimized formula and
            kind=MINIMAL.
        """
        self.logger.debug(
            "Minimizing boundary condition %s", condition.condition_id[:8]
        )
        minimal_formula = self._minimizer.minimize(condition.formula_str, session)

        region_name = f"minimal_{condition.region_name}"
        condition_id = _make_condition_id(region_name, minimal_formula)

        result = BoundaryCondition(
            formula_str=minimal_formula,
            kind=BoundaryKind.MINIMAL,
            region_name=region_name,
            law_name=condition.law_name,
            condition_id=condition_id,
            created_at=time.time(),
        )
        self._boundary_cache[condition_id] = result
        self._stats["minimize_calls"] = int(self._stats["minimize_calls"]) + 1
        original_len = len(condition.formula_str)
        reduced_len = len(minimal_formula)
        self.logger.info(
            "Minimized boundary: %d → %d chars (%.0f%% reduction)",
            original_len,
            reduced_len,
            100.0 * (1 - reduced_len / max(original_len, 1)),
        )
        return result

    def to_precision_formula(self, condition: BoundaryCondition) -> str:
        """Return a human-readable precision formula for *condition*.

        The precision formula expresses the condition in a style closer to
        mathematical notation, wrapping the SMT formula with metadata.

        Parameters
        ----------
        condition
            The boundary condition to describe.

        Returns
        -------
        str
            Multi-line string with region name, kind, law (if any), and
            the SMT formula.

        Example
        -------
        ::

            Precision formula for 'stack_heap_boundary' (EXACT):
              Law: stack_heap
              Formula: (and (not (= stack_base heap_base)) ...)
        """
        lines = [
            f"Precision formula for '{condition.region_name}' ({condition.kind.value.upper()}):",
        ]
        if condition.law_name:
            lines.append(f"  Law: {condition.law_name}")
        lines.append(f"  Condition-ID: {condition.condition_id}")
        lines.append(f"  Formula:")
        # Indent the formula for readability
        formula_lines = condition.formula_str.split(" ")
        chunk = []
        line_len = 0
        for token in formula_lines:
            if line_len + len(token) > 72:
                lines.append("    " + " ".join(chunk))
                chunk = [token]
                line_len = len(token)
            else:
                chunk.append(token)
                line_len += len(token) + 1
        if chunk:
            lines.append("    " + " ".join(chunk))
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Statistics and diagnostics
    # ------------------------------------------------------------------

    def get_stats(self) -> dict[str, Any]:
        """Return a snapshot of the encoder's runtime statistics."""
        return dict(self._stats)

    def cache_size(self) -> int:
        """Return the number of cached boundary conditions."""
        return len(self._boundary_cache)

    def clear_cache(self) -> None:
        """Evict all cached boundary conditions."""
        self._boundary_cache.clear()
        self.logger.debug("Boundary cache cleared")


