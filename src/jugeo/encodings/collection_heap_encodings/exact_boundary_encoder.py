def _make_condition_id(region: str, formula: str) -> str:
    """Derive a stable condition identifier from region name and formula."""
    digest = hashlib.sha256(f"{_ENCODER_VERSION}:{region}:{formula}".encode()).hexdigest()
    return f"bc_{digest[:16]}"


def _conjoin_constraints(constraints: list[str]) -> str:
    """Return the SMT-LIB2 conjunction of *constraints*.

    Parameters
    ----------
    constraints
        Non-empty list of Boolean SMT-LIB2 expressions.

    Returns
    -------
    str
        ``(and c1 c2 … cn)`` when len > 1, or the single element when
        len == 1, or ``true`` when the list is empty.

    Examples
    --------
    >>> _conjoin_constraints(["(= x 0)", "(> y 1)"])
    '(and (= x 0) (> y 1))'
    >>> _conjoin_constraints(["(= x 0)"])
    '(= x 0)'
    >>> _conjoin_constraints([])
    'true'
    """
    if not constraints:
        return "true"
    if len(constraints) == 1:
        return constraints[0]
    joined = " ".join(constraints)
    return f"(and {joined})"


def _region_membership(region: str, point: str) -> str:
    """Return the SMT-LIB2 formula asserting *point* is in *region*.

    This produces an uninterpreted predicate application of the form
    ``(in_region <region_id> <point>)``.  In a full model this predicate
    would be interpreted by the heap array theory; here we generate the
    formula string for later injection into a Z3 session.

    Parameters
    ----------
    region
        Symbolic region identifier (e.g. ``"r_stack"``, ``"r_heap"``).
    point
        Symbolic location (e.g. ``"p"`` or ``"addr_42"``).

    Returns
    -------
    str
        ``(in_region <region> <point>)``
    """
    safe_region = region.replace(" ", "_").replace("-", "_")
    return f"(in_region {safe_region} {point})"


def _disjoint_formula(region_a: str, region_b: str) -> str:
    """Return the SMT-LIB2 formula asserting two regions are disjoint."""
    return (
        f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
        f"(not (and (in_region {region_a} p) (in_region {region_b} p))))"
    )


def _subset_formula(region_a: str, region_b: str) -> str:
    """Return the SMT-LIB2 formula asserting region_a ⊆ region_b."""
    return (
        f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
        f"(=> (in_region {region_a} p) (in_region {region_b} p)))"
    )


def _equal_regions_formula(region_a: str, region_b: str) -> str:
    """Return the SMT-LIB2 formula asserting region_a = region_b (as sets)."""
    return (
        f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
        f"(= (in_region {region_a} p) (in_region {region_b} p)))"
    )


# ---------------------------------------------------------------------------
# _FormulaMinimizer — private helper
# ---------------------------------------------------------------------------


class _FormulaMinimizer:
    """Remove redundant conjuncts from an SMT-LIB2 conjunction.

    Strategy
    --------
    1. Parse the top-level conjunction into individual conjuncts.
    2. For each conjunct *c*, check whether the remaining conjunction implies
       *c* using Z3 (i.e. check unsatisfiability of
       ``(and remaining) ∧ (not c)``).
    3. If so, *c* is redundant and is removed from the set.
    4. Repeat until no further reductions are possible.

    This is an exact minimization under the assumption that the Z3 session
    can reliably answer the incremental satisfiability queries.  When Z3 is
    unavailable, the original formula is returned unchanged.
    """

    def __init__(self) -> None:
        self._logger = logging.getLogger(__name__ + "._FormulaMinimizer")

    def _parse_conjunction(self, formula: str) -> list[str]:
        """Split a top-level ``(and ...)`` into individual conjuncts."""
        formula = formula.strip()
        if formula.startswith("(and "):
            inner = formula[5:-1].strip()
            conjuncts: list[str] = []
            depth = 0
            start = 0
            for i, ch in enumerate(inner):
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                elif ch == " " and depth == 0:
                    token = inner[start:i].strip()
                    if token:
                        conjuncts.append(token)
                    start = i + 1
            last = inner[start:].strip()
            if last:
                conjuncts.append(last)
            return conjuncts
        return [formula]

    def minimize(self, formula: str, session: Z3Session) -> str:
        """Return a minimal equivalent sub-conjunction of *formula*.

        Parameters
        ----------
        formula
            SMT-LIB2 Boolean formula string.
        session
            Z3Session to use for satisfiability checks.

        Returns
        -------
        str
            A minimal conjunction equivalent to *formula*.
        """
        conjuncts = self._parse_conjunction(formula)
        if len(conjuncts) <= 1:
            return formula

        minimal: list[str] = list(conjuncts)
        changed = True
        while changed:
            changed = False
            for i in range(len(minimal) - 1, -1, -1):
                candidate = minimal[i]
                rest = minimal[:i] + minimal[i + 1:]
                if not rest:
                    continue
                rest_formula = _conjoin_constraints(rest)
                # Check if rest ⊨ candidate, i.e., (rest ∧ ¬candidate) is UNSAT
                check_formula = f"(and {rest_formula} (not {candidate}))"
                try:
                    result = session.check(check_formula)
                    if result.outcome is SolveOutcome.UNSAT:
                        self._logger.debug(
                            "Minimizer: removing redundant conjunct %s", candidate[:40]
                        )
                        minimal = rest
                        changed = True
                        break
                except Exception as exc:  # noqa: BLE001
                    self._logger.warning("Minimizer check failed: %s", exc)
        return _conjoin_constraints(minimal)


