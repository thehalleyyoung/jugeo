class NonAliasingLawLibrary:
    """Library of standard non-aliasing laws for memory safety.

    The library pre-computes BoundaryCondition objects for the six canonical
    non-aliasing laws used in separation-logic-based verification.  Custom
    laws can be added at runtime via :meth:`add_custom_law`.

    All laws are cached on first access.  The cache is keyed on the
    :class:`NonAliasingLawName` value so multiple encoders share the same
    BoundaryCondition instances.
    """

    def __init__(self) -> None:
        self.logger = logging.getLogger(__name__ + ".NonAliasingLawLibrary")
        self._laws: dict[str, BoundaryCondition] = {}
        self._build_standard_laws()

    def _build_standard_laws(self) -> None:
        """Eagerly construct all standard law BoundaryConditions."""
        self._laws[NonAliasingLawName.STACK_HEAP.value] = self.get_stack_heap_law()
        self._laws[NonAliasingLawName.FRESH_ALLOCATION.value] = (
            self.get_fresh_allocation_law()
        )
        self._laws[NonAliasingLawName.READ_ONLY.value] = self.get_read_only_law()
        self._laws[NonAliasingLawName.SEPARATION.value] = self.get_separation_law()
        self._laws[NonAliasingLawName.FRAME_DISJOINT.value] = (
            self.get_frame_disjoint_law()
        )
        self._laws[NonAliasingLawName.NULL_DISJOINT.value] = self.get_null_disjoint_law()

    # ------------------------------------------------------------------
    # Standard law constructors
    # ------------------------------------------------------------------

    def get_stack_heap_law(self) -> BoundaryCondition:
        """Stack pointers never alias heap pointers.

        The law encodes: for every location *p*, *p* cannot simultaneously
        reside in the stack region and the heap region.

        SMT formula
        -----------
        ``(not (= stack_base heap_base))`` together with a disjointness
        quantifier over all locations.
        """
        formula = _conjoin_constraints([
            f"(not (= {_STACK_BASE_SYMBOL} {_HEAP_BASE_SYMBOL}))",
            _disjoint_formula("stack_region", "heap_region"),
        ])
        return BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name="stack_heap_boundary",
            law_name=NonAliasingLawName.STACK_HEAP.value,
            condition_id=_make_condition_id("stack_heap_boundary", formula),
            created_at=time.time(),
        )

    def get_fresh_allocation_law(self) -> BoundaryCondition:
        """Freshly allocated location is disjoint from the existing heap.

        The fresh allocation law states that any pointer returned by
        ``alloc`` is outside the current heap footprint.  We encode this
        as disjointness between the fresh pointer's singleton region and
        the entire existing heap region.

        SMT formula
        -----------
        ::

            (forall ((p Loc))
              (=> (in_region heap_existing p) (not (= p fresh_ptr))))
        """
        formula = (
            f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
            f"(=> (in_region heap_existing p) (not (= p fresh_ptr))))"
        )
        return BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name="fresh_allocation_boundary",
            law_name=NonAliasingLawName.FRESH_ALLOCATION.value,
            condition_id=_make_condition_id("fresh_allocation_boundary", formula),
            created_at=time.time(),
        )

    def get_read_only_law(self) -> BoundaryCondition:
        """Write targets are disjoint from read-only regions.

        Read-only locations may be freely aliased, but any location that is
        a write target must not reside in the read-only region.

        SMT formula
        -----------
        ::

            (forall ((p Loc))
              (=> (in_region write_target p)
                  (not (in_region read_only_region p))))
        """
        formula = (
            f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
            f"(=> (in_region write_target p) "
            f"(not (in_region read_only_region p))))"
        )
        return BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name="read_only_boundary",
            law_name=NonAliasingLawName.READ_ONLY.value,
            condition_id=_make_condition_id("read_only_boundary", formula),
            created_at=time.time(),
        )

    def get_separation_law(self) -> BoundaryCondition:
        """Separation star requires disjoint footprints.

        For a star-composed predicate ``P * Q`` to hold on heap ``h``,
        the heap must be splittable into disjoint sub-heaps ``h1`` and
        ``h2`` such that ``P`` holds on ``h1`` and ``Q`` holds on ``h2``.

        SMT formula
        -----------
        ::

            (and
              (disjoint_regions footprint_P footprint_Q)
              (= (union footprint_P footprint_Q) full_footprint))
        """
        formula = _conjoin_constraints([
            _disjoint_formula("footprint_P", "footprint_Q"),
            (
                f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
                f"(= (in_region full_footprint p) "
                f"(or (in_region footprint_P p) (in_region footprint_Q p))))"
            ),
        ])
        return BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name="separation_star_boundary",
            law_name=NonAliasingLawName.SEPARATION.value,
            condition_id=_make_condition_id("separation_star_boundary", formula),
            created_at=time.time(),
        )

    def get_frame_disjoint_law(self) -> BoundaryCondition:
        """Frame footprint is disjoint from the modified region.

        The frame rule allows reasoning about unmodified parts of the heap.
        The frame predicate's footprint must not overlap with any location
        that the command may write.

        SMT formula
        -----------
        ::

            (forall ((p Loc))
              (not (and (in_region frame_footprint p)
                        (in_region modified_region p))))
        """
        formula = _disjoint_formula("frame_footprint", "modified_region")
        return BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name="frame_disjoint_boundary",
            law_name=NonAliasingLawName.FRAME_DISJOINT.value,
            condition_id=_make_condition_id("frame_disjoint_boundary", formula),
            created_at=time.time(),
        )

    def get_null_disjoint_law(self) -> BoundaryCondition:
        """Null pointer is disjoint from all valid heap locations.

        Any location that can be validly dereferenced must not be the null
        pointer.

        SMT formula
        -----------
        ::

            (forall ((p Loc))
              (=> (in_region valid_heap p) (not (= p null))))
        """
        formula = (
            f"(forall ((p {_DEFAULT_LOCATION_SORT})) "
            f"(=> (in_region valid_heap p) (not (= p {_NULL_POINTER_SYMBOL}))))"
        )
        return BoundaryCondition(
            formula_str=formula,
            kind=BoundaryKind.EXACT,
            region_name="null_disjoint_boundary",
            law_name=NonAliasingLawName.NULL_DISJOINT.value,
            condition_id=_make_condition_id("null_disjoint_boundary", formula),
            created_at=time.time(),
        )

    # ------------------------------------------------------------------
    # Query and management
    # ------------------------------------------------------------------

    def get_all_laws(self) -> list[tuple[str, BoundaryCondition]]:
        """Return all laws as a list of (name, condition) pairs."""
        return sorted(self._laws.items())

    def verify_law(self, name: str, session: Z3Session) -> Z3Result:
        """Check that the named law is satisfiable in *session*.

        Parameters
        ----------
        name
            Law name string (e.g. ``NonAliasingLawName.STACK_HEAP.value``).
        session
            An active Z3Session.

        Returns
        -------
        Z3Result
            The result of checking the law formula.

        Raises
        ------
        KeyError
            If *name* is not a known law.
        """
        condition = self._laws[name]
        self.logger.debug("Verifying law '%s'", name)
        try:
            return session.check(condition.formula_str)
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Law verification failed for '%s': %s", name, exc)
            return Z3Result(
                outcome=SolveOutcome.UNKNOWN,
                model=None,
                unsat_core=None,
                elapsed_ms=0.0,
                metadata={"error": str(exc)},
            )

    def add_custom_law(self, name: str, condition: BoundaryCondition) -> None:
        """Register a user-defined law under *name*.

        Parameters
        ----------
        name
            Unique identifier for the custom law.
        condition
            The BoundaryCondition representing the law.

        Raises
        ------
        ValueError
            If *name* already refers to an existing law.
        """
        if name in self._laws:
            raise ValueError(
                f"Law '{name}' already registered.  Use a unique name or "
                "remove the existing law first."
            )
        self._laws[name] = condition
        self.logger.info("Registered custom law '%s'", name)

    def law_count(self) -> int:
        """Return the number of laws currently registered."""
        return len(self._laws)

    def get_law(self, name: str) -> BoundaryCondition:
        """Return the named law, raising KeyError if absent."""
        return self._laws[name]


