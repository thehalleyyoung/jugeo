@dataclass(frozen=True, slots=True)
class MayAliasSet:
    """Conservative over-approximation of which references may alias.

    A pair (a, b) is in the may-alias set iff it has not been proven that
    a and b must-not-alias.  This is the default (sound, imprecise) result
    when proof obligations are not discharged.

    Attributes
    ----------
    set_id : str
        Unique identifier.
    coordinate : str
        Semantic coordinate.
    pairs : frozenset[frozenset[str]]
        All may-alias pairs.
    judgment : AliasJudgment
        The governing judgment.
    trust_tier : TrustTier
        Trust level of this approximation.
    is_precise : bool
        Whether this approximation is known to be exact.
    """

    set_id: str
    coordinate: str
    pairs: frozenset[frozenset[str]]
    judgment: AliasJudgment
    trust_tier: TrustTier = TrustTier.PROPOSAL
    is_precise: bool = False

    def contains(self, ref_a: str, ref_b: str) -> bool:
        return frozenset({ref_a, ref_b}) in self.pairs

    def num_pairs(self) -> int:
        return len(self.pairs)

    def all_references(self) -> frozenset[str]:
        return frozenset(r for pair in self.pairs for r in pair)

    def to_dict(self) -> dict[str, Any]:
        return {
            "set_id": self.set_id,
            "coordinate": self.coordinate,
            "num_pairs": len(self.pairs),
            "trust_tier": self.trust_tier.name,
            "is_precise": self.is_precise,
            "judgment": self.judgment.to_dict(),
        }


