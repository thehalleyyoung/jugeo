def generate_aliasing_obligations(
    reference_pairs: Sequence[tuple[str, str]],
    known_must_alias: Sequence[tuple[str, str]] | None = None,
    known_must_not_alias: Sequence[tuple[str, str]] | None = None,
    *,
    coordinate: str = "alias_obligations",
) -> AliasingObligation:
    """From a set of reference pairs, generate all aliasing obligations.

    Parameters
    ----------
    reference_pairs : Sequence[tuple[str, str]]
        All (ref_a, ref_b) pairs that must be analysed for aliasing.
    known_must_alias : Sequence[tuple[str, str]] or None
        Pairs known to must-alias (from program analysis).
    known_must_not_alias : Sequence[tuple[str, str]] or None
        Pairs known to must-not-alias (from separation logic).
    coordinate : str
        Semantic coordinate.

    Returns
    -------
    AliasingObligation
    """
    logger.debug(
        "generate_aliasing_obligations: %d pairs at %s",
        len(reference_pairs), coordinate,
    )
    obl = AliasingObligation(
        obligation_id=_stable_id("alias_obl", coordinate),
        coordinate=coordinate,
    )
    for ref_a, ref_b in (known_must_alias or []):
        try:
            obl.add_must_alias(ref_a, ref_b)
        except JuGeoError as exc:
            logger.warning("Skipping contradictory must-alias: %s", exc)

    for ref_a, ref_b in (known_must_not_alias or []):
        try:
            obl.add_disjointness(ref_a, ref_b)
        except JuGeoError as exc:
            logger.warning("Skipping contradictory must-not-alias: %s", exc)
    return obl


def check_may_alias(
    ref_a: str,
    ref_b: str,
    obligation: AliasingObligation,
    may_alias_set: MayAliasSet | None = None,
) -> bool:
    """Check whether ref_a and ref_b may alias.

    Returns True (conservative) unless a disjointness obligation or a
    MayAliasSet with is_precise=True proves they cannot alias.

    Parameters
    ----------
    ref_a : str
        First reference identifier.
    ref_b : str
        Second reference identifier.
    obligation : AliasingObligation
        The aliasing obligation workspace.
    may_alias_set : MayAliasSet or None
        Optional precise may-alias set; overrides conservative default.

    Returns
    -------
    bool
        True iff ref_a and ref_b may alias.
    """
    # Must-alias implies may-alias
    if obligation._must_alias_uf.same_class(ref_a, ref_b):
        return True
    # Must-not-alias implies cannot alias
    if frozenset({ref_a, ref_b}) in obligation._must_not_alias:
        return False
    # If a precise may-alias set is provided, consult it
    if may_alias_set is not None and may_alias_set.is_precise:
        return may_alias_set.contains(ref_a, ref_b)
    # Conservative: may alias
    return True


def discharge_alias_obligation(
    obligation: AliasingObligation,
    *,
    runtime_id_map: Mapping[str, int] | None = None,
) -> AliasGlobalSection | AliasDescentObstruction:
    """Attempt to discharge an aliasing obligation.

    Discharge NEVER raises — it returns either a resolution or an obstruction.

    Parameters
    ----------
    obligation : AliasingObligation
        The obligation to discharge.
    runtime_id_map : Mapping[str, int] or None
        Map from reference name to Python id() value.  If provided, used for
        runtime identity checks.

    Returns
    -------
    AliasGlobalSection | AliasDescentObstruction
    """
    logger.debug(
        "discharge_alias_obligation: id=%s", obligation.obligation_id
    )
    if not obligation.is_consistent():
        obs = AliasCechObstruction(
            coordinate=obligation.coordinate,
            cocycle_description="Must-alias and must-not-alias constraints are contradictory.",
            involved_refs=tuple(
                r for pair in obligation._must_not_alias for r in pair
            )[:10],
            trust_tier=TrustTier.PROOF_BACKED,
            is_coboundary=False,
            repair_suggestion="Review and resolve contradictory aliasing constraints.",
        )
        return AliasDescentObstruction(
            coordinate=obligation.coordinate,
            obstruction=obs,
            unresolved_pairs=tuple(obligation.disjointness_pairs()[:10]),
            diagnosis="Contradiction between must-alias and must-not-alias.",
            repair_hints=("review-aliasing-constraints", "add-separation-proof"),
        )

    # Runtime discharge: use id() equality
    unresolved: list[tuple[str, str]] = []
    if runtime_id_map is not None:
        for fs in obligation._must_not_alias:
            refs = sorted(fs)
            if len(refs) == 2:
                id_a = runtime_id_map.get(refs[0])
                id_b = runtime_id_map.get(refs[1])
                if id_a is not None and id_b is not None and id_a == id_b:
                    # Runtime says they ARE the same object, contradicting must-not-alias
                    unresolved.append((refs[0], refs[1]))

    if unresolved:
        obs = AliasCechObstruction(
            coordinate=obligation.coordinate,
            cocycle_description=(
                f"Runtime identity check failed for {len(unresolved)} must-not-alias pairs."
            ),
            involved_refs=tuple(r for pair in unresolved for r in pair)[:10],
            trust_tier=TrustTier.RUNTIME_WITNESSED,
            is_coboundary=False,
            repair_suggestion="Verify separation logic preconditions hold at this program point.",
        )
        return AliasDescentObstruction(
            coordinate=obligation.coordinate,
            obstruction=obs,
            unresolved_pairs=tuple(unresolved[:20]),
            diagnosis=f"{len(unresolved)} runtime alias contradictions detected.",
            repair_hints=("check-separation-preconditions",),
        )

    trust = TrustTier.RUNTIME_WITNESSED if runtime_id_map else TrustTier.REVIEWED
    jmt = _make_alias_judgment(
        coordinate=obligation.coordinate,
        phi="aliasing_obligation_discharged",
        carrier="alias_resolution",
        evidence=[f"obligation:{obligation.obligation_id}"],
        obligations=[],
        trust=trust,
        provenance={"obligation_id": obligation.obligation_id, "discharged_at": _now_iso()},
    )
    return AliasGlobalSection(
        coordinate=obligation.coordinate,
        resolved_classes=obligation.alias_classes(),
        proven_distinct_pairs=obligation.disjointness_pairs(),
        judgment=jmt,
    )


def build_proof_burden(obligation: AliasingObligation) -> AliasProofBurden:
    """Convert an AliasingObligation into a structured AliasProofBurden."""
    all_smt = obligation.emit_smt_obligations()
    alias_assertions = tuple(
        s for s in all_smt if s.startswith("(= ")
    )
    disjointness_assertions = tuple(
        s for s in all_smt if s.startswith("(not ")
    )
    jmt = _make_alias_judgment(
        coordinate=obligation.coordinate,
        phi="alias_proof_burden_generated",
        carrier="alias_proof_burden",
        evidence=[f"obligation:{obligation.obligation_id}"],
        obligations=list(alias_assertions) + list(disjointness_assertions),
        trust=TrustTier.PROPOSAL,
        provenance={"obligation_id": obligation.obligation_id},
    )
    return AliasProofBurden(
        burden_id=_stable_id("burden", obligation.obligation_id),
        obligation_id=obligation.obligation_id,
        alias_assertions=alias_assertions,
        disjointness_assertions=disjointness_assertions,
        judgment=jmt,
        discharge_result=DischargeResult.PENDING,
    )


