@dataclass
class AliasingObligation:
    """A collection of must-alias / must-not-alias constraints.

    This is the central mutable workspace for tracking aliasing relationships
    during heap analysis.  It maintains:
    * A union-find structure for must-alias equivalence classes.
    * A set of must-not-alias pairs (disjointness obligations).
    * A set of StalkerEquivalence witnesses.

    Design principle: state mutation is gated behind consistency checks.
    The builder pattern enables fluent chains:
        ``obl.add_must_alias("p", "q").add_disjointness("p", "r")``
    """

    obligation_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    coordinate: str = "alias_root"
    _must_alias_uf: _UnionFind = field(default_factory=_UnionFind, init=False, repr=False)
    _must_not_alias: set[frozenset[str]] = field(default_factory=set, init=False, repr=False)
    _stalker_equivalences: list[StalkerEquivalence] = field(default_factory=list, init=False, repr=False)
    _judgments: list[AliasJudgment] = field(default_factory=list, init=False, repr=False)
    _discharge_results: dict[str, DischargeResult] = field(default_factory=dict, init=False, repr=False)

    def add_must_alias(self, ref_a: str, ref_b: str) -> AliasingObligation:
        """Assert that ref_a and ref_b must alias.

        Raises JuGeoError if this contradicts an existing must-not-alias pair.
        """
        if frozenset({ref_a, ref_b}) in self._must_not_alias:
            raise_with_scope(
                "ALIAS_CONTRADICTION",
                message=f"Cannot add must-alias({ref_a}, {ref_b}): contradicts existing must-not-alias.",
                provenance={"ref_a": ref_a, "ref_b": ref_b, "obligation_id": self.obligation_id},
            )
        self._must_alias_uf.union(ref_a, ref_b)
        jmt = _make_alias_judgment(
            coordinate=f"{self.coordinate}.must_alias",
            phi=f"must_alias({ref_a},{ref_b})",
            carrier="alias_class",
            evidence=[f"assertion:must_alias({ref_a},{ref_b})"],
            obligations=[],
            trust=TrustTier.PROPOSAL,
            provenance={"ref_a": ref_a, "ref_b": ref_b},
        )
        self._judgments.append(jmt)
        return self

    def add_disjointness(self, ref_a: str, ref_b: str) -> AliasingObligation:
        """Assert that ref_a and ref_b must NOT alias.

        Raises JuGeoError if this contradicts an existing must-alias pair.
        """
        if self._must_alias_uf.same_class(ref_a, ref_b):
            raise_with_scope(
                "ALIAS_CONTRADICTION",
                message=f"Cannot add must-not-alias({ref_a}, {ref_b}): contradicts existing must-alias.",
                provenance={"ref_a": ref_a, "ref_b": ref_b, "obligation_id": self.obligation_id},
            )
        self._must_not_alias.add(frozenset({ref_a, ref_b}))
        jmt = _make_alias_judgment(
            coordinate=f"{self.coordinate}.disjoint",
            phi=f"must_not_alias({ref_a},{ref_b})",
            carrier="disjoint_pair",
            evidence=[f"assertion:must_not_alias({ref_a},{ref_b})"],
            obligations=[],
            trust=TrustTier.PROPOSAL,
            provenance={"ref_a": ref_a, "ref_b": ref_b},
        )
        self._judgments.append(jmt)
        return self

    def add_stalker_equivalence(self, equiv: StalkerEquivalence) -> AliasingObligation:
        """Record a stalk-level equivalence witness."""
        self._stalker_equivalences.append(equiv)
        return self

    def alias_classes(self) -> dict[str, list[str]]:
        """Return the current must-alias equivalence classes."""
        return self._must_alias_uf.classes()

    def disjointness_pairs(self) -> list[tuple[str, str]]:
        """Return all must-not-alias pairs."""
        return [(sorted(p)[0], sorted(p)[1]) for p in self._must_not_alias]

    def is_consistent(self) -> bool:
        """Check that must-alias and must-not-alias are not contradictory."""
        for fs in self._must_not_alias:
            refs = list(fs)
            if len(refs) == 2 and self._must_alias_uf.same_class(refs[0], refs[1]):
                return False
        return True

    def emit_smt_obligations(self) -> list[str]:
        """Emit all obligations as SMT-LIB2 assertion strings."""
        obligations: list[str] = []
        for rep, members in self.alias_classes().items():
            for m in members:
                if m != rep:
                    obligations.append(f"(= (heap-deref {rep}) (heap-deref {m}))")
        for ref_a, ref_b in self.disjointness_pairs():
            obligations.append(f"(not (= (heap-deref {ref_a}) (heap-deref {ref_b})))")
        return obligations

    def to_dict(self) -> dict[str, Any]:
        return {
            "obligation_id": self.obligation_id,
            "coordinate": self.coordinate,
            "alias_classes": self.alias_classes(),
            "disjointness_pairs": self.disjointness_pairs(),
            "num_stalker_equivalences": len(self._stalker_equivalences),
            "is_consistent": self.is_consistent(),
        }


