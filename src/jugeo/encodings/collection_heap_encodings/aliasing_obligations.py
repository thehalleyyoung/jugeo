"""Aliasing as shared sections: two references alias iff they restrict to the same stalk.

# copilot: collection-heap-encodings module 03 — aliasing obligations
# theory2.tex §27.12–§27.15: aliasing is modelled as shared stalks in the heap
# sheaf.  Two pointers p and q alias iff their restrictions to every open set U
# that contains both of their coordinates yield the same stalk value.

In the sheaf-theoretic heap model, *aliasing* is not a pointer equality check —
it is a property of the restriction maps.  Two references p and q **must-alias**
iff for every open U in the heap site, the restrictions res(p, U) and res(q, U)
are equal as stalks.  They **may-alias** iff there exists some U on which the
restrictions cannot be proven distinct.

This module implements:

* :class:`AliasingObligation` — a collection of must-alias / must-not-alias
  constraints, organised as a union-find structure.
* :class:`StalkerEquivalence` — a stalk-level equivalence record proving that
  two references restrict to the same stalk on some cover element.
* :class:`AliasProofBurden` — the set of proof burdens generated by an aliasing
  obligation, ready for discharge via solver or runtime.
* :class:`MayAliasSet` — a conservative over-approximation of which references
  may alias, used as the default when proofs are absent.

Public functions
----------------
:func:`generate_aliasing_obligations`
    From a heap graph and a set of reference pairs, generate all aliasing
    obligations that must be discharged.
:func:`check_may_alias`
    Check whether two references in a HeapSummary may alias.
:func:`discharge_alias_obligation`
    Attempt to discharge an aliasing obligation via local solver or runtime.

Theory invariants
-----------------
* Judgments are tuples ``(c, φ, A, E, O, B, T, Π)`` — NEVER booleans.
* Trust is an ordered algebra element — NEVER a float.
* TrustTier: PROPOSAL → REVIEWED → VERIFIED → RUNTIME_WITNESSED → PROOF_BACKED.
* Obstructions are Čech H¹ cohomology classes.
* Descent returns GlobalSection OR DescentObstruction — never raises.
* ``raise_with_scope(code, message=..., provenance=...)`` signature.
"""

