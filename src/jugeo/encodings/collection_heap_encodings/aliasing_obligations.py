@dataclass(frozen=True, slots=True)
class StalkerEquivalence:
    """A stalk-level equivalence witness proving two references restrict to the same stalk.

    Two references ``ref_a`` and ``ref_b`` restrict to the same stalk on a
    cover element ``U`` iff their restriction maps both yield the same value
    at every point in ``U``.

    Attributes
    ----------
    equivalence_id : str
        Unique identifier.
    ref_a : str
        Identifier of the first reference.
    ref_b : str
        Identifier of the second reference.
    cover_element : str
        The open set U on which equivalence was witnessed.
    kind : StalkerKind
        How the equivalence was established.
    stalk_value_repr : str
        Representation of the shared stalk value.
    judgment : AliasJudgment
        The governing judgment.
    """

    equivalence_id: str
    ref_a: str
    ref_b: str
    cover_element: str
    kind: StalkerKind
    stalk_value_repr: str
    judgment: AliasJudgment

    def to_smt_assertion(self) -> str:
        """Return the SMT-LIB2 assertion for this stalk equivalence."""
        return f"(= (heap-deref {self.ref_a}) (heap-deref {self.ref_b}))"

    def to_dict(self) -> dict[str, Any]:
        return {
            "equivalence_id": self.equivalence_id,
            "ref_a": self.ref_a,
            "ref_b": self.ref_b,
            "cover_element": self.cover_element,
            "kind": self.kind.value,
            "stalk_value_repr": self.stalk_value_repr,
            "judgment": self.judgment.to_dict(),
        }


# ---------------------------------------------------------------------------
# Union-find for alias classes
# ---------------------------------------------------------------------------

class _UnionFind:
    """A simple union-find (disjoint-set) structure for alias class tracking."""

    def __init__(self) -> None:
        self._parent: dict[str, str] = {}
        self._rank: dict[str, int] = {}

    def find(self, x: str) -> str:
        if x not in self._parent:
            self._parent[x] = x
            self._rank[x] = 0
        if self._parent[x] != x:
            self._parent[x] = self.find(self._parent[x])
        return self._parent[x]

    def union(self, x: str, y: str) -> bool:
        """Union the sets containing x and y.  Returns True if merged."""
        rx, ry = self.find(x), self.find(y)
        if rx == ry:
            return False
        if self._rank[rx] < self._rank[ry]:
            rx, ry = ry, rx
        self._parent[ry] = rx
        if self._rank[rx] == self._rank[ry]:
            self._rank[rx] += 1
        return True

    def same_class(self, x: str, y: str) -> bool:
        return self.find(x) == self.find(y)

    def classes(self) -> dict[str, list[str]]:
        """Return a dict mapping representative → members."""
        result: dict[str, list[str]] = defaultdict(list)
        for x in self._parent:
            result[self.find(x)].append(x)
        return dict(result)


