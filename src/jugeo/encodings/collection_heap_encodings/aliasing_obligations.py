@dataclass(frozen=True, slots=True)
class AliasProofBurden:
    """The set of proof burdens generated by an aliasing obligation.

    Each burden is an SMT-LIB2 assertion that must be discharged by
    a solver or runtime before the aliasing obligation is settled.

    Attributes
    ----------
    burden_id : str
        Unique identifier.
    obligation_id : str
        The AliasingObligation that generated this burden.
    alias_assertions : tuple[str, ...]
        SMT-LIB2 must-alias assertions.
    disjointness_assertions : tuple[str, ...]
        SMT-LIB2 must-not-alias assertions.
    judgment : AliasJudgment
        The governing judgment.
    discharge_result : DischargeResult
        The current discharge status.
    """

    burden_id: str
    obligation_id: str
    alias_assertions: tuple[str, ...]
    disjointness_assertions: tuple[str, ...]
    judgment: AliasJudgment
    discharge_result: DischargeResult = DischargeResult.PENDING

    def all_assertions(self) -> tuple[str, ...]:
        return self.alias_assertions + self.disjointness_assertions

    def is_discharged(self) -> bool:
        return self.discharge_result not in (
            DischargeResult.PENDING,
            DischargeResult.UNKNOWN,
            DischargeResult.FAILED_CONFLICTING_EVIDENCE,
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "burden_id": self.burden_id,
            "obligation_id": self.obligation_id,
            "num_alias_assertions": len(self.alias_assertions),
            "num_disjointness_assertions": len(self.disjointness_assertions),
            "discharge_result": self.discharge_result.value,
            "judgment": self.judgment.to_dict(),
        }


