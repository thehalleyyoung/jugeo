class ProofStatus(str, Enum):
    """Status of a proof attempt for a :class:`CollectionHeapTheorem`.

    UNVERIFIED
        The theorem has not yet been submitted to a solver.
    VERIFIED
        The solver returned SAT for the negation check (proof successful).
    FALSIFIED
        The solver found a counterexample (theorem is false in the encoding).
    TIMEOUT
        The solver did not return within the configured time limit.
    UNKNOWN
        The solver could not determine satisfiability (e.g., incomplete fragment).
    """

    UNVERIFIED = "unverified"
    VERIFIED = "verified"
    FALSIFIED = "falsified"
    TIMEOUT = "timeout"
    UNKNOWN = "unknown"


