class CollectionEncodingFaithfulnessTheorem(CollectionHeapTheorem):
    """Theorem 27.1 — Faithfulness of collection encoding.

    A list encoding is satisfiable iff the original list satisfies the
    element-type invariant: the Z3 encoding neither discards nor invents
    satisfying assignments relative to the original collection semantics.
    """

    def __init__(self) -> None:
        super().__init__("CollectionEncodingFaithfulness")

    @property
    def theorem_statement(self) -> str:
        return (
            "For all lists xs of type T, the Z3 encoding enc(xs) is SAT iff "
            "all elements of xs satisfy the T-invariant: "
            "SAT(enc(xs)) ↔ ∀ x ∈ xs. T-inv(x)."
        )

    @property
    def importance(self) -> str:
        return (
            "Ensures the encoding is not under- or over-approximating the original "
            "semantics: every satisfying assignment corresponds to a valid concrete "
            "collection and vice versa."
        )

    @property
    def category(self) -> TheoremCategory:
        return TheoremCategory.FAITHFULNESS

    def proof_obligation(self, session: Z3Session) -> list[ProofObligation]:
        """Return the faithfulness bi-implication as a proof obligation.

        We encode: ∀ x : T. T-inv(x) ↔ SAT(enc([x])).
        For the ground check we fix a concrete representative ``x0``.
        """
        obligation_str = (
            "(forall ((x Int)) "
            "  (= (>= x 0) "          # T-inv: non-negative integer
            "     (exists ((enc_x Int)) "
            "       (= enc_x x))))"   # enc([x]) satisfiable
        )
        return [
            ProofObligation(
                obligation_str=obligation_str,
                formula_kind="faithfulness",
                quantifier_depth=2,
                is_ground=False,
                obligation_id=str(uuid.uuid4()),
                created_at=time.time(),
            )
        ]

    def verify(self, session: Z3Session) -> Z3Result:
        obligations = self.proof_obligation(session)
        return self._run_negation_check(obligations, session)

    def counterexample(self, session: Z3Session) -> dict[str, Any] | None:
        result = self.verify(session)
        if result.outcome is SolveOutcome.SAT:
            return self._counterexample
        return None


