class CollectionHeapTheorem(abc.ABC):
    """Abstract base class for all Ch27 collection-heap theorems.

    Concrete sub-classes provide:
    - A formal ``theorem_statement`` string drawn from theory2.tex.
    - A ``category`` property indicating the verification dimension.
    - A ``proof_obligation`` method that produces Z3 formulae.
    - A ``verify`` method that discharges the obligation using a Z3Session.
    - A ``counterexample`` method that attempts to find a model falsifying the theorem.

    The base class tracks proof status, timing, and any discovered
    counterexample across calls to ``verify``.
    """

    def __init__(self, theorem_name: str = "") -> None:
        self.logger = logging.getLogger(f"{__name__}.{type(self).__name__}")
        self._proof_status: ProofStatus = ProofStatus.UNVERIFIED
        self._proof_time_ms: float = 0.0
        self._counterexample: dict[str, Any] | None = None
        self.theorem_name: str = theorem_name or type(self).__name__
        self.theorem_id: str = str(uuid.uuid4())

    # ------------------------------------------------------------------
    # Abstract interface
    # ------------------------------------------------------------------

    @property
    @abc.abstractmethod
    def theorem_statement(self) -> str:
        """Formal natural-language statement of the theorem (from theory2.tex)."""

    @property
    @abc.abstractmethod
    def importance(self) -> str:
        """Brief explanation of why this theorem matters for the encoding."""

    @property
    @abc.abstractmethod
    def category(self) -> TheoremCategory:
        """The verification category this theorem belongs to."""

    @abc.abstractmethod
    def proof_obligation(self, session: Z3Session) -> list[ProofObligation]:
        """Build the list of :class:`ProofObligation` objects for this theorem.

        Parameters
        ----------
        session:
            A Z3Session whose context can be used to create fresh sorts and
            constants for the obligation.

        Returns
        -------
        list[ProofObligation]
            One or more atomic proof obligations whose conjunction represents
            the theorem.
        """

    @abc.abstractmethod
    def verify(self, session: Z3Session) -> Z3Result:
        """Attempt to verify the theorem using *session*.

        Verification is done by negation: the obligation is negated and
        checked for unsatisfiability.  If the negation is UNSAT, the theorem
        is proved; if SAT, a counterexample is stored.

        Parameters
        ----------
        session:
            Active Z3Session.

        Returns
        -------
        Z3Result
            The result of the check.
        """

    @abc.abstractmethod
    def counterexample(self, session: Z3Session) -> dict[str, Any] | None:
        """Attempt to find a model that falsifies the theorem.

        Returns ``None`` if no counterexample exists (theorem holds) or if
        the solver is unable to determine satisfiability.

        Parameters
        ----------
        session:
            Active Z3Session.

        Returns
        -------
        dict[str, Any] | None
            A mapping from variable names to concrete values, or ``None``.
        """

    # ------------------------------------------------------------------
    # Concrete methods
    # ------------------------------------------------------------------

    def is_verified(self) -> bool:
        """Return True iff the theorem has been successfully verified."""
        return self._proof_status is ProofStatus.VERIFIED

    def status(self) -> ProofStatus:
        """Return the current proof status."""
        return self._proof_status

    def proof_time_ms(self) -> float:
        """Return the milliseconds spent on the most recent proof attempt."""
        return self._proof_time_ms

    def summary(self) -> str:
        """Return a multi-line human-readable summary of this theorem."""
        lines = [
            f"Theorem : {self.theorem_name}",
            f"ID      : {self.theorem_id[:8]}",
            f"Category: {self.category.value}",
            f"Status  : {self._proof_status.value}",
            f"Time    : {self._proof_time_ms:.2f} ms",
            f"Statement:",
            f"  {self.theorem_statement}",
            f"Importance:",
            f"  {self.importance}",
        ]
        if self._counterexample:
            lines.append("Counterexample:")
            for k, v in self._counterexample.items():
                lines.append(f"  {k} = {v!r}")
        return "\n".join(lines)

    def _build_negation_check(self, obligation_str: str) -> str:
        """Wrap the negation of *obligation_str* for a validity check.

        Returns the SMT-LIB2 assertion of ``(not obligation_str)``.
        """
        return f"(assert (not {obligation_str}))"

    def _extract_model(self, session: Z3Session) -> dict[str, Any]:
        """Extract variable assignments from the current Z3 model.

        Calls ``session.get_model()`` if available; returns an empty dict
        if no model is present.
        """
        try:
            model = session.get_model()
            if model is None:
                return {}
            return {str(decl): str(model[decl]) for decl in model.decls()}
        except Exception:  # noqa: BLE001
            return {}

    # ------------------------------------------------------------------
    # Internal shared verification helper
    # ------------------------------------------------------------------

    def _run_negation_check(
        self, obligations: list[ProofObligation], session: Z3Session
    ) -> Z3Result:
        """Check that the conjunction of negated obligations is UNSAT.

        If UNSAT → theorem is proved.  If SAT → counterexample found.
        """
        t0 = time.perf_counter()
        try:
            smt2_parts = ["(set-logic ALL)"]
            for obl in obligations:
                smt2_parts.append(obl.negate())
            smt2_parts.append("(check-sat)")
            smt2 = "\n".join(smt2_parts)
            result: Z3Result = session.check_smt2(smt2)
            elapsed = (time.perf_counter() - t0) * 1_000.0
            self._proof_time_ms = elapsed

            if result.outcome is SolveOutcome.UNSAT:
                self._proof_status = ProofStatus.VERIFIED
            elif result.outcome is SolveOutcome.SAT:
                self._proof_status = ProofStatus.FALSIFIED
                self._counterexample = self._extract_model(session)
            else:
                self._proof_status = ProofStatus.UNKNOWN

            self.logger.info(
                "theorem=%r status=%s time=%.2fms",
                self.theorem_name, self._proof_status.value, elapsed,
            )
            return result
        except Exception as exc:  # noqa: BLE001
            self.logger.error("Error checking theorem %r: %s", self.theorem_name, exc)
            self._proof_status = ProofStatus.UNKNOWN
            return Z3Result(outcome=SolveOutcome.UNKNOWN, model=None, reason=str(exc))


