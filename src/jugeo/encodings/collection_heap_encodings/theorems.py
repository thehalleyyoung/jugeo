def verify_all_theorems(session: Z3Session) -> dict[str, Z3Result]:
    """Convenience function: verify all theorems in the default suite.

    Creates fresh theorem instances (so proof status starts as UNVERIFIED)
    and discharges them against *session*.

    Parameters
    ----------
    session:
        Active Z3Session.

    Returns
    -------
    dict[str, Z3Result]
        Mapping from theorem name to verification result.

    Example
    -------
    .. code-block:: python

        from jugeo.solver.z3_session import Z3Session
        from jugeo.encodings.collection_heap_encodings.theorems import verify_all_theorems

        results = verify_all_theorems(Z3Session())
        for name, result in results.items():
            print(f"{name}: {result.outcome.value}")
    """
    suite = TheoremSuite.default_suite()
    return suite.verify_all(session)


