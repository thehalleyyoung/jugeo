class FrameRuleAdmissibilityTheorem(CollectionHeapTheorem):
    """Theorem 27.4 — Admissibility of the frame rule.

    The frame rule ``{P} C {Q} ⟹ {P ∗ R} C {Q ∗ R}`` is admissible for
    all R disjoint from the modification footprint of command C.
    This theorem is central to the modularity of separation logic.
    """

    def __init__(self) -> None:
        super().__init__("FrameRuleAdmissibility")

    @property
    def theorem_statement(self) -> str:
        return (
            "For all commands C and predicates P, Q, R, if {P} C {Q} is derivable "
            "and R is disjoint from modified(C), then {P ∗ R} C {Q ∗ R} is also "
            "derivable.  The frame rule is admissible in the encoding."
        )

    @property
    def importance(self) -> str:
        return (
            "The frame rule is fundamental to modular separation logic reasoning: "
            "it permits local proofs to be lifted to global contexts without "
            "re-verifying the entire program state."
        )

    @property
    def category(self) -> TheoremCategory:
        return TheoremCategory.ADMISSIBILITY

    def proof_obligation(self, session: Z3Session) -> list[ProofObligation]:
        """Encode the frame rule as a validity obligation.

        Simplified encoding: if P ∧ Q holds and R is over a disjoint set of
        locations, then (P ∧ R) ∧ (Q ∧ R) — the conjunction lifts.
        """
        # Ground encoding: P(x), Q(x), R(y), x ≠ y → (P(x) ∧ R(y)) ∧ (Q(x) ∧ R(y))
