class TheoremCategory(str, Enum):
    """Categorical classification of proof obligations in the JuGeo framework.

    Categories correspond to the standard correctness dimensions of an encoding:

    SOUNDNESS
        Every formula derivable in the encoding is valid in the semantics.
    COMPLETENESS
        Every semantically valid formula is derivable in the encoding.
    PRECISION
        Predicates that uniquely determine their footprint compose precisely.
    FAITHFULNESS
        The encoding neither over- nor under-approximates the original semantics.
    CONSISTENCY
        The axiom set is jointly satisfiable (no contradiction).
    ADMISSIBILITY
        Inference rules preserve the invariants of the judgment system.
    TOTALITY
        Functions are defined on all elements of their declared domain.
    CORRECTNESS
        Implementations conform to their abstract specifications.
    """

    SOUNDNESS = "soundness"
    COMPLETENESS = "completeness"
    PRECISION = "precision"
    FAITHFULNESS = "faithfulness"
    CONSISTENCY = "consistency"
    ADMISSIBILITY = "admissibility"
    TOTALITY = "totality"
    CORRECTNESS = "correctness"


