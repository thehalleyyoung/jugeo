@dataclass(slots=True)
class ProofObligation:
    """A single atomic proof obligation expressed as an SMT-LIB2 assertion.

    Attributes
    ----------
    obligation_str:
        The SMT-LIB2 expression (without the ``assert`` wrapper) representing
        the formula to be proved.
    formula_kind:
        Descriptive kind tag (e.g. ``"invariant"``, ``"separation"``,
        ``"disjointness"``).
    quantifier_depth:
        The nesting depth of universal/existential quantifiers in the formula.
        0 means the formula is quantifier-free.
    is_ground:
        True iff the formula contains no free variables.
    obligation_id:
        Stable unique identifier for this obligation (UUID4 string).
    created_at:
        Unix timestamp (seconds) at which this obligation was constructed.
    """

    obligation_str: str
    formula_kind: str
    quantifier_depth: int
    is_ground: bool
    obligation_id: str
    created_at: float

    def to_smt2_assertion(self) -> str:
        """Wrap *obligation_str* in an SMT-LIB2 ``assert`` form."""
        return f"(assert {self.obligation_str})"

    def negate(self) -> str:
        """Return the SMT-LIB2 assertion of the *negation* of this obligation.

        Used to check validity: the obligation holds iff its negation is UNSAT.
        """
        return f"(assert (not {self.obligation_str}))"

    def summary(self) -> str:
        """One-line human-readable summary of this obligation."""
        truncated = self.obligation_str[:80] + ("…" if len(self.obligation_str) > 80 else "")
        return (
            f"ProofObligation[{self.obligation_id[:8]}] "
            f"kind={self.formula_kind} "
            f"qdepth={self.quantifier_depth} "
            f"ground={self.is_ground}: {truncated}"
        )


