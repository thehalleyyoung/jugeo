class TheoremSuite:
    """A named collection of :class:`CollectionHeapTheorem` instances.

    Theorems can be added individually or loaded from the default suite.
    The suite provides batch verification and reporting utilities.

    Example
    -------
    .. code-block:: python

        suite = TheoremSuite.default_suite()
        results = suite.verify_all(z3_session)
        failures = suite.find_failures(results)
        print(suite.summary())
    """

    def __init__(self, suite_name: str = "default") -> None:
        self._theorems: list[CollectionHeapTheorem] = []
        self.suite_name = suite_name
        self.suite_id = str(uuid.uuid4())
        self.logger = logging.getLogger(f"{__name__}.{type(self).__name__}")

    # ------------------------------------------------------------------
    # Mutation
    # ------------------------------------------------------------------

    def add_theorem(self, theorem: CollectionHeapTheorem) -> None:
        """Append *theorem* to the suite.

        Parameters
        ----------
        theorem:
            Any :class:`CollectionHeapTheorem` instance.
        """
        self._theorems.append(theorem)
        self.logger.debug(
            "suite=%r added theorem %r (total=%d)",
            self.suite_name, theorem.theorem_name, len(self._theorems),
        )

    # ------------------------------------------------------------------
    # Verification
    # ------------------------------------------------------------------

    def verify_all(self, session: Z3Session) -> dict[str, Z3Result]:
        """Verify every theorem in the suite against *session*.

        Parameters
        ----------
        session:
            Active Z3Session shared across all checks.

        Returns
        -------
        dict[str, Z3Result]
            Mapping from theorem name to its Z3Result.
        """
        results: dict[str, Z3Result] = {}
        self.logger.info(
            "suite=%r verifying %d theorems", self.suite_name, len(self._theorems)
        )
        for theorem in self._theorems:
            self.logger.debug("Verifying %r …", theorem.theorem_name)
            results[theorem.theorem_name] = theorem.verify(session)
        return results

    def find_failures(self, results: dict[str, Z3Result]) -> list[str]:
        """Return the names of theorems whose Z3Result is not UNSAT (not proved).

        A theorem is considered a failure if its negation check returned SAT
        (counterexample found) or UNKNOWN.

        Parameters
        ----------
        results:
            Output of :meth:`verify_all`.

        Returns
        -------
        list[str]
            Names of failed theorems.
        """
        failures = []
        for name, result in results.items():
            if result is None or result.outcome is not SolveOutcome.UNSAT:
                failures.append(name)
        return failures

    def summary(self) -> str:
        """Return a multi-line summary of the suite and its theorem statuses."""
        lines = [
            f"TheoremSuite: {self.suite_name} [{self.suite_id[:8]}]",
            f"  Theorems: {len(self._theorems)}",
        ]
        for theorem in self._theorems:
            status_str = theorem.status().value
            lines.append(
                f"  [{status_str:>10}] {theorem.theorem_name} "
                f"({theorem.category.value})"
            )
        verified = sum(1 for t in self._theorems if t.is_verified())
        lines.append(f"  Verified: {verified}/{len(self._theorems)}")
        return "\n".join(lines)

    def theorem_names(self) -> list[str]:
        """Return a list of all theorem names in the suite (in insertion order)."""
        return [t.theorem_name for t in self._theorems]

    def get_theorem(self, name: str) -> CollectionHeapTheorem | None:
        """Look up a theorem by its ``theorem_name`` attribute.

        Returns ``None`` if no theorem with that name exists.
        """
        for t in self._theorems:
            if t.theorem_name == name:
                return t
        return None

    # ------------------------------------------------------------------
    # Class-level factory
    # ------------------------------------------------------------------

    @classmethod
    def default_suite(cls) -> TheoremSuite:
        """Create a :class:`TheoremSuite` containing all nine standard theorems.

        The suite is populated with one instance of each theorem class defined
        in this module.

        Returns
        -------
        TheoremSuite
            Suite with all nine theorems pre-added.
        """
        suite = cls(suite_name="ch27_default")
        for theorem_cls in ALL_THEOREM_CLASSES:
            suite.add_theorem(theorem_cls())
        suite.logger.info(
            "Default suite created with %d theorems", len(suite._theorems)
        )
        return suite


