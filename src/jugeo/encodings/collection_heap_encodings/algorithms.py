class BoundaryConditionMinimization(CollectionHeapAlgorithm):
    """Minimize a set of boundary conditions using unsat-core simulation.

    Given a list of formula strings, attempts to find the smallest subset
    that preserves the implication of the full set.  Uses a greedy
    backwards-elimination strategy.

    Parameters
    ----------
    session
        Optional Z3Session for implication checks.
    max_iterations
        Maximum elimination attempts.
    timeout_seconds
        Wall-clock timeout.
    """

    def __init__(
        self,
        session: Z3Session | None = None,
        max_iterations: int = _DEFAULT_MAX_ITERATIONS,
        timeout_seconds: float = _DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        super().__init__(max_iterations=max_iterations, timeout_seconds=timeout_seconds)
        self._formula_set: list[str] = []
        self._current_minimal: list[str] = []
        self._session = session
        self._elimination_idx: int = 0

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Run boundary condition minimization.

        Parameters
        ----------
        inputs
            Dictionary with key ``"conditions"``: list[str] of SMT-LIB2
            Boolean formula strings.

        Returns
        -------
        AlgorithmResult
            result is a list[str] of the minimal subset of formulas.
        """
        self._start_time = time.perf_counter()
        self._iteration_count = 0

        conditions: list[str] = inputs.get("conditions", [])
        if not conditions:
            return AlgorithmResult(
                status=AlgorithmStatus.CONVERGED,
                iterations=0,
                wall_time_ms=self.elapsed_ms(),
                result=[],
                error_message=None,
                metadata={"original_count": 0, "minimal_count": 0},
            )

        self._formula_set = list(conditions)
        self._current_minimal = list(conditions)
        self._elimination_idx = len(self._current_minimal) - 1

        self.logger.info(
            "Starting boundary minimization: %d conditions", len(conditions)
        )

        status, iters = self._run_iteration_loop()

        return AlgorithmResult(
            status=status,
            iterations=iters,
            wall_time_ms=self.elapsed_ms(),
            result=list(self._current_minimal),
            error_message=None,
            metadata={
                "original_count": len(conditions),
                "minimal_count": len(self._current_minimal),
                "reduction_pct": (
                    100.0 * (1 - len(self._current_minimal) / max(len(conditions), 1))
                ),
            },
        )

    def step(self) -> bool:
        """Attempt to remove one condition from the current minimal set.

        Returns
        -------
        bool
            True if all positions have been tried (converged).
        """
        if self._elimination_idx < 0:
            return True

        removed = self._try_remove_conjunct(self._elimination_idx)
        if removed:
            # Don't decrement — the list shrank, so the same index now points
            # to the next element
            self._elimination_idx = min(
                self._elimination_idx, len(self._current_minimal) - 1
            )
        else:
            self._elimination_idx -= 1

        return self._elimination_idx < 0

    def is_converged(self) -> bool:
        """Return True when the elimination scan is complete."""
        return self._elimination_idx < 0

    def summarize(self) -> str:
        """Return a human-readable description of the minimization state."""
        return (
            f"BoundaryConditionMinimization("
            f"status={self._status.value}, "
            f"original={len(self._formula_set)}, "
            f"current_minimal={len(self._current_minimal)}, "
            f"idx={self._elimination_idx})"
        )

    def _try_remove_conjunct(self, idx: int) -> bool:
        """Attempt to remove the condition at *idx* from the minimal set.

        The condition at *idx* is redundant iff the remaining conditions
        logically imply it.  We check this by verifying that
        ``(remaining_conditions ∧ ¬condition[idx])`` is UNSAT.

        Parameters
        ----------
        idx
            Index into *_current_minimal* to attempt removal.

        Returns
        -------
        bool
            True if the condition was removed (it was redundant).
        """
        if idx < 0 or idx >= len(self._current_minimal):
            return False

        candidate = self._current_minimal[idx]
        rest = self._current_minimal[:idx] + self._current_minimal[idx + 1:]

        if not rest:
            return False

        is_redundant = self._verify_implication(rest, self._formula_set)
        if is_redundant:
            self._current_minimal = rest
            self.logger.debug(
                "Removed redundant condition [%d]: %s", idx, candidate[:50]
            )
            return True
        return False

    def _verify_implication(
        self,
        subset: list[str],
        full: list[str],  # noqa: ARG002 — kept for API completeness
    ) -> bool:
        """Check whether *subset* implies the full conjunction.

        Parameters
        ----------
        subset
            Candidate minimal subset of formulas.
        full
            Original full set (unused in heuristic mode).

        Returns
        -------
        bool
            True if *subset* implies the full set (i.e., the removed formula
            is redundant).
        """
        if self._session is None:
            # Heuristic: assume the condition is not redundant (conservative)
            return False

        if not subset:
            return False

        subset_formula = "(and " + " ".join(subset) + ")" if len(subset) > 1 else subset[0]
        removed_conditions = [c for c in self._formula_set if c not in subset]
        if not removed_conditions:
            return True

        for removed in removed_conditions:
            # Check: subset ∧ ¬removed → UNSAT means subset ⊨ removed
            check_formula = f"(and {subset_formula} (not {removed}))"
            try:
                result = self._session.check(check_formula)
                if result.outcome is not SolveOutcome.UNSAT:
                    return False  # Could not prove implication for this condition
            except Exception as exc:  # noqa: BLE001
                self.logger.warning("Implication check failed: %s", exc)
                return False
        return True

    def get_minimal_set(self) -> list[str]:
        """Return the current minimal set of conditions."""
        return list(self._current_minimal)


