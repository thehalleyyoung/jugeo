class AlgorithmStatus(str, Enum):
    """Lifecycle status of a :class:`CollectionHeapAlgorithm` run.

    Values
    ------
    NOT_STARTED
        The algorithm has been constructed but :meth:`run` has not been
        called yet.
    RUNNING
        The algorithm is actively executing (iterating or waiting for
        solver responses).
    CONVERGED
        The fixed-point or termination criterion was reached successfully.
    TIMEOUT
        Execution was halted because the wall-clock limit was exceeded.
    ERROR
        An unrecoverable error occurred during execution.  The error
        message is stored in :attr:`AlgorithmResult.error_message`.
    PARTIAL
        Execution terminated before convergence, but partial results are
        available (e.g., the worklist was partially drained).
    """

    NOT_STARTED = "not_started"
    RUNNING = "running"
    CONVERGED = "converged"
    TIMEOUT = "timeout"
    ERROR = "error"
    PARTIAL = "partial"


# ---------------------------------------------------------------------------
# AlgorithmResult value object
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class AlgorithmResult:
    """Immutable record of a completed algorithm run.

    Fields
    ------
    status
        Final lifecycle status.
    iterations
        Number of :meth:`step` calls executed.
    wall_time_ms
        Elapsed wall-clock time in milliseconds from the first call to
        :meth:`run` until termination.
    result
        Algorithm-specific output.  Type varies by algorithm subclass.
    error_message
        Human-readable error description when ``status == ERROR``, else
        None.
    metadata
        Arbitrary key-value pairs for diagnostics, timing breakdowns, and
        intermediate state.
    """

    status: AlgorithmStatus
    iterations: int
    wall_time_ms: float
    result: Any
    error_message: str | None
    metadata: dict[str, Any]

    def is_success(self) -> bool:
        """Return True iff the algorithm converged without errors."""
        return self.status is AlgorithmStatus.CONVERGED

    def summary(self) -> str:
        """Return a compact human-readable summary of this result.

        Returns
        -------
        str
            One-liner with status, iterations, timing, and error (if any).

        Example
        -------
        ``AlgorithmResult(CONVERGED, 17 iters, 124.3 ms)``
        """
        parts = [
            f"AlgorithmResult({self.status.value.upper()}",
            f"{self.iterations} iters",
            f"{self.wall_time_ms:.1f} ms",
        ]
        if self.error_message:
            parts.append(f"error='{self.error_message[:40]}'")
        return ", ".join(parts) + ")"


