class FixedPointAliasAnalysis(CollectionHeapAlgorithm):
    """Fixed-point alias analysis using constraint propagation.

    Maintains a set of alias facts (pairs of pointer names that are known
    to alias) and a worklist of pairs to process.  Propagation is done by
    transitivity: if *a* aliases *b* and *b* aliases *c*, then *a* aliases
    *c*.

    When a Z3 session is provided, additional Z3-level constraints can be
    checked during propagation to prune spurious alias pairs.

    Parameters
    ----------
    session
        Optional Z3Session for constraint-based pruning.
    max_iterations
        Hard cap on worklist steps.
    timeout_seconds
        Wall-clock timeout.
    """

    def __init__(
        self,
        session: Z3Session | None = None,
        max_iterations: int = _DEFAULT_MAX_ITERATIONS,
        timeout_seconds: float = _DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        super().__init__(max_iterations=max_iterations, timeout_seconds=timeout_seconds)
        self._pointer_facts: dict[str, set[str]] = defaultdict(set)
        self._worklist: list[tuple[str, str]] = []
        self._z3_constraints: list[str] = []
        self._session = session

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Run the fixed-point alias analysis.

        Parameters
        ----------
        inputs
            Dictionary with keys:
            - ``"pointers"``: list[str] — names of pointer symbols.
            - ``"constraints"``: list[str] — initial alias constraints as
              pairs ``["p1 = p2", "p3 = p4", ...]``.

        Returns
        -------
        AlgorithmResult
            result is a dict[str, frozenset[str]] mapping each pointer to
            its alias set.
        """
        self._start_time = time.perf_counter()
        self._iteration_count = 0
        self._pointer_facts = defaultdict(set)
        self._worklist = []
        self._z3_constraints = []

        pointers: list[str] = inputs.get("pointers", [])
        raw_constraints: list[str] = inputs.get("constraints", [])

        # Initialise reflexive alias facts
        for p in pointers:
            self._pointer_facts[p].add(p)

        # Parse constraints of the form "p1 = p2"
        for constraint in raw_constraints:
            parts = [t.strip() for t in constraint.split("=")]
            if len(parts) == 2:
                p1, p2 = parts[0], parts[1]
                self._worklist.append((p1, p2))
            else:
                self._z3_constraints.append(constraint)

        self.logger.info(
            "Starting fixed-point alias analysis: %d pointers, %d initial constraints",
            len(pointers),
            len(raw_constraints),
        )

        status, iters = self._run_iteration_loop()

        alias_sets = {p: frozenset(s) for p, s in self._pointer_facts.items()}
        return AlgorithmResult(
            status=status,
            iterations=iters,
            wall_time_ms=self.elapsed_ms(),
            result=alias_sets,
            error_message=None,
            metadata={
                "pointer_count": len(pointers),
                "alias_fact_count": sum(len(s) for s in self._pointer_facts.values()),
            },
        )

    def step(self) -> bool:
        """Process one alias pair from the worklist.

        Returns
        -------
        bool
            True if the worklist is empty (converged).
        """
        if not self._worklist:
            return True
        p1, p2 = self._worklist.pop(0)
        changed = self._propagate_aliases(p1, p2)
        if changed:
            # Propagate transitivity
            for q in list(self._pointer_facts[p2]):
                pair = (p1, q)
                if q != p1 and pair not in set(self._worklist):
                    self._worklist.append(pair)
            for q in list(self._pointer_facts[p1]):
                pair = (q, p2)
                if q != p2 and pair not in set(self._worklist):
                    self._worklist.append(pair)
        return not self._worklist

    def is_converged(self) -> bool:
        """Return True when the worklist is empty."""
        return len(self._worklist) == 0

    def summarize(self) -> str:
        """Return a human-readable description of the current analysis state."""
        total_pairs = sum(len(s) for s in self._pointer_facts.values())
        return (
            f"FixedPointAliasAnalysis("
            f"status={self._status.value}, "
            f"iters={self._iteration_count}, "
            f"worklist={len(self._worklist)}, "
            f"alias_pairs={total_pairs})"
        )

    def add_constraint(self, constraint: str) -> None:
        """Add a new alias constraint to the worklist.

        Parameters
        ----------
        constraint
            Either a simple equality ``"p1 = p2"`` or a Z3-level formula
            string.  Equalities are parsed and added to the worklist;
            other formulas are stored for optional Z3 checking.
        """
        parts = [t.strip() for t in constraint.split("=")]
        if len(parts) == 2:
            p1, p2 = parts[0], parts[1]
            self._worklist.append((p1, p2))
            self.logger.debug("Added alias constraint: %s = %s", p1, p2)
        else:
            self._z3_constraints.append(constraint)
            self.logger.debug("Added Z3 constraint: %s", constraint[:60])

    def get_alias_set(self, pointer: str) -> frozenset[str]:
        """Return the current alias set for *pointer*.

        Parameters
        ----------
        pointer
            Name of the pointer.

        Returns
        -------
        frozenset[str]
            Set of pointers known to alias *pointer*, including *pointer*
            itself.  Returns a singleton set ``{pointer}`` if no aliases
            are known.
        """
        return frozenset(self._pointer_facts.get(pointer, {pointer}))

    def _propagate_aliases(self, p1: str, p2: str) -> bool:
        """Propagate the alias fact ``p1 aliases p2`` transitively.

        Adds p2's entire alias set to p1's alias set and vice versa.

        Parameters
        ----------
        p1, p2
            Pointer names.

        Returns
        -------
        bool
            True if any new alias facts were added.
        """
        before_p1 = len(self._pointer_facts[p1])
        before_p2 = len(self._pointer_facts[p2])

        # Merge alias sets symmetrically
        merged = self._pointer_facts[p1] | self._pointer_facts[p2] | {p1, p2}
        self._pointer_facts[p1] = merged
        self._pointer_facts[p2] = merged

        after_p1 = len(self._pointer_facts[p1])
        after_p2 = len(self._pointer_facts[p2])
        return after_p1 > before_p1 or after_p2 > before_p2


