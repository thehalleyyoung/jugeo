class InterfaceAbstractionSynthesis(CollectionHeapAlgorithm):
    """Synthesize interface abstractions from concrete examples.

    Uses CEGIS-style (Counter-Example Guided Inductive Synthesis) to build
    an :class:`InterfaceAbstraction` that is consistent with all provided
    concrete examples and is as tight as possible.

    Parameters
    ----------
    max_iterations
        Maximum CEGIS rounds.
    timeout_seconds
        Wall-clock timeout.
    """

    def __init__(
        self,
        max_iterations: int = _DEFAULT_MAX_ITERATIONS,
        timeout_seconds: float = _DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        super().__init__(max_iterations=max_iterations, timeout_seconds=timeout_seconds)
        self._concrete_examples: list[dict[str, Any]] = []
        self._current_abstraction: InterfaceAbstraction | None = None
        self._refinement_steps: list[str] = []
        self._interface_name: str = "unnamed_interface"
        self._example_idx: int = 0

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Run interface abstraction synthesis.

        Parameters
        ----------
        inputs
            Dictionary with keys:
            - ``"interface_name"``: str — name for the synthesized interface.
            - ``"concrete_examples"``: list[dict] — each dict is a concrete
              implementation example with keys ``"pre"``, ``"post"``,
              ``"name"``, and ``"heap_effect"``.

        Returns
        -------
        AlgorithmResult
            result is the synthesized :class:`InterfaceAbstraction`, or
            None if synthesis failed.
        """
        self._start_time = time.perf_counter()
        self._iteration_count = 0
        self._refinement_steps = []
        self._current_abstraction = None
        self._example_idx = 0

        self._interface_name = inputs.get("interface_name", "unnamed_interface")
        self._concrete_examples = inputs.get("concrete_examples", [])

        if not self._concrete_examples:
            return AlgorithmResult(
                status=AlgorithmStatus.ERROR,
                iterations=0,
                wall_time_ms=self.elapsed_ms(),
                result=None,
                error_message="No concrete examples provided",
                metadata={"interface_name": self._interface_name},
            )

        # Bootstrap: synthesize from first example
        self._current_abstraction = self._synthesize_from_examples(
            self._concrete_examples[:1]
        )
        self._example_idx = 1

        self.logger.info(
            "Starting interface abstraction synthesis for '%s': %d examples",
            self._interface_name,
            len(self._concrete_examples),
        )

        status, iters = self._run_iteration_loop()

        return AlgorithmResult(
            status=status,
            iterations=iters,
            wall_time_ms=self.elapsed_ms(),
            result=self._current_abstraction,
            error_message=None,
            metadata={
                "interface_name": self._interface_name,
                "examples_processed": self._example_idx,
                "refinement_steps": len(self._refinement_steps),
            },
        )

    def step(self) -> bool:
        """Process one more concrete example as a potential counterexample.

        Returns
        -------
        bool
            True if all examples have been processed.
        """
        if self._example_idx >= len(self._concrete_examples):
            return True

        example = self._concrete_examples[self._example_idx]
        self._example_idx += 1

        # Check if current abstraction covers this example
        if not self._is_consistent(self._current_abstraction, example):
            self.logger.debug(
                "Counterexample at index %d: refining abstraction", self._example_idx - 1
            )
            self._refine_with_counterexample(example)
            self._refinement_steps.append(f"refined_at_example_{self._example_idx - 1}")

        return self._example_idx >= len(self._concrete_examples)

    def is_converged(self) -> bool:
        """Return True when all concrete examples have been processed."""
        return self._example_idx >= len(self._concrete_examples)

    def summarize(self) -> str:
        """Return a human-readable description of the synthesis state."""
        abstr_name = (
            self._current_abstraction.interface_name
            if self._current_abstraction
            else "None"
        )
        return (
            f"InterfaceAbstractionSynthesis("
            f"interface='{self._interface_name}', "
            f"status={self._status.value}, "
            f"current='{abstr_name}', "
            f"examples_seen={self._example_idx}/{len(self._concrete_examples)}, "
            f"refinements={len(self._refinement_steps)})"
        )

    def _synthesize_from_examples(
        self, examples: list[dict[str, Any]]
    ) -> InterfaceAbstraction:
        """Build an initial :class:`InterfaceAbstraction` from *examples*.

        Extracts preconditions and postconditions from the examples and
        combines them into an over-approximate abstraction.

        Parameters
        ----------
        examples
            List of concrete example dicts.

        Returns
        -------
        InterfaceAbstraction
            The initial abstraction.
        """
        pre_conditions: list[str] = []
        post_conditions: list[str] = []
        heap_effects: list[str] = []

        for ex in examples:
            pre = ex.get("pre", "true")
            post = ex.get("post", "true")
            heap = ex.get("heap_effect", "unchanged")
            pre_conditions.append(str(pre))
            post_conditions.append(str(post))
            heap_effects.append(str(heap))

        # Join all preconditions disjunctively (over-approximate)
        if len(pre_conditions) == 1:
            pre_formula = pre_conditions[0]
        else:
            pre_formula = "(or " + " ".join(pre_conditions) + ")"

        # Join all postconditions conjunctively (conservative)
        if len(post_conditions) == 1:
            post_formula = post_conditions[0]
        else:
            # Find common parts (approximate as first condition)
            post_formula = post_conditions[0]

        return InterfaceAbstraction(
            interface_name=self._interface_name,
            pre_condition=pre_formula,
            post_condition=post_formula,
            heap_footprint=frozenset(heap_effects),
            abstraction_id=f"ia_{uuid.uuid4().hex[:8]}",
            created_at=time.time(),
        )

    def _is_consistent(
        self,
        abstraction: InterfaceAbstraction | None,
        example: dict[str, Any],
    ) -> bool:
        """Return True if *abstraction* is consistent with *example*.

        Consistency check: the example's pre-condition implies the
        abstraction's pre-condition (syntactic over-approximation check).
        """
        if abstraction is None:
            return False
        ex_pre = str(example.get("pre", "true"))
        ex_post = str(example.get("post", "true"))
        # Syntactic consistency: check if example terms appear in abstraction
        pre_ok = ex_pre in abstraction.pre_condition or abstraction.pre_condition == "true"
        post_ok = ex_post in abstraction.post_condition or abstraction.post_condition == "true"
        return pre_ok or post_ok

    def _refine_with_counterexample(self, ce: dict[str, Any]) -> None:
        """Refine the current abstraction to include *ce*.

        Weakens the precondition to admit the counterexample's pre-state
        and strengthens the postcondition if the counterexample's post-state
        is inconsistent.

        Parameters
        ----------
        ce
            Counterexample dict with keys ``"pre"``, ``"post"``,
            ``"heap_effect"``.
        """
        if self._current_abstraction is None:
            self._current_abstraction = self._synthesize_from_examples([ce])
            return

        ce_pre = str(ce.get("pre", "true"))
        ce_post = str(ce.get("post", "true"))
        ce_heap = str(ce.get("heap_effect", "unchanged"))

        # Weaken precondition disjunctively
        old_pre = self._current_abstraction.pre_condition
        new_pre = f"(or {old_pre} {ce_pre})"

        # Intersect postcondition (conservative: keep existing)
        old_post = self._current_abstraction.post_condition
        new_post = f"(and {old_post} {ce_post})"

        new_footprint = self._current_abstraction.heap_footprint | {ce_heap}

        self._current_abstraction = InterfaceAbstraction(
            interface_name=self._interface_name,
            pre_condition=new_pre,
            post_condition=new_post,
            heap_footprint=new_footprint,
            abstraction_id=f"ia_{uuid.uuid4().hex[:8]}",
            created_at=time.time(),
        )
        self.logger.debug(
            "Refined abstraction for '%s' (pre: %s → %s)",
            self._interface_name,
            old_pre[:30],
            new_pre[:30],
        )

    def get_abstraction(self) -> InterfaceAbstraction | None:
        """Return the current best abstraction, or None."""
        return self._current_abstraction


