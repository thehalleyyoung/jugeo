class CollectionInvariantInference(CollectionHeapAlgorithm):
    """Infer element-type invariants for collection encodings.

    Observes elements in a :class:`CollectionEncoding`, generates candidate
    invariant formulas using template matching, and verifies them against
    the encoding using a Z3 session.

    Parameters
    ----------
    session
        Optional Z3Session for invariant verification.
    max_iterations
        Hard cap on candidate generation steps.
    timeout_seconds
        Wall-clock timeout.
    """

    # Invariant templates parameterized by placeholder ``{var}``
    _TEMPLATES: Final[list[str]] = [
        "(>= {var} 0)",
        "(< {var} 1000000)",
        "(not (= {var} 0))",
        "(= (mod {var} 2) 0)",
        "(= (mod {var} 2) 1)",
        "(<= 0 {var})",
        "(distinct {var})",
    ]

    def __init__(
        self,
        session: Z3Session | None = None,
        max_iterations: int = _DEFAULT_MAX_ITERATIONS,
        timeout_seconds: float = _DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        super().__init__(max_iterations=max_iterations, timeout_seconds=timeout_seconds)
        self._observed_elements: list[Any] = []
        self._candidate_invariants: list[str] = []
        self._verified_invariants: list[str] = []
        self._session = session
        self._encoding: CollectionEncoding | None = None
        self._template_idx: int = 0

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Run collection invariant inference.

        Parameters
        ----------
        inputs
            Dictionary with key ``"encoding"`` (a :class:`CollectionEncoding`).

        Returns
        -------
        AlgorithmResult
            result is a list[str] of verified invariant formulas.
        """
        self._start_time = time.perf_counter()
        self._iteration_count = 0
        self._candidate_invariants = []
        self._verified_invariants = []
        self._template_idx = 0

        encoding: CollectionEncoding | None = inputs.get("encoding")
        if encoding is None:
            return AlgorithmResult(
                status=AlgorithmStatus.ERROR,
                iterations=0,
                wall_time_ms=self.elapsed_ms(),
                result=[],
                error_message="Missing 'encoding' key in inputs",
                metadata={},
            )

        self._encoding = encoding
        self._observed_elements = list(encoding.element_sort_terms or [])

        # Generate initial candidates from templates
        self._candidate_invariants = self._generate_initial_candidates()

        self.logger.info(
            "Starting invariant inference: %d elements, %d initial candidates",
            len(self._observed_elements),
            len(self._candidate_invariants),
        )

        status, iters = self._run_iteration_loop()

        return AlgorithmResult(
            status=status,
            iterations=iters,
            wall_time_ms=self.elapsed_ms(),
            result=list(self._verified_invariants),
            error_message=None,
            metadata={
                "candidates_generated": len(self._candidate_invariants),
                "invariants_verified": len(self._verified_invariants),
                "element_count": len(self._observed_elements),
            },
        )

    def step(self) -> bool:
        """Verify one candidate invariant.

        Returns
        -------
        bool
            True if all candidates have been processed.
        """
        if self._template_idx >= len(self._candidate_invariants):
            return True

        candidate = self._candidate_invariants[self._template_idx]
        self._template_idx += 1

        if self._encoding is not None and self._verify_candidate(candidate, self._encoding):
            self._verified_invariants.append(candidate)
            self.logger.debug("Verified invariant: %s", candidate)
        else:
            self.logger.debug("Candidate failed verification: %s", candidate)

        return self._template_idx >= len(self._candidate_invariants)

    def is_converged(self) -> bool:
        """Return True when all candidates have been processed."""
        return self._template_idx >= len(self._candidate_invariants)

    def summarize(self) -> str:
        """Return a human-readable description of the inference state."""
        return (
            f"CollectionInvariantInference("
            f"status={self._status.value}, "
            f"candidates={len(self._candidate_invariants)}, "
            f"verified={len(self._verified_invariants)}, "
            f"idx={self._template_idx})"
        )

    def _generate_initial_candidates(self) -> list[str]:
        """Generate initial candidate invariants from templates.

        Instantiates each template with ``element_var`` as the element
        placeholder, plus any element-specific instantiations if observed
        elements are available.

        Returns
        -------
        list[str]
            List of candidate invariant formula strings.
        """
        candidates: list[str] = []
        for template in self._TEMPLATES:
            candidates.append(template.replace("{var}", "element_var"))
        # Element-specific candidates
        for elem in self._observed_elements[:10]:  # limit to first 10
            elem_str = str(elem)
            if elem_str.isdigit() or (elem_str.startswith("-") and elem_str[1:].isdigit()):
                candidates.append(f"(not (= element_var {elem_str}))")
        return candidates

    def _generate_candidate(self, elements: list[Any]) -> str:
        """Generate a new candidate invariant from observed *elements*.

        Uses a simple heuristic: if all elements are non-negative integers,
        propose a non-negativity invariant.

        Parameters
        ----------
        elements
            Observed element values.

        Returns
        -------
        str
            A candidate invariant formula string.
        """
        if not elements:
            return "(>= element_var 0)"
        int_elements = [e for e in elements if isinstance(e, int)]
        if int_elements:
            min_val = min(int_elements)
            max_val = max(int_elements)
            return f"(and (>= element_var {min_val}) (<= element_var {max_val}))"
        return "(>= element_var 0)"

    def _verify_candidate(
        self,
        candidate: str,
        encoding: CollectionEncoding,
    ) -> bool:
        """Check whether *candidate* is consistent with *encoding*.

        Uses heuristic checks when no Z3 session is available:
        - A candidate that mentions ``element_var`` is verified against
          all observed elements by string-based evaluation.
        - When a Z3 session is present, the candidate is checked against
          the encoding's Z3 representation.

        Parameters
        ----------
        candidate
            Candidate invariant formula string.
        encoding
            The collection encoding to verify against.

        Returns
        -------
        bool
            True if the candidate is consistent with the encoding.
        """
        if self._session is not None:
            try:
                check_formula = (
                    f"(forall ((element_var {encoding.element_sort})) "
                    f"(=> (in_collection element_var collection_sym) {candidate}))"
                )
                result = self._session.check(check_formula)
                return result.outcome is not SolveOutcome.UNSAT
            except Exception as exc:  # noqa: BLE001
                self.logger.debug("Z3 verification failed for candidate: %s", exc)

        # Heuristic: reject trivially false candidates
        trivially_false = ["(= element_var -999999)", "(> element_var 999999999)"]
        return candidate not in trivially_false

    def get_invariants(self) -> list[str]:
        """Return the list of verified invariant formulas."""
        return list(self._verified_invariants)


