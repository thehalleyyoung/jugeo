class BottomUpHeapSummaryAlgorithm(CollectionHeapAlgorithm):
    """Compute heap summaries bottom-up through a call graph.

    For each function in the call graph (in reverse topological order),
    this algorithm computes a :class:`HeapSummary` that over-approximates
    the heap effect of that function and all its callees.

    The fixed-point iteration terminates when no heap summary changes
    between successive passes.

    Parameters
    ----------
    max_iterations
        Maximum number of worklist processing steps.
    timeout_seconds
        Wall-clock timeout.
    """

    def __init__(
        self,
        max_iterations: int = _DEFAULT_MAX_ITERATIONS,
        timeout_seconds: float = _DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        super().__init__(max_iterations=max_iterations, timeout_seconds=timeout_seconds)
        self._call_graph: dict[str, list[str]] = {}
        self._summaries: dict[str, HeapSummary] = {}
        self._worklist: list[str] = []
        self._topo_order: list[str] = []
        self._changed_in_pass: bool = False

    def run(self, inputs: dict[str, Any]) -> AlgorithmResult:
        """Execute the bottom-up heap summary algorithm.

        Parameters
        ----------
        inputs
            Dictionary with keys:
            - ``"call_graph"``: dict[str, list[str]] mapping function name
              to list of callee names.
            - ``"initial_heaps"``: dict[str, HeapSummary] mapping function
              name to its initial (pre-analysis) heap summary.

        Returns
        -------
        AlgorithmResult
            result is a dict[str, HeapSummary] mapping each function to its
            computed heap summary.
        """
        self._start_time = time.perf_counter()
        self._iteration_count = 0

        call_graph: dict[str, list[str]] = inputs.get("call_graph", {})
        initial_heaps: dict[str, HeapSummary] = inputs.get("initial_heaps", {})

        self._call_graph = call_graph
        self._summaries = dict(initial_heaps)

        try:
            self._topo_order = self._topological_sort(call_graph)
        except ValueError as exc:
            return AlgorithmResult(
                status=AlgorithmStatus.ERROR,
                iterations=0,
                wall_time_ms=self.elapsed_ms(),
                result=None,
                error_message=f"Topological sort failed: {exc}",
                metadata={"call_graph_size": len(call_graph)},
            )

        # Initialise worklist in reverse topological order (leaves first)
        self._worklist = list(reversed(self._topo_order))
        self.logger.info(
            "Starting bottom-up heap summary: %d functions, worklist=%d",
            len(call_graph),
            len(self._worklist),
        )

        status, iters = self._run_iteration_loop()

        return AlgorithmResult(
            status=status,
            iterations=iters,
            wall_time_ms=self.elapsed_ms(),
            result=dict(self._summaries),
            error_message=None,
            metadata={
                "function_count": len(call_graph),
                "topo_order": self._topo_order,
            },
        )

    def step(self) -> bool:
        """Process one function from the worklist.

        Returns
        -------
        bool
            True if the worklist is now empty (converged).
        """
        if not self._worklist:
            return True
        fn_name = self._worklist.pop(0)
        old_summary = self._summaries.get(fn_name)
        new_summary = self._compute_summary_for(fn_name)

        if old_summary is None or self._summaries_differ(old_summary, new_summary):
            self._summaries[fn_name] = new_summary
            # Re-add callers to worklist if their callee changed
            for caller, callees in self._call_graph.items():
                if fn_name in callees and caller not in self._worklist:
                    self._worklist.append(caller)
                    self.logger.debug(
                        "Re-queued caller '%s' due to change in '%s'", caller, fn_name
                    )

        return not self._worklist

    def is_converged(self) -> bool:
        """Return True when the worklist is empty."""
        return len(self._worklist) == 0

    def summarize(self) -> str:
        """Return a string summary of current analysis state."""
        return (
            f"BottomUpHeapSummaryAlgorithm("
            f"status={self._status.value}, "
            f"iters={self._iteration_count}, "
            f"worklist={len(self._worklist)}, "
            f"summaries={len(self._summaries)})"
        )

    def _compute_summary_for(self, fn_name: str) -> HeapSummary:
        """Compute the heap summary for *fn_name* by joining callees.

        Algorithm
        ---------
        1. Fetch the base summary for *fn_name* (from initial_heaps, or
           empty if not present).
        2. For each callee, retrieve its current summary and join the
           footprints and points-to maps.
        3. Return the joined summary.

        Parameters
        ----------
        fn_name
            Name of the function whose summary is to be computed.

        Returns
        -------
        HeapSummary
            The computed summary.
        """
        callees = self._call_graph.get(fn_name, [])
        base = self._summaries.get(fn_name) or self._empty_summary(fn_name)

        joined_footprint: set[str] = set(base.footprint)
        joined_points_to: dict[str, Any] = dict(base.points_to_map)
        joined_alias_classes: list[frozenset[str]] = list(base.alias_classes)

        for callee in callees:
            callee_summary = self._summaries.get(callee)
            if callee_summary is None:
                continue
            # Join footprints
            joined_footprint |= set(callee_summary.footprint)
            # Join points-to (caller takes precedence on conflicts)
            for loc, target in callee_summary.points_to_map.items():
                if loc not in joined_points_to:
                    joined_points_to[loc] = target
            # Merge alias classes
            for ac in callee_summary.alias_classes:
                if ac not in joined_alias_classes:
                    joined_alias_classes.append(ac)

        return HeapSummary(
            summary_id=f"hs_{fn_name}_{uuid.uuid4().hex[:6]}",
            points_to_map=joined_points_to,
            footprint=frozenset(joined_footprint),
            alias_classes=joined_alias_classes,
            frame_condition=base.frame_condition,
            is_empty=len(joined_points_to) == 0,
            created_at=time.time(),
        )

    def _summaries_differ(self, s1: HeapSummary, s2: HeapSummary) -> bool:
        """Return True if two heap summaries differ in any observable way."""
        return (
            s1.footprint != s2.footprint
            or s1.points_to_map != s2.points_to_map
            or set(map(frozenset, s1.alias_classes)) != set(map(frozenset, s2.alias_classes))
        )

    def _empty_summary(self, fn_name: str) -> HeapSummary:
        """Return an empty heap summary for *fn_name*."""
        return HeapSummary(
            summary_id=f"hs_empty_{fn_name}",
            points_to_map={},
            footprint=frozenset(),
            alias_classes=[],
            frame_condition="true",
            is_empty=True,
            created_at=time.time(),
        )

    def _topological_sort(self, graph: dict[str, list[str]]) -> list[str]:
        """Return a topological ordering of *graph*.

        Uses Kahn's algorithm.  Raises ValueError on cycle detection.

        Parameters
        ----------
        graph
            Adjacency list where edges go from caller to callees.

        Returns
        -------
        list[str]
            Functions in topological order (callers before callees).

        Raises
        ------
        ValueError
            If a cycle is detected in the call graph.
        """
        in_degree: dict[str, int] = {node: 0 for node in graph}
        for node in graph:
            for callee in graph[node]:
                if callee not in in_degree:
                    in_degree[callee] = 0
                in_degree[callee] += 1

        # Ensure all callees are in the in_degree map
        for node in list(graph):
            for callee in graph[node]:
                if callee not in in_degree:
                    in_degree[callee] = 0

        queue = [n for n, deg in in_degree.items() if deg == 0]
        result: list[str] = []
        while queue:
            node = queue.pop(0)
            result.append(node)
            for callee in graph.get(node, []):
                in_degree[callee] -= 1
                if in_degree[callee] == 0:
                    queue.append(callee)

        all_nodes = set(in_degree)
        if len(result) != len(all_nodes):
            cycle_nodes = all_nodes - set(result)
            raise ValueError(
                f"Call graph contains a cycle involving: {sorted(cycle_nodes)}"
            )
        return result

    def get_summary(self, fn_name: str) -> HeapSummary | None:
        """Return the computed heap summary for *fn_name*, or None."""
        return self._summaries.get(fn_name)


