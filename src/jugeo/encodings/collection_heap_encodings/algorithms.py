class CollectionHeapAlgorithm:
    """Abstract base class for all collection and heap encoding algorithms.

    Subclasses implement the three abstract methods :meth:`run`,
    :meth:`step`, and :meth:`is_converged`.  The base class provides
    timing, iteration counting, timeout detection, and logging helpers.

    Parameters
    ----------
    max_iterations
        Hard cap on the number of :meth:`step` invocations.
    timeout_seconds
        Wall-clock timeout.  :meth:`_check_timeout` returns True once
        this limit is exceeded.
    """

    def __init__(
        self,
        max_iterations: int = _DEFAULT_MAX_ITERATIONS,
        timeout_seconds: float = _DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        self.logger = logging.getLogger(
            f"{__name__}.{type(self).__name__}"
        )
        self._status: AlgorithmStatus = AlgorithmStatus.NOT_STARTED
        self._iteration_count: int = 0
        self._start_time: float | None = None
        self.max_iterations = max_iterations
        self.timeout_seconds = timeout_seconds

    # ------------------------------------------------------------------
    # Abstract interface
    # ------------------------------------------------------------------

    def run(self, inputs: Any) -> AlgorithmResult:  # noqa: ANN401
        """Execute the algorithm on *inputs* until convergence or abort.

        Subclasses must override this method.  The base implementation
        provides a generic iteration loop using :meth:`step`.

        Parameters
        ----------
        inputs
            Algorithm-specific input structure.

        Returns
        -------
        AlgorithmResult
        """
        raise NotImplementedError(f"{type(self).__name__}.run() not implemented")

    def step(self) -> bool:
        """Perform one iteration of the algorithm.

        Returns
        -------
        bool
            True if the algorithm has converged after this step; False if
            more steps are needed.
        """
        raise NotImplementedError(f"{type(self).__name__}.step() not implemented")

    def is_converged(self) -> bool:
        """Return True when the termination criterion is satisfied."""
        raise NotImplementedError(f"{type(self).__name__}.is_converged() not implemented")

    def summarize(self) -> str:
        """Return a human-readable summary of current algorithm state."""
        raise NotImplementedError(f"{type(self).__name__}.summarize() not implemented")

    # ------------------------------------------------------------------
    # Concrete helpers
    # ------------------------------------------------------------------

    def reset(self) -> None:
        """Reset the algorithm to its initial pre-run state.

        Subclasses should call ``super().reset()`` and then reset their
        own fields.
        """
        self._status = AlgorithmStatus.NOT_STARTED
        self._iteration_count = 0
        self._start_time = None
        self.logger.debug("Algorithm reset to NOT_STARTED")

    def elapsed_ms(self) -> float:
        """Return wall-clock time in milliseconds since :meth:`run` started.

        Returns 0.0 if the algorithm has not started yet.
        """
        if self._start_time is None:
            return 0.0
        return (time.perf_counter() - self._start_time) * 1000.0

    def _check_timeout(self) -> bool:
        """Return True if the wall-clock timeout has been exceeded."""
        if self._start_time is None:
            return False
        return self.elapsed_ms() > self.timeout_seconds * 1000.0

    def _log_iteration(self, iter_num: int, message: str) -> None:
        """Emit a debug log line for iteration *iter_num* with *message*."""
        self.logger.debug("[iter %d] %s", iter_num, message)

    def _run_iteration_loop(self) -> tuple[AlgorithmStatus, int]:
        """Drive the :meth:`step` loop.

        Runs :meth:`step` until convergence, timeout, or max-iterations.

        Returns
        -------
        tuple[AlgorithmStatus, int]
            Final status and total iteration count.
        """
        self._status = AlgorithmStatus.RUNNING
        while self._iteration_count < self.max_iterations:
            if self._check_timeout():
                self.logger.warning(
                    "Algorithm timed out after %d iterations (%.1f ms)",
                    self._iteration_count,
                    self.elapsed_ms(),
                )
                return AlgorithmStatus.TIMEOUT, self._iteration_count

            converged = self.step()
            self._iteration_count += 1
            self._log_iteration(
                self._iteration_count,
                f"step completed, converged={converged}",
            )
            if converged or self.is_converged():
                return AlgorithmStatus.CONVERGED, self._iteration_count

        self.logger.warning(
            "Max iterations (%d) reached without convergence", self.max_iterations
        )
        return AlgorithmStatus.PARTIAL, self._iteration_count


