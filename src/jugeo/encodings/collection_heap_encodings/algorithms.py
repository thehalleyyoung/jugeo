_ALGORITHM_REGISTRY: dict[str, type[CollectionHeapAlgorithm]] = {
    "bottom_up_heap_summary": BottomUpHeapSummaryAlgorithm,
    "fixed_point_alias": FixedPointAliasAnalysis,
    "collection_invariant_inference": CollectionInvariantInference,
    "interface_abstraction_synthesis": InterfaceAbstractionSynthesis,
    "boundary_condition_minimization": BoundaryConditionMinimization,
}


def create_algorithm(
    name: str,
    **kwargs: Any,
) -> CollectionHeapAlgorithm:
    """Instantiate a registered algorithm by name.

    Parameters
    ----------
    name
        Registry key (e.g. ``"bottom_up_heap_summary"``).
    **kwargs
        Keyword arguments forwarded to the algorithm constructor.

    Returns
    -------
    CollectionHeapAlgorithm
        A fresh algorithm instance.

    Raises
    ------
    KeyError
        If *name* is not in the registry.

    Examples
    --------
    >>> algo = create_algorithm("fixed_point_alias", max_iterations=100)
    >>> isinstance(algo, FixedPointAliasAnalysis)
    True
    """
    if name not in _ALGORITHM_REGISTRY:
        available = ", ".join(sorted(_ALGORITHM_REGISTRY))
        raise KeyError(
            f"Unknown algorithm '{name}'.  Available algorithms: {available}"
        )
    cls = _ALGORITHM_REGISTRY[name]
    return cls(**kwargs)


def run_all_algorithms(inputs: dict[str, Any]) -> dict[str, AlgorithmResult]:
    """Run every registered algorithm on *inputs* and collect results.

    Each algorithm is given the same *inputs* dict.  Algorithms that do
    not find the keys they need will return an ERROR result.

    Parameters
    ----------
    inputs
        Shared input dictionary passed to every algorithm's :meth:`run`.

    Returns
    -------
    dict[str, AlgorithmResult]
        Map from algorithm name to its result.
    """
    results: dict[str, AlgorithmResult] = {}
    for name, cls in _ALGORITHM_REGISTRY.items():
        algo = cls()
        log = logging.getLogger(__name__)
        log.info("Running algorithm '%s'", name)
        t0 = time.perf_counter()
        try:
            result = algo.run(inputs)
        except Exception as exc:  # noqa: BLE001
            elapsed = (time.perf_counter() - t0) * 1000
            log.error("Algorithm '%s' raised: %s", name, exc)
            result = AlgorithmResult(
                status=AlgorithmStatus.ERROR,
                iterations=0,
                wall_time_ms=elapsed,
                result=None,
                error_message=str(exc),
                metadata={"algorithm_name": name},
            )
        results[name] = result
        log.info("Algorithm '%s' finished: %s", name, result.summary())
    return results


def register_algorithm(
    name: str,
    cls: type[CollectionHeapAlgorithm],
) -> None:
    """Add a custom algorithm class to the registry.

    Parameters
    ----------
    name
        Unique registry key.
    cls
        Subclass of :class:`CollectionHeapAlgorithm`.

    Raises
    ------
    TypeError
        If *cls* is not a subclass of :class:`CollectionHeapAlgorithm`.
    ValueError
        If *name* is already registered.
    """
    if not issubclass(cls, CollectionHeapAlgorithm):
        raise TypeError(
            f"{cls.__name__} must be a subclass of CollectionHeapAlgorithm"
        )
    if name in _ALGORITHM_REGISTRY:
        raise ValueError(
            f"Algorithm '{name}' is already registered.  "
            "Use a unique name or remove the existing registration."
        )
    _ALGORITHM_REGISTRY[name] = cls
    logger.info("Registered custom algorithm '%s' → %s", name, cls.__name__)


