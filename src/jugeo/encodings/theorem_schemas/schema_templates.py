class TrustSchemaTemplate:
    """Template library for the Trust subsystem proof burden.

    The Trust subsystem maintains the trust algebra ``(T, ≤, ⊗, ⊤)`` and
    must prove that the trust map is monotone, that trust composition is
    well-defined and associative, that trust propagates correctly over
    evidence channels, that revocation is downward-closed, and that trust
    annotations are sound with respect to the semantic model.

    The five schemas are:

    ``trust_monotonicity_schema``
        Trust is monotone in the trust order.
    ``trust_composition_schema``
        Trust composes transitively via the tensor ⊗.
    ``trust_propagation_schema``
        Trust annotations transport correctly over evidence channels.
    ``trust_revocation_schema``
        Revocation is downward-closed in the dependency graph.
    ``trust_annotation_soundness_schema``
        Trust annotations are sound with respect to the semantic model.

    See theory2.tex §36.2.2 for the mathematical context.
    """

    def __init__(self) -> None:
        """Instantiate all five trust theorem schemas as instance attributes."""
        self.trust_monotonicity_schema: TheoremSchema = make_theorem_schema(
            name="trust_monotonicity",
            template_statement=(
                "If {A} is trusted at level {t1} and {t1} <= {t2} in the trust "
                "algebra, then {A} is trusted at level {t2}: trust is monotone "
                "in the trust order."
            ),
            variables={
                "A": "an agent or component in the trust graph",
                "t1": "the lower trust level at which A is known to be trusted",
                "t2": "any trust level above t1 in the trust partial order",
            },
            subsystem=SubsystemKind.TRUST,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "Monotonicity of the trust map means that once an agent A is "
                "trusted at level t1, it is automatically trusted at any higher "
                "level t2 >= t1 in the trust partial order. This ensures that "
                "raising the trust threshold never produces spurious distrust. "
                "In the quantale model, this corresponds to the up-set property: "
                "for all a in T, the set {t | A trusted at t} is an up-set. "
                "Proof: by definition of the trust map combined with the "
                "order-preserving property of the trust algebra operations."
            ),
            prerequisites=[],
            difficulty=2,
            tags=["trust", "monotone", "order", "quantale"],
        )

        self.trust_composition_schema: TheoremSchema = make_theorem_schema(
            name="trust_composition",
            template_statement=(
                "Trust composes: if {A} trusts {B} at level {t1} and {B} certifies "
                "{C} at level {t2}, then {A} transitively trusts {C} at level "
                "{t1 tensor t2}."
            ),
            variables={
                "A": "the trusting agent",
                "B": "the intermediate certifying agent",
                "C": "the target agent whose trust is composed",
                "t1": "the direct trust level of A in B",
                "t2": "the certification level of B for C",
                "t1 tensor t2": "the transitive trust level computed via the quantale tensor",
            },
            subsystem=SubsystemKind.TRUST,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "Trust composition defines a transitive closure of the trust "
                "relation via the tensor product tensor of the trust quantale. If "
                "agent A trusts B at level t1 and B in turn certifies C at level "
                "t2, then A's transitive trust in C is at level t1 tensor t2. The "
                "tensor is commutative and associative, with top element top as "
                "unit. This schema must be discharged for every trust chain "
                "appearing in the execution. Proof: by the quantale multiplication "
                "axioms and the definition of the certification relation."
            ),
            prerequisites=["trust_monotonicity"],
            difficulty=4,
            tags=["trust", "composition", "tensor", "quantale", "transitive"],
        )

        self.trust_propagation_schema: TheoremSchema = make_theorem_schema(
            name="trust_propagation",
            template_statement=(
                "Trust propagates along evidence channels: if evidence item {e} "
                "has trust annotation {T} and is transmitted over channel {ch}, "
                "the received annotation is {ch.transport(T)}."
            ),
            variables={
                "e": "an evidence item being transmitted",
                "T": "the trust annotation attached to e before transmission",
                "ch": "the evidence channel over which e is transmitted",
                "ch.transport(T)": "the received trust annotation after channel attenuation",
            },
            subsystem=SubsystemKind.TRUST,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "Evidence channels may attenuate or transform trust annotations "
                "during transmission. The channel transport map ch.transport must "
                "be order-preserving (it cannot raise trust) and must compose "
                "correctly with the trust tensor: for two channels ch1 and ch2 "
                "composed sequentially, (ch1 circ ch2).transport(T) = "
                "ch1.transport(ch2.transport(T)). This schema verifies that the "
                "received trust annotation accurately reflects the channel's "
                "attenuation policy, preventing trust inflation attacks where a "
                "low-quality channel claims to produce high-quality annotations."
            ),
            prerequisites=["trust_monotonicity"],
            difficulty=5,
            tags=["trust", "propagation", "channel", "transport", "attenuation"],
        )

        self.trust_revocation_schema: TheoremSchema = make_theorem_schema(
            name="trust_revocation",
            template_statement=(
                "Trust revocation is downward-closed: if trust at {coord} is "
                "revoked, all judgments depending on {coord} in the invalidation "
                "graph must be re-evaluated."
            ),
            variables={
                "coord": "the coordinate at which trust is being revoked",
            },
            subsystem=SubsystemKind.TRUST,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "When trust at a coordinate coord is revoked (e.g. because a "
                "certificate expires or is compromised), every judgment that "
                "depends on coord in the dependency graph inherits the revocation "
                "and must be re-evaluated. This is the downward-closure property "
                "of revocation: the set of affected judgments is the downward "
                "closure of {coord} in the dependency DAG. Without this property, "
                "stale or compromised trust could silently persist in derived "
                "judgments. Proof: by induction on the dependency depth combined "
                "with the cascade termination theorem of the Invalidation subsystem."
            ),
            prerequisites=["trust_composition"],
            difficulty=6,
            tags=["trust", "revocation", "downward-closed", "cascade", "invalidation"],
        )

        self.trust_annotation_soundness_schema: TheoremSchema = make_theorem_schema(
            name="trust_annotation_soundness",
            template_statement=(
                "The trust annotation {tau} attached to judgment {J} is sound: "
                "the semantic value of {J} in model {M} satisfies the trust "
                "level {tau} — formally, M satisfies trust(J) >= {tau}."
            ),
            variables={
                "tau": "a trust annotation element in the trust quantale T",
                "J": "the judgment carrying annotation tau",
                "M": "the semantic model against which soundness is checked",
            },
            subsystem=SubsystemKind.TRUST,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "Soundness of trust annotations requires that every annotation tau "
                "placed on a judgment J faithfully reflects the actual trust level "
                "that the semantic model M assigns to J. This is a joint property "
                "of the annotation assignment algorithm and the semantic model "
                "interpretation. If this schema fails, the trust subsystem could "
                "label a judgment as trusted when the model considers it "
                "untrustworthy, or vice versa. Proof: by semantic model inspection "
                "combined with the annotation assignment rules in section 36.2.2."
            ),
            prerequisites=["trust_monotonicity", "trust_composition"],
            difficulty=7,
            tags=["trust", "soundness", "annotation", "semantic-model"],
        )

    def get_all_schemas(self) -> list[TheoremSchema]:
        """Return all five trust theorem schemas in dependency order.

        Returns
        -------
        list[TheoremSchema]
            Schemas ordered: monotonicity, composition, propagation,
            revocation, annotation soundness.
        """
        return [
            self.trust_monotonicity_schema,
            self.trust_composition_schema,
            self.trust_propagation_schema,
            self.trust_revocation_schema,
            self.trust_annotation_soundness_schema,
        ]

    def get_schema_by_name(self, name: str) -> TheoremSchema | None:
        """Retrieve a trust schema by name.

        Parameters
        ----------
        name:
            Schema name to search for.

        Returns
        -------
        TheoremSchema or None
        """
        for schema in self.get_all_schemas():
            if schema.name == name:
                return schema
        return None

    def as_subsystem_schema(self) -> SubsystemSchema:
        """Wrap all trust schemas in a :class:`SubsystemSchema` bundle.

        Returns
        -------
        SubsystemSchema
        """
        bundle = SubsystemSchema(
            subsystem_name=SubsystemKind.TRUST,
            subsystem_id=str(uuid.uuid4()),
            required_theorems=self.required_names(),
        )
        for schema in self.get_all_schemas():
            bundle.add_schema(schema)
        return bundle

    def required_names(self) -> list[str]:
        """Return the list of theorem names required by the Trust subsystem.

        Returns
        -------
        list[str]
        """
        return [s.name for s in self.get_all_schemas()]

    def describe(self) -> str:
        """Return a human-readable description of this template library.

        Returns
        -------
        str
        """
        lines: list[str] = [
            "TrustSchemaTemplate — Trust subsystem theorem library",
            "  theory2.tex §36.2.2",
            "  Purpose: Encode the trust algebra proof burden.",
            "  Theorems:",
        ]
        for s in self.get_all_schemas():
            diff = s.metadata.get("difficulty", "?")
            lines.append(f"    [{diff}/10] {s.name}: {s.description[:80]}...")
        return "\n".join(lines)


