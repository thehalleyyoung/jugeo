class DescentSchemaTemplate:
    """Template library for the Descent subsystem proof burden.

    The Descent subsystem is responsible for ensuring that the JuGeo semantic
    site behaves as a Grothendieck site: local data glues to global sections,
    pullback functors respect the sheaf condition, and every effective descent
    morphism admits a canonical inverse to the descent category.

    This class creates five :class:`TheoremSchema` objects as attributes and
    provides a uniform interface — :meth:`get_all_schemas`,
    :meth:`get_schema_by_name`, :meth:`as_subsystem_schema`,
    :meth:`required_names`, and :meth:`describe` — used by the registry.

    The five schemas are:

    ``descent_compatibility_schema``
        Compatibility of a descent datum with pullback along a morphism.
    ``pullback_consistency_schema``
        The pullback functor preserves the sheaf condition.
    ``sheaf_condition_schema``
        The equalizer diagram for the sheaf condition is exact.
    ``descent_data_coherence_schema``
        The coherence conditions on descent data in the fibered category.
    ``effective_descent_schema``
        Characterisation of effective descent morphisms.

    See theory2.tex §36.2.1 for the full statement of these requirements.
    """

    def __init__(self) -> None:
        """Instantiate all five descent theorem schemas as instance attributes.

        Each schema is constructed via :func:`make_theorem_schema` with
        complete mathematical content drawn from theory2.tex §36.2.1.
        """
        self.descent_compatibility_schema: TheoremSchema = make_theorem_schema(
            name="descent_compatibility",
            template_statement=(
                "For morphism {f} in the semantic site, the descent datum {D} "
                "satisfies compatibility: the pullback {f^*D} is canonically "
                "isomorphic to {D} restricted along {f}."
            ),
            variables={
                "f": "a morphism in the semantic site",
                "D": "a descent datum over the target of f",
                "f^*D": "the pullback of D along f",
            },
            subsystem=SubsystemKind.DESCENT,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "Establishes that pulling back a descent datum along any morphism "
                "in the site recovers the original datum up to canonical isomorphism. "
                "This is the base coherence condition for the fibered category of "
                "descent data over the semantic site. It implies that descent data "
                "behave functorially with respect to the site morphisms."
            ),
            prerequisites=[],
            difficulty=4,
            tags=["descent", "pullback", "compatibility", "fibered-category"],
        )

        self.pullback_consistency_schema: TheoremSchema = make_theorem_schema(
            name="pullback_consistency",
            template_statement=(
                "The pullback functor {f^*} along {f} preserves the sheaf condition: "
                "if {S} satisfies descent along {U_cover}, then {f^*S} satisfies "
                "descent along {f^{-1}(U_cover)}."
            ),
            variables={
                "f^*": "the pullback functor induced by f",
                "f": "a morphism in the semantic site",
                "S": "a sheaf satisfying descent along U_cover",
                "U_cover": "a covering sieve on the target object",
                "f^{-1}(U_cover)": "the induced covering sieve on the source object",
            },
            subsystem=SubsystemKind.DESCENT,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "The pullback functor f^* sends sheaves to sheaves. More precisely, "
                "if a presheaf S satisfies the sheaf condition for a covering sieve "
                "U_cover of an object X, then its pullback f^*S satisfies the sheaf "
                "condition for the induced covering sieve f^{-1}(U_cover). "
                "This schema must be discharged for every morphism f and cover U_cover "
                "appearing in the execution trace. Proof proceeds by diagram chase "
                "in the category of sheaves on the induced site."
            ),
            prerequisites=["descent_compatibility"],
            difficulty=5,
            tags=["descent", "pullback", "sheaf", "functor", "cover"],
        )

        self.sheaf_condition_schema: TheoremSchema = make_theorem_schema(
            name="sheaf_condition",
            template_statement=(
                "The presheaf {P} satisfies the sheaf condition: for every cover "
                "{U} of {X}, the equalizer diagram "
                "Gamma({X},{P}) to prod_i Gamma({U_i},{P}) implies prod_ij Gamma({U_ij},{P}) "
                "is exact."
            ),
            variables={
                "P": "a presheaf on the semantic site",
                "U": "a covering family of X",
                "X": "the base object being covered",
                "U_i": "the individual covering objects U_i in U",
                "U_ij": "the pairwise intersections U_i cap U_j",
            },
            subsystem=SubsystemKind.DESCENT,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "The classical sheaf condition states that the global sections of P "
                "over X are uniquely determined by compatible local sections over a "
                "covering family {U_i to X}. The equalizer diagram encodes this "
                "exactly: injectivity of the left map says local sections determine "
                "global sections, and exactness at the product says compatible local "
                "sections glue. Discharging this schema for every cover used in the "
                "execution guarantees that section-assembly is well-defined."
            ),
            prerequisites=[],
            difficulty=3,
            tags=["sheaf", "equalizer", "gluing", "cover", "sections"],
        )

        self.descent_data_coherence_schema: TheoremSchema = make_theorem_schema(
            name="descent_data_coherence",
            template_statement=(
                "The descent datum {D} over cover {U_cover} of {X} satisfies the "
                "full coherence conditions: the transition isomorphisms "
                "{phi_ij : D_i|_{U_ij} to D_j|_{U_ij}} satisfy the cocycle condition "
                "{phi_jk circ phi_ij = phi_ik} on all triple overlaps {U_ijk}."
            ),
            variables={
                "D": "a descent datum assembled from local pieces",
                "U_cover": "the covering sieve on X",
                "X": "the base object",
                "phi_ij : D_i|_{U_ij} to D_j|_{U_ij}": "the transition isomorphism on pairwise overlaps",
                "U_ij": "the pairwise overlap U_i cap U_j",
                "phi_jk circ phi_ij = phi_ik": "the cocycle condition on triple overlaps",
                "U_ijk": "the triple overlap U_i cap U_j cap U_k",
            },
            subsystem=SubsystemKind.DESCENT,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "Descent data must satisfy a cocycle condition on triple overlaps "
                "to define a globally coherent object. The coherence conditions "
                "ensure that the transition isomorphisms phi_ij form a 1-cocycle "
                "in the Cech cohomology of the cover, which is the correct "
                "categorical condition for the datum to be effective. Without this "
                "coherence, multiple distinct local objects could claim to represent "
                "the same global descent datum, leading to inconsistency in the "
                "semantic model."
            ),
            prerequisites=["descent_compatibility"],
            difficulty=6,
            tags=["descent", "coherence", "cocycle", "cech", "transition-isomorphism"],
        )

        self.effective_descent_schema: TheoremSchema = make_theorem_schema(
            name="effective_descent",
            template_statement=(
                "The morphism {f : Y to X} is an effective descent morphism: the "
                "comparison functor {K_f : Sh(X) to Desc(f)} from sheaves on {X} "
                "to {f}-descent data is an equivalence of categories."
            ),
            variables={
                "f : Y to X": "a morphism in the semantic site",
                "K_f : Sh(X) to Desc(f)": "the comparison functor from sheaves on X to f-descent data",
                "Sh(X)": "the category of sheaves on X",
                "Desc(f)": "the category of f-descent data",
            },
            subsystem=SubsystemKind.DESCENT,
            proof_style=ProofStyle.AUTOMATED,
            description=(
                "An effective descent morphism f : Y to X is one for which the "
                "comparison functor K_f : Sh(X) to Desc(f) is an equivalence. This "
                "is the content of Grothendieck's descent theory: data on X is "
                "equivalent to data on Y together with coherent gluing. In JuGeo, "
                "this theorem must be discharged for every morphism that is used "
                "to pull back or push forward semantic content across the pack "
                "boundary. Proof proceeds by verifying that K_f is full, faithful, "
                "and essentially surjective, typically via the Barr-Beck monadicity "
                "theorem applied to the adjunction f^* dashv f_*."
            ),
            prerequisites=["descent_compatibility", "descent_data_coherence"],
            difficulty=8,
            tags=["descent", "effective-descent", "equivalence", "comparison-functor"],
        )

    # ------------------------------------------------------------------
    # Interface methods
    # ------------------------------------------------------------------

    def get_all_schemas(self) -> list[TheoremSchema]:
        """Return all five descent theorem schemas in canonical order.

        The canonical order is: compatibility, sheaf_condition,
        pullback_consistency, coherence, effective_descent.  This ordering
        respects prerequisite dependencies.

        Returns
        -------
        list[TheoremSchema]
            All five schemas in dependency order.
        """
        return [
            self.descent_compatibility_schema,
            self.sheaf_condition_schema,
            self.pullback_consistency_schema,
            self.descent_data_coherence_schema,
            self.effective_descent_schema,
        ]

    def get_schema_by_name(self, name: str) -> TheoremSchema | None:
        """Retrieve a schema by its ``name`` field.

        Performs a linear scan over the five schemas and returns the first
        match, or ``None`` if no schema has the given name.

        Parameters
        ----------
        name:
            The schema name to search for.

        Returns
        -------
        TheoremSchema or None
        """
        for schema in self.get_all_schemas():
            if schema.name == name:
                return schema
        return None

    def as_subsystem_schema(self) -> SubsystemSchema:
        """Wrap all descent schemas in a :class:`SubsystemSchema` bundle.

        Constructs a fresh :class:`SubsystemSchema` with all five schemas
        registered via ``add_schema``.

        Returns
        -------
        SubsystemSchema
            The bundle ready for registration in the theorem-schema registry.
        """
        bundle = SubsystemSchema(
            subsystem_name=SubsystemKind.DESCENT,
            subsystem_id=str(uuid.uuid4()),
            required_theorems=self.required_names(),
        )
        for schema in self.get_all_schemas():
            bundle.add_schema(schema)
        return bundle

    def required_names(self) -> list[str]:
        """Return the list of theorem names required by the Descent subsystem.

        Returns
        -------
        list[str]
            Theorem names in dependency order.
        """
        return [s.name for s in self.get_all_schemas()]

    def describe(self) -> str:
        """Return a human-readable description of this template library.

        Summarises the purpose of the Descent subsystem and lists the five
        theorems it must discharge, with difficulty ratings.

        Returns
        -------
        str
            Multi-line description string.
        """
        lines: list[str] = [
            "DescentSchemaTemplate — Descent subsystem theorem library",
            "  theory2.tex §36.2.1",
            "  Purpose: Encode the sheaf/descent proof burden for the semantic site.",
            "  Theorems:",
        ]
        for s in self.get_all_schemas():
            diff = s.metadata.get("difficulty", "?")
            lines.append(
                f"    [{diff}/10] {s.name}: {s.description[:80]}..."
            )
        return "\n".join(lines)


