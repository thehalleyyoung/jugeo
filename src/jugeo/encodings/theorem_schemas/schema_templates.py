"""Schema templates for descent, trust, evidence, federation, and invalidation subsystems.

Encodes the theorem template library for Chapter 36 of theory2.tex. Each template
class provides pre-built TheoremSchema instances covering the required proofs for
its subsystem. Templates use {variable} placeholders that are instantiated with
concrete mathematical objects at proof time.

copilot: schema template library for all JuGeo subsystems.

Background
----------
Chapter 36 of theory2.tex specifies the *proof burden* for each JuGeo
subsystem: the minimal set of theorems that must be discharged before the
subsystem can be trusted in production. This module encodes that burden as a
library of :class:`~jugeo.encodings.theorem_schemas.models.TheoremSchema`
objects, one per theorem family, each with carefully chosen ``{variable}``
placeholders so that concrete proof obligations can be mass-generated by
binding the variables to specific mathematical objects at proof time.

The five subsystems covered here — Descent, Trust, Evidence, Federation, and
Invalidation — are the ones whose mathematical content is most thoroughly
developed in theory2.tex.  The remaining three (Memory, Judgment, Encoding)
are handled directly in :mod:`jugeo.encodings.theorem_schemas.subsystem_schemas`
because they do not yet have sufficiently general template structure.

Mathematical context
--------------------
* **Descent**: The JuGeo semantic site is a Grothendieck site.  The descent
  subsystem manages the sheaf condition, pullback functors, and effective
  descent morphisms.  Correctness requires that every pack's local sections
  glue uniquely to global sections, and that pullback commutes with the sheaf
  condition in the expected functorial way.

* **Trust**: Trust is modelled as a commutative quantale ``(T, ≤, ⊗, ⊤)``.
  The trust subsystem maintains a monotone trust map, a composition law, a
  propagation mechanism over evidence channels, and a downward-closed
  revocation semantics.  Soundness of trust annotations is a joint property of
  the trust map and the semantic model.

* **Evidence**: An evidence bundle ``B`` is a finite set of discharge records
  paired with the propositions they support.  The evidence subsystem must prove
  that every discharged item is *sound* (true in the model), that the bundle is
  *complete* (covers all obligations), that items are *independent* when
  claimed to be, and that all items remain *fresh* with respect to the current
  revocation log.

* **Federation**: A JuGeo federation is a diagram of packs connected by
  interface morphisms.  The federation subsystem must prove consistency of
  shared boundary judgments, compatibility of interface morphisms with judgment
  types, cross-pack descent, global coherence, and boundary agreement.

* **Invalidation**: The invalidation subsystem maintains a directed acyclic
  graph ``σ`` of dependency edges between judgments.  It must prove that
  cascade BFS/DFS terminates (because ``σ`` is a DAG), that support sets are
  correct, that stale-marking is conservative, that the cascade is complete
  (every dependent judgment is reached), and that dependency trace records are
  not forged.
"""

