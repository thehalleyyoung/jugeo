def make_theorem_schema(
    name: str,
    template_statement: str,
    variables: dict[str, str],
    subsystem: SubsystemKind,
    proof_style: ProofStyle = ProofStyle.AUTOMATED,
    description: str = "",
    prerequisites: list[str] | None = None,
    difficulty: int = 5,
    tags: list[str] | None = None,
) -> TheoremSchema:
    """Construct a :class:`TheoremSchema` with all standard fields populated.

    This factory is the canonical way to create schemas within this module.
    It ensures that every schema receives a fresh UUID, a creation timestamp,
    and sensible defaults for optional fields.  Difficulty and prerequisite
    information are stored in the schema's ``metadata`` dict so that they are
    available to downstream tooling without polluting the core API.

    Parameters
    ----------
    name:
        Short ``snake_case`` identifier for the theorem.
    template_statement:
        The theorem statement with ``{variable}`` placeholders.
    variables:
        Mapping from placeholder name (matching ``{name}`` in the template)
        to a brief English description of what the variable ranges over.
    subsystem:
        The owning :class:`SubsystemKind`.
    proof_style:
        How the theorem should be discharged.  Defaults to
        :attr:`~ProofStyle.AUTOMATED`.
    description:
        Longer prose description of the theorem's mathematical content.
    prerequisites:
        Names of schemas that must be discharged before this one.
    difficulty:
        Proof difficulty on 1–10 scale.
    tags:
        Free-form keyword tags for search and categorisation.

    Returns
    -------
    TheoremSchema
        A fully-populated schema ready for registration.

    Examples
    --------
    >>> s = make_theorem_schema(
    ...     name="descent_compat",
    ...     template_statement="For {f}, the datum {D} satisfies compatibility.",
    ...     variables={"f": "a site morphism", "D": "a descent datum"},
    ...     subsystem=SubsystemKind.DESCENT,
    ... )
    >>> s.name
    'descent_compat'
    """
    all_tags = list(tags or [])
    all_tags.append(f"difficulty:{difficulty}")
    for prereq in (prerequisites or []):
        all_tags.append(f"prereq:{prereq}")

    return TheoremSchema(
        name=name,
        template_statement=template_statement,
        variables=variables,
        proof_style=proof_style,
        subsystem=subsystem,
        schema_id=str(uuid.uuid4()),
        tags=all_tags,
        description=description if description else f"Theorem schema: {name}",
        metadata={
            "prerequisites": list(prerequisites or []),
            "difficulty": difficulty,
            "source_chapter": "theory2.tex §36",
        },
        created_at=time.time(),
    )


