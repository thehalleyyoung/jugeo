#: Registry mapping subsystem name to template class.
#: Used by :func:`build_all_templates` and external callers.
ALL_TEMPLATES: dict[str, type] = {
    "descent": DescentSchemaTemplate,
    "trust": TrustSchemaTemplate,
    "evidence": EvidenceSchemaTemplate,
    "federation": FederationSchemaTemplate,
    "invalidation": InvalidationSchemaTemplate,
}


def build_all_templates() -> dict[str, Any]:
    """Instantiate all template classes and return a dict of live instances.

    Constructs one instance of each template class in :data:`ALL_TEMPLATES`
    and returns a dictionary mapping subsystem name to the instantiated
    template object.  This is the primary entry point for code that needs
    to access all template schemas at once, e.g. during registry
    initialisation or full-system validation.

    Returns
    -------
    dict[str, object]
        Keys are subsystem names (``"descent"``, ``"trust"``, etc.);
        values are instantiated template objects.

    Examples
    --------
    >>> templates = build_all_templates()
    >>> descent = templates["descent"]
    >>> schemas = descent.get_all_schemas()
    >>> print(len(schemas))
    5
    """
    return {name: cls() for name, cls in ALL_TEMPLATES.items()}


def describe_template(subsystem_name: str) -> str:
    """Return the :meth:`describe` output for a named subsystem template.

    Instantiates the template class for *subsystem_name* and returns its
    human-readable description.

    Parameters
    ----------
    subsystem_name:
        One of ``"descent"``, ``"trust"``, ``"evidence"``,
        ``"federation"``, ``"invalidation"``.

    Returns
    -------
    str
        Multi-line description, or an error message if not found.

    Raises
    ------
    KeyError
        If *subsystem_name* is not in :data:`ALL_TEMPLATES`.
    """
    cls = ALL_TEMPLATES[subsystem_name]
    instance = cls()
    return instance.describe()


def list_all_schema_names() -> dict[str, list[str]]:
    """Return the complete list of theorem names for every subsystem template.

    Instantiates each template class and collects the result of
    :meth:`required_names` into a dictionary.

    Returns
    -------
    dict[str, list[str]]
        Mapping from subsystem name to list of required theorem names.

    Examples
    --------
    >>> names = list_all_schema_names()
    >>> "descent_compatibility" in names["descent"]
    True
    """
    result: dict[str, list[str]] = {}
    for name, cls in ALL_TEMPLATES.items():
        instance = cls()
        result[name] = instance.required_names()
    return result
