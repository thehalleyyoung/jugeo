@dataclass(slots=True)
class ClauseSpecification:
    """Full specification for a single evaluation clause.

    A ``ClauseSpecification`` captures everything needed to evaluate a single
    logical clause: the type of claim being tested, which scoring function to
    invoke, the acceptance threshold, the relative weight in a weighted
    aggregation, and optional free-text metadata.

    Attributes:
        clause_id:        Unique identifier for this clause (auto-generated by
                          ``create()`` if not supplied).
        clause_name:      Human-readable short name, e.g. ``"completeness_01"``.
        clause_type:      Logical category drawn from ``ClauseType``.
        scoring_function: Name of the scoring function to dispatch to, e.g.
                          ``"soundness"`` or ``"completeness"``.
        threshold:        Minimum score required for the clause to *pass*.
                          Conventionally in [0.0, 1.0].
        weight:           Non-negative weight used in weighted aggregation.
                          Defaults to 1.0.
        description:      Free-text description of what the clause checks.
        tags:             Arbitrary string tags for grouping/filtering.
        metadata:         Arbitrary JSON-serialisable key-value pairs.
    """

    clause_id: str
    clause_name: str
    clause_type: ClauseType
    scoring_function: str
    threshold: float
    weight: float
    description: str
    tags: list[str] = field(default_factory=list)
    metadata: dict = field(default_factory=dict)

    # ---------------------------------------------------------------------------
    @classmethod
    def create(
        cls,
        clause_name: str,
        clause_type: ClauseType,
        scoring_function: str,
        threshold: float = 0.5,
        weight: float = 1.0,
        description: str = "",
        tags: list[str] | None = None,
        metadata: dict | None = None,
    ) -> ClauseSpecification:
        """Factory method: create a ``ClauseSpecification`` with a fresh UUID.

        Args:
            clause_name:      Human-readable name for the clause.
            clause_type:      The logical category (``ClauseType`` enum member).
            scoring_function: Name of the scoring function to use.
            threshold:        Acceptance threshold in [0, 1].  Defaults to 0.5.
            weight:           Relative weight >= 0.  Defaults to 1.0.
            description:      Optional human-readable description.
            tags:             Optional list of string tags.
            metadata:         Optional key-value metadata dict.

        Returns:
            ClauseSpecification: A new, fully initialised clause specification.
        """
        return cls(
            clause_id=_uid(),
            clause_name=clause_name,
            clause_type=clause_type,
            scoring_function=scoring_function,
            threshold=_clamp(threshold, 0.0, 1.0),
            weight=max(0.0, weight),
            description=description,
            tags=list(tags) if tags else [],
            metadata=dict(metadata) if metadata else {},
        )

    # ---------------------------------------------------------------------------
    def is_binary(self) -> bool:
        """Return ``True`` if this clause uses a binary (0/1) threshold.

        A clause is considered binary when its threshold is exactly 0.0 or 1.0,
        meaning the output either fully passes or fully fails with no gradient.

        Returns:
            bool: ``True`` iff threshold == 0.0 or threshold == 1.0.
        """
        return self.threshold == 0.0 or self.threshold == 1.0

    # ---------------------------------------------------------------------------
    def to_dict(self) -> dict:
        """Serialise the specification to a JSON-compatible dictionary.

        Returns:
            dict: All fields as plain Python types suitable for ``json.dumps``.
        """
        return {
            "clause_id": self.clause_id,
            "clause_name": self.clause_name,
            "clause_type": self.clause_type.value,
            "scoring_function": self.scoring_function,
            "threshold": self.threshold,
            "weight": self.weight,
            "description": self.description,
            "tags": list(self.tags),
            "metadata": dict(self.metadata),
        }

    # ---------------------------------------------------------------------------
    @classmethod
    def from_dict(cls, d: dict) -> ClauseSpecification:
        """Deserialise a ``ClauseSpecification`` from a plain dictionary.

        Args:
            d: Dictionary previously produced by ``to_dict()``.

        Returns:
            ClauseSpecification: The reconstructed specification object.
        """
        return cls(
            clause_id=d["clause_id"],
            clause_name=d["clause_name"],
            clause_type=ClauseType(d["clause_type"]),
            scoring_function=d["scoring_function"],
            threshold=float(d["threshold"]),
            weight=float(d["weight"]),
            description=d.get("description", ""),
            tags=list(d.get("tags", [])),
            metadata=dict(d.get("metadata", {})),
        )

    # ---------------------------------------------------------------------------
    def validate(self) -> list[str]:
        """Validate the specification and return a list of error messages.

        An empty list means the specification is valid.

        Returns:
            list[str]: A (possibly empty) list of human-readable error strings.
        """
        errors: list[str] = []
        if not self.clause_id:
            errors.append("clause_id must not be empty")
        if not self.clause_name:
            errors.append("clause_name must not be empty")
        if not (0.0 <= self.threshold <= 1.0):
            errors.append(
                f"threshold must be in [0, 1]; got {self.threshold}"
            )
        if self.weight < 0.0:
            errors.append(f"weight must be >= 0; got {self.weight}")
        if self.scoring_function not in _SCORING_REGISTRY:
            errors.append(
                f"unknown scoring_function '{self.scoring_function}'; "
                f"registered: {sorted(_SCORING_REGISTRY)}"
            )
        return errors

    # ---------------------------------------------------------------------------
    def render_description(self) -> str:
        """Return a rich human-readable description of this clause.

        Combines the clause name, type, scoring function, threshold, and the
        free-text description into a single formatted string for display in
        reports and logs.

        Returns:
            str: Multi-line human-readable description.
        """
        lines = [
            f"Clause: {self.clause_name} [{self.clause_id}]",
            f"  Type:             {self.clause_type.value}",
            f"  Scoring function: {self.scoring_function}",
            f"  Threshold:        {self.threshold:.4f}",
            f"  Weight:           {self.weight:.4f}",
        ]
        if self.description:
            lines.append(f"  Description:      {self.description}")
        if self.tags:
            lines.append(f"  Tags:             {', '.join(self.tags)}")
        return "\n".join(lines)

    # ---------------------------------------------------------------------------
    def summarize(self) -> str:
        """Return a compact one-line summary of the clause specification.

        Returns:
            str: Single-line summary string.
        """
        return (
            f"ClauseSpec({self.clause_name!r}, "
            f"type={self.clause_type.value}, "
            f"fn={self.scoring_function}, "
            f"thresh={self.threshold:.3f}, "
            f"w={self.weight:.3f})"
        )

    # ---------------------------------------------------------------------------
    def score_system_output(self, output: dict) -> float:
        """Dispatch to the registered scoring function and return a score.

        The returned score is clamped to [0.0, 1.0] regardless of what the
        underlying scoring function returns.

        Args:
            output: Arbitrary dictionary representing the system's output.
                    The scoring function will inspect relevant keys.

        Returns:
            float: Score in [0.0, 1.0] for this clause.

        Raises:
            KeyError: If ``scoring_function`` is not registered.
        """
        fn = _SCORING_REGISTRY[self.scoring_function]
        raw = fn(output, self)
        return _clamp(float(raw), 0.0, 1.0)


