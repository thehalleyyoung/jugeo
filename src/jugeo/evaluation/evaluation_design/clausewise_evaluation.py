@dataclass(slots=True)
class ClausewiseScorer:
    """Score a system output against a collection of clause specifications.

    ``ClausewiseScorer`` holds a list of ``ClauseSpecification`` objects and
    provides methods for scoring a single output or aggregating across a batch.
    It is the central workhorse of the clausewise evaluation pipeline.

    Attributes:
        specifications: Ordered list of ``ClauseSpecification`` objects to
                        evaluate against.
        strict_mode:    When ``True``, raise ``ValueError`` on invalid
                        specifications instead of silently skipping them.
        metadata:       Arbitrary JSON-serialisable key-value pairs.
    """

    specifications: list[ClauseSpecification]
    strict_mode: bool = False
    metadata: dict = field(default_factory=dict)

    # ---------------------------------------------------------------------------
    def score(self, system_output: dict) -> list[ClauseResult]:
        """Score *system_output* against every specification and return results.

        Iterates over ``self.specifications`` in order, invoking
        ``score_single`` for each.  Results are returned in the same order as
        the specifications.

        Args:
            system_output: Dictionary representing the system output to score.

        Returns:
            list[ClauseResult]: One ``ClauseResult`` per specification.
        """
        results: list[ClauseResult] = []
        for spec in self.specifications:
            result = self.score_single(spec, system_output)
            results.append(result)
        return results

    # ---------------------------------------------------------------------------
    def score_single(
        self, spec: ClauseSpecification, system_output: dict
    ) -> ClauseResult:
        """Evaluate a single clause specification against *system_output*.

        The raw score is obtained from the specification's registered scoring
        function, then compared against the threshold to determine pass/fail.

        Args:
            spec:          The ``ClauseSpecification`` to evaluate.
            system_output: Dictionary representing the system output.

        Returns:
            ClauseResult: An immutable result record for the clause.
        """
        errors = spec.validate()
        if errors:
            if self.strict_mode:
                raise ValueError(
                    f"Invalid spec '{spec.clause_name}': {errors}"
                )
            # Graceful degradation: score 0.0, mark as failed.
            return ClauseResult(
                clause_id=spec.clause_id,
                clause_type=spec.clause_type,
                score=0.0,
                passed=False,
                evidence={"validation_errors": errors},
                metadata={"scorer": "ClausewiseScorer", "graceful_fail": True},
            )

        raw_score = spec.score_system_output(system_output)
        passed = raw_score >= spec.threshold
        evidence: dict[str, Any] = {
            "raw_score": raw_score,
            "threshold": spec.threshold,
            "scoring_function": spec.scoring_function,
        }
        return ClauseResult(
            clause_id=spec.clause_id,
            clause_type=spec.clause_type,
            score=raw_score,
            passed=passed,
            evidence=evidence,
            metadata={"scorer": "ClausewiseScorer"},
        )

    # ---------------------------------------------------------------------------
    def get_spec_by_id(self, clause_id: str) -> ClauseSpecification | None:
        """Look up a specification by its unique clause_id.

        Args:
            clause_id: The UUID string identifying the desired specification.

        Returns:
            ClauseSpecification | None: The matching spec, or ``None`` if not
            found.
        """
        for spec in self.specifications:
            if spec.clause_id == clause_id:
                return spec
        return None

    # ---------------------------------------------------------------------------
    def aggregate_scores(self, results: list[ClauseResult]) -> float:
        """Compute the weighted-average score across a list of clause results.

        Weights are taken from the corresponding ``ClauseSpecification`` in
        ``self.specifications``.  Specifications with weight 0 are excluded.
        If no specifications have positive weight, returns 0.0.

        Args:
            results: List of ``ClauseResult`` objects to aggregate.

        Returns:
            float: Weighted-average score in [0.0, 1.0].
        """
        total_weight = 0.0
        weighted_sum = 0.0
        # Build a quick lookup for results.
        result_map: dict[str, float] = {r.clause_id: r.score for r in results}
        for spec in self.specifications:
            if spec.weight <= 0.0:
                continue
            score = result_map.get(spec.clause_id, 0.0)
            weighted_sum += spec.weight * score
            total_weight += spec.weight
        if total_weight == 0.0:
            return 0.0
        return _clamp(weighted_sum / total_weight, 0.0, 1.0)

    # ---------------------------------------------------------------------------
    def coverage(self) -> float:
        """Return the fraction of specifications that have a positive weight.

        A specification with weight == 0 is treated as inactive/disabled.

        Returns:
            float: Value in [0.0, 1.0] representing the fraction of active
            specifications.
        """
        if not self.specifications:
            return 0.0
        active = sum(1 for s in self.specifications if s.weight > 0.0)
        return active / len(self.specifications)

    # ---------------------------------------------------------------------------
    def add_specification(self, spec: ClauseSpecification) -> None:
        """Append a new ``ClauseSpecification`` to the scorer.

        Args:
            spec: The specification to add.  Duplicate clause_ids are allowed
                  but may produce unexpected aggregation results.

        Returns:
            None
        """
        self.specifications.append(spec)

    # ---------------------------------------------------------------------------
    def remove_specification(self, clause_id: str) -> bool:
        """Remove the specification with *clause_id* from the scorer.

        Only the first matching specification is removed.

        Args:
            clause_id: The UUID of the specification to remove.

        Returns:
            bool: ``True`` if a specification was removed, ``False`` otherwise.
        """
        for i, spec in enumerate(self.specifications):
            if spec.clause_id == clause_id:
                del self.specifications[i]
                return True
        return False


