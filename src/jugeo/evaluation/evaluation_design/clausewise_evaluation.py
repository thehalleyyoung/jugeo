@dataclass(slots=True)
class ClausewiseEvaluationRunner:
    """Orchestrate a full clausewise evaluation pipeline end-to-end.

    ``ClausewiseEvaluationRunner`` wires together a ``ClausewiseScorer``,
    a ``ClauseWeightCalculator``, and an optional ``EvaluationDesign`` to
    provide a single ``run()`` entry point.  It supports batch execution,
    report generation, and JSON persistence.

    Attributes:
        scorer:            The ``ClausewiseScorer`` that evaluates each output.
        weight_calculator: The ``ClauseWeightCalculator`` that manages weights.
        design:            Optional ``EvaluationDesign`` providing context.
        metadata:          Arbitrary JSON-serialisable key-value pairs.
    """

    scorer: ClausewiseScorer
    weight_calculator: ClauseWeightCalculator
    design: object | None = None  # EvaluationDesign | None
    metadata: dict = field(default_factory=dict)

    # ---------------------------------------------------------------------------
    def run(self, system_output: dict) -> dict:
        """Run the full evaluation pipeline for *system_output*.

        Recomputes weights from the current weighting strategy, scores the
        output, aggregates the scores, and returns a comprehensive result dict.

        Args:
            system_output: Dictionary representing the system output to
                           evaluate.

        Returns:
            dict: Result dictionary with keys ``run_id``, ``timestamp``,
            ``overall_score``, ``passed``, ``clause_results``, ``weights``,
            and ``metadata``.
        """
        run_id = _uid()
        timestamp = _utcnow()

        # Recompute weights for the current set of specs.
        weights = self.weight_calculator.compute_weights(
            self.scorer.specifications
        )
        normalised_weights = self.weight_calculator.normalize(weights)

        # Score the output.
        clause_results = self.scorer.score(system_output)

        # Aggregate using the normalised weights.
        weighted_sum = 0.0
        for result in clause_results:
            w = normalised_weights.get(result.clause_id, 0.0)
            weighted_sum += w * result.score
        overall_score = _clamp(weighted_sum, 0.0, 1.0)

        # Determine overall pass/fail: passed iff all mandatory clauses pass.
        all_pass = all(r.passed for r in clause_results)

        return {
            "run_id": run_id,
            "timestamp": timestamp,
            "overall_score": overall_score,
            "passed": all_pass,
            "clause_results": [
                {
                    "clause_id": r.clause_id,
                    "clause_type": r.clause_type.value,
                    "score": r.score,
                    "passed": r.passed,
                    "evidence": r.evidence,
                }
                for r in clause_results
            ],
            "weights": normalised_weights,
            "metadata": dict(self.metadata),
        }

    # ---------------------------------------------------------------------------
    def run_batch(self, system_outputs: list[dict]) -> list[dict]:
        """Run the evaluation pipeline for every output in *system_outputs*.

        Args:
            system_outputs: A list of system output dictionaries.  Each is
                            evaluated independently.

        Returns:
            list[dict]: One result dictionary per input, in the same order.
        """
        return [self.run(output) for output in system_outputs]

    # ---------------------------------------------------------------------------
    def generate_report(self, results: list[dict]) -> dict:
        """Generate a summary report over a list of run results.

        Computes aggregate statistics: mean/min/max overall score, pass rate,
        per-clause mean scores, and a distribution histogram.

        Args:
            results: List of result dicts returned by ``run()`` or
                     ``run_batch()``.

        Returns:
            dict: Report dict with keys ``n_runs``, ``mean_score``,
            ``min_score``, ``max_score``, ``pass_rate``, ``per_clause``,
            ``generated_at``.
        """
        if not results:
            return {
                "n_runs": 0,
                "mean_score": 0.0,
                "min_score": 0.0,
                "max_score": 0.0,
                "pass_rate": 0.0,
                "per_clause": {},
                "generated_at": _utcnow(),
            }

        scores = [r["overall_score"] for r in results]
        pass_count = sum(1 for r in results if r["passed"])

        # Per-clause statistics.
        per_clause: dict[str, dict] = {}
        for run in results:
            for cr in run.get("clause_results", []):
                cid = cr["clause_id"]
                if cid not in per_clause:
                    per_clause[cid] = {"scores": [], "passes": 0, "runs": 0}
                per_clause[cid]["scores"].append(cr["score"])
                per_clause[cid]["runs"] += 1
                if cr["passed"]:
                    per_clause[cid]["passes"] += 1

        per_clause_summary: dict[str, dict] = {}
        for cid, data in per_clause.items():
            s = data["scores"]
            per_clause_summary[cid] = {
                "mean_score": sum(s) / len(s) if s else 0.0,
                "min_score": min(s) if s else 0.0,
                "max_score": max(s) if s else 0.0,
                "pass_rate": data["passes"] / data["runs"]
                if data["runs"] > 0
                else 0.0,
            }

        return {
            "n_runs": len(results),
            "mean_score": sum(scores) / len(scores),
            "min_score": min(scores),
            "max_score": max(scores),
            "pass_rate": pass_count / len(results),
            "per_clause": per_clause_summary,
            "generated_at": _utcnow(),
        }

    # ---------------------------------------------------------------------------
    def save_results(self, results: list[dict], path: str) -> None:
        """Persist *results* to a JSON file at *path*.

        Args:
            results: List of result dicts to serialise.
            path:    Destination file path.  Parent directories must exist.

        Returns:
            None
        """
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(
                {"results": results, "saved_at": _utcnow()}, fh, indent=2
            )

    # ---------------------------------------------------------------------------
    def load_results(self, path: str) -> list[dict]:
        """Load results from a JSON file previously created by ``save_results``.

        Args:
            path: Path to the JSON file to read.

        Returns:
            list[dict]: The deserialized list of result dicts.
        """
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        return data.get("results", [])


