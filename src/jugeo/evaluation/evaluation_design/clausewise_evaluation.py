def _utcnow() -> float:
    """Return the current UTC time as a POSIX timestamp (float seconds).

    Returns:
        float: Current UTC epoch time in seconds.
    """
    return time.time()


def _uid() -> str:
    """Generate a fresh, collision-resistant UUID4 string.

    Returns:
        str: A 36-character hyphenated UUID4 string.
    """
    return str(uuid.uuid4())


def _clamp(v: float, lo: float, hi: float) -> float:
    """Clamp *v* to the closed interval [lo, hi].

    Args:
        v:  The value to clamp.
        lo: Lower bound (inclusive).
        hi: Upper bound (inclusive).

    Returns:
        float: The clamped value such that lo <= result <= hi.
    """
    return max(lo, min(hi, v))


# ---------------------------------------------------------------------------
# Internal scoring-function registry
# ---------------------------------------------------------------------------

# Maps scoring-function names to callables so that ClauseSpecification can
# dispatch by name rather than importing functions at class definition time.
_SCORING_REGISTRY: dict[str, Callable[..., float]] = {}


def _register_scoring(name: str) -> Callable:
    """Decorator that registers a scoring function under *name*."""

    def decorator(fn: Callable) -> Callable:
        _SCORING_REGISTRY[name] = fn
        return fn

    return decorator


