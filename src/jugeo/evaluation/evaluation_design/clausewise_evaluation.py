@dataclass(slots=True)
class ClauseWeightCalculator:
    """Compute and manage weights for a set of clause specifications.

    Supports three weighting strategies:

    * ``"uniform"`` – all active clauses get equal weight.
    * ``"inverse_frequency"`` – clauses belonging to more common types receive
      lower weight, rewarding diversity of clause types.
    * ``"importance"`` – uses ``base_weights`` as a prior; missing clauses
      default to 1.0.

    Attributes:
        weighting_strategy: One of ``"uniform"``, ``"inverse_frequency"``,
                            ``"importance"``.
        base_weights:       Mapping from ``clause_id`` to prior weight.  Used
                            by the ``"importance"`` strategy.
        metadata:           Arbitrary JSON-serialisable key-value pairs.
    """

    weighting_strategy: str = "uniform"
    base_weights: dict[str, float] = field(default_factory=dict)
    metadata: dict = field(default_factory=dict)

    # ---------------------------------------------------------------------------
    def compute_weights(
        self, specs: list[ClauseSpecification]
    ) -> dict[str, float]:
        """Compute weights for *specs* using the configured strategy.

        Args:
            specs: The list of ``ClauseSpecification`` objects to weight.

        Returns:
            dict[str, float]: Mapping from ``clause_id`` to weight.  The
            weights are NOT normalised; call ``normalize()`` explicitly if
            needed.
        """
        if self.weighting_strategy == "uniform":
            return {s.clause_id: 1.0 for s in specs}

        if self.weighting_strategy == "inverse_frequency":
            # Count occurrences of each ClauseType.
            type_counts: dict[str, int] = {}
            for s in specs:
                type_counts[s.clause_type.value] = (
                    type_counts.get(s.clause_type.value, 0) + 1
                )
            weights: dict[str, float] = {}
            for s in specs:
                count = type_counts[s.clause_type.value]
                # Inverse frequency: rarer clause types get higher weight.
                weights[s.clause_id] = 1.0 / count if count > 0 else 1.0
            return weights

        if self.weighting_strategy == "importance":
            return {
                s.clause_id: self.base_weights.get(s.clause_id, 1.0)
                for s in specs
            }

        # Unknown strategy – fall back to uniform.
        return {s.clause_id: 1.0 for s in specs}

    # ---------------------------------------------------------------------------
    def normalize(self, weights: dict[str, float]) -> dict[str, float]:
        """Normalise *weights* so that the values sum to 1.0.

        Args:
            weights: Raw weights mapping ``clause_id`` to a non-negative float.

        Returns:
            dict[str, float]: Normalised weights summing to 1.0.  If the total
            is zero, all weights are set to ``1 / len(weights)``.
        """
        total = sum(weights.values())
        if total == 0.0:
            n = len(weights)
            return {k: (1.0 / n if n > 0 else 0.0) for k in weights}
        return {k: v / total for k, v in weights.items()}

    # ---------------------------------------------------------------------------
    def update_from_results(self, results: list[ClauseResult]) -> None:
        """Update ``base_weights`` using the inverse of each clause's score.

        Clauses with low scores get higher weight on the next run, focusing
        attention on the weakest areas.

        Args:
            results: List of ``ClauseResult`` objects from a previous run.

        Returns:
            None
        """
        for result in results:
            # Inverse-score weighting: (1 - score) + epsilon to avoid zero.
            inverse_score = 1.0 - _clamp(result.score, 0.0, 1.0) + 1e-6
            self.base_weights[result.clause_id] = inverse_score

    # ---------------------------------------------------------------------------
    def get_effective_weight(self, clause_id: str) -> float:
        """Return the effective base weight for *clause_id*.

        Falls back to 1.0 if the clause has no recorded base weight.

        Args:
            clause_id: The UUID of the clause to look up.

        Returns:
            float: The recorded base weight, or 1.0 if not set.
        """
        return self.base_weights.get(clause_id, 1.0)


