def run_clausewise_evaluation(
    specifications: list[ClauseSpecification],
    system_output: dict,
    weights: dict[str, float] | None = None,
) -> list[ClauseResult]:
    """Run clausewise evaluation and return per-clause results.

    This is the primary functional entry point for clausewise evaluation.
    It constructs a temporary ``ClausewiseScorer``, applies any provided
    weight overrides, and returns the list of ``ClauseResult`` objects.

    Args:
        specifications: Ordered list of ``ClauseSpecification`` objects
                        defining the evaluation criteria.
        system_output:  Dictionary representing the system output to score.
        weights:        Optional mapping from ``clause_id`` to weight override.
                        Overrides ``spec.weight`` for matching clause IDs.

    Returns:
        list[ClauseResult]: One ``ClauseResult`` per specification, in the
        same order as *specifications*.
    """
    # Apply weight overrides if provided.
    effective_specs: list[ClauseSpecification] = []
    for spec in specifications:
        if weights and spec.clause_id in weights:
            # Create an updated copy with the overridden weight.
            updated = ClauseSpecification(
                clause_id=spec.clause_id,
                clause_name=spec.clause_name,
                clause_type=spec.clause_type,
                scoring_function=spec.scoring_function,
                threshold=spec.threshold,
                weight=weights[spec.clause_id],
                description=spec.description,
                tags=list(spec.tags),
                metadata=dict(spec.metadata),
            )
            effective_specs.append(updated)
        else:
            effective_specs.append(spec)

    scorer = ClausewiseScorer(specifications=effective_specs)
    return scorer.score(system_output)


def aggregate_clause_scores(
    results: list[ClauseResult],
    weights: dict[str, float] | None = None,
) -> float:
    """Aggregate clause results into a single overall score.

    Computes a weighted average of all clause scores.  If *weights* is
    supplied, it overrides any weights stored in ``ClauseResult`` metadata.
    Unweighted results default to weight 1.0.

    Args:
        results: List of ``ClauseResult`` objects to aggregate.
        weights: Optional mapping from ``clause_id`` to weight.  Missing
                 clause IDs default to 1.0.

    Returns:
        float: Weighted-average score in [0.0, 1.0].  Returns 0.0 for an
        empty list.
    """
    if not results:
        return 0.0

    total_weight = 0.0
    weighted_sum = 0.0
    for result in results:
        w = 1.0
        if weights is not None:
            w = weights.get(result.clause_id, 1.0)
        weighted_sum += w * result.score
        total_weight += w

    if total_weight == 0.0:
        return 0.0
    return _clamp(weighted_sum / total_weight, 0.0, 1.0)
