@_register_scoring("soundness")
def _score_soundness(output: dict, spec: ClauseSpecification) -> float:
    """Score *output* against a soundness clause.

    Soundness measures whether every claim made by the system output is
    supported by the available evidence.  The heuristic used here inspects
    the output dict for a ``"claims"`` list and a ``"supported_claims"`` list,
    computing the ratio of supported to total claims.  If neither key is
    present but a ``"score"`` key exists, that value is used directly.

    Args:
        output: Dictionary representing the system output.
        spec:   The ``ClauseSpecification`` being evaluated (may be used for
                threshold or tag-based customisation in future versions).

    Returns:
        float: Soundness score in [0.0, 1.0].
    """
    # Strategy 1: explicit soundness score in output.
    if "soundness_score" in output:
        return _clamp(float(output["soundness_score"]), 0.0, 1.0)

    # Strategy 2: count supported vs total claims.
    claims = output.get("claims", [])
    supported = output.get("supported_claims", [])
    if claims:
        ratio = len(supported) / len(claims)
        return _clamp(ratio, 0.0, 1.0)

    # Strategy 3: check for a generic score key.
    if "score" in output:
        return _clamp(float(output["score"]), 0.0, 1.0)

    # Strategy 4: presence-based – return 0.5 as a neutral default when no
    # evidence can be computed.
    return 0.5


@_register_scoring("completeness")
def _score_completeness(output: dict, spec: ClauseSpecification) -> float:
    """Score *output* against a completeness clause.

    Completeness measures whether the system output covers all required
    information fields.  The implementation looks for a ``"required_fields"``
    list in the spec metadata and computes the fraction of those fields
    present in the output.  Falls back to inspecting ``"coverage"`` or
    ``"completeness_score"`` keys in the output.

    Args:
        output: Dictionary representing the system output.
        spec:   The ``ClauseSpecification`` being evaluated.  The
                ``spec.metadata["required_fields"]`` key is consulted when
                present.

    Returns:
        float: Completeness score in [0.0, 1.0].
    """
    # Strategy 1: explicit completeness score.
    if "completeness_score" in output:
        return _clamp(float(output["completeness_score"]), 0.0, 1.0)

    # Strategy 2: check required fields from spec metadata.
    required_fields: list[str] = spec.metadata.get("required_fields", [])
    if required_fields:
        present = sum(1 for f in required_fields if f in output)
        return _clamp(present / len(required_fields), 0.0, 1.0)

    # Strategy 3: direct coverage key.
    if "coverage" in output:
        return _clamp(float(output["coverage"]), 0.0, 1.0)

    # Strategy 4: infer from non-empty fields in output.
    if output:
        non_empty = sum(
            1 for v in output.values() if v is not None and v != "" and v != []
        )
        return _clamp(non_empty / len(output), 0.0, 1.0)

    return 0.0


@_register_scoring("consistency")
def _score_consistency(output: dict, spec: ClauseSpecification) -> float:
    """Score *output* against a consistency clause.

    Consistency measures whether the output contains mutually contradictory
    statements.  The implementation checks for a ``"contradictions"`` key
    (a list of flagged contradictions) and a ``"total_statements"`` count.
    If no structured data is available, looks for ``"consistency_score"``.

    Args:
        output: Dictionary representing the system output.
        spec:   The ``ClauseSpecification`` being evaluated.

    Returns:
        float: Consistency score in [0.0, 1.0]; higher is more consistent.
    """
    # Strategy 1: explicit score.
    if "consistency_score" in output:
        return _clamp(float(output["consistency_score"]), 0.0, 1.0)

    # Strategy 2: count contradictions relative to total statements.
    contradictions = output.get("contradictions", [])
    total_statements = output.get("total_statements", None)

    if total_statements is not None and total_statements > 0:
        contradiction_rate = len(contradictions) / total_statements
        # Perfect consistency = 0 contradictions.
        return _clamp(1.0 - contradiction_rate, 0.0, 1.0)

    if contradictions:
        # We know there are contradictions but don't have a denominator;
        # penalise proportionally using a soft inverse function.
        n = len(contradictions)
        return _clamp(1.0 / (1.0 + math.log1p(n)), 0.0, 1.0)

    # Strategy 3: look for an "errors" key as a proxy for inconsistencies.
    errors_list = output.get("errors", [])
    if isinstance(errors_list, list):
        return _clamp(1.0 / (1.0 + len(errors_list)), 0.0, 1.0)

    return 1.0  # No evidence of inconsistency → maximum score.


@_register_scoring("precision")
def _score_precision(output: dict, spec: ClauseSpecification) -> float:
    """Score *output* against a precision clause.

    Precision measures the fraction of returned results that are relevant,
    following the standard information-retrieval definition:
    ``precision = |relevant ∩ retrieved| / |retrieved|``.

    The output is expected to have a ``"retrieved"`` list and a ``"relevant"``
    list (or set).  If a ``"precision_score"`` key is present, it is used
    directly.

    Args:
        output: Dictionary representing the system output.
        spec:   The ``ClauseSpecification`` being evaluated.

    Returns:
        float: Precision score in [0.0, 1.0].
    """
    # Strategy 1: explicit precision score.
    if "precision_score" in output:
        return _clamp(float(output["precision_score"]), 0.0, 1.0)

    # Strategy 2: compute from retrieved / relevant sets.
    retrieved = output.get("retrieved", [])
    relevant = output.get("relevant", [])

    if not retrieved:
        # Nothing retrieved – precision is undefined; return 0.
        return 0.0

    relevant_set = set(relevant)
    true_positives = sum(1 for r in retrieved if r in relevant_set)
    precision = true_positives / len(retrieved)
    return _clamp(precision, 0.0, 1.0)


@_register_scoring("recall")
def _score_recall(output: dict, spec: ClauseSpecification) -> float:
    """Score *output* against a recall clause.

    Recall measures the fraction of all relevant items that were retrieved,
    following the standard information-retrieval definition:
    ``recall = |relevant ∩ retrieved| / |relevant|``.

    The output is expected to have a ``"retrieved"`` list and a ``"relevant"``
    list (or set).  If a ``"recall_score"`` key is present, it is used
    directly.

    Args:
        output: Dictionary representing the system output.
        spec:   The ``ClauseSpecification`` being evaluated.

    Returns:
        float: Recall score in [0.0, 1.0].
    """
    # Strategy 1: explicit recall score.
    if "recall_score" in output:
        return _clamp(float(output["recall_score"]), 0.0, 1.0)

    # Strategy 2: compute from retrieved / relevant sets.
    retrieved = output.get("retrieved", [])
    relevant = output.get("relevant", [])

    if not relevant:
        # Nothing to recall – return 1.0 (vacuously true).
        return 1.0

    retrieved_set = set(retrieved)
    true_positives = sum(1 for r in relevant if r in retrieved_set)
    recall = true_positives / len(relevant)
    return _clamp(recall, 0.0, 1.0)


