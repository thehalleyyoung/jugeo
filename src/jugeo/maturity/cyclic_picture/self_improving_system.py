"""Stage S01: Self-Improving System — JuGeo cyclic_picture package.

copilot: shared-core marker
Theory reference: theory2.tex Ch65

Overview
--------
Stage S01 implements the self-improvement pipeline stage of the cyclic picture
framework described in Ch65 of theory2.tex.  The cyclic picture is a
formalisation of how a mature geometric-reasoning system bootstraps itself
through successive capability expansions while preserving soundness.  S01 is
the opening stage: it receives a raw ``MatureSystem`` object and drives it
through one or more improvement cycles, each of which may extend the system's
capability set, re-tune its priority weights, and record detailed metrics so
that later stages (S02 federated deployment, S03 mature pipeline) can consume
a stable, improved artefact.

Self-improvement soundness theorem (Ch65, §3.2)
-----------------------------------------------
The theorem states that, given a monotone improvement strategy *σ* and a
capability lattice *L*, every finite sequence of improvement cycles produces a
system whose capability set lies strictly above the starting point in *L*,
provided the improvement score exceeds the zero threshold at each step.  The
classes in this module implement the computational witnesses for that theorem:

* ``ImprovementStrategy`` encodes *σ* as a priority-weighted mapping from
  capability domains to improvement kinds.
* ``MetricsTracker`` provides the observation functor that maps system states
  to real-valued measurement sequences.
* ``CapabilityExpander`` maintains the capability lattice element for the
  current system and proposes upward moves.
* ``SelfImprovementRunner`` orchestrates a full sequence of cycles and
  produces the evidence record consumed by the provenance layer.

All public names are listed in ``__all__``.
"""
