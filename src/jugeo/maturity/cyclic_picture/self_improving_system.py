@dataclass(slots=True)
class ImprovementStrategy:
    """An improvement strategy encodes the target improvement kinds and scoring
    logic for a self-improvement cycle, acting as the computational witness for
    the monotone strategy *σ* described in Ch65 §3.2.

    Attributes
    ----------
    strategy_id : str
        Unique identifier for this strategy instance, generated by ``_uid()``.
    name : str
        Human-readable name, e.g. ``'balanced'`` or ``'geometry-first'``.
    description : str
        Prose description of what this strategy optimises.
    target_kinds : list[str]
        List of ``ImprovementKind`` values as strings that this strategy
        targets.  By default populated with all five canonical kinds:
        capability, efficiency, coverage, robustness, federation.
    """

    strategy_id: str
    name: str
    description: str
    target_kinds: list = field(default_factory=list)

    # ------------------------------------------------------------------
    @classmethod
    def create(cls, name: str, description: str) -> "ImprovementStrategy":
        """Factory method that constructs a new ``ImprovementStrategy``.

        Generates a fresh ``strategy_id`` via ``_uid()`` and populates
        ``target_kinds`` with every value in the ``ImprovementKind`` enum so
        that the strategy covers all improvement dimensions by default.

        Parameters
        ----------
        name:
            Short human-readable label for the strategy.
        description:
            Detailed prose explaining what the strategy targets and why.

        Returns
        -------
        ImprovementStrategy
            A freshly created instance with all ``ImprovementKind`` values as
            strings in ``target_kinds``.
        """
        try:
            kinds = [k.value for k in ImprovementKind]
        except Exception:
            kinds = ["capability", "efficiency", "coverage", "robustness", "federation"]
        return cls(
            strategy_id=_uid(),
            name=name,
            description=description,
            target_kinds=kinds,
        )

    # ------------------------------------------------------------------
    def score_opportunity(self, before: float, after: float) -> float:
        """Compute the relative improvement between two scalar metric values.

        Returns the normalised gain clamped at zero so that negative
        regressions score as 0.0 rather than a negative number.  The formula
        is::

            max(0.0, (after - before) / max(|before|, 1e-9))

        This satisfies the monotonicity requirement of the soundness theorem:
        a strategy never rewards regression.

        Parameters
        ----------
        before:
            The metric value before the improvement cycle.
        after:
            The metric value after the improvement cycle.

        Returns
        -------
        float
            Non-negative relative improvement score.
        """
        denom = max(abs(before), 1e-9)
        return max(0.0, (after - before) / denom)

    # ------------------------------------------------------------------
    def recommend_next_kind(self, history: list = None) -> str:
        """Recommend the next improvement kind based on cycle history length.

        Cycles through ``target_kinds`` using the length of *history* as a
        round-robin index so that successive calls with growing histories step
        through every kind in order.

        Parameters
        ----------
        history:
            Optional list of past cycle records.  Only its length is used.
            Defaults to an empty list when ``None``.

        Returns
        -------
        str
            The recommended improvement kind string.
        """
        if not self.target_kinds:
            return "capability"
        idx = len(history or []) % len(self.target_kinds)
        return self.target_kinds[idx]

    # ------------------------------------------------------------------
    def to_dict(self) -> dict:
        """Serialise this strategy to a plain dictionary.

        Returns
        -------
        dict
            A JSON-serialisable dictionary with keys ``strategy_id``, ``name``,
            ``description``, and ``target_kinds``.
        """
        return {
            "strategy_id": self.strategy_id,
            "name": self.name,
            "description": self.description,
            "target_kinds": list(self.target_kinds),
        }


