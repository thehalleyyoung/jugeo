@dataclass(slots=True)
class CapabilityExpander:
    """Maintains the current capability set and proposes upward expansions.

    This class is the capability-lattice element referred to in Ch65 §3.2.
    ``known_capabilities`` is the current position in the lattice; every call
    to ``propose_expansions`` suggests moves that would raise it.

    Attributes
    ----------
    expander_id : str
        Unique identifier for this expander instance.
    known_capabilities : list[str]
        The capabilities currently known/enabled for the system.
    """

    expander_id: str
    known_capabilities: list = field(default_factory=list)

    # ------------------------------------------------------------------
    @classmethod
    def create(cls, initial_capabilities: list = None) -> "CapabilityExpander":
        """Factory method for ``CapabilityExpander``.

        Parameters
        ----------
        initial_capabilities:
            Optional list of capability strings to seed the expander with.
            Defaults to an empty list when ``None``.

        Returns
        -------
        CapabilityExpander
            A fresh instance with the given initial capabilities.
        """
        return cls(
            expander_id=_uid(),
            known_capabilities=list(initial_capabilities) if initial_capabilities else [],
        )

    # ------------------------------------------------------------------
    def add_capability(self, cap: str) -> None:
        """Add *cap* to ``known_capabilities`` if not already present.

        Idempotent: adding a capability that already exists is a no-op.

        Parameters
        ----------
        cap:
            The capability string to add.
        """
        if cap not in self.known_capabilities:
            self.known_capabilities.append(cap)

    # ------------------------------------------------------------------
    def remove_capability(self, cap: str) -> None:
        """Remove *cap* from ``known_capabilities`` if present.

        No-op if *cap* is not in the list, so callers do not need to guard
        with ``in`` checks.

        Parameters
        ----------
        cap:
            The capability string to remove.
        """
        if cap in self.known_capabilities:
            self.known_capabilities.remove(cap)

    # ------------------------------------------------------------------
    def propose_expansions(self, candidate_pool: list = None) -> list:
        """Return a list of capabilities not yet in ``known_capabilities``.

        If *candidate_pool* is provided, returns the subset of pool members
        that are not already known.  If no pool is provided, returns a
        default set of three generic capability strings (excluding any that
        happen to already be known).

        Parameters
        ----------
        candidate_pool:
            Optional list of candidate capability strings to filter against.

        Returns
        -------
        list[str]
            Capabilities that are in the pool but not yet known.
        """
        if candidate_pool is not None:
            return [c for c in candidate_pool if c not in self.known_capabilities]
        defaults = [
            "streaming_inference",
            "incremental_learning",
            "distributed_aggregation",
        ]
        return [d for d in defaults if d not in self.known_capabilities]

    # ------------------------------------------------------------------
    def to_dict(self) -> dict:
        """Serialise this expander to a plain dictionary.

        Returns
        -------
        dict
            A JSON-serialisable dictionary with keys ``expander_id`` and
            ``known_capabilities``.
        """
        return {
            "expander_id": self.expander_id,
            "known_capabilities": list(self.known_capabilities),
        }


