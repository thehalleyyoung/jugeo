@dataclass(slots=True)
class SelfImprovementRunner:
    """Orchestrates a sequence of improvement cycles using a strategy, metrics
    tracker, and capability expander.

    ``SelfImprovementRunner`` is the top-level object for stage S01.  It wires
    together ``ImprovementStrategy``, ``MetricsTracker``, and
    ``CapabilityExpander`` into a coherent pipeline and records a history of
    cycle results that can be summarised into a report.

    Attributes
    ----------
    runner_id : str
        Unique identifier for this runner instance.
    strategy : ImprovementStrategy
        The strategy used to score and recommend improvements.
    tracker : MetricsTracker
        The metrics tracker that records per-cycle observations.
    expander : CapabilityExpander
        The capability expander that proposes new capabilities.
    cycle_history : list[dict]
        Append-only log of cycle result dictionaries produced by
        ``run_one_cycle``.
    """

    runner_id: str
    strategy: ImprovementStrategy
    tracker: MetricsTracker
    expander: CapabilityExpander
    cycle_history: list = field(default_factory=list)

    # ------------------------------------------------------------------
    @classmethod
    def create(cls) -> "SelfImprovementRunner":
        """Factory method for ``SelfImprovementRunner``.

        Creates a fresh strategy, tracker, and expander with default parameters
        and wires them together into a new runner.

        Returns
        -------
        SelfImprovementRunner
            A fully initialised runner ready to execute improvement cycles.
        """
        return cls(
            runner_id=_uid(),
            strategy=ImprovementStrategy.create("default", "Default improvement strategy"),
            tracker=MetricsTracker.create(),
            expander=CapabilityExpander.create(),
            cycle_history=[],
        )

    # ------------------------------------------------------------------
    def run_one_cycle(self, before_metrics: dict, after_metrics: dict) -> dict:
        """Execute a single improvement cycle and record the result.

        Records each metric in *before_metrics* and *after_metrics* to the
        tracker, computes the overall gain, and appends a result dict to
        ``cycle_history``.

        Parameters
        ----------
        before_metrics:
            Dict mapping metric names to their pre-cycle float values.
        after_metrics:
            Dict mapping metric names to their post-cycle float values.

        Returns
        -------
        dict
            A result dictionary with keys ``cycle_id``, ``gain``,
            ``before_metrics``, ``after_metrics``, and ``timestamp``.
        """
        for k, v in before_metrics.items():
            self.tracker.record("before_" + k, float(v))
        for k, v in after_metrics.items():
            self.tracker.record("after_" + k, float(v))

        gain = compute_improvement_score(before_metrics, after_metrics)
        result = {
            "cycle_id": _uid(),
            "gain": gain,
            "before_metrics": dict(before_metrics),
            "after_metrics": dict(after_metrics),
            "timestamp": _utcnow(),
        }
        self.cycle_history.append(result)
        return result

    # ------------------------------------------------------------------
    def run_n_cycles(self, n: int, metric_fn=None) -> list:
        """Execute *n* improvement cycles in sequence.

        Parameters
        ----------
        n:
            Number of cycles to run.  If ``n <= 0``, returns an empty list
            immediately.
        metric_fn:
            Optional callable with signature ``() -> (before_dict, after_dict)``.
            If provided, its return value is used as the metrics for each cycle.
            If ``None``, dummy metrics are used (``{"score": 0.5}`` before and
            ``{"score": 0.8}`` after).

        Returns
        -------
        list[dict]
            List of cycle result dicts in execution order.
        """
        results = []
        for _ in range(n):
            if metric_fn is not None:
                before, after = metric_fn()
            else:
                before = {"score": 0.5}
                after = {"score": 0.8}
            results.append(self.run_one_cycle(before, after))
        return results

    # ------------------------------------------------------------------
    def generate_report(self) -> dict:
        """Summarise all executed cycles into a report dictionary.

        Returns
        -------
        dict
            A dictionary with keys ``runner_id``, ``total_cycles``,
            ``avg_gain``, and ``cycle_history``.
        """
        total = len(self.cycle_history)
        avg_gain = (
            sum(c["gain"] for c in self.cycle_history) / total if total > 0 else 0.0
        )
        return {
            "runner_id": self.runner_id,
            "total_cycles": total,
            "avg_gain": avg_gain,
            "cycle_history": list(self.cycle_history),
        }

    # ------------------------------------------------------------------
    def to_dict(self) -> dict:
        """Serialise this runner to a plain dictionary.

        Returns
        -------
        dict
            A JSON-serialisable dictionary with keys ``runner_id``,
            ``strategy``, ``tracker``, and ``expander``.
        """
        return {
            "runner_id": self.runner_id,
            "strategy": self.strategy.to_dict(),
            "tracker": self.tracker.to_dict(),
            "expander": self.expander.to_dict(),
        }


