def run_improvement_cycle(system: Any = None, kind: str = "capability") -> dict:
    """Run a single named improvement cycle against *system*.

    Creates dummy before/after metric dicts and computes the gain.  This
    function is a convenience wrapper suitable for quick integration tests and
    scripting; for production use prefer ``SelfImprovementRunner.run_one_cycle``.

    Parameters
    ----------
    system:
        An optional system object.  Accepted but not inspected; present for
        API compatibility with callers that pass a ``MatureSystem`` instance.
    kind:
        The improvement kind string, e.g. ``'capability'``.  Included in the
        returned dict for traceability.

    Returns
    -------
    dict
        A dictionary with keys ``cycle_id``, ``kind``, and ``gain``.
    """
    before = {"score": 0.5, "coverage": 0.6}
    after = {"score": 0.75, "coverage": 0.85}
    gain = compute_improvement_score(before, after)
    return {
        "cycle_id": _uid(),
        "kind": kind,
        "gain": gain,
    }


def assess_improvement(before: dict, after: dict) -> dict:
    """Return the absolute change for each key in *before*.

    For every key *k* in *before*, the result maps *k* to
    ``after.get(k, 0.0) - before[k]``.  Keys present only in *after* are
    ignored; keys present only in *before* use ``0.0`` as the after-value.

    Parameters
    ----------
    before:
        Baseline metric dictionary.
    after:
        Post-cycle metric dictionary.

    Returns
    -------
    dict
        Mapping from metric name to absolute change (may be negative).
    """
    result = {}
    for k, v in before.items():
        result[k] = float(after.get(k, 0.0)) - float(v)
    return result


def compute_improvement_score(before: dict, after: dict) -> float:
    """Compute the mean relative improvement across shared keys.

    Implements the same formula as ``models._compute_gain_from_metrics``:

        score = mean over shared keys of (after_k - before_k) / max(|before_k|, 1e-9)

    Parameters
    ----------
    before:
        Metric values before the improvement.
    after:
        Metric values after the improvement.

    Returns
    -------
    float
        Mean relative improvement, or ``0.0`` if there are no shared keys.
    """
    shared = set(before.keys()) & set(after.keys())
    if not shared:
        return 0.0
    total = 0.0
    for k in shared:
        denom = max(abs(float(before[k])), 1e-9)
        total += (float(after[k]) - float(before[k])) / denom
    return total / len(shared)


def select_best_strategy(
    strategies: list,
    context: dict = None,
) -> "ImprovementStrategy":
    """Return the strategy with the most target kinds.

    Selects the ``ImprovementStrategy`` whose ``target_kinds`` list is longest.
    On a tie, returns the first strategy in *strategies* with the maximum
    length.  The *context* parameter is accepted for API compatibility but is
    not currently used.

    Parameters
    ----------
    strategies:
        Non-empty list of ``ImprovementStrategy`` instances.
    context:
        Optional context dictionary; reserved for future use.

    Returns
    -------
    ImprovementStrategy
        The strategy with the most target kinds.
    """
    return max(strategies, key=lambda s: len(s.target_kinds))
