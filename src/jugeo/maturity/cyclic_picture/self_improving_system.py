@dataclass(slots=True)
class MetricsTracker:
    """A windowed time-series tracker for named float metrics.

    Maintains an append-only list of observations for each metric key and
    provides rolling statistics (current, delta, trend, windowed average) over
    a configurable window.  This class is the observation functor referred to
    in Ch65 §3.2 — it maps a sequence of system states to a real-valued
    measurement stream.

    Attributes
    ----------
    tracker_id : str
        Unique identifier for this tracker instance.
    window_size : int
        Maximum number of recent observations used by windowed statistics.
    metrics : dict[str, list[float]]
        Raw observation lists, keyed by metric name.  Grows unboundedly; the
        window is applied only at query time.
    """

    tracker_id: str
    window_size: int
    metrics: dict = field(default_factory=dict)

    # ------------------------------------------------------------------
    @classmethod
    def create(cls, window_size: int = 20) -> "MetricsTracker":
        """Factory method for ``MetricsTracker``.

        Parameters
        ----------
        window_size:
            Number of recent values to use for windowed statistics.  Defaults
            to 20, which is sufficient for a typical improvement run of
            ten-to-twenty cycles.

        Returns
        -------
        MetricsTracker
            A fresh instance with an empty metrics dictionary.
        """
        return cls(
            tracker_id=_uid(),
            window_size=window_size,
            metrics={},
        )

    # ------------------------------------------------------------------
    def record(self, key: str, value: float) -> None:
        """Append *value* to the observation list for metric *key*.

        Creates the list on first access so callers never need to initialise
        keys explicitly.

        Parameters
        ----------
        key:
            The metric name, e.g. ``'accuracy'`` or ``'throughput'``.
        value:
            The observed float value to append.
        """
        if key not in self.metrics:
            self.metrics[key] = []
        self.metrics[key].append(float(value))

    # ------------------------------------------------------------------
    def current(self, key: str) -> Optional[float]:
        """Return the most recently recorded value for *key*, or ``None``.

        Parameters
        ----------
        key:
            The metric name to query.

        Returns
        -------
        float or None
            The last element of the observation list, or ``None`` if the key
            has no observations or does not exist.
        """
        vals = self.metrics.get(key)
        if not vals:
            return None
        return vals[-1]

    # ------------------------------------------------------------------
    def delta(self, key: str) -> Optional[float]:
        """Return the most recent one-step change for *key*.

        * If the key has two or more observations, returns ``last - second_last``.
        * If the key has exactly one observation, returns ``0.0`` (no change
          yet observable).
        * If the key is unknown or has no observations, returns ``None``.

        Parameters
        ----------
        key:
            The metric name to query.

        Returns
        -------
        float or None
        """
        vals = self.metrics.get(key)
        if vals is None or len(vals) == 0:
            return None
        if len(vals) == 1:
            return 0.0
        return vals[-1] - vals[-2]

    # ------------------------------------------------------------------
    def trend(self, key: str) -> float:
        """Estimate the linear trend (slope) over the last *window_size* values.

        Uses a simple first-to-last slope estimate:
        ``(last - first) / max(n - 1, 1)`` where *n* is the number of windowed
        values.  This is computationally cheap and sufficient for the heuristic
        steering decisions made by ``SelfImprovementRunner``.

        Parameters
        ----------
        key:
            The metric name to query.

        Returns
        -------
        float
            Estimated slope.  Returns ``0.0`` if fewer than two observations
            are available.
        """
        vals = self.metrics.get(key, [])
        window = vals[-self.window_size:] if vals else []
        n = len(window)
        if n < 2:
            return 0.0
        return (window[-1] - window[0]) / max(n - 1, 1)

    # ------------------------------------------------------------------
    def windowed_average(self, key: str) -> float:
        """Return the arithmetic mean of the last *window_size* values for *key*.

        Parameters
        ----------
        key:
            The metric name to query.

        Returns
        -------
        float
            The windowed mean.  Returns ``0.0`` if the key has no observations.
        """
        vals = self.metrics.get(key, [])
        window = vals[-self.window_size:] if vals else []
        if not window:
            return 0.0
        return sum(window) / len(window)

    # ------------------------------------------------------------------
    def to_dict(self) -> dict:
        """Serialise this tracker to a plain dictionary.

        Returns
        -------
        dict
            A JSON-serialisable dictionary with keys ``tracker_id``,
            ``window_size``, and the metric key names stored under ``keys``.
        """
        return {
            "tracker_id": self.tracker_id,
            "window_size": self.window_size,
            "keys": list(self.metrics.keys()),
        }


