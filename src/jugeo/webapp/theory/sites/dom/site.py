"""Grothendieck site modelling the DOM tree.

Each DOM node is a Coordinate; each parent-child edge is a RESTRICTION morphism
child → parent (the sheaf restriction map: data on a parent restricts to any
child).  The topology is generated by one axiom: the direct children of a node
cover it — satisfying Identity, Stability, and Local Character.
"""

from __future__ import annotations

__all__ = ["DOMSite"]

import re
from dataclasses import dataclass, field
from typing import Optional

from jugeo.geometry.site import (
    Site,
    Coordinate,
    CoordinateKind,
    Morphism,
    MorphismKind,
    CoveringFamily,
    GrothendieckTopology,
    SiteBuilder,
)


# ---------------------------------------------------------------------------
# DOMSite
# ---------------------------------------------------------------------------


@dataclass(init=False)
class DOMSite:
    """A Grothendieck site whose objects are DOM nodes and whose morphisms are
    parent-child containment edges.

    **Objects** — one ``Coordinate`` per DOM node (document root, element, text).
    Each uses a flat single-component name; structural nodes keep their tag name.

    **Morphisms** — every parent-child edge ``child → parent`` is a
    ``MorphismKind.RESTRICTION`` morphism (the sheaf restriction map: CSS cascade,
    event propagation, and inherited attributes all flow from parent to child,
    matching the direction of sheaf restriction).  Id-based references such as
    ``<label for="…">`` use ``MorphismKind.TRANSPORT`` because they transport
    data across coordinate boundaries at the same depth.

    **Covering families** — the direct children of any node form a covering
    (``subtree_covering``).  DOM subtrees are disjoint, so sibling overlaps are
    empty and the cocycle condition holds vacuously.
    """

    _site: Site
    _roots: list[str]
    _depth_index: dict[int, list[str]]

    # ------------------------------------------------------------------ #
    # Construction                                                         #
    # ------------------------------------------------------------------ #

    def __init__(self, document_id: str = "document") -> None:
        """Build a minimal DOM site seeded with document → html → {head, body}.

        Parameters
        ----------
        document_id:
            Coordinate name for the document root (defaults to ``"document"``).
            This becomes the single root of the covering site.
        """
        self._site = Site(label=document_id)
        self._roots: list[str] = [document_id]
        self._depth_index: dict[int, list[str]] = {}

        # Per-node bookkeeping (not dataclass fields)
        self._coord_lookup: dict[str, Coordinate] = {}
        self._parent_of: dict[str, str] = {}        # child_name → parent_name
        self._children_of: dict[str, list[str]] = {}
        self._tag_of: dict[str, str] = {}            # coord_name → HTML tag
        self._id_attr_of: dict[str, str] = {}        # coord_name → id attr value
        self._classes_of: dict[str, list[str]] = {}  # coord_name → class list
        self._id_refs: list[tuple[str, str]] = []
        self._counter: int = 0

        # Seed the document root (DOM depth 0)
        doc_coord = Coordinate(components=(document_id,), kind=CoordinateKind.REGION)
        self._register_coord(document_id, doc_coord, tag="document", depth=0)

        # Standard structural nodes
        html_name = self._add_named_node("html", document_id, tag="html", depth=1)
        self._add_named_node("head", html_name, tag="head", depth=2)
        self._add_named_node("body", html_name, tag="body", depth=2)

    # ------------------------------------------------------------------ #
    # Private helpers                                                      #
    # ------------------------------------------------------------------ #

    def _register_coord(
        self,
        name: str,
        coord: Coordinate,
        tag: str,
        depth: int,
        id_attr: Optional[str] = None,
        classes: Optional[list[str]] = None,
    ) -> None:
        """Register a coordinate in all internal indexes without adding morphisms."""
        self._site.add_coordinate(coord)
        self._coord_lookup[name] = coord
        self._tag_of[name] = tag
        self._children_of.setdefault(name, [])
        self._depth_index.setdefault(depth, []).append(name)
        if id_attr:
            self._id_attr_of[name] = id_attr
        if classes:
            self._classes_of[name] = list(classes)

    def _wire_parent_child(self, child_name: str, parent_name: str) -> None:
        """Add a RESTRICTION morphism child → parent and record the edge.

        The morphism goes child → parent (direction of inclusion U ↪ V in the
        site category), so the sheaf's restriction map ρ_{V,U}: F(V) → F(U)
        pulls sections from the parent back to the child.
        """
        child_coord = self._coord_lookup[child_name]
        parent_coord = self._coord_lookup[parent_name]
        morphism = Morphism(
            source=child_coord,
            target=parent_coord,
            kind=MorphismKind.RESTRICTION,
            label=f"{child_name}→{parent_name}",
        )
        self._site.add_morphism(morphism)
        self._parent_of[child_name] = parent_name
        self._children_of.setdefault(parent_name, []).append(child_name)

    def _add_named_node(
        self,
        name: str,
        parent_name: str,
        tag: str,
        depth: int,
        metadata: Optional[dict] = None,
    ) -> str:
        """Add a coordinate with an explicit *name* (used for structural nodes)."""
        coord = Coordinate(
            components=(name,),
            kind=CoordinateKind.REGION,
            metadata=metadata or {},
        )
        self._register_coord(name, coord, tag=tag, depth=depth)
        self._wire_parent_child(name, parent_name)
        return name

    def _fresh_name(self, tag: str) -> str:
        """Return a unique coordinate name for a new element with the given tag."""
        self._counter += 1
        return f"{tag}_{self._counter}"

    def _require_coord(self, name: str) -> Coordinate:
        """Return the Coordinate for *name*, raising ValueError if absent."""
        coord = self._coord_lookup.get(name)
        if coord is None:
            raise ValueError(f"Coordinate {name!r} is not present in the DOM site.")
        return coord

    # ------------------------------------------------------------------ #
    # Public API — adding nodes                                            #
    # ------------------------------------------------------------------ #

    def add_element(
        self,
        tag: str,
        parent_name: str,
        attrs: Optional[dict] = None,
        element_id: Optional[str] = None,
        classes: Optional[list[str]] = None,
    ) -> str:
        """Add a DOM element node under *parent_name* and return its coordinate name.

        A ``MorphismKind.RESTRICTION`` morphism child → parent is added: the new
        element is a restricted section of the parent's coordinate scope (CSS
        cascade, event scope, and inherited attributes all flow from parent to
        child, matching sheaf restriction).

        Parameters
        ----------
        tag:        HTML tag name (e.g. ``"div"``, ``"p"``).
        parent_name: Coordinate name of the parent (must exist).
        attrs:      HTML attributes stored in coordinate metadata.
        element_id: ``id`` attribute; indexed for ``query_selector("#id")``.
        classes:    CSS classes; indexed for ``.class`` selectors.

        Returns
        -------
        str
            Auto-generated coordinate name (e.g. ``"div_3"``).
        """
        self._require_coord(parent_name)
        name = self._fresh_name(tag)
        depth = self.depth_of(parent_name) + 1
        metadata: dict = dict(attrs or {})
        if element_id:
            metadata["id"] = element_id
        if classes:
            metadata["class"] = " ".join(classes)

        coord = Coordinate(
            components=(name,),
            kind=CoordinateKind.REGION,
            metadata=metadata,
        )
        self._register_coord(
            name, coord, tag=tag, depth=depth,
            id_attr=element_id, classes=classes,
        )
        self._wire_parent_child(name, parent_name)
        return name

    def add_text_node(self, parent_name: str, content: str) -> str:
        """Add a text node as a child of *parent_name* and return its coordinate name.

        Text nodes are ``CoordinateKind.REGION`` coordinates whose
        ``metadata["content"]`` carries the raw string.  A ``RESTRICTION``
        morphism child → parent is added — the text is a restricted section of
        the parent element's semantic scope.

        Raises ``ValueError`` if *parent_name* is not present.
        """
        self._require_coord(parent_name)
        name = self._fresh_name("text")
        depth = self.depth_of(parent_name) + 1
        coord = Coordinate(
            components=(name,),
            kind=CoordinateKind.REGION,
            metadata={"content": content, "node_type": "text"},
        )
        self._register_coord(name, coord, tag="#text", depth=depth)
        self._wire_parent_child(name, parent_name)
        return name

    def add_id_reference(self, from_name: str, to_id: str) -> None:
        """Register an id-based reference (e.g. ``<label for="…">``) as a morphism.

        Models a ``MorphismKind.TRANSPORT`` morphism: unlike hierarchical
        RESTRICTION, an id-reference links two nodes at the same depth via a
        named attribute — transporting semantic data (label association, ARIA
        relations) across coordinate boundaries.  TRANSPORT is appropriate
        because ``Morphism.is_invertible()`` treats equal-depth transport
        morphisms as isomorphisms, reflecting the bidirectionality of
        ``for``/``id`` links.

        If the target ``id`` is not yet in the site the reference is stored in
        ``_id_refs`` for bookkeeping but no morphism is created.
        """
        self._id_refs.append((from_name, to_id))
        target_name = self._coord_name_for_id(to_id)
        if (
            target_name is not None
            and from_name in self._coord_lookup
            and target_name in self._coord_lookup
        ):
            src_coord = self._coord_lookup[from_name]
            tgt_coord = self._coord_lookup[target_name]
            morphism = Morphism(
                source=src_coord,
                target=tgt_coord,
                kind=MorphismKind.TRANSPORT,
                label=f"id-ref:{from_name}→#{to_id}",
            )
            self._site.add_morphism(morphism)

    def _coord_name_for_id(self, id_value: str) -> Optional[str]:
        """Return the coordinate name whose HTML ``id`` attribute equals *id_value*."""
        return next(
            (n for n, id_attr in self._id_attr_of.items() if id_attr == id_value),
            None,
        )

    # ------------------------------------------------------------------ #
    # Public API — covering families                                       #
    # ------------------------------------------------------------------ #

    def subtree_covering(self, root_name: str) -> CoveringFamily:
        """Return a CoveringFamily where the direct children of *root_name* cover it.

        Children of a DOM node cover it because (a) any section over the node is
        determined by compatible sections over each child (local character);
        (b) sibling subtrees are disjoint so overlaps are empty and the cocycle
        condition holds vacuously; (c) the cover is stable under base change.
        This models the fact that a DOM node's content is exactly its children.

        Returns a ``CoveringFamily`` with one ``RESTRICTION`` morphism per child.
        Raises ``ValueError`` if *root_name* is not present.
        """
        base_coord = self._require_coord(root_name)
        children = self._children_of.get(root_name, [])
        family = CoveringFamily(base=base_coord, label=f"subtree({root_name})")
        for child_name in children:
            child_coord = self._coord_lookup[child_name]
            morphism = Morphism(
                source=child_coord,
                target=base_coord,
                kind=MorphismKind.RESTRICTION,
                label=f"{child_name}→{root_name}",
            )
            family.add_member(morphism)
        return family

    def document_covering(self) -> CoveringFamily:
        """Return a CoveringFamily for the top-level sections of the document.

        For a standard HTML document the root is covered by ``{html → document}``.
        A singleton covering trivially satisfies the cocycle condition (no
        non-trivial pairwise overlaps), making this the simplest valid cover.
        """
        return self.subtree_covering(self._roots[0])

    # ------------------------------------------------------------------ #
    # Public API — queries                                                 #
    # ------------------------------------------------------------------ #

    def query_selector(self, selector: str) -> list[str]:
        """Return coordinate names matching a simple CSS selector.

        Supported forms: ``tag``, ``#id``, ``.class``, ``tag.class``, ``tag#id``.
        Returns coordinate names in insertion order.
        """
        selector = selector.strip()
        id_match = re.search(r"#([\w-]+)", selector)
        class_match = re.search(r"\.([\w-]+)", selector)
        tag_part = re.sub(r"[#.][\w-]+", "", selector).strip() or None
        target_id = id_match.group(1) if id_match else None
        target_class = class_match.group(1) if class_match else None
        target_tag = tag_part

        results: list[str] = []
        for name in self._coord_lookup:
            if target_tag and self._tag_of.get(name) != target_tag:
                continue
            if target_id and self._id_attr_of.get(name) != target_id:
                continue
            if target_class and target_class not in self._classes_of.get(name, []):
                continue
            results.append(name)
        return results

    def path_to_root(self, coord_name: str) -> list[str]:
        """Return ancestor coordinate names from *coord_name* up to the document root.

        Follows ``_parent_of`` upward, mirroring the RESTRICTION morphism chain
        child → parent → … → document.  Reading the list in reverse gives the
        sequence of restriction maps that pull a section from the root down to
        *coord_name*.

        Returns ``[coord_name, parent, grandparent, …, root]``.
        Raises ``ValueError`` if *coord_name* is not in the site.
        """
        self._require_coord(coord_name)
        path: list[str] = [coord_name]
        current = coord_name
        while current in self._parent_of:
            current = self._parent_of[current]
            path.append(current)
        return path

    def depth_of(self, coord_name: str) -> int:
        """Return the DOM depth of *coord_name* (document root = 0).

        Raises ``KeyError`` if *coord_name* is not in the depth index.
        """
        for depth, names in self._depth_index.items():
            if coord_name in names:
                return depth
        raise KeyError(f"Coordinate {coord_name!r} not found in depth index.")

    def to_jugeo_site(self) -> Site:
        """Return the underlying jugeo ``Site`` object.

        Contains one ``Coordinate`` per DOM node, one ``RESTRICTION`` morphism per
        parent-child edge (child → parent), and ``TRANSPORT`` morphisms for any
        id-references.  Covering families are not pre-registered; call
        ``subtree_covering`` / ``document_covering`` and pass to
        ``site.add_covering_family`` if needed.
        """
        return self._site
