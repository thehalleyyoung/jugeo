# 5. TextRunMetrics — metrics for a concrete text run
# ---------------------------------------------------------------------------

@dataclass
class TextRunMetrics:
    """Typographic metrics for a run of text rendered in a given font.

    This is a thin, stdlib-only estimator.  Real text measurement requires
    a rendering engine; these formulae are useful for layout planning and
    unit tests where a browser is unavailable.

    Attributes
    ----------
    text:
        The string to be measured.
    font:
        ``FontMetrics`` for the typeface and size used to render *text*.
    letter_spacing_px:
        Additional tracking between characters (CSS ``letter-spacing``).
    word_spacing_px:
        Additional spacing between words (CSS ``word-spacing``).
    """

    text: str
    font: FontMetrics
    letter_spacing_px: float = 0.0
    word_spacing_px: float = 0.0

    def estimated_width_px(self, avg_char_width_ratio: float = 0.5) -> float:
        """Estimate the rendered width of ``self.text`` in pixels.

        The estimate uses a single average character-width ratio relative to
        the em size, plus explicit spacing overrides:

            width ≈ len(text) × size_px × avg_char_width_ratio
                   + letter_spacing_px × len(text)
                   + word_spacing_px × space_count

        Parameters
        ----------
        avg_char_width_ratio:
            Mean glyph advance as a fraction of ``font.size_px``.
            Proportional fonts: ~0.45–0.55.  Monospace: ~0.60.

        Returns
        -------
        float
            Estimated width in CSS pixels.
        """
        n_chars = len(self.text)
        n_spaces = self.text.count(" ")
        glyph_width = n_chars * self.font.size_px * avg_char_width_ratio
        letter_total = self.letter_spacing_px * n_chars
        word_total = self.word_spacing_px * n_spaces
        return glyph_width + letter_total + word_total

    def line_count(
        self,
        container_width_px: float,
        avg_char_width_ratio: float = 0.5,
    ) -> int:
        """Estimate the number of lines needed to render *text* in a container.

        Uses a word-wrap model: each word is estimated independently and a
        new line is started when the current line would overflow.

        Parameters
        ----------
        container_width_px:
            Available width in CSS pixels.
        avg_char_width_ratio:
            Passed to ``estimated_width_px`` for per-word estimates.

        Returns
        -------
        int
            Number of lines required; always ≥ 1.
        """
        if container_width_px <= 0:
            return max(len(self.text), 1)

        words = self.text.split(" ")
        lines = 1
        current_width = 0.0
        space_width = (
            self.font.size_px * avg_char_width_ratio * 1  # one space-glyph
            + self.word_spacing_px
        )

        for word in words:
            if not word:
                current_width += space_width
                continue
            word_run = TextRunMetrics(
                text=word,
                font=self.font,
                letter_spacing_px=self.letter_spacing_px,
                word_spacing_px=0.0,
            )
            word_w = word_run.estimated_width_px(avg_char_width_ratio)
            candidate = current_width + (space_width if current_width > 0 else 0) + word_w
            if current_width > 0 and candidate > container_width_px:
                lines += 1
                current_width = word_w
            else:
                current_width = candidate

        return lines
