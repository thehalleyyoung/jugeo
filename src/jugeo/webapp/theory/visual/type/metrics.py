"""
Type metrics as a presheaf.

Modular scales are ratio-based coordinate systems on the positive reals.
Font metrics are fiber data over glyph coordinates (the "em square").
Vertical rhythm is a descent condition: all line-heights lie in the
subgroup generated by the base grid unit.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from enum import Enum
from typing import TYPE_CHECKING

__all__ = [
    "TypeScaleRatio",
    "ModularScale",
    "FontMetrics",
    "VerticalRhythm",
    "TextRunMetrics",
]


# ---------------------------------------------------------------------------
# 1. TypeScaleRatio — named musical/harmonic ratios
# ---------------------------------------------------------------------------

class TypeScaleRatio(float, Enum):
    """Named typographic scale ratios drawn from musical interval theory.

    Each ratio r defines a geometric sequence: base, base·r, base·r², …
    The names mirror Western music intervals because both domains partition
    a continuous range into perceptually meaningful discrete steps.
    """

    MINOR_SECOND     = 1.067
    MAJOR_SECOND     = 1.125
    MINOR_THIRD      = 1.200
    MAJOR_THIRD      = 1.250
    PERFECT_FOURTH   = 1.333
    AUGMENTED_FOURTH = 1.414
    PERFECT_FIFTH    = 1.500
    GOLDEN_RATIO     = 1.618
    MAJOR_SIXTH      = 1.667
    OCTAVE           = 2.000


# ---------------------------------------------------------------------------
# 2. ModularScale — ratio-based coordinate system
# ---------------------------------------------------------------------------

@dataclass
class ModularScale:
    """A geometric coordinate system on type sizes.

    The scale is a presheaf on the poset of integers (steps): the
    restriction map sends step n to size base·ratio^n.  Morphisms in
    the base category (integer increments) map to multiplications by
    `ratio` in the fiber (pixel sizes).

    Attributes
    ----------
    base_size_px:
        The origin of the scale (step 0), in CSS pixels.
    ratio:
        Multiplicative step size.  Accepts ``TypeScaleRatio`` values or
        any positive float.
    steps:
        Number of upward steps exported by ``scale_values``; the scale
        also exports two downward steps (-2, -1).
    """

    base_size_px: float
    ratio: float
    steps: int = 8

    def size_at(self, step: int) -> float:
        """Return the size (px) at *step* positions from the base.

        Negative steps descend below the base size.

        Parameters
        ----------
        step:
            Integer offset from step 0 (the base).  May be negative.

        Returns
        -------
        float
            ``base_size_px * ratio ** step``
        """
        return self.base_size_px * (float(self.ratio) ** step)

    def step_for_size(self, size_px: float) -> float:
        """Invert ``size_at``: return the (possibly fractional) step for *size_px*.

        This is the logarithm change-of-base formula:
            step = log(size_px / base) / log(ratio)

        Parameters
        ----------
        size_px:
            Target size in pixels.  Must be positive.

        Returns
        -------
        float
            Fractional step value; may be non-integer for arbitrary sizes.

        Raises
        ------
        ValueError
            If *size_px* is not positive or *ratio* is 1 (degenerate scale).
        """
        if size_px <= 0:
            raise ValueError(f"size_px must be positive, got {size_px}")
        r = float(self.ratio)
        if r == 1.0:
            raise ValueError("ratio must differ from 1 to define a non-trivial scale")
        return math.log(size_px / self.base_size_px) / math.log(r)

    def scale_values(self) -> list[float]:
        """Return all sizes from step -2 up to ``self.steps`` (inclusive).

        Returns
        -------
        list[float]
            Sizes in ascending order.
        """
        return [self.size_at(s) for s in range(-2, self.steps + 1)]

    def nearest_step(self, size_px: float) -> int:
        """Round ``step_for_size(size_px)`` to the nearest integer step.

        Parameters
        ----------
        size_px:
            Target size in pixels.

        Returns
        -------
        int
            The closest integer step on this scale.
        """
        return round(self.step_for_size(size_px))


# ---------------------------------------------------------------------------
# 3. FontMetrics — fiber data over the em square
# ---------------------------------------------------------------------------

@dataclass
class FontMetrics:
    """Geometric metrics for a typeface at a specific size.

    The em square is the coordinate chart; all ratios are relative to it.
    A ``FontMetrics`` instance is the *fiber* over a point (family, size)
    in the space of typeface specifications.

    Attributes
    ----------
    family:
        CSS font-family name.
    size_px:
        Rendered size in CSS pixels (= 1 em).
    x_height_ratio:
        x-height / em.  Typically 0.45–0.55.
    cap_height_ratio:
        Cap-height / em.  Typically 0.60–0.75.
    ascender_ratio:
        Ascender / em.  Typically 0.80–0.90.
    descender_ratio:
        |Descender| / em (positive value).  Typically 0.20–0.30.
    line_gap_ratio:
        Extra gap / em suggested by the font designer.  Often 0.
    """

    family: str
    size_px: float
    x_height_ratio: float
    cap_height_ratio: float
    ascender_ratio: float
    descender_ratio: float
    line_gap_ratio: float = 0.0

    # -- pixel-valued properties -------------------------------------------

    @property
    def x_height(self) -> float:
        """x-height in CSS pixels."""
        return self.x_height_ratio * self.size_px

    @property
    def cap_height(self) -> float:
        """Cap-height in CSS pixels."""
        return self.cap_height_ratio * self.size_px

    @property
    def ascender(self) -> float:
        """Ascender height in CSS pixels (above the baseline)."""
        return self.ascender_ratio * self.size_px

    @property
    def descender(self) -> float:
        """Descender depth in CSS pixels (positive value, below baseline)."""
        return self.descender_ratio * self.size_px

    @property
    def natural_line_height(self) -> float:
        """Default line-box height suggested by the font, in CSS pixels.

        Computed as ``(ascender_ratio + descender_ratio + line_gap_ratio) * size_px``.
        This corresponds to the OS/2 ``sTypoAscender - sTypoDescender + sTypoLineGap``
        convention normalised to the em size.
        """
        return (self.ascender_ratio + self.descender_ratio + self.line_gap_ratio) * self.size_px

    # -- factory -----------------------------------------------------------

    @classmethod
    def system_fonts(cls, size_px: float = 16.0) -> dict[str, FontMetrics]:
        """Return approximate metrics for common system fonts at *size_px*.

        Values are derived from published font metrics and broadly accepted
        approximations used in web typography tooling.

        Parameters
        ----------
        size_px:
            Em size in CSS pixels; defaults to 16 (browser default).

        Returns
        -------
        dict[str, FontMetrics]
            Mapping from font-family name to its ``FontMetrics``.
        """
        # (family, x_height_ratio, cap_height_ratio, ascender_ratio,
        #  descender_ratio, line_gap_ratio)
        _specs: list[tuple[str, float, float, float, float, float]] = [
            # Serif — Georgia: large x-height, generous metrics
            ("Georgia",            0.481, 0.693, 0.917, 0.219, 0.033),
            # Serif — Times New Roman: compact, classical proportions
            ("Times New Roman",    0.447, 0.662, 0.891, 0.216, 0.000),
            # Sans — Arial: Helvetica clone, tall x-height
            ("Arial",              0.519, 0.716, 0.905, 0.212, 0.000),
            # Sans — Helvetica: slightly tighter than Arial
            ("Helvetica",          0.517, 0.714, 0.900, 0.210, 0.000),
            # Generic — system-ui (approximated from San Francisco / Segoe UI)
            ("system-ui",          0.530, 0.730, 0.920, 0.230, 0.000),
            # Generic — monospace (approximated from Courier / monospace stack)
            ("monospace-generic",  0.430, 0.630, 0.800, 0.200, 0.100),
            # Generic — serif placeholder
            ("serif-generic",      0.450, 0.670, 0.890, 0.220, 0.000),
            # Generic — sans-serif placeholder
            ("sans-serif-generic", 0.520, 0.720, 0.900, 0.220, 0.000),
        ]
        return {
            family: cls(
                family=family,
                size_px=size_px,
                x_height_ratio=xh,
                cap_height_ratio=ch,
                ascender_ratio=asc,
                descender_ratio=desc,
                line_gap_ratio=gap,
            )
            for family, xh, ch, asc, desc, gap in _specs
        }

    def at_size(self, size_px: float) -> FontMetrics:
        """Return a new ``FontMetrics`` for the same typeface at *size_px*.

        Ratios are preserved; only ``size_px`` changes — this is the
        pullback along the scaling morphism.
        """
        return FontMetrics(
            family=self.family,
            size_px=size_px,
            x_height_ratio=self.x_height_ratio,
            cap_height_ratio=self.cap_height_ratio,
            ascender_ratio=self.ascender_ratio,
            descender_ratio=self.descender_ratio,
            line_gap_ratio=self.line_gap_ratio,
        )


# ---------------------------------------------------------------------------
# 4. VerticalRhythm — descent condition on the grid
# ---------------------------------------------------------------------------

@dataclass
class VerticalRhythm:
    """Vertical rhythm as a divisibility (descent) condition.

    A layout satisfies vertical rhythm when every line-height value is an
    integer multiple of ``base_line_height_px``.  This is the descent
    condition in the sense that all sizes descend to the same grid object
    in the base category.

    Attributes
    ----------
    base_line_height_px:
        The grid unit (e.g., 24 px).  Every snapped line-height will be a
        positive integer multiple of this value.
    font_metrics:
        Default font whose natural line-height informs snapping calculations.
    """

    base_line_height_px: float
    font_metrics: FontMetrics

    # -- grid arithmetic ---------------------------------------------------

    def lines_for_size(self, font_size_px: float, min_lines: int = 1) -> int:
        """Minimum number of grid lines needed to contain *font_size_px*.

        Uses the font's natural line-height (scaled to *font_size_px*) as the
        content height, then takes the ceiling over the base grid unit.

        Parameters
        ----------
        font_size_px:
            The rendered font size in pixels.
        min_lines:
            Floor value; at least this many lines are always returned.

        Returns
        -------
        int
            Number of grid lines ≥ *min_lines*.
        """
        scaled = self.font_metrics.at_size(font_size_px).natural_line_height
        lines = math.ceil(scaled / self.base_line_height_px)
        return max(lines, min_lines)

    def line_height_for_size(self, font_size_px: float) -> float:
        """Grid-snapped line-height for *font_size_px*.

        Returns
        -------
        float
            ``lines_for_size(font_size_px) * base_line_height_px``
        """
        return self.lines_for_size(font_size_px) * self.base_line_height_px

    def margin_top_for_heading(self, font_size_px: float) -> float:
        """Recommended top margin for a heading at *font_size_px*.

        Convention: headings should be preceded by 2 grid lines of space
        (so the eye can parse the document hierarchy), less the heading's
        own line-height (to avoid double-counting the first line of the
        heading block).

        Returns
        -------
        float
            Top margin in CSS pixels, aligned to the grid.
        """
        heading_lh = self.line_height_for_size(font_size_px)
        two_lines = 2 * self.base_line_height_px
        margin = max(two_lines - heading_lh, self.base_line_height_px)
        # Snap to nearest grid multiple
        snapped = round(margin / self.base_line_height_px) * self.base_line_height_px
        return max(snapped, self.base_line_height_px)

    # -- rhythm validation -------------------------------------------------

    def is_rhythmic(self, elements: list[tuple[float, float]]) -> bool:
        """Return ``True`` iff every line-height in *elements* is a grid multiple.

        Parameters
        ----------
        elements:
            Sequence of ``(font_size_px, line_height_px)`` pairs.

        Returns
        -------
        bool
            ``True`` when all line-heights satisfy the descent condition.
        """
        return len(self.rhythm_violations(elements)) == 0

    def rhythm_violations(
        self,
        elements: list[tuple[float, float]],
    ) -> list[tuple[float, float, float]]:
        """Return a description of each element that violates the rhythm.

        A line-height *lh* violates the grid when
        ``lh % base_line_height_px`` is not within floating-point tolerance
        of 0 (or ``base_line_height_px``).

        Parameters
        ----------
        elements:
            Sequence of ``(font_size_px, line_height_px)`` pairs.

        Returns
        -------
        list of (font_size_px, line_height_px, expected_multiple)
            Triples for each violating element, where *expected_multiple* is
            the nearest grid multiple to *line_height_px*.
        """
        violations: list[tuple[float, float, float]] = []
        tol = 1e-6
        for font_size, line_height in elements:
            if self.base_line_height_px <= 0:
                continue
            quotient = line_height / self.base_line_height_px
            remainder = quotient - round(quotient)
            if abs(remainder) > tol:
                expected = round(quotient) * self.base_line_height_px
                violations.append((font_size, line_height, expected))
        return violations


